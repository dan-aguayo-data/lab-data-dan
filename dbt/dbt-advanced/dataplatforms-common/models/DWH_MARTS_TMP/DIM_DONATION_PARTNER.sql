SELECT
--Key naming convention applied for clarity "<TABLE NAME>_KEY". Dbt Util applied.
--Dimension Key
  C.DIM_CONSUMER_KEY as DIM_DONATION_PARTNER_KEY

--Natural Key
, C.CONSUMER_ID AS DONATION_PARTNER_ID

--Attributes
, C.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, C.SCHEME AS SCHEME
, C.CONSUMER_NAME AS DONATION_PARTNER_NAME
, C.ABN AS DONATION_PARTNER_ABN
, DP.APPROVAL_STATUS AS STATUS
, DP.CATEGORY AS CATEGORY

--Metrics
, H.COLLECTION_QTY_STD AS COLLECTION_QTY_STD

--Metadata Attributes
, SYSDATE() AS INSERT_DATE_UTC

FROM 
{{ ref('DIM_CONSUMER') }} AS C
LEFT JOIN (
    SELECT 
    H.RECIPIENT_CONSUMER_ID
    , SUM(H.COLLECTION_QTY) AS COLLECTION_QTY_STD
    , COUNT(H.FACT_CRP_COLLECTION_AGG_KEY) AS TRANSACTION_COUNT_STD
    , MAX(H.TRANSACTION_LOCAL_DATETIME) AS LAST_TRANSACTION_DATE
    , MIN(H.TRANSACTION_LOCAL_DATETIME) AS FIRST_TRANSACTION_DATE
    FROM {{ ref('FACT_CRP_COLLECTION_AGG') }} AS H
    GROUP BY
    H.RECIPIENT_CONSUMER_ID
) H
ON C.CONSUMER_ID = H.RECIPIENT_CONSUMER_ID
LEFT JOIN {{ source('CES_MSCM_KAFKA', 'DONATION_PARTNERS') }} AS DP
ON C.CONSUMER_ID = DP.SCHEME_PARTICIPANT_ID 
WHERE C.DONATION_PARTNER_FLAG = 1