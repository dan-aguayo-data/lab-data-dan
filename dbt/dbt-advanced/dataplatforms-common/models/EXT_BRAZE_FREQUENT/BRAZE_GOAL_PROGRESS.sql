SELECT
UUID.MARKETING_UUID AS "external_id"
, G.CONSUMER_ID || '-' ||  TO_CHAR(G.GOAL_START_DATE,'YYYY-MM-DD') || '-' || G.GOAL_MEMBER_TYPE AS "id"
, G.GOAL_D_ID AS "goal_d_id"
, G.GOAL_NAME AS "goal_name"
, CEIL((NVL(G.COLLECTION_QTY,0)/G.GOAL_AMOUNT) * 10, 2) AS "goal_progress_percent"
, CASE WHEN (NVL(G.COLLECTION_QTY,0)/G.GOAL_AMOUNT) * 10 <= 25 THEN 1 WHEN (G.COLLECTION_QTY/G.GOAL_AMOUNT) * 10 > 25 AND (G.COLLECTION_QTY/G.GOAL_AMOUNT) * 10 <= 50 THEN 2 WHEN (G.COLLECTION_QTY/G.GOAL_AMOUNT) * 10 > 50 AND (G.COLLECTION_QTY/G.GOAL_AMOUNT) * 10 <= 75 THEN 3 WHEN (G.COLLECTION_QTY/G.GOAL_AMOUNT) * 10 > 75 AND (G.COLLECTION_QTY/G.GOAL_AMOUNT) * 10 < 100 THEN 4 ELSE 5 END AS "goal_progress_banding"
, DATEDIFF('DAY',CONVERT_TIMEZONE('UTC','Australia/Queensland',SYSDATE()),G.GOAL_END_DATE) AS "days_remaining"
, CEIL(((CASE WHEN (NVL(G.COLLECTION_QTY,0)/G.GOAL_AMOUNT) * 10 <= 25 THEN 0.25 WHEN (G.COLLECTION_QTY/G.GOAL_AMOUNT) * 10 > 25 AND (G.COLLECTION_QTY/G.GOAL_AMOUNT) * 10 <= 50 THEN 0.50 WHEN (G.COLLECTION_QTY/G.GOAL_AMOUNT) * 10 > 50 AND (G.COLLECTION_QTY/G.GOAL_AMOUNT) * 10 <= 75 THEN 0.75 WHEN (G.COLLECTION_QTY/G.GOAL_AMOUNT) * 10 > 75 AND (G.COLLECTION_QTY/G.GOAL_AMOUNT) * 10 < 100 THEN 1 ELSE 0 END) * G.GOAL_AMOUNT * 10) - (CASE WHEN (G.COLLECTION_QTY/G.GOAL_AMOUNT) * 10 < 100 THEN NVL(G.COLLECTION_QTY,0) ELSE 0 END),0) AS "qty_remaining_to_reach_next_level"
, CAST(G.GOAL_START_DATE AS TIMESTAMP) AS "goal_start_date"
, CAST(G.GOAL_END_DATE AS TIMESTAMP) AS "goal_end_date"
, G.GOAL_AMOUNT * 10 AS "goal_target_qty"
, G.COLLECTION_QTY AS "qty_returned_towards_goal"
, CEIL(G.COLLECTION_QTY/10,2) AS "dollars_earned_towards_goal"
, CASE WHEN DATEDIFF('DAY',CONVERT_TIMEZONE('UTC','Australia/Queensland',SYSDATE()),G.GOAL_END_DATE) < 5 THEN 'TRUE' ELSE 'FALSE' END AS "goal_end_less_than_5_days_flag"
, CEIL((G.GOAL_AMOUNT * 10) - G.COLLECTION_QTY,0) AS "target_qty_remaining"
, CEIL((G.GOAL_AMOUNT) / CEIL(DATEDIFF('DAY',G.GOAL_START_DATE,G.GOAL_END_DATE)/7 ,0),1) AS "target_amount_per_week"
, CEIL((G.GOAL_AMOUNT * 10) / CEIL(DATEDIFF('DAY',G.GOAL_START_DATE,G.GOAL_END_DATE)/7 ,0),0) AS "target_qty_per_week"
FROM (
    SELECT 
    G.GOAL_D_ID,
    G.GOAL_START_DATE, 
    G.GOAL_END_DATE,
    G.GOAL_NAME,
    P.CONSUMER_NUMBER AS CONSUMER_ID,
    G.GOAL_AMOUNT,
    G.GOAL_MEMBER_TYPE,
    G.CREATED_ON AS GOAL_CREATED_ON,
    NVL(SUM(H.COLLECTION_QTY) OVER (PARTITION BY P.CONSUMER_NUMBER ,G.GOAL_D_ID),0) AS COLLECTION_QTY
    FROM {{ source('CES_DRUPAL', 'CFC_GOAL') }} AS G
    INNER JOIN {{ source('CES_DRUPAL', 'PARTICIPANT_SITES') }} AS PS
    ON G.PARTICIPANT_SITE_ID = PS.PARTICIPANT_SITE_ID AND PS._FIVETRAN_DELETED = FALSE
    INNER JOIN {{ source('CES_DRUPAL', 'PARTICIPANTS') }} AS P 
    ON P.PARTICIPANT_ID = PS.PARTICIPANT_ID AND P._FIVETRAN_DELETED = FALSE
    LEFT JOIN {{ ref('CRP_COLLECTION_HDR') }} AS H
    ON PS.SITE_NUMBER = H.CONSUMER_ID 
    AND H.TRANSACTION_DATE BETWEEN G.GOAL_START_DATE AND G.GOAL_END_DATE
    WHERE G.GOAL_AMOUNT <> 0 AND G.GOAL_MEMBER_TYPE = 0 AND G._FIVETRAN_DELETED = 'FALSE' AND (CONVERT_TIMEZONE('UTC','Australia/Queensland',SYSDATE()) BETWEEN G.GOAL_START_DATE AND G.GOAL_END_DATE) --GOAL ACTIVE AND INDIVIDUALS
    AND PS.MULTI_SCHEME_ID = 10000 --COEX
    AND PS.TAXONOMY_TYPE_ID = 'Consumer' 
    AND P.PARTICIPANT_GROUP = 'IND_CONSUMER'--Just send to individual customers
    AND (LOWER(PS.SITE_NAME) NOT LIKE '%pvt%' AND LOWER(PS.SITE_NAME) NOT LIKE'% test %')  --Test sites
    AND PS.SITE_NUMBER <> 'C10625269' --2 customer with same info (exclude customer without transactions)
    AND PS.STATE = 'QLD' --Customer address is of another state
    AND TRUNC(G.GOAL_START_DATE, 'DAY') <> TRUNC(G.GOAL_END_DATE, 'DAY')
    QUALIFY ROW_NUMBER() OVER (PARTITION BY PS.SITE_NUMBER ORDER BY G.GOAL_D_ID DESC) = 1
) G
LEFT JOIN {{ source('CES_DRUPAL', 'CFC_UUID') }} AS UUID
ON UUID.CONSUMER_NUMBER  = G.CONSUMER_ID AND UUID.MULTI_SCHEME_ID = 10000 AND UUID.TYPE = 'individual' AND UUID._FIVETRAN_DELETED = FALSE
WHERE UUID.MARKETING_UUID IS NOT NULL
AND UUID.CONSUMER_NUMBER <> 'C11340205'