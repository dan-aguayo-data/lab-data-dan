WITH CONTAINER_COLLECT_V1 AS (
    SELECT 
    CAST(CCB.ID AS VARCHAR) AS BOOKING_ID,
    CCB.LOCATION_ID AS BOOKING_LOCATION_ID,
    CONCAT('C',REPLACE(REPLACE(UPPER(CCB.SCHEME_ID),'C',''),' ','')) AS BOOKING_CONSUMER_ID,
    CCB.SUBURB AS BOOKING_SUBURB,
    COALESCE(CCB.PICKUP_STATUS,'Successful') AS BOOKING_PICKUP_STATUS,
    CASE WHEN COALESCE(LOWER(CCB.PICKUP_STATUS),'successful') = 'successful' THEN 'Successful'
        WHEN LOWER(CCB.PICKUP_STATUS) LIKE 'unsuccessful%' THEN 'Unsuccessful'
        WHEN LOWER(CCB.PICKUP_STATUS) LIKE 'partial%' THEN 'Partial'
        ELSE 'Unknown' END AS BOOKING_PICKUP_STATUS_GROUP,
    CASE WHEN REGEXP_COUNT(CCB.ADDRESS,',')=2 OR LEN(CCB.ADDRESS)=0 THEN CASE WHEN LEN(CCB.ADDRESS)=0 OR LEN(CCB.ADDRESS) IS NULL THEN CONCAT(CCB.STREET,',',CCB.SUBURB,',',CCB.POSTCODE,',QLD',',Australia') ELSE CONCAT(COALESCE(SPLIT_PART(CCB.ADDRESS,',',1),CCB.STREET),',',CCB.SUBURB,',',CCB.POSTCODE,',QLD',',Australia') END
        WHEN REGEXP_COUNT(CCB.ADDRESS,',')=3 THEN CONCAT(COALESCE(SPLIT_PART(CCB.ADDRESS,',',2),CCB.STREET) ,',',CCB.SUBURB,',',CCB.POSTCODE,',QLD',',Australia')
        WHEN REGEXP_COUNT(CCB.ADDRESS,',')=1 THEN CONCAT(COALESCE(SPLIT_PART(CCB.ADDRESS,',',1),CCB.STREET) ,',',CCB.SUBURB,',',CCB.POSTCODE,',QLD',',Australia')
        ELSE NULL END AS BOOKING_ADDRESS,
    TRY_TO_NUMBER(CCB.POSTCODE) AS BOOKING_POSTCODE,
    CCB.DATE AS BOOKING_PICK_UP_DATE,
    TRY_TO_NUMBER(CCB.CONTAINERS_COLLECTED) AS BOOKING_QUANTITY,
    CCB.CREATED_AT AS BOOKING_CREATED_DATETIME,
    TO_DATE(CCB.CREATED_AT) AS BOOKING_CREATED_DATE,
    CCB.UPDATED_AT AS BOOKING_UPDATE_DATETIME,
    NULL AS BOOKING_OPERATORNAME,
    NULL AS LATITUDE,
    NULL AS LONGITUDE,
    CCB.BAGS AS NUMBER_OF_BAGS,
    NULL AS BAGS_SMALL,
    NULL AS BAGS_MEDIUM,
    NULL AS BAGS_LARGE,
    BAG_LOCATION AS COLLECTION_INSTRUCTIONS
    FROM
    {{ source('COEX_COLLECT', 'CONTAINER_COLLECT_BOOKINGS') }} AS CCB
),
CONTAINER_COLLECT_V2 AS
(
    SELECT 
    CAST(CCB.ID AS VARCHAR) AS BOOKING_ID,
    CAST(LEFT(TRIM(REGEXP_REPLACE(CCB.SCHEDULEDCOLLECTION, '[a-z/-/A-z/./#/*]', '')),12) AS INT) AS BOOKING_LOCATION_ID,
    CCD.MEMBERNUMBER AS BOOKING_CONSUMER_ID,
    TRIM(LEFT(SPLIT_PART(ADDRESS,',',2), LEN(SPLIT_PART(ADDRESS,',',2) ) - 5)) AS BOOKING_SUBURB,
    INITCAP(CCB.STATUS) AS BOOKING_PICKUP_STATUS,
    CASE WHEN COALESCE(LOWER(CCB.STATUS),'successful') = 'successful' THEN 'Successful'
        WHEN LOWER(CCB.STATUS) LIKE 'unsuccessful%' THEN 'Unsuccessful'
        WHEN LOWER(CCB.STATUS) LIKE 'partial%' THEN 'Partial'
        WHEN LOWER(CCB.STATUS) LIKE 'pENDing%' THEN 'PENDing'
        WHEN LOWER(CCB.STATUS) LIKE 'cancel%' THEN 'Cancelled'
        ELSE 'Unknown' END AS BOOKING_PICKUP_STATUS_GROUP,
    CCB.ADDRESS AS BOOKING_ADDRESS,
    TRY_CAST(TRIM(RIGHT(ADDRESS,4)) AS INT) AS BOOKING_POSTCODE,
    TO_DATE(DATEADD(HOUR,10,CAST(CCB.DATE AS DATETIME))) AS BOOKING_PICK_UP_DATE,
    CCB.CONTAINERSCOLLECTED AS BOOKING_QUANTITY,
    DATEADD(HOUR,10,CAST(CCB.CREATEDAT AS DATETIME)) AS BOOKING_CREATED_DATETIME,
    TO_DATE(DATEADD(HOUR,10,CAST(CCB.CREATEDAT AS DATETIME))) AS BOOKING_CREATED_DATE,
    DATEADD(HOUR,10,CAST(CCB.UPDATEDAT AS DATETIME)) AS BOOKING_UPDATE_DATETIME,
    OPERATORNAME AS BOOKING_OPERATORNAME,
    SPLIT_PART(CCB.GEOLOCATION,',',2) AS LATITUDE,
    SPLIT_PART(CCB.GEOLOCATION,',',1) AS LONGITUDE,
    TRY_CAST(BAGS_SMALL AS INT) + TRY_CAST(BAGS_MEDIUM AS INT) + TRY_CAST(BAGS_LARGE AS INT) AS NUMBER_OF_BAGS,
    BAGS_SMALL,
    BAGS_MEDIUM,
    BAGS_LARGE,
    COLLECTION_INSTRUCTIONS       
    FROM
    {{ source('COEX_COLLECT', 'CONTAINER_COLLECT_BOOKING_V2') }} AS CCB 
    INNER JOIN
    {{ source('COEX_COLLECT', 'CONTAINER_COLLECT_CONTACT_DETAILS_V2') }} AS CCD
    ON CCB.ID = CCD.ID
),
CONTAINER_COLLECT AS
(
    SELECT DISTINCT A.*
    FROM
    CONTAINER_COLLECT_v1 A
    LEFT JOIN
    CONTAINER_COLLECT_v2 B
    ON A.BOOKING_CONSUMER_ID = B.BOOKING_CONSUMER_ID
    AND A.BOOKING_PICK_UP_DATE = B.BOOKING_PICK_UP_DATE
    WHERE B.BOOKING_CONSUMER_ID IS NULL

    UNION ALL

    SELECT *
    FROM
    CONTAINER_COLLECT_v2
)
SELECT 
10000 AS MULTI_SCHEME_ID,
'QLD' AS SCHEME_ID,
C.BOOKING_ID,
C.BOOKING_LOCATION_ID,
C.BOOKING_CONSUMER_ID,
C.BOOKING_SUBURB,
C.BOOKING_PICKUP_STATUS,
C.BOOKING_PICKUP_STATUS_GROUP,
C.BOOKING_ADDRESS,
C.BOOKING_POSTCODE,
C.BOOKING_PICK_UP_DATE,
C.BOOKING_QUANTITY,
C.BOOKING_CREATED_DATETIME,
C.BOOKING_CREATED_DATE,
C.BOOKING_UPDATE_DATETIME,
C.BOOKING_OPERATORNAME,
C.LATITUDE,
C.LONGITUDE,
C.NUMBER_OF_BAGS,
C.BAGS_SMALL,
C.BAGS_MEDIUM,
C.BAGS_LARGE,
C.COLLECTION_INSTRUCTIONS
FROM
CONTAINER_COLLECT C