SELECT
--Dbt Util not applied here. Key is already a hash from source.
--Fact Key
  SD.ID AS FACT_FRS_SALE_VOLUME_KEY

--Foreign Key
, {{ dbt_utils.generate_surrogate_key(['SD.MULTI_SCHEME_ID']) }} AS DIM_SCHEME_KEY
, {{ dbt_utils.generate_surrogate_key(['SD.MATERIAL_TYPE_ID']) }} AS DIM_MATERIAL_TYPE_KEY
, {{ dbt_utils.generate_surrogate_key(['SH.MANUFACTURER_ID']) }} AS DIM_SITE_FRS_KEY
, {{ dbt_utils.generate_surrogate_key(["REPLACE(CONCAT(TO_CHAR(SH.PERIOD),'01'), '-','')"]) }} AS DIM_DATE_PERIOD_KEY
, {{ dbt_utils.generate_surrogate_key(["TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(SH.SUBMITTED_DATE AS TIMESTAMP)),'YYYYMMDD')"]) }} as DIM_DATE_SUBMITTED_LOCAL_KEY

--Natural Key Cols
--, SD.ID AS ID

--Attributes
, SD.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, SD.MFG_SALES_VOLUME_HDR_ID AS BM_SALES_VOLUME_HDR_ID
, SH.MANUFACTURER_ID AS SITE_NUMBER
, SD.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID
, MT.NAME AS MATERIAL_TYPE
, 'Volume' AS VOLUME_HEADER
, SD.UOM AS UOM
, SH.PERIOD
, REPLACE(CONCAT(TO_CHAR(SH.PERIOD),'01'), '-','') AS PERIOD_DATE_ID
, SH.PERIOD_TYPE AS PERIOD_TYPE
, SH.ENTRY_TYPE AS ENTRY_TYPE
, SH.STATUS AS STATUS
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(SH.SUBMITTED_DATE AS TIMESTAMP)) AS SUBMITTED_LOCAL_DATETIME
, TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(SH.SUBMITTED_DATE AS TIMESTAMP)),'YYYYMMDD') AS SUBMITTED_LOCAL_DATE_ID
, SH.SUBMITTED_BY AS SUBMITTED_BY
, SH.SUBMITTED_DATE AS SUBMITTED_UTC_DATETIME
, NVL(SH.SS_AUDIT_ADJUSTMENT_ID, -1) AS SS_AUDIT_ADJUSTMENT_ID
, SH.ADJUSTMENT_REASON AS ADJUSTMENT_REASON

--Metrics
, SD.VOLUME AS VOLUME

--Metadata Attributes
, SD.CREATED_BY AS CREATED_BY
, SD.CREATED_ON AS CREATED_ON_UTC_DATETIME
, SD.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, SD.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC_DATETIME
, SYSDATE() AS INSERT_UTC_DATETIME

FROM
{{ source('CES_MSCM', 'MFG_SALES_VOLUME_DTL') }} AS SD
INNER JOIN {{ source('CES_MSCM', 'MFG_SALES_VOLUME_HDR') }} AS SH
ON SD.MFG_SALES_VOLUME_HDR_ID = SH.ID
LEFT JOIN {{ source('CES_MSCM', 'MANUFACTURER') }} AS M
ON SH.MANUFACTURER_ID = M.SCHEME_PARTICIPANT_ID
LEFT JOIN {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS MT
ON SD.MATERIAL_TYPE_ID = MT.ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON SD.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID