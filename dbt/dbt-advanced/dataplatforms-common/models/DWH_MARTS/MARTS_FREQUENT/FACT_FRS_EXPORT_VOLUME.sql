SELECT
--Dbt Util not applied here. Key is already a hash from source.
--Fact Key
  ED.ID AS FACT_FRS_EXPORT_VOLUME_KEY

--Foreign Key
, {{ dbt_utils.generate_surrogate_key(['EH.MULTI_SCHEME_ID']) }} AS DIM_SCHEME_KEY
, {{ dbt_utils.generate_surrogate_key(['ED.MATERIAL_TYPE_ID']) }} AS DIM_MATERIAL_TYPE_KEY
, {{ dbt_utils.generate_surrogate_key(['ED.MANUFACTURER_ID']) }} AS DIM_SITE_FRS_KEY
, {{ dbt_utils.generate_surrogate_key(['EH.EXPORTER_ID']) }} AS DIM_SITE_EXPORTER_KEY
, {{ dbt_utils.generate_surrogate_key(["REPLACE(CONCAT(TO_CHAR(EH.PERIOD),'01'), '-','')"]) }} AS DIM_DATE_PERIOD_KEY
, {{ dbt_utils.generate_surrogate_key(["TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(EH.SUBMITTED_DATE AS TIMESTAMP)),'YYYYMMDD')"]) }} as DIM_DATE_SUBMITTED_LOCAL_KEY

--Natural Key Cols
--, ED.ID AS ID

--Attributes
, EH.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, ED.EXPORT_VOLUME_HDR_ID AS BM_EXPORT_VOLUME_HDR_ID
, ED.MANUFACTURER_ID AS SITE_NUMBER
, ED.TO_STATE_ID AS EXPORT_TO
, EH.EXPORTER_ID AS EXPORTER_SITE_NUMBER
, ED.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID
, MT.NAME AS MATERIAL_TYPE
, 'Volume' AS VOLUME_HEADER
, ED.UOM AS UOM
, EH.PERIOD
, REPLACE(CONCAT(TO_CHAR(EH.PERIOD),'01'), '-','') AS PERIOD_DATE_ID
, EH.PERIOD_TYPE AS PERIOD_TYPE
, EH.ENTRY_TYPE AS ENTRY_TYPE
, EH.STATUS AS STATUS
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(EH.SUBMITTED_DATE AS TIMESTAMP)) AS SUBMITTED_LOCAL_DATETIME
, TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(EH.SUBMITTED_DATE AS TIMESTAMP)),'YYYYMMDD') AS SUBMITTED_LOCAL_DATE_ID
, EH.SUBMITTED_BY AS SUBMITTED_BY
, EH.SUBMITTED_DATE AS SUBMITTED_UTC_DATETIME
, NVL(EH.SS_AUDIT_ADJUSTMENT_ID, -1) AS SS_AUDIT_ADJUSTMENT_ID

--Metrics
, ED.VOLUME AS VOLUME

--Metadata Attributes
, ED.CREATED_BY AS CREATED_BY
, ED.CREATED_ON AS CREATED_ON_UTC_DATETIME
, ED.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, ED.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC_DATETIME
, SYSDATE() AS INSERT_UTC_DATETIME

FROM
{{ source('CES_MSCM', 'EXPORT_VOLUME_DTL') }} AS ED
INNER JOIN {{ source('CES_MSCM', 'EXPORT_VOLUME_HDR') }} AS EH
ON ED.EXPORT_VOLUME_HDR_ID = EH.ID
LEFT JOIN {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS MT
ON ED.MATERIAL_TYPE_ID = MT.ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON EH.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID