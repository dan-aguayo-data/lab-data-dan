SELECT
--Key naming convention applied for clarity "<TABLE NAME>_KEY". Dbt Util applied.
--Dimension Key
  {{ dbt_utils.generate_surrogate_key(['RP.ID']) }} AS DIM_SEASONALITY_INDEX_KEY

--Natural Key
, RP.ID AS ID

--Attributes
, RP.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, RP.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID
, MT.NAME AS MATERIAL_TYPE
, RP.VALUE AS SEASONALITY_INDEX
, CAST(RP.EFFECTIVE_FROM AS DATE) AS EFFECTIVE_FROM_DATE
, TO_CHAR(RP.EFFECTIVE_FROM, 'YYYYMMDD') AS EFFECTIVE_FROM_DATE_ID
, CAST(RP.EFFECTIVE_TO AS DATE) AS EFFECTIVE_TO_DATE
, CASE WHEN FILTER.N = 1 THEN 'Y' ELSE 'N' END AS ACTIVE_FLAG

--Metadata Attributes
, RP.CREATED_BY AS CREATED_BY
, RP.CREATED_ON AS CREATED_ON_UTC_DATETIME
, RP.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, RP.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC_DATETIME
, SYSDATE() AS INSERT_UTC_DATETIME

FROM
{{ source('CES_MSCM', 'SEASONALITY_INDEX_REFERENCE') }} AS RP
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON RP.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS MT
ON RP.MATERIAL_TYPE_ID = MT.ID
LEFT JOIN
    (SELECT
    P.ID
    ,ROW_NUMBER() OVER (PARTITION BY P.MULTI_SCHEME_ID, P.MATERIAL_TYPE_ID ORDER BY P.EFFECTIVE_FROM DESC, P.EFFECTIVE_TO DESC) N
    FROM {{ source('CES_MSCM', 'SEASONALITY_INDEX_REFERENCE') }} AS P
    WHERE CAST(CONVERT_TIMEZONE('UTC', 'Australia/Perth', SYSTIMESTAMP()) AS DATE)  BETWEEN NVL(P.EFFECTIVE_FROM,TO_DATE('01/JAN/1900','DD/MON/YYYY')) AND NVL(P.EFFECTIVE_TO,TO_DATE('01/JAN/9999','DD/MON/YYYY'))
    ) FILTER
ON RP.ID = FILTER.ID