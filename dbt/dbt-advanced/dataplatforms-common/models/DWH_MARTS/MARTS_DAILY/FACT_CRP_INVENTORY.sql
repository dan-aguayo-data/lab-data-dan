--############ CRP MART ############--

SELECT
--Dbt Util not applied here. Key is already a hash from source.
--Fact Key
  DTL.ID as FACT_CRP_INVENTORY_KEY

--Foreign Key
, {{ dbt_utils.generate_surrogate_key(['HDR.MULTI_SCHEME_ID']) }} AS DIM_SCHEME_KEY
, {{ dbt_utils.generate_surrogate_key(['DTL.MATERIAL_TYPE_ID']) }} AS DIM_MATERIAL_TYPE_KEY
, {{ dbt_utils.generate_surrogate_key(['HDR.CRP_ID']) }} AS DIM_SITE_CRP_KEY
, {{ dbt_utils.generate_surrogate_key(['PS.PARTICIPANT_ID']) }} AS DIM_B2B_SUPPLIER_KEY
, {{ dbt_utils.generate_surrogate_key(["REPLACE(HDR.PERIOD,'-','')"]) }} AS DIM_DATE_PERIOD_KEY
, {{ dbt_utils.generate_surrogate_key(["TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(HDR.SUBMITTED_DATE AS TIMESTAMP)),'YYYYMMDD')"]) }} as DIM_DATE_SUBMITTED_KEY

--Natural Key
--, DTL.ID AS ID

--Attributes
, HDR.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, HDR.ID AS INVENTORY_HDR_ID
, HDR.CRP_ID AS SITE_NUMBER
, PS.SITE_NAME AS SITE_NAME
, PS.PARTICIPANT_ID AS SUPPLIER_ID
, P.PARTICIPANT_NUMBER AS SUPPLIER_NUMBER
, P.PARTICIPANT_NAME AS SUPPLIER_NAME
, HDR.PERIOD
, REPLACE(PERIOD,'-','') AS PERIOD_DATE_ID
, HDR.ENTRY_TYPE AS ENTRY_TYPE
, HDR.STATUS AS STATUS
, HDR.SUBMITTED_BY AS SUBMITTED_BY
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(HDR.SUBMITTED_DATE AS TIMESTAMP)) AS SUBMITTED_LOCAL_DATETIME
, TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(HDR.SUBMITTED_DATE AS TIMESTAMP)),'YYYYMMDD') AS SUBMITTED_LOCAL_DATE_ID
, HDR.SUBMITTED_DATE AS SUBMITTED_UTC_DATETIME
, DTL.MATERIAL_TYPE_ID  AS MATERIAL_TYPE_ID 
, MT.NAME AS MATERIAL_TYPE
, DTL.UOM AS UOM

--Metrics
, DTL.VOLUME AS INVENTORY_QTY

--Metadata Attributes
, DTL.CREATED_BY AS CREATED_BY
, DTL.CREATED_ON AS CREATED_ON_UTC_DATETIME
, DTL.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, DTL.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC_DATETIME
, SYSDATE() AS INSERT_UTC_DATETIME

FROM
{{ source('CES_MSCM', 'CRP_INVENTORY_HDR') }} AS HDR
INNER JOIN {{ source('CES_MSCM', 'CRP_INVENTORY_DTL') }} AS DTL
ON HDR.ID = DTL.CRP_INVENTORY_HDR_ID
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS
ON HDR.CRP_ID = PS.SITE_NUMBER
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANTS') }} AS P
ON PS.PARTICIPANT_ID = P.PARTICIPANT_ID
INNER JOIN {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS MT
ON DTL.MATERIAL_TYPE_ID = MT.ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON HDR.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
INNER JOIN (
  SELECT
  H.ID
  , ROW_NUMBER() OVER (PARTITION BY H.CRP_ID, H.PERIOD, H.ENTRY_TYPE, H.STATUS ORDER BY H.LAST_MODIFIED_ON DESC) AS RN
  FROM {{ source('CES_MSCM', 'CRP_INVENTORY_HDR') }} AS H
) FILTER
ON HDR.ID = FILTER.ID
WHERE FILTER.RN = 1