SELECT
--Key naming convention applied for clarity "<TABLE NAME>_KEY". Dbt Util applied.
--Dimension Key
  {{ dbt_utils.generate_surrogate_key(['D.DATE_ID']) }} as DIM_DATE_KEY

--Natural Key
, D.DATE_ID as DATE_ID

--Attributes
, D.DT AS "DATE"
, DAY(D.DT) AS DAY
, DAYNAME(D.DT) AS DAY_NAME
, DAYOFWEEKISO(D.DT) AS DAY_OF_WEEK
, WEEKISO(D.DT) AS ISO_WEEK
, NEXT_DAY(D.DT - 1, 'SUNDAY') - 6 AS WEEK_START
, NEXT_DAY(D.DT - 1, 'SUNDAY') AS WEEK_END
, TO_CHAR(NEXT_DAY(D.DT - 1, 'SUNDAY') - 6,'DD/MM/YYYY') || ' - ' || TO_CHAR(NEXT_DAY(D.DT - 1, 'SUNDAY'),'DD/MM/YYYY') AS WEEK_PERIOD
, MONTH(D.DT) AS MONTH
, TO_CHAR(D.DT, 'MMMM') AS MONTH_NAME
, TO_CHAR(D.DT, 'MON') AS MONTH_NAME_ABBR
, QUARTER(D.DT) AS QUARTER
, YEAR(D.DT) AS YEAR
, YEAR(D.DT) || '-' || QUARTER(D.DT) AS YEAR_QUARTER
, YEAR(D.DT) || '-' || TO_CHAR(D.DT, 'MM') AS YEAR_MONTH
, YEAROFWEEKISO(D.DT) || '-' || TO_CHAR(WEEKISO(D.DT),'FM00') AS YEAR_WEEK_ISO
, CASE WHEN DAYOFWEEKISO(D.DT) IN (6,7) THEN 'WEEKEND' ELSE 'WEEKDAY' END AS DAY_TYPE
, YEAR(D.DT) + FLOOR(MONTH(D.DT) /7) AS FISCAL_YEAR
, 'FY' || TO_CHAR(YEAR(D.DT) + FLOOR(MONTH(D.DT) /7)) AS FISCAL_FY
, (YEAR(D.DT) + FLOOR(MONTH(D.DT) /7) - 1) || ' - ' || (YEAR(D.DT) + FLOOR(MONTH(D.DT)/7) ) AS FISCAL_YEAR_PERIOD
, QUARTER(D.DT) + 2 * SIGN(2.5 - QUARTER(D.DT)) AS FISCAL_QUARTER
, -(YEAR(D.DT) || QUARTER(D.DT)) AS YEAR_QUARTER_ORDER_DESC
, -TO_CHAR(D.DT, 'YYYYMM') AS YEAR_MONTH_ORDER_DESC
, -TO_NUMBER(YEAROFWEEKISO(D.DT) || TO_CHAR(WEEKISO(D.DT),'FM00')) AS YERA_WEEK_ISO_ORDER_DESC
, DATEADD(DD, -1, D.DT) AS DATE_FILTER
, COUNT(*) OVER (PARTITION BY YEAR(D.DT) || '-' || TO_CHAR(D.DT, 'MM')) AS NUM_DAYS_MONTH
, COUNT(*) OVER (PARTITION BY YEAR(D.DT) || '-' || QUARTER(D.DT)) AS NUM_DAYS_QUARTER
, CASE WHEN D.DT = LAST_DAY(D.DT, WEEK) THEN 1 ELSE 0 END AS WEEK_END_FLAG
, CASE WHEN D.DT = LAST_DAY(D.DT, MONTH) THEN 1 ELSE 0 END AS MONTH_END_FLAG
, CASE WHEN D.DT = LAST_DAY(D.DT, QUARTER) THEN 1 ELSE 0 END AS QUARTER_END_FLAG
, CASE WHEN D.DT = LAST_DAY(D.DT, YEAR) THEN 1 ELSE 0 END AS YEAR_END_FLAG
, CASE WHEN DATEDIFF('DAY', D.DT, CONVERT_TIMEZONE('UTC', 'Australia/NSW', SYSDATE())) < 0 THEN 0 ELSE DATEDIFF('WEEK', D.DT, CONVERT_TIMEZONE('UTC', 'Australia/NSW', SYSDATE())) + 1 END AS LAST_N_WEEK
, CASE WHEN DATEDIFF('DAY', D.DT, CONVERT_TIMEZONE('UTC', 'Australia/NSW', SYSDATE())) < 0 THEN 0 ELSE DATEDIFF('MONTH', D.DT, CONVERT_TIMEZONE('UTC', 'Australia/NSW', SYSDATE())) + 1 END AS LAST_N_MONTH
, CASE WHEN DATEDIFF('DAY', D.DT, CONVERT_TIMEZONE('UTC', 'Australia/NSW', SYSDATE())) < 0 THEN 0 ELSE DATEDIFF('QUARTER', D.DT, CONVERT_TIMEZONE('UTC', 'Australia/NSW', SYSDATE())) + 1 END AS LAST_N_QUARTER
, CASE WHEN DATEDIFF('DAY', D.DT, CONVERT_TIMEZONE('UTC', 'Australia/NSW', SYSDATE())) < 0 THEN 0 ELSE DATEDIFF('YEAR', D.DT, CONVERT_TIMEZONE('UTC', 'Australia/NSW', SYSDATE())) + 1 END AS LAST_N_YEAR
, CASE WHEN DATEDIFF('DAY', D.DT, CONVERT_TIMEZONE('UTC', 'Australia/NSW', SYSDATE())) < 0 THEN 0 ELSE (YEAR(CONVERT_TIMEZONE('UTC', 'Australia/NSW', SYSDATE())) + FLOOR(MONTH(CONVERT_TIMEZONE('UTC', 'Australia/NSW', SYSDATE())) /7)) - (YEAR(D.DT) + FLOOR(MONTH(D.DT) /7)) + 1 END AS LAST_N_FY
, CASE WHEN TO_CHAR(D.DT, 'YYYYMMDD') = TO_CHAR(CONVERT_TIMEZONE('UTC', 'Australia/NSW', SYSDATE()), 'YYYYMMDD') THEN 1 ELSE 0 END AS CURRENT_DAY_FLAG
, H_NSW.HOLIDAY_NAME AS HOLIDAY_NSW
, H_QLD.HOLIDAY_NAME AS HOLIDAY_QLD
, H_WA.HOLIDAY_NAME AS HOLIDAY_WA
, H_VIC.HOLIDAY_NAME AS HOLIDAY_VIC
, H_TAS.HOLIDAY_NAME AS HOLIDAY_TAS
, CASE WHEN DAYOFWEEKISO(D.DT) IN (6,7) OR H_NSW.HOLIDAY_NAME IS NOT NULL THEN 0 ELSE 1 END AS WORKDAY_FLAG_NSW
, CASE WHEN DAYOFWEEKISO(D.DT) IN (6,7) OR H_QLD.HOLIDAY_NAME IS NOT NULL THEN 0 ELSE 1 END AS WORKDAY_FLAG_QLD
, CASE WHEN DAYOFWEEKISO(D.DT) IN (6,7) OR H_WA.HOLIDAY_NAME IS NOT NULL THEN 0 ELSE 1 END AS WORKDAY_FLAG_WA
, CASE WHEN DAYOFWEEKISO(D.DT) IN (6,7) OR H_VIC.HOLIDAY_NAME IS NOT NULL THEN 0 ELSE 1 END AS WORKDAY_FLAG_VIC
, CASE WHEN DAYOFWEEKISO(D.DT) IN (6,7) OR H_TAS.HOLIDAY_NAME IS NOT NULL THEN 0 ELSE 1 END AS WORKDAY_FLAG_TAS
, CASE WHEN DAYOFWEEKISO(D.DT) IN (6,7) AND H_NSW.HOLIDAY_NAME IS NULL THEN 1 ELSE 0 END AS WEEKEND_NON_HOLIDAY_FLAG_NSW
, CASE WHEN DAYOFWEEKISO(D.DT) IN (6,7) AND H_QLD.HOLIDAY_NAME IS NULL THEN 1 ELSE 0 END AS WEEKEND_NON_HOLIDAY_FLAG_QLD
, CASE WHEN DAYOFWEEKISO(D.DT) IN (6,7) AND H_WA.HOLIDAY_NAME IS NULL THEN 1 ELSE 0 END AS WEEKEND_NON_HOLIDAY_FLAG_WA
, CASE WHEN DAYOFWEEKISO(D.DT) IN (6,7) AND H_VIC.HOLIDAY_NAME IS NULL THEN 1 ELSE 0 END AS WEEKEND_NON_HOLIDAY_FLAG_VIC
, CASE WHEN DAYOFWEEKISO(D.DT) IN (6,7) AND H_TAS.HOLIDAY_NAME IS NULL THEN 1 ELSE 0 END AS WEEKEND_NON_HOLIDAY_FLAG_TAS
, COUNT(D.DT) OVER (ORDER BY D.DT) AS DAYS_FROM_BEGINNING
, SUM(CASE WHEN DAYOFWEEKISO(D.DT) IN (6,7) OR H_NSW.HOLIDAY_NAME IS NOT NULL THEN 0 ELSE 1 END) OVER (ORDER BY D.DT) AS WORKDAYS_FROM_BEGINNING_NSW
, SUM(CASE WHEN DAYOFWEEKISO(D.DT) IN (6,7) OR H_QLD.HOLIDAY_NAME IS NOT NULL THEN 0 ELSE 1 END) OVER (ORDER BY D.DT) AS WORKDAYS_FROM_BEGINNING_QLD
, SUM(CASE WHEN DAYOFWEEKISO(D.DT) IN (6,7) OR H_WA.HOLIDAY_NAME IS NOT NULL THEN 0 ELSE 1 END) OVER (ORDER BY D.DT) AS WORKDAYS_FROM_BEGINNING_WA
, SUM(CASE WHEN DAYOFWEEKISO(D.DT) IN (6,7) OR H_VIC.HOLIDAY_NAME IS NOT NULL THEN 0 ELSE 1 END) OVER (ORDER BY D.DT) AS WORKDAYS_FROM_BEGINNING_VIC
, SUM(CASE WHEN DAYOFWEEKISO(D.DT) IN (6,7) OR H_TAS.HOLIDAY_NAME IS NOT NULL THEN 0 ELSE 1 END) OVER (ORDER BY D.DT) AS WORKDAYS_FROM_BEGINNING_TAS
, SUM(CASE WHEN DAYOFWEEKISO(D.DT) IN (6,7) OR H_NSW.HOLIDAY_NAME IS NOT NULL THEN 1 ELSE 0 END) OVER (ORDER BY D.DT) AS NON_WORKDAYS_FROM_BEGINNING_NSW
, SUM(CASE WHEN DAYOFWEEKISO(D.DT) IN (6,7) OR H_QLD.HOLIDAY_NAME IS NOT NULL THEN 1 ELSE 0 END) OVER (ORDER BY D.DT) AS NON_WORKDAYS_FROM_BEGINNING_QLD
, SUM(CASE WHEN DAYOFWEEKISO(D.DT) IN (6,7) OR H_WA.HOLIDAY_NAME IS NOT NULL THEN 1 ELSE 0 END) OVER (ORDER BY D.DT) AS NON_WORKDAYS_FROM_BEGINNING_WA
, SUM(CASE WHEN DAYOFWEEKISO(D.DT) IN (6,7) OR H_VIC.HOLIDAY_NAME IS NOT NULL THEN 1 ELSE 0 END) OVER (ORDER BY D.DT) AS NON_WORKDAYS_FROM_BEGINNING_VIC
, SUM(CASE WHEN DAYOFWEEKISO(D.DT) IN (6,7) OR H_TAS.HOLIDAY_NAME IS NOT NULL THEN 1 ELSE 0 END) OVER (ORDER BY D.DT) AS NON_WORKDAYS_FROM_BEGINNING_TAS
, SUM(CASE WHEN DAYOFWEEKISO(D.DT) IN (6,7) AND H_NSW.HOLIDAY_NAME IS NULL THEN 1 ELSE 0 END) OVER (ORDER BY D.DT) AS WEEKENDS_NON_HOLIDAY_FROM_BEGINNING_NSW
, SUM(CASE WHEN DAYOFWEEKISO(D.DT) IN (6,7) AND H_QLD.HOLIDAY_NAME IS NULL THEN 1 ELSE 0 END) OVER (ORDER BY D.DT) AS WEEKENDS_NON_HOLIDAY_FROM_BEGINNING_QLD
, SUM(CASE WHEN DAYOFWEEKISO(D.DT) IN (6,7) AND H_WA.HOLIDAY_NAME IS NULL THEN 1 ELSE 0 END) OVER (ORDER BY D.DT) AS WEEKENDS_NON_HOLIDAY_FROM_BEGINNING_WA
, SUM(CASE WHEN DAYOFWEEKISO(D.DT) IN (6,7) AND H_VIC.HOLIDAY_NAME IS NULL THEN 1 ELSE 0 END) OVER (ORDER BY D.DT) AS WEEKENDS_NON_HOLIDAY_FROM_BEGINNING_VIC
, SUM(CASE WHEN DAYOFWEEKISO(D.DT) IN (6,7) AND H_TAS.HOLIDAY_NAME IS NULL THEN 1 ELSE 0 END) OVER (ORDER BY D.DT) AS WEEKENDS_NON_HOLIDAY_FROM_BEGINNING_TAS
FROM (
    SELECT TO_DATE('31/12/2015', 'DD/MM/YYYY') + N AS DT
    , TO_CHAR(TO_DATE('31/12/2015', 'DD/MM/YYYY') + N, 'YYYYMMDD') AS DATE_ID
    FROM (
        SELECT SEQ4() + 1 as N
        FROM TABLE(GENERATOR(ROWCOUNT => 10000))
    )
) D
LEFT JOIN (
    SELECT
    H.DATE_KEY,
    H.HOLIDAY_NAME
    FROM {{ source('LOOKUPS', 'AUSTRALIA_PUBLIC_HOLIDAYS') }} AS H
    WHERE H.JURISDICTION = 'NSW'
) H_NSW
ON TO_CHAR(D.DT, 'YYYYMMDD') = H_NSW.DATE_KEY
LEFT JOIN (
    SELECT
    H.DATE_KEY,
    H.HOLIDAY_NAME
    FROM {{ source('LOOKUPS', 'AUSTRALIA_PUBLIC_HOLIDAYS') }} AS H
    WHERE H.JURISDICTION = 'QLD'
) H_QLD
ON TO_CHAR(D.DT, 'YYYYMMDD') = H_QLD.DATE_KEY
LEFT JOIN (
    SELECT
    H.DATE_KEY,
    H.HOLIDAY_NAME
    FROM {{ source('LOOKUPS', 'AUSTRALIA_PUBLIC_HOLIDAYS') }} AS H
    WHERE H.JURISDICTION = 'WA'
) H_WA
ON TO_CHAR(D.DT, 'YYYYMMDD') = H_WA.DATE_KEY
LEFT JOIN (
    SELECT
    H.DATE_KEY,
    H.HOLIDAY_NAME
    FROM {{ source('LOOKUPS', 'AUSTRALIA_PUBLIC_HOLIDAYS') }} AS H
    WHERE H.JURISDICTION = 'VIC'
) H_VIC
ON TO_CHAR(D.DT, 'YYYYMMDD') = H_VIC.DATE_KEY
LEFT JOIN (
    SELECT
    H.DATE_KEY,
    H.HOLIDAY_NAME
    FROM {{ source('LOOKUPS', 'AUSTRALIA_PUBLIC_HOLIDAYS') }} AS H
    WHERE H.JURISDICTION = 'TAS'
) H_TAS
ON TO_CHAR(D.DT, 'YYYYMMDD') = H_TAS.DATE_KEY