WITH SITES_CTE AS(
    SELECT 
    S.MULTI_SCHEME_ID,
    S.SCHEME, 
    S.SITE_NUMBER, 
    S.SITE_NAME,
    R.DATE AS WEEK_START,
    R.YEAR_WEEK_ISO, 
    R.WEEK_END, 
    S.STATUS
    FROM {{ ref('DIM_SITE_CRP') }} AS S
    CROSS JOIN {{ ref('DIM_DATE') }} AS R
    WHERE R.DAY_NAME = 'Mon' 
    AND S.MULTI_SCHEME_ID LIKE ANY ('10002%','10003%')
    AND R.DATE BETWEEN '2023-11-01' AND SYSDATE()
)
,AUDIT_CTE AS(
    SELECT 
    C.SITE_NUMBER, 
    C.YEAR_WEEK_ISO, 
    C.WEEK_START, 
    C.WEEK_END, 
    S.STATUS,
    S.LAST_MODIFIED_ON_UTC_DATETIME AS LAST_MODIFIED_ON_UTC,
    S.DISPLAY_IN_MARKETING
    FROM SITES_CTE C
    LEFT JOIN {{ ref('DIM_SITE_CRP_HIST') }} AS S
    ON S.SITE_NUMBER = C.SITE_NUMBER 
    AND S.LAST_MODIFIED_ON_UTC_DATETIME <= C.WEEK_END 
    QUALIFY ROW_NUMBER() OVER (PARTITION BY C.SITE_NUMBER, C.YEAR_WEEK_ISO ORDER BY S.LAST_MODIFIED_ON_UTC_DATETIME DESC) =1
)
,NOP_CLAIM_CTE AS(
    SELECT DISTINCT
    N.SITE_NUMBER,
    R.WEEK_START AS WEEK_START
    FROM {{ ref('NOP_CLAIM') }} AS N
    LEFT JOIN {{ ref('DIM_DATE') }} AS R
    ON R.DATE_ID = N.PERIOD_KEY
)
SELECT
--Key naming convention applied for clarity "<TABLE NAME>_KEY". Dbt Util applied.
--Dimension Key
{{ dbt_utils.generate_surrogate_key(['C.MULTI_SCHEME_ID', 'C.SITE_NUMBER', 'C.WEEK_START']) }} as DIM_NOP_UNSUBMITTED_CLAIM_WEEKLY_KEY

--Natural Key
, C.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, C.SITE_NUMBER AS SITE_NUMBER
, C.WEEK_START AS WEEK_START

--Attributes
, C.WEEK_END AS WEEK_END
, C.SCHEME AS SCHEME
, C.SITE_NAME AS SITE_NAME
, C.STATUS AS STATUS

--Metadata Attributes
, SYSDATE() AS INSERT_UTC_DATETIME

FROM SITES_CTE C
LEFT JOIN AUDIT_CTE A 
ON C.SITE_NUMBER = A.SITE_NUMBER 
AND C.YEAR_WEEK_ISO = A.YEAR_WEEK_ISO
LEFT JOIN NOP_CLAIM_CTE P 
ON C.SITE_NUMBER = P.SITE_NUMBER
AND C.WEEK_START = P.WEEK_START
WHERE A.DISPLAY_IN_MARKETING = 1 
AND P.SITE_NUMBER IS NULL