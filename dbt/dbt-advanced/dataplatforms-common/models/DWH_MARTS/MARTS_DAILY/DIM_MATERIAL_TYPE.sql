SELECT
--Key naming convention applied for clarity "<TABLE NAME>_KEY". Dbt Util applied.
--Dimension Key
  {{ dbt_utils.generate_surrogate_key(['MT.ID']) }} as DIM_MATERIAL_TYPE_KEY

--Natural Key
, MT.ID AS MATERIAL_TYPE_ID

--Attributes
, MT.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, MT.NAME AS MATERIAL_TYPE_ALL
, CASE WHEN MT.ID IN ('WA_GLASSAMBER', 'WA_GLASSFLINT', 'WA_GLASSGREEN') THEN 'Glass - Mixed' WHEN MT.ID = 'WA_PETWHITE' THEN 'PET - Colour' ELSE MT.NAME END AS MATERIAL_TYPE
, CASE WHEN MT.ID IN ('STEEL', 'WA_STEEL', 'WA_PETWHITE', 'OTHER', 'WA_OTHER', 'HDPE', 'WA_HDPE') THEN 'Other' ELSE MT.NAME END AS MATERIAL_TYPE_LOGISTICS
, CASE WHEN MT.ID LIKE '%GLASS%' THEN 'Glass' ELSE 'Non Glass' END AS GLASS_FLAG
, MT.DISPLAY_ORDER AS DISPLAY_ORDER
, MT.REFUND_ELIGIBLE AS REFUND_ELIGIBLE

--Metadata Attributes
, SYSDATE() AS INSERT_UTC_DATETIME

FROM
{{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS MT
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON MT.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID