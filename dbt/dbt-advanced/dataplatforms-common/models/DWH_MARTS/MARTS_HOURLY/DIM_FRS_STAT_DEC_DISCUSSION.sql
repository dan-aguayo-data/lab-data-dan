SELECT
--Key naming convention applied for clarity "<TABLE NAME>_KEY". Dbt Util applied.
--Dimension Key
 {{ dbt_utils.generate_surrogate_key(['D.ID']) }} AS DIM_FRS_STAT_DEC_DISCUSSION_KEY

--Natural Key Cols
, D.ID AS ID

--Attributes
, D.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, D.MFG_STATUTORY_DECLARATION_ID AS MFG_STATUTORY_DECLARATION_ID
, D.MANUFACTURER_ID AS MANUFACTURER_ID
, D.COMMENT_TEXT AS COMMENT
, D.COMMENT_TYPE AS COMMENT_TYPE

--Metadata Attributes
, D.CREATED_BY AS CREATED_BY
, CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, D.CREATED_ON) AS CREATED_ON_LOCAL_DATETIME
, D.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, D.LAST_MODIFIED_ON) AS LAST_MODIFIED_ON_LOCAL_DATETIME
, SYSDATE() AS INSERT_UTC_DATETIME

FROM
{{ source('CES_MSCM', 'MFG_STATUTORY_DECLARATION_DISCUSSION') }} AS D
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON D.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID