SELECT
--Key naming convention applied for clarity "<TABLE NAME>_KEY". Dbt Util applied.
--Dimension Key
{{ dbt_utils.generate_surrogate_key(['OH.AUDIT_ID']) }} as DIM_SITE_CRP_HOUR_HIST_KEY

--Natural Key
, OH.AUDIT_ID AS AUDIT_ID

--Attributes
, S.MULTI_SCHEME_ID  AS MULTI_SCHEME_ID 
, SCHEME.NAME AS SCHEME
, OH.MDT_SITE_OPENING_HOURS_ID AS ID
, S.SITE_NUMBER AS SITE_NUMBER
, OH.OPEN_24_HOURS AS OPEN_24_HOURS
, OH.HOURS_MONDAY_OPEN AS MON_OPEN
, OH.HOURS_MONDAY_CLOSE AS MON_CLOSE
, OH.HOURS_TUESDAY_OPEN AS TUE_OPEN
, OH.HOURS_TUESDAY_CLOSE AS TUE_CLOSE
, OH.HOURS_WEDNESDAY_OPEN AS WED_OPEN
, OH.HOURS_WEDNESDAY_CLOSE AS WED_CLOSE
, OH.HOURS_THURSDAY_OPEN AS THU_OPEN
, OH.HOURS_THURSDAY_CLOSE AS THU_CLOSE
, OH.HOURS_FRIDAY_OPEN AS FRI_OPEN
, OH.HOURS_FRIDAY_CLOSE AS FRI_CLOSE
, OH.HOURS_SATURDAY_OPEN AS SAT_OPEN
, OH.HOURS_SATURDAY_CLOSE AS SAT_CLOSE
, OH.HOURS_SUNDAY_OPEN AS SUN_OPEN
, OH.HOURS_SUNDAY_CLOSE AS SUN_CLOSE
, OH.SPECIAL_TRADING_HOURS AS SPECIAL_TRADING_HOURS

--Metadata Attributes
, OH.AUDIT_TYPE
, OH.AUDIT_DATE AS AUDIT_UTC_DATETIME
, OH.AUDIT_USER
, OH.CREATED_BY AS CREATED_BY
, OH.CREATED_ON AS CREATED_ON_UTC_DATETIME
, OH.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, OH.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC_DATETIME
, SYSDATE() AS INSERT_UTC_DATETIME


FROM
{{ source('CES_MSCM', 'MDT_SITE_OPENING_HOURS_A') }} AS OH
INNER JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES_A') }} AS PS
ON PS.PARTICIPANT_SITE_ID = OH.PARTICIPANT_SITE_ID
LEFT JOIN {{ ref('DIM_SITE_CRP') }} AS S
ON PS.SITE_NUMBER = S.SITE_NUMBER
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON S.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID