--############ MATERIAL SALES MART ############--

SELECT
--Dbt Util not applied here. Key is already a hash from source.
--Fact Key
 {{ dbt_utils.generate_surrogate_key(['B.ID']) }} AS FACT_AUCTION_BID_KEY

--Foreign Key
 , {{ dbt_utils.generate_surrogate_key(["TO_NUMBER(B.MULTI_SCHEME_ID, 38, 0)"]) }} AS DIM_SCHEME_KEY
 , {{ dbt_utils.generate_surrogate_key(["B.BIDDER"]) }} AS DIM_SITE_RECYCLER_BIDDER_KEY
 , {{ dbt_utils.generate_surrogate_key(['B.AUCTION_EVENT_LOT_ID']) }} AS FACT_AUCTION_EVENT_LOT_KEY
 , {{ dbt_utils.generate_surrogate_key(["TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(B.SUBMITTED_ON AS TIMESTAMP)),'YYYYMMDD')"]) }} AS DIM_DATE_BID_SUBMITTED_LOCAL_KEY
 , {{ dbt_utils.generate_surrogate_key(["TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(P.SUBMITTED_ON AS TIMESTAMP)),'YYYYMMDD')"]) }} AS DIM_DATE_PROXY_SUBMITTED_LOCAL_KEY


--Natural Key
, B.AUCTION_EVENT_LOT_ID AS EVENT_LOT_ID --- NATURAL KEY USED TO JOIN WITH EVENT_LOT_ID
,B.MULTI_SCHEME_ID  AS MULTI_SCHEME_ID 
, SCHEME.NAME AS SCHEME

, B.BIDDER AS BIDDER_SITE_NUMBER
, R.SITE_NAME AS BIDDER_SITE_NAME
, B.AUCTION_PROXY_BID_ID AS PROXY_BID_ID

--Attributes
, CASE WHEN B.AUCTION_PROXY_BID_ID IS NULL THEN 'Manual Bid' ELSE 'Proxy Bid' END AS BID_TYPE
, CASE WHEN E.END_DATE<B.SUBMITTED_ON OR E.END_DATE<P.SUBMITTED_ON THEN 1 ELSE 0 END AS OVERTIME_BID

--Metrics
, B.BID_PRICE_PER_TONNE AS BID_PRICE_PER_TONNE
, P.STARTING_BID AS PROXY_STARTING_BID
, P.MAXIMUM_BID AS PROXY_MAXIMUM_BID
, B.CANCELLED_BY AS CANCELLED_BY
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(B.SUBMITTED_ON AS TIMESTAMP)) AS BID_SUBMITTED_ON_LOCAL_DATETIME
, CAST(TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(B.SUBMITTED_ON AS TIMESTAMP)),'YYYYMMDD') AS NUMBER) AS BID_SUBMITTED_ON_LOCAL_DATE_ID
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(P.SUBMITTED_ON AS TIMESTAMP)) AS PROXY_SUBMITTED_ON_LOCAL_DATETIME
, CAST(TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(P.SUBMITTED_ON AS TIMESTAMP)),'YYYYMMDD') AS NUMBER) AS PROXY_SUBMITTED_ON_LOCAL_DATE_ID
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(B.CANCELLED_ON AS TIMESTAMP)) AS CANCELLED_ON_LOCAL_DATETIME

--Metadata Attributes

, B.CREATED_BY AS CREATED_BY
, B.CREATED_ON AS CREATED_ON_UTC_DATETIME
, B.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, B.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC_DATETIME
, SYSDATE() AS INSERT_UTC_DATETIME


FROM
{{ source('CES_MSCM', 'AUCTION_BID') }} AS B
LEFT JOIN {{ source('CES_MSCM', 'AUCTION_PROXY_BIDS') }} AS P
ON B.AUCTION_EVENT_LOT_ID = P.AUCTION_EVENT_LOT_ID
AND B.BIDDER = P.BIDDER
AND B.AUCTION_PROXY_BID_ID = P.AUCTION_PROXY_BID_ID
AND B.MSC_BIDDER_SITE_ID = P.MSC_BIDDER_SITE_ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON B.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'AUCTION_EVENT_LOT') }} AS A
ON A.ID = B.AUCTION_EVENT_LOT_ID
LEFT JOIN {{ source('CES_MSCM', 'AUCTION_EVENT') }} AS E
ON E.ID = A.AUCTION_EVENT_ID
LEFT JOIN {{ ref('DIM_SITE_RECYCLER') }} AS R
ON  B.BIDDER = R.SITE_NUMBER