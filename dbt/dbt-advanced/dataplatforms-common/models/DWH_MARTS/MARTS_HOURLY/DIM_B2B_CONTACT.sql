    post_hook=[
        "ALTER TABLE {{ this }} SET TAG DWH_GOLD.DATA_MART = 'B2B_PARTICIPANT'"
    ]
) 
}}


SELECT
--Key naming convention applied for clarity "<TABLE NAME>_KEY". Dbt Util applied.
--Dimension Key
  {{ dbt_utils.generate_surrogate_key(['CR.CONTACT_ROLE_ID']) }} AS DIM_B2B_CONTACT_KEY

--Natural Key
, CR.CONTACT_ROLE_ID  AS CONTACT_ROLE_ID

--Attributes
, PS.MULTI_SCHEME_ID  AS MULTI_SCHEME_ID 
, SCHEME.NAME AS SCHEME
, C.CONTACT_ID   AS CONTACT_ID  
, C.FIRST_NAME || ' ' || C.LAST_NAME AS CONTACT_NAME
, C.FIRST_NAME  AS FIRST_NAME 
, C.LAST_NAME  AS LAST_NAME 
, R_T.VALUE AS ROLE
, CR.ACTIVE AS ROLE_ACTIVE
, C.ACTIVE AS CONTACT_ACTIVE
, CR.ASSIGNMENT_TYPE AS ASSIGNMENT_TYPE
, C.PHONE_NUMBER  AS PHONE_NUMBER 
, C.PHONE_EXT  AS PHONE_EXT 
, C.MOBILE_PHONE_NUMBER AS MOBILE_PHONE_NUMBER
, TRIM(LOWER(C.EMAIL)) AS EMAIL
, 'live.com#' || TRIM(LOWER(C.EMAIL)) AS EMAIL_LIVE
, PS.SITE_NUMBER  AS SITE_NUMBER 
, PS.SITE_NAME  AS SITE_NAME 
, P.PARTICIPANT_NUMBER  AS SUPPLIER_NUMBER 
, P.PARTICIPANT_NAME  AS SUPPLIER_NAME 
, R_TT.VALUE AS TAXONOMY
, CAST(CR.EFFECTIVE_START_DATE AS DATE) AS EFFECTIVE_FROM_DATE
, CAST(CR.EFFECTIVE_END_DATE AS DATE) AS EFFECTIVE_TO_DATE
, CASE WHEN DATEADD(DAY,1,MAX(CR.CREATED_ON) OVER (PARTITION BY PS.MULTI_SCHEME_ID))>=SYSDATE() THEN 'Y' ELSE 'N' END AS CREATED_ON_LAST_1_DAY_EXTRACT
, CASE WHEN DATEADD(DAY,1,CR.CREATED_ON)>=SYSDATE() AND hour(CONVERT_TIMEZONE('UTC','Australia/Sydney',sysdate())) >= 16 THEN 'Y' ELSE 'N' END AS CREATED_ON_LAST_1_DAY
, CASE WHEN TO_CHAR(CR.EFFECTIVE_START_DATE,'yyyymm') = TO_CHAR(DATEADD(MONTH,-1,(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(SYSDATE() AS TIMESTAMP)))),'yyyymm') THEN 'New Account' WHEN TO_CHAR(CR.EFFECTIVE_END_DATE,'yyyymm') = TO_CHAR(DATEADD(MONTH,-1,(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(SYSDATE() AS TIMESTAMP)))),'yyyymm') THEN 'Deactivated Account' ELSE null END AS LAST_CALENDAR_MONTH_ACCOUNT_STATUS

--Metadata Attributes
, CR.CREATED_BY AS CREATED_BY
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(CR.CREATED_ON AS TIMESTAMP)) AS CREATED_ON_LOCAL_DATETIME
, CR.CREATED_ON AS CREATED_ON_UTC_DATETIME
, CR.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(CR.LAST_MODIFIED_ON AS TIMESTAMP)) AS LAST_MODIFIED_ON_LOCAL_DATETIME 
, CR.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC_DATETIME
, SYSDATE() AS INSERT_UTC_DATETIME

FROM
{{ source('CES_MSCM', 'MDT_CONTACTS') }} AS C
INNER JOIN {{ source('CES_MSCM', 'MDT_CONTACT_ROLES') }} AS CR 
ON C.CONTACT_ID = CR.CONTACT_ID
INNER JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS
ON CR.PARTICIPANT_SITE_ID = PS.PARTICIPANT_SITE_ID
INNER JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANTS') }} AS P
ON CR.PARTICIPANT_ID = P.PARTICIPANT_ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON PS.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'SCHEME_REF_CODES') }} AS R_T
ON CR.ROLE_TYPE_ID = R_T.SCHEME_REF_CODES_ID
LEFT JOIN {{ source('CES_MSCM', 'SCHEME_REF_CODES') }} AS R_TT
ON PS.TAXONOMY_TYPE_ID || '' = R_TT.SCHEME_REF_CODES_ID || ''
WHERE PS.SITE_TYPE_ID != '1537' -- NOT CONSUMER