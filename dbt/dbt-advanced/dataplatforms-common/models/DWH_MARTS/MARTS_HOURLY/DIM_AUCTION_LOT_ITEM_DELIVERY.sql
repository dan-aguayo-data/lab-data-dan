 SELECT
--Dbt Util not applied here. Key is already a hash from source.
--Fact Key
  {{ dbt_utils.generate_surrogate_key(["CONCAT(D.LOT_ITEM_ID,'DELIVERY')"]) }}  AS DIM_AUCTION_LOT_ITEM_DELIVERY_KEY  --APPLY DIFFERENT FORMATION TO MAKE IT LOOK UNIQUE VS DIM_LOT_ITEM
--Foreign Key

--Natural Key
    ,D.ID AS DELIVERY_ID 
    ,L.MULTI_SCHEME_ID
    , SCHEME.NAME AS SCHEME
    ,D.LOT_ITEM_ID  

--Attributes
    ,CASE WHEN D.FINAL_STATE = 'EXP' THEN 1 ELSE 0 END AS EXPORT_FLAG     
    , D.FINAL_ADDRESS AS FINAL_ADDRESS 
    , D.FINAL_SUBURB AS FINAL_SUBURB 
    , D.FINAL_STATE AS FINAL_STATE 
    , D.FINAL_COUNTRY AS FINAL_COUNTRY 
    , D.FINAL_POST_CODE AS FINAL_POST_CODE  
    , D.FINAL_PHONE_NUMBER AS FINAL_PHONE_NUMBER 
    , D.DELIVERY_ADDRESS AS DELIVERY_ADDRESS  
    , D.DELIVERY_SUBURB AS DELIVERY_SUBURB 
    , D.DELIVERY_STATE AS DELIVERY_STATE 
    , D.DELIVERY_COUNTRY AS DELIVERY_COUNTRY 
    , D.DELIVERY_POST_CODE AS DELIVERY_POST_CODE 
    , D.DELIVERY_PHONE_NUMBER AS DELIVERY_PHONE_NUMBER 

--Metrics


--Metadata Attributes
    , D.CREATED_BY AS CREATED_BY    
    , D.CREATED_ON AS CREATED_ON_UTC_DATETIME
    , D.LAST_MODIFIED_BY AS LAST_MODIFIED_BY 
    , D.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC_DATETIME
    , SYSDATE() AS INSERT_UTC_DATETIME

    FROM  {{ source('CES_MSCM', 'LOT_ITEM_DELIVERY') }} AS D
    LEFT JOIN {{ source('CES_MSCM', 'LOT_ITEM') }} AS L
    ON D.LOT_ITEM_ID = L.ID
    INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
    ON L.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID