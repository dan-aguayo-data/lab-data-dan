{{
    config(
        materialized = 'incremental',
        incremental_strategy = 'merge',
        unique_key = 'FACT_CRP_COLLECTION_AGG_1_KEY',
        snowflake_warehouse= wh_selector_models("ETL_CES_DEV","ETL_CES_SIT","ETL_CES_UAT","ETL_CES_SMALL"),
                post_hook=["
                {% if is_incremental() %}
                DELETE FROM {{this}} a
                WHERE a.DELETE_FLAG = 'TRUE';
                {% else %}
                SELECT 1 ;
                {% endif %}
                ",
            "ALTER TABLE {{ this }} SET TAG DWH_GOLD.DATA_MART = 'CRP'"
                ]
    )
}}




WITH CRP_COLLECTION_DTL_REF AS ( --  USED IN FULL REFRESH TO CATCH REFERENCES (LINEAGE)

SELECT * FROM  {{ ref('FACT_CRP_COLLECTION') }}  -- Hundreds M rows

){% if is_incremental() %} , CRP_COLLECTION_AGG_1_STAGE AS (

SELECT
D.FACT_CRP_COLLECTION_KEY AS ID, 
{{ dbt_utils.generate_surrogate_key(['H.MULTI_SCHEME_ID', 'H.SITE_NUMBER','H.CONSUMER_ID','H.TRANSACTION_LOCAL_DATE_ID','H.PAYMENT_METHOD','H.SCHEME_CONSUMER_FLAG', 'H.TRANSACTION_BANDING', 'H.TRANSACTION_POSTCODE', 'C.CONSUMER_TYPE','D.MATERIAL_TYPE_ID','PD.NAME']) }} AS FACT_CRP_COLLECTION_AGG_1_KEY
FROM {{ source('COMMON_DWH_GOLD','FACT_CRP_COLLECTION_AGG') }} AS H
INNER JOIN CRP_COLLECTION_DTL_REF AS D
ON H.TRANSACTION_ID = D.TRANSACTION_ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON H.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'POS_DEVICE') }} AS PD
ON H.POS_DEVICE_ID = PD.ID
LEFT JOIN {{ source('COMMON_DWH_GOLD','DIM_CONSUMER') }}  AS C
ON H.CONSUMER_ID = C.CONSUMER_ID

),INCREMENTAL_DATE_REF AS (

 SELECT DATEADD(HOUR, {{var('general_delta_load_hours')}} , SYSDATE()) AS INCREMENTAL_DELTA

) ,INCREMENTAL_LOAD_INCOMING AS (
SELECT
D.FACT_CRP_COLLECTION_KEY AS ID
FROM {{ source('COMMON_DWH_GOLD','FACT_CRP_COLLECTION_AGG') }} AS H  -- Hundreds M rows
INNER JOIN CRP_COLLECTION_DTL_REF AS D
ON H.TRANSACTION_ID = D.TRANSACTION_ID 
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON H.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID 
LEFT JOIN {{ source('CES_MSCM', 'POS_DEVICE') }} AS PD  --9K ROWS
ON H.POS_DEVICE_ID = PD.ID 
LEFT JOIN {{ source('COMMON_DWH_GOLD','DIM_CONSUMER') }}  AS C --1.2 M ROWS
ON H.CONSUMER_ID = C.CONSUMER_ID 
WHERE 
(H.LAST_MODIFIED_ON_UTC_DATETIME >= (SELECT INCREMENTAL_DELTA FROM INCREMENTAL_DATE_REF)
OR D.LAST_MODIFIED_ON_UTC_DATETIME>= (SELECT INCREMENTAL_DELTA FROM INCREMENTAL_DATE_REF)
OR SCHEME.LAST_MODIFIED_ON >= (SELECT INCREMENTAL_DELTA FROM INCREMENTAL_DATE_REF)
OR  PD.LAST_MODIFIED_ON  >= (SELECT INCREMENTAL_DELTA FROM INCREMENTAL_DATE_REF)
OR C.LAST_MODIFIED_ON_UTC_DATETIME    >= (SELECT INCREMENTAL_DELTA FROM INCREMENTAL_DATE_REF)
)

) , initial_txn AS (
SELECT   
A.ID,
A.FACT_CRP_COLLECTION_AGG_1_KEY
FROM CRP_COLLECTION_AGG_1_STAGE A
INNER JOIN INCREMENTAL_LOAD_INCOMING B 
ON  A.ID = B.ID
GROUP BY A.ID, 
A.FACT_CRP_COLLECTION_AGG_1_KEY
),

RECALCULATE_CURRENT_KEYS AS (  --GET ALL DTL ID  associated with FACT_CRP_COLLECTION_AGG_1_KEY that was changed on the incremental load
    
SELECT DISTINCT 
A.FACT_CRP_COLLECTION_AGG_1_KEY
FROM CRP_COLLECTION_AGG_1_STAGE A
INNER JOIN initial_txn B
ON A.FACT_CRP_COLLECTION_AGG_1_KEY = B.FACT_CRP_COLLECTION_AGG_1_KEY
GROUP BY A.FACT_CRP_COLLECTION_AGG_1_KEY


), INCREMENTAL_LOAD_SCOPE AS (   -- WE HAVE TO RE-SUM THE TRANSACTION_ID BASED ON THE INCREMENTAL_ID
 
 SELECT DISTINCT
 A.ID
 FROM CRP_COLLECTION_AGG_1_STAGE A
 WHERE (A.ID IN  (SELECT DISTINCT ID FROM INCREMENTAL_LOAD_INCOMING) 
 OR A.FACT_CRP_COLLECTION_AGG_1_KEY  IN (SELECT FACT_CRP_COLLECTION_AGG_1_KEY FROM RECALCULATE_CURRENT_KEYS))

), DELETE_FLAG AS (

SELECT * FROM {{this}} a
WHERE NOT EXISTS  (SELECT 1 FROM CRP_COLLECTION_AGG_1_STAGE b
                    WHERE a.FACT_CRP_COLLECTION_AGG_1_KEY = b.FACT_CRP_COLLECTION_AGG_1_KEY )

), CRP_COLLECTION_DTL_INCREMENTAL AS (

SELECT D.* 
FROM CRP_COLLECTION_DTL_REF D
INNER JOIN INCREMENTAL_LOAD_SCOPE IL
ON D.FACT_CRP_COLLECTION_KEY = IL.ID

) {% endif %}

SELECT

--Fact Key
  {{ dbt_utils.generate_surrogate_key(['H.MULTI_SCHEME_ID', 'H.SITE_NUMBER','H.CONSUMER_ID','H.TRANSACTION_LOCAL_DATE_ID','H.PAYMENT_METHOD','H.SCHEME_CONSUMER_FLAG', 'H.TRANSACTION_BANDING', 'H.TRANSACTION_POSTCODE', 'C.CONSUMER_TYPE','D.MATERIAL_TYPE_ID','PD.NAME']) }} AS FACT_CRP_COLLECTION_AGG_1_KEY

--Foreign Key
 , H.DIM_SCHEME_KEY AS DIM_SCHEME_KEY
 , D.DIM_MATERIAL_TYPE_KEY AS DIM_MATERIAL_TYPE_KEY
 , H.DIM_SITE_CRP_KEY AS DIM_SITE_CRP_KEY
 , H.DIM_CONSUMER_KEY AS DIM_CONSUMER_KEY
 , H.DIM_DATE_TRANSACTION_LOCAL_KEY AS DIM_DATE_TRANSACTION_LOCAL_KEY

--Attributes
, H.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, H.SITE_NUMBER AS SITE_NUMBER
, H.CONSUMER_ID AS CONSUMER_ID
, H.TRANSACTION_LOCAL_DATE_ID AS TRANSACTION_LOCAL_DATE_ID
, H.PAYMENT_METHOD AS PAYMENT_METHOD
, H.SCHEME_CONSUMER_FLAG AS SCHEME_CONSUMER_FLAG
, H.TRANSACTION_BANDING AS TRANSACTION_BANDING
, H.TRANSACTION_POSTCODE AS TRANSACTION_POSTCODE
, C.CONSUMER_TYPE AS CONSUMER_TYPE
, D.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID
, PD.NAME AS POS_DEVICE_NAME

--Metrics
, COUNT(DISTINCT H.TRANSACTION_ID) AS TOTAL_TRANSACTIONS
, SUM(D.COLLECTION_QTY) AS TOTAL_QTY
, SUM(D.GROSS_AMT) AS TOTAL_GROSS_AMT
, SUM(D.GST_AMT) AS TOTAL_GST_AMT
, SUM(D.TAXABLE_AMT) AS TOTAL_TAXABLE_AMT

--Metadata Attributes
, SYSDATE() AS INSERT_UTC_DATETIME
, 'FALSE' AS DELETE_FLAG

FROM {{ref('FACT_CRP_COLLECTION_AGG') }}  AS H
{% if is_incremental() %}
INNER JOIN CRP_COLLECTION_DTL_INCREMENTAL AS D
ON H.TRANSACTION_ID = D.TRANSACTION_ID
{% else %}
INNER JOIN CRP_COLLECTION_DTL_REF  AS D
ON H.TRANSACTION_ID = D.TRANSACTION_ID
{% endif %}
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }}  AS SCHEME
ON H.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'POS_DEVICE') }} AS PD
ON H.POS_DEVICE_ID = PD.ID
LEFT JOIN  {{ ref('DIM_CONSUMER') }}  AS C
ON H.CONSUMER_ID = C.CONSUMER_ID
GROUP BY ALL
{% if is_incremental() %}


UNION ALL

SELECT
--Fact Key
   FACT_CRP_COLLECTION_AGG_1_KEY
--Foreign Key
 , DIM_SCHEME_KEY
 , DIM_MATERIAL_TYPE_KEY
 , DIM_SITE_CRP_KEY
 , DIM_CONSUMER_KEY
 , DIM_DATE_TRANSACTION_LOCAL_KEY
--Attributes
, MULTI_SCHEME_ID
, SCHEME
, SITE_NUMBER
, CONSUMER_ID
, TRANSACTION_LOCAL_DATE_ID
, PAYMENT_METHOD
, SCHEME_CONSUMER_FLAG
, TRANSACTION_BANDING
, TRANSACTION_POSTCODE
, CONSUMER_TYPE
, MATERIAL_TYPE_ID
, POS_DEVICE_NAME
--Metrics
,TOTAL_TRANSACTIONS
,TOTAL_QTY
,TOTAL_GROSS_AMT
,TOTAL_GST_AMT
,TOTAL_TAXABLE_AMT
,INSERT_UTC_DATETIME
, 'TRUE' AS DELETE_FLAG
FROM DELETE_FLAG

{% endif %}