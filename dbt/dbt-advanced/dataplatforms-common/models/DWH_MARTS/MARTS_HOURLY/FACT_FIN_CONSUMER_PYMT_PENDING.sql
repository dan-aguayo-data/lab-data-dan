--############ SCHEME_FINANCE_PYMT ############--
WITH PPP_TABLE AS (

    SELECT
    P.MULTI_SCHEME_ID, 
    P.PARTICIPANT_SITE_ID,
    P.LAST_MODIFIED_ON
    FROM {{ source('CES_MSCM', 'PYMT_PAY_PARTY_PROFILES') }} AS P
    WHERE CAST(SYSDATE() AS DATE) BETWEEN P.START_DATE_ACTIVE AND NVL(P.END_DATE_ACTIVE, CAST(SYSDATE() AS DATE))
    QUALIFY ROW_NUMBER() OVER (PARTITION BY P.MULTI_SCHEME_ID, P.PARTICIPANT_SITE_ID ORDER BY LAST_MODIFIED_ON DESC) = 1

), MAX_TRXN_HEDAER_TABLE AS (

    SELECT PHD.POS_TXN_NUM
    , MAX(PHD.PYMT_TRXN_HEADER_ID) PYMT_TRXN_HEADER_ID
    FROM {{ source('CES_MSCM', 'PYMT_TRANSACTION_HEADERS') }} AS PHD
    GROUP BY PHD.POS_TXN_NUM

), PYMT_TRXN_HDR_ERROR AS (

    SELECT PTH.POS_TXN_NUM
         , PTH.PARTICIPANT_NUMBER                     AS CONSUMER_ID
         , PTH.PAYMENT_METHOD
         , PTH.CREATED_ON                             AS TRANSACTION_DATE
         , PTH.AMOUNT
         , PSS.STATUS                                 AS TRANSACTION_STATUS
         , PTH.MULTI_SCHEME_ID
         , PTH.PAY_REF_NUMBER
         , PPP.LAST_MODIFIED_ON                       AS BANK_DETAILS_UPDATED_ON
         , 'CUSTOMER NEED TO UPDATE THE BANK DETAILS' AS ACTION
         , PTH.CREATED_BY
         , PTH.CREATED_ON
         ,PTH.LAST_MODIFIED_ON
         ,PTH.LAST_MODIFIED_BY
    FROM {{ source('CES_MSCM', 'PYMT_TRANSACTION_HEADERS') }} AS PTH
        INNER JOIN (SELECT DISTINCT
        PPS.PYMT_TRXN_HEADER_ID,
        PPS.STATUS
        FROM  {{ source('CES_MSCM', 'PYMT_PAYMENT_STATUS') }} AS PPS
        WHERE PPS.STATUS IN ( 'ERROR_PAID', 'ERROR_PROCESSING' ) ) PSS
            ON PTH.PYMT_TRXN_HEADER_ID = PSS.PYMT_TRXN_HEADER_ID
        INNER JOIN MAX_TRXN_HEDAER_TABLE    PH
            ON PTH.PYMT_TRXN_HEADER_ID = PH.PYMT_TRXN_HEADER_ID
        INNER JOIN PPP_TABLE PPP
            ON PPP.PARTICIPANT_SITE_ID = PTH.PARTICIPANT_SITE_ID
        LEFT JOIN
        (
            SELECT DISTINCT
                PPS.PYMT_TRXN_HEADER_ID
            FROM {{ source('CES_MSCM', 'PYMT_PAYMENT_STATUS') }} AS PPS
            WHERE PPS.STATUS = 'PAID'
        )                                           P
            ON P.PYMT_TRXN_HEADER_ID = PH.PYMT_TRXN_HEADER_ID
    WHERE P.PYMT_TRXN_HEADER_ID IS NULL

), CONSUMER_REFUND_TRXN_NO_DETAIL AS (

SELECT  
POS_TXN_NUM
, CONSUMER_ID
, PAYMENT_METHOD
, TRANSACTION_DATE
, AMOUNT
, TRANSACTION_STATUS
, MULTI_SCHEME_ID
, PAY_REF_NUMBER
, BANK_DETAILS_UPDATED_ON
, ACTION
,CREATED_BY
,CREATED_ON
,LAST_MODIFIED_ON
,LAST_MODIFIED_BY

FROM  (
    SELECT HDR1.ID                  AS POS_TXN_NUM
         , HDR1.CONSUMER_ID
         , HDR1.PAYMENT_METHOD
         , HDR1.TRANSACTED_ON       AS TRANSACTION_DATE
         , SUM(DTL1.GROSS_AMOUNT)   AS AMOUNT
         , HDR1.STATUS              AS TRANSACTION_STATUS
         , HDR1.MULTI_SCHEME_ID
         , NULL                     AS PAY_REF_NUMBER
         , MAX(PP.LAST_MODIFIED_ON) AS BANK_DETAILS_UPDATED_ON
         , CASE
               WHEN COUNT(PP.SCHEME_PARTICIPANT_ID) = 0 THEN
                   'NO BANK DETAILS IN PAAS'
               ELSE
                   'BANK DETAILS AVAILABLE IN PAAS,NEED TO REPROCESS THE PAYMENT'
           END                      AS ACTION
        ,HDR1.LAST_MODIFIED_BY
        ,HDR1.LAST_MODIFIED_ON
        ,HDR1.CREATED_BY
        ,HDR1.CREATED_ON
    FROM {{ source('CES_MSCM', 'CONSUMER_REFUND_TXN_HDR') }}  AS HDR1
        INNER JOIN {{ source('CES_MSCM', 'CONSUMER_REFUND_TXN_DTL') }}  AS DTL1
            ON DTL1.TRANSACTION_ID = HDR1.ID
         LEFT JOIN (            SELECT
            P.MULTI_SCHEME_ID, 
            P.SCHEME_PARTICIPANT_ID,
            P.LAST_MODIFIED_ON
            FROM {{ source('CES_MSCM', 'PYMT_PAY_PARTY_PROFILES') }} AS P
            WHERE CAST(SYSDATE() AS DATE) BETWEEN P.START_DATE_ACTIVE AND nvl(P.END_DATE_ACTIVE, CAST(SYSDATE() AS DATE))
            QUALIFY ROW_NUMBER() OVER (PARTITION BY P.MULTI_SCHEME_ID, P.SCHEME_PARTICIPANT_ID ORDER BY LAST_MODIFIED_ON DESC) = 1) PP
            ON (PP.SCHEME_PARTICIPANT_ID = HDR1.CONSUMER_ID OR PP.SCHEME_PARTICIPANT_ID = HDR1.CONSUMER_ID || '002')
            AND PP.MULTI_SCHEME_ID = HDR1.MULTI_SCHEME_ID
    WHERE HDR1.PAYMENT_METHOD = 'SCHEME'
          AND HDR1.STATUS = 'FINAL'
    GROUP BY HDR1.ID
           , HDR1.CONSUMER_ID
           , HDR1.PAYMENT_METHOD
           , HDR1.TRANSACTED_ON
           , HDR1.STATUS
           , HDR1.MULTI_SCHEME_ID
            ,HDR1.LAST_MODIFIED_BY
            ,HDR1.LAST_MODIFIED_ON
            ,HDR1.CREATED_BY
            ,HDR1.CREATED_ON
) X

QUALIFY ROW_NUMBER() OVER (PARTITION BY POS_TXN_NUM, CONSUMER_ID, PAYMENT_METHOD, TRANSACTION_DATE, TRANSACTION_STATUS, MULTI_SCHEME_ID ORDER BY LAST_MODIFIED_ON DESC) = 1

), PYMT_TRXN_HEADER_WAITING_DETAIL AS (
    SELECT PTH.POS_TXN_NUM
         , PTH.PARTICIPANT_NUMBER                                                   AS CONSUMER_ID
         , PTH.PAYMENT_METHOD
         , PTH.CREATED_ON                                                           AS TRANSACTION_DATE
         , PTH.AMOUNT
         , PSS.STATUS                                                               AS TRANSACTION_STATUS
         , PTH.MULTI_SCHEME_ID
         , PTH.PAY_REF_NUMBER
         , PPP.LAST_MODIFIED_ON                                                     AS BANK_DETAILS_UPDATED_ON
         , 'RETURN PAYMENTS FROM BANK,WAITING FROM CUSTOMER TO UPDATE BANK DETAILS' AS ACTION
         , PTH.CREATED_BY
         ,PTH.CREATED_ON
         ,PTH.LAST_MODIFIED_ON
         ,PTH.LAST_MODIFIED_BY
    FROM {{ source('CES_MSCM', 'PYMT_TRANSACTION_HEADERS') }} AS PTH
        INNER JOIN (
            SELECT
            PPS.PAYMENT_STATUS_ID
            , PPS.PYMT_TRXN_HEADER_ID
            , PPS.STATUS
            , PPS.EFFECTIVE_FROM
            FROM
            {{ source('CES_MSCM', 'PYMT_PAYMENT_STATUS') }} AS PPS
            QUALIFY ROW_NUMBER() OVER (PARTITION BY PPS.PYMT_TRXN_HEADER_ID, PPS.STATUS ORDER BY PPS.PAYMENT_STATUS_ID DESC) = 1
            ) PSS
            ON PTH.PYMT_TRXN_HEADER_ID = PSS.PYMT_TRXN_HEADER_ID
        INNER JOIN MAX_TRXN_HEDAER_TABLE       PH
            ON PTH.PYMT_TRXN_HEADER_ID = PH.PYMT_TRXN_HEADER_ID
        INNER JOIN PPP_TABLE PPP
            ON PPP.PARTICIPANT_SITE_ID = PTH.PARTICIPANT_SITE_ID
               AND PSS.STATUS = 'VOID'
        LEFT JOIN
        (
            SELECT PTH1.POS_TXN_NUM
                 , MAX(PPS.EFFECTIVE_FROM) AS EFFECTIVE_FROM
            FROM {{ source('CES_MSCM', 'PYMT_PAYMENT_STATUS') }} AS PPS
                INNER JOIN {{ source('CES_MSCM', 'PYMT_TRANSACTION_HEADERS') }} AS PTH1
                    ON PPS.PYMT_TRXN_HEADER_ID = PTH1.PYMT_TRXN_HEADER_ID
                       AND PPS.STATUS = 'PAID'
            GROUP BY PTH1.POS_TXN_NUM
        )                                           X
            ON X.POS_TXN_NUM = PH.POS_TXN_NUM
    WHERE X.EFFECTIVE_FROM < PSS.EFFECTIVE_FROM
), BASE_TABLE AS (

SELECT 
POS_TXN_NUM
, CONSUMER_ID
, PAYMENT_METHOD
, TRANSACTION_DATE
, AMOUNT
, TRANSACTION_STATUS
, MULTI_SCHEME_ID
, PAY_REF_NUMBER
, BANK_DETAILS_UPDATED_ON
, ACTION
,CREATED_BY
,CREATED_ON
,LAST_MODIFIED_ON
,LAST_MODIFIED_BY
FROM PYMT_TRXN_HDR_ERROR
UNION ALL
SELECT 
POS_TXN_NUM
, CONSUMER_ID
, PAYMENT_METHOD
, TRANSACTION_DATE
, AMOUNT
, TRANSACTION_STATUS
, MULTI_SCHEME_ID
, PAY_REF_NUMBER
, BANK_DETAILS_UPDATED_ON
, ACTION
,CREATED_BY
,CREATED_ON
,LAST_MODIFIED_ON
,LAST_MODIFIED_BY
FROM CONSUMER_REFUND_TRXN_NO_DETAIL
UNION ALL
SELECT 
POS_TXN_NUM
, CONSUMER_ID
, PAYMENT_METHOD
, TRANSACTION_DATE
, AMOUNT
, TRANSACTION_STATUS
, MULTI_SCHEME_ID
, PAY_REF_NUMBER
, BANK_DETAILS_UPDATED_ON
, ACTION
,CREATED_BY
,CREATED_ON
,LAST_MODIFIED_ON
,LAST_MODIFIED_BY
FROM PYMT_TRXN_HEADER_WAITING_DETAIL

)      


SELECT

--Fact Key
 {{ dbt_utils.generate_surrogate_key(['A.POS_TXN_NUM']) }} AS FACT_FIN_CONSUMER_PYMT_PENDING_KEY
--Foreign Key
, {{ dbt_utils.generate_surrogate_key(["TO_NUMBER(A.MULTI_SCHEME_ID, 38, 0)"]) }} AS DIM_SCHEME_KEY
, {{ dbt_utils.generate_surrogate_key(['A.CONSUMER_ID']) }} AS DIM_CONSUMER_KEY
--, {{ dbt_utils.generate_surrogate_key(["to_char(PPP.PAY_PARTY_PROFILE_ID)"]) }} AS DIM_B2B_PAY_PARTY_PROFILE_KEY
, {{ dbt_utils.generate_surrogate_key(["TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(A.TRANSACTION_DATE AS TIMESTAMP)),'YYYYMMDD')"]) }} AS DIM_DATE_TRANSACTION_ON_LOCAL_KEY
, {{ dbt_utils.generate_surrogate_key(["TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(A.BANK_DETAILS_UPDATED_ON AS TIMESTAMP)),'YYYYMMDD')"]) }} AS DIM_DATE_BANK_DETAILS_UPDATED_LOCAL_KEY

--Natural Key
, A.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, A.POS_TXN_NUM AS POS_TXN_NUM
, A.CONSUMER_ID AS CONSUMER_ID
--, PPP.PAY_PARTY_PROFILE_ID AS PAY_PARTY_PROFILE_ID

--Attributes
, A.PAYMENT_METHOD AS PAYMENT_METHOD
, A.TRANSACTION_STATUS AS TRANSACTION_STATUS
, A.PAY_REF_NUMBER AS PAY_REF_NUMBER
, A.ACTION AS ACTION
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST( A.BANK_DETAILS_UPDATED_ON AS TIMESTAMP)) AS BANK_DETAILS_UPDATED_LOCAL_DATETIME
, TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(A.BANK_DETAILS_UPDATED_ON AS TIMESTAMP)),'YYYYMMDD') BANK_DETAILS_UPDATED_LOCAL_DATE_ID
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(A.TRANSACTION_DATE AS TIMESTAMP)) AS TRANSACTION_ON_LOCAL_DATETIME
, TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(A.TRANSACTION_DATE AS TIMESTAMP)),'YYYYMMDD') TRANSACTION_ON_LOCAL_DATE_ID

--Metrics
, A.AMOUNT AS PAYMENT_AMT

--Metadata Attributes
, A.CREATED_BY AS CREATED_BY
, A.CREATED_ON AS CREATED_ON_UTC_DATETIME
, A.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, A.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC_DATETIME
, SYSDATE() AS INSERT_UTC_DATETIME

FROM BASE_TABLE A 
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON A.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
