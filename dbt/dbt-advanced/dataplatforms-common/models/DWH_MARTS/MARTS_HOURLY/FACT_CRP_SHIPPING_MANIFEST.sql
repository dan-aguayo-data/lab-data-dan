                    CASE WHEN LEFT(CRP_SITE_NUMBER, 2) = 'WC' THEN PERIOD WHEN LEFT(CRP_SITE_NUMBER, 2) = 'QC' THEN TO_NUMBER(LEFT(PERIOD, 4) + 5) || SUBSTR(PERIOD, 5) END AS PERIOD, 
