                    CASE WHEN LEFT(CRP_SITE_NUMBER, 2) = 'WC' THEN GENERATED_DATE_LOCAL_DATETIME WHEN LEFT(CRP_SITE_NUMBER, 2) = 'QC' THEN DATEADD(YEAR, 5, GENERATED_DATE_LOCAL_DATETIME) END AS GENERATED_DATE_LOCAL_DATETIME,
                    CASE WHEN LEFT(CRP_SITE_NUMBER, 2) = 'WC' THEN GENERATED_DATE_UTC_DATETIME WHEN LEFT(CRP_SITE_NUMBER, 2) = 'QC' THEN DATEADD(YEAR, 5, GENERATED_DATE_UTC_DATETIME) END AS GENERATED_DATE_UTC_DATETIME
                    from {{ this }} where CRP_SITE_NUMBER in (
                        'WC20061002',
                        'WC20061001',
                        'QC12027110',
                        'QC12027194',
                        'QC12027187'
                    )
            ) src
            ON (trg.FACT_CRP_SHIPPING_MANIFEST_KEY = src.FACT_CRP_SHIPPING_MANIFEST_KEY)
            WHEN MATCHED THEN UPDATE
            set
            trg.QTY = src.QTY,
            trg.M3_DERIVED = src.M3_DERIVED,
            trg.ACTUAL_WEIGHT = src.ACTUAL_WEIGHT,
            trg.TRANSACTION_QTY = src.TRANSACTION_QTY,
            trg.CONVERTED_WEIGHT = src.CONVERTED_WEIGHT,
            trg.RECEIVED_KG_DERIVED = src.RECEIVED_KG_DERIVED,
