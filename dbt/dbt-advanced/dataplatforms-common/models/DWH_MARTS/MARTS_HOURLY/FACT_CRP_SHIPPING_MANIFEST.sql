SELECT
--Key naming convention applied for clarity "<TABLE NAME>_KEY". Dbt Util applied.
--Dimension Key
  DTL.ID as FACT_CRP_SHIPPING_MANIFEST_KEY

--Foreign Key
, {{ dbt_utils.generate_surrogate_key(['HDR.MULTI_SCHEME_ID']) }} AS DIM_SCHEME_KEY
, {{ dbt_utils.generate_surrogate_key(['DTL.MATERIAL_TYPE_ID']) }} AS DIM_MATERIAL_TYPE_KEY
, {{ dbt_utils.generate_surrogate_key(['HDR.CRP_ID']) }} AS DIM_SITE_CRP_KEY
, {{ dbt_utils.generate_surrogate_key(['HDR.CARRIER_ID']) }} AS DIM_SITE_LSP_KEY
, {{ dbt_utils.generate_surrogate_key(['P.SITE_NUMBER']) }} AS DIM_SITE_PROCESSOR_KEY
, {{ dbt_utils.generate_surrogate_key(["REPLACE(HDR.PERIOD, '-', '')"]) }} AS DIM_DATE_PERIOD_KEY

--Natural Key

--Attributes
, HDR.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, HDR.ID AS CRP_SHIPPING_MANIFEST_HDR_ID  --this is just a natural key that is left for reference
, DTL.TRANSACTION_MATERIAL_TYPE_ID AS TRANSACTION_MATERIAL_TYPE_ID
, DTL.ASSET_ID AS ASSET_ID
, DTL.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID
, DTL.SHIPPER_UNIT_TYPE_ID AS SHIPPER_UNIT_TYPE_ID
, CAST(REPLACE(HDR.PERIOD, '-', '') AS NUMBER) AS PERIOD_DATE_ID
, CONCAT(COALESCE(HDR.EXTERNAL_ID,''),'-',COALESCE(DTL.ASSET_ID,''),'-',COALESCE(MT.NAME,'')) AS MANIFEST_TO_PROCESSOR_ID
, HDR.PERIOD AS PERIOD
, HDR.PERIOD_TYPE AS PERIOD_TYPE
, HDR.EXTERNAL_ID AS MANIFEST_NUMBER
, REPLACE(UPPER(HDR.EXTERNAL_ID), '-', '') AS MANIFEST_NUMBER_ADJ
, HDR.CRP_ID AS CRP_SITE_NUMBER
, HDR.CARRIER_ID AS LSP_SITE_NUMBER
, HDR.LICENSE_PLATE AS LICENSE_PLATE
, HDR.GENERATED_BY AS GENERATED_BY
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(HDR.GENERATED_ON AS TIMESTAMP)) AS GENERATED_DATE_LOCAL_DATETIME
, MT.NAME AS MATERIAL_TYPE
, P.SITE_NUMBER AS PROCESSOR_SITE_NUMBER
, P.STATUS AS STATUS
, HDR.GENERATED_ON AS GENERATED_DATE_UTC_DATETIME


--Metrics
, DTL.EMPTY_WEIGHT AS EMPTY_WEIGHT
, DTL.QUANTITY AS QTY
, DTL.TRANSACTION_QUANTITY AS TRANSACTION_QTY
, DTL.QUANTITY / NVL(U_M3_QTY_A.CONVERSION_FACTOR,U_M3_QTY_B.CONVERSION_FACTOR) AS M3_DERIVED
, DTL.ACTUAL_WEIGHT AS ACTUAL_WEIGHT
, DTL.CONVERTED_WEIGHT AS CONVERTED_WEIGHT
, P.RECEIVED_KG_DERIVED AS RECEIVED_KG_DERIVED

--Metadata Attributes
, DTL.CREATED_BY AS CREATED_BY
, DTL.CREATED_ON AS CREATED_ON_UTC_DATETIME
, DTL.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, DATE_TRUNC(SECOND, DTL.LAST_MODIFIED_ON) AS LAST_MODIFIED_ON_UTC_DATETIME
, SYSDATE() AS INSERT_UTC_DATETIME

FROM
{{ source('CES_MSCM', 'CRP_SHIPPING_MANIFEST_HDR') }} AS HDR
LEFT JOIN {{ source('CES_MSCM', 'CRP_SHIPPING_MANIFEST_DTL') }} AS DTL
ON HDR.ID = DTL.CRP_SHIPPING_MANIFEST_HDR_ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON HDR.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS MT
ON DTL.MATERIAL_TYPE_ID = MT.ID
LEFT JOIN {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS MT_T
ON DTL.TRANSACTION_MATERIAL_TYPE_ID = MT_T.ID
LEFT JOIN {{ source('CES_MSCM', 'UOM_REFERENCE') }} AS U_M3_QTY_A
ON DTL.MATERIAL_TYPE_ID = U_M3_QTY_A.MATERIAL_TYPE_ID
AND U_M3_QTY_A.FROM_UNIT = 'CUBIC METRE'
AND U_M3_QTY_A.TO_UNIT = 'UNIT'
AND SYSDATE() BETWEEN NVL(U_M3_QTY_A.EFFECTIVE_FROM,TO_DATE('01/JAN/1900','DD/MON/YYYY')) AND NVL(U_M3_QTY_A.EFFECTIVE_TO,TO_DATE('01/JAN/9999','DD/MON/YYYY'))
AND HDR.CRP_ID = U_M3_QTY_A.SCHEME_PARTICIPANT_ID
AND DTL.MULTI_SCHEME_ID = U_M3_QTY_A.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'UOM_REFERENCE') }} AS U_M3_QTY_B
ON DTL.MATERIAL_TYPE_ID = U_M3_QTY_B.MATERIAL_TYPE_ID
AND U_M3_QTY_B.FROM_UNIT = 'CUBIC METRE'
AND U_M3_QTY_B.TO_UNIT = 'UNIT'
AND SYSDATE() BETWEEN NVL(U_M3_QTY_B.EFFECTIVE_FROM,TO_DATE('01/JAN/1900','DD/MON/YYYY')) AND NVL(U_M3_QTY_B.EFFECTIVE_TO,TO_DATE('01/JAN/9999','DD/MON/YYYY'))
AND U_M3_QTY_B.SCHEME_PARTICIPANT_ID IS NULL
AND DTL.MULTI_SCHEME_ID = U_M3_QTY_B.MULTI_SCHEME_ID
LEFT JOIN (
    SELECT
    CRP_SHIPPING_MANIFEST_HDR_ID
    , ASSET_ID
    , MATERIAL_TYPE_ID
    FROM {{ source('CES_MSCM', 'CRP_SHIPPING_MANIFEST_DTL') }} AS D
    GROUP BY
    CRP_SHIPPING_MANIFEST_HDR_ID
    , ASSET_ID
    , MATERIAL_TYPE_ID
    HAVING COUNT(*) > 1
) FILTER
ON DTL.CRP_SHIPPING_MANIFEST_HDR_ID = FILTER.CRP_SHIPPING_MANIFEST_HDR_ID
AND DTL.ASSET_ID = FILTER.ASSET_ID
AND DTL.MATERIAL_TYPE_ID = FILTER.MATERIAL_TYPE_ID
LEFT JOIN {{ ref('PROCESSOR_RECEIPT') }} AS P 
ON HDR.ID= P.CRP_SHIPPING_MANIFEST_HDR_ID 
AND DTL.ASSET_ID = P.ASSET_ID
AND DTL.MATERIAL_TYPE_ID = P.MATERIAL_TYPE_ID
WHERE FILTER.CRP_SHIPPING_MANIFEST_HDR_ID IS NULL