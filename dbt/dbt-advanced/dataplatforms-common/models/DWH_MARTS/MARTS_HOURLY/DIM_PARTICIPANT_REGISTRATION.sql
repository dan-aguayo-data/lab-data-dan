SELECT
--Key naming convention applied for clarity "<TABLE NAME>_KEY". Dbt Util applied.
--Dimension Key
  {{ dbt_utils.generate_surrogate_key(['PR.ID']) }} AS DIM_PARTICIPANT_REGISTRATION_KEY

--Natural Key
, PR.ID  AS ID

--Attributes
, PR.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, PR.REGISTRATION_ID AS REGISTRATION_ID
, PR.PARTICIPANT_ID AS PARTICIPANT_ID
, TO_NUMBER(COALESCE(PR.PARTICIPANT_NUMBER, BS.SUPPLIER_NUMBER,BSS.SUPPLIER_NUMBER)) AS SUPPLIER_NUMBER
, PR.TRADING_NAME AS TRADING_NAME
, PR.ABN AS ABN
, PR.ACN AS ACN
, PR.ENTITY_TYPE AS ENTITY_TYPE
, PR.ENTITY_NAME AS ENTITY_NAME
, PR.BEVERAGE_MANUFACTURER_SIZE AS BEVERAGE_MANUFACTURER_SIZE
, PR.MANUFACTURES_ONLY_WINE_OR_SPIRITS AS MANUFACTURES_ONLY_WINE_OR_SPIRITS
, PR.BUS_ADDR_POSTCODE AS BUSINESS_ADDRESS_POSTCODE
, PR.BUS_ADDR_STATE AS BUSINESS_ADDRESS_STATE
, PR.BUS_ADDR_STREET_ADDRESS AS BUSINESS_ADDRESS_STREET_ADDRESS
, PR.BUS_ADDR_SUBURB AS BUSINESS_ADDRESS_SUBURB
, PR.REG_ADDR_POSTCODE AS REGISTRATION_ADDRESS_POSTCODE
, PR.REG_ADDR_STATE AS REGISTRATION_ADDRESS_STATE
, PR.REG_ADDR_STREET_ADDRESS AS REGISTRATION_ADDRESS_STREET_ADDRESS
, PR.REG_ADDR_SUBURB AS REGISTRATION_ADDRESS_SUBURB
, PR.INVOICE_FREQUENCY AS INVOICE_FREQUENCY
, PR.STATUS AS STATUS
, CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, PR.REG_PARTICIPANT_CREATED_AT) AS PARTICIPANT_CREATED_LOCAL_DATE
, TO_CHAR(CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, PR.REG_PARTICIPANT_CREATED_AT), 'YYYYMMDD') AS PARTICIPANT_CREATED_LOCAL_DATE_ID
, CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, PR.SUBMITTED_AT) AS SUBMITTED_LOCAL_DATETIME
, TO_CHAR(CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, PR.SUBMITTED_AT), 'YYYYMMDD') AS SUBMITTED_LOCAL_DATE_ID
, CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, PR.REG_CONTRACT_EXECUTED_AT) AS CONTRACT_EXECUTED_LOCAL_DATE
, CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, PR.REG_LAST_REVIEWED_AT) AS LAST_REVIEWED_LOCAL_DATE
, PR.REG_LAST_REVIEWED_BY AS LAST_REVIEWED_BY
, PR.REG_REVIEW_COMMENT_TEXT AS REVIEWER_COMMENTS
, PR.TYPE_ORDER AS STATUS_ORDER
, PR.REG_EMAIL AS PRIMARY_CONTACT_EMAIL
, PR.ACCEPTED_PRIVACY_POLICY AS TERMS_ACCEPTED
, PR.TRUST_NAME AS TRUST_NAME
, PR.CORPORATE_TRUSTEE AS CORPORATE_TRUSTEE_NAME
, PR.BUSINESS_REG_NUMBER AS CORPORATE_TRUSTEE_ABN_ACN
, PR.IS_SOLE_DIRECTOR AS IS_SOLE_DIRECTOR
, DECODE(PR.REG_STATUS, 'EMAIL_ADDED', 'In Progress', 'ABN_ADDED', 'In Progress', 'COMPANY_DETAILS_ADDED', 'In Progress', 'CONTACTS_ADDED', 'In Progress', 'REVIEW_PENDING', 'Pending', 'REVIEW_INFORMATION_REQUESTED', 'Information Requested', 'REVIEW_REJECTED', 'Rejected', 'REVIEW_APPROVED', 'Contract Created', 'PARTICIPANT_CREATED', 'Onboarded') AS STATUS_ON_PORTAL
, DECODE(PR.REG_STATUS, 'EMAIL_ADDED', 1, 'ABN_ADDED', 1, 'COMPANY_DETAILS_ADDED', 1, 'CONTACTS_ADDED', 1, 'REVIEW_PENDING', 2, 'REVIEW_INFORMATION_REQUESTED', 3, 'REVIEW_REJECTED', 4, 'REVIEW_APPROVED', 5, 'PARTICIPANT_CREATED', 6) AS STATUS_ON_PORTAL_ORDER
, NVL(D.DOCUMENT_UPLOADED, 'No') AS DOCUMENT_UPLOADED
, NVL(D.DOCUMENT_COUNT, 0) AS DOCUMENT_COUNT
, C_S.FIRST_NAME AS SIGNATORY_FIRST_NAME
, C_S.LAST_NAME AS SIGNATORY_LAST_NAME
, C_S.EMAIL AS SIGNATORY_EMAIL
, C_S.PHONE_NUMBER AS SIGNATORY_PHONE_NUMBER
, C_S.POSITION_TITLE AS SIGNATORY_POSITION_TITLE
, C_S.SIGNATORY_PORTAL_ACCESS_REQUESTED AS SIGNATORY_PORTAL_ACCESS_REQUESTED
, C_W.FIRST_NAME AS WITNESS_FIRST_NAME
, C_W.LAST_NAME AS WITNESS_LAST_NAME
, C_W.EMAIL AS WITNESS_EMAIL
, C_W.PHONE_NUMBER AS WITNESS_PHONE_NUMBER
, C_W.STREET_ADDRESS AS WITNESS_STREET_ADDRESS
, C_W.SUBURB AS WITNESS_SUBURB
, C_W.POSTCODE AS WITNESS_POSTCODE
, C_W.STATE AS WITNESS_STATE
, C_S1.FIRST_NAME AS SIGNATORY_1_FIRST_NAME
, C_S1.LAST_NAME AS SIGNATORY_1_LAST_NAME
, C_S1.EMAIL AS SIGNATORY_1_EMAIL
, C_S1.PHONE_NUMBER AS SIGNATORY_1_PHONE_NUMBER
, C_S1.POSITION_TITLE AS SIGNATORY_1_POSITION_TITLE
, C_S1.SIGNATORY_PORTAL_ACCESS_REQUESTED AS SIGNATORY_1_PORTAL_ACCESS_REQUESTED
, C_S2.FIRST_NAME AS SIGNATORY_2_FIRST_NAME
, C_S2.LAST_NAME AS SIGNATORY_2_LAST_NAME
, C_S2.EMAIL AS SIGNATORY_2_EMAIL
, C_S2.PHONE_NUMBER AS SIGNATORY_2_PHONE_NUMBER
, C_S2.POSITION_TITLE AS SIGNATORY_2_POSITION_TITLE
, C_S2.SIGNATORY_PORTAL_ACCESS_REQUESTED AS SIGNATORY_2_PORTAL_ACCESS_REQUESTED
, CASE WHEN ROW_NUMBER() OVER (PARTITION BY PR.REGISTRATION_ID ORDER BY PR.KAFKA_DATETIME DESC, PR.TYPE_ORDER DESC) = 1 THEN 1 ELSE 0 END AS RECENT_FLAG

--Metadata Attributes
, PR.KAFKA_ID AS KAFKA_ID
, PR.KAFKA_DATETIME AS KAFKA_UTC_DATETIME
, SYSDATE() AS INSERT_UTC_DATETIME

FROM
{{ source('CES_MSCM_KAFKA', 'PARTICIPANT_REGISTRATION') }} AS PR
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON PR.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ ref('DIM_SITE_FRS') }} AS BS
ON LOWER(BS.SITE_NAME) = LOWER(PR.ENTITY_NAME) AND PR.STATUS = 'PARTICIPANT_CREATED' AND BS.MULTI_SCHEME_ID = PR.MULTI_SCHEME_ID
LEFT JOIN {{ ref('DIM_B2B_SUPPLIER') }} AS BSS
ON LOWER(BSS.SUPPLIER_NAME) = LOWER(PR.ENTITY_NAME) AND PR.STATUS = 'PARTICIPANT_CREATED'
LEFT JOIN (
    SELECT
    DOC.KAFKA_ID
    , CASE WHEN COUNT(DOC.DOCUMENT_ID) > 0 THEN 'Yes' ELSE 'No' END AS DOCUMENT_UPLOADED
    , COUNT(DOC.DOCUMENT_ID) AS DOCUMENT_COUNT
    FROM {{ source('CES_MSCM_KAFKA', 'PARTICIPANT_REGISTRATION_DOCUMENTS') }} AS DOC
    GROUP BY ALL
) D
ON PR.KAFKA_ID = D.KAFKA_ID
LEFT JOIN (
    SELECT
    C.KAFKA_ID
    , C.REGISTRATION_ID
    , C.FIRST_NAME
    , C.LAST_NAME
    , C.EMAIL
    , C.PHONE_NUMBER
    , C.POSITION_TITLE
    , C.SIGNATORY_PORTAL_ACCESS_REQUESTED
    FROM {{ ref('PARTICIPANT_REG_CONTACT') }} AS C
    WHERE C.SIGNATORY_FLAG = 'Yes'
) C_S
ON PR.KAFKA_ID = C_S.KAFKA_ID
LEFT JOIN (
    SELECT
    C.KAFKA_ID
    , C.REGISTRATION_ID
    , C.FIRST_NAME
    , C.LAST_NAME
    , C.EMAIL
    , C.PHONE_NUMBER
    , C.STREET_ADDRESS
    , C.SUBURB
    , C.POSTCODE
    , C.STATE
    FROM {{ ref('PARTICIPANT_REG_CONTACT') }} AS C
    WHERE C.WITNESS_FLAG = 'Yes'
) C_W
ON PR.KAFKA_ID = C_W.KAFKA_ID
LEFT JOIN (
    SELECT
    C.KAFKA_ID
    , C.REGISTRATION_ID
    , C.FIRST_NAME
    , C.LAST_NAME
    , C.EMAIL
    , C.PHONE_NUMBER
    , C.POSITION_TITLE
    , C.SIGNATORY_PORTAL_ACCESS_REQUESTED
    FROM {{ ref('PARTICIPANT_REG_CONTACT') }} AS C
    WHERE C.SIGNATORY_1_FLAG = 'Yes'
) C_S1
ON PR.KAFKA_ID = C_S1.KAFKA_ID
LEFT JOIN (
    SELECT
    C.KAFKA_ID
    , C.REGISTRATION_ID
    , C.FIRST_NAME
    , C.LAST_NAME
    , C.EMAIL
    , C.PHONE_NUMBER
    , C.POSITION_TITLE
    , C.SIGNATORY_PORTAL_ACCESS_REQUESTED
    FROM {{ ref('PARTICIPANT_REG_CONTACT') }} AS C
    WHERE C.SIGNATORY_2_FLAG = 'Yes'
) C_S2
ON PR.KAFKA_ID = C_S2.KAFKA_ID