SELECT

--Fact Key
 {{ dbt_utils.generate_surrogate_key(["RD.ID"]) }} AS FACT_PROCESSOR_RECEIPT_KEY
--Foreign Key
, {{ dbt_utils.generate_surrogate_key(["TO_NUMBER(RH.MULTI_SCHEME_ID, 38, 0)"]) }} AS DIM_SCHEME_KEY
, {{ dbt_utils.generate_surrogate_key(["RH.PROCESSOR_ID"]) }} AS DIM_SITE_PROCESSOR_KEY
, {{ dbt_utils.generate_surrogate_key(['RD.MATERIAL_TYPE_ID']) }} AS DIM_MATERIAL_TYPE_KEY
, {{ dbt_utils.generate_surrogate_key(["TO_CHAR(CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, TO_TIMESTAMP(RH.PERIOD)),'YYYYMMDD')"]) }} AS DIM_DATE_PERIOD_LOCAL_KEY
, {{ dbt_utils.generate_surrogate_key(["TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(RH.SUBMITTED_ON AS TIMESTAMP)),'YYYYMMDD')"]) }} AS DIM_DATE_SUBMITTED_LOCAL_KEY

--Natural Key
, RH.MULTI_SCHEME_ID  AS MULTI_SCHEME_ID 
, SCHEME.NAME AS SCHEME
, RD.ASSET_ID AS ASSET_ID
, RD.PROCESSOR_RECEIPT_HDR_ID AS RECEIPT_HDR_ID
, RH.CRP_SHIPPING_MANIFEST_HDR_ID AS CRP_SHIPPING_MANIFEST_HDR_ID
, RH.RECEIPT_ID AS MANIFEST_NUMBER
, RH.PROCESSOR_ID AS SITE_NUMBER 
, PS.SITE_NAME  AS SITE_NAME 
, RD.MATERIAL_TYPE_ID  AS MATERIAL_TYPE_ID 
, MT.NAME AS MATERIAL_TYPE
, CONCAT(COALESCE(RH.RECEIPT_ID,''),'-',COALESCE(RD.ASSET_ID,''),'-',COALESCE(MT.NAME,'')) AS MANIFEST_TO_PROCESSOR_ID
, RH.PERIOD AS PERIOD
, TO_CHAR(CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, TO_TIMESTAMP(RH.PERIOD)),'YYYYMMDD') PERIOD_DATE_ID

--Attributes
, RH.PERIOD_TYPE AS PERIOD_TYPE
, RH.STATUS AS STATUS
, RD.RECEIVED AS RECEIVED
, RH.SUBMITTED_BY AS SUBMITTED_BY
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(RH.SUBMITTED_ON AS TIMESTAMP)) AS SUBMITTED_ON_LOCAL_DATETIME
, TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(RH.SUBMITTED_ON AS TIMESTAMP)),'YYYYMMDD') SUBMITTED_ON_LOCAL_DATE_ID

--Metrics
, RD.RECEIVED_UNITS AS RECEIVED_QTY
, RD.RECEIVED_KILOS AS RECEIVED_KG
, CASE NVL(RD.RECEIVED_UNITS,0) WHEN 0 THEN RD.RECEIVED_KILOS*NVL(U_KG_QTY_A.CONVERSION_FACTOR,U_KG_QTY_B.CONVERSION_FACTOR) ELSE RD.RECEIVED_UNITS END AS RECEIVED_QTY_DERIVED
, CASE NVL(RD.RECEIVED_KILOS,0) WHEN 0 THEN RD.RECEIVED_UNITS/NVL(U_KG_QTY_A.CONVERSION_FACTOR,U_KG_QTY_B.CONVERSION_FACTOR) ELSE RD.RECEIVED_KILOS END AS RECEIVED_KG_DERIVED

--Metadata Attributes

, RD.CREATED_BY AS CREATED_BY
, RD.CREATED_ON AS CREATED_ON_UTC_DATETIME
, RD.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, RD.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC_DATETIME
, SYSDATE() AS INSERT_UTC_DATETIME

FROM {{ source('CES_MSCM', 'PROCESSOR_RECEIPT_DTL') }} AS RD
INNER JOIN {{ source('CES_MSCM', 'PROCESSOR_RECEIPT_HDR') }} AS RH
ON RD.PROCESSOR_RECEIPT_HDR_ID = RH.ID
INNER JOIN {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS MT
ON RD.MATERIAL_TYPE_ID = MT.ID
LEFT JOIN {{ source('CES_MSCM', 'UOM_REFERENCE') }} AS U_KG_QTY_A
ON RD.MATERIAL_TYPE_ID = U_KG_QTY_A.MATERIAL_TYPE_ID
AND U_KG_QTY_A.FROM_UNIT = 'KILOGRAM'
AND U_KG_QTY_A.TO_UNIT = 'UNIT'
AND SYSDATE() BETWEEN NVL(U_KG_QTY_A.EFFECTIVE_FROM,TO_DATE('01/JAN/1900','DD/MON/YYYY')) AND NVL(U_KG_QTY_A.EFFECTIVE_TO,TO_DATE('01/JAN/9999','DD/MON/YYYY'))
AND RH.PROCESSOR_ID = U_KG_QTY_A.SCHEME_PARTICIPANT_ID
AND RH.MULTI_SCHEME_ID = U_KG_QTY_A.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'UOM_REFERENCE') }} AS U_KG_QTY_B
ON RD.MATERIAL_TYPE_ID = U_KG_QTY_B.MATERIAL_TYPE_ID
AND U_KG_QTY_B.FROM_UNIT = 'KILOGRAM'
AND U_KG_QTY_B.TO_UNIT = 'UNIT'
AND SYSDATE() BETWEEN NVL(U_KG_QTY_B.EFFECTIVE_FROM,TO_DATE('01/JAN/1900','DD/MON/YYYY')) AND NVL(U_KG_QTY_B.EFFECTIVE_TO,TO_DATE('01/JAN/9999','DD/MON/YYYY'))
AND U_KG_QTY_B.SCHEME_PARTICIPANT_ID IS NULL
AND RH.MULTI_SCHEME_ID = U_KG_QTY_B.MULTI_SCHEME_ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON RH.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS
ON PS.SITE_NUMBER=RH.PROCESSOR_ID