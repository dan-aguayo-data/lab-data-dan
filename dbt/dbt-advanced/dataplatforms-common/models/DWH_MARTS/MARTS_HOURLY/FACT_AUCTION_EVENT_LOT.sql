WITH AUCTION_EVENT_LOT_BASE AS (
    SELECT 
    EL.MULTI_SCHEME_ID 
    , EL.ID
    , E.ID AS EVENT_ID
    , E.NAME  AS EVENT_NAME
    , E.DESCRIPTION 
    , EL.LOT_ITEM_ID
    , E.STATUS
    , E.START_DATE
    , NVL(ED.END_DATE_TIME,E.END_DATE) AS END_DATE
    , E.SUBMITTED_BY
    , E.SUBMITTED_ON 
    , EL.CREATED_BY
    , EL.CREATED_ON
    , EL.LAST_MODIFIED_BY
    , EL.LAST_MODIFIED_ON 
    , B.BID_PRICE_PER_TONNE
    , L.RESERVE_PRICE_PER_TONNE
    , L.AGREEMENT_DATE 
    FROM {{ source('CES_MSCM', 'AUCTION_EVENT') }} AS E
    LEFT JOIN {{ source('CES_MSCM', 'AUCTION_EVENT_LOT') }} AS EL
    ON E.ID = EL.AUCTION_EVENT_ID
    LEFT JOIN {{ source('CES_MSCM', 'LOT_ITEM') }} AS L
    ON EL.LOT_ITEM_ID = L.ID
    LEFT JOIN (
        SELECT 
        AB.AUCTION_EVENT_LOT_ID
        , MAX(AB.BID_PRICE_PER_TONNE) AS BID_PRICE_PER_TONNE
        FROM {{ source('CES_MSCM', 'AUCTION_BID') }} AS AB
        WHERE AB.CANCELLED_ON IS NULL
        GROUP BY AB.AUCTION_EVENT_LOT_ID
    ) B
    ON EL.ID = B.AUCTION_EVENT_LOT_ID
    LEFT JOIN
    (SELECT AUCTION_EVENT_ID, MAX(END_DATE_TIME) AS END_DATE_TIME
    FROM {{ source('CES_MSCM', 'AUCTION_EVENT_HISTORY') }} AS EH
    GROUP BY AUCTION_EVENT_ID) ED ON ED.AUCTION_EVENT_ID=E.ID
    UNION ALL
    SELECT
    LL.MULTI_SCHEME_ID 
    , 'DIRECT_SALE' || '-' || LL.ID AS ID
    , 'DIRECT_SALE' AS EVENT_ID
    , 'DIRECT_SALE' AS EVENT_NAME 
    , 'DIRECT_SALE' AS DESCRIPTION 
    , LL.ID AS LOT_ITEM_ID
    , NULL AS STATUS
    , NULL AS START_DATE
    , NULL AS END_DATE 
    , NULL AS SUBMITTED_BY
    , NULL AS SUBMITTED_ON 
    , NULL AS CREATED_BY
    , NULL AS CREATED_ON
    , NULL AS LAST_MODIFIED_BY
    , NULL AS LAST_MODIFIED_ON 
    , NULL AS BID_PRICE_PER_TONNE
    , NULL AS RESERVE_PRICE_PER_TONNE
    , NULL AS AGREEMENT_DATE
    FROM {{ source('CES_MSCM', 'LOT_ITEM') }} AS LL
    WHERE LL.DIRECT_SALE_MODE = 1

) SELECT

--Dbt Util not applied here. Key is already a hash from source.
--Fact Key
  {{ dbt_utils.generate_surrogate_key(['SS.ID']) }} AS FACT_AUCTION_EVENT_LOT_KEY

--Foreign Key
 , {{ dbt_utils.generate_surrogate_key(["TO_NUMBER(SS.MULTI_SCHEME_ID , 38, 0)"]) }} AS DIM_SCHEME_KEY
 , {{ dbt_utils.generate_surrogate_key(['SS.LOT_ITEM_ID']) }}  AS DIM_AUCTION_LOT_ITEM_KEY
 , {{ dbt_utils.generate_surrogate_key(["TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(SS.AGREEMENT_DATE AS TIMESTAMP)),'YYYYMMDD')"]) }} AS DIM_DATE_AGREEMENT_LOCAL_KEY
 , {{ dbt_utils.generate_surrogate_key(["TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(SS.SUBMITTED_ON AS TIMESTAMP)),'YYYYMMDD')"]) }} AS DIM_DATE_SUBMITTED_ON_LOCAL_KEY


--Natural Key
, SS.EVENT_ID AS EVENT_LOT_ID
, SS.EVENT_NAME AS EVENT_NAME
, SS.MULTI_SCHEME_ID  AS MULTI_SCHEME_ID 
, SCHEME.NAME AS SCHEME
, SS.LOT_ITEM_ID AS LOT_ITEM_ID

--Attributes
, CASE WHEN SS.EVENT_ID  ='DIRECT_SALE' THEN 'DIRECT_SALE' ELSE 'AUCTION' END AS EVENT_TYPE
, SS.DESCRIPTION AS EVENT_DESCRIPTION
, SS.STATUS AS EVENT_STATUS
, CAST(CASE WHEN SS.EVENT_ID  ='DIRECT_SALE' OR (CAST(SS.AGREEMENT_DATE AS DATE) <= CAST(SS.END_DATE AS DATE) AND SS.BID_PRICE_PER_TONNE >= SS.RESERVE_PRICE_PER_TONNE ) THEN 1 ELSE 0 END AS BOOLEAN) AS SOLD_FLAG
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(SS.START_DATE AS TIMESTAMP))  AS EVENT_START_LOCAL_DATETIME
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(SS.END_DATE AS TIMESTAMP))  AS EVENT_END_LOCAL_DATETIME
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(SS.AGREEMENT_DATE AS TIMESTAMP))  AS AGREEMENT_LOCAL_DATETIME
, CAST(TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(SS.AGREEMENT_DATE AS TIMESTAMP)),'YYYYMMDD') AS NUMBER) AGREEMENT_LOCAL_DATE_ID
, SS.SUBMITTED_BY AS SUBMITTED_BY
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(SS.SUBMITTED_ON AS TIMESTAMP))  AS SUBMITTED_ON_LOCAL_DATETIME
, CAST(TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(SS.SUBMITTED_ON AS TIMESTAMP)),'YYYYMMDD') AS NUMBER) SUBMITTED_ON_LOCAL_DATE_ID

--Metrics


--Metadata Attributes
, SS.CREATED_BY AS CREATED_BY
, SS.CREATED_ON AS CREATED_ON_UTC_DATETIME
, SS.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, SS.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC_DATETIME
, SYSDATE() AS INSERT_UTC_DATETIME

FROM AUCTION_EVENT_LOT_BASE SS
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON SS.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID

 