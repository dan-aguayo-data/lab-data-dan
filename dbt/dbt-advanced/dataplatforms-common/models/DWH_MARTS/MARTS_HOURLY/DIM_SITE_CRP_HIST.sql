{{ config(
    post_hook=[
        "ALTER TABLE {{ this }} SET TAG DWH_GOLD.DATA_MART = 'B2B_PARTICIPANT'"
    ]
) 
}}

SELECT
--Key naming convention applied for clarity "<TABLE NAME>_KEY". Dbt Util applied.
--Dimension Key
{{ dbt_utils.generate_surrogate_key(['PS.AUDIT_ID']) }} AS DIM_SITE_CRP_HIST_KEY

--Natural Key
, PS.AUDIT_ID AS AUDIT_ID

--Attributes
, PS.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, PS.SITE_NUMBER AS SITE_NUMBER
, PS.SITE_NAME AS SITE_NAME
, P.PARTICIPANT_NUMBER AS SUPPLIER_NUMBER
, P.PARTICIPANT_NAME AS SUPPLIER_NAME
, PS.STATUS AS STATUS
, CASE WHEN PS.STATUS <> CK.STATUS THEN 1 ELSE 0 END AS STATUS_UPDATED
, PS.ADDRESS_LINE_1 AS ADDRESS_LINE_1
, PS.ADDRESS_LINE_2 AS ADDRESS_LINE_2
, PS.CITY_SUBURB AS SUBURB
, PS.STATE AS STATE
, PS.POST_CODE AS POSTCODE
, CASE WHEN NVL(PS.ADDRESS_LINE_1, '') || NVL(PS.ADDRESS_LINE_2, '') || NVL(PS.CITY_SUBURB, '') || NVL(PS.STATE, '') ||NVL(PS.POST_CODE, '') <> CK.ADDRESS THEN 1 ELSE 0 END AS ADDRESS_UPDATED
, R_C.VALUE AS COUNTRY
, LGA.VALUE AS LGA
, AR.VALUE AS AREA
, PS.DISPLAY_IN_MARKETING AS DISPLAY_IN_MARKETING
, CASE WHEN PS.DISPLAY_IN_MARKETING <> CK.DISPLAY_IN_MARKETING THEN 1 ELSE 0 END AS DISPLAY_IN_MARKETING_UPDATED

--Metadata Attributes
, PS.AUDIT_TYPE
, PS.AUDIT_DATE AS AUDIT_UTC_DATETIME
, PS.AUDIT_USER
, PS.CREATED_BY AS CREATED_BY
, CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, PS.CREATED_ON) AS CREATED_ON_LOCAL_DATETIME
, PS.CREATED_ON AS CREATED_ON_UTC_DATETIME
, PS.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, PS.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC_DATETIME
, SYSDATE() AS INSERT_UTC_DATETIME

FROM (
    SELECT 
    PS.*
    , ROW_NUMBER() OVER (PARTITION BY PS.SITE_NUMBER ORDER BY PS.LAST_MODIFIED_ON DESC) AS CURRENT_RN
    FROM {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES_A') }} AS PS) PS
INNER JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANTS') }} AS P
ON P.PARTICIPANT_ID = PS.PARTICIPANT_ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON PS.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'SCHEME_REF_CODES') }} AS R_C
ON PS.COUNTRY_ID = R_C.SCHEME_REF_CODES_ID
LEFT JOIN {{ source('CES_MSCM', 'SCHEME_REF_CODES') }} AS LGA
ON PS.LGA_ID = LGA.SCHEME_REF_CODES_ID
LEFT JOIN {{ source('CES_MSCM', 'SCHEME_REF_CODES') }} AS AR
ON PS.AREA_ID = AR.SCHEME_REF_CODES_ID
LEFT JOIN {{ ref('DIM_B2B_SUPPLIER') }} AS S
ON P.PARTICIPANT_NUMBER = S.SUPPLIER_NUMBER
LEFT JOIN (
    SELECT
    PS.SITE_NUMBER
    , PS.STATUS
    , NVL(PS.ADDRESS_LINE_1, '') || NVL(PS.ADDRESS_LINE_2, '') || NVL(PS.CITY_SUBURB, '') || NVL(PS.STATE, '') ||NVL(PS.POST_CODE, '') AS ADDRESS
    , PS.DISPLAY_IN_MARKETING
    , ROW_NUMBER() OVER (PARTITION BY PS.SITE_NUMBER ORDER BY PS.LAST_MODIFIED_ON DESC) AS PREVIOUS
    FROM
    {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES_A') }} AS PS) CK
ON PS.SITE_NUMBER = CK.SITE_NUMBER
AND CK.PREVIOUS - 1 = PS.CURRENT_RN
WHERE PS.SITE_TYPE_ID IN ('1538', '2591', '2688')
ORDER BY PS.LAST_MODIFIED_ON DESC