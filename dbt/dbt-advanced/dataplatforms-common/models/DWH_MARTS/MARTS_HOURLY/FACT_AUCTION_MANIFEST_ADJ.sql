SELECT

--Dbt Util not applied here. Key is already a hash from source.
--Fact Key
 {{ dbt_utils.generate_surrogate_key(['LM.AUDIT_ID']) }} AS FACT_AUCTION_MANIFEST_ADJ_KEY

--Foreign Key
, {{ dbt_utils.generate_surrogate_key(["TO_NUMBER(LM.MULTI_SCHEME_ID  , 38, 0)"]) }} AS DIM_SCHEME_KEY
, {{ dbt_utils.generate_surrogate_key(["CONCAT(LM.LOT_ITEM_ID,'DELIVERY')"]) }}  AS DIM_AUCTION_LOT_ITEM_DELIVERY_KEY 
, {{ dbt_utils.generate_surrogate_key(['LM.LOT_ITEM_ID']) }}  AS DIM_AUCTION_LOT_ITEM_KEY
, {{ dbt_utils.generate_surrogate_key(["TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(LM.MANIFEST_DATE AS TIMESTAMP)),'YYYYMMDD')"]) }} AS DIM_DATE_MANIFEST_LOCAL_KEY
, {{ dbt_utils.generate_surrogate_key(["TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(LM.AUDIT_DATE AS TIMESTAMP)),'YYYYMMDD')"]) }} AS DIM_DATE_AUDIT_LOCAL_KEY


--Natural Key
, LM.ID AS MANIFEST_ID -- NATURAL KEY TO JOIN TO ANOTHER FACT ---> NEEDED TO JOIN 
, LM.MULTI_SCHEME_ID  AS MULTI_SCHEME_ID 
, SCHEME.NAME AS SCHEME

, LM.LOT_ITEM_ID AS LOT_ITEM_ID
, LM.AUDIT_ID AS AUDIT_ID

--Attributes
, LM.NOTE AS NOTE
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(LM.MANIFEST_DATE AS TIMESTAMP))  MANIFEST_LOCAL_DATETIME
, TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(LM.MANIFEST_DATE AS TIMESTAMP)),'YYYYMMDD') MANIFEST_LOCAL_DATE_ID
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(LM.AUDIT_DATE  AS TIMESTAMP))  AUDIT_LOCAL_DATETIME
, TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(LM.AUDIT_DATE AS TIMESTAMP)),'YYYYMMDD') AUDIT_LOCAL_DATE_ID

, LM.AUDIT_TYPE AS AUDIT_TYPE
, LM.AUDIT_USER AS AUDIT_USER
, LM.CARRIER AS CARRIER
, LM.CONSIGNMENT_NO AS CONSIGNMENT_NO
, LM.REGISTRATION_NO AS REGISTRATION_NO
, LM.TRANSPORT_UNIT_TYPE AS TRANSPORT_UNIT_TYPE
, LM.TRANSPORT_UNIT_COUNT AS TRANSPORT_UNIT_COUNT
, CASE WHEN LM.FINAL_MANIFEST = 1 THEN 1 else 0 end AS FINAL_MANIFEST_ADJ_FLAG

--Metrics
, LM.ACTUAL_BLOCKS AS ACTUAL_BLOCKS
, LM.ACTUAL_WEIGHT_KGS AS MANIFEST_WEIGHT_KG
, LM.EMPTY_TRUCK_WEIGHT AS EMPTY_TRUCK_WEIGHT_KG
, LM.EMPTY_CONTAINER_WEIGHT AS EMPTY_CONTAINER_WEIGHT_KG
, LM.TOTAL_TRUCK_WEIGHT AS TOTAL_TRUCK_WEIGHT_KG

--Metadata
, LM.CREATED_BY AS CREATED_BY
, LM.CREATED_ON AS CREATED_ON_UTC_DATETIME
, LM.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, LM.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC_DATETIME
, SYSDATE() AS INSERT_UTC_DATETIME

FROM
{{ source('CES_MSCM', 'LOT_ITEM_MANIFEST_A') }} AS LM
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON LM.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID