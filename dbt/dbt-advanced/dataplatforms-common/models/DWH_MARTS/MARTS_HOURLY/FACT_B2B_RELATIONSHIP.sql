--############ B2B MART ############--


WITH CL_FILTER AS (  --GETTING ROW NUMBERS OF 2 ON P.MULTI_SCHEME_ID, P.SOURCE_PARTICIPANT_ID, 
    SELECT
        P.ID
        ,ROW_NUMBER() OVER (PARTITION BY P.MULTI_SCHEME_ID, P.SOURCE_PARTICIPANT_ID,  P.TARGET_PARTICIPANT_ID ORDER BY P.LAST_MODIFIED_ON DESC, P.EFFECTIVE_FROM DESC, P.EFFECTIVE_TO DESC) N
        FROM {{ source('CES_MSCM', 'SCHEME_PARTICIPANT_REL_HDR') }} AS P
        WHERE 
        CAST(CONVERT_TIMEZONE('UTC', 'Australia/Perth', SYSTIMESTAMP()) AS DATE)  BETWEEN NVL(P.EFFECTIVE_FROM,TO_DATE('01/JAN/1900','DD/MON/YYYY')) AND NVL(P.EFFECTIVE_TO,TO_DATE('01/JAN/9999','DD/MON/YYYY'))
        AND CASE WHEN P.MULTI_SCHEME_ID IN (10000, 10001) THEN SUBSTR(P.TARGET_PARTICIPANT_ID,2,1) = 'L' ELSE SUBSTR(P.TARGET_PARTICIPANT_ID,3,1) = 'L' END

), CL_TABLE AS (
    
SELECT
    D.ID,
    H.SOURCE_PARTICIPANT_ID AS CRP_SITE_NUMBER,
    H.TARGET_PARTICIPANT_ID AS LSP_SITE_NUMBER,
    D.MATERIAL_TYPE_ID,
    H.EFFECTIVE_FROM,
    H.EFFECTIVE_TO,
    H.CREATED_BY,
    H.CREATED_ON,
    H.LAST_MODIFIED_BY,
    H.LAST_MODIFIED_ON,
    FILTER.N,
    H.MULTI_SCHEME_ID
    FROM {{ source('CES_MSCM', 'SCHEME_PARTICIPANT_REL_HDR') }} AS H
    INNER JOIN {{ source('CES_MSCM', 'SCHEME_PARTICIPANT_REL_DTL') }} AS D
    ON H.ID = D.SCHEME_PARTICIPANT_REL_ID
    LEFT JOIN CL_FILTER FILTER
    ON H.ID = FILTER.ID
    WHERE CASE WHEN H.MULTI_SCHEME_ID IN (10000, 10001) THEN SUBSTR(H.TARGET_PARTICIPANT_ID,2,1) = 'L' ELSE SUBSTR(H.TARGET_PARTICIPANT_ID,3,1) = 'L' END
), CP_FILTER AS ( -- UNIQUE VALUES

SELECT
        P.ID
        ,ROW_NUMBER() OVER (PARTITION BY P.MULTI_SCHEME_ID, P.SOURCE_PARTICIPANT_ID,  P.TARGET_PARTICIPANT_ID ORDER BY P.LAST_MODIFIED_ON DESC, P.EFFECTIVE_FROM DESC, P.EFFECTIVE_TO DESC) N
        FROM {{ source('CES_MSCM', 'SCHEME_PARTICIPANT_REL_HDR') }} AS P
        WHERE CAST(CONVERT_TIMEZONE('UTC', 'Australia/Perth', SYSTIMESTAMP()) AS DATE)  BETWEEN NVL(P.EFFECTIVE_FROM,TO_DATE('01/JAN/1900','DD/MON/YYYY')) AND NVL(P.EFFECTIVE_TO,TO_DATE('01/JAN/9999','DD/MON/YYYY'))
        AND CASE WHEN P.MULTI_SCHEME_ID IN (10000, 10001) THEN SUBSTR(P.TARGET_PARTICIPANT_ID,2,1) = 'P' ELSE SUBSTR(P.TARGET_PARTICIPANT_ID,3,1) = 'P' END

), CP_TABLE AS (

--FULL OUTER JOIN (
    SELECT
    D.ID,
    H.SOURCE_PARTICIPANT_ID AS CRP_SITE_NUMBER,
    H.TARGET_PARTICIPANT_ID AS PROCESSOR_SITE_NUMBER,
    D.MATERIAL_TYPE_ID,
    H.EFFECTIVE_FROM,
    H.EFFECTIVE_TO,
    H.CREATED_BY,
    H.CREATED_ON,
    H.LAST_MODIFIED_BY,
    H.LAST_MODIFIED_ON,
    FILTER.N,
    H.MULTI_SCHEME_ID
    FROM {{ source('CES_MSCM', 'SCHEME_PARTICIPANT_REL_HDR') }} AS H
    INNER JOIN {{ source('CES_MSCM', 'SCHEME_PARTICIPANT_REL_DTL') }} AS D
    ON H.ID = D.SCHEME_PARTICIPANT_REL_ID
    LEFT JOIN CP_FILTER FILTER
    ON H.ID = FILTER.ID
    WHERE CASE WHEN H.MULTI_SCHEME_ID IN (10000, 10001) THEN SUBSTR(H.TARGET_PARTICIPANT_ID,2,1) = 'P' ELSE SUBSTR(H.TARGET_PARTICIPANT_ID,3,1) = 'P' END
) 
SELECT
--Fact Key
 {{ dbt_utils.generate_surrogate_key(["IFNULL(CL.ID,'') || '-' || IFNULL(CP.ID,'')"]) }} AS FACT_B2B_RELATIONSHIP_KEY
--Foreign Key
, {{ dbt_utils.generate_surrogate_key(["TO_NUMBER(CL.MULTI_SCHEME_ID, 38, 0)"]) }} AS DIM_SCHEME_KEY
, {{ dbt_utils.generate_surrogate_key(["CL.CRP_SITE_NUMBER"]) }} AS DIM_SITE_CRP_KEY
, {{ dbt_utils.generate_surrogate_key(["CL.LSP_SITE_NUMBER"]) }} AS DIM_SITE_LSP_KEY
, {{ dbt_utils.generate_surrogate_key(["CP.PROCESSOR_SITE_NUMBER"]) }} AS DIM_SITE_PROCESSOR_KEY
, {{ dbt_utils.generate_surrogate_key(['CL.MATERIAL_TYPE_ID']) }} AS DIM_MATERIAL_TYPE_KEY
, {{ dbt_utils.generate_surrogate_key(["TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(CL.EFFECTIVE_TO AS TIMESTAMP)),'YYYYMMDD')"]) }} AS DIM_DATE_LSP_EFFECTIVE_TO_LOCAL_KEY
, {{ dbt_utils.generate_surrogate_key(["TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(CL.EFFECTIVE_FROM AS TIMESTAMP)),'YYYYMMDD')"]) }} AS DIM_DATE_LSP_EFFECTIVE_FROM_LOCAL_KEY
, {{ dbt_utils.generate_surrogate_key(["TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(CP.EFFECTIVE_TO AS TIMESTAMP)),'YYYYMMDD')"]) }} AS DIM_DATE_PROC_EFFECTIVE_TO_LOCAL_KEY
, {{ dbt_utils.generate_surrogate_key(["TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(CP.EFFECTIVE_FROM AS TIMESTAMP)),'YYYYMMDD')"]) }} AS DIM_DATE_PROC_EFFECTIVE_FROM_LOCAL_KEY

--Natural Key
,CL.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, CL.CRP_SITE_NUMBER AS CRP_SITE_NUMBER
, PS_C.SITE_NAME AS CRP_SITE_NAME
, CL.LSP_SITE_NUMBER AS LSP_SITE_NUMBER
, PS_L.SITE_NAME AS LSP_SITE_NAME
, CP.PROCESSOR_SITE_NUMBER AS PROC_SITE_NUMBER
, PS_P.SITE_NAME AS PROC_SITE_NAME
, CL.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID
, MT.NAME AS MATERIAL_TYPE
--Attributes

--Metrics
, CAST(CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, CL.EFFECTIVE_FROM) AS DATE) AS LSP_EFFECTIVE_FROM_LOCAL_DATE
, CAST(CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, CL.EFFECTIVE_TO)   AS DATE) AS LSP_EFFECTIVE_TO_LOCAL_DATE
, CAST(CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, CP.EFFECTIVE_FROM) AS DATE) AS PROC_EFFECTIVE_FROM_LOCAL_DATE
, CAST(CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, CP.EFFECTIVE_TO)   AS DATE) AS PROC_EFFECTIVE_TO_LOCAL_DATE

, CAST(CASE WHEN CL.N*CP.N IS NULL THEN 0 ELSE 1 END AS BOOLEAN) AS ACTIVE_FLAG  --ACTIVE FLAG FOR LSP OR PROCESSOR 
--Metadata Attributes
, CL.CREATED_BY AS LSP_CREATED_BY
, CL.CREATED_ON AS LSP_CREATED_ON_UTC_DATETIME
, CL.LAST_MODIFIED_BY AS LSP_LAST_MODIFIED_BY
, CL.LAST_MODIFIED_ON AS LSP_LAST_MODIFIED_ON_UTC_DATETIME
, CP.CREATED_BY AS PROC_CREATED_BY
, CP.CREATED_ON AS PROC_CREATED_ON_UTC_DATETIME
, CP.LAST_MODIFIED_BY AS PROC_LAST_MODIFIED_BY
, CP.LAST_MODIFIED_ON AS PROC_LAST_MODIFIED_ON_UTC_DATETIME
, SYSDATE() AS INSERT_UTC_DATETIME

FROM CL_TABLE CL
FULL OUTER JOIN CP_TABLE CP
ON CL.CRP_SITE_NUMBER = CP.CRP_SITE_NUMBER
AND CL.MATERIAL_TYPE_ID = CP.MATERIAL_TYPE_ID
AND CL.MULTI_SCHEME_ID = CP.MULTI_SCHEME_ID
INNER JOIN {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS MT
ON CL.MATERIAL_TYPE_ID = MT.ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON CL.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS_C
ON CL.CRP_SITE_NUMBER = PS_C.SITE_NUMBER
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS_L
ON CL.LSP_SITE_NUMBER = PS_L.SITE_NUMBER
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS_P
ON CP.PROCESSOR_SITE_NUMBER = PS_P.SITE_NUMBER