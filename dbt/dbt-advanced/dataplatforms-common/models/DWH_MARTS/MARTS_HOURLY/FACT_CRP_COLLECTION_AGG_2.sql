SELECT
--Fact Key
  {{ dbt_utils.generate_surrogate_key(['H.MULTI_SCHEME_ID', 'H.SITE_NUMBER','PSM.CONSUMER_ID','H.TRANSACTION_LOCAL_DATE_ID','H.PAYMENT_METHOD','H.PAYMENT_TYPE','H.SCHEME_CONSUMER_FLAG','H.TRANSACTION_BANDING','H.TRANSACTION_POSTCODE','C.CONSUMER_TYPE','C.SUBURB']) }} AS FACT_CRP_COLLECTION_AGG_2_KEY

--Foreign Key
 , H.DIM_SCHEME_KEY AS DIM_SCHEME_KEY
 , H.DIM_SITE_CRP_KEY AS DIM_SITE_CRP_KEY
 , {{ dbt_utils.generate_surrogate_key(['PSM.CONSUMER_ID']) }} AS DIM_CONSUMER_KEY
 , H.DIM_DATE_TRANSACTION_LOCAL_KEY AS DIM_DATE_TRANSACTION_LOCAL_KEY

--Attributes
, H.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, H.SITE_NUMBER AS SITE_NUMBER
, NVL(PSM.CONSUMER_ID, '-') AS CONSUMER_ID
, H.TRANSACTION_LOCAL_DATE_ID AS TRANSACTION_LOCAL_DATE_ID
, H.PAYMENT_METHOD AS PAYMENT_METHOD
, H.PAYMENT_TYPE AS PAYMENT_TYPE
, H.SCHEME_CONSUMER_FLAG AS SCHEME_CONSUMER_FLAG
, H.TRANSACTION_BANDING AS TRANSACTION_BANDING
, H.TRANSACTION_POSTCODE AS TRANSACTION_POSTCODE
, C.CONSUMER_TYPE AS CONSUMER_TYPE
, NVL(INITCAP(TRIM(C.SUBURB)), '-') AS CONSUMER_SUBURB

--Metrics
, COUNT(DISTINCT H.TRANSACTION_ID) AS TOTAL_TRANSACTIONS
, SUM(H.COLLECTION_QTY) AS TOTAL_QTY
, SUM(H.COLLECTION_INELIGIBLE_QTY) AS TOTAL_INELIGIBLE_QTY

--Metadata Attributes
, SYSDATE() AS INSERT_UTC_DATETIME

FROM
{{ ref('FACT_CRP_COLLECTION_AGG') }} AS H
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON H.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ ref('DIM_CONSUMER') }} AS C
ON H.CONSUMER_ID = C.CONSUMER_ID
LEFT JOIN (
    SELECT DISTINCT
    P.CONSUMER_ID
    FROM {{ ref('PARTNER_SECURITY_MAPPING') }} AS P
) PSM
ON H.CONSUMER_ID = PSM.CONSUMER_ID
GROUP BY ALL