SELECT
--Key naming convention applied for clarity "<TABLE NAME>_KEY". Dbt Util not applied here. Key is already a hash from source.
--Dimension Key
  PD.ID AS DIM_POS_DEVICE_KEY

--Natural Key
--, PD.ID AS ID

--Attributes
, PD.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, PD.CRP_ID AS CRP_SITE_NUMBER
, PS.SITE_NAME AS CRP_SITE_NAME
, P.PARTICIPANT_NUMBER AS SUPPLIER_NUMBER
, P.PARTICIPANT_NAME AS SUPPLIER_NAME
, PD.NAME AS NAME
, PD.TYPE AS TYPE
, PD.STATUS AS STATUS
, PD.SYNCED AS SYNCED
, NVL(H.VERSION, '-') AS CURRENT_VERSION
, NVL(H.OS_VERSION, '-') AS CURRENT_OS_VERSION
, H.ENVIRONMENT AS ENVIRONMENT
, H.LATITUDE AS LATITUDE
, H.LONGITUDE AS LONGITUDE
, H.LAST_MODIFIED_ON AS LAST_HEARTBEAT_ON_LOCAL_DATETIME
, L.LAST_BAG_LABEL_ON AS LAST_BAG_LABEL_ON_UTC_DATETIME
, C.LAST_TRANSACTION_ON AS LAST_TRANSACTION_ON_LOCAL_DATETIME
, GREATEST(NVL(H.LAST_MODIFIED_ON, TO_TIMESTAMP('19000101','YYYYMMDD')) , NVL(L.LAST_BAG_LABEL_ON, TO_TIMESTAMP('19000101','YYYYMMDD')), NVL(C.LAST_TRANSACTION_ON, TO_TIMESTAMP('19000101','YYYYMMDD'))) AS LAST_LOCAL_DATETIME
, CASE WHEN L.LAST_BAG_LABEL_ON IS NOT NULL THEN 'Bag Drop' WHEN C.LAST_TRANSACTION_ON IS NOT NULL THEN 'Transactional' ELSE 'Not Use' END AS POS_FLAG

--Metadata Attributes
, PD.CREATED_BY AS CREATED_BY
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(PD.CREATED_ON AS TIMESTAMP)) AS CREATED_ON_LOCAL_DATETIME
, PD.CREATED_ON AS CREATED_ON_UTC_DATETIME
, PD.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, PD.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC_DATETIME
, SYSDATE() AS INSERT_UTC_DATETIME

FROM
{{ source('CES_MSCM', 'POS_DEVICE') }} AS PD
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS
ON PD.CRP_ID = PS.SITE_NUMBER
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANTS') }} AS P
ON PS.PARTICIPANT_ID = P.PARTICIPANT_ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON PD.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ ref('CRP_POS_DEVICE_HEARTBEAT') }} AS H
ON PD.ID = H.POS_DEVICE_ID
AND H.LAST_MODIFIED_ORDER = 1
LEFT JOIN (
    SELECT
    BL.CREATED_BY
    , MAX(BL.GENERATED_ON) AS LAST_BAG_LABEL_ON
    FROM {{ ref('CRP_BAG_DROP_LABEL') }} AS BL
    GROUP BY
    BL.CREATED_BY
) L
ON PD.ID = L.CREATED_BY
LEFT JOIN (
    SELECT
    CH.POS_DEVICE_ID
    , MAX(CH.TRANSACTION_DATE) AS LAST_TRANSACTION_ON
    FROM {{ ref('CRP_COLLECTION_HDR') }} AS CH
    GROUP BY
    CH.POS_DEVICE_ID
) C
ON PD.ID = C.POS_DEVICE_ID
 