WITH SS_AUCTION_EVENT_LOT_AGG_TABLE AS (

    SELECT 
    EL.MULTI_SCHEME_ID 
    , EL.ID
    , E.ID AS EVENT_ID
    , E.NAME 
    , E.DESCRIPTION 
    , EL.LOT_ITEM_ID
    , E.STATUS
    , E.START_DATE
    , NVL(ED.END_DATE_TIME,E.END_DATE) AS END_DATE
    , E.SUBMITTED_BY
    , E.SUBMITTED_ON 
    , EL.CREATED_BY
    , EL.CREATED_ON
    , EL.LAST_MODIFIED_BY
    , EL.LAST_MODIFIED_ON 
    , L.AVAILABLE_FROM
    , L.AGREEMENT_DATE
    , B.BID_PRICE_PER_TONNE
    , L.RESERVE_PRICE_PER_TONNE 
    , L.WEIGHT_IN_TONNES
    FROM RAW_PROD.CES_MSCM_ORACLE.AUCTION_EVENT AS E
    LEFT JOIN RAW_PROD.CES_MSCM_ORACLE.AUCTION_EVENT_LOT AS EL
    ON E.ID = EL.AUCTION_EVENT_ID
    LEFT JOIN RAW_PROD.CES_MSCM_ORACLE.LOT_ITEM AS L
    ON EL.LOT_ITEM_ID = L.ID
    LEFT JOIN (
        SELECT 
        AB.AUCTION_EVENT_LOT_ID
        , MAX(AB.BID_PRICE_PER_TONNE) AS BID_PRICE_PER_TONNE
        FROM RAW_PROD.CES_MSCM_ORACLE.AUCTION_BID AS AB
        WHERE AB.CANCELLED_ON IS NULL
        GROUP BY AB.AUCTION_EVENT_LOT_ID
    ) B
    ON EL.ID = B.AUCTION_EVENT_LOT_ID
    LEFT JOIN
    (SELECT AUCTION_EVENT_ID, MAX(END_DATE_TIME) AS END_DATE_TIME
    FROM RAW_PROD.CES_MSCM_ORACLE.AUCTION_EVENT_HISTORY AS EH
    GROUP BY AUCTION_EVENT_ID) ED ON ED.AUCTION_EVENT_ID=E.ID
    UNION ALL
    SELECT
    LL.MULTI_SCHEME_ID 
    , 'DIRECT_SALE' || '-' || LL.ID AS ID
    , 'DIRECT_SALE' AS EVENT_ID
    , 'DIRECT_SALE' AS NAME 
    , 'DIRECT_SALE' AS DESCRIPTION 
    , LL.ID AS LOT_ITEM_ID
    , NULL AS STATUS
    , NULL AS START_DATE
    , NULL AS END_DATE 
    , NULL AS SUBMITTED_BY
    , NULL AS SUBMITTED_ON 
    , NULL AS CREATED_BY
    , NULL AS CREATED_ON
    , NULL AS LAST_MODIFIED_BY
    , NULL AS LAST_MODIFIED_ON 
    , LL.AVAILABLE_FROM
    , LL.AGREEMENT_DATE
    , NULL AS BID_PRICE_PER_TONNE
    , NULL AS RESERVE_PRICE_PER_TONNE
    , NULL AS WEIGHT_IN_TONNES
    FROM RAW_PROD.CES_MSCM_ORACLE.LOT_ITEM AS LL
    WHERE LL.DIRECT_SALE_MODE = 1

), WD_AUCTION_EVENT_LOT_AGG_TABLE AS ( 

  SELECT * 
    FROM (
        SELECT 
        D.DATE AS WRKDAY
        ,ROW_NUMBER() OVER (ORDER BY DATE) AS SEQ 
        FROM COMMON_PROD.DWH.REF_DATE AS D
        WHERE DAY_TYPE = 'WEEKDAY'
    ) DATE_A
    LEFT JOIN (
        SELECT 
        D.DATE
        , ROW_NUMBER() OVER (ORDER BY DATE) + 10 AS SEQ 
        FROM COMMON_PROD.DWH.REF_DATE AS D
        WHERE DAY_TYPE = 'WEEKDAY'
    ) DATE_B 
    ON DATE_B.SEQ=DATE_A.SEQ
    
    ),  AUCTION_EVENT_LOT_AGG_TABLE AS (
SELECT 
SS.LOT_ITEM_ID,
MAX(SS.END_DATE) AS EVENT_END_DATE,
MAX(WD.WRKDAY) AS COLLECTION_END_DATE
FROM SS_AUCTION_EVENT_LOT_AGG_TABLE SS
INNER JOIN RAW_PROD.CES_MSCM_ORACLE.SCHEME AS SCHEME
ON SS.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN WD_AUCTION_EVENT_LOT_AGG_TABLE WD
ON WD.DATE = CAST(
    CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, 
        CAST(
            (
                CASE WHEN SS.AVAILABLE_FROM < coalesce(SS.END_DATE,SS.AGREEMENT_DATE)  
                THEN coalesce(SS.END_DATE,SS.AGREEMENT_DATE) 
                ELSE SS.AVAILABLE_FROM 
                END
            ) 
        AS TIMESTAMP)
    )
AS DATE) + 
(
    CASE WHEN DAYOFWEEKISO(
        CAST(
            CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, 
                CAST(
                    (
                        CASE WHEN SS.AVAILABLE_FROM < coalesce(SS.END_DATE,SS.AGREEMENT_DATE)
                        THEN coalesce(SS.END_DATE,SS.AGREEMENT_DATE) 
                        ELSE SS.AVAILABLE_FROM
                        END
                    ) 
                AS TIMESTAMP)
            )
        AS DATE)) = 6
    THEN 2
    WHEN DAYOFWEEKISO(
        CAST(
            CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE,
                CAST(
                    (
                        CASE WHEN SS.AVAILABLE_FROM < coalesce(SS.END_DATE,SS.AGREEMENT_DATE)   
                        THEN coalesce(SS.END_DATE,SS.AGREEMENT_DATE) 
                        ELSE SS.AVAILABLE_FROM 
                        END
                    ) 
                AS TIMESTAMP)
            )
        AS DATE)) = 7
    THEN 1
    ELSE 0 END
)
GROUP BY 1

),  AUCTION_MANIFEST_BASE AS (

 SELECT
    L.MULTI_SCHEME_ID  AS MULTI_SCHEME_ID 
    , LM.ID AS MANIFEST_ID
    , LM.ACTUAL_WEIGHT_KGS AS MANIFEST_WEIGHT_KG
   ,  LM.LOT_ITEM_ID
    , LM.EMPTY_TRUCK_WEIGHT AS EMPTY_TRUCK_WEIGHT_KG
    , LM.EMPTY_CONTAINER_WEIGHT AS EMPTY_CONTAINER_WEIGHT_KG
    , LM.TOTAL_TRUCK_WEIGHT AS TOTAL_TRUCK_WEIGHT
    , CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(LM.MANIFEST_DATE AS TIMESTAMP))  AS MANIFEST_DATE
    , L.SELLER_ID
    , PS_S.SITE_NAME AS SELLER_NAME
    , L.BUYER_ID
    , PS_B.SITE_NAME AS BUYER_NAME
    , NVL(L.SCHEME_MATERIAL_TYPE_ID, L.MRF_MATERIAL_TYPE_ID) AS MATERIAL_TYPE
    , L.PICKUP_LOCATION
    , LM.ACTUAL_WEIGHT_KGS / 1000 AS MANIFEST_WEIGHT_TONNES
    , LM.ACTUAL_BLOCKS AS ACTUAL_BLOCKS
    , L.STATUS
    , L.SALE_PRICE_PER_TONNE
    , CAST(CASE WHEN LM.FINAL_MANIFEST = 1 THEN 1 else 0 end AS BOOLEAN) AS FINAL_MANIFEST_FLAG
    , CASE WHEN L.DIRECT_SALE_MODE = 1 THEN 'DIRECT_SALE' WHEN  L.STATUS IN ('AWAITING_COLLECTION','SOLD_AND_COLLECTED','AWAITING_DESTINATION_CONFIRMATION') THEN 'AUCTION' ELSE 'NOT_SOLD' END AS SALE_MODE
    , CASE WHEN L.DIRECT_SALE_MODE = 1 THEN  CAST(L.AGREEMENT_DATE AS TIMESTAMP) ELSE EL.EVENT_END_DATE END AS AGREEMENT_DATE
    , LM.NOTE AS COMMENT
    , LM.CARRIER AS CARRIER
    , LM.CONSIGNMENT_NO AS CONSIGNMENT_NO
    , LM.REGISTRATION_NO AS REGISTRATION_NO
    , LM.TRANSPORT_UNIT_TYPE AS TRANSPORT_UNIT_TYPE
    , LM.TRANSPORT_UNIT_COUNT AS TRANSPORT_UNIT_COUNT        
    , LM.MANIFEST_DATE AS MANIFEST_DATE_UTC
    , LM.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
    , LM.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
    , LM.CREATED_BY AS CREATED_BY    
    , LM.CREATED_ON AS CREATED_ON_UTC 

    FROM {{ source('CES_MSCM', 'LOT_ITEM_MANIFEST') }} AS LM
    LEFT JOIN {{ source('CES_MSCM', 'LOT_ITEM') }} AS L
    ON LM.LOT_ITEM_ID = L.ID
    LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS_S
    ON L.SELLER_ID = PS_S.SITE_NUMBER
    LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS_B
    ON L.BUYER_ID = PS_B.SITE_NUMBER
    LEFT JOIN AUCTION_EVENT_LOT_AGG_TABLE EL
    ON L.ID = EL.LOT_ITEM_ID
    INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
    ON L.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID

)
SELECT
--Dbt Util not applied here. Key is already a hash from source.
--Fact Key
 {{ dbt_utils.generate_surrogate_key(['M.MANIFEST_ID']) }} AS FACT_AUCTION_MANIFEST_KEY

--Foreign Key
 , {{ dbt_utils.generate_surrogate_key(["TO_NUMBER(M.MULTI_SCHEME_ID , 38, 0)"]) }} AS DIM_SCHEME_KEY
 , {{ dbt_utils.generate_surrogate_key(["M.SELLER_ID"]) }} AS DIM_SITE_PROCESSOR_SELLER_KEY
 , {{ dbt_utils.generate_surrogate_key(["M.BUYER_ID"]) }} AS DIM_SITE_RECYCLER_BUYER_KEY
 , {{ dbt_utils.generate_surrogate_key(['M.MATERIAL_TYPE']) }} AS DIM_MATERIAL_TYPE_KEY
 , {{ dbt_utils.generate_surrogate_key(['M.LOT_ITEM_ID']) }}  AS DIM_AUCTION_LOT_ITEM_KEY
 , {{ dbt_utils.generate_surrogate_key(["CONCAT(M.LOT_ITEM_ID,'DELIVERY')"]) }}  AS DIM_AUCTION_LOT_ITEM_DELIVERY_KEY  --APPLY DIFFERENT FORMATION TO MAKE IT LOOK UNIQUE VS DIM_LOT_ITEM
 , {{ dbt_utils.generate_surrogate_key(["TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(M.MANIFEST_DATE_UTC AS TIMESTAMP)),'YYYYMMDD')"]) }} AS DIM_DATE_MANIFEST_LOCAL_KEY
 , {{ dbt_utils.generate_surrogate_key(["TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(M.AGREEMENT_DATE AS TIMESTAMP)),'YYYYMMDD')"]) }} AS DIM_DATE_AGREEMENT_LOCAL_KEY


--Natural Key
, M.MANIFEST_ID AS MANIFEST_ID  
, M.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, M.LOT_ITEM_ID AS LOT_ITEM_ID    
, M.SELLER_ID AS SELLER_SITE_ID  
, M.SELLER_NAME AS SELLER_NAME   
, M.BUYER_ID AS BUYER_SITE_ID 
, M.BUYER_NAME AS BUYER_NAME  
, M.MATERIAL_TYPE AS MATERIAL_TYPE_ID 
, NVL(MT.NAME,MR.NAME) AS MATERIAL_TYPE

--Attributes
,CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(M.MANIFEST_DATE_UTC AS TIMESTAMP)) MANIFEST_LOCAL_DATETIME
, CAST(TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(M.MANIFEST_DATE_UTC AS TIMESTAMP)),'YYYYMMDD') AS NUMBER) AS  MANIFEST_LOCAL_DATE_ID
,CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(M.AGREEMENT_DATE AS TIMESTAMP)) AGREEMENT_LOCAL_DATETIME
, CAST(TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(M.AGREEMENT_DATE AS TIMESTAMP)),'YYYYMMDD') AS NUMBER) AS AGREEMENT_LOCAL_DATE_ID
, M.CARRIER AS CARRIER
, M.PICKUP_LOCATION AS PICKUP_LOCATION
, M.STATUS AS STATUS
, M.FINAL_MANIFEST_FLAG AS FINAL_MANIFEST_FLAG
, M.SALE_MODE AS SALE_MODE
, M.COMMENT AS COMMENT
, M.CONSIGNMENT_NO AS CONSIGNMENT_NO
, M.REGISTRATION_NO AS REGISTRATION_NO
, M.TRANSPORT_UNIT_TYPE AS TRANSPORT_UNIT_TYPE
, M.TRANSPORT_UNIT_COUNT AS TRANSPORT_UNIT_COUNT
, M.SALE_PRICE_PER_TONNE AS SALE_PRICE_PER_TONNE

--Metrics
, M.MANIFEST_WEIGHT_KG AS MANIFEST_WEIGHT_KG
, M.EMPTY_TRUCK_WEIGHT_KG AS EMPTY_TRUCK_WEIGHT_KG
, M.EMPTY_CONTAINER_WEIGHT_KG AS EMPTY_CONTAINER_WEIGHT_KG
, M.TOTAL_TRUCK_WEIGHT AS TOTAL_TRUCK_WEIGHT_KG
, M.MANIFEST_WEIGHT_KG/1000 AS MANIFEST_WEIGHT_TONNES
, M.ACTUAL_BLOCKS AS ACTUAL_BLOCKS
, M.SALE_PRICE_PER_TONNE*M.MANIFEST_WEIGHT_TONNES AS ESTIMATED_VALUE

--Metadata Attributes
, M.CREATED_BY AS CREATED_BY
, M.CREATED_ON_UTC AS CREATED_ON_UTC_DATETIME
, M.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, M.LAST_MODIFIED_ON_UTC AS LAST_MODIFIED_ON_UTC_DATETIME
, SYSDATE() AS INSERT_UTC_DATETIME


FROM AUCTION_MANIFEST_BASE M
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON M.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS MT
ON M.MATERIAL_TYPE = MT.ID 
LEFT JOIN {{ source('CES_MSCM', 'MRF_MATERIAL_TYPE') }} AS MR
ON M.MATERIAL_TYPE = MR.ID 
{% if target.name.upper() != 'UAT' %}
WHERE LOWER(M.SELLER_NAME) NOT LIKE '%pvt%' AND LOWER(M.SELLER_NAME) NOT LIKE '%test%'
AND LOWER(M.BUYER_NAME) NOT LIKE '%pvt%' AND LOWER(M.BUYER_NAME) NOT LIKE '%test%'
{% endif %}