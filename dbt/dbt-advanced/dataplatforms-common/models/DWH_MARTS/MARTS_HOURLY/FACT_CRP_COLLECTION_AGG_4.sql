SELECT
--Fact Key
  {{ dbt_utils.generate_surrogate_key(['H.SITE_NUMBER', 'H.TRANSACTION_LOCAL_DATE_ID','H.PAYMENT_METHOD','H.PAYMENT_TYPE','H.CONSUMER_TYPE','H.SCHEME_CONSUMER_FLAG','H.TRANSACTION_BANDING','PD.NAME','PD.TYPE','H.POS_USER_NAME']) }} AS FACT_CRP_COLLECTION_AGG_4_KEY

--Foreign Key
 , H.DIM_SCHEME_KEY AS DIM_SCHEME_KEY
 , H.DIM_SITE_CRP_KEY AS DIM_SITE_CRP_KEY
 , H.DIM_DATE_TRANSACTION_LOCAL_KEY AS DIM_DATE_TRANSACTION_LOCAL_KEY

--Attributes
, H.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, H.SCHEME AS SCHEME
, H.SITE_NUMBER AS SITE_NUMBER
, H.TRANSACTION_LOCAL_DATE_ID AS TRANSACTION_LOCAL_DATE_ID
, H.PAYMENT_METHOD AS PAYMENT_METHOD
, H.PAYMENT_TYPE AS PAYMENT_TYPE
, H.CONSUMER_TYPE AS CONSUMER_TYPE
, H.SCHEME_CONSUMER_FLAG AS SCHEME_CONSUMER_FLAG
, H.TRANSACTION_BANDING AS TRANSACTION_BANDING
, PD.NAME AS POS_DEVICE_NAME
, PD.TYPE AS POS_DEVICE_TYPE
, H.POS_USER_NAME AS POS_USER_NAME

--Metrics
, COUNT(H.TRANSACTION_ID) AS TOTAL_TRANSACTIONS
, SUM(H.COLLECTION_QTY) AS TOTAL_QTY
, SUM(H.COLLECTION_INELIGIBLE_QTY) AS TOTAL_INELIGIBLE_QTY

--Metadata Attributes
, SYSDATE() AS INSERT_UTC_DATETIME

FROM
{{ ref('FACT_CRP_COLLECTION_AGG') }} AS H
LEFT JOIN {{ source('CES_MSCM', 'POS_DEVICE') }} AS PD
ON H.POS_DEVICE_ID = PD.ID
GROUP BY ALL