SELECT
TO_NUMBER(NULLIF(TRIM(REGEXP_REPLACE(R.SUBREGION, '[^[:digit:]]', ' ')), '')) AS "id"
, CASE WHEN SUBSTRING(R.SUBREGION,1,2) IN ('02','03','04','05','11') THEN 'the ' || RIGHT(R.SUBREGION,LEN(R.SUBREGION)-3) ELSE RIGHT(R.SUBREGION,LEN(R.SUBREGION)-3) END AS "subregion"
, CEIL(CLAIM.REGION_NUM_CONTAINERS,0) AS "region_num_containers"
, CLAIM.REGION_REFUND_AMOUNT AS "region_refund_amount"
, R.REGION_AVG_MONTHLY_AMOUNT_PP AS "region_avg_monthly_amount_pp"
, RANK() OVER (ORDER BY CLAIM.REGION_NUM_CONTAINERS DESC) AS "region_ranking"
, R.REGION_AMOUNT_FUNDRAISING AS "region_amount_fundraising"
, CHARITY.NOMINATED_CHARITY AS "region_top_charity"
, R.REGION_CHARITY_NAME_1 AS "region_charity_name_1"
, R.REGION_CHARITY_NAME_2 AS "region_charity_name_2"
, R.REGION_CHARITY_NAME_3 AS "region_charity_name_3"
, R.REGION_CHARITY_NAME_4 AS "region_charity_name_4"
, R.REGION_CHARITY_NAME_5 AS "region_charity_name_5"
, CEIL((S.SALES_VOLUME - E.EXPORT_VOLUME) * POP.POP_PERCENT,0) AS "region_avg_sales"
, CEIL((S.SALES_VOLUME - E.EXPORT_VOLUME) * POP.POP_PERCENT,0)/10 AS "region_avg_sales_amount"
, IFNULL(RP.CRP_SITES,0) AS "region_num_rp"
, R.REGION_CHARITY_SCHEMEID_1 AS "region_charity_schemeid_1"
, R.REGION_CHARITY_SCHEMEID_2 AS "region_charity_schemeid_2"
, R.REGION_CHARITY_SCHEMEID_3 AS "region_charity_schemeid_3"
, R.REGION_CHARITY_SCHEMEID_4 AS "region_charity_schemeid_4"
, R.REGION_CHARITY_SCHEMEID_5 AS "region_charity_schemeid_5"
, R.REGION_CHARITY_AMOUNT_1 AS "region_charity_amount_1"
, R.REGION_CHARITY_AMOUNT_2 AS "region_charity_amount_2"
, R.REGION_CHARITY_AMOUNT_3 AS "region_charity_amount_3"
, R.REGION_CHARITY_AMOUNT_4 AS "region_charity_amount_4"
, R.REGION_CHARITY_AMOUNT_5 AS "region_charity_amount_5"
, GROUPS.BUSINESS_REGISTERED AS "region_businesses_registered"
, GROUPS.CHARITIES_REGISTERED AS "region_charities_registered"
, GROUPS.COMMUNITY_GROUPS_REGISTERED AS "region_community_groups_registered"
, GROUPS.SCHOOLS_REGISTERED AS "region_schools_registered"
FROM   
    (SELECT 
     CRP.*,
     --BY MONTH
     MAX(CRP.AVG_MONTHLY_AMOUNT_PP) OVER (PARTITION BY CRP.SUBREGION) AS REGION_AVG_MONTHLY_AMOUNT_PP,
     MAX(CRP.MAX_MONTHLY_AMOUNT_PP) OVER (PARTITION BY CRP.SUBREGION) AS REGION_MAX_MONTHLY_AMOUNT_PP,
     --BY CHARITY
     FIRST_VALUE(CASE WHEN CRP.CHARITY_RANK = 1 THEN CRP.CHARITY ELSE NULL END) OVER (PARTITION BY CRP.SUBREGION ORDER BY CRP.CHARITY_RANK = 1 DESC) AS REGION_CHARITY_SCHEMEID_1,
     FIRST_VALUE(CASE WHEN CRP.CHARITY_RANK = 2 THEN CRP.CHARITY ELSE NULL END) OVER (PARTITION BY CRP.SUBREGION ORDER BY CRP.CHARITY_RANK = 2 DESC) AS REGION_CHARITY_SCHEMEID_2,
     FIRST_VALUE(CASE WHEN CRP.CHARITY_RANK = 3 THEN CRP.CHARITY ELSE NULL END) OVER (PARTITION BY CRP.SUBREGION ORDER BY CRP.CHARITY_RANK = 3 DESC) AS REGION_CHARITY_SCHEMEID_3,
     FIRST_VALUE(CASE WHEN CRP.CHARITY_RANK = 4 THEN CRP.CHARITY ELSE NULL END) OVER (PARTITION BY CRP.SUBREGION ORDER BY CRP.CHARITY_RANK = 4 DESC) AS REGION_CHARITY_SCHEMEID_4,
     FIRST_VALUE(CASE WHEN CRP.CHARITY_RANK = 5 THEN CRP.CHARITY ELSE NULL END) OVER (PARTITION BY CRP.SUBREGION ORDER BY CRP.CHARITY_RANK = 5 DESC) AS REGION_CHARITY_SCHEMEID_5,
     FIRST_VALUE(CASE WHEN CRP.CHARITY_RANK = 1 THEN CRP.TRADING_NAME ELSE NULL END) OVER (PARTITION BY CRP.SUBREGION ORDER BY CRP.CHARITY_RANK = 1 DESC) AS REGION_CHARITY_NAME_1,
     FIRST_VALUE(CASE WHEN CRP.CHARITY_RANK = 2 THEN CRP.TRADING_NAME ELSE NULL END) OVER (PARTITION BY CRP.SUBREGION ORDER BY CRP.CHARITY_RANK = 2 DESC) AS REGION_CHARITY_NAME_2,
     FIRST_VALUE(CASE WHEN CRP.CHARITY_RANK = 3 THEN CRP.TRADING_NAME ELSE NULL END) OVER (PARTITION BY CRP.SUBREGION ORDER BY CRP.CHARITY_RANK = 3 DESC) AS REGION_CHARITY_NAME_3,
     FIRST_VALUE(CASE WHEN CRP.CHARITY_RANK = 4 THEN CRP.TRADING_NAME ELSE NULL END) OVER (PARTITION BY CRP.SUBREGION ORDER BY CRP.CHARITY_RANK = 4 DESC) AS REGION_CHARITY_NAME_4,
     FIRST_VALUE(CASE WHEN CRP.CHARITY_RANK = 5 THEN CRP.TRADING_NAME ELSE NULL END) OVER (PARTITION BY CRP.SUBREGION ORDER BY CRP.CHARITY_RANK = 5 DESC) AS REGION_CHARITY_NAME_5, 
     FIRST_VALUE(CASE WHEN CRP.CHARITY_RANK = 1 THEN CRP.CHARITY_AMOUNT ELSE NULL END) OVER (PARTITION BY CRP.SUBREGION ORDER BY CRP.CHARITY_RANK = 1 DESC) AS REGION_CHARITY_AMOUNT_1,
     FIRST_VALUE(CASE WHEN CRP.CHARITY_RANK = 2 THEN CRP.CHARITY_AMOUNT ELSE NULL END) OVER (PARTITION BY CRP.SUBREGION ORDER BY CRP.CHARITY_RANK = 2 DESC) AS REGION_CHARITY_AMOUNT_2,
     FIRST_VALUE(CASE WHEN CRP.CHARITY_RANK = 3 THEN CRP.CHARITY_AMOUNT ELSE NULL END) OVER (PARTITION BY CRP.SUBREGION ORDER BY CRP.CHARITY_RANK = 3 DESC) AS REGION_CHARITY_AMOUNT_3,
     FIRST_VALUE(CASE WHEN CRP.CHARITY_RANK = 4 THEN CRP.CHARITY_AMOUNT ELSE NULL END) OVER (PARTITION BY CRP.SUBREGION ORDER BY CRP.CHARITY_RANK = 4 DESC) AS REGION_CHARITY_AMOUNT_4,
     FIRST_VALUE(CASE WHEN CRP.CHARITY_RANK = 5 THEN CRP.CHARITY_AMOUNT ELSE NULL END) OVER (PARTITION BY CRP.SUBREGION ORDER BY CRP.CHARITY_RANK = 5 DESC) AS REGION_CHARITY_AMOUNT_5
     FROM   
        (SELECT 
        C.*,
        CASE WHEN C.MONTHLY_AMOUNT_PP_RN = 1 THEN AVG(C.MONTHLY_AMOUNT_PP) OVER (PARTITION BY C.SUBREGION, C.MONTHLY_AMOUNT_PP_RN = 1) ELSE 0 END AS AVG_MONTHLY_AMOUNT_PP,
        CASE WHEN C.MONTHLY_AMOUNT_PP_RN = 1 THEN MAX(C.MONTHLY_AMOUNT_PP) OVER (PARTITION BY C.SUBREGION, C.MONTHLY_AMOUNT_PP_RN = 1) ELSE 0 END AS MAX_MONTHLY_AMOUNT_PP,
        CASE WHEN C.CHARITY_RANK_RN = 1 THEN RANK() OVER (PARTITION BY C.SUBREGION, C.CHARITY_RANK_RN = 1 ORDER BY C.CHARITY_AMOUNT DESC) ELSE 0 END AS CHARITY_RANK
        FROM
           (SELECT 
             --JOINING FIELDS
            H.MULTI_SCHEME_ID 
            , H.SCHEME
            , D.MATERIAL_TYPE_ID 
            , IFNULL(CS.SUBREGION,'00 Unknown') AS SUBREGION
            , P.PARTICIPANT_NAME AS TRADING_NAME
            , CASE WHEN H.CONSUMER_TYPE IN ('School','Community Groups','Charity') THEN  H.CONSUMER_ID ELSE NULL END AS CHARITY
            , SUM(CASE WHEN H.CONSUMER_TYPE IN ('School','Community Groups','Charity') THEN D.GROSS_AMOUNT ELSE 0 END) OVER (PARTITION BY CS.SUBREGION) AS REGION_AMOUNT_FUNDRAISING
            , SUM(CASE WHEN H.CONSUMER_TYPE IN ('School','Community Groups','Charity') THEN D.GROSS_AMOUNT ELSE 0 END) OVER (PARTITION BY CS.SUBREGION,H.CONSUMER_ID) AS CHARITY_AMOUNT
            , SUM(D.COLLECTION_QTY) OVER (PARTITION BY CS.SUBREGION,D.MATERIAL_TYPE_ID) AS REGION_MATERIAL_QTY    
            , SUM(D.GROSS_AMOUNT) OVER (PARTITION BY H.CONSUMER_ID, LEFT(H.TRANSACTION_DATE_KEY,6) ) AS MONTHLY_AMOUNT_PP
            , CASE WHEN H.CONSUMER_TYPE IN ('School','Community Groups','Charity') THEN ROW_NUMBER() OVER (PARTITION BY CS.SUBREGION, H.CONSUMER_ID ORDER BY H.TRANSACTION_DATE DESC) ELSE 0 END AS CHARITY_RANK_RN
            , ROW_NUMBER() OVER (PARTITION BY CS.SUBREGION ORDER BY H.TRANSACTION_DATE DESC) AS REGION_RANK_RN
            , ROW_NUMBER() OVER (PARTITION BY H.CONSUMER_ID, LEFT(H.TRANSACTION_DATE_KEY,6) ORDER BY H.TRANSACTION_DATE DESC) AS MONTHLY_AMOUNT_PP_RN
            FROM {{ ref('CRP_COLLECTION_HDR') }} AS H
            INNER JOIN {{ ref('CRP_COLLECTION_DTL') }} AS D
            ON D.TRANSACTION_ID = H.TRANSACTION_ID
            LEFT JOIN {{ source('CES_DRUPAL', 'PARTICIPANT_SITES') }} AS PSC --CONSUMER REGION
            ON PSC.SITE_NUMBER = H.CONSUMER_ID AND PSC._FIVETRAN_DELETED = FALSE
            INNER JOIN {{ source('CES_DRUPAL', 'PARTICIPANTS') }} AS P
            ON P.PARTICIPANT_ID = PSC.PARTICIPANT_ID AND P._FIVETRAN_DELETED = FALSE
            LEFT JOIN {{ ref('REF_STATE') }} AS STATE
            ON STATE.STATE = PSC.STATE 
            LEFT JOIN {{ ref('CRP_SITES') }} AS CS
            ON CS.SITE_NUMBER = H.SITE_NUMBER
            LEFT JOIN {{ source('COEX_ALL_IN_ONE_DATASET', 'MATERIAL_TYPE') }} AS MH
            ON MH.MATERIALTYPEID = D.MATERIAL_TYPE_ID 
            WHERE H.CONSUMER_ID <> '-' 
            AND H.MULTI_SCHEME_ID = 10000 AND D.MATERIAL_TYPE_ID <> 'INELIGIBLE' AND (LOWER(P.PARTICIPANT_NAME) NOT LIKE '%pvt%' AND LOWER(P.PARTICIPANT_NAME) NOT LIKE'% test %')
            ) C 
      ) CRP
      QUALIFY ROW_NUMBER() OVER (PARTITION BY CRP.SUBREGION ORDER BY CRP.SUBREGION) = 1
    ) R
LEFT JOIN (
    SELECT
    COUNT(DISTINCT SITE_NUMBER) AS CRP_SITES,
    MULTI_SCHEME_ID,
    SUBREGION
    FROM {{ ref('CRP_SITES') }} AS CS
    WHERE STATUS = 'Active' AND MULTI_SCHEME_ID = 10000 AND (LOWER(CS.SITE_NAME) NOT LIKE '%pvt%' AND LOWER(CS.SITE_NAME) NOT LIKE'% test %')
    GROUP BY MULTI_SCHEME_ID, SUBREGION) RP
ON RP.MULTI_SCHEME_ID = R.MULTI_SCHEME_ID
AND RP.SUBREGION = R.SUBREGION
LEFT JOIN (
        SELECT 
        MULTI_SCHEME_ID,
        SUM(VOLUME)/12 AS SALES_VOLUME
        FROM {{ ref('BM_SALES_VOLUME') }} AS BMSV
        WHERE ENTRY_TYPE IN ('A','L','R') AND STATUS IN ('FINAL','INVOICED') AND MULTI_SCHEME_ID = '10000'
        AND DATE_TRUNC('quarter', TO_DATE(PERIOD || '-01')) BETWEEN DATE_TRUNC('quarter', DATEADD('quarter', -4, CURRENT_DATE())) AND DATEADD('day', -1, DATE_TRUNC('quarter', CURRENT_DATE()))
        GROUP BY  MULTI_SCHEME_ID
    ) S
ON R.MULTI_SCHEME_ID = S.MULTI_SCHEME_ID
LEFT JOIN (
        SELECT 
        MULTI_SCHEME_ID,
        SUM(VOLUME)/12 AS EXPORT_VOLUME
        FROM {{ ref('BM_EXPORT_VOLUME') }} AS BMEV
        WHERE ENTRY_TYPE IN ('A','L','R') AND STATUS IN ('FINAL','INVOICED')  AND MULTI_SCHEME_ID = '10000'
        AND DATE_TRUNC('quarter', TO_DATE(PERIOD || '-01')) BETWEEN DATE_TRUNC('quarter', DATEADD('quarter', -4, CURRENT_DATE())) AND DATEADD('day', -1, DATE_TRUNC('quarter', CURRENT_DATE()))
        GROUP BY  MULTI_SCHEME_ID
    ) E
ON R.MULTI_SCHEME_ID = E.MULTI_SCHEME_ID
LEFT JOIN (
        SELECT 
        COEX_SUBREGION,
        SUM(PERSON) OVER (PARTITION BY COEX_SUBREGION) / SUM(PERSON) OVER (PARTITION BY STATE_CODE_2021) AS POP_PERCENT,
        ROW_NUMBER() OVER (PARTITION BY COEX_SUBREGION ORDER BY COEX_SUBREGION) AS FILTER
        FROM {{ source('ABS', 'VW_COEX_GEOGRAPHY_2021') }} AS GEO
        WHERE STATE_CODE_2021 = 3
        AND COEX_SUBREGION <> '00 Unknown'
    ) POP
ON POP.COEX_SUBREGION = R.SUBREGION AND POP.FILTER = 1
LEFT JOIN (
    SELECT
    SUM(C.CLAIM_QTY) AS REGION_NUM_CONTAINERS 
    , SUM(C.CLAIM_QTY)/10 AS REGION_REFUND_AMOUNT
    , CS.SUBREGION
    , C.MULTI_SCHEME_ID
    FROM {{ ref('CRP_CLAIM') }} AS C
    LEFT JOIN {{ source('COEX_ALL_IN_ONE_DATASET', 'REF_ENVIRONMENTAL_BENEFITS_KILO') }} AS EK
    ON EK.MATERIAL_TYPE_ID = C.MATERIAL_TYPE_ID 
    LEFT JOIN {{ ref('CRP_SITES') }} AS CS
    ON CS.SITE_NUMBER= C.SITE_NUMBER
    WHERE C.MULTI_SCHEME_ID = 10000 AND C.MATERIAL_TYPE_ID <> 'INELIGIBLE' --AND (LOWER(CS.SITE_NAME) NOT LIKE '%pvt%' AND LOWER(CS.SITE_NAME) NOT LIKE'% test %')
    GROUP BY C.MULTI_SCHEME_ID, CS.SUBREGION) CLAIM
ON CLAIM.MULTI_SCHEME_ID = R.MULTI_SCHEME_ID
AND CLAIM.SUBREGION= R.SUBREGION
LEFT JOIN (
    SELECT * FROM
            (SELECT 
            H.MULTI_SCHEME_ID 
            , IFNULL(CS.SUBREGION,'00 Unknown') AS SUBREGION
            , PTT.PARTICIPANT_NAME AS NOMINATED_CHARITY
            , SUM(CASE WHEN PTT.PARTICIPANT_NAME IS NOT NULL THEN D.GROSS_AMOUNT ELSE 0 END) AS REFUND_AMOUNT_CHARITY
            FROM {{ ref('CRP_COLLECTION_HDR') }} AS H
            INNER JOIN {{ ref('CRP_COLLECTION_DTL') }} AS D
            ON D.TRANSACTION_ID = H.TRANSACTION_ID
            LEFT JOIN {{ source('CES_DRUPAL', 'PARTICIPANT_SITES') }} AS PT
            ON PT.SITE_NUMBER = H.RECIPIENT_CONSUMER_ID AND H.RECIPIENT_CONSUMER_ID <> H.CONSUMER_ID AND PT._FIVETRAN_DELETED = FALSE
            LEFT JOIN {{ source('CES_DRUPAL', 'PARTICIPANTS') }} AS PTT
            ON PTT.PARTICIPANT_ID = PT.PARTICIPANT_ID AND PTT._FIVETRAN_DELETED = FALSE
            LEFT JOIN {{ ref('CRP_SITES') }} AS CS
            ON CS.SITE_NUMBER = H.SITE_NUMBER         
            AND H.MULTI_SCHEME_ID = 10000 AND D.MATERIAL_TYPE_ID <> 'INELIGIBLE' AND (LOWER(PTT.PARTICIPANT_NAME) NOT LIKE '%pvt%' AND LOWER(PTT.PARTICIPANT_NAME) NOT LIKE'% test %') AND PTT.PARTICIPANT_NAME IS NOT NULL
            GROUP BY H.MULTI_SCHEME_ID, IFNULL(CS.SUBREGION,'00 Unknown') , PTT.PARTICIPANT_NAME) CHARITY
      QUALIFY RANK() OVER (PARTITION BY CHARITY.SUBREGION ORDER BY CHARITY.REFUND_AMOUNT_CHARITY DESC) = 1
) CHARITY
ON CHARITY.MULTI_SCHEME_ID = R.MULTI_SCHEME_ID
AND CHARITY.SUBREGION = R.SUBREGION
LEFT JOIN (
    SELECT 
    COUNT(DISTINCT CASE WHEN PS.TAXONOMY_TYPE_ID IN ('Consumer GST Registered') THEN P.CONSUMER_NUMBER ELSE NULL END) AS BUSINESS_REGISTERED
    , COUNT(DISTINCT CASE WHEN PS.TAXONOMY_TYPE_ID IN ('Charity') THEN P.CONSUMER_NUMBER ELSE NULL END) AS CHARITIES_REGISTERED
    , COUNT(DISTINCT CASE WHEN PS.TAXONOMY_TYPE_ID IN ('Community Groups') THEN P.CONSUMER_NUMBER ELSE NULL END) AS COMMUNITY_GROUPS_REGISTERED
    , COUNT(DISTINCT CASE WHEN PS.TAXONOMY_TYPE_ID IN ('School') THEN P.CONSUMER_NUMBER ELSE NULL END) AS SCHOOLS_REGISTERED
    , PS.MULTI_SCHEME_ID
    , NVL(SSC.SUBREGION, POA.SUBREGION) AS SUBREGION
    FROM {{ source('CES_DRUPAL', 'PARTICIPANT_SITES') }} AS PS
    INNER JOIN {{ source('CES_DRUPAL', 'PARTICIPANTS') }} AS P
    ON P.PARTICIPANT_ID = PS.PARTICIPANT_ID AND P._FIVETRAN_DELETED = FALSE
    LEFT JOIN {{ ref('REF_STATE') }} AS STATE
    ON STATE.STATE = PS.STATE 
    LEFT JOIN {{ ref('REF_LOCALITY_SSC') }} AS SSC
    ON PS.CITY_SUBURB = SSC.SUBURB
    AND PS.POST_CODE = SSC.POSTCODE
    AND STATE.STATE_NAME = SSC.STATE
    LEFT JOIN {{ ref('REF_LOCALITY_POA') }} AS POA
    ON PS.POST_CODE = POA.POSTCODE
    AND STATE.STATE_NAME = POA.STATE
    WHERE 
    PS.MULTI_SCHEME_ID = 10000 AND PS._FIVETRAN_DELETED = FALSE--COEX
    AND (LOWER(PS.SITE_NAME) NOT LIKE '%pvt%' AND LOWER(PS.SITE_NAME) NOT LIKE'% test %') 
    GROUP BY PS.MULTI_SCHEME_ID, NVL(SSC.SUBREGION, POA.SUBREGION)) GROUPS
ON GROUPS.MULTI_SCHEME_ID = R.MULTI_SCHEME_ID
AND GROUPS.SUBREGION = R.SUBREGION
WHERE R.SUBREGION <> '00 Unknown'