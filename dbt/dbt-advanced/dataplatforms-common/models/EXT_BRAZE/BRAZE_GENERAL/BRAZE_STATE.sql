SELECT
CRP.SCHEME AS "id"
, CLAIM.CLAIM_QTY AS "state_collection_qty"
, CRP.STATE_AMOUNT_FUNDRAISING AS "state_amount_fundraising"
, RP.CRP_SITES AS "state_num_rp"
, FIRST_VALUE(CRP.TRADING_NAME) OVER (ORDER BY (CASE WHEN CRP.CHARITY_RANK = 1 THEN CRP.CHARITY_RANK ELSE 0 END) DESC) AS "state_charity_name_1"
, FIRST_VALUE(CRP.CHARITY) OVER (ORDER BY (CASE WHEN CRP.CHARITY_RANK = 1 THEN CRP.CHARITY_RANK ELSE 0 END) DESC) AS "state_charity_schemeid_1"
, FIRST_VALUE(CRP.TRADING_NAME) OVER (ORDER BY (CASE WHEN CRP.CHARITY_RANK = 2 THEN CRP.CHARITY_RANK ELSE 0 END) DESC) AS "state_charity_name_2"
, FIRST_VALUE(CRP.CHARITY) OVER (ORDER BY (CASE WHEN CRP.CHARITY_RANK = 2 THEN CRP.CHARITY_RANK ELSE 0 END) DESC) AS "state_charity_schemeid_2"
, FIRST_VALUE(CRP.TRADING_NAME) OVER (ORDER BY (CASE WHEN CRP.CHARITY_RANK = 3 THEN CRP.CHARITY_RANK ELSE 0 END) DESC) AS "state_charity_name_3"
, FIRST_VALUE(CRP.CHARITY) OVER (ORDER BY (CASE WHEN CRP.CHARITY_RANK = 3 THEN CRP.CHARITY_RANK ELSE 0 END) DESC) AS "state_charity_schemeid_3"
, FIRST_VALUE(CRP.TRADING_NAME) OVER (ORDER BY (CASE WHEN CRP.CHARITY_RANK = 4 THEN CRP.CHARITY_RANK ELSE 0 END) DESC) AS "state_charity_name_4"
, FIRST_VALUE(CRP.CHARITY) OVER (ORDER BY (CASE WHEN CRP.CHARITY_RANK = 4 THEN CRP.CHARITY_RANK ELSE 0 END) DESC) AS "state_charity_schemeid_4"
, FIRST_VALUE(CRP.TRADING_NAME) OVER (ORDER BY (CASE WHEN CRP.CHARITY_RANK = 5 THEN CRP.CHARITY_RANK ELSE 0 END) DESC) AS "state_charity_name_5"
, FIRST_VALUE(CRP.CHARITY) OVER (ORDER BY (CASE WHEN CRP.CHARITY_RANK = 5 THEN CRP.CHARITY_RANK ELSE 0 END) DESC) AS "state_charity_schemeid_5"
, CLAIM.STATE_EMMISSIONS_REDUCED_TONNES AS "state_emmissions_reduced_tonnes"
, CS.STATE_NUM_CONTAINERS_SOLD AS "state_num_containers_sold"
, CEIL(CLAIM.STATE_EMMISSIONS_REDUCED_TONNES/2.4008305,0) AS "state_emmissions_reduced_car"
, CLAIM.CLAIM_QTY/10 AS "state_refund_amount"
, FIRST_VALUE(CRP.CHARITY_AMOUNT_FUNDRAISING) OVER (ORDER BY (CASE WHEN CRP.CHARITY_RANK = 1 THEN CRP.CHARITY_RANK ELSE 0 END) DESC) AS "charity_amount_1"
, FIRST_VALUE(CRP.CHARITY_AMOUNT_FUNDRAISING) OVER (ORDER BY (CASE WHEN CRP.CHARITY_RANK = 2 THEN CRP.CHARITY_RANK ELSE 0 END) DESC) AS "charity_amount_2"
, FIRST_VALUE(CRP.CHARITY_AMOUNT_FUNDRAISING) OVER (ORDER BY (CASE WHEN CRP.CHARITY_RANK = 3 THEN CRP.CHARITY_RANK ELSE 0 END) DESC) AS "charity_amount_3"
, FIRST_VALUE(CRP.CHARITY_AMOUNT_FUNDRAISING) OVER (ORDER BY (CASE WHEN CRP.CHARITY_RANK = 4 THEN CRP.CHARITY_RANK ELSE 0 END) DESC) AS "charity_amount_4"
, FIRST_VALUE(CRP.CHARITY_AMOUNT_FUNDRAISING) OVER (ORDER BY (CASE WHEN CRP.CHARITY_RANK = 5 THEN CRP.CHARITY_RANK ELSE 0 END) DESC) AS "charity_amount_5"
, CC_AVAILABLE.SUBURBS_CC_AVAILABLE AS "num_suburbs_cc_available"
, CAUSES.CAUSES_REGISTERED AS "state_causes_registered"
, CAUSES.BUSINESS_REGISTERED AS "state_businesses_registered"
, CAUSES.CHARITIES_REGISTERED AS "state_charities_registered"
, CAUSES.COMMUNITY_GROUPS_REGISTERED AS "state_community_groups_registered"
, CAUSES.SCHOOLS_REGISTERED AS "state_schools_registered"
 FROM   
    (SELECT 
    C.*,
    RANK() OVER (ORDER BY C.CHARITY_AMOUNT_FUNDRAISING DESC) AS CHARITY_RANK
    FROM
        ( SELECT 
         --JOINING FIELDS
        H.MULTI_SCHEME_ID
        , H.SCHEME
        , P.PARTICIPANT_NAME AS TRADING_NAME
        , CASE WHEN PSC.TAXONOMY_TYPE_ID IN ('School','Community Groups','Charity') THEN  PSC.SITE_NUMBER ELSE NULL END AS CHARITY
        , SUM(CASE WHEN PSC.TAXONOMY_TYPE_ID IN ('School','Community Groups','Charity') THEN D.GROSS_AMOUNT ELSE 0 END) OVER (PARTITION BY H.SCHEME) AS STATE_AMOUNT_FUNDRAISING
        , SUM(CASE WHEN PSC.TAXONOMY_TYPE_ID IN ('School','Community Groups','Charity') THEN D.GROSS_AMOUNT ELSE 0 END) OVER (PARTITION BY H.SCHEME, PSC.SITE_NUMBER) AS CHARITY_AMOUNT_FUNDRAISING
        , CASE WHEN H.CONSUMER_ID <> '-' THEN ROW_NUMBER() OVER (PARTITION BY PSC.SITE_NUMBER ORDER BY H.TRANSACTION_DATE DESC) ELSE 0 END AS CHARITY_RANK_RN
        FROM {{ ref('CRP_COLLECTION_HDR') }} AS H
        INNER JOIN {{ ref('CRP_COLLECTION_DTL') }} AS D
        ON D.TRANSACTION_ID = H.TRANSACTION_ID
        LEFT JOIN {{ source('CES_DRUPAL', 'PARTICIPANT_SITES') }} AS PSC
        ON PSC.SITE_NUMBER = H.CONSUMER_ID AND PSC._FIVETRAN_DELETED = FALSE
        LEFT JOIN {{ source('CES_DRUPAL', 'PARTICIPANTS') }} AS P
        ON P.PARTICIPANT_ID = PSC.PARTICIPANT_ID AND P._FIVETRAN_DELETED = FALSE
        LEFT JOIN {{ source('COEX_ALL_IN_ONE_DATASET', 'MATERIAL_TYPE') }} AS MH
        ON MH.MATERIALTYPEID = D.MATERIAL_TYPE_ID 
        WHERE 
        H.MULTI_SCHEME_ID = 10000 AND D.MATERIAL_TYPE_ID <> 'INELIGIBLE'  AND (LOWER(PSC.SITE_NAME) NOT LIKE '%pvt%' AND LOWER(PSC.SITE_NAME) NOT LIKE'% test %')  --Test sites
        --QUALIFY ROW_NUMBER() OVER (PARTITION BY H.CONSUMER_ID,(CASE WHEN D.MATERIAL_TYPE_ID IN ('LQDPAPERBRD','ALUMINIUM','GLASSMIXED') THEN D.MATERIAL_TYPE_ID WHEN D.MATERIAL_TYPE_ID IN ('PETCOLORED','PETCLEAR') THEN 'PET' ELSE NULL END) ORDER BY H.TRANSACTION_DATE DESC) = 1 --GROUP BY MATERIAL,CONSUMER_ID
    ) C 
    WHERE C.CHARITY IS NOT NULL AND C.CHARITY_RANK_RN = 1--Materials excluded from ranking
    ORDER BY C.CHARITY
  ) CRP
LEFT JOIN (
    SELECT COUNT(DISTINCT CS.SITE_NUMBER) AS CRP_SITES
    , CS.MULTI_SCHEME_ID
    FROM {{ ref('CRP_SITES') }} AS CS
    WHERE CS.STATUS = 'Active' AND CS.MULTI_SCHEME_ID = 10000
    GROUP BY CS.MULTI_SCHEME_ID) RP
ON RP.MULTI_SCHEME_ID = CRP.MULTI_SCHEME_ID
LEFT JOIN (
    SELECT CEIL(SUM((L.MANIFEST_WEIGHT_KG)*CONVERSION_FACTOR),0) AS STATE_NUM_CONTAINERS_SOLD
    , L.MULTI_SCHEME_ID
    FROM {{ ref('AUCTION_MANIFEST_CLEANSED') }} AS L
    LEFT JOIN {{ source('CES_MSCM', 'UOM_REFERENCE') }} AS A
    ON L.MATERIAL_TYPE_ID = A.MATERIAL_TYPE_ID
    AND A.FROM_UNIT = 'KILOGRAM'
    AND A.TO_UNIT = 'UNIT'
    AND SYSDATE() BETWEEN NVL(A.EFFECTIVE_FROM,TO_DATE('01/JAN/1900','DD/MON/YYYY')) AND NVL(A.EFFECTIVE_TO,TO_DATE('01/JAN/9999','DD/MON/YYYY'))
    AND L.MULTI_SCHEME_ID = A.MULTI_SCHEME_ID
    WHERE L.STATUS IN ('SOLD_AND_COLLECTED','AWAITING_COLLECTION','AWAITING_DESTINATION_CONFIRMATION') AND L.MULTI_SCHEME_ID = 10000 AND L.SELLER_ID NOT LIKE 'QF%'  --AND (TO_CHAR(L.AGREEMENT_DATE,'YYYYMMDD') BETWEEN '20211201' AND  '20221130') 
    GROUP BY L.MULTI_SCHEME_ID) CS
ON CS.MULTI_SCHEME_ID = CRP.MULTI_SCHEME_ID
LEFT JOIN (
    SELECT 
    COUNT(DISTINCT CASE WHEN PS.TAXONOMY_TYPE_ID IN ('Community Groups','Charity','School') THEN P.CONSUMER_NUMBER ELSE NULL END) AS CAUSES_REGISTERED
    , COUNT(DISTINCT CASE WHEN PS.TAXONOMY_TYPE_ID IN ('Consumer GST Registered') THEN P.CONSUMER_NUMBER ELSE NULL END) AS BUSINESS_REGISTERED
    , COUNT(DISTINCT CASE WHEN PS.TAXONOMY_TYPE_ID IN ('Charity') THEN P.CONSUMER_NUMBER ELSE NULL END) AS CHARITIES_REGISTERED
    , COUNT(DISTINCT CASE WHEN PS.TAXONOMY_TYPE_ID IN ('Community Groups') THEN P.CONSUMER_NUMBER ELSE NULL END) AS COMMUNITY_GROUPS_REGISTERED
    , COUNT(DISTINCT CASE WHEN PS.TAXONOMY_TYPE_ID IN ('School') THEN P.CONSUMER_NUMBER ELSE NULL END) AS SCHOOLS_REGISTERED
    , PS.MULTI_SCHEME_ID
    FROM {{ source('CES_DRUPAL', 'PARTICIPANT_SITES') }} AS PS
    INNER JOIN {{ source('CES_DRUPAL', 'PARTICIPANTS') }} AS P
    ON P.PARTICIPANT_ID = PS.PARTICIPANT_ID AND P._FIVETRAN_DELETED = FALSE
    WHERE 
    PS.MULTI_SCHEME_ID = 10000  AND PS._FIVETRAN_DELETED = FALSE --COEX
    AND (LOWER(PS.SITE_NAME) NOT LIKE '%pvt%' AND LOWER(PS.SITE_NAME) NOT LIKE'% test %')
    GROUP BY PS.MULTI_SCHEME_ID) CAUSES
ON CAUSES.MULTI_SCHEME_ID = CRP.MULTI_SCHEME_ID
LEFT JOIN (
    SELECT 
    COUNT(DISTINCT A.POST_CODE || '-' || IFNULL(A.SUBURB_NAME,A.ABS_SUBURB)) AS SUBURBS_CC_AVAILABLE
    , 10000 AS MULTI_SCHEME_ID
    FROM {{ source('COEX_AGILOFT', 'AG_SUBURB') }} AS A
    WHERE STATUS = '05 LIVE') CC_AVAILABLE
ON CC_AVAILABLE.MULTI_SCHEME_ID = CRP.MULTI_SCHEME_ID
LEFT JOIN (
    SELECT
    SUM(C.CLAIM_QTY) AS CLAIM_QTY
    , SUM(C.CLAIM_KG_DERIVED) AS CLAIM_KG
    , SUM(EK.CO2_TONNES * C.CLAIM_KG_DERIVED) AS STATE_EMMISSIONS_REDUCED_TONNES
    , C.MULTI_SCHEME_ID
    FROM {{ ref('CRP_CLAIM') }} AS C
    LEFT JOIN {{ source('COEX_ALL_IN_ONE_DATASET', 'REF_ENVIRONMENTAL_BENEFITS_KILO') }} AS EK
    ON EK.MATERIAL_TYPE_ID = C.MATERIAL_TYPE_ID 
    LEFT JOIN {{ ref('CRP_SITES') }} AS CS
    ON CS.SITE_NUMBER= C.SITE_NUMBER
    WHERE C.MULTI_SCHEME_ID = 10000 AND C.MATERIAL_TYPE_ID <> 'INELIGIBLE' AND (LOWER(CS.SITE_NAME) NOT LIKE '%pvt%' AND LOWER(CS.SITE_NAME) NOT LIKE'% test %')
    GROUP BY C.MULTI_SCHEME_ID) CLAIM
ON CLAIM.MULTI_SCHEME_ID = CRP.MULTI_SCHEME_ID
QUALIFY ROW_NUMBER() OVER (PARTITION BY CRP.MULTI_SCHEME_ID ORDER BY CRP.MULTI_SCHEME_ID) = 1 --Filter out dups