SELECT
I.CONSUMER_ID_INDIVIDUAL AS "consumer_id"
, PG.CONSUMER_NUMBER AS "team_member_number"
, PG.ALTERNATE_NAME AS "team_name"
, PSG.POST_CODE AS "team_postcode"
, PSG.CITY_SUBURB AS "team_suburb"
, CASE WHEN PSG.TAXONOMY_TYPE_ID = 'Consumer GST Registered' THEN 'Business' ELSE PSG.TAXONOMY_TYPE_ID END AS "team_type"
, CASE WHEN CRG.ROLE_TYPE_CODE = 'GROUP_MEMBER' THEN 'team_mate' ELSE 'team_captain' END AS "role"
, NVL(CRP.FLAG,'FALSE') AS "team_member_number_transacted"
, PPP.PAYMENT_METHOD AS "team_payment_method"
, PSG.CREATED_ON AS "team_registration_date"
, TO_NUMBER(NULLIF(TRIM(REGEXP_REPLACE(NVL(SSC.SUBREGION, POA.SUBREGION), '[^[:digit:]]', ' ')), '')) AS "team_subregion_id"
, PSG.PARTICIPANT_SITE_ID AS PARTICIPANT_SITE_ID
, COUNT(DISTINCT I.CONSUMER_ID_INDIVIDUAL) OVER (PARTITION BY PG.CONSUMER_NUMBER) AS "team_num_teammates"
, CASE WHEN PW.PUBLIC_WEBSITE_CONSENT = 'Y' THEN 'TRUE' ELSE 'FALSE' END AS "team_shared_cause"
FROM 
{{ source('CES_DRUPAL', 'CONTACTS') }} AS CG
INNER JOIN {{ source('CES_DRUPAL', 'CONTACT_ROLES') }} AS CRG
ON CG.CONTACT_ID = CRG.CONTACT_ID AND CRG._FIVETRAN_DELETED = FALSE
INNER JOIN {{ source('CES_DRUPAL', 'PARTICIPANT_SITES') }} AS PSG
ON CRG.PARTICIPANT_SITE_ID = PSG.PARTICIPANT_SITE_ID AND PSG._FIVETRAN_DELETED = FALSE
INNER JOIN {{ source('CES_DRUPAL', 'PARTICIPANTS') }} AS PG
ON PG.PARTICIPANT_ID = PSG.PARTICIPANT_ID AND PG._FIVETRAN_DELETED = FALSE
INNER JOIN (
    SELECT
    PS.MULTI_SCHEME_ID,
    P.CONSUMER_NUMBER AS CONSUMER_ID_INDIVIDUAL,
    CR.CONTACT_ID,
    CR.EFFECTIVE_START_DATE,
    CR.EFFECTIVE_END_DATE,
    CR.ACTIVE
    FROM {{ source('CES_DRUPAL', 'CONTACT_ROLES') }} AS CR
    LEFT JOIN {{ source('CES_DRUPAL', 'PARTICIPANT_SITES') }} AS PS
    ON CR.PARTICIPANT_SITE_ID = PS.PARTICIPANT_SITE_ID AND PS._FIVETRAN_DELETED = FALSE
    LEFT JOIN {{ source('CES_DRUPAL', 'PARTICIPANTS') }} AS P
    ON P.PARTICIPANT_ID = PS.PARTICIPANT_ID AND P._FIVETRAN_DELETED = FALSE
    WHERE CR.ROLE_TYPE_CODE = 'AUTHORISED_CONTACT_B2C' AND CR._FIVETRAN_DELETED = FALSE --Authorised Contact B2C
    AND P.PARTICIPANT_GROUP = 'IND_CONSUMER' --Individual Consumer
    AND PS.TAXONOMY_TYPE_ID = 'Consumer' 
    QUALIFY ROW_NUMBER() OVER (PARTITION BY PS.MULTI_SCHEME_ID, CR.CONTACT_ID ORDER BY PS.LAST_MODIFIED_ON DESC) = 1 --TO REMOVE THE DUPS SCXT-3407
) I
ON CRG.CONTACT_ID = I.CONTACT_ID
AND PSG.MULTI_SCHEME_ID = I.MULTI_SCHEME_ID
LEFT JOIN (
    SELECT 
    H.CONSUMER_ID
    , 'TRUE' AS FLAG
    , H.PAYMENT_METHOD AS LAST_USED_PAYMENT_METHOD
    FROM {{ ref('CRP_COLLECTION_HDR') }} AS H
    INNER JOIN {{ ref('CRP_COLLECTION_DTL') }} AS D
    ON D.TRANSACTION_ID = H.TRANSACTION_ID
    INNER JOIN {{ source('CES_DRUPAL', 'PARTICIPANT_SITES') }} AS PSC
    ON PSC.SITE_NUMBER = H.CONSUMER_ID AND PSC.TAXONOMY_TYPE_ID <> 'Consumer' AND PSC._FIVETRAN_DELETED = FALSE
    INNER JOIN {{ source('CES_DRUPAL', 'PARTICIPANTS') }} AS P 
    ON P.PARTICIPANT_ID = PSC.PARTICIPANT_ID --AND P.PARTICIPANT_GROUP = 'IND_CONSUMER' AND P._FIVETRAN_DELETED = FALSE
    WHERE H.MULTI_SCHEME_ID = 10000 AND D.MATERIAL_TYPE_ID <> 'INELIGIBLE' 
    QUALIFY ROW_NUMBER() OVER (PARTITION BY H.CONSUMER_ID ORDER BY H.TRANSACTION_DATE DESC) = 1 --IF 2 ACTIVE GOALS EXIST
) CRP
ON CRP.CONSUMER_ID = PSG.SITE_NUMBER
LEFT JOIN (
    SELECT 
    PPP.SCHEME_PARTICIPANT_ID
    , PPP.PAYMENT_METHOD
    FROM {{ source('CES_MSCM', 'PYMT_PAY_PARTY_PROFILES') }} AS PPP
    WHERE PPP.DEFAULT_FLAG = 'Y' AND PPP.MULTI_SCHEME_ID = 10000
    AND SYSDATE() BETWEEN PPP.START_DATE_ACTIVE AND NVL(PPP.END_DATE_ACTIVE,'9999-12-01')
    QUALIFY ROW_NUMBER() OVER (PARTITION BY PPP.SCHEME_PARTICIPANT_ID ORDER BY PPP.LAST_MODIFIED_ON DESC) = 1
) PPP
ON PPP.SCHEME_PARTICIPANT_ID = PG.CONSUMER_NUMBER
--SUBREGION MAPPING
LEFT JOIN {{ ref('REF_STATE') }} AS STATE
ON STATE.STATE = PSG.STATE 
LEFT JOIN {{ ref('REF_LOCALITY_SSC') }} AS SSC
ON PSG.CITY_SUBURB = SSC.SUBURB
AND PSG.POST_CODE = SSC.POSTCODE
AND STATE.STATE_NAME = SSC.STATE
LEFT JOIN {{ ref('REF_LOCALITY_POA') }} AS POA
ON PSG.POST_CODE = POA.POSTCODE
--GOAL
LEFT JOIN (
    SELECT 
    DISTINCT
    G.PARTICIPANT_SITE_ID
    FROM {{ source('CES_DRUPAL', 'CFC_GOAL') }} AS G
    WHERE G.GOAL_AMOUNT <> 0 AND G._FIVETRAN_DELETED = 'FALSE' 
    AND G.GOAL_MEMBER_TYPE = 1 --TEAMS 
    AND SYSDATE() BETWEEN TRUNC(G.GOAL_START_DATE, 'DAY') AND TRUNC(G.GOAL_END_DATE, 'DAY')
) G
ON G.PARTICIPANT_SITE_ID = PSG.PARTICIPANT_SITE_ID
LEFT JOIN {{ ref('CONSUMER_PUBLIC_INFO') }} AS PW
ON PW.CONSUMER_ID = PG.CONSUMER_NUMBER AND PW.PUBLIC_WEBSITE_CONSENT = 'Y'
WHERE PSG.TAXONOMY_TYPE_ID <> 'Consumer'
AND CRG.ROLE_TYPE_CODE <> 'AUTHORISED_CONTACT_B2C'
AND CG.ACTIVE = 1
AND CRG.ACTIVE = 1
AND PSG.MULTI_SCHEME_ID = 10000 --COEX
QUALIFY COUNT(*) OVER (PARTITION BY I.CONSUMER_ID_INDIVIDUAL) = 1 --TO REMOVE THE DUPS WHERE CUSTOMERS BELONG TO MORE THAN 1 GROUP (SCXT-3407)