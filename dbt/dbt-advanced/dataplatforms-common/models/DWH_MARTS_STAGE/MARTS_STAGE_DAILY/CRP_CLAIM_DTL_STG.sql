WITH UOM_REFERENCE AS (

    SELECT * FROM
    {{ source('CES_MSCM', 'UOM_REFERENCE') }}
    WHERE FROM_UNIT = 'KILOGRAM'
    AND TO_UNIT = 'UNIT'
    AND SYSDATE() BETWEEN NVL(EFFECTIVE_FROM,TO_DATE('01/JAN/1900','DD/MON/YYYY')) AND NVL(EFFECTIVE_TO,TO_DATE('01/JAN/9999','DD/MON/YYYY'))

), PERIOD AS ( --could use REF from DATE_DIMENSION_STG

        WITH RECURSIVE date_range AS (
            SELECT TO_DATE('2015-01-01', 'YYYY-MM-DD') AS DT
            UNION ALL
            SELECT DATEADD(DAY, 1, DT)
            FROM date_range
            WHERE DT < DATEADD(YEAR, 20, DATE_TRUNC('YEAR', CURRENT_DATE))
        )
        SELECT 
            DT,
            TO_CHAR(DT, 'YYYYMMDD') AS DATE_ID,
            YEAROFWEEKISO(DT) || '-' || TO_CHAR(WEEKISO(DT),'FM00') AS YEAR_WEEK_ISO
        FROM date_range

), CLAIM_DTL AS (

SELECT
    --Natural Key
     DTL.ID
    --Attributes
    ,DTL.MULTI_SCHEME_ID
    ,DTL.CRP_CLAIM_HDR_ID
    ,DTL.WHO_PAYS
    ,DTL.MATERIAL_TYPE_ID
    ,DTL.UOM
    ,MT.NAME AS MATERIAL_TYPE
    ,'Claim QTY' AS CLAIM_QTY_HEADER
    ,D.YEAR_WEEK_ISO AS LAST_MODIFIED_ON_UTC_YEAR_WEEK_ISO
    ,CASE WHEN DTL.WHO_PAYS = 'CRP' THEN 'Cash' WHEN DTL.WHO_PAYS = 'PRO' THEN 'Scheme' ELSE DTL.WHO_PAYS END AS PAYMENT_TYPE
    ,HDR.CRP_ID AS SITE_NUMBER
    --Metrics
    ,DTL.VOLUME AS CLAIM_QTY
    ,DTL.VOLUME/NVL(U_KG_QTY_A.CONVERSION_FACTOR,U_KG_QTY_B.CONVERSION_FACTOR) AS CLAIM_KG_DERIVED
    --Metadata Attributes
    ,DTL.CREATED_BY
    ,DTL.CREATED_ON AS CREATED_ON_UTC_DATETIME
    ,DTL.LAST_MODIFIED_BY
    ,DTL.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC_DATETIME
    ,GREATEST(COALESCE(HDR.LAST_MODIFIED_ON,to_timestamp('1900-01-01 00:00:00','YYYY-MM-DD HH24:MI:SS')),
              COALESCE(DTL.LAST_MODIFIED_ON,to_timestamp('1900-01-01 00:00:00','YYYY-MM-DD HH24:MI:SS')),
              COALESCE(SCHEME.LAST_MODIFIED_ON,to_timestamp('1900-01-01 00:00:00','YYYY-MM-DD HH24:MI:SS')),
              COALESCE(MT.LAST_MODIFIED_ON,to_timestamp('1900-01-01 00:00:00','YYYY-MM-DD HH24:MI:SS'))
             ) AS INCREMENTAL_UTC_DATETIME

FROM 
--Txn
{{ source('CES_MSCM', 'CRP_CLAIM_HDR') }} AS HDR
INNER JOIN {{ source('CES_MSCM', 'CRP_CLAIM_DTL') }} AS DTL ON HDR.ID = DTL.CRP_CLAIM_HDR_ID
--Scheme
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME ON HDR.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
--Material
INNER JOIN {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS MT ON DTL.MATERIAL_TYPE_ID = MT.ID
LEFT JOIN PERIOD AS D ON TO_CHAR(DTL.LAST_MODIFIED_ON, 'YYYYMMDD') = D.DATE_ID   
--Conversion
LEFT JOIN UOM_REFERENCE AS U_KG_QTY_A ON DTL.MATERIAL_TYPE_ID = U_KG_QTY_A.MATERIAL_TYPE_ID AND HDR.CRP_ID = U_KG_QTY_A.SCHEME_PARTICIPANT_ID AND DTL.MULTI_SCHEME_ID = U_KG_QTY_A.MULTI_SCHEME_ID
LEFT JOIN UOM_REFERENCE AS U_KG_QTY_B ON DTL.MATERIAL_TYPE_ID = U_KG_QTY_B.MATERIAL_TYPE_ID AND U_KG_QTY_B.SCHEME_PARTICIPANT_ID IS NULL AND DTL.MULTI_SCHEME_ID = U_KG_QTY_B.MULTI_SCHEME_ID
{% if is_incremental() %}
WHERE INCREMENTAL_UTC_DATETIME >= (SELECT dateadd(hours, {{var('general_delta_load_hours')}}, max(LATEST_UPDATE_UTC_TIME)) FROM  CES_REF.CES_DBT.DBT_INCREMENTAL_LOG_CONTROL WHERE TABLE_NAME = '{{model.name}}' )
{% endif %} 

)
SELECT * FROM CLAIM_DTL