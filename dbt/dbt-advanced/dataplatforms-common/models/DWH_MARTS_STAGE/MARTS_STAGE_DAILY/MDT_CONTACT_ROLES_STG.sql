{{
    config(
        materialized = 'incremental',
        incremental_strategy = 'merge',
        unique_key = 'CONTACT_ROLE_ID',        
        pre_hook= "{{ incremental_pre() }}",
        post_hook= "{{ incremental_post() }}",
        enabled = run_flag_dev()
    )
}}

SELECT
    --Natural Key
    CR.CONTACT_ROLE_ID
    --Attributes
    , CR.CONTACT_ID
    , CR.CONTRACT_ORG_ID
    , CR.CRM_CONTACT_ID
    , CR.CRM_ROLE_ID
    , CR.PARTICIPANT_ID
    , CR.PARTICIPANT_SITE_ID
    , CR.ROLE_TYPE_ID
    , PS.MULTI_SCHEME_ID
    , SCHEME.NAME AS SCHEME 
    , C.FIRST_NAME || ' ' || C.LAST_NAME AS CONTACT_NAME
    , C.FIRST_NAME  AS FIRST_NAME 
    , C.LAST_NAME  AS LAST_NAME 
    , R_T.VALUE AS ROLE
    , CR.ACTIVE AS ROLE_ACTIVE
    , C.ACTIVE AS CONTACT_ACTIVE
    , CR.ASSIGNMENT_TYPE AS ASSIGNMENT_TYPE
    , C.PHONE_NUMBER  AS PHONE_NUMBER 
    , C.PHONE_EXT  AS PHONE_EXT 
    , C.MOBILE_PHONE_COUNTRY_CODE
    , C.MOBILE_PHONE_AREA_CODE
    , C.MOBILE_PHONE_NUMBER AS MOBILE_PHONE_NUMBER
    , TRIM(LOWER(C.EMAIL)) AS EMAIL
    , 'live.com#' || TRIM(LOWER(C.EMAIL)) AS EMAIL_LIVE
    , C.AREA_CODE
    , C.ATTRIBUTE_CATEGORY
    , C.ATTRIBUTE1
    , C.ATTRIBUTE12
    , C.COUNTRY_CODE
    , C.CRM_LOGIN_ID
    , C.EFFECTIVE_END_DATE AS CONTACT_EFFECTIVE_FROM_DATE
    , C.EFFECTIVE_START_DATE AS CONTACT_EFFECTIVE_START_DATE
    , C.ERP_PERSON_PROFILE_ID
    , C.JOB_TITLE
    , C.PRIMARY
    , C.SALUTATION
    , C.SUPPLIED_CONSUMER_EMAIL
    , PS.SITE_NUMBER  AS SITE_NUMBER 
    , PS.SITE_NAME  AS SITE_NAME 
    , P.PARTICIPANT_NUMBER  AS SUPPLIER_NUMBER 
    , P.PARTICIPANT_NAME  AS SUPPLIER_NAME 
    , R_TT.VALUE AS TAXONOMY
    , CAST(CR.EFFECTIVE_START_DATE AS DATE) AS ROLE_EFFECTIVE_FROM_DATE
    , CAST(CR.EFFECTIVE_END_DATE AS DATE) AS ROLE_EFFECTIVE_TO_DATE
    , CASE WHEN DATEADD(DAY,1,MAX(CR.CREATED_ON) OVER (PARTITION BY PS.MULTI_SCHEME_ID))>=SYSDATE() THEN 'Y' ELSE 'N' END AS ROLE_CREATED_ON_LAST_1_DAY_EXTRACT
    , CASE WHEN DATEADD(DAY,1,CR.CREATED_ON)>=SYSDATE() AND hour(CONVERT_TIMEZONE('UTC','Australia/Sydney',sysdate())) >= 16 THEN 'Y' ELSE 'N' END AS ROLE_CREATED_ON_LAST_1_DAY
    , CASE WHEN TO_CHAR(CR.EFFECTIVE_START_DATE,'yyyymm') = TO_CHAR(DATEADD(MONTH,-1,(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(SYSDATE() AS TIMESTAMP)))),'yyyymm') THEN 'New Account' WHEN TO_CHAR(CR.EFFECTIVE_END_DATE,'yyyymm') = TO_CHAR(DATEADD(MONTH,-1,(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(SYSDATE() AS TIMESTAMP)))),'yyyymm') THEN 'Deactivated Account' ELSE null END AS LAST_CALENDAR_MONTH_ACCOUNT_STATUS
    --Metadata Attributes
    , CR.CREATED_BY AS ROLE_CREATED_BY
    , CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(CR.CREATED_ON AS TIMESTAMP)) AS ROLE_CREATED_ON_LOCAL_DATETIME
    , CR.CREATED_ON AS ROLE_CREATED_ON_UTC_DATETIME
    , CR.LAST_MODIFIED_BY AS ROLE_LAST_MODIFIED_BY
    , CR.LAST_MODIFIED_ON AS ROLE_LAST_MODIFIED_ON

    , C.CREATED_BY AS CONTACT_CREATED_BY
    , CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(C.CREATED_ON AS TIMESTAMP)) AS CONTACT_CREATED_ON_LOCAL_DATETIME
    , C.CREATED_ON AS CONTACT_CREATED_ON_UTC_DATETIME
    , C.LAST_MODIFIED_BY AS CONTACT_LAST_MODIFIED_BY
    , C.LAST_MODIFIED_ON AS CONTACT_LAST_MODIFIED_ON

    , CASE WHEN C.LAST_MODIFIED_ON < CR.LAST_MODIFIED_ON THEN CR.LAST_MODIFIED_BY ELSE C.LAST_MODIFIED_BY END AS LAST_MODIFIED_BY
    , CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(GREATEST(NVL(C.LAST_MODIFIED_ON, TO_DATE('01/01/1900', 'DD/MM/YYYY')), NVL(CR.LAST_MODIFIED_ON, TO_DATE('01/01/1900', 'DD/MM/YYYY'))) AS TIMESTAMP)) AS LAST_MODIFIED_ON_LOCAL_DATETIME 
    , GREATEST(NVL(C.LAST_MODIFIED_ON, TO_DATE('01/01/1900', 'DD/MM/YYYY')), NVL(CR.LAST_MODIFIED_ON, TO_DATE('01/01/1900', 'DD/MM/YYYY'))) AS LAST_MODIFIED_ON_UTC_DATETIME
    , GREATEST(COALESCE(C.LAST_MODIFIED_ON,to_timestamp('1900-01-01 00:00:00','YYYY-MM-DD HH24:MI:SS')),
               COALESCE(CR.LAST_MODIFIED_ON,to_timestamp('1900-01-01 00:00:00','YYYY-MM-DD HH24:MI:SS')),
               COALESCE(PS.LAST_MODIFIED_ON,to_timestamp('1900-01-01 00:00:00','YYYY-MM-DD HH24:MI:SS')),
               COALESCE(P.LAST_MODIFIED_ON,to_timestamp('1900-01-01 00:00:00','YYYY-MM-DD HH24:MI:SS')),
               COALESCE(SCHEME.LAST_MODIFIED_ON,to_timestamp('1900-01-01 00:00:00','YYYY-MM-DD HH24:MI:SS')),
               COALESCE(R_T.LAST_MODIFIED_ON,to_timestamp('1900-01-01 00:00:00','YYYY-MM-DD HH24:MI:SS')),
               COALESCE(R_TT.LAST_MODIFIED_ON,to_timestamp('1900-01-01 00:00:00','YYYY-MM-DD HH24:MI:SS'))
               ) AS INCREMENTAL_UTC_DATETIME

FROM {{ source('CES_MSCM', 'MDT_CONTACTS') }} AS C 
INNER JOIN {{ source('CES_MSCM', 'MDT_CONTACT_ROLES') }} AS CR   --Around 4,500 contact_id's with no relation
ON C.CONTACT_ID = CR.CONTACT_ID
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS
ON CR.PARTICIPANT_SITE_ID = PS.PARTICIPANT_SITE_ID
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANTS') }} AS P
ON CR.PARTICIPANT_ID = P.PARTICIPANT_ID
LEFT JOIN {{ source('CES_MSCM', 'SCHEME') }} SCHEME
ON PS.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'SCHEME_REF_CODES') }} AS R_T
ON CR.ROLE_TYPE_ID = R_T.SCHEME_REF_CODES_ID
LEFT JOIN {{ source('CES_MSCM', 'SCHEME_REF_CODES') }} AS R_TT
ON PS.TAXONOMY_TYPE_ID || '' = R_TT.SCHEME_REF_CODES_ID || ''
{% if is_incremental() %}
WHERE INCREMENTAL_UTC_DATETIME >= (SELECT dateadd(hours, {{var('general_delta_load_hours')}}, max(LATEST_UPDATE_UTC_TIME)) FROM  CES_REF.CES_DBT.DBT_INCREMENTAL_LOG_CONTROL WHERE TABLE_NAME = '{{model.name}}' )
{% endif %}
