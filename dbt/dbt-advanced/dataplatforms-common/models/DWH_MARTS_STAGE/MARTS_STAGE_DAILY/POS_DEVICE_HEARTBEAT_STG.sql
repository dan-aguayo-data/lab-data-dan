SELECT
    --Natural Key
    PD.ID AS ID
    --Foreign Natural Key
    , PD.DEVICE_ID AS POS_DEVICE_ID
    --Attributes
    , PD.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
    , SCHEME.NAME AS SCHEME
    , PD.VERSION AS CURRENT_VERSION
    , PD.NAME AS NAME
    , PD.ENVIRONMENT AS ENVIRONMENT
    , PD.TYPE AS TYPE
    , PD.OS_VERSION AS CURRENT_OS_VERSION
    , PD.IP_ADDRESS AS IP_ADDRESS
    , PD.CRP_ID AS CRP_SITE_NUMBER
    , PD.LONGITUDE AS LONGITUDE
    , PD.LATITUDE AS LATITUDE
    , PD.MSC_CRP_SITE_ID
    , PD.USER_DEFINED_1
    , PD.USER_DEFINED_2
    , PD.USER_DEFINED_3
    , PD.USER_DEFINED_4
    --Metadata Attributes
    , PD.CREATED_BY AS CREATED_BY
    , PD.CREATED_ON AS CREATED_ON_UTC_DATETIME
    , PD.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
    , PD.LAST_MODIFIED_ON AS LAST_HEARTBEAT_ON_LOCAL_DATETIME
    , CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(PD.LAST_MODIFIED_ON AS TIMESTAMP)) AS LAST_MODIFIED_ON_UTC_DATETIME
    , GREATEST(COALESCE(PD.LAST_MODIFIED_ON,to_timestamp('1900-01-01 00:00:00','YYYY-MM-DD HH24:MI:SS')), 
               COALESCE(PS.LAST_MODIFIED_ON,to_timestamp('1900-01-01 00:00:00','YYYY-MM-DD HH24:MI:SS')), 
               COALESCE(SCHEME.LAST_MODIFIED_ON,to_timestamp('1900-01-01 00:00:00','YYYY-MM-DD HH24:MI:SS'))
              ) AS INCREMENTAL_UTC_DATETIME
    , ROW_NUMBER() OVER (PARTITION BY PD.NAME ORDER BY PD.LAST_MODIFIED_ON DESC, PD.CREATED_ON DESC) AS LAST_MODIFIED_RANK
FROM {{ source('CES_MSCM', 'POS_DEVICE_HEARTBEAT') }} AS PD
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS
ON PD.CRP_ID = PS.SITE_NUMBER
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON NVL(PD.MULTI_SCHEME_ID, PS.MULTI_SCHEME_ID) = SCHEME.MULTI_SCHEME_ID
{% if is_incremental() %}
WHERE INCREMENTAL_UTC_DATETIME >= (SELECT dateadd(hours, {{var('general_delta_load_hours')}}, max(LATEST_UPDATE_UTC_TIME)) FROM  CES_REF.CES_DBT.DBT_INCREMENTAL_LOG_CONTROL WHERE TABLE_NAME = '{{model.name}}' )
{% endif %}  