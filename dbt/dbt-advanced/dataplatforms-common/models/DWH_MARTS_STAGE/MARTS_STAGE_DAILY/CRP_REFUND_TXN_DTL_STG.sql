WITH CRP_HDR AS (

    SELECT 
     HDR.ID
    ,HDR.MULTI_SCHEME_ID
    ,HDR.REFUND_CRP
    ,HDR.RECIPIENT_CONSUMER_ID
    ,HDR.POS_DEVICE_ID
    ,HDR.TRANSACTED_ON
    ,HDR.TRANSACTED_BY
    ,HDR.PHOTO_ID_TYPE
    ,CASE WHEN HDR.MULTI_SCHEME_ID <> CON.MULTI_SCHEME_ID THEN HDR.CONSUMER || '002' ELSE HDR.CONSUMER END AS CONSUMER_CROSS_SCHEME
    ,CASE WHEN HDR.MULTI_SCHEME_ID <> CON_RECIP.MULTI_SCHEME_ID THEN HDR.RECIPIENT_CONSUMER_ID || '002' ELSE HDR.RECIPIENT_CONSUMER_ID END AS RECIPIENT_CONSUMER_ID_CROSS_SCHEME
    FROM 
    --Txn
    RAW_PROD.CES_MSCM_ORACLE.CRP_REFUND_TXN_HDR AS HDR
    --Consumer and recipient consumer to resolve cross scheme refunds
    LEFT JOIN RAW_PROD.CES_MSCM_ORACLE.MDT_PARTICIPANT_SITES CON ON HDR.CONSUMER = CON.SITE_NUMBER
    LEFT JOIN RAW_PROD.CES_MSCM_ORACLE.MDT_PARTICIPANT_SITES CON_RECIP ON HDR.RECIPIENT_CONSUMER_ID = CON_RECIP.SITE_NUMBER

), CRP_DTL AS (

    SELECT
     DTL.*
    ,CASE WHEN DTL.MATERIAL_TYPE_ID NOT LIKE '%INELIGIBLE%' THEN DTL.QUANTITY ELSE 0 END AS ELIGIBLE_QUANTITY
    ,CASE WHEN DTL.MATERIAL_TYPE_ID NOT LIKE '%INELIGIBLE%' THEN DTL.GROSS_AMOUNT ELSE 0 END AS ELIGIBLE_GROSS_AMOUNT
    ,CASE WHEN DTL.MATERIAL_TYPE_ID NOT LIKE '%INELIGIBLE%' THEN DTL.GST_AMOUNT ELSE 0 END AS ELIGIBLE_GST_AMOUNT
    ,CASE WHEN DTL.MATERIAL_TYPE_ID NOT LIKE '%INELIGIBLE%' THEN DTL.TAXABLE_AMOUNT ELSE 0 END AS ELIGIBLE_TAXABLE_AMOUNT
    ,CASE WHEN DTL.MATERIAL_TYPE_ID LIKE '%INELIGIBLE%' THEN DTL.QUANTITY ELSE 0 END AS INELIGIBLE_QUANTITY     
    FROM 
    RAW_PROD.CES_MSCM_ORACLE.CRP_REFUND_TXN_DTL AS DTL


), CRP_COLLECTION AS (

    SELECT
    --Natural Key
     DTL.ID
    --Attributes
    ,DTL.TRANSACTION_ID
    ,DTL.MULTI_SCHEME_ID
    ,SCHEME.NAME AS SCHEME
    ,SCHEME.TIMEZONE
    ,DTL.MATERIAL_TYPE_ID
    ,MT.NAME AS MATERIAL_TYPE
    ,DTL.SHIPPER_UNIT_ID
    ,HDR.REFUND_CRP AS SITE_NUMBER
    ,PD.CRP_ID AS SITE_NUMBER_POS
    ,HDR.RECIPIENT_CONSUMER_ID
    ,HDR.POS_DEVICE_ID
    ,HDR.TRANSACTED_ON
    ,PS.PARTICIPANT_ID AS SUPPLIER_ID
    ,CS.SITE_NUMBER AS CONSUMER_ID      
    --Metrics
    ,DTL.QUANTITY
    ,DTL.REFUND_PER_UNIT
    ,DTL.GROSS_AMOUNT
    ,DTL.TAXABLE_AMOUNT
    ,DTL.GST_AMOUNT
    ,DTL.ELIGIBLE_QUANTITY
    ,DTL.ELIGIBLE_GROSS_AMOUNT
    ,DTL.ELIGIBLE_GST_AMOUNT
    ,DTL.ELIGIBLE_TAXABLE_AMOUNT
    ,DTL.INELIGIBLE_QUANTITY  
    --Metadata Attributes
    ,DTL.CREATED_BY
    ,DTL.CREATED_ON AS CREATED_ON_UTC_DATETIME
    ,DTL.LAST_MODIFIED_BY
    ,DTL.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC_DATETIME
  
    FROM 
    --TXN Tables
    CRP_HDR AS HDR
    INNER JOIN CRP_DTL AS DTL ON HDR.ID=DTL.TRANSACTION_ID
    INNER JOIN RAW_PROD.CES_MSCM_ORACLE.MATERIAL_TYPE AS MT ON DTL.MATERIAL_TYPE_ID = MT.ID
    --Scheme
    INNER JOIN RAW_PROD.CES_MSCM_ORACLE.SCHEME AS SCHEME ON HDR.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
    --POS
    LEFT JOIN RAW_PROD.CES_MSCM_ORACLE.POS_DEVICE AS PD ON HDR.POS_DEVICE_ID = PD.ID
    LEFT JOIN RAW_PROD.CES_MSCM_ORACLE.POS_USER AS PU ON HDR.TRANSACTED_BY = PU.ID
    --CRP site details
    LEFT JOIN RAW_PROD.CES_MSCM_ORACLE.MDT_PARTICIPANT_SITES AS PS ON NVL(NULLIF(HDR.REFUND_CRP,''),PD.CRP_ID) = PS.SITE_NUMBER
    LEFT JOIN RAW_PROD.CES_MSCM_ORACLE.MDT_PARTICIPANTS AS P ON PS.PARTICIPANT_ID = P.PARTICIPANT_ID
    --Consumer details
    LEFT JOIN RAW_PROD.CES_MSCM_ORACLE.MDT_PARTICIPANT_SITES AS CS ON HDR.CONSUMER_CROSS_SCHEME = CS.SITE_NUMBER
    LEFT JOIN RAW_PROD.CES_MSCM_ORACLE.MDT_PARTICIPANTS AS CP ON CS.PARTICIPANT_ID = CP.PARTICIPANT_ID
    --Other
    LEFT JOIN RAW_PROD.CES_MSCM_ORACLE.PHOTO_ID_TYPE AS PIT ON HDR.PHOTO_ID_TYPE = PIT.ID
    LEFT JOIN RAW_PROD.CES_MSCM_ORACLE.REFUND_TXN_SURVEY AS RTS ON HDR.ID = RTS.REFUND_TXN_ID AND RTS.SURVEY_TYPE = 'POSTCODE'
    LEFT JOIN RAW_PROD.CES_MSCM_ORACLE.SCHEME_REF_CODES AS R_TT ON CS.TAXONOMY_TYPE_ID = R_TT.SCHEME_REF_CODES_ID

)
SELECT * FROM CRP_COLLECTION