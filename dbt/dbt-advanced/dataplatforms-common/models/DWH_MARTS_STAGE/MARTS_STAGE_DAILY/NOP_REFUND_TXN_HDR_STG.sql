WITH KAFKA_HDR AS (

	SELECT
    H.REFUND_TRANSACTION_ID AS ID,
	CAST(H.MULTI_SCHEME_ID AS NUMBER) AS MULTI_SCHEME_ID,
	H.EXTERNAL_REFUND_ID,
	HDR.EXTERNAL_MEMBER_ID,
	H.PAYMENT_TYPE AS PAYMENT_METHOD,
	HDR.TRANSACTED_BY,
	HDR.TRANSACTION_SUBMITTED_BY,	
	H.TRANSACTED_ON_UTC AS TRANSACTED_ON,
	H.CRP_SITE_NUMBER AS REFUND_CRP,
    HDR.CUSTOMER_NUMBER AS CONSUMER_ID,
	CASE WHEN H.MULTI_SCHEME_ID <> C.MULTI_SCHEME_ID THEN NVL(HDR.CUSTOMER_NUMBER, '-') || '002' ELSE NVL(HDR.CUSTOMER_NUMBER, '-') END AS CONSUMER_CROSS_SCHEME,
	NVL(HDR.RECIPIENT_NUMBER, '-') AS RECIPIENT_CONSUMER_ID,
	NVL(HDR.DEVICE_ID, '-') AS POS_DEVICE_ID,
	NVL(HDR.DEVICE_NAME, '-') AS DEVICE_NAME,
	HDR.MODIFIEDBY AS CREATED_BY,
	H.KAFKA_DATETIME AS CREATED_ON,
	HDR.MODIFIEDBY AS LAST_MODIFIED_BY,
	H.KAFKA_DATETIME AS LAST_MODIFIED_ON 
	FROM {{ source('CES_MSCM_KAFKA', 'NOP_CLAIM_REFUND') }} AS H
	LEFT JOIN {{ source('CES_MSCM_KAFKA', 'REFUND_TRANSACTION_HDR') }} AS HDR
	ON H.EXTERNAL_REFUND_ID = HDR.EXTERNAL_REFUND_ID
	AND H.MULTI_SCHEME_ID = HDR.MULTI_SCHEME_ID
	LEFT JOIN 
    {% if target.name.upper() == 'UAT' %}
    (select * from {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} QUALIFY row_number() OVER (PARTITION BY site_number ORDER BY last_modified_on DESC) = 1) AS C
    {%- else -%}
    {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS C
    {% endif %}
	ON NVL(HDR.CUSTOMER_NUMBER, '-') = C.SITE_NUMBER
	WHERE H.MULTI_SCHEME_ID IN (100020002, 100020003, 100030001)

), KAFKA_DTL AS (

    SELECT
        C.REFUND_TRANSACTION_ID AS ID,
        CAST(C.MULTI_SCHEME_ID AS NUMBER) AS MULTI_SCHEME_ID,
        SUM(C.CONTAINER_COUNT) AS QUANTITY,
        SUM(C.CONTAINER_COUNT * 0.1) AS GROSS_AMOUNT,
        NULL AS GST_AMOUNT,
        NULL AS TAXABLE_AMOUNT,        
        SUM(CASE WHEN C.MATERIAL_TYPE_ID NOT LIKE '%INELIGIBLE%' THEN C.CONTAINER_COUNT ELSE 0 END) AS ELIGIBLE_QUANTITY,
        SUM(CASE WHEN C.MATERIAL_TYPE_ID NOT LIKE '%INELIGIBLE%' THEN C.CONTAINER_COUNT * 0.1 ELSE 0 END) AS ELIGIBLE_GROSS_AMOUNT,
        NULL AS ELIGIBLE_GST_AMOUNT,
        NULL AS ELIGIBLE_TAXABLE_AMOUNT,
        SUM(CASE WHEN C.MATERIAL_TYPE_ID LIKE '%INELIGIBLE%' THEN C.CONTAINER_COUNT ELSE 0 END) AS INELIGIBLE_QUANTITY
    FROM {{ source('CES_MSCM_KAFKA', 'NOP_CLAIM_REFUND_ITEMS') }} AS C
    WHERE C.MULTI_SCHEME_ID IN (100020002, 100020003, 100030001)
    GROUP BY ALL

), KAFKA_COLLECTION AS (

    SELECT
    --Natural Key
     HDR.ID
    --Attributes
    ,HDR.MULTI_SCHEME_ID
    ,SCHEME.NAME AS SCHEME
    ,HDR.EXTERNAL_REFUND_ID
    ,SCHEME.TIMEZONE
    ,HDR.POS_DEVICE_ID
    ,PD.NAME AS POS_DEVICE_NAME
    ,PU.POS_USER_NAME
    ,CS.PARTICIPANT_ID AS CONSUMER_ID
    ,HDR.CONSUMER_ID AS CONSUMER
    ,HDR.CONSUMER_CROSS_SCHEME
    ,R_TT.VALUE AS CONSUMER_TYPE
    ,HDR.EXTERNAL_MEMBER_ID
    ,CS.SITE_NAME AS CONSUMER_NAME
    ,CS.POST_CODE AS CONSUMER_POSTCODE
    ,RTS.VALUE AS REFUND_TXN_SURVEY_POSTCODE
    ,CP.PARTICIPANT_GROUP_ID CONSUMER_GROUP_ID
    ,HDR.PAYMENT_METHOD    
    ,HDR.TRANSACTED_ON AS TRANSACTION_UTC_DATETIME
    ,CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(HDR.TRANSACTED_ON AS TIMESTAMP)) AS TRANSACTION_LOCAL_DATETIME
    ,TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(HDR.TRANSACTED_ON AS TIMESTAMP)),'YYYYMMDD') AS TRANSACTION_LOCAL_DATE_ID
    ,TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(HDR.TRANSACTED_ON AS TIMESTAMP)),'HHMISS') AS TRANSACTION_LOCAL_TIME_ID
    ,HDR.REFUND_CRP AS SITE_NUMBER
    ,PD.CRP_ID AS SITE_NUMBER_POS
    ,PS.SITE_NAME AS SITE_NAME
    ,PS.POST_CODE AS SITE_POSTCODE
    ,P.PARTICIPANT_ID AS SUPPLIER_ID
    ,P.PARTICIPANT_NUMBER AS SUPPLIER_NUMBER
    ,P.PARTICIPANT_NAME AS SUPPLIER_NAME
    ,HDR.RECIPIENT_CONSUMER_ID      

    --Metrics
    ,DTL.QUANTITY
    ,DTL.GROSS_AMOUNT
    ,DTL.GST_AMOUNT
    ,DTL.TAXABLE_AMOUNT
    ,DTL.ELIGIBLE_QUANTITY
    ,DTL.ELIGIBLE_GROSS_AMOUNT
    ,DTL.ELIGIBLE_GST_AMOUNT
    ,DTL.ELIGIBLE_TAXABLE_AMOUNT
    ,DTL.INELIGIBLE_QUANTITY
    --Metadata Attributes
    ,HDR.TRANSACTION_SUBMITTED_BY
    ,HDR.TRANSACTED_BY
    ,HDR.CREATED_BY
    ,HDR.CREATED_ON AS CREATED_ON_UTC_DATETIME
    ,HDR.LAST_MODIFIED_BY
    ,HDR.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC_DATETIME
    
    FROM 
    --TXN Tables
    KAFKA_HDR AS HDR
    LEFT JOIN KAFKA_DTL DTL ON HDR.ID=DTL.ID and HDR.MULTI_SCHEME_ID=DTL.MULTI_SCHEME_ID
    --Scheme
    INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME ON HDR.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
    --POS
    LEFT JOIN {{ source('CES_MSCM', 'POS_DEVICE') }} AS PD ON HDR.POS_DEVICE_ID = PD.ID
     LEFT JOIN {{ source('CES_MSCM', 'POS_USER') }} AS PU ON HDR.TRANSACTED_BY = PU.ID
    --CRP site details
    LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS ON NVL(NULLIF(HDR.REFUND_CRP,''),PD.CRP_ID) = PS.SITE_NUMBER
    LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANTS') }} AS P ON PS.PARTICIPANT_ID = P.PARTICIPANT_ID
    --Consumer details
    LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS CS ON HDR.CONSUMER_CROSS_SCHEME = CS.SITE_NUMBER
    LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANTS') }} AS CP ON CS.PARTICIPANT_ID = CP.PARTICIPANT_ID
    --Other
    LEFT JOIN {{ source('CES_MSCM', 'REFUND_TXN_SURVEY') }} AS RTS ON HDR.ID = RTS.REFUND_TXN_ID AND RTS.SURVEY_TYPE = 'POSTCODE'
    LEFT JOIN {{ source('CES_MSCM', 'SCHEME_REF_CODES') }} AS R_TT ON CS.TAXONOMY_TYPE_ID = R_TT.SCHEME_REF_CODES_ID

)
SELECT * FROM KAFKA_COLLECTION