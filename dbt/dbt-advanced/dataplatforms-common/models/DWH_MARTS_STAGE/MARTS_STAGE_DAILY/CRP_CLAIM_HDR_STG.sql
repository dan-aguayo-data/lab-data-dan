WITH CLAIM_APPROVAL_HISTORY AS (

    SELECT
    CA.CLAIM_ID AS CLAIM_ID
    , CA.ENTRY_TYPE AS ENTRY_TYPE
    , CA.STATUS AS STATUS
    , CA.KAFKA_DATETIME AS KAFKA_DATETIME
    FROM (
        SELECT
        CA.CLAIM_ID
        , CA.TYPE_FLAG AS ENTRY_TYPE
        , CA.STATUS AS STATUS
        , CA.KAFKA_DATETIME AS KAFKA_DATETIME
        FROM {{ source('CES_MSCM_KAFKA', 'CRP_CLAIM_APPROVAL') }} AS CA
        UNION
        SELECT
        CC.CLAIM_ID AS CLAIM_ID
        , 'R' AS ENTRY_TYPE
        , CC.STATUS AS STATUS
        , CC.KAFKA_DATETIME AS KAFKA_DATETIME
        FROM {{ source('CES_MSCM_KAFKA', 'CRP_CLAIM') }} AS CC
        UNION
        SELECT
        CCA.ADJUSTMENT_ID AS CLAIM_ID
        , 'A' AS ENTRY_TYPE
        , CCA.STATUS AS STATUS
        , CCA.KAFKA_DATETIME AS KAFKA_DATETIME
        FROM {{ source('CES_MSCM_KAFKA', 'CRP_CLAIM_ADJUSTMENT') }} AS CCA
    ) CA
    QUALIFY row_number() OVER (PARTITION BY CA.CLAIM_ID ORDER BY KAFKA_DATETIME DESC) = 1

), PERIOD AS (

    SELECT
    TO_CHAR(D.DT, 'YYYYMMDD') AS KEY
    , DAYOFWEEKISO(D.DT) AS DAY_OF_WEEK
    , YEAROFWEEKISO(D.DT) || '-' || TO_CHAR(WEEKISO(D.DT),'FM00') AS YEAR_WEEK_ISO
    FROM (
        SELECT TO_DATE('31/12/2015', 'DD/MM/YYYY') + N AS DT
        FROM (
            SELECT SEQ4() + 1 as N
            FROM TABLE(GENERATOR(ROWCOUNT => 10000))
        )
    ) D
    WHERE DAY_OF_WEEK=1
    
), CLAIM_HDR AS (

SELECT
    --Natural Key
     HDR.ID AS CLAIM_HDR_ID
    --Attributes
    ,HDR.MULTI_SCHEME_ID 
    ,SCHEME.NAME AS SCHEME
    ,SCHEME.TIMEZONE
    ,HDR.CRP_ID AS SITE_NUMBER
    ,PS.SITE_NAME AS SITE_NAME
    ,PS.PARTICIPANT_ID AS SUPPLIER_ID
    ,P.PARTICIPANT_NUMBER AS SUPPLIER_NUMBER
    ,P.PARTICIPANT_NAME AS SUPPLIER_NAME
    ,HDR.PERIOD
    ,WS.KEY AS PERIOD_DATE_ID
    ,HDR.PERIOD_TYPE
    ,HDR.ENTRY_TYPE
    ,CASE WHEN HDR.ENTRY_TYPE = 'R' THEN 'Claim' WHEN HDR.ENTRY_TYPE = 'A' THEN 'Adjustment' ELSE HDR.ENTRY_TYPE END AS ENTRY_TYPE_DESC
    ,HDR.STATUS
    ,CA.STATUS AS CLAIM_APPROVAL_KAFKA_STATUS
    ,HDR.SUBMITTED_BY
    ,CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(HDR.SUBMITTED_DATE AS TIMESTAMP)) AS SUBMITTED_DATE_LOCAL_DATETIME
    ,TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(HDR.SUBMITTED_DATE AS TIMESTAMP)),'YYYYMMDD') AS SUBMITTED_LOCAL_DATE_ID
    ,HDR.SUBMITTED_DATE
    ,HDR.MSC_CRP_SITE_ID
    ,HDR.SS_AUDIT_ADJUSTMENT_ID    
    --Metadata Attributes
    ,HDR.CREATED_BY
    ,HDR.CREATED_ON AS CREATED_ON_UTC_DATETIME
    ,HDR.LAST_MODIFIED_BY
    ,HDR.LAST_MODIFIED_ON AS LAST_MODIFIED_ONASUTC_DATETIME
    ,GREATEST(COALESCE(HDR.LAST_MODIFIED_ON,to_timestamp('1900-01-01 00:00:00','YYYY-MM-DD HH24:MI:SS')),
              COALESCE(SCHEME.LAST_MODIFIED_ON,to_timestamp('1900-01-01 00:00:00','YYYY-MM-DD HH24:MI:SS')),
              COALESCE(PS.LAST_MODIFIED_ON,to_timestamp('1900-01-01 00:00:00','YYYY-MM-DD HH24:MI:SS')),
              COALESCE(P.LAST_MODIFIED_ON,to_timestamp('1900-01-01 00:00:00','YYYY-MM-DD HH24:MI:SS'))
             ) AS INCREMENTAL_UTC_DATETIME

FROM 
{{ source('CES_MSCM', 'CRP_CLAIM_HDR') }} AS HDR
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME ON HDR.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS ON HDR.CRP_ID = PS.SITE_NUMBER
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANTS') }} AS P ON PS.PARTICIPANT_ID = P.PARTICIPANT_ID
LEFT JOIN PERIOD WS ON HDR.PERIOD = WS.YEAR_WEEK_ISO
LEFT JOIN CLAIM_APPROVAL_HISTORY CA ON HDR.ID = CA.CLAIM_ID AND HDR.ENTRY_TYPE = CA.ENTRY_TYPE
{% if is_incremental() %}
WHERE
INCREMENTAL_UTC_DATETIME >= (SELECT dateadd(hours, {{var('general_delta_load_hours')}}, max(LATEST_UPDATE_UTC_TIME)) FROM  CES_REF.CES_DBT.DBT_INCREMENTAL_LOG_CONTROL WHERE TABLE_NAME = '{{model.name}}' )
{% endif %} 

)
SELECT * FROM CLAIM_HDR