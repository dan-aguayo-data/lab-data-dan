    WITH POS_ID_TXNS AS (    --NOP CLAIM NOT ADDED BECAUSE ALL POS_DEVICE IS NULL IN KAFKA TABLE
    /*SILVER TABLE CREATED TO BRING MORE ATTRIBUTES TO POS_DEVICE_STG, THIS WIL PROVIDE THE LATEST TRANSACTED DATE PER POS_DEVICE IN TWO CATEGORIES: NORMAL TRANSACTIONS AND BAG DROPS */    
    SELECT 
    CH.POS_DEVICE_ID
    , 'Transactional' as TXN_TYPE
    ,CH.TRANSACTED_ON AS LAST_TRANSACTION_ON
    FROM {{ source('CES_MSCM', 'CRP_REFUND_TXN_HDR') }} CH
    UNION ALL
    SELECT 
    CH.POS_DEVICE_ID
    , 'Transactional' as TXN_TYPE
    , CH.TRANSACTED_ON AS LAST_TRANSACTION_ON
    FROM {{ source('CES_MSCM', 'CONSUMER_REFUND_TXN_HDR') }} CH  
    UNION ALL 
    SELECT
    BL.CREATED_BY AS POS_DEVICE_ID
    , 'Bag Drop' as TXN_TYPE
    , BL.GENERATED_ON AS LAST_TRANSACTION_ON  --LAST_BAG_LABEL_ON
    FROM {{ source('CES_MSCM', 'CRP_BAG_DROP_LABEL') }} AS BL
    ), POS_DEVICELATEST_TXN AS (
    SELECT POS_DEVICE_ID, 
    TXN_TYPE, 
    MAX(LAST_TRANSACTION_ON) LAST_TRANSACTION_LOCAL_DATETIME 
    FROM POS_ID_TXNS
    GROUP BY POS_DEVICE_ID, TXN_TYPE
    ) 
     SELECT
    --Natural Key
     PD.ID AS ID
    --Attributes
    , PD.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
    , SCHEME.NAME AS SCHEME
    , PD.CRP_ID AS CRP_SITE_NUMBER
    , PD.IDCS_APPLICATION_ID
    , PS.SITE_NAME AS CRP_SITE_NAME
    , P.PARTICIPANT_NUMBER AS SUPPLIER_NUMBER
    , P.PARTICIPANT_NAME AS SUPPLIER_NAME
    , PD.NAME AS NAME
    , PD.TYPE AS TYPE
    , PD.STATUS AS STATUS
    , PD.SYNCED AS SYNCED
    , L.LAST_TRANSACTION_LOCAL_DATETIME AS LAST_BAG_LABEL_LOCAL_DATETIME
    , GREATEST(NVL(H.LAST_MODIFIED_ON, TO_TIMESTAMP('19000101','YYYYMMDD')) , NVL(L.LAST_TRANSACTION_LOCAL_DATETIME, TO_TIMESTAMP('19000101','YYYYMMDD')), NVL(C.LAST_TRANSACTION_LOCAL_DATETIME, TO_TIMESTAMP('19000101','YYYYMMDD'))) AS LAST_TXN_LOCAL_DATETIME
    , CASE WHEN L.LAST_TRANSACTION_LOCAL_DATETIME IS NOT NULL THEN L.TXN_TYPE WHEN C.LAST_TRANSACTION_LOCAL_DATETIME IS NOT NULL THEN C.TXN_TYPE ELSE 'Not Use' END AS POS_FLAG    
    --Metadata Attributes
    , PD.CREATED_BY AS CREATED_BY
    , CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(PD.CREATED_ON AS TIMESTAMP)) AS CREATED_ON_LOCAL_DATETIME
    , PD.CREATED_ON AS CREATED_ON_UTC_DATETIME
    , PD.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
    , PD.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC_DATETIME
    , GREATEST(COALESCE(PD.LAST_MODIFIED_ON,to_timestamp('1900-01-01 00:00:00','YYYY-MM-DD HH24:MI:SS')), 
               COALESCE(PS.LAST_MODIFIED_ON,to_timestamp('1900-01-01 00:00:00','YYYY-MM-DD HH24:MI:SS')), 
               COALESCE(P.LAST_MODIFIED_ON,to_timestamp('1900-01-01 00:00:00','YYYY-MM-DD HH24:MI:SS')), 
               COALESCE(SCHEME.LAST_MODIFIED_ON,to_timestamp('1900-01-01 00:00:00','YYYY-MM-DD HH24:MI:SS')),
               COALESCE(H.LAST_MODIFIED_ON,to_timestamp('1900-01-01 00:00:00','YYYY-MM-DD HH24:MI:SS'))
              ) AS INCREMENTAL_UTC_DATETIME

    FROM {{ source('CES_MSCM', 'POS_DEVICE') }} AS PD
    LEFT JOIN RAW_PROD.CES_MSCM_ORACLE.MDT_PARTICIPANT_SITES AS PS
    ON PD.CRP_ID = PS.SITE_NUMBER
    LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANTS') }} AS P
    ON PS.PARTICIPANT_ID = P.PARTICIPANT_ID
    INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
    ON PD.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
    LEFT JOIN {{ source('CES_MSCM', 'POS_DEVICE_HEARTBEAT') }} AS H
    ON PD.ID = H.DEVICE_ID
    LEFT JOIN POS_DEVICELATEST_TXN L 
    ON PD.ID = L.POS_DEVICE_ID AND L.TXN_TYPE = 'Bag Drop'
    LEFT JOIN POS_DEVICELATEST_TXN C
    ON PD.ID = C.POS_DEVICE_ID AND C.TXN_TYPE = 'Transactional'
    {% if is_incremental() %}
    WHERE INCREMENTAL_UTC_DATETIME >= (SELECT dateadd(hours, {{var('general_delta_load_hours')}}, max(LATEST_UPDATE_UTC_TIME)) FROM  CES_REF.CES_DBT.DBT_INCREMENTAL_LOG_CONTROL WHERE TABLE_NAME = '{{model.name}}' )
    {% endif %}