SELECT
    --Natural Key
     SCO.CONTRACT_ORGANIZATION_ID
    --Attrubutes
    ,SCO.MULTI_SCHEME_ID
    ,SCHEME.NAME AS SCHEME
    ,SCHEME.TIMEZONE    
    ,SCO.PARTICIPANT_ID
    ,P.PARTICIPANT_NUMBER
    ,P.PARTICIPANT_NAME
    ,SCO.CONTRACT_ORGANIZATION_NUMBER
    ,SCO.CRM_CONTRACT_ORG_ID
    ,SCO.CONTRACT_TYPE
    ,SCO.STATUS
    ,SCO.ESTABLISHED_DATE
    ,SCO.INACTIVE_DATE
    ,SCO.CURRENT_CONTRACT_EXPIRY_DATE
    ,SCO.CURRENT_CONTRACT_TERM
    ,SCO.CONTRACT_MANAGER
    ,SCO.ATTRIBUTE_CATEGORY
    ,SCO.ATTRIBUTE1
    ,SCO.ATTRIBUTE2
    ,SCO.ATTRIBUTE3
    ,SCO.ATTRIBUTE4
    ,SCO.ATTRIBUTE5
    ,SCO.ATTRIBUTE6
    ,SCO.ATTRIBUTE7
    ,SCO.ATTRIBUTE8
    ,SCO.ATTRIBUTE9
    ,SCO.ATTRIBUTE10
    ,SCO.ATTRIBUTE11
    ,SCO.ATTRIBUTE12
    ,SCO.ATTRIBUTE13
    ,SCO.ATTRIBUTE14
    ,SCO.ATTRIBUTE15
    --Metadata Attributes
    ,SCO.CREATED_BY
    ,SCO.CREATED_ON AS CREATED_ON_UTC_DATETIME
    ,SCO.LAST_MODIFIED_BY
    ,SCO.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC_DATETIME
    ,GREATEST(COALESCE(SCO.LAST_MODIFIED_ON,to_timestamp('1900-01-01 00:00:00','YYYY-MM-DD HH24:MI:SS')),
              COALESCE(P.LAST_MODIFIED_ON,to_timestamp('1900-01-01 00:00:00','YYYY-MM-DD HH24:MI:SS')),
              COALESCE(SCHEME.LAST_MODIFIED_ON,to_timestamp('1900-01-01 00:00:00','YYYY-MM-DD HH24:MI:SS'))
             ) AS INCREMENTAL_UTC_DATETIME
FROM
{{ source('CES_MSCM', 'MDT_SCHEME_CONTRACT_ORGS') }} AS SCO
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANTS') }} AS P
ON SCO.PARTICIPANT_ID = P.PARTICIPANT_ID
LEFT JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON SCO.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
{% if is_incremental() %}
WHERE INCREMENTAL_UTC_DATETIME >= (SELECT dateadd(hours, {{var('general_delta_load_hours')}}, max(LATEST_UPDATE_UTC_TIME)) FROM  CES_REF.CES_DBT.DBT_INCREMENTAL_LOG_CONTROL WHERE TABLE_NAME = '{{model.name}}' )
{% endif %}  