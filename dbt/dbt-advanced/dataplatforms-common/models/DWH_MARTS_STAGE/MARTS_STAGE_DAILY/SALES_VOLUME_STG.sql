{{
    config(
        materialized = 'incremental',
        incremental_strategy = 'merge',
        unique_key = 'ID',        
        pre_hook= "{{ incremental_pre() }}",
        post_hook= "{{ incremental_post() }}",
        enabled = run_flag_dev()
    )
}}

SELECT
    --Natural Key
     DTL.ID
    --Attributes
    ,DTL.MFG_SALES_VOLUME_HDR_ID
    ,DTL.MULTI_SCHEME_ID
    ,SCHEME.NAME AS SCHEME
    ,SCHEME.TIMEZONE
    ,DTL.MATERIAL_TYPE_ID
    ,MT.NAME AS MATERIAL_TYPE
    ,'Volume' AS VOLUME_HEADER
    ,HDR.MANUFACTURER_ID AS SITE_NUMBER
    ,HDR.PERIOD
    ,REPLACE(CONCAT(TO_CHAR(HDR.PERIOD),'01'), '-','') AS PERIOD_DATE_ID
    ,HDR.PERIOD_TYPE
    ,HDR.ENTRY_TYPE
    ,HDR.STATUS
    ,HDR.SUBMITTED_BY
    ,HDR.SUBMITTED_DATE AS SUBMITTED_UTC_DATETIME
    ,CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(HDR.SUBMITTED_DATE AS TIMESTAMP)) AS SUBMITTED_LOCAL_DATETIME
    ,TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(HDR.SUBMITTED_DATE AS TIMESTAMP)),'YYYYMMDD') AS SUBMITTED_LOCAL_DATE_ID
    ,HDR.MSC_MANUFACTURER_SITE_ID
    ,HDR.SS_AUDIT_ADJUSTMENT_ID
    ,HDR.ADJUSTMENT_REASON    
    ,DTL.UOM
    --Metrics
    ,DTL.VOLUME
    --Metadata Attributes
    ,HDR.CREATED_BY AS HDR_CREATED_BY
    ,HDR.CREATED_ON AS HDR_CREATED_ON_UTC_DATETIME
    ,HDR.LAST_MODIFIED_BY AS HDR_LAST_MODIFIED_BY
    ,HDR.LAST_MODIFIED_ON AS HDR_LAST_MODIFIED_ON_UTC_DATETIME    
    ,DTL.CREATED_BY
    ,DTL.CREATED_ON AS CREATED_ON_UTC_DATETIME
    ,DTL.LAST_MODIFIED_BY
    ,DTL.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC_DATETIME
    ,GREATEST(COALESCE(DTL.LAST_MODIFIED_ON,to_timestamp('1900-01-01 00:00:00','YYYY-MM-DD HH24:MI:SS')), 
              COALESCE(HDR.LAST_MODIFIED_ON,to_timestamp('1900-01-01 00:00:00','YYYY-MM-DD HH24:MI:SS')), 
              COALESCE(M.LAST_MODIFIED_ON,to_timestamp('1900-01-01 00:00:00','YYYY-MM-DD HH24:MI:SS')),
              COALESCE(MT.LAST_MODIFIED_ON,to_timestamp('1900-01-01 00:00:00','YYYY-MM-DD HH24:MI:SS')),
              COALESCE(SCHEME.LAST_MODIFIED_ON,to_timestamp('1900-01-01 00:00:00','YYYY-MM-DD HH24:MI:SS'))
             ) AS INCREMENTAL_UTC_DATETIME

FROM
{{ source('CES_MSCM', 'MFG_SALES_VOLUME_DTL') }} AS DTL
INNER JOIN {{ source('CES_MSCM', 'MFG_SALES_VOLUME_HDR') }} AS HDR ON DTL.MFG_SALES_VOLUME_HDR_ID = HDR.ID
LEFT JOIN {{ source('CES_MSCM', 'MANUFACTURER') }} AS M ON HDR.MANUFACTURER_ID = M.SCHEME_PARTICIPANT_ID
LEFT JOIN {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS MT ON DTL.MATERIAL_TYPE_ID = MT.ID
LEFT JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME ON DTL.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
{% if is_incremental() %}
WHERE INCREMENTAL_UTC_DATETIME >= (SELECT dateadd(hours, {{var('general_delta_load_hours')}}, max(LATEST_UPDATE_UTC_TIME)) FROM  CES_REF.CES_DBT.DBT_INCREMENTAL_LOG_CONTROL WHERE TABLE_NAME = '{{model.name}}' )
{% endif %}   