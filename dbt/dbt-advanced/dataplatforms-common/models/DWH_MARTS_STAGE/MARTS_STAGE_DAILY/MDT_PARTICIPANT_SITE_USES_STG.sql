    config(
        materialized = 'incremental',
        incremental_strategy = 'merge',
        unique_key = 'SITE_USE_ID',        
        pre_hook= "{{ incremental_pre() }}",
        post_hook= "{{ incremental_post() }}",
        enabled = run_flag_dev()
    )
