SELECT
    --Natural Key
    SU.SITE_USE_ID
    --Attributes
    ,SU.MULTI_SCHEME_ID
    ,SCHEME.NAME AS SCHEME
    ,SCHEME.TIMEZONE  AS TIMEZONE 
    ,SU.PARTICIPANT_SITE_ID
    ,PS.SITE_NUMBER
    ,PS.SITE_NAME AS SITE_NAME
    ,PS.POST_CODE AS SITE_POSTCODE
    ,P.PARTICIPANT_ID
    ,P.PARTICIPANT_NUMBER
    ,P.PARTICIPANT_NAME
    ,SU.SITE_USE_TYPE
    ,SU.COMMENTS
    ,SU.START_DATE_ACTIVE AS ACTIVE_START_DATE
    ,SU.END_DATE_ACTIVE AS ACTIVE_END_DATE
    ,SU.ERP_DATA_ACCESS_TYPE
    ,SU.ERP_DATA_ACCESS_VALUE
    ,SU.ERP_CUST_SITE_PURPOSE
    ,SU.ERP_SITE_PURCHASING
    ,SU.ERP_SITE_PAY
    ,SU.ERP_ADD_ORDERING
    ,SU.ERP_ADD_REMIT
    ,SU.ERP_ADD_RFQ_BID
    ,SU.ERP_CUST_ACCT_SITE_ID
    ,SU.ERP_VENDOR_SITE_ID
    ,SU.ERP_CUST_PROFILE_CLASS
    ,SU.SITE_PROFILE_CLASS
    ,SU.SOLD_TO_CUST_ACC_NUMBER
    ,SU.PO_PAY_ON_RECEIPT
    ,SU.INV_PAY_GROUP
    ,SU.INV_TERM_DATE_BASIS
    ,SU.INV_PAYMENT_TERMS
    --Metadata Attributes
    ,SU.CREATED_BY
    ,SU.CREATED_ON AS CREATED_ON_UTC_DATETIME
    ,SU.LAST_MODIFIED_BY
    ,SU.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC_DATETIME
    ,GREATEST(COALESCE(SU.LAST_MODIFIED_ON,to_timestamp('1900-01-01 00:00:00','YYYY-MM-DD HH24:MI:SS')),
              COALESCE(SCHEME.LAST_MODIFIED_ON,to_timestamp('1900-01-01 00:00:00','YYYY-MM-DD HH24:MI:SS')),
              COALESCE(PS.LAST_MODIFIED_ON,to_timestamp('1900-01-01 00:00:00','YYYY-MM-DD HH24:MI:SS')),
              COALESCE(P.LAST_MODIFIED_ON,to_timestamp('1900-01-01 00:00:00','YYYY-MM-DD HH24:MI:SS'))
             ) AS INCREMENTAL_UTC_DATETIME

FROM 
{{ source('CES_MSCM', 'MDT_PARTICIPANT_SITE_USES') }} AS SU
LEFT JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME ON SU.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS ON SU.PARTICIPANT_SITE_ID = PS.PARTICIPANT_SITE_ID
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANTS') }} AS P ON PS.PARTICIPANT_ID = P.PARTICIPANT_ID
{% if is_incremental() %}
WHERE INCREMENTAL_UTC_DATETIME >= (SELECT dateadd(hours, {{var('general_delta_load_hours')}}, max(LATEST_UPDATE_UTC_TIME)) FROM  CES_REF.CES_DBT.DBT_INCREMENTAL_LOG_CONTROL WHERE TABLE_NAME = '{{model.name}}' )
{% endif %}  