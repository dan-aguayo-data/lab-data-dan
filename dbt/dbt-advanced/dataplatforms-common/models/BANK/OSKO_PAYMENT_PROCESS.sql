WITH O AS (
SELECT
H.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, L.ID AS ID
, H.ID AS HEADER_ID
, H.ACCOUNT_NUMBER AS ACCOUNT_NUMBER
, H.FILE_DATE AS FILE_DATE
, CASE WHEN L.TYPE_CODE = 495 AND TO_CHAR(H.ACCOUNTING_DATE, 'YYYYMMDD') >= '20241214' THEN NVL(TRY_TO_DATE(SPLIT_PART(L.TEXT, ' ', -1), 'YYYYMMDD'), H.ACCOUNTING_DATE) ELSE H.ACCOUNTING_DATE END AS ACCOUNTING_DATE
, CASE WHEN L.TYPE_CODE = 495 AND TO_CHAR(H.ACCOUNTING_DATE, 'YYYYMMDD') >= '20241214' THEN TO_CHAR(NVL(TRY_TO_DATE(SPLIT_PART(L.TEXT, ' ', -1), 'YYYYYMMDD'), H.ACCOUNTING_DATE), 'YYYYMMDD') ELSE TO_CHAR(H.ACCOUNTING_DATE, 'YYYYMMDD') END AS ACCOUNTING_DATE_KEY
, H.FILE_NAME AS FILE_NAME
, H.CURRENCY_CODE AS CURRENCY
, L.FILE_ROW_NUMBER AS FILE_ROW_NUMBER
, L.TYPE_CODE AS TYPE_CODE
, L.AMOUNT AS AMOUNT
, ROUND(CASE WHEN ACCOUNTING_DATE_KEY <= 20241204 THEN FLOOR(L.AMOUNT, 1) ELSE L.AMOUNT END, 2) AS AMOUNT_COMPARE
, L.VALUE_DATE AS VALUE_DATE
, L.BANK_REF_NUM AS BANK_REF_NUM
, CASE WHEN L.TYPE_CODE = 495 AND L.CUSTOMER_REF_NUM IS NULL THEN SPLIT_PART(L.TEXT, ' ', -1) ELSE L.CUSTOMER_REF_NUM END AS PAY_REF_NUMBER
, ROW_NUMBER() OVER (PARTITION BY PAY_REF_NUMBER, CASE WHEN L.TYPE_CODE = 266 THEN 195 ELSE L.TYPE_CODE END ORDER BY H.FILE_DATE, L.BANK_REF_NUM, L.FILE_ROW_NUMBER) AS SN
, ROW_NUMBER() OVER (PARTITION BY PAY_REF_NUMBER, CASE WHEN L.TYPE_CODE = 266 THEN 195 ELSE L.TYPE_CODE END ORDER BY H.FILE_DATE DESC, L.BANK_REF_NUM DESC, L.FILE_ROW_NUMBER DESC) AS SN_DESC
, L.TEXT AS NARRATIVE
FROM
{{ source('RAW_CES_FINANCE', 'ANZ_BTR_HEADER') }} AS H
INNER JOIN {{ source('RAW_CES_FINANCE', 'ANZ_BTR_LINES') }} AS L
ON H.ID = L.HEADER_ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON H.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
WHERE L.TYPE_CODE IN (495, 266)
OR (L.TYPE_CODE = 195 AND NVL(LEFT(L.BANK_REF_NUM, 1), 'A') IN ('1', '2'))
),
 
SD AS (
SELECT
SD.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, SD.KAFKA_ID AS ID
, NVL(B.ACCOUNTING_DATE, TO_DATE(SPLIT_PART(SD.SUBJECT, '_', -2), 'YYYYMMDD')) AS ACCOUNTING_DATE
, NVL(TO_CHAR(B.ACCOUNTING_DATE, 'YYYYMMDD'), SPLIT_PART(SD.SUBJECT, '_', -2)) AS ACCOUNTING_DATE_KEY
, SD.CURRENCY AS CURRENCY
, SD.AMOUNT AS TOTAL_AMOUNT
, SD.AMOUNT AS AMOUNT
, SD.BATCH_ID AS BATCH_ID
, SD.PAY_REF_NUMBER AS PAY_REF_NUMBER
, SD.SUBJECT AS STEP_DOWN_FILE_NAME
, SD.ROW_NUMBER AS STEP_DOWN_FILE_ROW_NUMBER
, TO_DATE(SPLIT_PART(SD.SUBJECT, '_', -2), 'YYYYMMDD') AS STEP_DOWN_FILE_DATE
, SPLIT_PART(SD.SUBJECT, '_', -2) AS STEP_DOWN_FILE_DATE_KEY
, CASE WHEN SPLIT_PART(SD.SUBJECT, '_', -2) <= '20241204' THEN CASE WHEN (HOUR(CONVERT_TIMEZONE('UTC', 'Australia/Sydney', SD.KAFKA_DATETIME)) = '00' OR HOUR(CONVERT_TIMEZONE('UTC', 'Australia/Sydney', SD.KAFKA_DATETIME)) BETWEEN '12' AND '23') AND LEFT(SPLIT_PART(SD.SUBJECT, '_', -1), 2) BETWEEN '01' AND '11' THEN TO_CHAR(LEFT(SPLIT_PART(SD.SUBJECT, '_', -1), 6) + 120000, 'FM000000') WHEN HOUR(CONVERT_TIMEZONE('UTC', 'Australia/Sydney', SD.KAFKA_DATETIME)) BETWEEN '01' AND '11' AND LEFT(SPLIT_PART(SD.SUBJECT, '_', -1), 2) = '12' THEN TO_CHAR(LEFT(SPLIT_PART(SD.SUBJECT, '_', -1), 6) - 120000, 'FM000000') ELSE LEFT(SPLIT_PART(SD.SUBJECT, '_', -1), 6) END ELSE LEFT(SPLIT_PART(SD.SUBJECT, '_', -1), 6) END AS STEP_DOWN_FILE_TIME_KEY
, P.PROCESSING_DATE AS PROCESSING_DATE
FROM
{{ source('CES_MSCM_KAFKA', 'PYMT_STEP_DOWN') }} AS SD
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON SD.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
INNER JOIN (
    SELECT
    H.ACCOUNTING_DATE
    , L.TYPE_CODE
    , L.BANK_REF_NUM AS BATCH_ID
    FROM
    {{ source('RAW_CES_FINANCE', 'ANZ_BTR_HEADER') }} AS H
    INNER JOIN {{ source('RAW_CES_FINANCE', 'ANZ_BTR_LINES') }} AS L
    ON H.ID = L.HEADER_ID
    WHERE L.TYPE_CODE = 467
    AND L.BANK_REF_NUM = L.CUSTOMER_REF_NUM
    AND NOT(L.CUSTOMER_REF_NUM LIKE ANY ('COEX', 'FAD%'))
) B
ON SD.BATCH_ID = B.BATCH_ID
LEFT JOIN (
    SELECT DISTINCT
    F.MULTI_SCHEME_ID
    , F.SCHEME
    , CAST(F.PAY_REF_NUMBER AS STRING) AS PAY_REF_NUMBER
    , F.POS_TXN_NUM
    , F.PROCESSING_DATE
    , F.PROCESSING_DATE_KEY
    FROM {{ ref('FIN_RTP') }} AS F
    WHERE F.PAYMENT_STATUS = 'PAID'
    AND F.PAYMENT_METHOD = 'BANK'
    AND F.PAID_DATE_KEY >= TO_CHAR(ADD_MONTHS(SYSDATE(), -6), 'YYYYMMDD')
) P
ON SD.PAY_REF_NUMBER = P.PAY_REF_NUMBER
)
 
SELECT
OP.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, OP.SCHEME AS SCHEME
, OP.ID AS ID
, OP.HEADER_ID AS HEADER_ID_P
, OP.ACCOUNT_NUMBER AS ACCOUNT_NUMBER_P
, OP.FILE_DATE AS FILE_DATE_P
, OP.ACCOUNTING_DATE AS ACCOUNTING_DATE_P
, OP.ACCOUNTING_DATE_KEY AS ACCOUNTING_DATE_KEY_P
, OP.FILE_NAME AS FILE_NAME_P
, OP.CURRENCY AS CURRENCY_P
, OP.FILE_ROW_NUMBER AS FILE_ROW_NUMBER_P
, OP.TYPE_CODE AS TYPE_CODE_P
, OP.AMOUNT AS AMOUNT_P
, OP.VALUE_DATE AS VALUE_DATE_P
, OP.BANK_REF_NUM AS BANK_REF_NUM_P
, OP.PAY_REF_NUMBER AS PAY_REF_NUMBER_P
, OP.SN AS SN_P
, OP.NARRATIVE AS NARRATIVE_P
, OD.HEADER_ID AS HEADER_ID_D
, OD.ACCOUNT_NUMBER AS ACCOUNT_NUMBER_D
, OD.FILE_DATE AS FILE_DATE_D
, OD.ACCOUNTING_DATE AS ACCOUNTING_DATE_D
, OD.ACCOUNTING_DATE_KEY AS ACCOUNTING_DATE_KEY_D
, OD.FILE_NAME AS FILE_NAME_D
, OD.CURRENCY AS CURRENCY_D
, OD.FILE_ROW_NUMBER AS FILE_ROW_NUMBER_D
, OD.TYPE_CODE AS TYPE_CODE_D
, OD.AMOUNT AS AMOUNT_D
, OD.VALUE_DATE AS VALUE_DATE_D
, OD.BANK_REF_NUM AS BANK_REF_NUM_D
, OD.PAY_REF_NUMBER AS PAY_REF_NUMBER_D
, OD.SN AS SN_D
, OD.NARRATIVE AS NARRATIVE_D
, CASE WHEN P.PAY_REF_NUMBER IS NOT NULL AND OD.SN_DESC = 1 THEN 'Paypal Payment' WHEN PE.PAY_REF_NUMBER IS NOT NULL AND OD.SN_DESC = 1 THEN 'Payment Error' WHEN PE2424.NEW_PAY_REF_NUMBER IS NOT NULL AND OD.SN_DESC = 1 THEN 'Change to New Pay Ref Number' WHEN OD.TYPE_CODE = 195 THEN 'Immediately Dishonoured' ELSE 'OSKO Payment' END AS PAYMENT_STATUS
, CASE WHEN SUM(CASE WHEN PAYMENT_STATUS = 'Payment Error' THEN 1 ELSE 0 END) OVER (PARTITION BY OP.PAY_REF_NUMBER) = 1 THEN 'Payment Error' WHEN SUM(CASE WHEN PAYMENT_STATUS = 'OSKO Payment' THEN 1 ELSE 0 END) OVER (PARTITION BY OP.PAY_REF_NUMBER) = 1 THEN 'Paid by OSKO' WHEN SUM(CASE WHEN PAYMENT_STATUS = 'Paypal Payment' THEN 1 ELSE 0 END) OVER (PARTITION BY OP.PAY_REF_NUMBER) = 1 THEN 'Paid by Paypal' WHEN SUM(CASE WHEN PAYMENT_STATUS = 'Change to New Pay Ref Number' THEN 1 ELSE 0 END) OVER (PARTITION BY OP.PAY_REF_NUMBER) = 1 THEN 'Paid by New Pay Ref Number' WHEN SUM(CASE WHEN PAYMENT_STATUS IN ('OSKO Payment', 'Paypal Payment') THEN 1 ELSE 0 END) OVER (PARTITION BY OP.PAY_REF_NUMBER) > 1 THEN 'Multi Paid' ELSE 'Paid by Step Down' END AS PAYMENT_METHOD
, CASE WHEN OD.SN_DESC = 1 THEN 1 ELSE 0 END AS LAST_DISHONOURED_FLAG
, PE2424.NEW_PAY_REF_NUMBER AS NEW_PAY_REF_NUMBER
, CASE WHEN PAYMENT_METHOD = 'Paid by Step Down' AND LAST_DISHONOURED_FLAG = 1 THEN SD.ID ELSE NULL END AS ID_SD
, CASE WHEN PAYMENT_METHOD = 'Paid by Step Down' AND LAST_DISHONOURED_FLAG = 1 THEN SD.ACCOUNTING_DATE ELSE NULL END AS ACCOUNTING_DATE_SD
, CASE WHEN PAYMENT_METHOD = 'Paid by Step Down' AND LAST_DISHONOURED_FLAG = 1 THEN SD.ACCOUNTING_DATE_KEY ELSE NULL END AS ACCOUNTING_DATE_KEY_SD
, CASE WHEN PAYMENT_METHOD = 'Paid by Step Down' AND LAST_DISHONOURED_FLAG = 1 THEN SD.CURRENCY ELSE NULL END AS CURRENCY_SD
, CASE WHEN PAYMENT_METHOD = 'Paid by Step Down' AND LAST_DISHONOURED_FLAG = 1 THEN SD.AMOUNT ELSE NULL END AS AMOUNT_SD
, CASE WHEN PAYMENT_METHOD = 'Paid by Step Down' AND LAST_DISHONOURED_FLAG = 1 THEN SD.BATCH_ID ELSE NULL END AS BATCH_ID_SD
, CASE WHEN PAYMENT_METHOD = 'Paid by Step Down' AND LAST_DISHONOURED_FLAG = 1 THEN SD.PAY_REF_NUMBER ELSE NULL END AS PAY_REF_NUMBER_SD
, CASE WHEN PAYMENT_METHOD = 'Paid by Step Down' AND LAST_DISHONOURED_FLAG = 1 THEN SD.STEP_DOWN_FILE_NAME ELSE NULL END AS STEP_DOWN_FILE_NAME_SD
, CASE WHEN PAYMENT_METHOD = 'Paid by Step Down' AND LAST_DISHONOURED_FLAG = 1 THEN SD.STEP_DOWN_FILE_ROW_NUMBER ELSE NULL END AS STEP_DOWN_FILE_ROW_NUMBER_SD
, CASE WHEN PAYMENT_METHOD = 'Paid by Step Down' AND LAST_DISHONOURED_FLAG = 1 THEN SD.STEP_DOWN_FILE_DATE ELSE NULL END AS STEP_DOWN_FILE_DATE_SD
, CASE WHEN PAYMENT_METHOD = 'Paid by Step Down' AND LAST_DISHONOURED_FLAG = 1 THEN SD.STEP_DOWN_FILE_DATE_KEY ELSE NULL END AS STEP_DOWN_FILE_DATE_KEY_SD
, CASE WHEN PAYMENT_METHOD = 'Paid by Step Down' AND LAST_DISHONOURED_FLAG = 1 THEN SD.STEP_DOWN_FILE_TIME_KEY ELSE NULL END AS STEP_DOWN_FILE_TIME_KEY_SD
, CASE WHEN PAYMENT_METHOD = 'Paid by Step Down' AND LAST_DISHONOURED_FLAG = 1 THEN SD.PROCESSING_DATE ELSE NULL END AS PROCESSING_DATE_SD
, CASE WHEN PAYMENT_STATUS IN ('OSKO Payment', 'Paypal Payment', 'Payment Error', 'Change to New Pay Ref Number') THEN 'Not Applicable' ELSE CASE WHEN PAYMENT_METHOD <> 'Paid by Step Down' OR LAST_DISHONOURED_FLAG = 0 THEN CASE WHEN OP.AMOUNT_COMPARE = OD.AMOUNT_COMPARE THEN 'Reconciled' ELSE 'Not Reconciled' END WHEN SD.PAY_REF_NUMBER IS NULL THEN 'Missing Step Down Payment' WHEN OP.AMOUNT_COMPARE = OD.AMOUNT_COMPARE AND OP.AMOUNT_COMPARE = SD.AMOUNT THEN 'Reconciled' WHEN OP.AMOUNT_COMPARE = OD.AMOUNT_COMPARE AND OP.AMOUNT_COMPARE <> SD.AMOUNT THEN 'Step Down Amount is not Reconciled' WHEN OP.AMOUNT_COMPARE <> OD.AMOUNT_COMPARE AND OP.AMOUNT_COMPARE = SD.AMOUNT THEN 'Dishonoured Amount is not Reconciled' WHEN OP.AMOUNT_COMPARE <> OD.AMOUNT_COMPARE AND OD.AMOUNT_COMPARE = SD.AMOUNT THEN 'Dishonoured Amount and Step Down Amount are equal, but not Same as the Original Amount' WHEN OP.AMOUNT_COMPARE <> OD.AMOUNT_COMPARE AND OP.AMOUNT_COMPARE <> SD.AMOUNT AND OD.AMOUNT_COMPARE <> SD.AMOUNT THEN 'Not Reconciled' END END AS RECONCILIATION_FLAG
, SYSDATE() AS INSERT_DATE_UTC
FROM
(SELECT * FROM O WHERE TYPE_CODE = 495) OP
LEFT JOIN (SELECT * FROM O WHERE TYPE_CODE IN (195, 266)) OD
ON OP.PAY_REF_NUMBER = OD.PAY_REF_NUMBER
AND OP.SN = OD.SN
LEFT JOIN SD
ON OD.PAY_REF_NUMBER = SD.PAY_REF_NUMBER
AND OD.TYPE_CODE = 195
LEFT JOIN (
    SELECT DISTINCT
    CAST(F.PAY_REF_NUMBER AS STRING) AS PAY_REF_NUMBER
    FROM {{ ref('FIN_RTP') }} AS F
    WHERE F.PAYMENT_STATUS = 'PAID'
    AND F.PAYMENT_METHOD = 'PAYPAL'
    AND PYMT_AMOUNT_RECENT_FLAG = 1
    AND F.PAID_DATE_KEY >= 20240601
) P
ON OP.PAY_REF_NUMBER = P.PAY_REF_NUMBER
LEFT JOIN (
    SELECT DISTINCT
    CAST(F.PAY_REF_NUMBER AS STRING) AS PAY_REF_NUMBER
    FROM {{ ref('FIN_RTP') }} AS F
    WHERE F.PAYMENT_STATUS = 'PAYMENT ERROR'
    AND PYMT_AMOUNT_RECENT_FLAG = 1
    AND F.PAID_DATE_KEY >= 20240601
) PE
ON OP.PAY_REF_NUMBER = PE.PAY_REF_NUMBER
LEFT JOIN (
    SELECT
    R.MULTI_SCHEME_ID
    , R.ERROR_MESSAGE
    , R.NEW_PAY_REF_NUMBER
    , RR.PREV_PAY_REF_NUMBER
    FROM {{ source('CES_MSCM_KAFKA', 'PYMT_REATTEMPT') }} AS R
    INNER JOIN {{ source('CES_MSCM_KAFKA', 'PYMT_REATTEMPT_RELATIONSHIP') }} AS RR
    ON R.KAFKA_ID = RR.KAFKA_ID
    WHERE R.ERROR_MESSAGE LIKE '2424%'
    AND RR.PREV_PAY_REF_NUMBER IS NOT NULL
    AND R.NEW_PAY_REF_NUMBER NOT IN (
        SELECT
        RR.PREV_PAY_REF_NUMBER
        FROM {{ source('CES_MSCM_KAFKA', 'PYMT_REATTEMPT') }} AS R
        INNER JOIN {{ source('CES_MSCM_KAFKA', 'PYMT_REATTEMPT_RELATIONSHIP') }} AS RR
        ON R.KAFKA_ID = RR.KAFKA_ID
        WHERE R.ERROR_MESSAGE LIKE '2424%'
        AND RR.PREV_PAY_REF_NUMBER IS NOT NULL
    )
) PE2424
ON OD.PAY_REF_NUMBER = PE2424.PREV_PAY_REF_NUMBER