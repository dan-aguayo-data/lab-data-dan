A.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, A.SCHEME AS SCHEME
, A.ID AS ID
, A.COMPANY_CODE AS COMPANY_CODE
, '00' AS MATERIAL_TYPE_CODE
, '0000' AS COST_CENTRE_CODE
, '20005' AS ACCOUNT_CODE
, '0000' AS INTERCOMPANY_CODE
, '00000' AS SPARE_CODE
