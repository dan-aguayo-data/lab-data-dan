, A.TRANSACTION_ID AS TRANSACTION_ID
, A.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID
, A.MATERIAL_TYPE AS MATERIAL_TYPE
, A.CURRENCY AS CURRENCY
, A.AMOUNT AS AMOUNT_DR
, 0 AS AMOUNT_CR
, A.PAY_REF_NUMBER AS PAY_REF_NUMBER
, A.PAID_DATE AS PAID_DATE
, A.PAID_DATE_KEY AS PAID_DATE_KEY
, A.PAYMENT_METHOD AS PAYMENT_METHOD
, A.INVOICE_NUMBER_AND_STATUS AS INVOICE_NUMBER_AND_STATUS
, A.PYMT_AMOUNT_RECENT_FLAG AS PYMT_AMOUNT_RECENT_FLAG
, 'PAYMENT' AS INVOICE_PAYMENT_FLAG
, 'BANK 1 PAYMENT' AS SCENARIO
, A.KAFKA_DATE AS KAFKA_DATE
, A.KAFKA_TIME_KEY AS KAFKA_TIME_KEY
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ ref('ACCOUNTING_WITH_COMPANY_CODE') }} AS A
WHERE A.PAYMENT_METHOD = 'BANK'
 
