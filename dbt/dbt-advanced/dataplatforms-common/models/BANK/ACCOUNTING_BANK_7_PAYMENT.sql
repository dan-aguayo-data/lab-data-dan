SELECT
B.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, B.SCHEME AS SCHEME
, B.ID AS ID
, B.ACCOUNT_NUMBER AS ACCOUNT_NUMBER
, B.ACCOUNTING_DATE AS ACCOUNTING_DATE
, B.ACCOUNTING_DATE_KEY AS ACCOUNTING_DATE_KEY
, DECODE(B.MULTI_SCHEME_ID, 10000, '9501', 10001, '9601', 100020001, '9701') AS COMPANY_CODE
, '00' AS MATERIAL_TYPE_CODE
, '0000' AS COST_CENTRE_CODE
, DECODE(B.MULTI_SCHEME_ID, 10000, '10025', 10001, '10025', 100020001, '10020') AS ACCOUNT_CODE
, '0000' AS INTERCOMPANY_CODE
, '00000' AS SPARE_CODE
, DECODE(B.MULTI_SCHEME_ID, 10000, '9501', 10001, '9601', 100020001, '9701') || '-' || '00-0000' || '-' || DECODE(B.MULTI_SCHEME_ID, 10000, '10025', 10001, '10025', 100020001, '10020') || '-' || '0000-00000' AS DISTRIBUTION_COMBINATION
, B.CURRENCY AS CURRENCY
, B.AMOUNT AS AMOUNT_DR
, 0 AS AMOUNT_CR
, B.NARRATIVE AS NARRATIVE
, M.PAY_REF_NUMBER AS PAY_REF_NUMBER
, M.TRANSACTION_ID AS TRANSACTION_ID
, A.INVOICE_NUMBER_AND_STATUS AS INVOICE_NUMBER_AND_STATUS
, 'BANK' AS PAYMENT_METHOD
, 'PAYMENT' AS INVOICE_PAYMENT_FLAG
, 'BANK 7 PAYMENT' AS SCENARIO
, A.KAFKA_DATE AS KAFKA_DATE
, A.KAFKA_TIME_KEY AS KAFKA_TIME_KEY
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ ref('BTR') }} AS B
INNER JOIN {{ source('CES_FINANCE', 'BTR_PAY_REF_NUMBER_MAPPING') }} AS M
ON TO_CHAR(B.FILE_DATE, 'YYYYMMDD') = M.FILE_DATE_YYYYMMDD
AND B.ACCOUNT_NUMBER = M.ACCOUNT_NUMBER
AND B.FILE_ROW_NUMBER = M.FILE_ROW_NUMBER
LEFT JOIN (
    SELECT
    AWCC.PAY_REF_NUMBER
    , AWCC.INVOICE_NUMBER_AND_STATUS
    , AWCC.KAFKA_DATE
    , AWCC.KAFKA_TIME_KEY
    FROM {{ ref('ACCOUNTING_WITH_COMPANY_CODE') }} AS AWCC
    QUALIFY ROW_NUMBER() OVER (PARTITION BY AWCC.PAY_REF_NUMBER ORDER BY AWCC.PAID_DATE_KEY DESC) = 1
) A
ON M.PAY_REF_NUMBER = A.PAY_REF_NUMBER
WHERE (
    B.TYPE_CODE IN (195)
    OR (B.TYPE_CODE IN (169) AND B.MULTI_SCHEME_ID IN (10000, 10001))
    OR (B.TYPE_CODE IN (169) AND B.MULTI_SCHEME_ID IN (100020001) AND NOT(B.NARRATIVE LIKE ANY ('%WESTPAC%', '%WORKING CAPITAL%')))
)
AND NVL(LEFT(B.BANK_REF_NUM, 1), 'A') NOT IN ('1', '2')
AND M.TYPE = 'FULL'
 
UNION ALL
 
