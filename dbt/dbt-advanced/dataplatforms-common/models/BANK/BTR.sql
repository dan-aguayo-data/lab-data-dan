SELECT
H.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, L.ID AS ID
, H.ID AS HEADER_ID
, H.ACCOUNT_NUMBER AS ACCOUNT_NUMBER
, H.FILE_DATE AS FILE_DATE
, CASE WHEN L.TYPE_CODE = 495 AND TO_CHAR(H.ACCOUNTING_DATE, 'YYYYMMDD') >= '20241214' THEN NVL(TRY_TO_DATE(SPLIT_PART(L.TEXT, ' ', -1), 'YYYYMMDD'), H.ACCOUNTING_DATE) ELSE H.ACCOUNTING_DATE END AS ACCOUNTING_DATE
, CASE WHEN L.TYPE_CODE = 495 AND TO_CHAR(H.ACCOUNTING_DATE, 'YYYYMMDD') >= '20241214' THEN TO_CHAR(NVL(TRY_TO_DATE(SPLIT_PART(L.TEXT, ' ', -1), 'YYYYYMMDD'), H.ACCOUNTING_DATE), 'YYYYMMDD') ELSE TO_CHAR(H.ACCOUNTING_DATE, 'YYYYMMDD') END AS ACCOUNTING_DATE_KEY
, H.FILE_NAME AS FILE_NAME
, H.CURRENCY_CODE AS CURRENCY
, H.AMOUNT AS TOTAL_AMOUNT
, L.FILE_ROW_NUMBER AS FILE_ROW_NUMBER
, L.TYPE_CODE AS TYPE_CODE
, L.AMOUNT AS AMOUNT
, L.VALUE_DATE AS VALUE_DATE
, CASE WHEN L.TYPE_CODE = 467 AND L.BANK_REF_NUM = L.CUSTOMER_REF_NUM AND NOT(L.BANK_REF_NUM LIKE ANY ('COEX', 'FAD%')) THEN L.BANK_REF_NUM ELSE NULL END AS BATCH_ID
, L.BANK_REF_NUM AS BANK_REF_NUM
, CASE WHEN L.TYPE_CODE = 495 AND L.CUSTOMER_REF_NUM IS NULL THEN SPLIT_PART(L.TEXT, ' ', -1) ELSE L.CUSTOMER_REF_NUM END AS PAY_REF_NUMBER
, L.TEXT AS NARRATIVE
, CASE WHEN L.TYPE_CODE = 252 THEN SPLIT_PART(SUBSTR(L.TEXT, POSITION('533816', L.TEXT, LENGTH(REGEXP_SUBSTR(L.TEXT, '\\w\* XXX-XXX XXXXX')) + 1) + 7), ' ', 2) ELSE NULL END AS ORIGINAL_PAY_REF_NUMBER
, SD.SUBJECT AS STEP_DOWN_FILE_NAME
, SD.ROW_NUMBER AS STEP_DOWN_FILE_ROW_NUMBER
, TO_DATE(SPLIT_PART(SD.SUBJECT, '_', -2), 'YYYYMMDD') AS STEP_DOWN_FILE_DATE
, SPLIT_PART(SD.SUBJECT, '_', -2) AS STEP_DOWN_FILE_DATE_KEY
, CASE WHEN SPLIT_PART(SD.SUBJECT, '_', -2) <= '20241204' THEN CASE WHEN (HOUR(CONVERT_TIMEZONE('UTC', 'Australia/Sydney', SD.KAFKA_DATETIME)) = '00' OR HOUR(CONVERT_TIMEZONE('UTC', 'Australia/Sydney', SD.KAFKA_DATETIME)) BETWEEN '12' AND '23') AND LEFT(SPLIT_PART(SD.SUBJECT, '_', -1), 2) BETWEEN '01' AND '11' THEN TO_CHAR(LEFT(SPLIT_PART(SD.SUBJECT, '_', -1), 6) + 120000, 'FM000000') WHEN HOUR(CONVERT_TIMEZONE('UTC', 'Australia/Sydney', SD.KAFKA_DATETIME)) BETWEEN '01' AND '11' AND LEFT(SPLIT_PART(SD.SUBJECT, '_', -1), 2) = '12' THEN TO_CHAR(LEFT(SPLIT_PART(SD.SUBJECT, '_', -1), 6) - 120000, 'FM000000') ELSE LEFT(SPLIT_PART(SD.SUBJECT, '_', -1), 6) END ELSE LEFT(SPLIT_PART(SD.SUBJECT, '_', -1), 6) END AS STEP_DOWN_FILE_TIME_KEY
, NULL AS PROCESSING_DATE
, NULL AS BANK_REC_DATE
, CASE WHEN L.TYPE_CODE IN (467, 495, 252, 266, 195, 698, 699, 169, 354) THEN 0 WHEN L.TYPE_CODE IN (275, 654) AND H.MULTI_SCHEME_ID IN (10000, 10001) THEN 0 WHEN L.TYPE_CODE IN (469) AND H.MULTI_SCHEME_ID IN (100020001) THEN 0 ELSE 1 END AS EXCEPTION_FLAG
, CASE WHEN L.TYPE_CODE IN (495, 266) THEN 1 ELSE 0 END AS OSKO_FLAG
, CASE WHEN L.TYPE_CODE = 467 AND L.BANK_REF_NUM = L.CUSTOMER_REF_NUM AND NOT(L.CUSTOMER_REF_NUM LIKE ANY ('COEX', 'FAD%')) THEN 1 ELSE 0 END AS BULK_FLAG
, 0 AS STEP_DOWN_FLAG
, CASE WHEN L.TYPE_CODE IN (495, 266) THEN CASE WHEN D_SD.WORKDAY_FLAG_NSW = 1 AND LEFT(CASE WHEN SPLIT_PART(SD.SUBJECT, '_', -2) <= '20241204' THEN CASE WHEN (HOUR(CONVERT_TIMEZONE('UTC', 'Australia/Sydney', SD.KAFKA_DATETIME)) = '00' OR HOUR(CONVERT_TIMEZONE('UTC', 'Australia/Sydney', SD.KAFKA_DATETIME)) BETWEEN '12' AND '23') AND LEFT(SPLIT_PART(SD.SUBJECT, '_', -1), 2) BETWEEN '01' AND '11' THEN TO_CHAR(LEFT(SPLIT_PART(SD.SUBJECT, '_', -1), 6) + 120000, 'FM000000') WHEN HOUR(CONVERT_TIMEZONE('UTC', 'Australia/Sydney', SD.KAFKA_DATETIME)) BETWEEN '01' AND '11' AND LEFT(SPLIT_PART(SD.SUBJECT, '_', -1), 2) = '12' THEN TO_CHAR(LEFT(SPLIT_PART(SD.SUBJECT, '_', -1), 6) - 120000, 'FM000000') ELSE LEFT(SPLIT_PART(SD.SUBJECT, '_', -1), 6) END ELSE LEFT(SPLIT_PART(SD.SUBJECT, '_', -1), 6) END, 4) BETWEEN '0900' AND '1759' THEN 'OSKO paid at business hours' ELSE 'OSKO paid not at business hours' END ELSE NULL END AS OSKO_PAID_AT_BUSINESS_HOUR_FLAG
, 'Bank' AS EXISTING_IN_BTR_FLAG
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('RAW_CES_FINANCE', 'ANZ_BTR_HEADER') }} AS H
INNER JOIN {{ source('RAW_CES_FINANCE', 'ANZ_BTR_LINES') }} AS L
ON H.ID = L.HEADER_ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON H.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM_KAFKA', 'PYMT_STEP_DOWN') }} AS SD
ON NVL(L.CUSTOMER_REF_NUM, SPLIT_PART(L.TEXT, ' ', -1)) = SD.PAY_REF_NUMBER
LEFT JOIN {{ ref('REF_DATE') }} AS D_SD
ON SPLIT_PART(SD.SUBJECT, '_', -2) = D_SD.KEY
LEFT JOIN (
    SELECT
    NVL(L.CUSTOMER_REF_NUM, SPLIT_PART(L.TEXT, ' ', -1)) AS PAY_REF_NUMBER
    , SUM(CASE WHEN L.TYPE_CODE = 495 THEN 1 ELSE 0 END) AS COUNT_495
    , SUM(CASE WHEN L.TYPE_CODE = 195 THEN 1 ELSE 0 END) AS COUNT_195
    FROM {{ source('RAW_CES_FINANCE', 'ANZ_BTR_LINES') }} AS L
    WHERE L.TYPE_CODE IN (495, 195)
    GROUP BY ALL
) C
ON CASE WHEN L.TYPE_CODE = 495 AND L.CUSTOMER_REF_NUM IS NULL THEN SPLIT_PART(L.TEXT, ' ', -1) ELSE L.CUSTOMER_REF_NUM END = C.PAY_REF_NUMBER
LEFT JOIN {{ ref('OSKO_PAYMENT_PROCESS') }} AS OPP
ON H.FILE_DATE = OPP.FILE_DATE_P
AND L.FILE_ROW_NUMBER = OPP.FILE_ROW_NUMBER_P
AND L.CUSTOMER_REF_NUM = OPP.PAY_REF_NUMBER_P
WHERE CASE WHEN L.TYPE_CODE = 495 AND C.COUNT_495 = COUNT_195 + 1 AND COUNT_195 > 0
THEN 1
WHEN L.TYPE_CODE = 495 AND NVL(L.CUSTOMER_REF_NUM, SPLIT_PART(L.TEXT, ' ', -1)) || L.FILE_DATE IN (
    SELECT DISTINCT
    L.CUSTOMER_REF_NUM || L.FILE_DATE AS PAY_REF_NUMBER_FILE_DATE
    FROM {{ source('RAW_CES_FINANCE', 'ANZ_BTR_LINES') }} AS L
    WHERE L.TYPE_CODE IN (195)
    AND L.CUSTOMER_REF_NUM IS NOT NULL
)
THEN 0 ELSE 1 END = 1
AND CASE WHEN OPP.PAYMENT_STATUS IN ('Immediately Dishonoured') THEN 0 ELSE 1 END = 1
 
UNION ALL
 
SELECT
SD.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, SD.KAFKA_ID AS ID
, NULL AS HEADER_ID
, NULL AS ACCOUNT_NUMBER
, BTR.FILE_DATE AS FILE_DATE
, NVL(B.ACCOUNTING_DATE, TO_DATE(SPLIT_PART(SD.SUBJECT, '_', -2), 'YYYYMMDD')) AS ACCOUNTING_DATE
, NVL(TO_CHAR(B.ACCOUNTING_DATE, 'YYYYMMDD'), SPLIT_PART(SD.SUBJECT, '_', -2)) AS ACCOUNTING_DATE_KEY
, BTR.FILE_NAME AS FILE_NAME
, SD.CURRENCY AS CURRENCY
, SD.AMOUNT AS TOTAL_AMOUNT
, BTR.FILE_ROW_NUMBER AS FILE_ROW_NUMBER
, NVL(B.TYPE_CODE, '000') AS TYPE_CODE
, SD.AMOUNT AS AMOUNT
, NULL AS VALUE_DATE
, SD.BATCH_ID AS BATCH_ID
, SD.BATCH_ID AS BANK_REF_NUM
, SD.PAY_REF_NUMBER AS PAY_REF_NUMBER
, NULL AS NARRATIVE
, NULL AS ORIGINAL_PAY_REF_NUMBER
, SD.SUBJECT AS STEP_DOWN_FILE_NAME
, SD.ROW_NUMBER AS STEP_DOWN_FILE_ROW_NUMBER
, TO_DATE(SPLIT_PART(SD.SUBJECT, '_', -2), 'YYYYMMDD') AS STEP_DOWN_FILE_DATE
, SPLIT_PART(SD.SUBJECT, '_', -2) AS STEP_DOWN_FILE_DATE_KEY
, CASE WHEN SPLIT_PART(SD.SUBJECT, '_', -2) <= '20241204' THEN CASE WHEN (HOUR(CONVERT_TIMEZONE('UTC', 'Australia/Sydney', SD.KAFKA_DATETIME)) = '00' OR HOUR(CONVERT_TIMEZONE('UTC', 'Australia/Sydney', SD.KAFKA_DATETIME)) BETWEEN '12' AND '23') AND LEFT(SPLIT_PART(SD.SUBJECT, '_', -1), 2) BETWEEN '01' AND '11' THEN TO_CHAR(LEFT(SPLIT_PART(SD.SUBJECT, '_', -1), 6) + 120000, 'FM000000') WHEN HOUR(CONVERT_TIMEZONE('UTC', 'Australia/Sydney', SD.KAFKA_DATETIME)) BETWEEN '01' AND '11' AND LEFT(SPLIT_PART(SD.SUBJECT, '_', -1), 2) = '12' THEN TO_CHAR(LEFT(SPLIT_PART(SD.SUBJECT, '_', -1), 6) - 120000, 'FM000000') ELSE LEFT(SPLIT_PART(SD.SUBJECT, '_', -1), 6) END ELSE LEFT(SPLIT_PART(SD.SUBJECT, '_', -1), 6) END AS STEP_DOWN_FILE_TIME_KEY
, P.PROCESSING_DATE AS PROCESSING_DATE
, CASE WHEN BTR_PRN.PAY_REF_NUMBER IS NULL THEN P.PROCESSING_DATE ELSE TO_DATE(SPLIT_PART(SD.SUBJECT, '_', -2), 'YYYYMMDD') END AS BANK_REC_DATE
, 0 AS EXCEPTION_FLAG
, 0 AS OSKO_FLAG
, 0 AS BULK_FLAG
, 1 AS STEP_DOWN_FLAG
, 'Step down payment' AS OSKO_PAID_AT_BUSINESS_HOUR_FLAG
, CASE WHEN BTR_PRN.PAY_REF_NUMBER IS NULL THEN 'Payable' ELSE 'Bank' END AS EXISTING_IN_BTR_FLAG
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM_KAFKA', 'PYMT_STEP_DOWN') }} AS SD
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON SD.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN (
    SELECT
    H.ACCOUNTING_DATE
    , L.TYPE_CODE
    , L.BANK_REF_NUM AS BATCH_ID
    FROM
    {{ source('RAW_CES_FINANCE', 'ANZ_BTR_HEADER') }} AS H
    INNER JOIN {{ source('RAW_CES_FINANCE', 'ANZ_BTR_LINES') }} AS L
    ON H.ID = L.HEADER_ID
    WHERE L.TYPE_CODE IN (467, 266)
    AND L.BANK_REF_NUM = L.CUSTOMER_REF_NUM
    AND NOT(L.CUSTOMER_REF_NUM LIKE ANY ('COEX', 'FAD%'))
) B
ON SD.BATCH_ID = B.BATCH_ID
LEFT JOIN (
    SELECT
    H.FILE_NAME
    , L.FILE_ROW_NUMBER
    , H.FILE_DATE
    , L.CUSTOMER_REF_NUM AS PAY_REF_NUMBER
    FROM
    {{ source('RAW_CES_FINANCE', 'ANZ_BTR_HEADER') }} AS H
    INNER JOIN {{ source('RAW_CES_FINANCE', 'ANZ_BTR_LINES') }} AS L
    ON H.ID = L.HEADER_ID
    WHERE L.TYPE_CODE IN (266, 195)
    QUALIFY ROW_NUMBER() OVER (PARTITION BY L.CUSTOMER_REF_NUM ORDER BY L.LANDED_DATETIME DESC) = 1
) BTR
ON SD.PAY_REF_NUMBER = BTR.PAY_REF_NUMBER
LEFT JOIN (
    SELECT DISTINCT
    F.MULTI_SCHEME_ID
    , F.SCHEME
    , CAST(F.PAY_REF_NUMBER AS STRING) AS PAY_REF_NUMBER
    , F.POS_TXN_NUM
    , F.PROCESSING_DATE
    , F.PROCESSING_DATE_KEY
    FROM {{ ref('FIN_RTP') }} AS F
    WHERE F.PAYMENT_STATUS = 'PAID'
    AND F.PAYMENT_METHOD = 'BANK'
    AND F.PAID_DATE_KEY >= TO_CHAR(ADD_MONTHS(SYSDATE(), -6), 'YYYYMMDD')
) P
ON SD.PAY_REF_NUMBER = P.PAY_REF_NUMBER
LEFT JOIN (
    SELECT DISTINCT
    L.CUSTOMER_REF_NUM AS PAY_REF_NUMBER
    FROM {{ source('RAW_CES_FINANCE', 'ANZ_BTR_LINES') }} AS L
) BTR_PRN
ON SD.PAY_REF_NUMBER = BTR_PRN.PAY_REF_NUMBER
WHERE SD.PAY_REF_NUMBER NOT IN (
    SELECT DISTINCT
    CASE WHEN L.TYPE_CODE = 495 AND L.CUSTOMER_REF_NUM IS NULL THEN SPLIT_PART(L.TEXT, ' ', -1) ELSE L.CUSTOMER_REF_NUM END AS PAY_REF_NUMBER
    FROM {{ source('RAW_CES_FINANCE', 'ANZ_BTR_LINES') }} AS L
    LEFT JOIN (
        SELECT
        NVL(L.CUSTOMER_REF_NUM, SPLIT_PART(L.TEXT, ' ', -1)) AS PAY_REF_NUMBER
        , SUM(CASE WHEN L.TYPE_CODE = 495 THEN 1 ELSE 0 END) AS COUNT_495
        , SUM(CASE WHEN L.TYPE_CODE = 195 THEN 1 ELSE 0 END) AS COUNT_195
        FROM {{ source('RAW_CES_FINANCE', 'ANZ_BTR_LINES') }} AS L
        WHERE L.TYPE_CODE IN (495, 195)
        GROUP BY ALL
    ) C
    ON CASE WHEN L.TYPE_CODE = 495 AND L.CUSTOMER_REF_NUM IS NULL THEN SPLIT_PART(L.TEXT, ' ', -1) ELSE L.CUSTOMER_REF_NUM END = C.PAY_REF_NUMBER
    WHERE CASE WHEN L.TYPE_CODE = 495 AND L.CUSTOMER_REF_NUM IS NULL THEN SPLIT_PART(L.TEXT, ' ', -1) ELSE L.CUSTOMER_REF_NUM END IS NOT NULL
    AND CASE WHEN L.TYPE_CODE = 495 AND C.COUNT_495 = COUNT_195 + 1 AND COUNT_195 > 0
    THEN 1
    WHEN L.TYPE_CODE = 495 AND NVL(L.CUSTOMER_REF_NUM, SPLIT_PART(L.TEXT, ' ', -1)) || L.FILE_DATE IN (
        SELECT DISTINCT
        L.CUSTOMER_REF_NUM || L.FILE_DATE AS PAY_REF_NUMBER_FILE_DATE
        FROM {{ source('RAW_CES_FINANCE', 'ANZ_BTR_LINES') }} AS L
        WHERE L.TYPE_CODE IN (195)
        AND L.CUSTOMER_REF_NUM IS NOT NULL
    )
    THEN 0 
    WHEN L.TYPE_CODE IN (266, 195) THEN 0 ELSE 1 END = 1
)