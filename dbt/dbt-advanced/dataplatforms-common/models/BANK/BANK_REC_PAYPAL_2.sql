SELECT
NVL(PAYPAL.MULTI_SCHEME_ID, ERP.MULTI_SCHEME_ID) AS MULTI_SCHEME_ID
, NVL(PAYPAL.SCHEME, ERP.SCHEME) AS SCHEME
, NVL(PAYPAL.MULTI_SCHEME_ID, ERP.MULTI_SCHEME_ID) || '-' || NVL(PAYPAL.ACCOUNTING_YEAR_MONTH_KEY, ERP.ACCOUNTING_YEAR_MONTH_KEY) || '-' || NVL(PAYPAL.AMOUNT, ERP.AMOUNT) AS ID
, NVL(PAYPAL.ACCOUNTING_YEAR_MONTH_KEY, ERP.ACCOUNTING_YEAR_MONTH_KEY) AS REPORTING_DATE_KEY
, PAYPAL.ACCOUNTING_YEAR_MONTH AS PAYPAL_ACCOUNTING_YEAR_MONTH
, PAYPAL.ACCOUNTING_YEAR_MONTH_KEY AS PAYPAL_ACCOUNTING_YEAR_MONTH_KEY
, PAYPAL.TRANSACTION_EVENT_CODE AS TRANSACTION_EVENT_CODE
, PAYPAL.CURRENCY AS CURRENCY
, PAYPAL.AMOUNT AS PAYPAL_AMOUNT
, ERP.ACCOUNTING_YEAR_MONTH AS PAYABLE_ACCOUNTING_YERA_MONTH
, ERP.ACCOUNTING_YEAR_MONTH_KEY AS PAYABLE_ACCOUNTING_YERA_MONTH_KEY
, ERP.ACCOUNT_CODE AS ACCOUNT_CODE
, ERP.AMOUNT_CR AS AMOUNT_CR
, ERP.AMOUNT_DR AS AMOUNT_DR
, ERP.AMOUNT_ENTERED_CR AS AMOUNT_ENTERED_CR
, ERP.AMOUNT_ENTERED_DR AS AMOUNT_ENTERED_DR
, ERP.AMOUNT AS PAYABLE_AMOUNT
, 'PAYPAL 2' AS SCENARIO
, 'PAYPAL' AS PAYMENT_METHOD
, CASE WHEN PAYPAL.MULTI_SCHEME_ID IS NULL AND ERP.MULTI_SCHEME_ID IS NOT NULL THEN 'Exist in PAYABLE, not exist in BANK STATEMENT' WHEN PAYPAL.MULTI_SCHEME_ID IS NOT NULL AND ERP.MULTI_SCHEME_ID IS NULL THEN 'Exist in BANK STATEMENT, not exist in PAYABLE' WHEN PAYPAL.MULTI_SCHEME_ID IS NOT NULL AND ERP.MULTI_SCHEME_ID IS NOT NULL THEN 'Reconciled' ELSE 'N/A' END AS RECONCILIATION_FLAG
, SYSDATE() AS INSERT_DATE_UTC
FROM (
    SELECT
    S.MULTI_SCHEME_ID
    , S.SCHEME
    , DATE_TRUNC(MONTH, S.TRANSACTION_COMPLETION_DATE) AS ACCOUNTING_YEAR_MONTH
    , TO_CHAR(S.TRANSACTION_COMPLETION_DATE, 'YYYYMM01') AS ACCOUNTING_YEAR_MONTH_KEY
    , S.TRANSACTION_EVENT_CODE
    , S.CURRENCY
    , ROUND(SUM(S.GROSS_TRANSACTION_AMOUNT), 2) AS AMOUNT
    FROM {{ ref('PAYPAL_SETTLEMENT') }} AS S
    WHERE S.TRANSACTION_EVENT_CODE = 'T0300'
    AND S.TRANSACTION_COMPLETION_DATE_KEY >= TO_CHAR(ADD_MONTHS(SYSDATE(), -6), 'YYYYMMDD')
    GROUP BY ALL
) PAYPAL
FULL OUTER JOIN (
    SELECT
    DECODE(J.LEDGER_NAME, 'Processor QLD Ledger AU', 10000, 'Processor WA Ledger AU', 10001, 'Scheme VIC NOP Ledger', 100020001) AS MULTI_SCHEME_ID
    , SCHEME.NAME AS SCHEME
    , DATE_TRUNC(MONTH, CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, CAST(J.ACCOUNTING_DATE AS TIMESTAMP))) AS ACCOUNTING_YEAR_MONTH
    , TO_CHAR(CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, CAST(J.ACCOUNTING_DATE AS TIMESTAMP)), 'YYYYMM01') AS ACCOUNTING_YEAR_MONTH_KEY
    , J.ACCOUNT_CODE
    , SUM(J.AMOUNT_CR) AS AMOUNT_CR
    , SUM(J.AMOUNT_DR) AS AMOUNT_DR
    , SUM(J.AMOUNT_ENTERED_CR) AS AMOUNT_ENTERED_CR
    , SUM(J.AMOUNT_ENTERED_DR) AS AMOUNT_ENTERED_DR
    , NVL(SUM(J.AMOUNT_DR), 0) - NVL(SUM(J.AMOUNT_CR), 0) AS AMOUNT
    FROM {{ source('CES_ERP', 'GL_JOURNALS') }} AS J
    LEFT JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
    ON DECODE(J.LEDGER_NAME, 'Processor QLD Ledger AU', 10000, 'Processor WA Ledger AU', 10001, 'Scheme VIC NOP Ledger', 100020001) = SCHEME.MULTI_SCHEME_ID
    WHERE J.LEDGER_NAME IN ('Processor QLD Ledger AU', 'Processor WA Ledger AU', 'Scheme VIC NOP Ledger')
    AND UPPER(J.JOURNAL_LINE_DESC) LIKE ANY ('%PAYPAL%TRF%', '%PAYPAL%TFR%', '%TRF%PAYPAL%', '%TFR%PAYPAL%', '%PAYPAL%TOP%', '%TOP%PAYPAL%', '%TRANSFER%PAYPAL%', 'PAYPAL%TRANSFER%')
    AND J.SOURCE_JOURNAL_SOURCE_NAME = 'Spreadsheet'
    AND J.ACCOUNT_CODE = 10040
    AND TO_CHAR(J.ACCOUNTING_DATE, 'YYYYMMDD') >= TO_CHAR(ADD_MONTHS(SYSDATE(), -6), 'YYYYMMDD')
    GROUP BY ALL
    HAVING AMOUNT <> 0
) ERP
ON PAYPAL.MULTI_SCHEME_ID = ERP.MULTI_SCHEME_ID
AND PAYPAL.ACCOUNTING_YEAR_MONTH_KEY = ERP.ACCOUNTING_YEAR_MONTH_KEY
AND ROUND(PAYPAL.AMOUNT, 2) = ROUND(ERP.AMOUNT, 2)