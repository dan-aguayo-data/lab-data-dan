SELECT
I.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, I.SCHEME AS SCHEME
, I.INVOICE_LINE_ID AS ID
, I.POS_TRANSACTION_ID AS POS_TRANSACTION_ID
, I.COMPANY_CODE AS COMPANY_CODE
, I.MATERIAL_TYPE_CODE AS MATERIAL_TYPE_CODE
, I.COST_CENTRE_CODE AS COST_CENTRE_CODE
, I.ACCOUNT_CODE AS ACCOUNT_CODE
, I.INTERCOMPANY_CODE AS INTERCOMPANY_CODE
, I.SPARE_CODE AS SPARE_CODE
, I.DISTRIBUTION_COMBINATION AS DISTRIBUTION_COMBINATION
, I.LEGAL_ENTITY AS LEGAL_ENTITY
, I.PAY_GROUP AS PAY_GROUP
, I.PAYMENT_METHOD AS PAYMENT_METHOD
, I.PAYMENT_TERMS AS PAYMENT_TERMS
, I.PAYMENT_NUMBER AS PAYMENT_NUMBER
, I.ACCOUNTING_DATE AS ACCOUNTING_DATE
, I.ACCOUNTING_DATE_KEY AS ACCOUNTING_DATE_KEY
, I.INVOICE_DATE AS INVOICE_DATE
, I.INVOICE_DATE_KEY AS INVOICE_DATE_KEY
, I.CURRENCY AS CURRENCY
, CASE WHEN I.ACCOUNT_CODE IN ('14920', '51005') THEN I.LINE_AMOUNT ELSE 0 END AS AMOUNT_DR
, CASE WHEN I.ACCOUNT_CODE IN ('14930') THEN I.LINE_AMOUNT ELSE 0 END AS AMOUNT_CR
, I.SUPPLIER_NUMBER AS SUPPLIER_NUMBER
, I.SITE_NUMBER AS SITE_NUMBER
, I.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID
, 'INVOICE' AS INVOICE_PAYMENT_FLAG
, 'BANK 1 INVOICE' AS SCENARIO
, I.KAFKA_DATE AS KAFKA_DATE
, I.KAFKA_TIME_KEY AS KAFKA_TIME_KEY
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ ref('INVOICE_EVENT') }} AS I
WHERE I.ACCOUNT_CODE IN ('14920', '14930', '51005')
AND I.PAYMENT_METHOD = 'BANK'
AND I.ACCOUNTING_DATE_KEY >= TO_CHAR(ADD_MONTHS(SYSDATE(), -6), 'YYYYMMDD')
 
UNION ALL
 
SELECT
I.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, I.SCHEME AS SCHEME
, I.POS_TRANSACTION_ID AS ID
, I.POS_TRANSACTION_ID AS POS_TRANSACTION_ID
, I.COMPANY_CODE AS COMPANY_CODE
, '00' AS MATERIAL_TYPE_CODE
, '0000' AS COST_CENTRE_CODE
, '20005' AS ACCOUNT_CODE
, '0000' AS INTERCOMPANY_CODE
, '00000' AS SPARE_CODE
, I.COMPANY_CODE || '-' || '00-0000-20005-0000-00000' AS DISTRIBUTION_COMBINATION
, I.LEGAL_ENTITY AS LEGAL_ENTITY
, I.PAY_GROUP AS PAY_GROUP
, I.PAYMENT_METHOD AS PAYMENT_METHOD
, I.PAYMENT_TERMS AS PAYMENT_TERMS
, I.PAYMENT_NUMBER AS PAYMENT_NUMBER
, I.ACCOUNTING_DATE AS ACCOUNTING_DATE
, I.ACCOUNTING_DATE_KEY AS ACCOUNTING_DATE_KEY
, I.INVOICE_DATE AS INVOICE_DATE
, I.INVOICE_DATE_KEY AS INVOICE_DATE_KEY
, I.CURRENCY AS CURRENCY
, SUM(CASE WHEN I.ACCOUNT_CODE IN ('14930') THEN I.LINE_AMOUNT ELSE 0 END) AS AMOUNT_DR
, SUM(CASE WHEN I.ACCOUNT_CODE IN ('14920', '51005') THEN I.LINE_AMOUNT ELSE 0 END) AS AMOUNT_CR
, I.SUPPLIER_NUMBER AS SUPPLIER_NUMBER
, I.SITE_NUMBER AS SITE_NUMBER
, NULL AS MATERIAL_TYPE_ID
, 'INVOICE' AS INVOICE_PAYMENT_FLAG
, 'BANK 1 INVOICE' AS SCENARIO
, I.KAFKA_DATE AS KAFKA_DATE
, I.KAFKA_TIME_KEY AS KAFKA_TIME_KEY
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ ref('INVOICE_EVENT') }} AS I
WHERE I.ACCOUNTING_DATE_KEY IS NOT NULL
AND I.PAYMENT_METHOD = 'BANK'
AND I.ACCOUNTING_DATE_KEY >= TO_CHAR(ADD_MONTHS(SYSDATE(), -6), 'YYYYMMDD')
GROUP BY ALL