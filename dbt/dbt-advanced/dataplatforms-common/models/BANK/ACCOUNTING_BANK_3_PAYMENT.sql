SELECT
R.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, R.SCHEME AS SCHEME
, R.ID AS ID
, R.ACCOUNTING_DATE AS ACCOUNTING_DATE
, R.ACCOUNTING_DATE_KEY AS ACCOUNTING_DATE_KEY
, DECODE(R.MULTI_SCHEME_ID, 10000, '9501', 10001, '9601', 100020001, '9701') AS COMPANY_CODE
, '00' AS MATERIAL_TYPE_CODE
, '0000' AS COST_CENTRE_CODE
, DECODE(R.MULTI_SCHEME_ID, 10000, '10025', 10001, '10025', 100020001, '10020') AS ACCOUNT_CODE
, '0000' AS INTERCOMPANY_CODE
, '00000' AS SPARE_CODE
, DECODE(R.MULTI_SCHEME_ID, 10000, '9501', 10001, '9601', 100020001, '9701') || '-' || '00-0000' || '-' || DECODE(R.MULTI_SCHEME_ID, 10000, '10025', 10001, '10025', 100020001, '10020') || '-' || '0000-00000' AS DISTRIBUTION_COMBINATION
, R.CURRENCY AS CURRENCY
, R.AMOUNT AS AMOUNT_DR
, 0 AS AMOUNT_CR
, R.ORIGINAL_PAY_REF_NUMBER AS ORIGINAL_PAY_REF_NUMBER
, R.RETURN_REASON AS RETURN_REASON
, 'BANK' AS PAYMENT_METHOD
, 'PAYMENT' AS INVOICE_PAYMENT_FLAG
, 'BANK 3 PAYMENT' AS SCENARIO
, NULL AS KAFKA_DATE
, NULL AS KAFKA_TIME_KEY
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ ref('RTI') }} AS R
 
UNION ALL
 
SELECT
R.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, R.SCHEME AS SCHEME
, R.ID AS ID
, R.ACCOUNTING_DATE AS ACCOUNTING_DATE
, R.ACCOUNTING_DATE_KEY AS ACCOUNTING_DATE_KEY
, DECODE(R.MULTI_SCHEME_ID, 10000, '9501', 10001, '9601') AS COMPANY_CODE
, '00' AS MATERIAL_TYPE_CODE
, '0000' AS COST_CENTRE_CODE
, '15005' AS ACCOUNT_CODE
, NVL(A.COMPANY_CODE, CC.COMPANY_CODE) AS INTERCOMPANY_CODE
, '00000' AS SPARE_CODE
, DECODE(R.MULTI_SCHEME_ID, 10000, '9501', 10001, '9601') || '-' || '00-0000-15005' || '-' || NVL(A.COMPANY_CODE, CC.COMPANY_CODE) || '-' || '00000' AS DISTRIBUTION_COMBINATION
, R.CURRENCY AS CURRENCY
, 0 AS AMOUNT_DR
, NVL(A.AMOUNT, CC.AMOUNT) AS AMOUNT_CR
, R.ORIGINAL_PAY_REF_NUMBER AS ORIGINAL_PAY_REF_NUMBER
, R.RETURN_REASON AS RETURN_REASON
, 'BANK' AS PAYMENT_METHOD
, 'PAYMENT' AS INVOICE_PAYMENT_FLAG
, 'BANK 3 PAYMENT' AS SCENARIO
, A.KAFKA_DATE AS KAFKA_DATE
, A.KAFKA_TIME_KEY AS KAFKA_TIME_KEY
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ ref('RTI') }} AS R
LEFT JOIN {{ ref('ACCOUNTING_WITH_COMPANY_CODE') }} AS A
ON R.ORIGINAL_PAY_REF_NUMBER = CAST(A.PAY_REF_NUMBER AS STRING)
LEFT JOIN (
    SELECT
    AP.CHECK_NUMBER AS PAY_REF_NUMBER
    , AP.INVOICE_NUMBER
    FROM {{ source('CES_ERP', 'AP_BALANCES') }} AS AP
    WHERE AP.INVOICE_NUMBER IN (
        SELECT
        T.INVOICE_NUM
        FROM {{ source('CES_ERP', 'AP_TRANSACTIONS') }} AS T
        WHERE T.PAY_GROUP = 'CRP REFUND'
    )
    AND AP.PAYMENT_STATUS = 'Voided'
    AND TO_CHAR(AP.PAYMENT_DATE, 'YYYYMMDD') >= TO_CHAR(ADD_MONTHS(SYSDATE(), -6), 'YYYYMMDD')
    QUALIFY ROW_NUMBER() OVER (PARTITION BY AP.INVOICE_NUMBER ORDER BY AP.PAYMENT_DATE) = 1
) APB --CRP REFUND
ON R.ORIGINAL_PAY_REF_NUMBER = APB.PAY_REF_NUMBER
LEFT JOIN (
SELECT
    H.INVOICE_NUMBER
    , ROUND(H.INVOICE_AMOUNT * 1.1, 2) AS AMOUNT
    , MAX(LEFT(D.DISTRIBUTION_COMBINATION, 4)) AS COMPANY_CODE
    FROM {{ source('CES_MSCM', 'INVOICE_AP_TXN_HDR') }} AS H
    INNER JOIN {{ source('CES_MSCM', 'INVOICE_AP_TXN_DTL') }} AS D
    ON H.ID = D.INVOICE_HDR_REF
    WHERE H.INVOICE_SOURCE = 'CRP'
    AND H.PAY_GROUP = 'CRP REFUND'
    AND TO_CHAR(H.CREATED_ON, 'YYYYMMDD') >= TO_CHAR(ADD_MONTHS(SYSDATE(), -6), 'YYYYMMDD')
    GROUP BY ALL
) CC
ON APB.INVOICE_NUMBER = CC.INVOICE_NUMBER
WHERE R.MULTI_SCHEME_ID IN (10000, 10001)
 
UNION ALL
 
