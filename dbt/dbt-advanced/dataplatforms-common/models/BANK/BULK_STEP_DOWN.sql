SELECT
NVL(B.MULTI_SCHEME_ID, SD.MULTI_SCHEME_ID) AS MULTI_SCHEME_ID
, NVL(B.SCHEME, SD.SCHEME) AS SCHEME
, NVL(B.ID, SD.ID) AS ID
, NVL(B.BATCH_ID, SD.BATCH_ID) AS BATCH_ID
, NVL(B.ACCOUNTING_DATE, SD.ACCOUNTING_DATE) AS ACCOUNTING_DATE
, NVL(B.ACCOUNTING_DATE_KEY, SD.ACCOUNTING_DATE_KEY) AS ACCOUNTING_DATE_KEY
, B.HEADER_ID AS BTR_HEADER_ID
, B.ACCOUNT_NUMBER AS BTR_ACCOUNT_NUMBER
, B.FILE_DATE AS BTR_FILE_DATE
, B.FILE_NAME AS BTR_FILE_NAME
, B.FILE_ROW_NUMBER AS BTR_FILE_ROW_NUMBER
, NVL(B.CURRENCY, SD.CURRENCY) AS CURRENCY
, B.AMOUNT AS BTR_AMOUNT
, B.TYPE_CODE AS BTR_TYPE_CODE
, B.NARRATIVE AS BTR_NARRATIVE
, SD.STEP_DOWN_FILE_DATE AS STEP_DOWN_FILE_DATE
, SD.STEP_DOWN_FILE_NAME AS STEP_DOWN_FILE_NAME
, SD.STEP_DOWN_FILE_ROW_NUMBER AS STEP_DOWN_FILE_ROW_NUMBER
, SD.STEP_DOWN_FILE_DATE_KEY AS STEP_DOWN_FILE_DATE_KEY
, SD.STEP_DOWN_FILE_TIME_KEY AS STEP_DOWN_FILE_TIME_KEY
, SD.AMOUNT AS STEP_DOWN_AMOUNT
, SD.PAY_REF_NUMBER AS PAY_REF_NUMBER
, SD.ORIGINAL_PAY_REF_NUMBER AS ORIGINAL_PAY_REF_NUMBER
, SD.PROCESSING_DATE AS PROCESSING_DATE
, SD.BANK_REC_DATE AS BANK_REC_DATE
, SD.EXISTING_IN_BTR_FLAG AS EXISTING_IN_BTR_FLAG
, CASE WHEN B.AMOUNT = ROUND(SUM(SD.AMOUNT) OVER (PARTITION BY NVL(B.BATCH_ID, SD.BATCH_ID)), 2) THEN 'Y' ELSE 'N' END AS RECONCILIATION_FLAG
, SYSDATE() AS INSERT_DATE_UTC
FROM (
    SELECT
    BTR.MULTI_SCHEME_ID
    , BTR.SCHEME
    , BTR.ID
    , BTR.BATCH_ID
    , BTR.ACCOUNTING_DATE
    , BTR.ACCOUNTING_DATE_KEY
    , BTR.HEADER_ID
    , BTR.ACCOUNT_NUMBER
    , BTR.FILE_DATE
    , BTR.FILE_NAME
    , BTR.FILE_ROW_NUMBER
    , BTR.CURRENCY
    , BTR.AMOUNT
    , BTR.TYPE_CODE
    , BTR.NARRATIVE
    FROM {{ ref('BTR') }} AS BTR
    WHERE BTR.BULK_FLAG = 1
) B
FULL OUTER JOIN (
    SELECT
    BTR.MULTI_SCHEME_ID
    , BTR.SCHEME
    , BTR.ID
    , BTR.BATCH_ID
    , BTR.ACCOUNTING_DATE
    , BTR.ACCOUNTING_DATE_KEY
    , BTR.CURRENCY
    , BTR.STEP_DOWN_FILE_DATE
    , BTR.STEP_DOWN_FILE_NAME
    , BTR.STEP_DOWN_FILE_ROW_NUMBER
    , BTR.STEP_DOWN_FILE_DATE_KEY
    , BTR.STEP_DOWN_FILE_TIME_KEY
    , BTR.PROCESSING_DATE
    , BTR.BANK_REC_DATE
    , BTR.AMOUNT
    , BTR.PAY_REF_NUMBER
    , BTR.ORIGINAL_PAY_REF_NUMBER
    , BTR.EXISTING_IN_BTR_FLAG
    FROM {{ ref('BTR') }} AS BTR
    WHERE BTR.STEP_DOWN_FLAG = 1
) SD
ON B.MULTI_SCHEME_ID = SD.MULTI_SCHEME_ID
AND B.BATCH_ID = SD.BATCH_ID