SELECT
NVL(BTR.MULTI_SCHEME_ID, P.MULTI_SCHEME_ID) AS MULTI_SCHEME_ID
, NVL(BTR.SCHEME, P.SCHEME) AS SCHEME
, NVL(BTR.ID, P.ID) AS ID
, NVL(BTR.PAY_REF_NUMBER, P.PAY_REF_NUMBER) AS PAY_REF_NUMBER
, NVL(BTR.ACCOUNTING_DATE_KEY, P.PAYMENT_DATE_KEY) AS REPORTING_DATE_KEY
, BTR.ID AS BTR_ID
, BTR.ACCOUNT_NUMBER AS ACCOUNT_NUMBER
, BTR.FILE_DATE AS FILE_DATE
, BTR.ACCOUNTING_DATE AS ACCOUNTING_DATE
, BTR.ACCOUNTING_DATE_KEY AS ACCOUNTING_DATE_KEY
, BTR.FILE_NAME AS FILE_NAME
, BTR.FILE_ROW_NUMBER AS FILE_ROW_NUMBER
, BTR.TYPE_CODE AS TYPE_CODE
, BTR.PAY_REF_NUMBER AS BTR_PAY_REF_NUMBER
, BTR.CURRENCY AS CURRENCY
, BTR.AMOUNT AS BTR_AMOUNT
, BTR.NARRATIVE AS NARRATIVE
, BTR.OSKO_FLAG AS OSKO_FLAG
, P.PAY_REF_NUMBER AS PAYABLE_PAY_REF_NUMBER
, P.POS_TXN_NUM AS POS_TXN_NUM
, P.PAYMENT_DATE AS PAYMENT_DATE
, P.PAYMENT_DATE_KEY AS PAYMENT_DATE_KEY
, P.AMOUNT AS PAYABLE_AMOUNT
, 'BANK 1' AS SCENARIO
, 'BANK' AS PAYMENT_METHOD
, CASE WHEN BTR.PAY_REF_NUMBER IS NULL AND P.PAY_REF_NUMBER IS NOT NULL THEN 'Exist in PAYABLE, not exist in BANK STATEMENT' WHEN BTR.PAY_REF_NUMBER IS NOT NULL AND P.PAY_REF_NUMBER IS NULL THEN 'Exist in BANK STATEMENT, not exist in PAYABLE' WHEN BTR.PAY_REF_NUMBER IS NOT NULL AND P.PAY_REF_NUMBER IS NOT NULL THEN 'Reconciled' ELSE 'N/A' END AS RECONCILIATION_FLAG
, SYSDATE() AS INSERT_DATE_UTC
FROM (
    SELECT
    *
    FROM {{ ref('BTR') }} AS B
    WHERE B.TYPE_CODE IN (467, 495)
    AND B.ACCOUNTING_DATE_KEY >= TO_CHAR(ADD_MONTHS(SYSDATE(), -6), 'YYYYMMDD')
    AND B.BULK_FLAG = 0
) BTR
FULL OUTER JOIN (
    SELECT
    F.MULTI_SCHEME_ID
    , F.SCHEME
    , F.ID
    , CAST(F.PAY_REF_NUMBER AS STRING) AS PAY_REF_NUMBER
    , F.POS_TXN_NUM
    , F.PAID_DATE AS PAYMENT_DATE
    , F.PAID_DATE_KEY AS PAYMENT_DATE_KEY
    , ROUND(SUM(F.GROSS_AMOUNT), 2) AS AMOUNT
    FROM {{ ref('FIN_RTP') }} AS F
    WHERE F.PAYMENT_STATUS = 'PAID'
    AND F.PAYMENT_METHOD = 'BANK'
    AND F.PAID_DATE_KEY >= TO_CHAR(ADD_MONTHS(SYSDATE(), -6), 'YYYYMMDD')
    GROUP BY ALL
) P
ON BTR.PAY_REF_NUMBER = CAST(P.PAY_REF_NUMBER AS STRING)
AND ROUND(CASE WHEN BTR.ACCOUNTING_DATE_KEY <= 20241204 THEN FLOOR(BTR.AMOUNT, 1) ELSE BTR.AMOUNT END, 2) = ROUND(CASE WHEN P.PAYMENT_DATE_KEY <= 20241204 THEN FLOOR(P.AMOUNT, 1) ELSE P.AMOUNT END, 2)
WHERE (
    NVL(LEFT(BTR.PAY_REF_NUMBER, 1), '2') BETWEEN '2' AND '9'
    OR (NVL(LEFT(BTR.PAY_REF_NUMBER, 1), '1') = '1' AND P.PAY_REF_NUMBER IS NOT NULL)
    OR LEFT(BTR.PAY_REF_NUMBER, 3) = 'FAD'
)