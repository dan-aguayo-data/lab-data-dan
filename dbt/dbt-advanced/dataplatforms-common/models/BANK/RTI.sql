SELECT
DECODE(R.ACCOUNT_NAME, 'COEX QLD AP SETT', 10000, 'WARRRL AP SETT A', 10001, 'OPERATING ACCOUN', 100020001) AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, R.FILE_NAME || '-' || R.FILE_ROW_NUMBER AS ID
, R.RETURN_DATE AS ACCOUNTING_DATE
, TO_CHAR(R.RETURN_DATE, 'YYYYMMDD') AS ACCOUNTING_DATE_KEY
, R.FILE_NAME AS FILE_NAME
, 'AUD' AS CURRENCY
, R.FILE_ROW_NUMBER AS FILE_ROW_NUMBER
, R.AMOUNT AS AMOUNT
, R.LODGEMENT_DATE AS ORIGINAL_PAID_DATE
, R.LODGEMENT_REFERENCE AS ORIGINAL_PAY_REF_NUMBER
, R.RETURN_REASON_TEXT AS RETURN_REASON
, '252' AS TYPE_CODE
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('RAW_CES_FINANCE', 'ANZ_RTI_REC') }} AS R
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON DECODE(R.ACCOUNT_NAME, 'COEX QLD AP SETT', 10000, 'WARRRL AP SETT A', 10001, 'OPERATING ACCOUN', 100020001) = SCHEME.MULTI_SCHEME_ID
 
UNION ALL
 
SELECT
BTR.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, BTR.SCHEME AS SCHEME
, BTR.ID AS ID
, BTR.ACCOUNTING_DATE AS ACCOUNTING_DATE
, BTR.ACCOUNTING_DATE_KEY AS ACCOUNTING_DATE_KEY
, BTR.FILE_NAME AS FILE_NAME
, BTR.CURRENCY AS CURRENCY
, BTR.FILE_ROW_NUMBER AS FILE_ROW_NUMBER
, BTR.AMOUNT AS AMOUNT
, NULL AS ORIGINAL_PAID_DATE
, BTR.PAY_REF_NUMBER AS ORIGINAL_PAY_REF_NUMBER
, BTR.NARRATIVE AS RETURN_REASON
, BTR.TYPE_CODE AS TYPE_CODE
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ ref('BTR') }} AS BTR
WHERE BTR.TYPE_CODE = 266