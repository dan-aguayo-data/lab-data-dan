SELECT
P.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, P.SCHEME AS SCHEME
, P.ID AS ID
, M.COMPANY_CODE AS COMPANY_CODE
, M.LEGAL_ENTITY AS LEGAL_ENTITY
, M.CURRENCY AS CURRENCY
, P.TRANSACTION_ID AS TRANSACTION_ID
, P.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID
, P.MATERIAL_TYPE AS MATERIAL_TYPE
, P.AMOUNT AS AMOUNT
, P.PAY_REF_NUMBER AS PAY_REF_NUMBER
, P.PAID_DATE AS PAID_DATE
, P.PAID_DATE_KEY AS PAID_DATE_KEY
, P.PAYMENT_METHOD AS PAYMENT_METHOD
, P.INVOICE_NUMBER_AND_STATUS AS INVOICE_NUMBER_AND_STATUS
, P.PYMT_AMOUNT_RECENT_FLAG AS PYMT_AMOUNT_RECENT_FLAG
, M.KAFKA_DATE AS KAFKA_DATE
, M.KAFKA_TIME_KEY AS KAFKA_TIME_KEY
, SYSDATE() AS INSERT_DATE_UTC
FROM (
    SELECT
    F.MULTI_SCHEME_ID
    , F.SCHEME
    , F.ID
    , F.POS_TXN_NUM AS TRANSACTION_ID
    , F.MATERIAL_TYPE_ID
    , M.NAME AS MATERIAL_TYPE
    , F.GROSS_AMOUNT AS AMOUNT
    , F.PAY_REF_NUMBER
    , F.PAID_DATE
    , F.PAID_DATE_KEY
    , F.PAYMENT_METHOD
    , F.INVOICE_NUMBER_AND_STATUS
    , F.PYMT_AMOUNT_RECENT_FLAG
    FROM {{ ref('FIN_RTP') }} AS F
    LEFT JOIN {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS M
    ON F.MATERIAL_TYPE_ID = M.ID
    WHERE F.PAYMENT_STATUS = 'PAID'
    AND F.PAYMENT_METHOD <> 'EFT'
    AND M.NAME <> 'Ineligible Containers'
    AND F.PAID_DATE_KEY >= TO_CHAR(ADD_MONTHS(SYSDATE(), -6), 'YYYYMMDD')
) P
INNER JOIN (
    SELECT
    I.LEGAL_ENTITY
    , I.COMPANY_CODE
    , I.POS_TRANSACTION_ID AS TRANSACTION_ID
    , I.POS_MATERIAL_TYPE AS MATERIAL_TYPE
    , I.CURRENCY
    , MAX(I.KAFKA_DATE) AS KAFKA_DATE
    , MAX(I.KAFKA_TIME_KEY) AS KAFKA_TIME_KEY
    FROM {{ ref('INVOICE_EVENT') }} AS I
    WHERE I.POS_MATERIAL_TYPE IS NOT NULL
    GROUP BY ALL
) M
ON P.TRANSACTION_ID = M.TRANSACTION_ID
AND P.MATERIAL_TYPE = M.MATERIAL_TYPE