SELECT
NVL(BTR.MULTI_SCHEME_ID, ERP.MULTI_SCHEME_ID) AS MULTI_SCHEME_ID
, NVL(BTR.SCHEME, ERP.SCHEME) AS SCHEME
, NVL(BTR.MULTI_SCHEME_ID, ERP.MULTI_SCHEME_ID) || '-' || NVL(BTR.ACCOUNTING_DATE_KEY, ERP.ACCOUNTING_DATE_KEY) || '-' || NVL(BTR.AMOUNT, ERP.AMOUNT) AS ID
, NVL(BTR.ACCOUNTING_DATE_KEY, ERP.ACCOUNTING_DATE_KEY) AS REPORTING_DATE_KEY
, BTR.ID AS BTR_ID
, BTR.ACCOUNT_NUMBER AS ACCOUNT_NUMBER
, BTR.FILE_DATE AS FILE_DATE
, BTR.ACCOUNTING_DATE AS ACCOUNTING_DATE
, BTR.ACCOUNTING_DATE_KEY AS ACCOUNTING_DATE_KEY
, BTR.FILE_NAME AS FILE_NAME
, BTR.FILE_ROW_NUMBER AS FILE_ROW_NUMBER
, BTR.TYPE_CODE AS TYPE_CODE
, BTR.PAY_REF_NUMBER AS BTR_PAY_REF_NUMBER
, BTR.CURRENCY AS CURRENCY
, BTR.AMOUNT AS BTR_AMOUNT
, BTR.NARRATIVE AS NARRATIVE
, ERP.ACCOUNTING_DATE AS PAYABLE_ACCOUNTING_DATE
, ERP.ACCOUNTING_DATE_KEY AS PAYABLE_ACCOUNTING_DATE_KEY
, ERP.ACCOUNT_CODE AS ACCOUNT_CODE
, ERP.AMOUNT_CR AS AMOUNT_CR
, ERP.AMOUNT_DR AS AMOUNT_DR
, ERP.AMOUNT_ENTERED_CR AS AMOUNT_ENTERED_CR
, ERP.AMOUNT_ENTERED_DR AS AMOUNT_ENTERED_DR
, ERP.AMOUNT AS PAYABLE_AMOUNT
, 'BANK 4' AS SCENARIO
, 'BANK' AS PAYMENT_METHOD
, CASE WHEN BTR.MULTI_SCHEME_ID IS NULL AND ERP.MULTI_SCHEME_ID IS NOT NULL THEN 'Exist in PAYABLE, not exist in BANK STATEMENT' WHEN BTR.MULTI_SCHEME_ID IS NOT NULL AND ERP.MULTI_SCHEME_ID IS NULL THEN 'Exist in BANK STATEMENT, not exist in PAYABLE' WHEN BTR.MULTI_SCHEME_ID IS NOT NULL AND ERP.MULTI_SCHEME_ID IS NOT NULL THEN 'Reconciled' ELSE 'N/A' END AS RECONCILIATION_FLAG
, SYSDATE() AS INSERT_DATE_UTC
FROM (
    SELECT
    *
    FROM {{ ref('BTR') }} AS B
    WHERE B.TYPE_CODE IN (275)
    AND B.MULTI_SCHEME_ID IN (10000, 10001)
    AND B.ACCOUNTING_DATE_KEY >= TO_CHAR(ADD_MONTHS(SYSDATE(), -6), 'YYYYMMDD')
) BTR
FULL OUTER JOIN (
    SELECT
    DECODE(J.LEDGER_NAME, 'Processor QLD Ledger AU', 10000, 'Processor WA Ledger AU', 10001) AS MULTI_SCHEME_ID
    , SCHEME.NAME AS SCHEME
    , CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, CAST(CASE WHEN J.ID IN ('3872652-1', '3872653-1', '3872649-1', '3872650-1', '3872651-1') THEN DATEADD(DAY, 7, J.ACCOUNTING_DATE) ELSE J.ACCOUNTING_DATE END AS TIMESTAMP)) AS ACCOUNTING_DATE
    , TO_CHAR(CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, CAST(CASE WHEN J.ID IN ('3872652-1', '3872653-1', '3872649-1', '3872650-1', '3872651-1') THEN DATEADD(DAY, 7, J.ACCOUNTING_DATE) ELSE J.ACCOUNTING_DATE END AS TIMESTAMP)), 'YYYYMMDD') AS ACCOUNTING_DATE_KEY
    , J.ACCOUNT_CODE
    , SUM(J.AMOUNT_CR) AS AMOUNT_CR
    , SUM(J.AMOUNT_DR) AS AMOUNT_DR
    , SUM(J.AMOUNT_ENTERED_CR) AS AMOUNT_ENTERED_CR
    , SUM(J.AMOUNT_ENTERED_DR) AS AMOUNT_ENTERED_DR
    , NVL(SUM(J.AMOUNT_DR), 0) - NVL(SUM(J.AMOUNT_CR), 0) AS AMOUNT
    FROM {{ source('CES_ERP', 'GL_JOURNALS') }} AS J
    LEFT JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
    ON DECODE(J.LEDGER_NAME, 'Processor QLD Ledger AU', 10000, 'Processor WA Ledger AU', 10001) = SCHEME.MULTI_SCHEME_ID
    WHERE J.LEDGER_NAME IN ('Processor QLD Ledger AU', 'Processor WA Ledger AU')
    AND (J.JOURNAL_NAME LIKE '%SWP%' OR J.JOURNAL_BATCH_NAME LIKE '%SWP%')
    AND J.SOURCE_JOURNAL_SOURCE_NAME = 'Spreadsheet'
    AND J.ACCOUNT_CODE = 10025
    AND TO_CHAR(J.ACCOUNTING_DATE, 'YYYYMMDD') >= TO_CHAR(ADD_MONTHS(SYSDATE(), -6), 'YYYYMMDD')
    GROUP BY ALL
    HAVING AMOUNT <> 0
) ERP
ON BTR.ACCOUNTING_DATE_KEY = ERP.ACCOUNTING_DATE_KEY
AND ROUND(BTR.AMOUNT, 2) = ROUND(ERP.AMOUNT, 2)
AND BTR.MULTI_SCHEME_ID = ERP.MULTI_SCHEME_ID