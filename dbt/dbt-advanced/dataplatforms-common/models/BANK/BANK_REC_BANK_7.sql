SELECT
NVL(BTR.MULTI_SCHEME_ID, ERP.MULTI_SCHEME_ID) AS MULTI_SCHEME_ID
, NVL(BTR.SCHEME, ERP.SCHEME) AS SCHEME
, NVL(BTR.MULTI_SCHEME_ID, ERP.MULTI_SCHEME_ID) || '-' || NVL(BTR.ACCOUNTING_DATE_KEY, ERP.ACCOUNTING_DATE_KEY) || '-' || NVL(BTR.AMOUNT, ERP.AMOUNT) AS ID
, NVL(BTR.ACCOUNTING_DATE_KEY, ERP.ACCOUNTING_DATE_KEY) AS REPORTING_DATE_KEY
, BTR.ID AS BTR_ID
, BTR.ACCOUNT_NUMBER AS ACCOUNT_NUMBER
, BTR.FILE_DATE AS FILE_DATE
, BTR.ACCOUNTING_DATE AS ACCOUNTING_DATE
, BTR.ACCOUNTING_DATE_KEY AS ACCOUNTING_DATE_KEY
, BTR.FILE_NAME AS FILE_NAME
, BTR.FILE_ROW_NUMBER AS FILE_ROW_NUMBER
, BTR.TYPE_CODE AS TYPE_CODE
, BTR.CURRENCY AS CURRENCY
, BTR.AMOUNT AS BTR_AMOUNT
, BTR.NARRATIVE AS NARRATIVE
, ERP.ACCOUNTING_DATE AS PAYABLE_ACCOUNTING_DATE
, ERP.ACCOUNTING_DATE_KEY AS PAYABLE_ACCOUNTING_DATE_KEY
, ERP.ACCOUNT_CODE AS ACCOUNT_CODE
, ERP.AMOUNT_CR AS AMOUNT_CR
, ERP.AMOUNT_DR AS AMOUNT_DR
, ERP.AMOUNT_ENTERED_CR AS AMOUNT_ENTERED_CR
, ERP.AMOUNT_ENTERED_DR AS AMOUNT_ENTERED_DR
, ERP.AMOUNT AS PAYABLE_AMOUNT
, 'BANK 7' AS SCENARIO
, 'BANK' AS PAYMENT_METHOD
, CASE WHEN BTR.MULTI_SCHEME_ID IS NULL AND ERP.MULTI_SCHEME_ID IS NOT NULL THEN 'Exist in PAYABLE, not exist in BANK STATEMENT' WHEN BTR.MULTI_SCHEME_ID IS NOT NULL AND ERP.MULTI_SCHEME_ID IS NULL THEN 'Exist in BANK STATEMENT, not exist in PAYABLE' WHEN BTR.MULTI_SCHEME_ID IS NOT NULL AND ERP.MULTI_SCHEME_ID IS NOT NULL THEN 'Reconciled' ELSE 'N/A' END AS RECONCILIATION_FLAG
, SYSDATE() AS INSERT_DATE_UTC
FROM (
    SELECT
    *
    FROM {{ ref('BTR') }} AS B
    WHERE (
        B.TYPE_CODE IN (195)
        OR (B.TYPE_CODE IN (169) AND B.MULTI_SCHEME_ID IN (10000, 10001))
        OR (B.TYPE_CODE IN (169) AND B.MULTI_SCHEME_ID IN (100020001) AND NOT(B.NARRATIVE LIKE ANY ('%WESTPAC%', '%WORKING CAPITAL%')))
    )
    AND NVL(LEFT(B.BANK_REF_NUM, 1), 'A') NOT IN ('1', '2')
    AND B.ACCOUNTING_DATE_KEY >= TO_CHAR(ADD_MONTHS(SYSDATE(), -6), 'YYYYMMDD')
) BTR
FULL OUTER JOIN (
    SELECT
    DECODE(J.LEDGER_NAME, 'Processor QLD Ledger AU', 10000, 'Processor WA Ledger AU', 10001, 'Scheme VIC NOP Ledger', 100020001) AS MULTI_SCHEME_ID
    , SCHEME.NAME AS SCHEME
    , TO_DATE(SPLIT_PART(J.JOURNAL_LINE_DESC, ' - ', 2), 'DD/MM/YYYY') AS ACCOUNTING_DATE
    , TO_CHAR(TO_DATE(SPLIT_PART(J.JOURNAL_LINE_DESC, ' - ', 2), 'DD/MM/YYYY'), 'YYYYMMDD') AS ACCOUNTING_DATE_KEY
    , J.ACCOUNT_CODE
    , NULL AS BTR_AMOUNT
    , J.AMOUNT_CR AS AMOUNT_CR
    , J.AMOUNT_DR AS AMOUNT_DR
    , J.AMOUNT_ENTERED_CR AS AMOUNT_ENTERED_CR
    , J.AMOUNT_ENTERED_DR AS AMOUNT_ENTERED_DR
    , ROUND(NVL(J.AMOUNT_DR, 0) - NVL(J.AMOUNT_CR, 0), 2) AS AMOUNT
    FROM {{ source('CES_ERP', 'GL_JOURNALS') }} AS J
    LEFT JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
    ON DECODE(J.LEDGER_NAME, 'Processor QLD Ledger AU', 10000, 'Processor WA Ledger AU', 10001, 'Scheme VIC NOP Ledger', 100020001) = SCHEME.MULTI_SCHEME_ID
    LEFT JOIN {{ source('CES_FINANCE', 'BANK_REC_BANK_7_GROUPING') }} AS G
    ON DECODE(J.LEDGER_NAME, 'Processor QLD Ledger AU', 10000, 'Processor WA Ledger AU', 10001, 'Scheme VIC NOP Ledger', 100020001) = G.MULTI_SCHEME_ID
    AND TO_CHAR(TO_DATE(SPLIT_PART(J.JOURNAL_LINE_DESC, ' - ', 2), 'DD/MM/YYYY'), 'YYYYMMDD') = G.ACCOUNTING_DATE_KEY_YYYYMMDD
    AND ROUND(NVL(J.AMOUNT_DR, 0) - NVL(J.AMOUNT_CR, 0), 2) = G.JOURNAL_AMOUNT
    WHERE J.LEDGER_NAME IN ('Processor QLD Ledger AU', 'Processor WA Ledger AU', 'Scheme VIC NOP Ledger')
    AND (UPPER(J.JOURNAL_NAME) LIKE ANY ('%RETURN PAYMENT%') OR UPPER(J.JOURNAL_LINE_DESC) LIKE ANY ('%RETURN PAYMENT%'))
    AND J.SOURCE_JOURNAL_SOURCE_NAME = 'Spreadsheet'
    AND CASE WHEN J.LEDGER_NAME = 'Scheme VIC NOP Ledger' THEN J.ACCOUNT_CODE = 10020 ELSE J.ACCOUNT_CODE = 10025 END
    AND TO_CHAR(J.ACCOUNTING_DATE, 'YYYYMMDD') >= TO_CHAR(ADD_MONTHS(SYSDATE(), -6), 'YYYYMMDD')
    AND G.MULTI_SCHEME_ID IS NULL
 
    UNION ALL
 
    SELECT
    G.MULTI_SCHEME_ID
    , SCHEME.NAME AS SCHEME
    , TO_DATE(CAST(G.ACCOUNTING_DATE_KEY_YYYYMMDD AS STRING), 'YYYYMMDD') AS ACCOUNTING_DATE
    , G.ACCOUNTING_DATE_KEY_YYYYMMDD AS ACCOUNTING_DATE_KEY
    , CASE WHEN G.MULTI_SCHEME_ID = 100020001 THEN 10020 ELSE 10025 END ACCOUNT_CODE
    , G.BTR_AMOUNT AS BTR_AMOUNT
    , NULL AS AMOUNT_CR
    , CAST(SUM(G.JOURNAL_AMOUNT) AS NUMBER(38, 2)) AS AMOUNT_DR
    , NULL AS AMOUNT_ENTERED_CR
    , CAST(SUM(G.JOURNAL_AMOUNT) AS NUMBER(38, 2)) AS AMOUNT_ENTERED_DR
    , CAST(SUM(G.JOURNAL_AMOUNT) AS NUMBER(38, 2)) AS AMOUNT
    FROM {{ source('CES_FINANCE', 'BANK_REC_BANK_7_GROUPING') }} AS G
    LEFT JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
    ON G.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
    GROUP BY ALL
 
    UNION ALL
 
    SELECT
    J.MULTI_SCHEME_ID
    , SCHEME.NAME AS SCHEME
    , DATE(J.ACCOUNTING_DATE_KEY_YYYYMMDD, 'YYYYMMDD') AS ACCOUNTING_DATE
    , J.ACCOUNTING_DATE_KEY_YYYYMMDD AS ACCOUNTING_DATE_KEY
    , J.ACCOUNT_CODE
    , NULL AS BTR_AMOUNT
    , SUM(J.AMOUNT_CR) AS AMOUNT_CR
    , SUM(J.AMOUNT_DR) AS AMOUNT_DR
    , NULL AS AMOUNT_ENTERED_CR
    , NULL AS AMOUNT_ENTERED_DR
    , NVL(SUM(J.AMOUNT_CR), 0) - NVL(SUM(J.AMOUNT_DR), 0) AS AMOUNT
    FROM {{ source('CES_FINANCE', 'JOURNALS_BANK_7') }} AS J
    LEFT JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
    ON J.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
    GROUP BY ALL
    HAVING AMOUNT <> 0
) ERP
ON BTR.ACCOUNTING_DATE_KEY = ERP.ACCOUNTING_DATE_KEY
AND ROUND(BTR.AMOUNT, 2) = ROUND(ERP.AMOUNT, 2)
AND BTR.MULTI_SCHEME_ID = ERP.MULTI_SCHEME_ID