SELECT
DECODE(S.LEDGER_ID, '300000001407023', 10000,  '300000035198785', 10001, '300000126421633', 100020001) AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, 20 || SPLIT_PART(S.PERIOD_NAME, '-', 2) || DECODE(SPLIT_PART(S.PERIOD_NAME, '-', 1), 'Jan', '01', 'Feb', '02', 'Mar', '03', 'Apr', '04', 'May', '05', 'Jun', '06', 'Jul', '07', 'Aug', '08', 'Sep', '09', 'Oct', '10', 'Nov', '11', 'Dec', '12') AS YEAR_MONTH
, SCHEME.MULTI_SCHEME_ID || '-' || YEAR_MONTH AS ID
, S.PERIOD_NAME AS PERIOD_NAME
, S.LAST_UPDATED_BY AS LAST_UPDATED_BY
, CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, CASE WHEN LAG(S.CLOSING_STATUS, 1) OVER (PARTITION BY SCHEME.MULTI_SCHEME_ID ORDER BY YEAR_MONTH) = 'O' THEN SYSDATE() ELSE LAG(CAST(S.LAST_UPDATE_DATE AS TIMESTAMP_NTZ), 1) OVER (PARTITION BY SCHEME.MULTI_SCHEME_ID ORDER BY YEAR_MONTH) END) AS PERIOD_START_DATE
, CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, CASE WHEN CLOSING_STATUS = 'O' THEN SYSDATE() ELSE CAST(LAST_UPDATE_DATE AS TIMESTAMP_NTZ) END) AS PERIOD_END_DATE
, S.CLOSING_STATUS AS CLOSING_STATUS
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_ERP_FSCM_FINGLCALACC', 'PERIOD_STATUS_PVO') }} AS S
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON DECODE(S.LEDGER_ID, '300000001407023', 10000,  '300000035198785', 10001, '300000126421633', 100020001) = SCHEME.MULTI_SCHEME_ID
WHERE S.LEDGER_ID IN ('300000001407023', '300000035198785', '300000126421633')
AND S.APPLICATION_PEOAPPLICATION_NAME = 'Payables'
AND S.CLOSING_STATUS IN ('C', 'O')