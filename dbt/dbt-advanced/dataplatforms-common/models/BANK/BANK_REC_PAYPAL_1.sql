SELECT
NVL(PAYPAL.MULTI_SCHEME_ID, P.MULTI_SCHEME_ID) AS MULTI_SCHEME_ID
, NVL(PAYPAL.SCHEME, P.SCHEME) AS SCHEME
, NVL(PAYPAL.MULTI_SCHEME_ID, P.MULTI_SCHEME_ID) || '-' || NVL(PAYPAL.TRANSACTION_COMPLETION_DATE_KEY, P.PAYMENT_DATE_KEY) || '-' || NVL(PAYPAL.GROSS_TRANSACTION_AMOUNT, P.AMOUNT) AS ID
, NVL(PAYPAL.PAY_REF_NUMBER, P.PAY_REF_NUMBER) AS PAY_REF_NUMBER
, NVL(PAYPAL.TRANSACTION_COMPLETION_DATE_KEY, P.PAYMENT_DATE_KEY) AS REPORTING_DATE_KEY
, PAYPAL.TRANSACTION_COMPLETION_DATE AS TRANSACTION_COMPLETION_DATE
, PAYPAL.TRANSACTION_COMPLETION_DATE_KEY AS TRANSACTION_COMPLETION_DATE_KEY
, PAYPAL.TRANSACTION_EVENT_CODE AS TRANSACTION_EVENT_CODE
, PAYPAL.PAY_REF_NUMBER AS PAYPAL_PAY_REF_NUMBER
, PAYPAL.CURRENCY AS CURRENCY
, PAYPAL.GROSS_TRANSACTION_AMOUNT AS PAYPAL_AMOUNT
, P.PAY_REF_NUMBER AS PAYABLE_PAY_REF_NUMBER
, P.POS_TXN_NUM AS POS_TXN_NUM
, P.PAYMENT_DATE AS PAYMENT_DATE
, P.PAYMENT_DATE_KEY AS PAYMENT_DATE_KEY
, P.AMOUNT AS PAYABLE_AMOUNT
, 'PAYPAL 1' AS SCENARIO
, 'PAYPAL' AS PAYMENT_METHOD
, CASE WHEN PAYPAL.MULTI_SCHEME_ID IS NULL AND P.MULTI_SCHEME_ID IS NOT NULL THEN 'Exist in PAYABLE, not exist in BANK STATEMENT' WHEN PAYPAL.MULTI_SCHEME_ID IS NOT NULL AND P.MULTI_SCHEME_ID IS NULL THEN 'Exist in BANK STATEMENT, not exist in PAYABLE' WHEN PAYPAL.MULTI_SCHEME_ID IS NOT NULL AND P.MULTI_SCHEME_ID IS NOT NULL THEN 'Reconciled' ELSE 'N/A' END AS RECONCILIATION_FLAG
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ ref('PAYPAL_SETTLEMENT') }} AS PAYPAL
FULL OUTER JOIN (
    SELECT
    F.MULTI_SCHEME_ID
    , F.SCHEME
    , F.ID
    , CAST(F.PAY_REF_NUMBER AS STRING) AS PAY_REF_NUMBER
    , F.POS_TXN_NUM
    , F.PAID_DATE AS PAYMENT_DATE
    , F.PAID_DATE_KEY AS PAYMENT_DATE_KEY
    , SUM(F.GROSS_AMOUNT) AS AMOUNT
    FROM {{ ref('FIN_RTP') }} AS F
    WHERE F.PAYMENT_STATUS = 'PAID'
    AND F.PAYMENT_METHOD = 'PAYPAL'
    AND F.PAID_DATE_KEY >= TO_CHAR(ADD_MONTHS(SYSDATE(), -6), 'YYYYMMDD')
    GROUP BY ALL
) P
ON PAYPAL.PAY_REF_NUMBER = CAST(P.PAY_REF_NUMBER AS STRING)
AND ROUND(PAYPAL.GROSS_TRANSACTION_AMOUNT, 2) = ROUND(P.AMOUNT, 2)
WHERE PAYPAL.TRANSACTION_EVENT_CODE = 'T0001'
AND PAYPAL.TRANSACTION_COMPLETION_DATE_KEY >= TO_CHAR(ADD_MONTHS(SYSDATE(), -6), 'YYYYMMDD')