, A.ACCOUNTING_DATE_KEY AS ACCOUNTING_DATE_KEY
, A.INVOICE_DATE AS INVOICE_DATE
, A.INVOICE_DATE_KEY AS INVOICE_DATE_KEY
, A.CURRENCY AS CURRENCY
, CAST(A.AMOUNT_DR AS NUMBER(38, 2)) AS AMOUNT_DR
, 0 AS AMOUNT_CR
, A.SUPPLIER_NUMBER AS SUPPLIER_NUMBER
, A.SITE_NUMBER AS SITE_NUMBER
, A.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID
, A.PAY_REF_NUMBER AS PAY_REF_NUMBER
, A.ORIGINAL_PAY_REF_NUMBER AS ORIGINAL_PAY_REF_NUMBER
, A.INVOICE_NUMBER_AND_STATUS AS INVOICE_NUMBER_AND_STATUS
, A.INVOICE_PAYMENT_FLAG AS INVOICE_PAYMENT_FLAG
, 'DR' AS AMOUNT_TYPE
, A.SCENARIO AS SCENARIO
, A.SCHEME || ' - ' ||
TO_CHAR(A.ACCOUNTING_DATE, 'YYYY-MM') || ' - ' ||
A.INVOICE_PAYMENT_FLAG || ' - ' ||
CASE A.SCENARIO 
    WHEN 'BANK 1 INVOICE' THEN 'BANK - successful payment (consumer)'
    WHEN 'BANK 1 PAYMENT' THEN 'BANK - successful payment (consumer)'
    WHEN 'BANK 3 PAYMENT' THEN 'BANK - dishonoured payment'
    WHEN 'BANK 7 INVOICE' THEN 'BANK - return payment (consumer)'
    WHEN 'BANK 7 PAYMENT' THEN 'BANK - return payment (consumer)'
    WHEN 'PAYPAL 1 INVOICE' THEN 'PAYPAL - successful payment (consumer)'
    WHEN 'PAYPAL 1 PAYMENT' THEN 'PAYPAL - successful payment (consumer)'
END AS DESCRIPTION_SUMMARY
, A.SCHEME || ' - ' ||
TO_CHAR(A.ACCOUNTING_DATE, 'DD/MM/YYYY') || ' - ' ||
A.INVOICE_PAYMENT_FLAG || ' - ' ||
CASE A.SCENARIO 
    WHEN 'BANK 1 INVOICE' THEN 'BANK - successful payment (consumer)'
    WHEN 'BANK 1 PAYMENT' THEN 'BANK - successful payment (consumer)'
    WHEN 'BANK 3 PAYMENT' THEN 'BANK - dishonoured payment'
    WHEN 'BANK 7 INVOICE' THEN 'BANK - return payment (consumer)'
    WHEN 'BANK 7 PAYMENT' THEN 'BANK - return payment (consumer)'
    WHEN 'PAYPAL 1 INVOICE' THEN 'PAYPAL - successful payment (consumer)'
    WHEN 'PAYPAL 1 PAYMENT' THEN 'PAYPAL - successful payment (consumer)'
END || ' - ' ||
CASE WHEN A.INVOICE_PAYMENT_FLAG = 'INVOICE' THEN '' WHEN A.INVOICE_PAYMENT_FLAG = 'PAYMENT' THEN TO_CHAR(CAST(NVL(A.PAY_REF_NUMBER, A.ORIGINAL_PAY_REF_NUMBER) AS NUMBER)) END AS DESCRIPTION_DETAILS
, A.KAFKA_DATE AS KAFKA_DATE
, A.KAFKA_TIME_KEY AS KAFKA_TIME_KEY
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ ref('ACCOUNTING_BASE') }} AS A
WHERE NVL(A.AMOUNT_DR, 0) <> 0
OR (
    SCENARIO = 'BANK 7 INVOICE'
    AND NVL(A.AMOUNT_DR, 0) = 0
    AND NVL(A.AMOUNT_CR, 0) = 0
    AND A.ACCOUNT_CODE = 14930
)
 
