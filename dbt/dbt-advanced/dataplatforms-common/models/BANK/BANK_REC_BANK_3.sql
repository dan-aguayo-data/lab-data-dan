SELECT
NVL(RTI.MULTI_SCHEME_ID, ERP.MULTI_SCHEME_ID) AS MULTI_SCHEME_ID
, NVL(RTI.SCHEME, ERP.SCHEME) AS SCHEME
, NVL(RTI.MULTI_SCHEME_ID, ERP.MULTI_SCHEME_ID) || '-' || NVL(RTI.ACCOUNTING_DATE_KEY, ERP.ACCOUNTING_DATE_KEY) || '-' || NVL(RTI.AMOUNT, ERP.AMOUNT) AS ID
, NVL(RTI.ACCOUNTING_DATE_KEY, ERP.ACCOUNTING_DATE_KEY) AS REPORTING_DATE_KEY
, RTI.ID AS RTI_ID
, RTI.ACCOUNTING_DATE AS ACCOUNTING_DATE
, RTI.ACCOUNTING_DATE_KEY AS ACCOUNTING_DATE_KEY
, RTI.FILE_NAME AS FILE_NAME
, RTI.FILE_ROW_NUMBER AS FILE_ROW_NUMBER
, RTI.CURRENCY AS CURRENCY
, RTI.AMOUNT AS RTI_AMOUNT
, RTI.RETURN_REASON AS RETURN_REASON
, RTI.ORIGINAL_PAID_DATE AS ORIGINAL_PAID_DATE
, RTI.ORIGINAL_PAY_REF_NUMBER AS ORIGINAL_PAY_REF_NUMBER
, RTI.TYPE_CODE AS TYPE_CODE
, ERP.ACCOUNTING_DATE AS PAYABLE_ACCOUNTING_DATE
, ERP.ACCOUNTING_DATE_KEY AS PAYABLE_ACCOUNTING_DATE_KEY
, ERP.ACCOUNT_CODE AS ACCOUNT_CODE
, ERP.AMOUNT_CR AS AMOUNT_CR
, ERP.AMOUNT_DR AS AMOUNT_DR
, ERP.AMOUNT_ENTERED_CR AS AMOUNT_ENTERED_CR
, ERP.AMOUNT_ENTERED_DR AS AMOUNT_ENTERED_DR
, ERP.AMOUNT AS PAYABLE_AMOUNT
, 'BANK 3' AS SCENARIO
, 'BANK' AS PAYMENT_METHOD
, CASE WHEN RTI.MULTI_SCHEME_ID IS NULL AND ERP.MULTI_SCHEME_ID IS NOT NULL THEN 'Exist in PAYABLE, not exist in BANK STATEMENT' WHEN RTI.MULTI_SCHEME_ID IS NOT NULL AND ERP.MULTI_SCHEME_ID IS NULL THEN 'Exist in BANK STATEMENT, not exist in PAYABLE' WHEN RTI.MULTI_SCHEME_ID IS NOT NULL AND ERP.MULTI_SCHEME_ID IS NOT NULL THEN 'Reconciled' ELSE 'N/A' END AS RECONCILIATION_FLAG
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ ref('RTI') }} AS RTI
FULL OUTER JOIN (
    SELECT
    DECODE(J.LEDGER_NAME, 'Processor QLD Ledger AU', 10000, 'Processor WA Ledger AU', 10001, 'Scheme VIC NOP Ledger', 100020001) AS MULTI_SCHEME_ID
    , SCHEME.NAME AS SCHEME
    , CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, CAST(J.ACCOUNTING_DATE AS TIMESTAMP)) AS ACCOUNTING_DATE
    , TO_CHAR(CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, CAST(J.ACCOUNTING_DATE AS TIMESTAMP)), 'YYYYMMDD') AS ACCOUNTING_DATE_KEY
    , J.ACCOUNT_CODE
    , TRIM(SPLIT_PART(J.JOURNAL_LINE_DESC, '-', -1)) AS ORIGINAL_PAY_REF_NUMBER
    , J.AMOUNT_CR AS AMOUNT_CR
    , J.AMOUNT_DR AS AMOUNT_DR
    , J.AMOUNT_ENTERED_CR AS AMOUNT_ENTERED_CR
    , J.AMOUNT_ENTERED_DR AS AMOUNT_ENTERED_DR
    , NVL(J.AMOUNT_DR, 0) - NVL(J.AMOUNT_CR, 0) AS AMOUNT
    FROM {{ source('CES_ERP', 'GL_JOURNALS') }} AS J
    LEFT JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
    ON DECODE(J.LEDGER_NAME, 'Processor QLD Ledger AU', 10000, 'Processor WA Ledger AU', 10001, 'Scheme VIC NOP Ledger', 100020001) = SCHEME.MULTI_SCHEME_ID
    WHERE J.LEDGER_NAME IN ('Processor QLD Ledger AU', 'Processor WA Ledger AU', 'Scheme VIC NOP Ledger')
    AND UPPER(J.JOURNAL_DESC) LIKE ANY ('%DISHONOUR%')
    AND UPPER(J.JOURNAL_DESC) LIKE ANY ('%POWER BI%')
    AND J.SOURCE_JOURNAL_SOURCE_NAME = 'Spreadsheet'
    AND CASE WHEN J.LEDGER_NAME = 'Scheme VIC NOP Ledger' THEN J.ACCOUNT_CODE = 10020 ELSE J.ACCOUNT_CODE = 10025 END
    AND TO_CHAR(J.ACCOUNTING_DATE, 'YYYYMMDD') >= TO_CHAR(ADD_MONTHS(SYSDATE(), -6), 'YYYYMMDD')
 
    UNION ALL
 
    SELECT
    J.MULTI_SCHEME_ID
    , SCHEME.NAME AS SCHEME
    , DATE(J.ACCOUNTING_DATE_KEY_YYYYMMDD, 'YYYYMMDD') AS ACCOUNTING_DATE
    , J.ACCOUNTING_DATE_KEY_YYYYMMDD AS ACCOUNTING_DATE_KEY
    , J.ACCOUNT_CODE
    , J.ORIGINAL_PAY_REF_NUMBER
    , SUM(J.AMOUNT_CR) AS AMOUNT_CR
    , SUM(J.AMOUNT_DR) AS AMOUNT_DR
    , NULL AS AMOUNT_ENTERED_CR
    , NULL AS AMOUNT_ENTERED_DR
    , NVL(SUM(J.AMOUNT_DR), 0) - NVL(SUM(J.AMOUNT_CR), 0) AS AMOUNT
    FROM {{ source('CES_FINANCE', 'JOURNALS_BANK_3') }} AS J
    LEFT JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
    ON J.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
    GROUP BY ALL
    HAVING AMOUNT <> 0
) ERP
ON RTI.ORIGINAL_PAY_REF_NUMBER = ERP.ORIGINAL_PAY_REF_NUMBER
AND ROUND(RTI.AMOUNT, 2) = ROUND(ERP.AMOUNT, 2)
WHERE NVL(RTI.ACCOUNTING_DATE_KEY, ERP.ACCOUNTING_DATE_KEY) >= TO_CHAR(ADD_MONTHS(SYSDATE(), -6), 'YYYYMMDD')