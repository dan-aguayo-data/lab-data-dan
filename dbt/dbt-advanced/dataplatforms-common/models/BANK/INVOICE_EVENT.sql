SELECT
H.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, L.INVOICE_LINE_ID AS INVOICE_LINE_ID
, H.INVOICE_NUM AS INVOICE_NUMBER
, CASE WHEN TO_CHAR(H.INVOICE_DATE, 'YYYYMM') = LEFT(F.PAID_DATE_KEY, 6) THEN H.INVOICE_DATE WHEN TO_CHAR(H.INVOICE_DATE, 'YYYYMM') = PP.YEAR_MONTH THEN H.INVOICE_DATE WHEN TO_CHAR(H.INVOICE_DATE, 'YYYYMM') < PP.YEAR_MONTH THEN TO_DATE(PP.YEAR_MONTH || '01', 'YYYYMMDD') ELSE NULL END AS ACCOUNTING_DATE
, CASE WHEN TO_CHAR(H.INVOICE_DATE, 'YYYYMM') = LEFT(F.PAID_DATE_KEY, 6) THEN TO_CHAR(H.INVOICE_DATE, 'YYYYMMDD') WHEN TO_CHAR(H.INVOICE_DATE, 'YYYYMM') = PP.YEAR_MONTH THEN TO_CHAR(H.INVOICE_DATE, 'YYYYMMDD') WHEN TO_CHAR(H.INVOICE_DATE, 'YYYYMM') < PP.YEAR_MONTH THEN PP.YEAR_MONTH || '01' ELSE NULL END AS ACCOUNTING_DATE_KEY
, H.LEGAL_ENTITY AS LEGAL_ENTITY
, H.PAY_GROUP AS PAY_GROUP
, CASE WHEN H.PAYMENT_METHOD = 'XX_DIRECT_PAY' THEN 'BANK' ELSE H.PAYMENT_METHOD END AS PAYMENT_METHOD
, H.INVOICE_DATE AS INVOICE_DATE
, TO_CHAR(H.INVOICE_DATE, 'YYYYMMDD') AS INVOICE_DATE_KEY
, H.INVOICE_CURRENCY AS CURRENCY
, H.INVOICE_AMOUNT AS INVOICE_AMOUNT
, H.PAYMENT_TERMS AS PAYMENT_TERMS
, H.SUPPLIER_NUMBER AS SUPPLIER_NUMBER
, H.SITE_NUMBER AS SITE_NUMBER
, H.PAYMENT_NUMBER AS PAYMENT_NUMBER
, H.POS_TRANSACTION_ID AS POS_TRANSACTION_ID
, L.COMPANY_CODE AS COMPANY_CODE
, L.MATERIAL_TYPE_CODE AS MATERIAL_TYPE_CODE
, L.COST_CENTRE_CODE AS COST_CENTRE_CODE
, L.ACCOUNT_CODE AS ACCOUNT_CODE
, L.INTERCOMPANY_CODE AS INTERCOMPANY_CODE
, L.SPARE_CODE AS SPARE_CODE
, L.DISTRIBUTION_COMBINATION AS DISTRIBUTION_COMBINATION
, L.POS_TRANSACTION_LINE_ID AS POS_TRANSACTION_LINE_ID
, L.LINE_NUMBER AS LINE_NUMBER
, M.ID AS MATERIAL_TYPE_ID
, L.POS_MATERIAL_TYPE AS POS_MATERIAL_TYPE
, CASE WHEN L.ACCOUNT_CODE = '14930' THEN - L.LINE_AMOUNT ELSE L.LINE_AMOUNT END AS LINE_AMOUNT
, CAST(CONVERT_TIMEZONE('UTC', 'Australia/Sydney', H.KAFKA_DATETIME) AS DATE) AS KAFKA_DATE
, TO_CHAR(CONVERT_TIMEZONE('UTC', 'Australia/Sydney', H.KAFKA_DATETIME), 'HHMISS') AS KAFKA_TIME_KEY
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM_KAFKA', 'INVOICINGEVENT_HEADER') }} AS H
INNER JOIN {{ source('CES_MSCM_KAFKA', 'INVOICINGEVENT_LINES') }} AS L
ON H.INVOICE_NUM = L.INVOICE_NUM
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON H.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS M
ON H.MULTI_SCHEME_ID = M.MULTI_SCHEME_ID
AND L.POS_MATERIAL_TYPE = M.NAME
LEFT JOIN (
    SELECT
    RTP.MULTI_SCHEME_ID
    , RTP.POS_TXN_NUM
    , MIN(NVL(RTP.INVOICED_DATE, RTP.PAID_DATE)) AS PAID_DATE
    , MIN(NVL(RTP.INVOICED_DATE_KEY, RTP.PAID_DATE_KEY)) AS PAID_DATE_KEY
    FROM {{ ref('FIN_RTP') }} AS RTP
    GROUP BY ALL
) F
ON H.MULTI_SCHEME_ID = F.MULTI_SCHEME_ID
AND H.POS_TRANSACTION_ID = F.POS_TXN_NUM
LEFT JOIN {{ ref('LEDGER_PERIOD') }} AS PP
ON F.MULTI_SCHEME_ID = PP.MULTI_SCHEME_ID
AND F.PAID_DATE > PP.PERIOD_START_DATE
AND F.PAID_DATE <= PP.PERIOD_END_DATE
WHERE NVL(L.POS_MATERIAL_TYPE, '-') <> 'Ineligible Containers'
 
UNION ALL
 
SELECT
I.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, CAST(L.AP_INVOICE_LINE_INT_ID AS STRING) AS INVOICE_LINE_ID
, I.INVOICE_NUMBER AS INVOICE_NUMBER
, CASE WHEN TO_CHAR(I.INVOICE_DATE, 'YYYYMM') = LEFT(F.PAID_DATE_KEY, 6) THEN I.INVOICE_DATE WHEN TO_CHAR(I.INVOICE_DATE, 'YYYYMM') = PP.YEAR_MONTH THEN I.INVOICE_DATE WHEN TO_CHAR(I.INVOICE_DATE, 'YYYYMM') < PP.YEAR_MONTH THEN TO_DATE(PP.YEAR_MONTH || '01', 'YYYYMMDD') ELSE NULL END AS ACCOUNTING_DATE
, CASE WHEN TO_CHAR(I.INVOICE_DATE, 'YYYYMM') = LEFT(F.PAID_DATE_KEY, 6) THEN TO_CHAR(I.INVOICE_DATE, 'YYYYMMDD') WHEN TO_CHAR(I.INVOICE_DATE, 'YYYYMM') = PP.YEAR_MONTH THEN TO_CHAR(I.INVOICE_DATE, 'YYYYMMDD') WHEN TO_CHAR(I.INVOICE_DATE, 'YYYYMM') < PP.YEAR_MONTH THEN PP.YEAR_MONTH || '01' ELSE NULL END AS ACCOUNTING_DATE_KEY
, I.LEGAL_ENTITY AS LEGAL_ENTITY
, I.PAY_GROUP AS PAY_GROUP
, CASE WHEN I.PAYMENT_METHOD = 'XX_DIRECT_PAY' THEN 'BANK' ELSE I.PAYMENT_METHOD END AS PAYMENT_METHOD
, I.INVOICE_DATE AS INVOICE_DATE
, TO_CHAR(I.INVOICE_DATE, 'YYYYMMDD') AS INVOICE_DATE_KEY
, I.INVOICE_CURRENCY AS CURRENCY
, I.INVOICE_AMOUNT AS INVOICE_AMOUNT
, I.PAYMENT_TERMS AS PAYMENT_TERMS
, I.SUPPLIER_NUMBER AS SUPPLIER_NUMBER
, I.SUPPLIER_SITE_NUMBER AS SITE_NUMBER
, I.ORIG_HEADER_ID AS PAYMENT_NUMBER
, I.ATTRIBUTE1 AS POS_TRANSACTION_ID
, SPLIT_PART(D.DIST_COMBINATION, '-' , 1) AS COMPANY_CODE
, SPLIT_PART(D.DIST_COMBINATION, '-' , 2) AS MATERIAL_TYPE_CODE
, SPLIT_PART(D.DIST_COMBINATION, '-' , 3) AS COST_CENTRE_CODE
, SPLIT_PART(D.DIST_COMBINATION, '-' , 4) AS ACCOUNT_CODE
, SPLIT_PART(D.DIST_COMBINATION, '-' , 5) AS INTERCOMPANY_CODE
, SPLIT_PART(D.DIST_COMBINATION, '-' , 6) AS SPARE_CODE
, D.DIST_COMBINATION AS DISTRIBUTION_COMBINATION
, L.ATTRIBUTE1 AS POS_TRANSACTION_LINE_ID
, L.LINE_NUMBER AS LINE_NUMBER
, M.ID AS MATERIAL_TYPE_ID
, L.ATTRIBUTE2 AS POS_MATERIAL_TYPE
, CASE WHEN SPLIT_PART(D.DIST_COMBINATION, '-' , 4) = '14930' THEN - L.AMOUNT ELSE L.AMOUNT END AS LINE_AMOUNT
, NULL AS KAFKA_DATE
, NULL AS KAFKA_TIME_KEY
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM', 'INV_AP_INVOICES_INT') }} AS I
INNER JOIN {{ source('CES_MSCM', 'INV_AP_INVOICE_LINES_INT') }} AS L
ON I.AP_INVOICE_INT_ID = L.AP_INVOICE_INT_ID
INNER JOIN {{ source('CES_MSCM', 'INV_AP_INVOICE_DIST_INT') }} AS D
ON L.AP_INVOICE_LINE_INT_ID = D.AP_INVOICE_LINE_INT_ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON I.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS M
ON L.MULTI_SCHEME_ID = M.MULTI_SCHEME_ID
AND L.ATTRIBUTE2 = M.NAME
LEFT JOIN (
    SELECT
    RTP.MULTI_SCHEME_ID
    , RTP.POS_TXN_NUM
    , MIN(NVL(RTP.INVOICED_DATE, RTP.PAID_DATE)) AS PAID_DATE
    , MIN(NVL(RTP.INVOICED_DATE_KEY, RTP.PAID_DATE_KEY)) AS PAID_DATE_KEY
    FROM {{ ref('FIN_RTP') }} AS RTP
    GROUP BY ALL
) F
ON I.MULTI_SCHEME_ID = F.MULTI_SCHEME_ID
AND I.ATTRIBUTE1 = F.POS_TXN_NUM
LEFT JOIN {{ ref('LEDGER_PERIOD') }} AS PP
ON F.MULTI_SCHEME_ID = PP.MULTI_SCHEME_ID
AND F.PAID_DATE > PP.PERIOD_START_DATE
AND F.PAID_DATE <= PP.PERIOD_END_DATE
WHERE I.INVOICE_NUMBER NOT IN (
    SELECT
    H.INVOICE_NUM
    FROM {{ source('CES_MSCM_KAFKA', 'INVOICINGEVENT_HEADER') }} AS H
)
AND NVL(L.ATTRIBUTE2, '-') <> 'Ineligible Containers'
AND TO_CHAR(I.INVOICE_DATE, 'YYYYMMDD') BETWEEN 20230701 AND 20240925