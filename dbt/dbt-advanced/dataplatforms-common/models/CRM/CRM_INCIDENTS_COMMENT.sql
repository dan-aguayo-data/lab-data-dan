WITH COMMENT AS (
SELECT
NVL(B.MULTI_SCHEME_ID, 0) AS MULTI_SCHEME_ID
, NVL(B.SCHEME, 'CES') AS SCHEME
, C.ID AS ID
, C.TICKET_ID || '' AS TICKET_ID
, U.NAME AS USER_NAME
, C.CREATED AS CREATED_ON_UTC
, CONVERT_TIMEZONE('UTC', 'Australia/Sydney', CAST(C.CREATED AS TIMESTAMP)) AS CREATED_ON
, CAST(CONVERT_TIMEZONE('UTC', 'Australia/Sydney', CAST(C.CREATED AS TIMESTAMP)) AS DATE) AS CREATED_DATE
, TO_CHAR(CONVERT_TIMEZONE('UTC', 'Australia/Sydney', CAST(C.CREATED AS TIMESTAMP)), 'YYYYMMDD') AS CREATED_DATE_KEY
, C.BODY AS BODY
, C.HTML_BODY AS HTML_BODY
, C.PLAIN_BODY AS PLAIN_BODY
, C.VIA_SOURCE_TO_NAME AS VIA_SOURCE_TO_NAME
, C.VIA_SOURCE_TO_ADDRESS AS VIA_SOURCE_TO_ADDRESS
, C.PUBLIC AS PUBLIC
, ROW_NUMBER() OVER (PARTITION BY C.TICKET_ID ORDER BY C.CREATED) AS RN
, CASE WHEN T.VIA_CHANNEL = 'voice' THEN 1 ELSE 0 END AS VOICE_FLAG
, CASE WHEN T.VIA_CHANNEL = 'voice' AND UPPER(SPLIT_PART(C.BODY, ' ', 1)) IN ('INBOUND', 'OUTBOUND') THEN 1 ELSE 0 END AS VOICE_INBOUND_OUTBOUND_FLAG
, CASE WHEN T.VIA_CHANNEL = 'voice' AND UPPER(SPLIT_PART(C.BODY, ' ', 1)) IN ('GHOST') THEN 1 ELSE 0 END AS VOICE_GHOST_FLAG
, CASE WHEN T.VIA_CHANNEL = 'voice' AND UPPER(SPLIT_PART(BODY, ' ', 1)) IN ('INBOUND', 'OUTBOUND') THEN SUBSTR(C.BODY, POSITION('Listen to the recording:', BODY) + 25) ELSE NULL END AS VOICE_RECORD_URL
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_ZENDESK', 'TICKET_COMMENT') }} AS C
LEFT JOIN {{ source('CES_ZENDESK', 'TICKET') }} AS T
ON C.TICKET_ID = T.ID
LEFT JOIN (
    SELECT
    BD.ID
    , BD.NAME
    , DECODE(BD.NAME, 'Containers for Change QLD', 10000, 'Containers for Change WA', 10001, 'CDS VIC', 10002, 'Return It', 100020001, 'TasRecycle', 10003, 'CES', -1, 'Circular Economy Systems', -1, 'Internal Help Centre', 0) AS MULTI_SCHEME_ID
    , DECODE(BD.NAME, 'Containers for Change QLD', 'QLD', 'Containers for Change WA', 'WA', 'CDS VIC', 'VIC', 'Return It', 'VIC-ReturnIT', 'TasRecycle', 'TAS', 'CES', 'CES', 'Circular Economy Systems', 'CES', 'Internal Help Centre', 'CES - INTERNAL') AS SCHEME
    FROM {{ source('CES_ZENDESK', 'BRAND') }} AS BD
) B
ON T.BRAND_ID = B.ID
LEFT JOIN {{ source('CES_ZENDESK', 'USER') }} AS U
ON C.USER_ID = U.ID
)
 
SELECT
C.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, C.SCHEME AS SCHEME
, C.ID AS ID
, C.TICKET_ID AS TICKET_ID
, C.USER_NAME AS USER_NAME
, C.CREATED_ON_UTC AS CREATED_ON_UTC
, C.CREATED_ON AS CREATED_ON
, C.CREATED_DATE AS CREATED_DATE
, C.CREATED_DATE_KEY AS CREATED_DATE_KEY
, C.BODY AS BODY
, C.HTML_BODY AS HTML_BODY
, C.PLAIN_BODY AS PLAIN_BODY
, C.VIA_SOURCE_TO_NAME AS VIA_SOURCE_TO_NAME
, C.VIA_SOURCE_TO_ADDRESS AS VIA_SOURCE_TO_ADDRESS
, C.PUBLIC AS PUBLIC
, C.RN AS RN
, C.VOICE_FLAG AS VOICE_FLAG
, C.VOICE_INBOUND_OUTBOUND_FLAG AS VOICE_INBOUND_OUTBOUND_FLAG
, C.VOICE_GHOST_FLAG AS VOICE_GHOST_FLAG
, CASE WHEN C.VOICE_FLAG = 1 THEN MIN(CASE WHEN C.VOICE_INBOUND_OUTBOUND_FLAG = 1 THEN RN ELSE NULL END) OVER (PARTITION BY C.TICKET_ID) ELSE NULL END AS VOICE_INBOUND_OUTBOUND_RN
, CASE WHEN C.VOICE_FLAG = 0 AND C.RN = 1 THEN 1 WHEN C.VOICE_FLAG = 1 AND CASE WHEN VOICE_INBOUND_OUTBOUND_RN = 2 THEN 3 WHEN VOICE_INBOUND_OUTBOUND_RN <> 2 THEN VOICE_INBOUND_OUTBOUND_RN - 1 ELSE NULL END = C.RN THEN 1 ELSE 0 END AS COMMENT_DESCRIPTION_FLAG
, C.VOICE_RECORD_URL AS VOICE_RECORD_URL
, C.INSERT_DATE_UTC AS INSERT_DATE_UTC
FROM
COMMENT C