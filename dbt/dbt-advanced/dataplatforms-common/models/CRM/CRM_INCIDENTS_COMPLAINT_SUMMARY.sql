SELECT
I.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, I.SCHEME AS SCHEME
, NULL AS ID
, PS.ATTRIBUTE5 AS ZONE
, LOWER(I.CHANNEL) AS CHANNEL
, I.FORM AS FORM
, 1 AS CUSOMER_TYPE
, 'M' AS PERIOD_TYPE
, LEFT(I.CREATED_DATE_KEY, 4) || '-' || SUBSTR(I.CREATED_DATE_KEY, 5, 2) AS PERIOD
, I.CREATED_DATE_KEY AS PERIOD_KEY
, COUNT(I.TICKET_ID) AS COUNT_OF_INCIDENTS
, COUNT(CASE WHEN I.STATUS = 'solved' THEN I.TICKET_ID ELSE NULL END) AS COUNT_OF_INCIDENTS_RESOLVED
, DATEDIFF(SECOND, I.CREATED_ON, I.RESPONSE_ON) AS AVG_TIME_TO_RESPOND_SEC
, DATEDIFF(SECOND, I.CREATED_ON, I.SOLVED_ON) AS AVG_TIME_TO_RESOLVE_SEC
, DATEDIFF(SECOND, I.CREATED_ON, I.RESPONSE_ON) / 3600 AS AVG_TIME_TO_RESPOND_HOUR
, DATEDIFF(SECOND, I.CREATED_ON, I.SOLVED_ON) / 3600 AS AVG_TIME_TO_RESOLVE_HOUR
, 'CES' AS SOURCE
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ ref('CRM_INCIDENTS') }} AS I
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS
ON I.RELATED_SITE_NUMBER = PS.SITE_NUMBER
WHERE I.IS_COMPLAINT = 'Yes'
GROUP BY ALL
 
UNION ALL
 
SELECT
DECODE(S.NOP_IDENTIFIER, 'VISY', 100020002, 'ReturnIT', 100020001, 'TCV', 100020003) AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, NULL AS ID
, 'ZONE_' || S.ZONE_ID AS ZONE
, DECODE(S.CHANNEL_TYPE, 'E', 'email', 'P', 'phone') AS CHANNEL
, S.CATEGORY_TYPE || '' AS FORM
, S.CUSTOMER_TYPE
, S.PERIOD_TYPE
, CASE WHEN S.PERIOD_TYPE = 'W' THEN RIGHT(S.PERIOD, 4) || '-' || LEFT (S.PERIOD, 2) ELSE S.PERIOD END AS PERIOD
, CASE WHEN S.PERIOD_TYPE = 'W' THEN P.KEY WHEN S.PERIOD_TYPE = 'M' THEN LEFT(S.PERIOD, 4) || RIGHT(S.PERIOD, 2) || '01' END AS PERIOD_KEY
, COUNT_OF_INTERACTIONS AS COUNT_OF_INCIDENTS
, COUNT_OF_INTERACTIONS_RESOLVED AS COUNT_OF_INCIDENTS_RESOLVED
, AVERAGE_TIME_TO_RESPOND AS AVG_TIME_TO_RESPOND_SEC
, AVERAGE_TIME_TO_RESOLVE AS AVG_TIME_TO_RESOLVE_SEC
, AVERAGE_TIME_TO_RESPOND / 3600 AS AVG_TIME_TO_RESPOND_HOUR
, AVERAGE_TIME_TO_RESOLVE / 3600 AS AVG_TIME_TO_RESOLVE_HOUR
, 'VIC' AS SOURCE
, SYSDATE() AS INSERT_DATE_UTC
FROM {{ source('VICRETURN_REF', 'COMPLAINT_SUMMARY') }} AS S
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON DECODE(S.NOP_IDENTIFIER, 'VISY', 100020002, 'ReturnIT', 100020001, 'TCV', 100020003) = SCHEME.MULTI_SCHEME_ID
LEFT JOIN (
    SELECT
    DT.DATE
    , DT.KEY
    , DT.YEAR_MONTH
    , DT.YEAR_WEEK_ISO
    FROM {{ ref('REF_DATE') }} AS DT
    WHERE DAY_OF_WEEK = 1
) P
ON CASE WHEN S.PERIOD_TYPE = 'W' THEN RIGHT(S.PERIOD, 4) || '-' || LEFT (S.PERIOD, 2) ELSE NULL END = P.YEAR_WEEK_ISO