LEFT JOIN {{ source('CES_ZENDESK', 'USER') }} AS U_C
ON T.REQUESTER_ID = U_C.ID
LEFT JOIN {{ source('CES_ZENDESK', 'ZENDESK_GROUP') }} AS G
ON T.GROUP_ID = G.ID
LEFT JOIN {{ ref('CRP_SITES') }} AS CRP
ON T.CUSTOM_MIGRATED_RELATED_SITE = CRP.SITE_NUMBER
LEFT JOIN (
    SELECT
    FORM.ID
    , FORM.NAME AS FORM_NAME
    , TRIM(LOWER(FORM.DISPLAY_NAME)) AS FORM_DISPLAY_NAME
    FROM {{ source('CES_ZENDESK', 'TICKET_FORM_HISTORY') }} AS FORM
    WHERE FORM.ACTIVE = 'TRUE'
    QUALIFY ROW_NUMBER() OVER (PARTITION BY ID ORDER BY UPDATED_AT DESC) = 1 --remove duplicates
) F
ON T.TICKET_FORM_ID = F.ID
LEFT JOIN (
    SELECT
    TC.TICKET_ID
    , CAST(CREATED AS TIMESTAMP) AS RESPONSE_ON_UTC
    FROM {{ source('CES_ZENDESK', 'TICKET_COMMENT') }} AS TC
    QUALIFY ROW_NUMBER() OVER (PARTITION BY TC.TICKET_ID ORDER BY TC.CREATED) = 1
) R --response on
ON T.ID = R.TICKET_ID
LEFT JOIN (
    SELECT
    F.TICKET_ID
    , CAST(F.UPDATED AS TIMESTAMP) AS UPDATED
    FROM {{ source('CES_ZENDESK', 'TICKET_FIELD_HISTORY') }} AS F
    WHERE F.FIELD_NAME = 'status'
    AND F.VALUE = 'solved'
    QUALIFY ROW_NUMBER() OVER (PARTITION BY F.TICKET_ID ORDER BY F.UPDATED DESC) = 1
) F_S
ON T.ID = F_S.TICKET_ID
LEFT JOIN (
    SELECT
    F.TICKET_ID
    , CAST(F.UPDATED AS TIMESTAMP) AS UPDATED
    FROM {{ source('CES_ZENDESK', 'TICKET_FIELD_HISTORY') }} AS F
    WHERE F.FIELD_NAME = 'status'
    AND F.VALUE = 'closed'
    QUALIFY ROW_NUMBER() OVER (PARTITION BY F.TICKET_ID ORDER BY F.UPDATED DESC) = 1
