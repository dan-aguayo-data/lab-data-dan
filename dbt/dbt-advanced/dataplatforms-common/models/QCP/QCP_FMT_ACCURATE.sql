SELECT
C.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, C.SCHEME AS SCHEME
, C.SUBMITTED_DATE_KEY AS CLAIM_SUBMITTED_DATE_KEY
, C.TRIP_LEG_ID AS TRIP_LEG_ID
, T.TRIP_ID AS TRIP_ID
, T.TRIP_TYPE AS TRIP_TYPE
, T.TRIP_STATUS AS TRIP_STATUS
, T.ACTUAL_START AS ACTUAL_START
, T.ACTUAL_END AS ACTUAL_END
, C.CHARGE_RATE AS CHARGE_RATE
, R.RATE AS RATE
, LSP.SITE_NAME AS ORGANISATION_NAME
, R.VEHICLE_TYPE AS VEHICLE_TYPE
, R.RATE_TYPE AS RATE_TYPE
, R.RATE - C.CHARGE_RATE AS RATE_VARIANCE_TO_CHARGE_RATE
, CASE WHEN R.RATE - C.CHARGE_RATE = 0 THEN 'Yes' ELSE 'No' END AS MEET_SLA
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ ref('FMT_CLAIM') }} AS C
LEFT JOIN {{ ref('FMT_TRIPS') }} AS T
ON C.TRIP_LEG_ID = T.TRIP_LEG_ID
LEFT JOIN {{ ref('FMT_VEHICLE_RATES') }} AS R
ON C.VEHICLE_RATE_ID = R.ID
LEFT JOIN {{ ref('LSP_SITES') }} AS LSP
ON R.SITE_NUMBER = LSP.SITE_NUMBER
WHERE C.CHARGE_TYPE <> 'Adjustment'