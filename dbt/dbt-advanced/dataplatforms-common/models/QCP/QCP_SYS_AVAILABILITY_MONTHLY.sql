SELECT
QCP.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, QCP.QCP_ID || '-' || YM.YEAR_MONTH || '-' || NVL(I.ID, '') AS ID
, QCP.QCP_ID AS QCP_ID
, YM.YEAR_MONTH AS YEAR_MONTH
, YM.YEAR_MONTH_START_KEY AS YEAR_MONTH_START_KEY
, I.ID AS INCIDENT_ID
, YM.NUMBER_OF_DAYS AS NUMBER_OF_DAYS
, YM.NUMBER_OF_DAYS * 24 AS TOTAL_HOURS
, YM.NUMBER_OF_DAYS * 86400 AS TOTAL_SECONDS
, CASE WHEN QCP.MULTI_SCHEME_ID = 10000 THEN YM.NUMBER_OF_WORKDAYS_QLD WHEN QCP.MULTI_SCHEME_ID = 10001 THEN YM.NUMBER_OF_WORKDAYS_WA WHEN QCP.MULTI_SCHEME_ID LIKE '10002%' THEN YM.NUMBER_OF_WORKDAYS_VIC END AS NUMBER_OF_WORKDAYS
, NUMBER_OF_WORKDAYS * 28800 AS WORK_SECONDS_8
, NUMBER_OF_WORKDAYS * 32400 AS WORK_SECONDS_9
, NUMBER_OF_WORKDAYS * 61200 AS WORK_SECONDS_17
, CASE WHEN QCP.MULTI_SCHEME_ID = 10000 THEN YM.NUMBER_OF_WEEKENDS_NON_HOLIDAY_QLD WHEN QCP.MULTI_SCHEME_ID = 10001 THEN YM.NUMBER_OF_WEEKENDS_NON_HOLIDAY_WA WHEN QCP.MULTI_SCHEME_ID LIKE '10002%' THEN YM.NUMBER_OF_WEEKENDS_NON_HOLIDAY_VIC END AS NUMBER_OF_WEEKENDS_NON_HOLIDAY
, NUMBER_OF_WEEKENDS_NON_HOLIDAY * 28800 AS WORK_SECONDS_8_WEEKEND_NON_HOLIDAY
, CASE WHEN QCP.MULTI_SCHEME_ID = 10000 THEN I.CREATED_ON_QLD WHEN QCP.MULTI_SCHEME_ID = 10001 THEN I.CREATED_ON_WA WHEN QCP.MULTI_SCHEME_ID LIKE '10002%' THEN I.CREATED_ON_VIC END AS CREATED_ON
, CASE WHEN QCP.MULTI_SCHEME_ID = 10000 THEN I.RESOLVED_ON_QLD WHEN QCP.MULTI_SCHEME_ID = 10001 THEN I.RESOLVED_ON_WA WHEN QCP.MULTI_SCHEME_ID LIKE '10002%' THEN I.RESOLVED_ON_VIC END AS RESOLVED_ON
, CASE WHEN QCP.MULTI_SCHEME_ID = 10000 THEN I.MONITORING_ON_QLD WHEN QCP.MULTI_SCHEME_ID = 10001 THEN I.MONITORING_ON_WA WHEN QCP.MULTI_SCHEME_ID LIKE '10002%' THEN I.MONITORING_ON_VIC END AS MONITORING_ON
, D_C.DAY_NAME AS CREATED_ON_DAY_NAME
, D_R.DAY_NAME AS RESOLVED_ON_DAY_NAME
, D_M.DAY_NAME AS MONITORING_ON_DAY_NAME
, CASE WHEN I.ID IS NULL THEN NULL ELSE GREATEST_IGNORE_NULLS(CAST(YM.YEAR_MONTH_START AS TIMESTAMP), CREATED_ON) END AS YM_CREATED_ON
, CASE WHEN I.ID IS NULL THEN NULL ELSE LEAST_IGNORE_NULLS(TIMEADD(SECOND, 86399, CAST(YM.YEAR_MONTH_END AS TIMESTAMP)), NVL(MONITORING_ON, RESOLVED_ON)) END AS YM_END_ON
, TIMEDIFF(SECOND, YM_CREATED_ON, YM_END_ON) AS INCIDENT_SECONDS
, CASE WHEN YM_CREATED_ON >= TIMEADD(HOUR, 17, DATE_TRUNC(DAY, YM_CREATED_ON)) THEN TIMEADD(HOUR, 9, DATEADD(DAY, 1, DATE_TRUNC(DAY, YM_CREATED_ON))) ELSE GREATEST(YM_CREATED_ON, TIMEADD(HOUR, 9, DATE_TRUNC(DAY, YM_CREATED_ON))) END AS YM_CREATED_ON_95
, CASE WHEN YM_END_ON <= TIMEADD(HOUR, 9, DATE_TRUNC(DAY, YM_END_ON)) THEN TIMEADD(HOUR, 17, DATEADD(DAY, -1, DATE_TRUNC(DAY, YM_END_ON))) ELSE LEAST(YM_END_ON, TIMEADD(HOUR, 17, DATE_TRUNC(DAY, YM_END_ON))) END AS YM_END_ON_95
, CASE WHEN QCP.MULTI_SCHEME_ID = 10000 THEN D_E_95.WORKDAYS_FROM_BEGINNING_QLD - D_C_95.WORKDAYS_FROM_BEGINNING_QLD - D_E_95.WORKDAY_FLAG_QLD WHEN QCP.MULTI_SCHEME_ID = 10001 THEN D_E_95.WORKDAYS_FROM_BEGINNING_WA - D_C_95.WORKDAYS_FROM_BEGINNING_WA - D_E_95.WORKDAY_FLAG_WA WHEN QCP.MULTI_SCHEME_ID LIKE '10002%' THEN D_E_95.WORKDAYS_FROM_BEGINNING_VIC - D_C_95.WORKDAYS_FROM_BEGINNING_VIC - D_E_95.WORKDAY_FLAG_VIC END AS INCIDENT_DAYS_BETWEEN_95
, DATEDIFF(SECOND, YM_CREATED_ON_95, TIMEADD(HOUR, 17, DATE_TRUNC(DAY, YM_CREATED_ON_95))) * (CASE WHEN QCP.MULTI_SCHEME_ID = 10000 THEN D_C_95.WORKDAY_FLAG_QLD WHEN QCP.MULTI_SCHEME_ID = 10001 THEN D_C_95.WORKDAY_FLAG_WA WHEN QCP.MULTI_SCHEME_ID LIKE '10002%' THEN D_C_95.WORKDAY_FLAG_VIC END) AS FIRST_DAY_SECONDS_95
, DATEDIFF(SECOND, TIMEADD(HOUR, 9, DATE_TRUNC(DAY, YM_END_ON_95)), YM_END_ON_95) * (CASE WHEN QCP.MULTI_SCHEME_ID = 10000 THEN D_E_95.WORKDAY_FLAG_QLD WHEN QCP.MULTI_SCHEME_ID = 10001 THEN D_E_95.WORKDAY_FLAG_WA WHEN QCP.MULTI_SCHEME_ID LIKE '10002%' THEN D_E_95.WORKDAY_FLAG_VIC END) AS LAST_DAY_SECONDS_95
, INCIDENT_DAYS_BETWEEN_95 * 28800 + FIRST_DAY_SECONDS_95 + LAST_DAY_SECONDS_95 AS INCIDENT_SECONDS_95
, CASE WHEN YM_CREATED_ON >= TIMEADD(HOUR, 17, DATE_TRUNC(DAY, YM_CREATED_ON)) THEN TIMEADD(HOUR, 8, DATEADD(DAY, 1, DATE_TRUNC(DAY, YM_CREATED_ON))) ELSE GREATEST(YM_CREATED_ON, TIMEADD(HOUR, 8, DATE_TRUNC(DAY, YM_CREATED_ON))) END AS YM_CREATED_ON_85
, CASE WHEN YM_END_ON <= TIMEADD(HOUR, 8, DATE_TRUNC(DAY, YM_END_ON)) THEN TIMEADD(HOUR, 17, DATEADD(DAY, -1, DATE_TRUNC(DAY, YM_END_ON))) ELSE LEAST(YM_END_ON, TIMEADD(HOUR, 17, DATE_TRUNC(DAY, YM_END_ON))) END AS YM_END_ON_85
, CASE WHEN QCP.MULTI_SCHEME_ID = 10000 THEN D_E_85.WORKDAYS_FROM_BEGINNING_QLD - D_C_85.WORKDAYS_FROM_BEGINNING_QLD - D_E_85.WORKDAY_FLAG_QLD WHEN QCP.MULTI_SCHEME_ID = 10001 THEN D_E_85.WORKDAYS_FROM_BEGINNING_WA - D_C_85.WORKDAYS_FROM_BEGINNING_WA - D_E_85.WORKDAY_FLAG_WA WHEN QCP.MULTI_SCHEME_ID LIKE '10002%' THEN D_E_85.WORKDAYS_FROM_BEGINNING_VIC - D_C_85.WORKDAYS_FROM_BEGINNING_VIC - D_E_85.WORKDAY_FLAG_VIC END AS INCIDENT_DAYS_BETWEEN_85
, DATEDIFF(SECOND, YM_CREATED_ON_85, TIMEADD(HOUR, 17, DATE_TRUNC(DAY, YM_CREATED_ON_85))) * (CASE WHEN QCP.MULTI_SCHEME_ID = 10000 THEN D_C_85.WORKDAY_FLAG_QLD WHEN QCP.MULTI_SCHEME_ID = 10001 THEN D_C_85.WORKDAY_FLAG_WA WHEN QCP.MULTI_SCHEME_ID LIKE '10002%' THEN D_C_85.WORKDAY_FLAG_VIC END) AS FIRST_DAY_SECONDS_85
, DATEDIFF(SECOND, TIMEADD(HOUR, 8, DATE_TRUNC(DAY, YM_END_ON_85)), YM_END_ON_85) * (CASE WHEN QCP.MULTI_SCHEME_ID = 10000 THEN D_E_85.WORKDAY_FLAG_QLD WHEN QCP.MULTI_SCHEME_ID = 10001 THEN D_E_85.WORKDAY_FLAG_WA WHEN QCP.MULTI_SCHEME_ID LIKE '10002%' THEN D_E_85.WORKDAY_FLAG_VIC END) AS LAST_DAY_SECONDS_85
, INCIDENT_DAYS_BETWEEN_85 * 28800 + FIRST_DAY_SECONDS_85 + LAST_DAY_SECONDS_85 AS INCIDENT_SECONDS_85
, CASE WHEN YM_CREATED_ON >= TIMEADD(HOUR, 20, DATE_TRUNC(DAY, YM_CREATED_ON)) THEN TIMEADD(HOUR, 5, DATEADD(DAY, 1, DATE_TRUNC(DAY, YM_CREATED_ON))) ELSE GREATEST(YM_CREATED_ON, TIMEADD(HOUR, 5, DATE_TRUNC(DAY, YM_CREATED_ON))) END AS YM_CREATED_ON_5X
, CASE WHEN YM_END_ON <= TIMEADD(HOUR, 5, DATE_TRUNC(DAY, YM_END_ON)) THEN TIMEADD(HOUR, 20, DATEADD(DAY, -1, DATE_TRUNC(DAY, YM_END_ON))) ELSE LEAST(YM_END_ON, TIMEADD(HOUR, 20, DATE_TRUNC(DAY, YM_END_ON))) END AS YM_END_ON_5X
, CASE WHEN QCP.MULTI_SCHEME_ID = 10000 THEN D_E_5X.WORKDAYS_FROM_BEGINNING_QLD - D_C_5X.WORKDAYS_FROM_BEGINNING_QLD - D_E_5X.WORKDAY_FLAG_QLD WHEN QCP.MULTI_SCHEME_ID = 10001 THEN D_E_5X.WORKDAYS_FROM_BEGINNING_WA - D_C_5X.WORKDAYS_FROM_BEGINNING_WA - D_E_5X.WORKDAY_FLAG_WA WHEN QCP.MULTI_SCHEME_ID LIKE '10002%' THEN D_E_5X.WORKDAYS_FROM_BEGINNING_VIC - D_C_5X.WORKDAYS_FROM_BEGINNING_VIC - D_E_5X.WORKDAY_FLAG_VIC END AS INCIDENT_DAYS_BETWEEN_5X
, DATEDIFF(SECOND, YM_CREATED_ON_5X, TIMEADD(HOUR, 20, DATE_TRUNC(DAY, YM_CREATED_ON_5X))) * (CASE WHEN QCP.MULTI_SCHEME_ID = 10000 THEN D_C_5X.WORKDAY_FLAG_QLD WHEN QCP.MULTI_SCHEME_ID = 10001 THEN D_C_5X.WORKDAY_FLAG_WA WHEN QCP.MULTI_SCHEME_ID LIKE '10002%' THEN D_C_5X.WORKDAY_FLAG_VIC END) AS FIRST_DAY_SECONDS_5X
, DATEDIFF(SECOND, TIMEADD(HOUR, 5, DATE_TRUNC(DAY, YM_END_ON_5X)), YM_END_ON_5X) * (CASE WHEN QCP.MULTI_SCHEME_ID = 10000 THEN D_E_5X.WORKDAY_FLAG_QLD WHEN QCP.MULTI_SCHEME_ID = 10001 THEN D_E_5X.WORKDAY_FLAG_WA WHEN QCP.MULTI_SCHEME_ID LIKE '10002%' THEN D_E_5X.WORKDAY_FLAG_VIC END) AS LAST_DAY_SECONDS_5X
, INCIDENT_DAYS_BETWEEN_5X * 28800 + FIRST_DAY_SECONDS_5X + LAST_DAY_SECONDS_5X AS INCIDENT_SECONDS_5X
, CASE WHEN QCP.MULTI_SCHEME_ID = 10000 THEN D_E_95.WEEKENDS_NON_HOLIDAY_FROM_BEGINNING_QLD - D_C_95.WEEKENDS_NON_HOLIDAY_FROM_BEGINNING_QLD - D_E_95.WEEKEND_NON_HOLIDAY_FLAG_QLD WHEN QCP.MULTI_SCHEME_ID = 10001 THEN D_E_95.WEEKENDS_NON_HOLIDAY_FROM_BEGINNING_WA - D_C_95.WEEKENDS_NON_HOLIDAY_FROM_BEGINNING_WA - D_E_95.WEEKEND_NON_HOLIDAY_FLAG_WA WHEN QCP.MULTI_SCHEME_ID LIKE '10002%' THEN D_E_95.WEEKENDS_NON_HOLIDAY_FROM_BEGINNING_VIC - D_C_95.WEEKENDS_NON_HOLIDAY_FROM_BEGINNING_VIC - D_E_95.WEEKEND_NON_HOLIDAY_FLAG_VIC END AS INCIDENT_DAYS_BETWEEN_95_WEEKEND_NON_HOLIDAY
, DATEDIFF(SECOND, YM_CREATED_ON_95, TIMEADD(HOUR, 17, DATE_TRUNC(DAY, YM_CREATED_ON_95))) * (CASE WHEN QCP.MULTI_SCHEME_ID = 10000 THEN D_C_95.WEEKEND_NON_HOLIDAY_FLAG_QLD WHEN QCP.MULTI_SCHEME_ID = 10001 THEN D_C_95.WEEKEND_NON_HOLIDAY_FLAG_WA WHEN QCP.MULTI_SCHEME_ID LIKE '10002%' THEN D_C_95.WEEKEND_NON_HOLIDAY_FLAG_VIC END) AS FIRST_DAY_SECONDS_95_WEEKEND_NON_HOLIDAY
, DATEDIFF(SECOND, TIMEADD(HOUR, 9, DATE_TRUNC(DAY, YM_END_ON_95)), YM_END_ON_95) * (CASE WHEN QCP.MULTI_SCHEME_ID = 10000 THEN D_E_95.WEEKEND_NON_HOLIDAY_FLAG_QLD WHEN QCP.MULTI_SCHEME_ID = 10001 THEN D_E_95.WEEKEND_NON_HOLIDAY_FLAG_WA WHEN QCP.MULTI_SCHEME_ID LIKE '10002%' THEN D_E_95.WEEKEND_NON_HOLIDAY_FLAG_VIC END) AS LAST_DAY_SECONDS_95_WEEKEND_NON_HOLIDAY
, INCIDENT_DAYS_BETWEEN_95_WEEKEND_NON_HOLIDAY * 28800 + FIRST_DAY_SECONDS_95_WEEKEND_NON_HOLIDAY + LAST_DAY_SECONDS_95_WEEKEND_NON_HOLIDAY AS INCIDENT_SECONDS_95_WEEKEND_NON_HOLIDAY
, NVL(I.CALCULATION_FLAG, 1) AS CALCULATION_FLAG
, QCP.CALCULATION_TYPE AS CALCULATION_TYPE
, CASE WHEN QCP.CALCULATION_TYPE = 'Business Day 9am to 5pm' THEN INCIDENT_SECONDS_95 WHEN QCP.CALCULATION_TYPE = 'Business Day 8am to 5pm' THEN INCIDENT_SECONDS_85 WHEN QCP.CALCULATION_TYPE = 'Business Day 5am to 10pm' THEN INCIDENT_SECONDS_5X WHEN QCP.CALCULATION_TYPE = 'All Day 24/7' THEN INCIDENT_SECONDS WHEN QCP.CALCULATION_TYPE = 'Weekend Non-holiday 9am to 5pm' THEN INCIDENT_SECONDS_95_WEEKEND_NON_HOLIDAY END AS INCIDENT_RATE_NUMERATOR
, CASE WHEN QCP.CALCULATION_TYPE = 'Business Day 9am to 5pm' THEN WORK_SECONDS_8 WHEN QCP.CALCULATION_TYPE = 'Business Day 8am to 5pm' THEN WORK_SECONDS_9 WHEN QCP.CALCULATION_TYPE = 'Business Day 5am to 10pm' THEN WORK_SECONDS_17 WHEN QCP.CALCULATION_TYPE = 'All Day 24/7' THEN TOTAL_SECONDS WHEN QCP.CALCULATION_TYPE = 'Weekend Non-holiday 9am to 5pm' THEN WORK_SECONDS_8_WEEKEND_NON_HOLIDAY END AS INCIDENT_RATE_DENOMINATOR
, DIV0NULL(INCIDENT_RATE_NUMERATOR, INCIDENT_RATE_DENOMINATOR) AS INCIDENT_RATE
, SYSDATE() AS INSERT_DATE_UTC
FROM (
    SELECT
    A.MULTI_SCHEME_ID
    , A.QCP_ID
    , A.CALCULATION_TYPE
    FROM VALUES 
        ('10000', 'QCP_017_QLD', 'Business Day 9am to 5pm'),
        ('10001', 'QCP_017_WA', 'Business Day 9am to 5pm'),
        ('10000', 'QCP_018_QLD', 'Business Day 9am to 5pm'),
        ('10001', 'QCP_018_WA', 'Business Day 9am to 5pm'),
        ('10002', 'QCP_018_VIC', 'Business Day 9am to 5pm'),
        ('10000', 'QCP_019_QLD', 'Business Day 9am to 5pm'),
        ('10001', 'QCP_019_WA', 'Business Day 9am to 5pm'),
        ('10000', 'QCP_020_QLD', 'All Day 24/7'),
        ('10001', 'QCP_020_WA', 'All Day 24/7'),
        ('10000', 'QCP_021_QLD', 'All Day 24/7'),
        ('10001', 'QCP_021_WA', 'All Day 24/7'),
        ('10000', 'QCP_022_QLD', 'Business Day 8am to 5pm'),
        ('10001', 'QCP_022_WA', 'Business Day 9am to 5pm'),
        ('10002', 'QCP_022_VIC', 'Business Day 9am to 5pm'),
        ('100020001', 'QCP_022_VIC-ReturnIT', 'Business Day 9am to 5pm'),
        ('10000', 'QCP_023_QLD', 'Business Day 8am to 5pm'),
        ('10001', 'QCP_023_WA', 'Business Day 9am to 5pm'),
        ('10002', 'QCP_023_VIC', 'Business Day 9am to 5pm'),
        ('100020001', 'QCP_023_VIC-ReturnIT', 'Business Day 9am to 5pm'),
        ('10000', 'QCP_024_QLD', 'Business Day 8am to 5pm'),
        ('10001', 'QCP_025_WA', 'Business Day 9am to 5pm'),
        ('10001', 'QCP_026_WA', 'Business Day 5am to 10pm'),
        ('10001', 'QCP_027_WA', 'Business Day 9am to 5pm'),
        ('10001', 'QCP_028_WA', 'Business Day 5am to 10pm'),
        ('10001', 'QCP_029_WA', 'Business Day 9am to 5pm'),
        ('10002', 'QCP_051_VIC', 'Business Day 9am to 5pm'),
        ('10002', 'QCP_052_VIC', 'Business Day 9am to 5pm'),
        ('10002', 'QCP_053_VIC', 'Business Day 9am to 5pm'),
        ('10002', 'QCP_054_VIC', 'Business Day 9am to 5pm'),
        ('10002', 'QCP_055_VIC', 'Business Day 9am to 5pm'),
        ('10002', 'QCP_056_VIC', 'Business Day 9am to 5pm'),
        ('100020001', 'QCP_056_VIC-ReturnIT', 'Business Day 9am to 5pm'),
        ('10002', 'QCP_057_VIC', 'Business Day 9am to 5pm'),
        ('10002', 'QCP_058_VIC', 'Business Day 9am to 5pm'),
        ('10002', 'QCP_059_VIC', 'Business Day 9am to 5pm'),
        ('10002', 'QCP_060_VIC', 'Business Day 9am to 5pm'),
        ('100020001', 'QCP_061_VIC-ReturnIT', 'Business Day 9am to 5pm'),
        ('100020001', 'QCP_062_VIC-ReturnIT', 'Business Day 9am to 5pm'),
        ('100020001', 'QCP_063_VIC-ReturnIT', 'Business Day 9am to 5pm'),
        ('100020001', 'QCP_064_VIC-ReturnIT', 'Business Day 9am to 5pm'),
        ('100020001', 'QCP_065_VIC-ReturnIT', 'Business Day 9am to 5pm'),
        ('100020001', 'QCP_066_VIC-ReturnIT', 'Business Day 9am to 5pm'),
        ('100020001', 'QCP_067_VIC-ReturnIT', 'Business Day 9am to 5pm'),
        ('100020001', 'QCP_068_VIC-ReturnIT', 'Weekend Non-holiday 9am to 5pm')
    AS A (MULTI_SCHEME_ID, QCP_ID, CALCULATION_TYPE)
) QCP
CROSS JOIN (
    SELECT
    D.YEAR_MONTH
    , MIN(D.KEY) AS YEAR_MONTH_START_KEY
    , MAX(D.KEY) AS YEAR_MONTH_END_KEY
    , MIN(D.DATE) AS YEAR_MONTH_START
    , MAX(D.DATE) AS YEAR_MONTH_END
    , COUNT(KEY) AS NUMBER_OF_DAYS
    , SUM(WORKDAY_FLAG_QLD) AS NUMBER_OF_WORKDAYS_QLD
    , SUM(WORKDAY_FLAG_WA) AS NUMBER_OF_WORKDAYS_WA
    , SUM(WORKDAY_FLAG_VIC) AS NUMBER_OF_WORKDAYS_VIC
    , SUM(WEEKEND_NON_HOLIDAY_FLAG_QLD) AS NUMBER_OF_WEEKENDS_NON_HOLIDAY_QLD
    , SUM(WEEKEND_NON_HOLIDAY_FLAG_WA) AS NUMBER_OF_WEEKENDS_NON_HOLIDAY_WA
    , SUM(WEEKEND_NON_HOLIDAY_FLAG_VIC) AS NUMBER_OF_WEEKENDS_NON_HOLIDAY_VIC
    FROM {{ ref('REF_DATE') }} AS D
    WHERE D.KEY >= 20240701
    AND DATE_TRUNC(MONTH, D.DATE) <= SYSDATE()
    GROUP BY ALL
) YM
LEFT JOIN (
    SELECT DISTINCT
    IQM.INCIDENT_ID
    , IQM.QCP_ID
    FROM {{ ref('QCP_SYS_AVAILABILITY_MAPPING') }} AS IQM
) M
ON QCP.QCP_ID = M.QCP_ID
LEFT JOIN {{ ref('QCP_SYS_AVAILABILITY_INCIDENT') }} AS I
ON M.INCIDENT_ID = I.ID
AND (
    CASE WHEN QCP.MULTI_SCHEME_ID = 10000 THEN TO_CHAR(I.CREATED_ON_QLD, 'YYYYMMDD') WHEN QCP.MULTI_SCHEME_ID = 10001 THEN TO_CHAR(I.CREATED_ON_WA, 'YYYYMMDD') WHEN QCP.MULTI_SCHEME_ID LIKE '10002%' THEN TO_CHAR(I.CREATED_ON_VIC, 'YYYYMMDD') END BETWEEN YM.YEAR_MONTH_START_KEY AND YM.YEAR_MONTH_END_KEY
    OR CASE WHEN QCP.MULTI_SCHEME_ID = 10000 THEN TO_CHAR(NVL(I.MONITORING_ON_QLD, I.RESOLVED_ON_QLD), 'YYYYMMDD') WHEN QCP.MULTI_SCHEME_ID = 10001 THEN TO_CHAR(NVL(I.MONITORING_ON_WA, I.RESOLVED_ON_WA), 'YYYYMMDD') WHEN QCP.MULTI_SCHEME_ID LIKE '10002%' THEN TO_CHAR(NVL(I.MONITORING_ON_VIC, I.RESOLVED_ON_VIC), 'YYYYMMDD') END BETWEEN YM.YEAR_MONTH_START_KEY AND YM.YEAR_MONTH_END_KEY
    )
INNER JOIN (
    SELECT S.MULTI_SCHEME_ID, S.NAME, S.TIMEZONE
    FROM {{ source('CES_MSCM', 'SCHEME') }} AS S
) SCHEME
ON QCP.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ ref('REF_DATE') }} AS D_C
ON TO_CHAR(CREATED_ON, 'YYYYMMDD') = D_C.KEY
LEFT JOIN {{ ref('REF_DATE') }} AS D_R
ON TO_CHAR(RESOLVED_ON, 'YYYYMMDD') = D_R.KEY
LEFT JOIN {{ ref('REF_DATE') }} AS D_M
ON TO_CHAR(MONITORING_ON, 'YYYYMMDD') = D_M.KEY
LEFT JOIN {{ ref('REF_DATE') }} AS D_C_95
ON TO_CHAR(YM_CREATED_ON_95, 'YYYYMMDD') = D_C_95.KEY
LEFT JOIN {{ ref('REF_DATE') }} AS D_E_95
ON TO_CHAR(YM_END_ON_95, 'YYYYMMDD') = D_E_95.KEY
LEFT JOIN {{ ref('REF_DATE') }} AS D_C_85
ON TO_CHAR(YM_CREATED_ON_85, 'YYYYMMDD') = D_C_85.KEY
LEFT JOIN {{ ref('REF_DATE') }} AS D_E_85
ON TO_CHAR(YM_END_ON_85, 'YYYYMMDD') = D_E_85.KEY
LEFT JOIN {{ ref('REF_DATE') }} AS D_C_5X
ON TO_CHAR(YM_CREATED_ON_5X, 'YYYYMMDD') = D_C_5X.KEY
LEFT JOIN {{ ref('REF_DATE') }} AS D_E_5X
ON TO_CHAR(YM_END_ON_5X, 'YYYYMMDD') = D_E_5X.KEY