SELECT
M.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, M.SCHEME AS SCHEME
, D.YEAR_QUARTER || '_QCP_009_' || M.SCHEME || '-' || M.PAY_GROUP AS ID
, 'QCP_009_' || M.SCHEME AS QCP_ID
, M.PAY_GROUP AS PAY_GROUP
, D.YEAR || CASE D.QUARTER WHEN 1 THEN '01' WHEN 2 THEN '04' WHEN 3 THEN '07' WHEN 4 THEN '10' END || '01' AS DATE_KEY
, SUM(CASE WHEN M.MEET_SLA = 'Yes' THEN 1 ELSE 0 END) + SUM(CASE WHEN M.MEET_SLA = 'No' THEN 1 ELSE 0 END) AS NUMBER_OF_TOTAL
, NVL(I.NUMBER_OF_INACCURATE, 0) AS NUMBER_OF_INACCURATE
, SUM(CASE WHEN M.MEET_SLA = 'Yes' THEN 1 ELSE 0 END) + SUM(CASE WHEN M.MEET_SLA = 'No' THEN 1 ELSE 0 END) - NVL(I.NUMBER_OF_INACCURATE, 0) AS NUMBER_OF_ACCURATE
, 1 - DIV0NULL(NVL(I.NUMBER_OF_INACCURATE, 0), SUM(CASE WHEN M.MEET_SLA IN ('Yes', 'No') THEN 1 ELSE 0 END)) AS SLA_ACTUAL
, I.COMMENT AS COMMENT
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ ref('QCP_AUCTION_INVOICE') }} AS M
LEFT JOIN {{ ref('REF_DATE') }} AS D
ON M.MANIFEST_DATE_KEY = D.KEY
LEFT JOIN {{ source('CES_FINANCE', 'QCP_INACCURATE') }} AS I
ON 'QCP_009_' || M.SCHEME = I.QCP_ID
AND M.PAY_GROUP = I.PAY_GROUP
AND D.YEAR || D.QUARTER = I.YEAR_QUARTER_YYYYQ
WHERE M.MEET_SLA IS NOT NULL
GROUP BY
M.MULTI_SCHEME_ID
, M.SCHEME
, D.YEAR_QUARTER || '_QCP_009_' || M.SCHEME || '-' || M.PAY_GROUP
, 'QCP_009_' || M.SCHEME
, M.PAY_GROUP
, D.YEAR || CASE D.QUARTER WHEN 1 THEN '01' WHEN 2 THEN '04' WHEN 3 THEN '07' WHEN 4 THEN '10' END || '01'
, I.NUMBER_OF_INACCURATE
, I.COMMENT
 
UNION ALL
 
