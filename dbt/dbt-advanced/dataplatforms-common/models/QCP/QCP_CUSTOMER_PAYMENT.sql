SELECT
P.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, P.SCHEME AS SCHEME
, P.PAID_DATE AS PAID_DATE
, P.PAID_DATE_KEY AS PAID_DATE_KEY
, P.CREATED_ON AS CREATED_ON
, P.PAYMENT_PERIOD AS PAYMENT_PERIOD
, TO_CHAR(P.PAYMENT_PERIOD, 'YYYYMMDD') AS PAYMENT_PERIOD_KEY
, P.PAYMENT_STATUS_VOID AS PAYMENT_STATUS_VOID
, P.APPROVAL_STATUS AS APPROVAL_STATUS
, P.VOID_STATUS AS VOID_STATUS
, NVL(O.NUMBER_OF_TRANSACTIONS, P.NUMBER_OF_TRANSACTIONS) AS NUMBER_OF_TRANSACTIONS
, NVL(CAST(REPLACE(O.PAYMENT_AMOUNT, ',') AS FLOAT), P.PAYMENT_AMOUNT) AS PAYMENT_AMOUNT
, CASE WHEN P.MULTI_SCHEME_ID = 10000 THEN D_P.WORKDAYS_FROM_BEGINNING_QLD - D_C.WORKDAYS_FROM_BEGINNING_QLD WHEN P.MULTI_SCHEME_ID = 10001 THEN D_P.WORKDAYS_FROM_BEGINNING_WA - D_C.WORKDAYS_FROM_BEGINNING_WA WHEN P.MULTI_SCHEME_ID LIKE '10002%' THEN D_P.WORKDAYS_FROM_BEGINNING_VIC - D_C.WORKDAYS_FROM_BEGINNING_VIC ELSE D_P.WORKDAYS_FROM_BEGINNING_NSW - D_C.WORKDAYS_FROM_BEGINNING_NSW END AS WORKDAYS_FROM_INVOICE_TO_PAYMENT
, NVL(O.MEET_SLA, CASE WHEN P.APPROVAL_STATUS = 'REJECTED' THEN NULL WHEN WORKDAYS_FROM_INVOICE_TO_PAYMENT <= 2 THEN 'Yes' WHEN WORKDAYS_FROM_INVOICE_TO_PAYMENT > 2 THEN 'No' WHEN P.PAID_DATE IS NULL THEN 'No' ELSE NULL END) AS MEET_SLA
, CASE WHEN O.MULTI_SCHEME_ID IS NOT NULL THEN 'Yes' ELSE 'No' END AS MEET_SLA_OVERWRITE_FLAG
, O.COMMENT AS MEET_SLA_OVERWRITE_COMMENT
, SYSDATE() AS INSERT_DATE_UTC
FROM (
    SELECT
    RTP.MULTI_SCHEME_ID
    , RTP.SCHEME
    , CAST(RTP.PAID_DATE AS DATE) AS PAID_DATE
    , RTP.PAID_DATE_KEY
    , CAST(NVL(K.APPROVED_ON, RTP.CREATED_ON) AS DATE) AS CREATED_ON
    , CAST(RTP.PAYMENT_PERIOD AS DATE) AS PAYMENT_PERIOD
    , RTP.PAYMENT_STATUS_VOID
    , K.APPROVAL_STATUS
    , RTP.VOID_STATUS
    , COUNT(DISTINCT RTP.ID) AS NUMBER_OF_TRANSACTIONS
    , SUM(RTP.GROSS_AMOUNT) AS PAYMENT_AMOUNT
    FROM (
        SELECT
        F.MULTI_SCHEME_ID
        , F.SCHEME
        , F.POS_TXN_NUM
        , F.MATERIAL_TYPE_ID
        , F.PAID_DATE
        , F.PAID_DATE_KEY
        , F.CREATED_ON
        , F.PAYMENT_PERIOD
        , F.PAYMENT_STATUS_VOID
        , F.VOID_STATUS
        , F.ID
        , F.GROSS_AMOUNT
        FROM {{ ref('FIN_RTP') }} AS F
        WHERE F.PYMT_AMOUNT_RECENT_FLAG = 1
    ) RTP
    LEFT JOIN (
        SELECT
        F.MULTI_SCHEME_ID
        , F.POS_TXN_NUM
        , F.MATERIAL_TYPE_ID
        , F.WF_RULES_PASSED
        , CASE WHEN F.WF_RULES_PASSED = 'FALSE' AND F.MULTI_SCHEME_ID = 100020001 THEN MIN(CASE WHEN F.APPROVAL_STATUS = 'APPROVED' THEN CONVERT_TIMEZONE('UTC', 'Australia/Melbourne', F.PERIOD) ELSE NULL END) OVER (PARTITION BY F.POS_TXN_NUM) ELSE NULL END AS APPROVED_ON
        , F.APPROVAL_STATUS
        FROM {{ ref('FIN_RTP_KAFKA') }} AS F
        WHERE F.PYMT_AMOUNT_RECENT_FLAG = 1
        AND F.RECIPIENT_TYPE <> 'SERVIC_PROVIDER'
    ) K
    ON RTP.MULTI_SCHEME_ID = K.MULTI_SCHEME_ID
    AND RTP.POS_TXN_NUM = K.POS_TXN_NUM
    AND RTP.MATERIAL_TYPE_ID = K.MATERIAL_TYPE_ID
    GROUP BY
    RTP.MULTI_SCHEME_ID
    , RTP.SCHEME
    , CAST(RTP.PAID_DATE AS DATE)
    , RTP.PAID_DATE_KEY
    , CAST(NVL(K.APPROVED_ON, RTP.CREATED_ON) AS DATE)
    , CAST(RTP.PAYMENT_PERIOD AS DATE)
    , RTP.PAYMENT_STATUS_VOID
    , K.APPROVAL_STATUS
    , RTP.VOID_STATUS
) P
LEFT JOIN {{ ref('REF_DATE') }} AS D_P
ON P.PAID_DATE_KEY = D_P.KEY
LEFT JOIN {{ ref('REF_DATE') }} AS D_C
ON TO_CHAR(P.CREATED_ON, 'YYYYMMDD') = D_C.KEY
LEFT JOIN {{ source('CES_FINANCE', 'QCP_SLA_OVERWRITE_CUSTOMER_PAYMENT') }} AS O
ON P.MULTI_SCHEME_ID = O.MULTI_SCHEME_ID
AND NVL(P.PAID_DATE_KEY, '-') = NVL(O.PAID_DATE_YYYYMMDD || '', '-')
AND NVL(TO_CHAR(P.CREATED_ON, 'YYYYMMDD'), '-') = NVL(O.CREATED_ON_YYYYMMDD || '', '-')
AND NVL(TO_CHAR(P.PAYMENT_PERIOD, 'YYYYMMDD'), '-') = NVL(O.PAYMENT_PERIOD_YYYYMMDD || '', '-')
AND P.PAYMENT_STATUS_VOID = O.PAYMENT_STATUS