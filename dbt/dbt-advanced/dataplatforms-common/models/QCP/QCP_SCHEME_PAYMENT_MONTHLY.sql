SELECT
M.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, M.SCHEME AS SCHEME
, D.YEAR_MONTH || '-' || M.SCHEME || '-' || 'EXPORTER' AS ID
, 'Exporter' AS CATEGORY
, 2 AS CATEGORY_ORDER
, REPLACE(D.YEAR_MONTH, '-') || '01' AS DATE_KEY
, M.PAY_GROUP AS PAY_GROUP
, SUM(CASE WHEN M.MEET_SLA = 'Yes' THEN 1 ELSE 0 END) AS NUMBER_OF_YES
, SUM(CASE WHEN M.MEET_SLA = 'No' THEN 1 ELSE 0 END) AS NUMBER_OF_NO
, SUM(CASE WHEN M.MEET_SLA = 'Yes' THEN 1 ELSE 0 END) + SUM(CASE WHEN M.MEET_SLA = 'No' THEN 1 ELSE 0 END) AS NUMBER_OF_TOTAL
, SUM(M.INVOICE_AMOUNT) AS INVOICE_AMOUNT
, SUM(M.PAYMENT_AMOUNT) AS PAYMENT_AMOUNT
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ ref('QCP_EXPORTER_PAYMENT') }} AS M
LEFT JOIN {{ ref('REF_DATE') }} AS D
ON M.INVOICE_DATE_KEY = D.KEY
WHERE M.MEET_SLA IS NOT NULL
GROUP BY ALL
 
UNION ALL
 
