SELECT
AM.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, AM.SCHEME AS SCHEME
, AM.MANIFEST_ID AS MANIFEST_ID
, AM.MANIFEST_WEIGHT_KG AS MANIFEST_WEIGHT_KG
, AM.LOT_ID AS LOT_ID
, AM.MANIFEST_DATE AS MANIFEST_DATE
, AM.MANIFEST_DATE_KEY AS MANIFEST_DATE_KEY
, AM.SELLER_ID AS SELLER_ID
, AM.SELLER_NAME AS SELLER_NAME
, AM.BUYER_ID AS BUYER_ID
, AM.BUYER_NAME AS BUYER_NAME
, AP.INVOICE_NUMBER AS INVOICE_NUMBER
, AP.INVOICE_DATE AS INVOICE_DATE
, AP.SUPPLIER_NAME AS SUPPLIER_NAME
, AP.SITE_NUMBER AS SITE_NUMBER
, AP.PAY_GROUP AS PAY_GROUP
, AP.INVOICE_AMOUNT AS INVOICE_AMOUNT
, AP.INVOICE_LINE_DESCRIPTION AS INVOICE_LINE_DESCRIPTION
, AP.INV_PAYMENT_TERMS AS INV_PAYMENT_TERMS
, CASE WHEN AM.MULTI_SCHEME_ID = 10000 THEN D_AP.WORKDAYS_FROM_BEGINNING_QLD - D_AM.WORKDAYS_FROM_BEGINNING_QLD WHEN AM.MULTI_SCHEME_ID = 10001 THEN D_AP.WORKDAYS_FROM_BEGINNING_WA - D_AM.WORKDAYS_FROM_BEGINNING_WA WHEN AM.MULTI_SCHEME_ID LIKE '10002%' THEN D_AP.WORKDAYS_FROM_BEGINNING_VIC - D_AM.WORKDAYS_FROM_BEGINNING_VIC ELSE D_AP.WORKDAYS_FROM_BEGINNING_NSW - D_AM.WORKDAYS_FROM_BEGINNING_NSW END AS WORKDAYS_TO_ISSUE_INVOICE
, NVL(O.MEET_SLA, CASE WHEN WORKDAYS_TO_ISSUE_INVOICE <=5 THEN 'Yes' WHEN WORKDAYS_TO_ISSUE_INVOICE > 5 THEN 'No' WHEN AP.INVOICE_NUMBER IS NULL THEN 'No' ELSE NULL END) AS MEET_SLA
, CASE WHEN O.MANIFEST_ID IS NOT NULL THEN 'Yes' ELSE 'No' END AS MEET_SLA_OVERWRITE_FLAG
, O.COMMENT AS MEET_SLA_OVERWRITE_COMMENT
, SYSDATE() AS INSERT_DATE_UTC
FROM (
    SELECT
    AMC.MULTI_SCHEME_ID
    , AMC.SCHEME
    , AMC.MANIFEST_ID
    , AMC.MANIFEST_WEIGHT_KG
    , AMC.LOT_ID
    , AMC.MANIFEST_DATE
    , AMC.MANIFEST_DATE_KEY
    , AMC.SELLER_ID
    , AMC.SELLER_NAME
    , AMC.BUYER_ID
    , AMC.BUYER_NAME
    FROM {{ ref('AUCTION_MANIFEST_CLEANSED') }} AS AMC
    WHERE AMC.MANIFEST_ID LIKE 'LM%'
) AM
LEFT JOIN (
    SELECT
    REGEXP_SUBSTR(AP.DISTRIBUTION_DESC, 'LM\\d+') AS MANIFEST_ID
    , AP.INVOICE_NUM AS INVOICE_NUMBER
    , AP.INVOICE_DATE
    , AP.SUPPLIER_NAME
    , AP.SUPPLIER_SITE_CODE AS SITE_NUMBER
    , AP.PAY_GROUP
    , AP.INVOICE_AMOUNT
    , AP.DISTRIBUTION_DESC AS INVOICE_LINE_DESCRIPTION
    , S.INV_PAYMENT_TERMS
    FROM {{ source('CES_ERP', 'AP_TRANSACTIONS') }} AS AP
    LEFT JOIN {{ ref('B2B_SITES') }} AS S
    ON AP.SUPPLIER_SITE_CODE = S.SITE_NUMBER
    WHERE AP.PAY_GROUP IN ('PROCESSOR AUCTION', 'MRF AUCTION', 'RECYCLER NEGATIVE AUCTION')
    AND AP.DISTRIBUTION_DESC LIKE '%Manifest ID%'
    QUALIFY ROW_NUMBER() OVER (PARTITION BY MANIFEST_ID, AP.INVOICE_NUM ORDER BY AP.DISTRIBUTION_LINE_NUM DESC) = 1
 
    UNION ALL
 
    SELECT
    MAX(REGEXP_SUBSTR(AR.LINE_DESC, 'LM\\d+')) AS MANIFEST_ID
    , AR.TRANSACTION_NUMBER AS INVOICE_NUMBER
    , CAST(AR.TRANSACTION_DATE AS DATE) AS INVOICE_DATE
    , AR.BILL_TO_CUST_ORG_NAME AS SUPPLIER_NAME
    , AR.BILL_TO_SITE_NUM AS SITE_NUMBER
    , AR.TRANSACTION_TYPE AS PAY_GROUP
    , SUM(AR.TRANSACTION_ACCOUNTED_AMT) AS INVOICE_AMOUNT
    , MAX(CASE WHEN REGEXP_SUBSTR(AR.LINE_DESC, 'LM\\d+') IS NOT NULL THEN AR.LINE_DESC ELSE NULL END) AS INVOICE_LINE_DESCRIPTION
    , AR.PAYMENT_TERM_NAME AS INV_PAYMENT_TERMS
    FROM {{ source('CES_ERP', 'AR_TRANSACTIONS_LINE_DTL') }} AS AR
    WHERE AR.ACCOUNTING_CALENDAR_NAME = 'Scheme Ledger'
    AND AR.ACCOUNTING_CLASS <> 'Exchange gain or loss'
    AND AR.TRANSACTION_TYPE IN (
        'Auction Neg MRF Cr',
        'Auction Neg MRF Inv',
        'Auction Processor Cr',
        'AuctionMRFRecyclr Cr',
        'AuctionMRFRecyclrInv',
        'AuctionPlatfomMRF Cr',
        'AuctionPlatfomMRFInv',
        'AuctionPrcRecyclr Cr',
        'AuctionPrcRecyclrInv',
        'AuctionProcessor Inv'
    )
    GROUP BY ALL
) AP
ON AM.MANIFEST_ID = AP.MANIFEST_ID
LEFT JOIN {{ ref('REF_DATE') }} AS D_AM
ON AM.MANIFEST_DATE_KEY = D_AM.KEY
LEFT JOIN {{ ref('REF_DATE') }} AS D_AP
ON TO_CHAR(INVOICE_DATE, 'YYYYMMDD') = D_AP.KEY
LEFT JOIN {{ source('CES_FINANCE', 'QCP_SLA_OVERWRITE_AUCTION_INVOICE') }} AS O
ON AM.MANIFEST_ID = O.MANIFEST_ID
AND NVL(AP.INVOICE_NUMBER, '-') = NVL(REPLACE(O.INVOICE_NUMBER, '"'), '-')