SELECT
SLA.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, SLA.QCP_ID AS QCP_ID
, SLA.QCP_ID_PARENT AS QCP_ID_PARENT
, SLA.CATEGORY AS CATEGORY
, TO_NUMBER(RIGHT(MIN(SLA.QCP_ID_PARENT) OVER (PARTITION BY SLA.CATEGORY), 3)) AS CATEGORY_ORDER
, SLA.QCP_NAME AS QCP_NAME
, SLA.SLA_ID AS SLA_ID
, SLA.SLA_DESC AS SLA_DESC
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_FINANCE', 'QCP_SLA') }} AS SLA
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON SLA.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID