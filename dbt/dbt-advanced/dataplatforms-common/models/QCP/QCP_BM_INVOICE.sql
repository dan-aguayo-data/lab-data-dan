SELECT
BM.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, BM.SCHEME AS SCHEME
, BM.TRANSACTION_NUMBER AS TRANSACTION_NUMBER
, BM.TRANSACTION_TYPE AS TRANSACTION_TYPE
, BM.TRANSACTION_DATE AS TRANSACTION_DATE
, TO_CHAR(BM.TRANSACTION_DATE, 'YYYYMMDD') AS TRANSACTION_DATE_KEY
, BM.BILL_TO_SITE_NUMBER AS BILL_TO_SITE_NUMBER
, BM.BU_NAME AS BU_NAME
, BM.TRANSACTION_ENTERED_AMOUNT AS TRANSACTION_ENTERED_AMOUNT
, CASE WHEN BM.MULTI_SCHEME_ID = 10000 THEN D_T.WORKDAYS_FROM_BEGINNING_QLD - D_I.WORKDAYS_FROM_BEGINNING_QLD WHEN BM.MULTI_SCHEME_ID = 10001 THEN D_T.WORKDAYS_FROM_BEGINNING_WA - D_I.WORKDAYS_FROM_BEGINNING_WA WHEN BM.MULTI_SCHEME_ID LIKE '10002%' THEN D_T.WORKDAYS_FROM_BEGINNING_VIC - D_I.WORKDAYS_FROM_BEGINNING_VIC WHEN BM.MULTI_SCHEME_ID LIKE '10003%' THEN D_T.WORKDAYS_FROM_BEGINNING_TAS - D_I.WORKDAYS_FROM_BEGINNING_TAS ELSE D_T.WORKDAYS_FROM_BEGINNING_NSW - D_I.WORKDAYS_FROM_BEGINNING_NSW END AS WORKDAYS_FROM_FIRST_DAY_OF_MONTH_TO_INVOICE
, NVL(O.MEET_SLA, CASE WHEN WORKDAYS_FROM_FIRST_DAY_OF_MONTH_TO_INVOICE <= 20 THEN 'Yes' WHEN WORKDAYS_FROM_FIRST_DAY_OF_MONTH_TO_INVOICE > 20 THEN 'No' ELSE NULL END) AS MEET_SLA
, CASE WHEN O.INVOICE_NUMBER IS NOT NULL THEN 'Yes' ELSE 'No' END AS MEET_SLA_OVERWRITE_FLAG
, O.COMMENT AS MEET_SLA_OVERWRITE_COMMENT
, SYSDATE() AS INSERT_DATE_UTC
FROM (
    SELECT
    PS.MULTI_SCHEME_ID
    , SCHEME.NAME AS SCHEME
    , AR.TRANSACTION_NUMBER
    , AR.TRANSACTION_TYPE
    , AR.TRANSACTION_DATE
    , AR.BILL_TO_SITE_NUM AS BILL_TO_SITE_NUMBER
    , AR.BU_NAME
    , SUM(AR.TRANSACTION_ENTERED_AMT) AS TRANSACTION_ENTERED_AMOUNT
    FROM {{ source('CES_ERP', 'AR_TRANSACTIONS') }} AS AR
    INNER JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS
    ON AR.BILL_TO_SITE_NUM = PS.SITE_NUMBER
    INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
    ON PS.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
    WHERE AR.TRANSACTION_SOURCE_NAME IN ('MANUFACTURER', 'Manual')
    AND AR.TRANSACTION_TYPE IN ('BM Invoice', 'BM Credit', 'Scheme Admin Credit', 'Scheme Admin Invoice')
    AND AR.ACCOUNTING_CLASS = 'Receivable'
    AND AR.ACCOUNTING_CALENDAR_NAME IN ('Scheme Ledger', 'VIC Ledger', 'TAS Ledger')
    GROUP BY
    PS.MULTI_SCHEME_ID
    , SCHEME.NAME
    , AR.TRANSACTION_NUMBER
    , AR.TRANSACTION_TYPE
    , AR.TRANSACTION_DATE
    , AR.BILL_TO_SITE_NUM
    , AR.BU_NAME
) BM
LEFT JOIN {{ ref('REF_DATE') }} AS D_I
ON TO_CHAR(TRUNC(BM.TRANSACTION_DATE, 'MONTH'), 'YYYYMMDD') = D_I.KEY
LEFT JOIN {{ ref('REF_DATE') }} AS D_T
ON TO_CHAR(BM.TRANSACTION_DATE, 'YYYYMMDD') = D_T.KEY
LEFT JOIN {{ source('CES_FINANCE', 'QCP_SLA_OVERWRITE') }} AS O
ON UPPER(O.PAY_GROUP) IN ('BM INVOICE', 'BM CREDIT', 'SCHEME ADMIN CREDIT', 'SCHEME ADMIN INVOICE')
AND BM.TRANSACTION_NUMBER = REPLACE(O.INVOICE_NUMBER, '"')
AND TO_CHAR(BM.TRANSACTION_DATE, 'YYYYMMDD') = O.INVOICE_DATE_YYYYMMDD
AND NVL(BM.BILL_TO_SITE_NUMBER, '-') = NVL(O.SITE_NUMBER, '-')