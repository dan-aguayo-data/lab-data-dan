SELECT
-1 AS MULTI_SCHEME_ID
, 'CES' AS SCHEME
, I.ID AS ID
, I.PAGE_ID AS PAGE_ID
, I.NAME AS NAME
, I.STATUS AS STATUS
, I.CREATED_AT AS CREATED_ON_UTC
, CONVERT_TIMEZONE('UTC', 'Australia/Sydney', CAST(I.CREATED_AT AS TIMESTAMP)) AS CREATED_ON_NSW
, TO_CHAR(CONVERT_TIMEZONE('UTC', 'Australia/Sydney', CAST(I.CREATED_AT AS TIMESTAMP)), 'YYYYMMDD') AS CREATED_ON_NSW_KEY
, CONVERT_TIMEZONE('UTC', 'Australia/Brisbane', CAST(I.CREATED_AT AS TIMESTAMP)) AS CREATED_ON_QLD
, CONVERT_TIMEZONE('UTC', 'Australia/Perth', CAST(I.CREATED_AT AS TIMESTAMP)) AS CREATED_ON_WA
, CONVERT_TIMEZONE('UTC', 'Australia/Melbourne', CAST(I.CREATED_AT AS TIMESTAMP)) AS CREATED_ON_VIC
, CONVERT_TIMEZONE('UTC', 'Australia/Hobart', CAST(I.CREATED_AT AS TIMESTAMP)) AS CREATED_ON_TAS
, CONVERT_TIMEZONE('UTC', 'Australia/Sydney', CAST(I.RESOLVED_AT AS TIMESTAMP)) AS RESOLVED_ON_NSW
, CONVERT_TIMEZONE('UTC', 'Australia/Brisbane', CAST(I.RESOLVED_AT AS TIMESTAMP)) AS RESOLVED_ON_QLD
, CONVERT_TIMEZONE('UTC', 'Australia/Perth', CAST(I.RESOLVED_AT AS TIMESTAMP)) AS RESOLVED_ON_WA
, CONVERT_TIMEZONE('UTC', 'Australia/Melbourne', CAST(I.RESOLVED_AT AS TIMESTAMP)) AS RESOLVED_ON_VIC
, CONVERT_TIMEZONE('UTC', 'Australia/Hobart', CAST(I.RESOLVED_AT AS TIMESTAMP)) AS RESOLVED_ON_TAS
, CONVERT_TIMEZONE('UTC', 'Australia/Sydney', CAST(I.MONITORING_AT AS TIMESTAMP)) AS MONITORING_ON_NSW
, CONVERT_TIMEZONE('UTC', 'Australia/Brisbane', CAST(I.MONITORING_AT AS TIMESTAMP)) AS MONITORING_ON_QLD
, CONVERT_TIMEZONE('UTC', 'Australia/Perth', CAST(I.MONITORING_AT AS TIMESTAMP)) AS MONITORING_ON_WA
, CONVERT_TIMEZONE('UTC', 'Australia/Melbourne', CAST(I.MONITORING_AT AS TIMESTAMP)) AS MONITORING_ON_VIC
, CONVERT_TIMEZONE('UTC', 'Australia/Hobart', CAST(I.MONITORING_AT AS TIMESTAMP)) AS MONITORING_ON_TAS
, I.IMPACT AS IMPACT
, I.IMPACT_OVERRIDE AS IMPACT_OVERRIDE
, CASE WHEN I.IMPACT IN ('critical', 'major') THEN 1 ELSE 0 END AS CALCULATION_FLAG
, CONVERT_TIMEZONE('UTC', 'Australia/Sydney', CAST(I.SCHEDULED_FOR AS TIMESTAMP)) AS SCHEDULED_FOR
, CONVERT_TIMEZONE('UTC', 'Australia/Sydney', CAST(I.SCHEDULED_UNTIL AS TIMESTAMP)) AS SCHEDULED_UNTIL
, CONVERT_TIMEZONE('UTC', 'Australia/Sydney', CAST(I.SCHEDULED_REMINDED_AT AS TIMESTAMP)) AS SCHEDULED_REMINDED_ON
, I.SCHEDULED_AUTO_IN_PROGRESS AS SCHEDULED_AUTO_IN_PROGRESS
, I.SCHEDULED_REMIND_PRIOR AS SCHEDULED_REMIND_PRIOR
, CONVERT_TIMEZONE('UTC', 'Australia/Sydney', CAST(I.POSTMORTEM_PUBLISHED_AT AS TIMESTAMP)) AS POSTMORTEM_PUBLISHED_ON
, CONVERT_TIMEZONE('UTC', 'Australia/Sydney', CAST(I.POSTMORTEM_BODY_LAST_UPDATED_AT AS TIMESTAMP)) AS POSTMORTEM_BODY_LAST_UPDATED_ON
, I.POSTMORTEM_IGNORED AS POSTMORTEM_IGNORED
, I.POSTMORTEM_BODY AS POSTMORTEM_BODY
, I.POSTMORTEM_NOTIFIED_TWITTER AS POSTMORTEM_NOTIFIED_TWITTER
, I.POSTMORTEM_NOTIFIED_SUBSCRIBERS AS POSTMORTEM_NOTIFIED_SUBSCRIBERS
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_STATUSPAGE', 'INCIDENT') }} AS I
WHERE
I._FIVETRAN_DELETED = 'FALSE'
AND I.PAGE_ID = 'qcc7tn2gwzq3' --Circular Economy Systems