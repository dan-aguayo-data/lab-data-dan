SELECT
NVL(R.MULTI_SCHEME_ID, C.MULTI_SCHEME_ID) AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, NVL(R.MULTI_SCHEME_ID, C.MULTI_SCHEME_ID) || '-' || NVL(R.DATE_KEY, TO_CHAR(ADD_MONTHS(TO_DATE(C.PERIOD_KEY, 'YYYYMMDD'), -2), 'YYYYMMDD')) AS ID
, NVL(R.DATE_KEY, TO_CHAR(ADD_MONTHS(TO_DATE(C.PERIOD_KEY, 'YYYYMMDD'), -2), 'YYYYMMDD')) AS DATE_KEY
, R.AVG_BM_REVENUE AS AVG_BM_REVENUE
, C.ENDING_BALANCE AS ENDING_BALANCE
, (NVL(R.AVG_BM_REVENUE * T_1.DEBTOR_PERCENT, 0) + NVL(C.ENDING_BALANCE * T_2.DEBTOR_PERCENT, 0)) / 2000 AS SLA_TARGET
, SYSDATE() AS INSERT_DATE_UTC
FROM (
    SELECT
    M.MULTI_SCHEME_ID
    , D.YEAR || CASE D.QUARTER WHEN 1 THEN '01' WHEN 2 THEN '04' WHEN 3 THEN '07' WHEN 4 THEN '10' END || '01' AS DATE_KEY
    , SUM(TRANSACTION_ENTERED_AMOUNT) / 3 / 1.1 AS AVG_BM_REVENUE
    FROM {{ ref('QCP_BM_INVOICE') }} AS M
    LEFT JOIN {{ ref('REF_DATE') }} AS D
    ON M.TRANSACTION_DATE_KEY = D.KEY
    WHERE M.TRANSACTION_TYPE = 'BM Invoice'
    GROUP BY
    M.MULTI_SCHEME_ID
    , D.YEAR || CASE D.QUARTER WHEN 1 THEN '01' WHEN 2 THEN '04' WHEN 3 THEN '07' WHEN 4 THEN '10' END || '01'
) R
FULL OUTER JOIN (
    SELECT
    DECODE(B.LEDGER_NAME, 'Scheme Ledger AU', 10000, 'Scheme WA Ledger AU', 10001, 'Scheme VIC Ledger', 10002) AS MULTI_SCHEME_ID
    , TO_CHAR(NVL(P1.FISCAL_PERIOD_START_DATE,P2.FISCAL_PERIOD_START_DATE), 'YYYYMMDD') AS PERIOD_KEY
    , SUM(B.BASE_BEGIN_BALANCE + B.BASE_PERIOD_NET_ACTIVITY) AS ENDING_BALANCE
    FROM {{ source('CES_ERP', 'GL_BALANCES') }} AS B
    INNER JOIN {{ source('CES_ERP', 'GL_ACCOUNT') }} AS A
    ON B.ACCOUNT_CODE = A.ACCOUNT_CODE
    AND A.ACCOUNT_TREE_CODE = CASE WHEN B.LEDGER_NAME = 'Scheme VIC Ledger' THEN 'Account VIC Scheme Ledger-Account VIC Scheme Ledger Current' ELSE 'Account Scheme Ledger-Account Scheme Ledger Current' END
    LEFT JOIN {{ source('CES_ERP', 'GL_PERIOD') }} AS P1
    ON P1.FISCAL_PERIOD_SET_NAME = DECODE(B.LEDGER_NAME, 'Scheme Ledger AU', 'Scheme Ledger', 'Scheme WA Ledger AU', 'WA Ledger', 'Scheme VIC Ledger', 'VIC Ledger')
    AND B.PERIOD_NAME = CASE WHEN B.BALANCE_TYPE <> 'Actual' and P1.ADJ_PERIOD_IND =  'No'  THEN TO_CHAR(P1.FISCAL_PERIOD_START_DATE, 'MON') ||'-'|| RIGHT(P1.FISCAL_YEAR,2) ELSE P1.FISCAL_PERIOD END
    LEFT JOIN {{ source('CES_ERP', 'GL_PERIOD') }} AS P2
    ON P2.FISCAL_PERIOD_SET_NAME = DECODE(B.LEDGER_NAME, 'Scheme Ledger AU', 'Scheme Sec Cal', 'Scheme WA Ledger AU', 'SchemeWA Sec')
    AND B.PERIOD_NAME = CASE WHEN B.BALANCE_TYPE <> 'Actual' and P2.ADJ_PERIOD_IND =  'No'  THEN TO_CHAR(P2.FISCAL_PERIOD_START_DATE, 'MON') ||'-'|| RIGHT(P2.FISCAL_YEAR,2) ELSE P2.FISCAL_PERIOD END
    LEFT JOIN {{ ref('REF_DATE') }} AS D
    ON TO_CHAR(NVL(P1.FISCAL_PERIOD_START_DATE,P2.FISCAL_PERIOD_START_DATE), 'YYYYMMDD') = D.KEY
    WHERE B.ACCOUNT_CODE = 11005
    AND B.LEDGER_NAME IN ('Scheme Ledger AU', 'Scheme WA Ledger AU', 'Scheme VIC Ledger')
    AND D.KEY = D.YEAR || CASE D.QUARTER WHEN 1 THEN '03' WHEN 2 THEN '06' WHEN 3 THEN '09' WHEN 4 THEN '12' END || '01'
    GROUP BY
    DECODE(B.LEDGER_NAME, 'Scheme Ledger AU', 10000, 'Scheme WA Ledger AU', 10001, 'Scheme VIC Ledger', 10002)
    , TO_CHAR(NVL(P1.FISCAL_PERIOD_START_DATE,P2.FISCAL_PERIOD_START_DATE), 'YYYYMMDD')
) C
ON R.MULTI_SCHEME_ID = C.MULTI_SCHEME_ID
AND R.DATE_KEY = TO_CHAR(ADD_MONTHS(TO_DATE(C.PERIOD_KEY, 'YYYYMMDD'), -2), 'YYYYMMDD')
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON NVL(R.MULTI_SCHEME_ID, C.MULTI_SCHEME_ID) = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_FINANCE', 'QCP_SLA_TARGET_DEBTOR_PERCENT') }} AS T_1
ON T_1.CATEGORY = 'AVG_BM_REVENUE'
AND R.DATE_KEY BETWEEN T_1.EFFECTIVE_FROM_YYYYMMDD AND NVL(T_1.EFFECTIVE_TO_YYYYMMDD, 99990101)
LEFT JOIN {{ source('CES_FINANCE', 'QCP_SLA_TARGET_DEBTOR_PERCENT') }} AS T_2
ON T_2.CATEGORY = 'ENDING_BALANCE'
AND C.PERIOD_KEY BETWEEN T_1.EFFECTIVE_FROM_YYYYMMDD AND NVL(T_1.EFFECTIVE_TO_YYYYMMDD, 99990101)