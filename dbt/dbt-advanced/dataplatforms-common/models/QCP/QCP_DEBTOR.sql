SELECT
O.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, O.SCHEME AS SCHEME
, O.PAYMENT_SCHEDULE_ID || '-' || O.YEAR_QUARTER AS ID
, O.END_OF_YEAR_QUARTER AS END_OF_YEAR_QUARTER
, O.END_OF_YEAR_QUARTER_KEY AS END_OF_YEAR_QUARTER_KEY
, DATE_TRUNC('QUARTER', O.END_OF_YEAR_QUARTER) AS START_OF_YEAR_QUARTER
, TO_CHAR(DATE_TRUNC('QUARTER', O.END_OF_YEAR_QUARTER), 'YYYYMMDD') AS START_OF_YEAR_QUARTER_KEY
, O.YEAR_QUARTER AS YEAR_QUARTER
, O.PAYMENT_SCHEDULE_ID AS PAYMENT_SCHEDULE_ID
, O.PARTY_NAME AS PARTY_NAME
, O.DUE_DATE AS DUE_DATE
, O.CLASS AS CLASS
, CASE WHEN O.CLASS='INV' THEN (NVL(O.AMOUNT_DUE_ORIGINAL_EXCH, 0) - NVL(DUE.AR_ACCTD_AMT_DUE_EXCH, 0)) ELSE (NVL(O.AMOUNT_DUE_ORIGINAL_EXCH, 0) + NVL(DUE.AR_ACCTD_AMT_DUE_EXCH, 0)) END AS OUTSTANDING_AMOUNT
, O.END_OF_YEAR_QUARTER - O.DUE_DATE AS DAYS_DIFF
, CASE WHEN O.END_OF_YEAR_QUARTER - O.DUE_DATE BETWEEN 61 AND 90 THEN '61-90' WHEN O.END_OF_YEAR_QUARTER - O.DUE_DATE BETWEEN 91 AND 120 THEN '91-120' WHEN O.END_OF_YEAR_QUARTER - O.DUE_DATE BETWEEN 121 AND 150 THEN '121-150' ELSE '151+' END AS DAYS_DIFF_BANDING
, CASE WHEN O.END_OF_YEAR_QUARTER - O.DUE_DATE BETWEEN 61 AND 90 THEN 1 WHEN O.END_OF_YEAR_QUARTER - O.DUE_DATE BETWEEN 91 AND 120 THEN 2 WHEN O.END_OF_YEAR_QUARTER - O.DUE_DATE BETWEEN 121 AND 150 THEN 3 ELSE 4 END AS DAYS_DIFF_BANDING_ORDER
, SYSDATE() AS INSERT_DATE_UTC
FROM (
    SELECT
    TD.MULTI_SCHEME_ID
    , TD.SCHEME
    , TD.PAYMENT_SCHEDULE_ID
    , TD.PARTY_NAME
    , TD.DUE_DATE
    , TD.CLASS
    , TD.BU_NAME
    , TD.GL_DATE_PS
    , TD.AMOUNT_DUE_ORIGINAL_EXCH
    , D.YEAR_QUARTER
    , D.DATE AS END_OF_YEAR_QUARTER
    , TO_CHAR(D.DATE, 'YYYYMMDD') AS END_OF_YEAR_QUARTER_KEY
    FROM (
        SELECT
        DECODE(ARTD.LOCATION_CODE, 'CoExQLD', 10000, 'WARRRL', 10001, 'VIC RECYCLE', 10002, 'TAS RECYCLE', 10003, 'CoExService', -1) AS MULTI_SCHEME_ID
        , DECODE(ARTD.LOCATION_CODE, 'CoExQLD', 'QLD', 'WARRRL', 'WA', 'VIC RECYCLE', 'VIC', 'TAS RECYCLE', 'TAS', 'CoExService', 'CES') AS SCHEME
        , ARTD.PAYMENT_SCHEDULE_ID
        , ARTD.PARTY_NAME
        , ARTD.DUE_DATE
        , ARTD.CLASS
        , ARTD.BU_NAME
        , ARTD.GL_DATE_PS
        , ARTD.AMOUNT_DUE_ORIGINAL_EXCH
        FROM (
            SELECT
            ARDUE.LOCATION_CODE
            , ARDUE.PAYMENT_SCHEDULE_ID
            , ARDUE.PARTY_NAME
            , ARDUE.DUE_DATE
            , ARDUE.CLASS
            , ARDUE.BU_NAME
            , ARDUE.GL_DATE_PS
            , NVL(ARDUE.AMOUNT_DUE_ORIGINAL_EXCH, 0) AS AMOUNT_DUE_ORIGINAL_EXCH
            FROM {{ source('CES_ERP', 'AR_TRANSACTIONS_DUE_SCHED') }} AS ARDUE
            LEFT JOIN {{ source('CES_ERP', 'AR_TRANSACTIONS_DUE_APP') }} AS AR
            ON ARDUE.PAYMENT_SCHEDULE_ID = AR.PAYMENT_SCHEDULE_ID
            QUALIFY ROW_NUMBER() OVER (PARTITION BY ARDUE.PAYMENT_SCHEDULE_ID ORDER BY AR.RECEIPT_DATE DESC) = 1
        ) ARTD
        WHERE ARTD.CLASS IN ('CM', 'INV')
        AND ARTD.BU_NAME IN ('Scheme QLD BU', 'WA SCHEME BU', 'Scheme VIC BU', 'Scheme TAS BU')
    ) TD
    CROSS JOIN (
        SELECT
        DT.YEAR_QUARTER
        , DT.DATE
        , DT.KEY
        FROM {{ ref('REF_DATE') }} AS DT
        QUALIFY ROW_NUMBER() OVER (PARTITION BY DT.YEAR_QUARTER ORDER BY DT.DATE DESC) = 1
    ) D
    WHERE TD.GL_DATE_PS <= D.DATE
) O
LEFT JOIN (
    SELECT
    T.PAYMENT_SCHEDULE_ID
    , T.GL_DATE_AR
    , D.YEAR_QUARTER
    , T.AR_ACCTD_AMT_DUE_EXCH
    FROM (
        SELECT
        S.PAYMENT_SCHEDULE_ID
        , AR.GL_DATE_AR
        , ROUND(SUM(NVL((CASE WHEN S.CLASS = 'INV' THEN NVL(AR.AMOUNT_APPLIED, 0) ELSE (CASE WHEN AR.APPLICATION_TYPE = 'CASH' THEN NVL(ABS(AR.AMOUNT_APPLIED), 0) ELSE NVL(AR.AMOUNT_APPLIED, 0) END) END) * S.EXCHANGE_RATE, 0)) OVER (PARTITION BY AR.PAYMENT_SCHEDULE_ID ORDER BY YEAR(AR.GL_DATE_AR) || '-' || QUARTER(AR.GL_DATE_AR)), 2) AS AR_ACCTD_AMT_DUE_EXCH
        FROM {{ source('CES_ERP', 'AR_TRANSACTIONS_DUE_SCHED') }} AS S
        LEFT JOIN {{ source('CES_ERP', 'AR_TRANSACTIONS_DUE_APP') }} AS AR
        ON S.PAYMENT_SCHEDULE_ID = AR.PAYMENT_SCHEDULE_ID
        --WHERE AR.DISPLAY_AR = 'Y'
    ) T
    CROSS JOIN (
        SELECT
        DT.DATE
        , DT.KEY
        , DT.YEAR_QUARTER
        FROM {{ ref('REF_DATE') }} AS DT
        QUALIFY ROW_NUMBER() OVER (PARTITION BY DT.YEAR_QUARTER ORDER BY DT.DATE DESC) = 1
    ) D
    WHERE T.GL_DATE_AR <= D.DATE
    QUALIFY ROW_NUMBER() OVER (PARTITION BY T.PAYMENT_SCHEDULE_ID, D.YEAR_QUARTER ORDER BY T.GL_DATE_AR DESC) = 1
) DUE
ON O.PAYMENT_SCHEDULE_ID = DUE.PAYMENT_SCHEDULE_ID
AND O.YEAR_QUARTER = DUE.YEAR_QUARTER
WHERE NVL(ABS(O.AMOUNT_DUE_ORIGINAL_EXCH),0) - NVL(ABS(DUE.AR_ACCTD_AMT_DUE_EXCH),0) > 0
AND O.END_OF_YEAR_QUARTER - O.DUE_DATE > 60