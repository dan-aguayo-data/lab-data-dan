SELECT
NVL(SLA.MULTI_SCHEME_ID, '-1') AS MULTI_SCHEME_ID
, NVL(SCHEME.NAME, 'CES') AS SCHEME
, I.ID || '-' || NVL(IC.COMPONENT_ID, 'N/A') || '-' || NVL(M.QCP_ID, 'N/A') AS ID
, I.ID AS INCIDENT_ID
, I.NAME AS INCIDENT_NAME
, IC.COMPONENT_ID AS COMPONENT_ID
, C.NAME AS COMPONENT_NAME
, M.QCP_ID AS QCP_ID
, CONVERT_TIMEZONE('UTC', NVL(SCHEME.TIMEZONE, 'Australia/Sydney'), CAST(I.CREATED_AT AS TIMESTAMP)) AS INCIDENT_CREATED_ON
, CONVERT_TIMEZONE('UTC', NVL(SCHEME.TIMEZONE, 'Australia/Sydney'), CAST(I.MONITORING_AT AS TIMESTAMP)) AS INCIDENT_MONITORING_ON
, CONVERT_TIMEZONE('UTC', NVL(SCHEME.TIMEZONE, 'Australia/Sydney'), CAST(I.RESOLVED_AT AS TIMESTAMP)) AS INCIDENT_RESOLVED_ON
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_STATUSPAGE', 'INCIDENT_COMPONENT') }} AS IC
RIGHT JOIN {{ source('CES_STATUSPAGE', 'INCIDENT') }} AS I
ON IC.INCIDENT_ID = I.ID
LEFT JOIN {{ source('CES_STATUSPAGE', 'COMPONENT') }} AS C
ON IC.COMPONENT_ID = C.ID
LEFT JOIN {{ source('CES_FINANCE', 'QCP_COMPONENT_QCP_ID_MAPPING') }} AS M
ON IC.COMPONENT_ID = M.COMPONENT_ID
AND NVL(TO_CHAR(CONVERT_TIMEZONE('UTC', 'Australia/Sydney', CAST(I.CREATED_AT AS TIMESTAMP)), 'YYYYMMDD'), '20180101') BETWEEN M.EFFECTIVE_FROM_YYYYMMDD AND NVL(M.EFFECTIVE_TO_YYYYMMDD, '99990101')
LEFT JOIN {{ source('CES_FINANCE', 'QCP_SLA') }} AS SLA
ON M.QCP_ID = SLA.QCP_ID
LEFT JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON SLA.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
WHERE
NVL(IC._FIVETRAN_DELETED, 'FALSE') = 'FALSE'
AND I._FIVETRAN_DELETED = 'FALSE'
AND NVL(C._FIVETRAN_DELETED, 'FALSE') = 'FALSE'
AND I.PAGE_ID = 'qcc7tn2gwzq3' --Circular Economy Systems