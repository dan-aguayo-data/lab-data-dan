SELECT
FMT.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, FMT.SCHEME AS SCHEME
, FMT.TRIP_ID AS TRIP_ID
, FMT.SCHEDULED_START AS SCHEDULED_START
, FMT.SCHEDULED_END AS SCHEDULED_END
, FMT.ACTUAL_START AS ACTUAL_START
, FMT.ACTUAL_END AS ACTUAL_END
, TO_CHAR(FMT.ACTUAL_END, 'YYYYMMDD') AS ACTUAL_END_KEY
, FMT.CREATED_BY AS CREATED_BY
, FMT.CREATED_ON AS CREATED_ON
, FMT.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, FMT.LAST_MODIFIED_BY_ROLE AS LAST_MODIFIED_BY_ROLE
, FMT.LAST_MODIFIED_ON AS LAST_MODIFIED_ON
, FMT.MOBILE_APP_UPLOAD_TIME_HOUR AS MOBILE_APP_UPLOAD_TIME_HOUR
, FMT.MEET_SLA_RAW AS MEET_SLA_RAW
, FMT.TIME_DIFFERENCE_BETWEEN_CREATE_AND_LAST_MODIFIED_HOUR AS TIME_DIFFERENCE_BETWEEN_CREATE_AND_LAST_MODIFIED_HOUR
, FMT.FLAG_1 AS FLAG_1
, FMT.FLAG_2 AS FLAG_2
, FMT.FLAG_3 AS FLAG_3
, NVL(O.MEET_SLA, CASE WHEN FMT.FLAG_1 * FMT.FLAG_2 * FMT.FLAG_3 = 1 THEN FMT.MEET_SLA_RAW ELSE NULL END) AS MEET_SLA
, CASE WHEN O.TRIP_ID IS NOT NULL THEN 'Yes' ELSE 'No' END AS MEET_SLA_OVERWRITE_FLAG
, O.COMMENT AS MEET_SLA_OVERWRITE_COMMENT
, SYSDATE() AS INSERT_DATE_UTC
FROM (
    SELECT
    O.SCHEME_ID AS MULTI_SCHEME_ID
    , SCHEME.NAME AS SCHEME
    , T.TRIP_ID
    , CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(T.SCHEDULED_START AS TIMESTAMP)) AS SCHEDULED_START
    , CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(T.SCHEDULED_END AS TIMESTAMP)) AS SCHEDULED_END
    , CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(T.ACTUAL_START AS TIMESTAMP)) AS ACTUAL_START
    , CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(T.ACTUAL_END AS TIMESTAMP)) AS ACTUAL_END
    , T.CREATED_BY
    , CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(T.CREATED_ON AS TIMESTAMP)) AS CREATED_ON
    , T.LAST_MODIFIED_BY
    , P.ROLE AS LAST_MODIFIED_BY_ROLE
    , CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(T.LAST_MODIFIED_ON AS TIMESTAMP)) AS LAST_MODIFIED_ON
    , DATEDIFF('S', T.ACTUAL_END, T.LAST_MODIFIED_ON) / 3600 AS MOBILE_APP_UPLOAD_TIME_HOUR
    , CASE WHEN DATEDIFF('S', T.ACTUAL_END, T.LAST_MODIFIED_ON) / 3600 <= 24 THEN 'Yes' WHEN NVL(DATEDIFF('S', T.ACTUAL_END, T.LAST_MODIFIED_ON), 0)/3600 > 24 THEN 'No' ELSE NULL END AS MEET_SLA_RAW
    , DATEDIFF('S', T.CREATED_ON, T.LAST_MODIFIED_ON) / 3600 AS TIME_DIFFERENCE_BETWEEN_CREATE_AND_LAST_MODIFIED_HOUR
    , CASE WHEN DATEDIFF('S', T.CREATED_ON, T.LAST_MODIFIED_ON) / 3600 >= 0.25 THEN 1 ELSE 0 END AS FLAG_1
    , CASE WHEN LOWER(T.CREATED_BY) <> LOWER(T.LAST_MODIFIED_BY) THEN 1 ELSE 0 END AS FLAG_2
    , CASE WHEN P.ROLE = 'LSP Admin' THEN 0 ELSE 1 END AS FLAG_3
    FROM {{ source('CES_MSCM', 'FMT_TRIPS') }} AS T
    INNER JOIN {{ source('CES_MSCM', 'FMT_ORGANISATIONS') }} AS O
    ON T.ORGANISATION_ID = O.ORGANISATION_ID
    INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
    ON O.SCHEME_ID = SCHEME.MULTI_SCHEME_ID
    LEFT JOIN {{ source('CES_MSCM', 'FMT_PEOPLE') }} AS P
    ON LOWER(T.LAST_MODIFIED_BY) = LOWER(P.LOGIN)
    AND TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(T.LAST_MODIFIED_ON AS TIMESTAMP)), 'YYYYMMDD') BETWEEN TO_CHAR(P.START_DATE_ACTIVE, 'YYYYMMDD') AND NVL(TO_CHAR(P.END_DATE_ACTIVE, 'YYYYMMDD'), '99990101')
    WHERE T.TRIP_STATUS_ID = 1399
) FMT
LEFT JOIN {{ source('CES_FINANCE', 'QCP_SLA_OVERWRITE_FMT_TIME') }} AS O
ON FMT.TRIP_ID = O.TRIP_ID