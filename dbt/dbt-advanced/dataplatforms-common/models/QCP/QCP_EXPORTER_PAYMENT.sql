SELECT
I.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, I.SCHEME AS SCHEME
, I.ID || '-' || P.ID AS ID
, I.INVOICE_NUMBER AS INVOICE_NUMBER
, I.INVOICE_DATE AS INVOICE_DATE
, TO_CHAR(I.INVOICE_DATE, 'YYYYMMDD') AS INVOICE_DATE_KEY
, I.SUPPLIER_NAME AS SUPPLIER_NAME
, I.SITE_NUMBER AS SITE_NUMBER
, I.PAY_GROUP AS PAY_GROUP
, I.INVOICE_AMOUNT AS INVOICE_AMOUNT
, I.BU_NAME AS BU_NAME
, P.PAYMENT_TERMS AS PAYMENT_TERMS
, P.DUE_DATE AS DUE_DATE
, P.PAYMENT_DATE AS PAYMENT_DATE
, P.PAYMENT_STATUS AS PAYMENT_STATUS
, P.PAYMENT_AMOUNT AS PAYMENT_AMOUNT
, P.PAYMENT_AMOUNT_IN_INVOICE_CURRENCY AS PAYMENT_AMOUNT_IN_INVOICE_CURRENCY
, CASE WHEN I.MULTI_SCHEME_ID = 10000 THEN D_P.WORKDAYS_FROM_BEGINNING_QLD - D_I.WORKDAYS_FROM_BEGINNING_QLD WHEN I.MULTI_SCHEME_ID = 10001 THEN D_P.WORKDAYS_FROM_BEGINNING_WA - D_I.WORKDAYS_FROM_BEGINNING_WA WHEN I.MULTI_SCHEME_ID LIKE '10002%' THEN D_P.WORKDAYS_FROM_BEGINNING_VIC - D_I.WORKDAYS_FROM_BEGINNING_VIC WHEN I.MULTI_SCHEME_ID LIKE '10003%' THEN D_P.WORKDAYS_FROM_BEGINNING_TAS - D_I.WORKDAYS_FROM_BEGINNING_TAS ELSE D_P.WORKDAYS_FROM_BEGINNING_NSW - D_I.WORKDAYS_FROM_BEGINNING_NSW END AS WORKDAYS_FROM_INVOICE_TO_PAYMENT
, NVL(O.MEET_SLA, CASE WHEN I.MULTI_SCHEME_ID LIKE ANY ('10002%', '10003%') THEN CASE WHEN WORKDAYS_FROM_INVOICE_TO_PAYMENT <= 10 THEN 'Yes' WHEN WORKDAYS_FROM_INVOICE_TO_PAYMENT > 10 THEN 'No' END WHEN I.MULTI_SCHEME_ID IN (10000, 10001) AND P.PAYMENT_STATUS IN ('Cleared', 'Negotiable') THEN CASE WHEN P.PAYMENT_DATE <= D.DATE THEN 'Yes' WHEN P.PAYMENT_DATE > D.DATE THEN 'No' ELSE 'No' END WHEN P.PAYMENT_STATUS IS NULL AND P.PAYMENT_DATE IS NULL THEN 'No' ELSE NULL END) AS MEET_SLA
, CASE WHEN O.INVOICE_NUMBER IS NOT NULL THEN 'Yes' ELSE 'No' END AS MEET_SLA_OVERWRITE_FLAG
, O.COMMENT AS MEET_SLA_OVERWRITE_COMMENT
, SYSDATE() AS INSERT_DATE_UTC
FROM (
    SELECT
    PS.MULTI_SCHEME_ID
    , SCHEME.NAME AS SCHEME 
    , API.CONCATENATED_SEGMENTS || '-' || API.INVOICE_ID || '-' || API.DISTRIBUTION_LINE_NUM || '-' || API.LINE_NUMBER AS ID
    , API.INVOICE_ID
    , API.INVOICE_NUM AS INVOICE_NUMBER
    , API.INVOICE_DATE
    , CAST(CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, API.INV_CREATION_DATE) AS DATE) AS INVOICE_CREATE_DATE
    , API.SUPPLIER_NAME
    , API.SUPPLIER_SITE_CODE AS SITE_NUMBER
    , API.PAY_GROUP
    , API.INVOICE_AMOUNT
    , API.BUSINESS_UNIT_NAME AS BU_NAME
    FROM {{ source('CES_ERP', 'AP_TRANSACTIONS') }} AS API
    INNER JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS
    ON API.SUPPLIER_SITE_CODE = PS.SITE_NUMBER
    INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
    ON PS.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
    WHERE API.PAY_GROUP IN ('EXPORTER')
    QUALIFY ROW_NUMBER() OVER (PARTITION BY API.INVOICE_ID ORDER BY API.LINE_NUMBER, API.DISTRIBUTION_LINE_NUM) = 1
) I
LEFT JOIN (
    SELECT
    APP.CHECK_NUMBER || '-' || APP.INVOICE_NUMBER || '-' || APP.INVOICE_DATE AS ID
    , APP.INVOICE_ID
    , APP.INVOICE_NUMBER
    , INITCAP(APP.PAYMENT_TERMS) AS PAYMENT_TERMS
    , APP.DUE_DATE
    , CAST(APP.PAYMENT_DATE AS DATE) AS PAYMENT_DATE
    , APP.PAYMENT_STATUS
    , APP.PAYMENT_AMOUNT
    , APP.PAID_AMOUNT_IN_INVOICE_CURRENCY AS PAYMENT_AMOUNT_IN_INVOICE_CURRENCY
    FROM {{ source('CES_ERP', 'AP_BALANCES') }} AS APP
) P
ON I.INVOICE_ID = P.INVOICE_ID
LEFT JOIN {{ ref('REF_DATE') }} AS D_I
ON TO_CHAR(CASE WHEN I.MULTI_SCHEME_ID LIKE '10002%' THEN I.INVOICE_CREATE_DATE WHEN I.MULTI_SCHEME_ID IN (10000, 10001) THEN I.INVOICE_DATE END, 'YYYYMMDD') = D_I.KEY
LEFT JOIN {{ ref('REF_DATE') }} AS D_P
ON TO_CHAR(P.PAYMENT_DATE, 'YYYYMMDD') = D_P.KEY
LEFT JOIN {{ ref('REF_DATE') }} AS D
ON D.YEAR_MONTH = CASE WHEN DAY(I.INVOICE_DATE) <= 15 THEN TO_CHAR(I.INVOICE_DATE, 'YYYY-MM') ELSE TO_CHAR(ADD_MONTHS(I.INVOICE_DATE, 1), 'YYYY-MM') END
AND D.DAY >= 15
AND CASE I.MULTI_SCHEME_ID WHEN 10000 THEN D.WORKDAY_FLAG_QLD WHEN 10001 THEN D.WORKDAY_FLAG_WA ELSE D.WORKDAY_FLAG_NSW END = 1
LEFT JOIN {{ source('CES_FINANCE', 'QCP_SLA_OVERWRITE') }} AS O
ON I.PAY_GROUP = O.PAY_GROUP
AND I.INVOICE_NUMBER = REPLACE(O.INVOICE_NUMBER, '"')
AND TO_CHAR(I.INVOICE_DATE, 'YYYYMMDD') = O.INVOICE_DATE_YYYYMMDD
AND NVL(I.SITE_NUMBER, '-') = NVL(O.SITE_NUMBER, '-')
QUALIFY ROW_NUMBER() OVER (PARTITION BY I.INVOICE_NUMBER, P.ID ORDER BY D.DATE) = 1