WITH  HDR_TABLE AS ( 
    
SELECT * FROM {{ref('CRP_REFUND_TXN_HDR_PRE_STG_TST')}}


{% if is_incremental() %} 

), INCREMENTAL_DATE_REF AS (

SELECT 
dateadd(minutes, {{var('general_delta_load_minutes')}}, max(LATEST_UPDATE_UTC_TIME)) INCREMENTAL_DELTA 
FROM  CES_REF.CES_DBT.DBT_INCREMENTAL_LOG_CONTROL 
WHERE TABLE_NAME = '{{model.name}}' 


), INCREMENTAL_RECORDS_TABLE AS (

SELECT
HDR.ID
FROM HDR_TABLE AS HDR

WHERE 
( HDR.INSERTED_ON_UTC_DATETIME = (SELECT INCREMENTAL_DELTA FROM INCREMENTAL_DATE_REF)
)
GROUP BY HDR.ID

{% endif %} 
),    MERGE_COMPILE AS (

    SELECT
    --Natural Key
     HDR.ID
    --Attributes
    ,HDR.MULTI_SCHEME_ID
    ,SCHEME.NAME AS SCHEME
    ,SCHEME.TIMEZONE
    ,HDR.POS_DEVICE_ID
    ,PD.NAME AS POS_DEVICE_NAME
    ,PU.POS_USER_NAME
    ,CS.PARTICIPANT_ID AS CONSUMER_ID
    ,HDR.CONSUMER
    ,HDR.CONSUMER_CROSS_SCHEME
    ,R_TT.VALUE AS CONSUMER_TYPE
    ,CS.SITE_NAME AS CONSUMER_NAME
    ,CS.POST_CODE AS CONSUMER_POSTCODE
    ,RTS.VALUE AS REFUND_TXN_SURVEY_POSTCODE
    ,CP.PARTICIPANT_GROUP_ID CONSUMER_GROUP_ID
    ,HDR.PHOTO_ID
    ,HDR.PHOTO_ID_TYPE
    ,PIT.NAME AS PHOTO_ID_TYPE_NAME
    ,HDR.PHOTO_ID_NAME
    ,HDR.PHOTO_ID_NUMBER
    ,HDR.PAYMENT_METHOD
    ,HDR.CUSTOMER_DECLARATION
    ,HDR.BAG_LABEL_ID
    ,HDR.BAG_ISSUE_TYPE
    ,HDR.TRANSACTION_UTC_DATETIME
    ,HDR.TRANSACTION_LOCAL_DATETIME
    ,HDR.TRANSACTION_LOCAL_DATE_ID
    ,HDR.TRANSACTION_LOCAL_TIME_ID
    ,HDR.NOTIFIED
    ,HDR.MSC_CONSUMER_SITE_ID
    ,HDR.PHYSICAL_CONTAINER_RETURN_POINT
    ,HDR.SITE_NUMBER 
    ,PD.CRP_ID AS SITE_NUMBER_POS
    ,PS.SITE_NAME AS SITE_NAME
    ,PS.POST_CODE AS SITE_POSTCODE
    ,P.PARTICIPANT_ID AS SUPPLIER_ID
    ,P.PARTICIPANT_NUMBER AS SUPPLIER_NUMBER
    ,P.PARTICIPANT_NAME AS SUPPLIER_NAME
    ,HDR.CONSUMER_ALIAS
    ,HDR.RECIPIENT_ALIAS
    ,HDR.RECIPIENT_CONSUMER_ID
    ,HDR.RECIPIENT_CONSUMER_ID_CROSS_SCHEME
    ,HDR.MSC_RECIPIENT_SITE_ID
    --Metrics
    ,HDR.QUANTITY
    ,HDR.GROSS_AMOUNT
    ,HDR.GST_AMOUNT
    ,HDR.TAXABLE_AMOUNT
    ,HDR.ELIGIBLE_QUANTITY
    ,HDR.ELIGIBLE_GROSS_AMOUNT
    ,HDR.ELIGIBLE_GST_AMOUNT
    ,HDR.ELIGIBLE_TAXABLE_AMOUNT
    ,HDR.INELIGIBLE_QUANTITY
    --Metadata Attributes
    ,HDR.TRANSACTED_BY
    ,HDR.CREATED_BY
    ,HDR.CREATED_ON_UTC_DATETIME
    ,HDR.LAST_MODIFIED_BY
    ,HDR.LAST_MODIFIED_ON_UTC_DATETIME
  
    
    FROM 
    {{ref('CRP_REFUND_TXN_HDR_PRE_STG_TST')}}  AS HDR
    {% if is_incremental() %}
    INNER JOIN INCREMENTAL_RECORDS_TABLE INC_TXNS 
    ON INC_TXNS.ID = HDR.ID
    {% endif %}
    INNER JOIN RAW_PROD.CES_MSCM_ORACLE.SCHEME AS SCHEME 
    ON HDR.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
    LEFT JOIN RAW_PROD.CES_MSCM_ORACLE.POS_DEVICE AS PD 
    ON HDR.POS_DEVICE_ID = PD.ID
    LEFT JOIN RAW_PROD.CES_MSCM_ORACLE.POS_USER AS PU 
    ON HDR.TRANSACTED_BY = PU.ID
    LEFT JOIN RAW_PROD.CES_MSCM_ORACLE.MDT_PARTICIPANT_SITES AS PS 
    ON NVL(NULLIF(HDR.SITE_NUMBER,''),PD.CRP_ID) = PS.SITE_NUMBER
    LEFT JOIN RAW_PROD.CES_MSCM_ORACLE.MDT_PARTICIPANTS AS P 
    ON PS.PARTICIPANT_ID = P.PARTICIPANT_ID
    LEFT JOIN RAW_PROD.CES_MSCM_ORACLE.MDT_PARTICIPANT_SITES AS CS 
    ON HDR.CONSUMER_CROSS_SCHEME = CS.SITE_NUMBER
    LEFT JOIN RAW_PROD.CES_MSCM_ORACLE.MDT_PARTICIPANTS AS CP
     ON CS.PARTICIPANT_ID = CP.PARTICIPANT_ID
    LEFT JOIN RAW_PROD.CES_MSCM_ORACLE.PHOTO_ID_TYPE AS PIT 
    ON HDR.PHOTO_ID_TYPE = PIT.ID
    LEFT JOIN RAW_PROD.CES_MSCM_ORACLE.REFUND_TXN_SURVEY AS RTS 
    ON HDR.ID = RTS.REFUND_TXN_ID AND RTS.SURVEY_TYPE = 'POSTCODE'
    LEFT JOIN RAW_PROD.CES_MSCM_ORACLE.SCHEME_REF_CODES AS R_TT 
    ON CS.TAXONOMY_TYPE_ID = R_TT.SCHEME_REF_CODES_ID

) 

SELECT  * FROM MERGE_COMPILE