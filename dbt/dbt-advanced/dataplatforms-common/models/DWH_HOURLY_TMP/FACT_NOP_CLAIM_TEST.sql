WITH PAYMENT_DATE AS (  --USED TO DEFINE VIC CUTOFF DATE
SELECT
B.DATE AS BASE_DATE,
B.KEY AS BASE_KEY,
B.DAY_NAME,
B.DAY_OF_WEEK,
B.ISO_WEEK,
V.DATE AS CUTOFF_DATE_VIC,
V.KEY AS CUTOFF_DATE_KEY_VIC,
V_NT.DATE AS PD_TUE_VIC,
V_NT.KEY AS PD_KEY_TUE_VIC,
V_NW.DATE AS PD_NEXT_WORKDAY_VIC,
V_NW.KEY AS PD_KEY_NEXT_WORKDAY_VIC,
CASE WHEN V_NT.WORKDAY_FLAG_VIC = 0 THEN V_NW.DATE ELSE V_NT.DATE END AS PAYMENT_DATE_VIC,
CASE WHEN V_NT.WORKDAY_FLAG_VIC = 0 THEN V_NW.KEY ELSE V_NT.KEY END AS PAYMENT_DATE_KEY_VIC
FROM {{ ref('REF_DATE') }} AS B --base date
LEFT JOIN  {{ ref('REF_DATE') }} AS V --VIC cutoff date
ON B.WORKDAYS_FROM_BEGINNING_VIC + 5 = V.WORKDAYS_FROM_BEGINNING_VIC
AND V.WORKDAY_FLAG_VIC = 1
LEFT JOIN  {{ ref('REF_DATE') }} AS V_NT --VIC next Tue of cutoff date
ON NEXT_DAY(V.DATE, 'TU') = V_NT.DATE
LEFT JOIN  {{ ref('REF_DATE') }} AS V_NW --VIC next workday of next Tue of cutoff date
ON V_NT.WORKDAYS_FROM_BEGINNING_VIC + 1 = V_NW.WORKDAYS_FROM_BEGINNING_VIC
AND V_NW.WORKDAY_FLAG_VIC = 1
WHERE B.DAY_OF_WEEK = 2

), REF_DATE AS  (

SELECT
CASE WHEN WS.KEY = 20231031 THEN 20231101 ELSE WS.KEY END AS PD_KEY, --ASK REASON FOR HARDCODING MODEL
WS.*
FROM  {{ ref('REF_DATE') }} WS

), KAFKA_NOP_CLAIM AS ( -- THIS IS THE BASE TABLE THAT EXPANDS WITH JOINS

SELECT
NOPC.MULTI_SCHEME_ID,
SCHEME.NAME AS SCHEME,
SCHEME.TIMEZONE,
NOPC.CLAIM_ID,
NOPC.PERIOD,
NOPC.STATUS,
NOPC.SUBMITTED_DATE_UTC AS CLAIM_SUBMITTED_DATE_UTC,
CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(NOPC.SUBMITTED_DATE_UTC AS TIMESTAMP))  AS CLAIM_SUBMITTED_DATE,
TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(NOPC.SUBMITTED_DATE_UTC AS TIMESTAMP)),'YYYYMMDD') AS CLAIM_SUBMITTED_DATE_KEY,
NOPC.SUBMITTED_BY
FROM {{ source('CES_MSCM_KAFKA', 'NOP_CLAIM') }} AS NOPC
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON NOPC.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
QUALIFY ROW_NUMBER() OVER (PARTITION BY NOPC.CLAIM_ID ORDER BY NOPC.KAFKA_DATETIME DESC) = 1

), KAFKA_NOP_CLAIM_CUTOFF AS (  --ADDING THE NEAREST CUTOFF DATE, RANGE JOIN. THIS WILL NOT PERFORM WELL IF VALUES OF CLAIMS INCREASE

SELECT
NOPC.MULTI_SCHEME_ID,
NOPC.SCHEME,
NOPC.TIMEZONE,
NOPC.CLAIM_ID,
NOPC.PERIOD,
NOPC.STATUS,
NOPC.CLAIM_SUBMITTED_DATE_UTC,
NOPC.CLAIM_SUBMITTED_DATE,
NOPC.CLAIM_SUBMITTED_DATE_KEY,
NOPC.SUBMITTED_BY,
PD.CUTOFF_DATE_KEY_VIC ,
PD.PAYMENT_DATE_VIC ,
PD.PAYMENT_DATE_KEY_VIC 
FROM KAFKA_NOP_CLAIM NOPC
LEFT JOIN PAYMENT_DATE PD
ON PD.CUTOFF_DATE_KEY_VIC >= NOPC.CLAIM_SUBMITTED_DATE_KEY

QUALIFY ROW_NUMBER() OVER (PARTITION BY NOPC.CLAIM_ID ORDER BY PD.CUTOFF_DATE_KEY_VIC - NOPC.CLAIM_SUBMITTED_DATE_KEY) = 1

), NOP_CLAIM_AGG AS (  --SUMMING THE CLAIM QTY OF NOP CLAIMS

SELECT
NC.MULTI_SCHEME_ID,
NC.SCHEME,
NC.CLAIM_ID,
H.CRP_SITE_NUMBER AS SITE_NUMBER,
H.PAYMENT_TYPE,
NC.PERIOD,
NC.STATUS,
NC.CLAIM_SUBMITTED_DATE_UTC,
NC.CLAIM_SUBMITTED_DATE,
NC.CLAIM_SUBMITTED_DATE_KEY,
NULL AS ADJUSTMENT_SUBMITTED_DATE_UTC,
NULL AS ADJUSTMENT_SUBMITTED_DATE_KEY,
NC.SUBMITTED_BY,
H.LATE_SYNC,
D.MATERIAL_TYPE_ID,
NVL(SUM(D.CONTAINER_COUNT), 0) AS CLAIM_QTY,
NC.CUTOFF_DATE_KEY_VIC,
NC.PAYMENT_DATE_VIC,
NC.PAYMENT_DATE_KEY_VIC
FROM KAFKA_NOP_CLAIM_CUTOFF NC
INNER JOIN {{ source('CES_MSCM_KAFKA', 'NOP_CLAIM_REFUND') }} AS H
ON NC.CLAIM_ID = H.CLAIM_ID
LEFT JOIN {{ source('CES_MSCM_KAFKA', 'NOP_CLAIM_REFUND_ITEMS') }} AS D
ON H.REFUND_TRANSACTION_ID = D.REFUND_TRANSACTION_ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }}  AS SCHEME
ON NC.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
GROUP BY ALL
    
), PADDED_NOP_CLAIM as( --ADDING A ROW FOR EACH MATERIAL_TYPE/SCHEME, IF IT IS A PADDING ROW THEN CLAIM AMOUNT = 0

SELECT
PA.MULTI_SCHEME_ID,
PA.SCHEME,
PA.CLAIM_ID || '_' || PA.SITE_NUMBER || '-' || PA.PAYMENT_TYPE || '-' || NVL(PA.LATE_SYNC, '-') || '-' || MT.ID AS ID,
PA.CLAIM_ID,
PA.SITE_NUMBER,
CS.ZONE,
CASE 
WHEN CS.AUTOMATED_COUNTING_FACILITY = 1 THEN 'AUTOMATED_COUNTING_FACILITY' 
WHEN CS.OVER_THE_COUNTER = 1 THEN 'OVER_THE_COUNTER' 
ELSE 'UNKNOWN' 
END AS CRP_TYPE,
PA.PERIOD,
'R' AS ENTRY_TYPE,
'Claim' as ENTRY_TYPE_DESCRIPTION,
PA.STATUS,
MT.ID AS MATERIAL_TYPE_ID,
MT.NAME AS MATERIAL_TYPE, 
sum(CASE WHEN MT.ID <>  PA.MATERIAL_TYPE_ID THEN 0 ELSE PA.CLAIM_QTY END )AS CLAIM_QTY,
PA.PAYMENT_TYPE,
PA.CLAIM_SUBMITTED_DATE_UTC,
PA.CLAIM_SUBMITTED_DATE,
CLAIM_SUBMITTED_DATE_KEY,
NULL AS ADJUSTMENT_SUBMITTED_DATE_UTC,
NULL AS ADJUSTMENT_SUBMITTED_DATE_KEY,
PA.SUBMITTED_BY AS CLAIM_SUBMITTED_BY,
NULL AS ADJUSTMENT_SUBMITTED_BY,
PA.LATE_SYNC,
PA.CUTOFF_DATE_KEY_VIC,
PA.PAYMENT_DATE_VIC,
PA.PAYMENT_DATE_KEY_VIC
FROM NOP_CLAIM_AGG PA
INNER JOIN {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS MT
on LEFT(PA.MULTI_SCHEME_ID, 5) = MT.MULTI_SCHEME_ID
LEFT JOIN {{ ref('CRP_SITES') }} AS CS
ON PA.SITE_NUMBER = CS.SITE_NUMBER

GROUP BY ALL 

), NOP_ADJ_RAW AS ( --SUMMING THE CLAIM QTY OF NOP CLAIMS ADJUSTMENTS

SELECT
HDR.MULTI_SCHEME_ID AS MULTI_SCHEME_ID,
NC.SCHEME,
HDR.ADJUSTMENT_ID || '_' || HDR.SITE_NUMBER || '-' || HDR.PAYMENT_TYPE || '-' || DTL.MATERIAL_TYPE_ID AS ID,
HDR.CLAIM_ID AS CLAIM_ID,
HDR.SITE_NUMBER AS SITE_NUMBER,
CS.ZONE AS ZONE,
CASE WHEN CS.AUTOMATED_COUNTING_FACILITY = 1 THEN 'AUTOMATED_COUNTING_FACILITY' WHEN CS.OVER_THE_COUNTER = 1 THEN 'OVER_THE_COUNTER' WHEN CS.AUTOMATED_COUNTING_FACILITY = 0 AND CS.OVER_THE_COUNTER = 0 THEN 'UNKNOWN' END AS CRP_TYPE,
NC.PERIOD AS PERIOD,
'A' AS ENTRY_TYPE,
'Adjustment' as ENTRY_TYPE_DESCRIPTION,
NC.STATUS AS STATUS,
DTL.MATERIAL_TYPE_ID,
SUM(DTL.CONTAINER_COUNT) AS CLAIM_QTY,
HDR.PAYMENT_TYPE AS PAYMENT_TYPE,
'Unit' AS UOM,
NC.CLAIM_SUBMITTED_DATE_UTC,
NC.CLAIM_SUBMITTED_DATE,
NC.CLAIM_SUBMITTED_DATE_KEY,
CONVERT_TIMEZONE('UTC',NC.TIMEZONE,CAST(HDR.SUBMITTED_DATE_UTC AS TIMESTAMP)) AS ADJUSTMENT_SUBMITTED_DATE_UTC,
TO_CHAR(CONVERT_TIMEZONE('UTC',NC.TIMEZONE,CAST(HDR.SUBMITTED_DATE_UTC AS TIMESTAMP)),'YYYYMMDD') AS ADJUSTMENT_SUBMITTED_DATE_KEY,
NC.SUBMITTED_BY AS CLAIM_SUBMITTED_BY,
HDR.SUBMITTED_BY AS ADJUSTMENT_SUBMITTED_BY,
NULL AS LATE_SYNC,
NC.CUTOFF_DATE_KEY_VIC,
NC.PAYMENT_DATE_VIC,
NC.PAYMENT_DATE_KEY_VIC
FROM {{ source('CES_MSCM_KAFKA', 'NOP_CLAIM_ADJUSTMENT') }} AS HDR
LEFT JOIN {{ ref('CRP_SITES') }} AS CS
ON HDR.SITE_NUMBER = CS.SITE_NUMBER
INNER JOIN {{ source('CES_MSCM_KAFKA', 'NOP_CLAIM_ADJ_ITEMS') }} AS DTL
ON HDR.ADJUSTMENT_ID = DTL.ADJUSTMENT_ID
INNER JOIN KAFKA_NOP_CLAIM_CUTOFF NC --LATEST STATUS
ON HDR.CLAIM_ID = NC.CLAIM_ID
GROUP BY ALL


), CLAIM_CONSOLIDATED AS(  --UNIONING NOP CLAIMS AND ADJUSTMENTS

SELECT  
PNC.MULTI_SCHEME_ID,
PNC.SCHEME,
PNC.ID,
PNC.CLAIM_ID,
PNC.SITE_NUMBER,
PNC.ZONE,
PNC.CRP_TYPE,
PNC.PERIOD,
WS.KEY AS PERIOD_KEY,
MT.NAME AS MATERIAL_TYPE,
PNC.ENTRY_TYPE,
PNC.ENTRY_TYPE_DESCRIPTION,
PNC.STATUS,
PNC.MATERIAL_TYPE_ID ,
PNC.CLAIM_QTY,
PNC.PAYMENT_TYPE,
'Unit' AS UOM,
CASE WHEN MT.NAME = 'Ineligible Containers' THEN 0 ELSE PNC.CLAIM_QTY * (NF.CENTS_PER_CONTAINER_EX_GST/100) END AS NETWORK_FEE_EX_GST,
CASE WHEN MT.NAME = 'Ineligible Containers' THEN 0 ELSE PNC.CLAIM_QTY * (1/11) END AS REFUND_AMOUNT_EX_GST,
PNC.CLAIM_SUBMITTED_DATE_UTC,
PNC.CLAIM_SUBMITTED_DATE,
PNC.CUTOFF_DATE_KEY_VIC AS SUBMISSION_CUTOFF_DATE,
PNC.CLAIM_SUBMITTED_DATE_KEY,
PNC.ADJUSTMENT_SUBMITTED_DATE_UTC,
PNC.ADJUSTMENT_SUBMITTED_DATE_KEY,
PNC.PAYMENT_DATE_VIC AS PAYMENT_DATE_VIC,
PNC.PAYMENT_DATE_KEY_VIC AS PAYMENT_DATE_KEY_VIC,
PNC.CLAIM_SUBMITTED_BY,
PNC.ADJUSTMENT_SUBMITTED_BY,
PNC.LATE_SYNC
FROM PADDED_NOP_CLAIM PNC
LEFT JOIN REF_DATE AS WS  --10 K ROWS
ON PNC.PERIOD = WS.YEAR_WEEK_ISO AND WS.DAY_OF_WEEK = 2 
INNER JOIN {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS MT
ON PNC.MATERIAL_TYPE_ID = MT.ID AND LEFT(PNC.MULTI_SCHEME_ID,5) = MT.MULTI_SCHEME_ID
LEFT JOIN {{ ref('NETWORK_FEE') }} AS NF  --56 ROWS
ON NF.MULTI_SCHEME_ID = PNC.MULTI_SCHEME_ID 
AND NF.MATERIAL_TYPE_ID = PNC.MATERIAL_TYPE_ID
AND WS.PD_KEY BETWEEN NF.EFFECTIVE_FROM AND NVL(EFFECTIVE_TO, '99991101')

UNION ALL

SELECT
ADJ.MULTI_SCHEME_ID,
ADJ.SCHEME,
ADJ.ID,
ADJ.CLAIM_ID,
ADJ.SITE_NUMBER,
ADJ.ZONE,
ADJ.CRP_TYPE,
ADJ.PERIOD,
WS.KEY AS PERIOD_KEY,
MT.NAME AS MATERIAL_TYPE,
ADJ.ENTRY_TYPE,
ADJ.ENTRY_TYPE_DESCRIPTION,
ADJ.STATUS,
ADJ.MATERIAL_TYPE_ID,
ADJ.CLAIM_QTY,
ADJ.PAYMENT_TYPE,
ADJ.UOM,
CASE WHEN MT.NAME = 'Ineligible Containers' THEN 0 ELSE ADJ.CLAIM_QTY * (NF.CENTS_PER_CONTAINER_EX_GST/100) END AS NETWORK_FEE_EX_GST,
CASE WHEN MT.NAME = 'Ineligible Containers' THEN 0 ELSE ADJ.CLAIM_QTY * (1/11) END AS REFUND_AMOUNT_EX_GST,
ADJ.CLAIM_SUBMITTED_DATE_UTC,
ADJ.CLAIM_SUBMITTED_DATE,
ADJ.CUTOFF_DATE_KEY_VIC AS SUBMISSION_CUTOFF_DATE,
ADJ.CLAIM_SUBMITTED_DATE_KEY,
ADJ.ADJUSTMENT_SUBMITTED_DATE_UTC,
ADJ.ADJUSTMENT_SUBMITTED_DATE_KEY,
ADJ.PAYMENT_DATE_VIC AS PAYMENT_DATE_VIC,
ADJ.PAYMENT_DATE_KEY_VIC AS PAYMENT_DATE_KEY_VIC,
ADJ.CLAIM_SUBMITTED_BY,
ADJ.ADJUSTMENT_SUBMITTED_BY,
ADJ.LATE_SYNC
FROM NOP_ADJ_RAW AS ADJ
LEFT JOIN REF_DATE AS WS  --10 K ROWS
ON ADJ.PERIOD = WS.YEAR_WEEK_ISO AND WS.DAY_OF_WEEK = 2 
INNER JOIN {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS MT
ON ADJ.MATERIAL_TYPE_ID = MT.ID
LEFT JOIN {{ ref('NETWORK_FEE') }} AS NF  --56 ROWS
ON NF.MULTI_SCHEME_ID =ADJ.MULTI_SCHEME_ID  AND LEFT(ADJ.MULTI_SCHEME_ID,5) = MT.MULTI_SCHEME_ID
AND NF.MATERIAL_TYPE_ID = ADJ.MATERIAL_TYPE_ID
AND WS.PD_KEY BETWEEN NF.EFFECTIVE_FROM AND NVL(EFFECTIVE_TO, '99991101')

)

SELECT

--Fact Key
 {{ dbt_utils.generate_surrogate_key(['C.ID']) }} AS FACT_NOP_CLAIM_KEY

--Foreign Key
, {{ dbt_utils.generate_surrogate_key(["TO_NUMBER(C.MULTI_SCHEME_ID, 38, 0)"]) }} AS DIM_SCHEME_KEY
, {{ dbt_utils.generate_surrogate_key(['C.MATERIAL_TYPE_ID']) }} AS DIM_MATERIAL_TYPE_KEY
, {{ dbt_utils.generate_surrogate_key(['C.SITE_NUMBER']) }} AS DIM_SITE_CRP_KEY
, {{ dbt_utils.generate_surrogate_key(['C.PERIOD_KEY']) }} AS DIM_DATE_PERIOD_KEY
, {{ dbt_utils.generate_surrogate_key(['C.CLAIM_SUBMITTED_DATE_KEY']) }} as DIM_DATE_CLAIM_SUBMITTED_LOCAL_KEY
, {{ dbt_utils.generate_surrogate_key(['C.PAYMENT_DATE_KEY_VIC']) }} as DIM_DATE_PAYMENT_KEY
--, {{ dbt_utils.generate_surrogate_key(["TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(C.ADJUSTMENT_SUBMITTED_DATE_UTC AS TIMESTAMP)),'YYYYMMDD')"]) }} as DIM_DATE_ADJ_SUBMITTED_LOCAL_KEY
--, {{ dbt_utils.generate_surrogate_key(['PS.PARTICIPANT_ID']) }} AS DIM_B2B_SUPPLIER_KEY

--Natural Key Cols
, C.CLAIM_ID AS CLAIM_ID
, C.SITE_NUMBER AS SITE_NUMBER
, C.PAYMENT_TYPE AS PAYMENT_METHOD
, C.LATE_SYNC AS LATE_SYNC
, C.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID

--Attributes
,TO_NUMBER(C.MULTI_SCHEME_ID, 38, 0) AS MULTI_SCHEME_ID
, C.SCHEME
, PS.SITE_NAME AS SITE_NAME
, PS.PARTICIPANT_ID AS SUPPLIER_ID
, P.PARTICIPANT_NUMBER AS SUPPLIER_NUMBER
, P.PARTICIPANT_NAME AS SUPPLIER_NAME
, C.PERIOD AS PERIOD
, C.PERIOD_KEY AS PERIOD_DATE_ID
, C.SUBMISSION_CUTOFF_DATE
, C.ENTRY_TYPE AS ENTRY_TYPE
, C.ENTRY_TYPE_DESCRIPTION AS ENTRY_TYPE_DESC
, C.STATUS AS CLAIM_STATUS
, C.CLAIM_SUBMITTED_DATE AS CLAIM_SUBMITTED_LOCAL_DATETIME
, C.CLAIM_SUBMITTED_DATE_KEY AS CLAIM_SUBMITTED_LOCAL_DATE_ID
, C.ADJUSTMENT_SUBMITTED_DATE_UTC  AS ADJUSTMENT_SUBMITTED_LOCAL_DATETIME
, C.ADJUSTMENT_SUBMITTED_DATE_KEY  AS ADJUSTMENT_SUBMITTED_LOCAL_DATE_ID
, C.PAYMENT_DATE_VIC AS PAYMENT_DATE
, C.PAYMENT_DATE_KEY_VIC AS PAYMENT_DATE_ID
, C.MATERIAL_TYPE
, C.UOM
, C.CLAIM_SUBMITTED_DATE_UTC AS CLAIM_SUBMITTED_UTC_DATETIME
, C.CLAIM_SUBMITTED_BY AS CLAIM_SUBMITTED_BY

--Metrics
, C.CLAIM_QTY AS CLAIM_QTY
, C.NETWORK_FEE_EX_GST
, C.REFUND_AMOUNT_EX_GST
, RA.AVG_CLAIM_QTY_1_MONTH_ROLLING AS AVG_CLAIM_QTY_1_MONTH_ROLLING
, RZ.AVG_CLAIM_QTY_1_MONTH_ROLLING AS AVG_CLAIM_QTY_1_MONTH_ROLLING_BY_ZONE
, RC.AVG_CLAIM_QTY_1_MONTH_ROLLING AS AVG_CLAIM_QTY_1_MONTH_ROLLING_BY_CRP_TYPE

--METADATA ATTRIBUTES
, SYSDATE() AS INSERT_UTC_DATETIME

FROM CLAIM_CONSOLIDATED C 
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS  -- 1,162,748 ROWS
ON C.SITE_NUMBER = PS.SITE_NUMBER
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANTS') }} AS P  -- 1,144,410 ROWS
ON PS.PARTICIPANT_ID = P.PARTICIPANT_ID
LEFT JOIN {{ ref('NOP_CLAIM_ROLLING_AVG') }} AS RA  -- 38696 ROWS
ON C.SITE_NUMBER = RA.SITE_NUMBER
AND C.PERIOD = RA.PERIOD
LEFT JOIN {{ ref('NOP_CLAIM_ROLLING_AVG_ZONE') }} AS RZ  -- 38,717 ROWS
ON C.SITE_NUMBER = RZ.SITE_NUMBER
AND C.ZONE = RZ.ZONE
AND C.PERIOD = RZ.PERIOD
LEFT JOIN {{ ref('NOP_CLAIM_ROLLING_AVG_CRP_TYPE') }} AS RC  -- 38,717 ROWS
ON C.SITE_NUMBER = RC.SITE_NUMBER
AND C.CRP_TYPE = RC.CRP_TYPE
AND C.PERIOD = RC.PERIOD 