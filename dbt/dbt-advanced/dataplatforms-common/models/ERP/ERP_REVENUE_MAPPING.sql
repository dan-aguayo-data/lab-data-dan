SELECT
NVL(U.MULTI_SCHEME_ID, '-1') AS MULTI_SCHEME_ID
, NVL(U.SCHEME, 'CES') AS SCHEME
, U.REVENUE_ANALYSIS_SORT AS REVENUE_ANALYSIS_SORT
, U.PAYMENT_PROCESSES_AP_SORT AS PAYMENT_PROCESSES_AP_SORT
, U.REVENUE_ANALYSIS_CLASSIFICATION AS REVENUE_ANALYSIS_CLASSIFICATION
, U.CLASSIFICATION AS CLASSIFICATION
, U.SOURCE AS SOURCE
, U.COMMENTS AS COMMENTS
, U.ACCOUNTING_MONTH_KEY AS ACCOUNTING_MONTH_KEY
, SUM(U.AMOUNT) AS AMOUNT
, (CASE WHEN U.CLASSIFICATION = 'Processing Refunds (MRF)' THEN 1.1 ELSE 1 END) * ABS(SUM(U.AMOUNT)) AS AMOUNT_INCLUDING_GST
, ABS(SUM(U.AMOUNT)) / (CASE WHEN U.SOURCE in ('BAS Payments','Inv / Accrual') THEN  1 ELSE 1.1 END) AS AMOUNT_EXCLUDING_GST
, SYSDATE() AS INSERT_DATE_UTC
FROM (
    SELECT
    L.MULTI_SCHEME_ID
    , L.SCHEME
    , M.REVENUE_ANALYSIS_SORT
    , M.PAYMENT_PROCESSES_AP_SORT
    , M.REVENUE_ANALYSIS_CLASSIFICATION
    , M.CLASSIFICATION
    , M.SOURCE
    , M.COMMENTS
    , AP.ACCOUNTING_MONTH_KEY
    , AP.AMOUNT
    FROM {{ source('CES_FINANCE', 'ERP_REVENUE_MAPPING') }} AS M
    LEFT JOIN
        (SELECT
         APT.SUPPLIER_NUMBER
         , NVL(APT.PAY_GROUP ,'') AS PAY_GROUP
         , APT.LEDGER_NAME
         , TO_CHAR(DATE_TRUNC('MONTH', APT.INV_DIST_ACCOUNTING_DATE),'YYYYMMDD') AS ACCOUNTING_MONTH_KEY
         , SUM(CASE WHEN (APT.PAY_GROUP IN ('MRF RECOVERY','') AND APT.COST_CENTER_CODE = '0000') THEN 0 ELSE APT.TOTAL_DISTRIBUTION_AMOUNT END) AS AMOUNT
         , APT.COST_CENTER_CODE 
         FROM {{ source('CES_ERP', 'AP_TRANSACTIONS') }} AS APT
         WHERE APT.LEDGER_NAME IN ('Scheme Ledger AU','Processor QLD Ledger AU') AND APT.BUSINESS_UNIT_NAME <> 'PRO QLD BU' AND APT.SUPPLIER_NAME <> 'CONTAINER EXCHANGE(SERVICES)PTY LTD'
         GROUP BY
         APT.SUPPLIER_NUMBER
         , NVL(APT.PAY_GROUP ,'')
         , APT.LEDGER_NAME
         , TO_CHAR(DATE_TRUNC('MONTH', APT.INV_DIST_ACCOUNTING_DATE),'YYYYMMDD')
         , APT.COST_CENTER_CODE
         ) AP
    ON CASE WHEN M.PAYMENT_PROCESSES_AP_SORT IN ('14','17') THEN AP.SUPPLIER_NUMBER = TO_CHAR(M.SUPPLIER_NUMBER) WHEN M.PAYMENT_PROCESSES_AP_SORT = 8 THEN AP.PAY_GROUP = NVL(M.PAY_GROUP,'') AND AP.SUPPLIER_NUMBER <> '1000084' ELSE AP.PAY_GROUP = NVL(M.PAY_GROUP,'') END
    LEFT JOIN {{ ref('ERP_LEDGER') }} AS L
    ON L.LEDGER_NAME = AP.LEDGER_NAME
    WHERE M.SOURCE_TABLE = 'AP_TRANSACTIONS'
    UNION ALL
    SELECT
    AR.MULTI_SCHEME_ID
    , AR.SCHEME
    , M.REVENUE_ANALYSIS_SORT
    , M.PAYMENT_PROCESSES_AP_SORT
    , M.REVENUE_ANALYSIS_CLASSIFICATION
    , M.CLASSIFICATION
    , M.SOURCE
    , M.COMMENTS
    , LEFT(AR.ACCOUNTING_DATE_KEY,6) || '01' AS ACCOUNTING_MONTH_KEY
    , NVL(AR.AMOUNT_DR,0) + NVL(AR.AMOUNT_CR,0) AS AMOUNT
    FROM {{ source('CES_FINANCE', 'ERP_REVENUE_MAPPING') }} AS M
    LEFT JOIN {{ ref('ERP_GL_TRANSACTIONS') }} AS AR
    ON M.TRANSACTION_TYPE = AR.TRANSACTION_TYPE AND AR.LEDGER_NAME = 'Scheme Ledger AU' AND AR.EVENT_TYPE_NAME <> 'Credit Memo Updated' AND AR.ACCOUNT <> '21020 - GST Output' AND AR.COST_CENTER_PARENT = 'Balance Sheet'
    WHERE M.SOURCE_TABLE = 'GL_TRANSACTIONS' AND AR.BUSINESS_CLASS_NAME = 'Receivable' 
    UNION ALL
    SELECT
    B.MULTI_SCHEME_ID
    , B.SCHEME
    , M.REVENUE_ANALYSIS_SORT
    , M.PAYMENT_PROCESSES_AP_SORT
    , M.REVENUE_ANALYSIS_CLASSIFICATION
    , M.CLASSIFICATION
    , M.SOURCE
    , M.COMMENTS
    , TO_CHAR(DATE_TRUNC('MONTH', B.PERIOD),'YYYYMMDD') AS ACCOUNTING_MONTH_KEY
    , B.BASE_PERIOD_NET_ACTIVITY AS AMOUNT
    FROM {{ source('CES_FINANCE', 'ERP_REVENUE_MAPPING') }} AS M
    LEFT JOIN {{ ref('ERP_BALANCES') }} AS B
    ON B.ACCOUNT_CODE = M.ACCOUNT_CODE AND B.LEDGER_NAME = 'Scheme Ledger AU'
    WHERE M.SOURCE_TABLE = 'GL_BALANCES'
    UNION ALL
    SELECT
    -1 AS MULTI_SCHEME_ID
    , 'CES' AS SCHEME
    , M.REVENUE_ANALYSIS_SORT
    , M.PAYMENT_PROCESSES_AP_SORT
    , M.REVENUE_ANALYSIS_CLASSIFICATION
    , M.CLASSIFICATION
    , M.SOURCE
    , M.COMMENTS
    , B.PERIOD AS ACCOUNTING_MONTH_KEY
    , B.AMOUNT AS AMOUNT
    FROM {{ source('CES_FINANCE', 'ERP_REVENUE_MAPPING') }} AS M
    INNER JOIN {{ source('CES_FINANCE', 'AP_ADHOC_MANUAL_INPUT') }} AS B
    ON M.SOURCE_TABLE = 'AP_ADHOC_MANUAL_INPUT'
    UNION ALL
    SELECT
    -1 AS MULTI_SCHEME_ID
    , 'CES' AS SCHEME
    , M.REVENUE_ANALYSIS_SORT
    , M.PAYMENT_PROCESSES_AP_SORT
    , M.REVENUE_ANALYSIS_CLASSIFICATION
    , M.CLASSIFICATION
    , M.SOURCE
    , M.COMMENTS
    , FT.PERIOD_KEY AS ACCOUNTING_MONTH_KEY
    , CASE WHEN M.TRANSACTION_SUMMARY IS NULL THEN FT.TOTAL_FEE * 1.1 ELSE FT.TOTAL_FEE END AS AMOUNT
    FROM {{ source('CES_FINANCE', 'ERP_REVENUE_MAPPING') }} AS M
    INNER JOIN (
                SELECT
                COALESCE(F.ACCOUNTING_MONTH_KEY,MA.PERIOD) AS PERIOD_KEY,
                SUM(CASE WHEN NVL(MA.RATE_MARGIN_TYPE,RM.RATE_MARGIN_TYPE) IN ('Percent','Rate') THEN NVL(MA.RATE_MARGIN,RM.RATE_MARGIN) * NVL(MA.DRIVER_VALUE,F.AMOUNT) ELSE NVL(MA.DRIVER_VALUE,F.AMOUNT) END) AS TOTAL_FEE
                FROM 
                {{ source('CES_FINANCE', 'CES_SERVICE_FEE_SUMMARY') }} AS RM -- MAPPING
                LEFT JOIN (
                            --AP ERP_REVENUE_MAPPING
                            SELECT
                            RM.SORT AS ID,
                            TO_CHAR(DATE_TRUNC('MONTH', AP.INV_DIST_ACCOUNTING_DATE),'YYYYMMDD') AS ACCOUNTING_MONTH_KEY,
                            SUM(AP.TOTAL_DISTRIBUTION_AMOUNT) AS AMOUNT
                            FROM {{ source('CES_FINANCE', 'ERP_REVENUE_MAPPING') }} AS M 
                            INNER JOIN {{ source('CES_FINANCE', 'CES_SERVICE_FEE_SUMMARY') }} AS RM -- MAPPING
                            ON RM.AP_LINK_LOGIC = M.REVENUE_ANALYSIS_SORT AND RM.AP_LINK_LOGIC IN ('6','7','8')
                            LEFT JOIN {{ source('CES_ERP', 'AP_TRANSACTIONS') }} AS AP-- AMOUNT
                            ON AP.PAY_GROUP = M.PAY_GROUP
                            WHERE AP.LEDGER_NAME IN ('Scheme Ledger AU','Processor QLD Ledger AU') AND AP.BUSINESS_UNIT_NAME <> 'PRO QLD BU' AND AP.SUPPLIER_NAME <> 'CONTAINER EXCHANGE(SERVICES)PTY LTD'
                            GROUP BY 
                            RM.SORT,
                            TO_CHAR(DATE_TRUNC('MONTH', AP.INV_DIST_ACCOUNTING_DATE),'YYYYMMDD') 
 
                            UNION ALL
                            --AR + AP - 1.7 Material Brokerage Auction Fee 
                            SELECT
                            9 AS ID,
                            C.ACCOUNTING_MONTH_KEY AS ACCOUNTING_MONTH_KEY,
                            SUM(C.AMOUNT) AS AMOUNT
                            FROM (
                                  SELECT --PROCESSOR NEGATIVE
                                  B.INVOICE_NUMBER,
                                  LEFT(B.ACCOUNTING_DATE_KEY,6) || '01' AS ACCOUNTING_MONTH_KEY,
                                  (CASE WHEN SUM((B.TOTAL_DISTRIBUTION_AMOUNT/1.1) * 0.026) > 14.5 THEN SUM((B.TOTAL_DISTRIBUTION_AMOUNT/1.1) * 0.026) ELSE 14.5 END) AS AMOUNT
                                  FROM {{ ref('ERP_AP_TRANSACTIONS') }} AS B
                                  WHERE B.PAY_GROUP = 'RECYCLER NEGATIVE AUCTION' AND B.BUSINESS_UNIT_NAME = 'Scheme QLD BU' AND B.LEDGER_NAME IN ('Scheme Ledger AU','Processor QLD Ledger AU')
                                  GROUP BY LEFT(B.ACCOUNTING_DATE_KEY,6) || '01', B.INVOICE_NUMBER
                                  UNION
                                  SELECT 
                                  C.TRANSACTION_NUMBER AS INVOICE_NUMBER,
                                  LEFT(C.ACCOUNTING_DATE_KEY,6) || '01' AS ACCOUNTING_MONTH_KEY,
                                  (CASE WHEN SUM((C.AMOUNT_DR/1.1) * 0.026) > 14.5 THEN SUM((C.AMOUNT_DR/1.1) * 0.026) ELSE 14.5 END) AS AMOUNT
                                  FROM {{ ref('ERP_GL_TRANSACTIONS') }} AS C
                                  WHERE C.TRANSACTION_TYPE IN ('AuctionPrcRecyclrInv','AuctionPrcRecyclr Cr') AND C.BUSINESS_UNIT_NAME = 'Scheme QLD BU' AND C.LEDGER_NAME IN ('Scheme Ledger AU','Processor QLD Ledger AU')
                                  GROUP BY LEFT(C.ACCOUNTING_DATE_KEY,6) || '01', C.TRANSACTION_NUMBER) C --PROCESSOR_POSITIVE
                            GROUP BY C.ACCOUNTING_MONTH_KEY
                            UNION ALL    
                            --AR ERP_REVENUE_MAPPING
                            SELECT
                            7 AS ID,
                            LEFT(C.ACCOUNTING_DATE_KEY,6) || '01' AS ACCOUNTING_MONTH_KEY,
                            SUM(C.AMOUNT_DR)*(2/3) AS AMOUNT
                            FROM {{ ref('ERP_GL_TRANSACTIONS') }} AS C
                            WHERE C.JOURNAL_CATEGORY_NAME = 'Adjustment' AND C.COST_CENTER = '8100 - Marketing' AND C.LEDGER_NAME IN ('Scheme Ledger AU','Processor QLD Ledger AU','Service Co Ledger AU')
                            GROUP BY LEFT(C.ACCOUNTING_DATE_KEY,6) || '01'
 
                            UNION ALL
                            --AR ERP_REVENUE_MAPPING
                            SELECT
                            8 AS ID,
                            LEFT(C.ACCOUNTING_DATE_KEY,6) || '01' AS ACCOUNTING_MONTH_KEY,
                            SUM(C.AMOUNT_DR) AS AMOUNT
                            FROM {{ ref('ERP_GL_TRANSACTIONS') }} AS C
                            WHERE C.JOURNAL_CATEGORY_NAME IN ('Purchase Invoices','Payroll','Adjustment') AND C.COST_CENTER = '8400 - Call Centre' AND C.LEDGER_NAME IN ('Scheme Ledger AU','Processor QLD Ledger AU','Service Co Ledger AU')
                            GROUP BY LEFT(C.ACCOUNTING_DATE_KEY,6) || '01'
                  ) F ON RM.SORT = F.ID
 
                  --MANUAL ENTRY/ADJUSTMENTS BY ESHAN
                  FULL JOIN {{ source('CES_FINANCE', 'SERVICE_FEE_MANUAL_INPUT') }} AS MA
                  ON MA.SORT = RM.SORT AND MA.PERIOD = F.ACCOUNTING_MONTH_KEY AND MA.SORT > 2--EXCLUDE AP SUMMARY ID MANUALLY UPDATED
                  WHERE NVL(RM.AP_LINK_LOGIC,0) NOT IN ('6','8') 
                  GROUP BY COALESCE(F.ACCOUNTING_MONTH_KEY,MA.PERIOD)
                  ---QUALIFY ROW_NUMBER() OVER (PARTITION BY COALESCE(MA.PERIOD,F.ACCOUNTING_MONTH_KEY),RM.SORT ORDER BY RM.AP_LINK_LOGIC) = 1
              ) FT     
              ON M.PAYMENT_PROCESSES_AP_SORT = 13
) U
GROUP BY 
U.MULTI_SCHEME_ID
, U.SCHEME
, U.REVENUE_ANALYSIS_SORT
, U.PAYMENT_PROCESSES_AP_SORT
, U.REVENUE_ANALYSIS_CLASSIFICATION
, U.CLASSIFICATION
, U.SOURCE
, U.COMMENTS
, U.ACCOUNTING_MONTH_KEY