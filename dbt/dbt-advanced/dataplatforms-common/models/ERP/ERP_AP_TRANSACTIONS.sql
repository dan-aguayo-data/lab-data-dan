SELECT
L.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, L.SCHEME AS SCHEME
, MAX(B.CONCATENATED_SEGMENTS || '-' || B.INVOICE_ID || '-' || B.DISTRIBUTION_LINE_NUM || '-' || B.LINE_NUMBER) AS ID
, A.ACCOUNT_CODE || ' - ' ||  A.ACCOUNT_DESC AS ACCOUNT
, B.SCHEME_CODE AS SCHEME_CODE
, TO_CHAR(B.INVOICE_DATE, 'YYYYMMDD') AS INVOICE_DATE
, TO_CHAR(B.INV_DIST_ACCOUNTING_DATE, 'YYYYMMDD') AS ACCOUNTING_DATE_KEY
, B.INVOICE_TYPE_NAME AS INVOICE_TYPE_NAME
, B.INVOICE_CURRENCY AS INVOICE_CURRENCY
, B.BUSINESS_UNIT_NAME AS BUSINESS_UNIT_NAME
, B.LEGAL_ENTITY_NAME AS LEGAL_ENTITY_NAME
, B.SUPPLIER_NAME AS SUPPLIER_NAME
, B.INVOICE_SOURCE_NAME AS INVOICE_SOURCE_NAME
, B.PAY_GROUP AS PAY_GROUP
, B.LEDGER_NAME AS LEDGER_NAME
, SUM(B.TOTAL_DISTRIBUTION_AMOUNT) AS TOTAL_DISTRIBUTION_AMOUNT
, MAX(B.INVOICE_AMOUNT) AS INVOICE_AMOUNT
, SUM(B.INVOICES_WITHHELD_TAX_AMOUNT) AS INVOICES_WITHHELD_TAX_AMOUNT
, SUM(B.QUANTITY_INVOICED) AS QUANTITY_INVOICED
, SUM(B.UNIT_PRICE) AS UNIT_PRICE
, B.INVOICE_NUM AS INVOICE_NUMBER
, NVL(B.ENTITY_CODE || ' - ' ||  E.ENTITY_DESC, B.ENTITY_CODE) AS ENTITY
, E.ENTITY_L31_CODE|| ' - ' ||  E.ENTITY_L31_DESC AS ENTITY_PARENT
, B.COST_CENTER_CODE || ' - ' ||  C.COST_CENTER_DESC AS COST_CENTER
, CC.COST_CENTER_MAP_L_1 AS COST_CENTER_PARENT
, CASE WHEN (LEFT(A.ACCOUNT_CODE || ' - ' ||  A.ACCOUNT_DESC, 5) IN ('52005', '53006', '52010') AND COST_CENTER IN ('1600 - Logistics') ) THEN 'Logistics'  WHEN B.SUPPLIER_NAME IN ('CIRCULAR ECONOMY SYSTEMS PTY LTD','CIRCULAR ECONOMY SYSTEMS PTY LTD.','CONTAINER EXCHANGE(SERVICES)PTY LTD') THEN 'Service Fees'  WHEN B.SUPPLIER_NAME IN ('Australian Taxation Office') THEN 'BAS' ELSE 'Other Direct' END AS MANUAL_CATEGORY
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_ERP', 'AP_TRANSACTIONS') }} AS B
LEFT JOIN {{ ref('ERP_LEDGER') }} AS L
ON B.LEDGER_NAME = L.LEDGER_NAME
LEFT JOIN {{ source('CES_ERP', 'GL_ENTITY') }} AS E
ON B.ENTITY_CODE = E.ENTITY_CODE
AND E.ENTITY_TREE_CODE = L.ENTITY_TREE_CODE
INNER JOIN {{ source('CES_ERP', 'GL_ACCOUNT') }} AS A
ON B.ACCOUNT_CODE = A.ACCOUNT_CODE
AND A.ACCOUNT_TREE_CODE = L.ACCOUNT_TREE_CODE
LEFT JOIN {{ source('CES_ERP', 'GL_COST_CENTER') }} AS C
ON B.COST_CENTER_CODE= C.COST_CENTER_CODE
AND C.COST_CENTER_TREE_CODE= L.COST_CENTRE_TREE_CODE
LEFT JOIN {{ source('CES_FINANCE', 'COST_CENTRE_MAPPING') }} AS CC
ON B.COST_CENTER_CODE = CC.COST_CENTER_CODE
GROUP BY
L.MULTI_SCHEME_ID
, L.SCHEME
, A.ACCOUNT_CODE || ' - ' ||  A.ACCOUNT_DESC
, B.SCHEME_CODE
, TO_CHAR(B.INVOICE_DATE, 'YYYYMMDD')
, B.INVOICE_TYPE_NAME
, TO_CHAR(B.INV_DIST_ACCOUNTING_DATE, 'YYYYMMDD')
, B.INV_DIST_POSTING_STATUS
, B.INV_DIST_REVERSAL_STATUS
, B.MATCH_STATUS
, B.INVOICE_CURRENCY
, B.MATCH_TYPE
, B.BUSINESS_UNIT_NAME
, B.LEGAL_ENTITY_NAME
, B.SUPPLIER_NAME
, B.MATCH_STATUS_CODE
, B.MATCH_TYPE_CODE
, B.INVOICE_SOURCE_NAME
, B.PAY_GROUP
, B.LEDGER_NAME
, NVL(B.ENTITY_CODE || ' - ' ||  E.ENTITY_DESC, B.ENTITY_CODE)
, E.ENTITY_L31_CODE|| ' - ' ||  E.ENTITY_L31_DESC
, B.COST_CENTER_CODE || ' - ' ||  C.COST_CENTER_DESC
, CC.COST_CENTER_MAP_L_1
, C.COST_CENTER_DESC
, B.INVOICE_NUM
