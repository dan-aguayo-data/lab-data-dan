SELECT
L.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, L.SCHEME AS SCHEME
, MAX(NVL(B.JOURNAL_HEADER_ID || '-' || B.JOURNAL_LINE_NUM, J.JOURNAL_HEADER_ID || '-' || J.JOURNAL_LINE_NUM)) AS ID
, TO_CHAR(B.INVOICE_DATE, 'YYYYMMDD') AS INVOICE_DATE
, TO_CHAR(NVL(B.POSTING_DATE,J.POSTING_DATE), 'YYYY-MM') AS POSTING_DATE
, TO_CHAR(NVL(B.ACCOUNTING_DATE,J.ACCOUNTING_DATE), 'YYYYMMDD') AS ACCOUNTING_DATE_KEY
, B.ACCOUNTING_ENTRY_TYPE AS ACCOUNTING_ENTRY_TYPE
, NVL(B.BALANCE_TYPE,J.BALANCE_TYPE) AS BALANCE_TYPE
, B.BUSINESS_CLASS_NAME AS BUSINESS_CLASS_NAME
, B.BUSINESS_UNIT_NAME AS BUSINESS_UNIT_NAME
, B.CURRENCY_CONVERSION_DESC AS CURRENCY_CONVERSION_DESC
, NVL(B.CURRENCY_CONVERSION_RATE, J.CONVERSION_RATE) AS CURRENCY_CONVERSION_RATE
, NVL(B.CURRENCY_CONVERSION_TYPE, J.CONVERSION_RATE_TYPE) AS CURRENCY_CONVERSION_TYPE
, TO_CHAR(B.DATE_COMPLETED, 'YYYY-MM') AS DATE_COMPLETED
, B.EVENT_TYPE_CODE AS EVENT_TYPE_CODE
, B.EVENT_TYPE_NAME AS EVENT_TYPE_NAME
, NVL(B.JOURNAL_CATEGORY_NAME,J.JOURNAL_CATEGORY_NAME) AS JOURNAL_CATEGORY_NAME
, TO_CHAR(NVL(B.JOURNAL_CREATED_DATE,J.JOURNAL_CREATED_DATE), 'YYYY-MM') AS JOURNAL_CREATED_DATE
, B.OVERRIDE_REASON AS OVERRIDE_REASON
, NVL(B.SOURCE_JOURNAL_SOURCE_DESC,J.SOURCE_JOURNAL_SOURCE_DESC) AS JOURNAL_SOURCE_DESC
, NVL(B.SOURCE_JOURNAL_SOURCE_NAME,J.SOURCE_JOURNAL_SOURCE_NAME) AS JOURNAL_SOURCE_NAME
, B.DOCUMENT_CURRENCY_NAME AS DOCUMENT_CURRENCY_NAME
, NVL(B.LEDGER_NAME,J.LEDGER_NAME) AS LEDGER_NAME
, SUM(NVL(B.AMOUNT_CR,J.AMOUNT_CR)) AS AMOUNT_CR
, CASE WHEN NVL(B.JOURNAL_CATEGORY_NAME,J.JOURNAL_CATEGORY_NAME) = 'Credit Memo' THEN -1* SUM(NVL(B.AMOUNT_DR,J.AMOUNT_DR)) ELSE SUM(NVL(B.AMOUNT_DR,J.AMOUNT_DR)) END AS AMOUNT_DR
, CASE WHEN NVL(B.COST_CENTER_CODE,J.COST_CENTER_CODE) IN ('8400','8100','8500', '5500') THEN J.JOURNAL_LINE_DESC ELSE NULL END AS JOURNAL_LINE_DESC
, J.JOURNAL_NAME AS JOURNAL_NAME
, J.JOURNAL_STATUS AS JOURNAL_STATUS 
, B.TRANSACTION_CLASS AS TRANSACTION_CLASS
, B.TRANSACTION_TYPE AS TRANSACTION_TYPE
, B.TRANSACTION_COMPLETE AS TRANSACTION_COMPLETE
, CASE WHEN B.TRANSACTION_TYPE IN ('AuctionPrcRecyclr Cr','AuctionPrcRecyclrInv', 'AuctionMRFRecyclrInv', 'AuctionMRFRecyclr Cr') THEN B.AR_TRANSACTION_NUMBER ELSE NULL END AS TRANSACTION_NUMBER
, NVL(B.ACCOUNT_CODE,J.ACCOUNT_CODE) || ' - ' ||  A.ACCOUNT_DESC AS ACCOUNT
, NVL(B.COST_CENTER_CODE,J.COST_CENTER_CODE) || ' - ' ||  C.COST_CENTER_DESC AS COST_CENTER
, CC.COST_CENTER_MAP_L_1 AS COST_CENTER_PARENT
, CASE WHEN NVL(B.COST_CENTER_CODE,J.COST_CENTER_CODE) IN ('8400','8100','8500') THEN B.PARTY_NAME ELSE NULL END AS PARTY_NAME
, B.BILL_TO_CUSTOMER AS CUSTOMER_NAME
, CASE WHEN NVL(B.COST_CENTER_CODE,J.COST_CENTER_CODE) IN ('8400', '5500') THEN J.STATISTICAL_QUANTITY ELSE NULL END AS STATISTICAL_QUANTITY
, CASE WHEN NVL(B.COST_CENTER_CODE,J.COST_CENTER_CODE) IN ('8400', '5500') THEN J.JOURNAL_BATCH_NAME ELSE NULL END AS JOURNAL_BATCH_NAME
, CASE WHEN NVL(B.COST_CENTER_CODE,J.COST_CENTER_CODE) IN ('8400', '5500') THEN J.LEDGER_CURRENCY ELSE NULL END AS LEDGER_CURRENCY
, CASE WHEN NVL(B.COST_CENTER_CODE,J.COST_CENTER_CODE) IN ('8400', '5500') THEN J.FUND_STATUS_MEANING ELSE NULL END AS FUND_STATUS_MEANING
, CASE WHEN NVL(B.COST_CENTER_CODE,J.COST_CENTER_CODE) IN ('8400', '5500') THEN J.JOURNAL_LINE_NUM ELSE NULL END AS JOURNAL_LINE_NUM
, CASE WHEN NVL(B.COST_CENTER_CODE,J.COST_CENTER_CODE) IN ('8400', '5500') THEN J.LINE_CURRENCY_CODE ELSE NULL END AS LINE_CURRENCY_CODE
, CASE WHEN UPPER(NVL(B.LEDGER_NAME,J.LEDGER_NAME)) IN ('SERVICE CO LEDGER AU') THEN NVL(B.SCHEME_CODE, J.SCHEME_CODE) ELSE NULL END AS SCHEME_CODE
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_ERP', 'GL_TRANSACTIONS_SUBLEDGER') }} AS B
FULL JOIN {{ source('CES_ERP', 'GL_JOURNALS') }} AS J
ON J.JOURNAL_HEADER_ID = B.GL_JOURNAL_HEADER_ID
AND J.JOURNAL_LINE_NUM = B.GL_JOURNAL_LINE_NUM
LEFT JOIN {{ ref('ERP_LEDGER') }} AS L
ON NVL(B.LEDGER_NAME,J.LEDGER_NAME) = L.LEDGER_NAME
INNER JOIN {{ source('CES_ERP', 'GL_ACCOUNT') }} AS A
ON NVL(B.ACCOUNT_CODE,J.ACCOUNT_CODE) = A.ACCOUNT_CODE
AND A.ACCOUNT_TREE_CODE = L.ACCOUNT_TREE_CODE
LEFT JOIN {{ source('CES_ERP', 'GL_COST_CENTER') }} AS C
ON NVL(B.COST_CENTER_CODE,J.COST_CENTER_CODE)= C.COST_CENTER_CODE
AND C.COST_CENTER_TREE_CODE= L.COST_CENTRE_TREE_CODE
LEFT JOIN {{ source('CES_FINANCE', 'COST_CENTRE_MAPPING') }} AS CC
ON NVL(B.COST_CENTER_CODE,J.COST_CENTER_CODE) = CC.COST_CENTER_CODE
GROUP BY
B.SCHEME_CODE
, TO_CHAR(B.INVOICE_DATE, 'YYYYMMDD')
, TO_CHAR(NVL(B.POSTING_DATE,J.POSTING_DATE), 'YYYY-MM')
, TO_CHAR(NVL(B.ACCOUNTING_DATE,J.ACCOUNTING_DATE), 'YYYYMMDD')
, B.ACCOUNTING_ENTRY_TYPE
, NVL(B.BALANCE_TYPE,J.BALANCE_TYPE)
, B.BUSINESS_CLASS_NAME
, B.BUSINESS_UNIT_NAME
, B.CURRENCY_CONVERSION_DESC
, NVL(B.CURRENCY_CONVERSION_RATE, J.CONVERSION_RATE)
, NVL(B.CURRENCY_CONVERSION_TYPE, J.CONVERSION_RATE_TYPE)
, TO_CHAR(B.DATE_COMPLETED, 'YYYY-MM')
, B.EVENT_TYPE_CODE
, B.EVENT_TYPE_NAME
, NVL(B.JOURNAL_CATEGORY_NAME,J.JOURNAL_CATEGORY_NAME)
, TO_CHAR(NVL(B.JOURNAL_CREATED_DATE,J.JOURNAL_CREATED_DATE), 'YYYY-MM')
, B.OVERRIDE_REASON
, NVL(B.SOURCE_JOURNAL_SOURCE_DESC,J.SOURCE_JOURNAL_SOURCE_DESC)
, NVL(B.SOURCE_JOURNAL_SOURCE_NAME,J.SOURCE_JOURNAL_SOURCE_NAME)
, B.DOCUMENT_CURRENCY_NAME
, NVL(B.LEDGER_NAME,J.LEDGER_NAME)
, L.MULTI_SCHEME_ID
, L.SCHEME
, NVL(B.ACCOUNT_CODE,J.ACCOUNT_CODE) || ' - ' ||  A.ACCOUNT_DESC
, NVL(B.COST_CENTER_CODE,J.COST_CENTER_CODE) || ' - ' ||  C.COST_CENTER_DESC
, CC.COST_CENTER_MAP_L_1
, CASE WHEN NVL(B.COST_CENTER_CODE,J.COST_CENTER_CODE) IN ('8400','8100','8500','5500') THEN J.JOURNAL_LINE_DESC ELSE NULL END
, CASE WHEN NVL(B.COST_CENTER_CODE,J.COST_CENTER_CODE) IN ('8400','8100','8500') THEN B.PARTY_NAME ELSE NULL END
, J.JOURNAL_NAME
, J.JOURNAL_STATUS
, B.TRANSACTION_CLASS
, B.TRANSACTION_TYPE
, B.TRANSACTION_COMPLETE
, CASE WHEN B.TRANSACTION_TYPE IN ('AuctionPrcRecyclr Cr','AuctionPrcRecyclrInv', 'AuctionMRFRecyclrInv', 'AuctionMRFRecyclr Cr') THEN B.AR_TRANSACTION_NUMBER ELSE NULL END
, B.BILL_TO_CUSTOMER
, CASE WHEN NVL(B.COST_CENTER_CODE,J.COST_CENTER_CODE) IN ('8400', '5500') THEN J.STATISTICAL_QUANTITY ELSE NULL END
, CASE WHEN NVL(B.COST_CENTER_CODE,J.COST_CENTER_CODE) IN ('8400', '5500') THEN J.JOURNAL_BATCH_NAME ELSE NULL END
, CASE WHEN NVL(B.COST_CENTER_CODE,J.COST_CENTER_CODE) IN ('8400', '5500') THEN J.LEDGER_CURRENCY ELSE NULL END
, CASE WHEN NVL(B.COST_CENTER_CODE,J.COST_CENTER_CODE) IN ('8400', '5500') THEN J.FUND_STATUS_MEANING ELSE NULL END
, CASE WHEN NVL(B.COST_CENTER_CODE,J.COST_CENTER_CODE) IN ('8400', '5500') THEN J.JOURNAL_LINE_NUM ELSE NULL END
, CASE WHEN NVL(B.COST_CENTER_CODE,J.COST_CENTER_CODE) IN ('8400', '5500') THEN J.LINE_CURRENCY_CODE ELSE NULL END
, CASE WHEN UPPER(NVL(B.LEDGER_NAME,J.LEDGER_NAME)) IN ('SERVICE CO LEDGER AU') THEN NVL(B.SCHEME_CODE, J.SCHEME_CODE) ELSE NULL END