SELECT
-1 AS MULTI_SCHEME_ID
, 'CES' AS SCHEME
, COALESCE(RM.SORT,MA.SORT) || COALESCE(RM.CODE,MA.CODE) || COALESCE(FO.FORECAST_DATE_KEY,F.ACCOUNTING_MONTH_KEY,MA.PERIOD) AS ID
, COALESCE(RM.CODE,MA.CODE) AS CODE
, COALESCE(RM.ITEM,MA.ITEM) AS ITEM
, COALESCE(RM.DRIVER,MA.DRIVER) AS DRIVER
, IFNULL(MA.DRIVER_VALUE,F.AMOUNT) AS DRIVER_VALUE
, CASE WHEN IFNULL(MA.RATE_MARGIN_TYPE,RM.RATE_MARGIN_TYPE) = 'Percent' THEN ROUND((IFNULL(MA.RATE_MARGIN,RM.RATE_MARGIN) * 100),2) || '%' ELSE IFNULL(MA.RATE_MARGIN,RM.RATE_MARGIN) END AS RATE_MARGIN
, IFNULL(MA.RATE_MARGIN_TYPE,RM.RATE_MARGIN_TYPE) AS RATE_MARGIN_TYPE
, FO.AMOUNT AS FORECAST
, COALESCE(RM.COMMENT,MA.COMMENT) AS COMMENT
, COALESCE(FO.FORECAST_DATE_KEY,F.ACCOUNTING_MONTH_KEY,MA.PERIOD) AS PERIOD_KEY
, COALESCE(RM.SORT,MA.SORT) AS SORT
, CASE WHEN IFNULL(MA.RATE_MARGIN_TYPE,RM.RATE_MARGIN_TYPE) IN ('Percent' ,'Rate') THEN IFNULL(MA.RATE_MARGIN,RM.RATE_MARGIN) * IFNULL(MA.DRIVER_VALUE,F.AMOUNT) ELSE IFNULL(MA.DRIVER_VALUE,F.AMOUNT) END AS TOTAL_FEE
, NVL((CASE WHEN IFNULL(MA.RATE_MARGIN_TYPE,RM.RATE_MARGIN_TYPE) IN ('Percent' ,'Rate') THEN IFNULL(MA.RATE_MARGIN,RM.RATE_MARGIN) * IFNULL(MA.DRIVER_VALUE,F.AMOUNT) ELSE IFNULL(MA.DRIVER_VALUE,F.AMOUNT) END),0) - NVL(FO.AMOUNT,0) AS VARIANCE
, SYSDATE() AS INSERT_DATE_UTC
FROM 
{{ source('CES_FINANCE', 'CES_SERVICE_FEE_SUMMARY_DEV') }} AS RM -- MAPPING
LEFT JOIN (
    --PPS
    SELECT
    RM.SORT AS ID,
    F.ACCOUNTING_MONTH_KEY,
    SUM(F.AMOUNT_INCLUDING_GST) AS AMOUNT
    FROM {{ ref('ERP_REVENUE_MAPPING_VIC') }} AS F 
    INNER JOIN {{ source('CES_FINANCE', 'CES_SERVICE_FEE_SUMMARY_DEV') }} AS RM -- MAPPING
    ON RM.SORT = 1 
    WHERE RM.SCHEME = 'VIC' 
    GROUP BY 
    RM.SORT,
    F.ACCOUNTING_MONTH_KEY
 
    UNION ALL
    --PRF
    SELECT
    RM.SORT AS ID,
    F.ACCOUNTING_MONTH_KEY,
    P.CONTAINERS*0.52*1.038 AS AMOUNT
    FROM {{ ref('ERP_REVENUE_MAPPING_VIC') }} AS F 
    INNER JOIN {{ source('CES_FINANCE', 'CES_SERVICE_FEE_SUMMARY_DEV') }} AS RM -- MAPPING
    ON RM.SORT = 3
    LEFT JOIN (
        SELECT
        P.MONTH_KEY,
        SUM(P.DISTINCT_COUNT) OVER (ORDER BY P.MONTH_KEY ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS CONTAINERS
        FROM (
            SELECT
            TO_CHAR(P.APPROVED_DATE, 'YYYYMM01') AS MONTH_KEY,
            COUNT(DISTINCT P.BARCODE) AS DISTINCT_COUNT
            FROM {{ source('APPROVED_CONTAINER', 'REF_PRODUCT') }} AS P
            WHERE P.ACTIVE_FLAG = 'Y' AND P.STATUS = 'APPROVED'
            GROUP BY TO_CHAR(P.APPROVED_DATE, 'YYYYMM01')
        ) P
    ) P
    ON P.MONTH_KEY = F.ACCOUNTING_MONTH_KEY
    WHERE RM.SCHEME = 'VIC' 
    GROUP BY 
    RM.SORT,
    F.ACCOUNTING_MONTH_KEY,
    P.CONTAINERS

    UNION ALL
    --BF
    SELECT
    RM.SORT AS ID,
    F.ACCOUNTING_MONTH_KEY,
    SUM(F.AMOUNT_INCLUDING_GST) AS AMOUNT
    FROM {{ ref('ERP_REVENUE_MAPPING_VIC') }} AS F 
    INNER JOIN {{ source('CES_FINANCE', 'CES_SERVICE_FEE_SUMMARY_DEV') }} AS RM -- MAPPING
    ON RM.SORT = 4 AND F.REVENUE_ANALYSIS_SORT = 1
    WHERE RM.SCHEME = 'VIC' 
    GROUP BY 
    RM.SORT,
    F.ACCOUNTING_MONTH_KEY

    UNION ALL
    --DP Reporting Tool, Data Warehouse SaaS Fee, Customer Service, Audit and Verification
    SELECT
    DP.ID AS ID,
    DP.ACCOUNTING_MONTH_KEY,
    SUM(DP.AMOUNT) AS AMOUNT
    FROM (
        --DP Reporting Tool
        SELECT
        RM.SORT AS ID,
        CU.ACCOUNTING_MONTH_KEY,
        (CU.CUR_USER*20.85*1.038) + ((CU.CUR_USER-PU.PREV_USER)*41.91*1.038) AS AMOUNT
        FROM (
            SELECT
            TO_VARCHAR(ADD_MONTHS(TO_DATE(GM.EXTRACT_DATE, 'YYYYMMDD'), -1), 'YYYYMMDD') AS ACCOUNTING_MONTH_KEY, 
            COUNT(DISTINCT GM.USER_ID) AS CUR_USER
            FROM {{ source('CES_ADF', 'AD_GROUP_MEMBERS_MONTHLY') }} AS GM,
            {{ source('CES_ADF', 'AD_GROUPS_MONTHLY') }} AS G
            WHERE GM.GROUP_ID = G.ID
            AND G.DISPLAYNAME LIKE 'Power BI - VicReturn%'
            AND GM.MAIL NOT LIKE '%coexservices.com.au'
            AND GM.MAIL NOT LIKE '%cesystems.com'
            AND GM.MAIL NOT LIKE '%kada.ai'
            AND GM.MAIL NOT LIKE '%edgered.com.au'
            GROUP BY TO_VARCHAR(ADD_MONTHS(TO_DATE(GM.EXTRACT_DATE, 'YYYYMMDD'), -1), 'YYYYMMDD')
        ) CU
        LEFT JOIN (
            SELECT
            TO_VARCHAR(ADD_MONTHS(TO_DATE(GM.EXTRACT_DATE, 'YYYYMMDD'), -1), 'YYYYMMDD') AS ACCOUNTING_MONTH_KEY, 
            COUNT(DISTINCT GM.USER_ID) AS PREV_USER
            FROM {{ source('CES_ADF', 'AD_GROUP_MEMBERS_MONTHLY') }} AS GM,
            {{ source('CES_ADF', 'AD_GROUPS_MONTHLY') }} AS G
            WHERE GM.GROUP_ID = G.ID
            AND G.DISPLAYNAME LIKE 'Power BI - VicReturn%'
            AND GM.MAIL NOT LIKE '%coexservices.com.au'
            AND GM.MAIL NOT LIKE '%cesystems.com'
            AND GM.MAIL NOT LIKE '%kada.ai'
            AND GM.MAIL NOT LIKE '%edgered.com.au'
            GROUP BY TO_VARCHAR(ADD_MONTHS(TO_DATE(GM.EXTRACT_DATE, 'YYYYMMDD'), -1), 'YYYYMMDD')
        ) PU
        ON TO_DATE(CU.ACCOUNTING_MONTH_KEY, 'YYYYMMDD') = ADD_MONTHS(TO_DATE(PU.ACCOUNTING_MONTH_KEY, 'YYYYMMDD'), 1)
        INNER JOIN {{ source('CES_FINANCE', 'CES_SERVICE_FEE_SUMMARY_DEV') }} AS RM -- MAPPING
        ON RM.SORT = 8
        WHERE RM.SCHEME = 'VIC'
        GROUP BY 
        RM.SORT,
        CU.ACCOUNTING_MONTH_KEY,
        CU.CUR_USER,
        PU.PREV_USER

        UNION ALL
        --DP Data Warehouse
        SELECT
        RM.SORT AS ID,
        F.ACCOUNTING_MONTH_KEY,
        (DAY(LAST_DAY(TO_DATE(LEFT(F.ACCOUNTING_MONTH_KEY, 8), 'YYYYMMDD')))*24)*(31.42*1.038) AS AMOUNT
        FROM {{ ref('ERP_REVENUE_MAPPING_VIC') }} AS F 
        INNER JOIN {{ source('CES_FINANCE', 'CES_SERVICE_FEE_SUMMARY_DEV') }} AS RM -- MAPPING
        ON RM.SORT = 8
        WHERE RM.SCHEME = 'VIC' 
        GROUP BY 
        RM.SORT,
        F.ACCOUNTING_MONTH_KEY

        UNION ALL
        --DP Audit and Verification
        SELECT 
        RM.SORT AS ID,
        F.ACCOUNTING_MONTH_KEY,
        T.NUM_TRANSACTIONS*0.0009*1.038 AS AMOUNT
        FROM {{ ref('ERP_REVENUE_MAPPING_VIC') }} AS F
        LEFT JOIN (
            SELECT 
            YEAR_MONTH AS YEAR_MONTH,
            MAX(P.ROLLING_COUNT) AS NUM_TRANSACTIONS
            FROM (
                SELECT 
                LEFT(D.KEY, 6) AS YEAR_MONTH, 
                COUNT(*) OVER (ORDER BY D.YEAR_MONTH ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS ROLLING_COUNT
                FROM {{ source('CRPO', 'CRP_COLLECTION_HDR') }} AS HDR
                LEFT JOIN {{ ref('REF_DATE') }} AS D
                ON HDR.TRANSACTION_DATE_KEY = D.KEY
                WHERE LEFT(D.KEY, 6) >= '202311'
                ) P
            GROUP BY YEAR_MONTH
        ) T
        ON T.YEAR_MONTH = LEFT(F.ACCOUNTING_MONTH_KEY, 6)
        INNER JOIN {{ source('CES_FINANCE', 'CES_SERVICE_FEE_SUMMARY_DEV') }} AS RM -- MAPPING
        ON RM.SORT = 8
        WHERE RM.SCHEME = 'VIC' 
        GROUP BY 
        RM.SORT,
        F.ACCOUNTING_MONTH_KEY,
        T.NUM_TRANSACTIONS

        UNION ALL
        --DP Customer Service System
        SELECT 
        RM.SORT AS ID,
        F.ACCOUNTING_MONTH_KEY,
        (C.NUM_CONTACTS*0.38*1.038) + 633.25 AS AMOUNT
        FROM {{ ref('ERP_REVENUE_MAPPING_VIC') }} AS F 
        INNER JOIN {{ source('CES_FINANCE', 'CES_SERVICE_FEE_SUMMARY_DEV') }} AS RM -- MAPPING
        ON RM.SORT = 8
        LEFT JOIN (
            SELECT
            LEFT(C.CREATED_DATE_KEY, 6) || '01' AS ACCOUNTING_MONTH_KEY,
            COUNT(DISTINCT C.TICKET_ID) AS NUM_CONTACTS
            FROM {{ ref('CRM_INCIDENTS') }} AS C
            WHERE C.SCHEME = 'VIC'
            GROUP BY LEFT(C.CREATED_DATE_KEY, 6)
        ) C
        ON F.ACCOUNTING_MONTH_KEY = C.ACCOUNTING_MONTH_KEY
        WHERE RM.SCHEME = 'VIC' 
        GROUP BY 
        RM.SORT,
        F.ACCOUNTING_MONTH_KEY,
        C.NUM_CONTACTS
    ) DP
    GROUP BY
    DP.ID,
    DP.ACCOUNTING_MONTH_KEY

    UNION ALL
    --POS
    SELECT
    RM.SORT AS ID,
    F.ACCOUNTING_MONTH_KEY,
    4603.93 AS AMOUNT
    FROM {{ ref('ERP_REVENUE_MAPPING_VIC') }} AS F 
    INNER JOIN {{ source('CES_FINANCE', 'CES_SERVICE_FEE_SUMMARY_DEV') }} AS RM -- MAPPING
    ON RM.SORT = 9
    WHERE RM.SCHEME = 'VIC'
    GROUP BY 
    RM.SORT,
    F.ACCOUNTING_MONTH_KEY

    UNION ALL
    --EXCESS
    SELECT
    RM.SORT AS ID,
    U.ACCOUNTING_MONTH_KEY,
    (U.NUM_USERS-30)*20.85*1.0381 AS AMOUNT
    FROM (
        SELECT
        TO_VARCHAR(ADD_MONTHS(TO_DATE(GM.EXTRACT_DATE, 'YYYYMMDD'), -1), 'YYYYMMDD') AS ACCOUNTING_MONTH_KEY,
        COUNT(DISTINCT GM.USER_ID) AS NUM_USERS
        FROM {{ source('CES_ADF', 'AD_GROUP_MEMBERS_MONTHLY') }} AS GM,
        {{ source('CES_ADF', 'AD_GROUPS_MONTHLY') }} AS G
        WHERE GM.GROUP_ID = G.ID
        AND G.DISPLAYNAME LIKE 'Power BI - ReturnIT%'
        AND GM.MAIL NOT LIKE '%coexservices.com.au'
        AND GM.MAIL NOT LIKE '%cesystems.com'
        AND GM.MAIL NOT LIKE '%kada.ai'
        AND GM.MAIL NOT LIKE '%edgered.com.au'
        GROUP BY TO_VARCHAR(ADD_MONTHS(TO_DATE(GM.EXTRACT_DATE, 'YYYYMMDD'), -1), 'YYYYMMDD')
    ) U
    INNER JOIN {{ source('CES_FINANCE', 'CES_SERVICE_FEE_SUMMARY_DEV') }} AS RM -- MAPPING
    ON RM.SORT = 10
    WHERE RM.SCHEME = 'VIC'
    GROUP BY 
    RM.SORT,
    U.ACCOUNTING_MONTH_KEY,
    U.NUM_USERS

    UNION ALL
    --NOP FEE
    SELECT
    RM.SORT AS ID,
    F.ACCOUNTING_MONTH_KEY,
    74399.24 AS AMOUNT
    FROM {{ ref('ERP_REVENUE_MAPPING_VIC') }} AS F 
    INNER JOIN {{ source('CES_FINANCE', 'CES_SERVICE_FEE_SUMMARY_DEV') }} AS RM -- MAPPING
    ON RM.SORT = 11
    WHERE RM.SCHEME = 'VIC'
    GROUP BY 
    RM.SORT,
    F.ACCOUNTING_MONTH_KEY

    UNION ALL
    -- DP Reporting Tool SaaS Fee
    SELECT
    RM.SORT AS ID,
    CU.ACCOUNTING_MONTH_KEY,
    (CU.CUR_USER*20.85*1.038) + ((CU.CUR_USER-PU.PREV_USER)*41.91*1.038) AS AMOUNT
    FROM (
        SELECT
        TO_VARCHAR(ADD_MONTHS(TO_DATE(GM.EXTRACT_DATE, 'YYYYMMDD'), -1), 'YYYYMMDD') AS ACCOUNTING_MONTH_KEY, 
        COUNT(DISTINCT GM.USER_ID) AS CUR_USER
        FROM {{ source('CES_ADF', 'AD_GROUP_MEMBERS_MONTHLY') }} AS GM,
        {{ source('CES_ADF', 'AD_GROUPS_MONTHLY') }} AS G
        WHERE GM.GROUP_ID = G.ID
        AND G.DISPLAYNAME LIKE 'Power BI - VicReturn%'
        AND GM.MAIL NOT LIKE '%coexservices.com.au'
        AND GM.MAIL NOT LIKE '%cesystems.com'
        AND GM.MAIL NOT LIKE '%kada.ai'
        AND GM.MAIL NOT LIKE '%edgered.com.au'
        GROUP BY TO_VARCHAR(ADD_MONTHS(TO_DATE(GM.EXTRACT_DATE, 'YYYYMMDD'), -1), 'YYYYMMDD')
    ) CU
    LEFT JOIN (
        SELECT
        TO_VARCHAR(ADD_MONTHS(TO_DATE(GM.EXTRACT_DATE, 'YYYYMMDD'), -1), 'YYYYMMDD') AS ACCOUNTING_MONTH_KEY, 
        COUNT(DISTINCT GM.USER_ID) AS PREV_USER
        FROM {{ source('CES_ADF', 'AD_GROUP_MEMBERS_MONTHLY') }} AS GM,
        {{ source('CES_ADF', 'AD_GROUPS_MONTHLY') }} AS G
        WHERE GM.GROUP_ID = G.ID
        AND G.DISPLAYNAME LIKE 'Power BI - VicReturn%'
        AND GM.MAIL NOT LIKE '%coexservices.com.au'
        AND GM.MAIL NOT LIKE '%cesystems.com'
        AND GM.MAIL NOT LIKE '%kada.ai'
        AND GM.MAIL NOT LIKE '%edgered.com.au'
        GROUP BY TO_VARCHAR(ADD_MONTHS(TO_DATE(GM.EXTRACT_DATE, 'YYYYMMDD'), -1), 'YYYYMMDD')
    ) PU
    ON TO_DATE(CU.ACCOUNTING_MONTH_KEY, 'YYYYMMDD') = ADD_MONTHS(TO_DATE(PU.ACCOUNTING_MONTH_KEY, 'YYYYMMDD'), 1)
    INNER JOIN {{ source('CES_FINANCE', 'CES_SERVICE_FEE_SUMMARY_DEV') }} AS RM -- MAPPING
    ON RM.SORT = 12
    WHERE RM.SCHEME = 'VIC'
    GROUP BY 
    RM.SORT,
    CU.ACCOUNTING_MONTH_KEY,
    CU.CUR_USER,
    PU.PREV_USER

    UNION ALL
    --DP Data Warehouse SaaS Fee
    SELECT
    RM.SORT AS ID,
    F.ACCOUNTING_MONTH_KEY,
    (DAY(LAST_DAY(TO_DATE(LEFT(F.ACCOUNTING_MONTH_KEY, 8), 'YYYYMMDD')))*24)*(31.42*1.038) AS AMOUNT
    FROM {{ ref('ERP_REVENUE_MAPPING_VIC') }} AS F 
    INNER JOIN {{ source('CES_FINANCE', 'CES_SERVICE_FEE_SUMMARY_DEV') }} AS RM -- MAPPING
    ON RM.SORT = 13
    WHERE RM.SCHEME = 'VIC' 
    GROUP BY 
    RM.SORT,
    F.ACCOUNTING_MONTH_KEY

    UNION ALL
    --DP Customer Service System
    SELECT
    RM.SORT AS ID,
    F.ACCOUNTING_MONTH_KEY,
    (C.NUM_CONTACTS*0.38*1.038) + 633.25 AS AMOUNT
    FROM {{ ref('ERP_REVENUE_MAPPING_VIC') }} AS F 
    INNER JOIN {{ source('CES_FINANCE', 'CES_SERVICE_FEE_SUMMARY_DEV') }} AS RM -- MAPPING
    ON RM.SORT = 14
    LEFT JOIN (
        SELECT
        LEFT(C.CREATED_DATE_KEY, 6) || '01' AS ACCOUNTING_MONTH_KEY,
        COUNT(DISTINCT C.TICKET_ID) AS NUM_CONTACTS
        FROM {{ ref('CRM_INCIDENTS') }} AS C
        WHERE C.SCHEME = 'VIC'
        GROUP BY LEFT(C.CREATED_DATE_KEY, 6)
    ) C
    ON F.ACCOUNTING_MONTH_KEY = C.ACCOUNTING_MONTH_KEY
    WHERE RM.SCHEME = 'VIC' 
    GROUP BY 
    RM.SORT,
    F.ACCOUNTING_MONTH_KEY,
    C.NUM_CONTACTS

    UNION ALL
    --DP Audit and Verification
    SELECT 
    RM.SORT AS ID,
    F.ACCOUNTING_MONTH_KEY,
    T.NUM_TRANSACTIONS*0.0009*1.038 AS AMOUNT
    FROM {{ ref('ERP_REVENUE_MAPPING_VIC') }} AS F
    LEFT JOIN (
        SELECT 
        YEAR_MONTH AS YEAR_MONTH,
        MAX(P.ROLLING_COUNT) AS NUM_TRANSACTIONS
        FROM (
            SELECT 
            LEFT(D.KEY, 6) AS YEAR_MONTH, 
            COUNT(*) OVER (ORDER BY D.YEAR_MONTH ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS ROLLING_COUNT
            FROM {{ source('CRPO', 'CRP_COLLECTION_HDR') }} AS HDR
            LEFT JOIN {{ ref('REF_DATE') }} AS D
            ON HDR.TRANSACTION_DATE_KEY = D.KEY
            WHERE LEFT(D.KEY, 6) >= '202311'
            ) P
        GROUP BY YEAR_MONTH
    ) T
    ON T.YEAR_MONTH = LEFT(F.ACCOUNTING_MONTH_KEY, 6)
    INNER JOIN {{ source('CES_FINANCE', 'CES_SERVICE_FEE_SUMMARY_DEV') }} AS RM -- MAPPING
    ON RM.SORT = 15
    WHERE RM.SCHEME = 'VIC' 
    GROUP BY 
    RM.SORT,
    F.ACCOUNTING_MONTH_KEY,
    T.NUM_TRANSACTIONS
) F
ON F.ID = RM.SORT
    --MANUAL ENTRY/ADJUSTMENTS BY ESHAN
FULL JOIN (
          SELECT
          RM.CODE AS CODE
          , RM.ITEM AS ITEM
          , RM.SORT AS SORT
          , RM.DRIVER AS DRIVER
          , M.RATE_MARGIN
          , M.RATE_MARGIN_TYPE
          , RM.FORECAST_PN_L_LINE_CODE 
          , RM.COMMENT
          , M.PERIOD
          , M.DRIVER_VALUE
          , M.MANUAL
          FROM
          {{ source('CES_FINANCE', 'SERVICE_FEE_MANUAL_INPUT_DEV') }} AS M
          LEFT JOIN {{ source('CES_FINANCE', 'CES_SERVICE_FEE_SUMMARY_DEV') }} AS RM
          ON M.SORT = RM.SORT
          WHERE M.SCHEME = 'VIC' AND RM.SCHEME = 'VIC') MA
ON MA.SORT = RM.SORT AND MA.PERIOD = F.ACCOUNTING_MONTH_KEY
LEFT JOIN {{ source('CES_FINANCE', 'ERP_SUMMARY_FORECAST_DEV') }} AS FO -- FORECAST
ON FO.PNL_LINE = COALESCE(RM.FORECAST_PN_L_LINE_CODE,MA.FORECAST_PN_L_LINE_CODE) AND COALESCE(MA.PERIOD,F.ACCOUNTING_MONTH_KEY) = FO.FORECAST_DATE_KEY AND FO.SCHEME = 'VIC'
WHERE NVL(RM.AP_LINK_LOGIC,0) NOT IN ('6','8') AND RM.SCHEME = 'VIC' --AND COALESCE(FO.FORECAST_DATE_KEY,F.ACCOUNTING_MONTH_KEY,MA.PERIOD) = '20221201'
