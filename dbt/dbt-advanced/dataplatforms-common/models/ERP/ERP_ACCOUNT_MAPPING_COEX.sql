SELECT
10000 AS MULTI_SCHEME_ID
, 'QLD' AS SCHEME
, AM.ACCOUNT_CODE AS ACCOUNT_CODE
, AM.ACCOUNT_MAP_L_1 AS ACCOUNT
, AM.ACCOUNT_MAP_L_2 AS ACCOUNT_MAP_L_2
, AM.ACCOUNT_MAP_L_3 AS ACCOUNT_MAP_L_3
, AM.ACCOUNT_MAP_L_4 AS ACCOUNT_MAP_L_4
, AM.ACCOUNT_MAP_L_5 AS ACCOUNT_MAP_L_5
, CASE WHEN AM.ACCOUNT_MAP_L_5 = 'Key Performance Indicators'  THEN 1 WHEN AM.ACCOUNT_MAP_L_5 = 'Financials'  THEN 2 ELSE NULL END AS SORT_ORDER_L5
, AM.SORT_ORDER_L4 AS SORT_ORDER_L4
, MAX(AM.ACCOUNT_CODE) OVER (PARTITION BY AM.ACCOUNT_MAP_L_3) AS SORT_ORDER_L3
, MAX(AM.ACCOUNT_CODE) OVER (PARTITION BY AM.ACCOUNT_MAP_L_2) AS SORT_ORDER_L2
, SYSDATE() AS INSERT_DATE_UTC
FROM 
(
    SELECT
    CASE WHEN A.ACCOUNT_MAP_L_4 = 'Revenue'  THEN 1 WHEN A.ACCOUNT_MAP_L_4 = 'Expenses'  THEN 2 ELSE 4  END AS  SORT_ORDER_L4,
    A.ACCOUNT_CODE,
    A.ACCOUNT_MAP_L_1,
    A.ACCOUNT_MAP_L_2,
    A.ACCOUNT_MAP_L_3,
    A.ACCOUNT_MAP_L_4,
    'Financials' AS ACCOUNT_MAP_L_5
    FROM
    {{ source('CES_FINANCE', 'ACCOUNT_MAPPING') }} AS A
    UNION ALL
    SELECT
    3 AS SORT_ORDER_L4,
    B.ACCOUNT_CODE,
    B.ACCOUNT_MAP_L_1,
    B.ACCOUNT_MAP_L_2 AS ACCOUNT_MAP_L_2,
    B.ACCOUNT_MAP_L_4 AS ACCOUNT_MAP_L_3,
    'Gross Operating Surplus / (Deficit)' AS  ACCOUNT_MAP_L_4,
    'Financials' AS ACCOUNT_MAP_L_5
    FROM
    {{ source('CES_FINANCE', 'ACCOUNT_MAPPING') }} AS B
    WHERE B.ACCOUNT_MAP_L_4 IN ('Expenses','Revenue')
    UNION ALL
    SELECT
    5 AS SORT_ORDER_L4,
    C.ACCOUNT_CODE,
    C.ACCOUNT_MAP_L_1,
    C.ACCOUNT_MAP_L_2 AS ACCOUNT_MAP_L_2,
    C.ACCOUNT_MAP_L_4 AS ACCOUNT_MAP_L_3,
    'Net Operating Surplus / (Deficit)' AS ACCOUNT_MAP_L_4,
    'Financials' AS ACCOUNT_MAP_L_5
    FROM
    {{ source('CES_FINANCE', 'ACCOUNT_MAPPING') }} AS C
    UNION ALL
    SELECT
    NULL AS SORT_ORDER_L4,
    D.ACCOUNT_CODE,
    D.ACCOUNT_MAP_L_1,
    D.ACCOUNT_MAP_L_2 AS ACCOUNT_MAP_L_2,
    D.ACCOUNT_MAP_L_4 AS ACCOUNT_MAP_L_3,
    'Gross Profit Percent' AS ACCOUNT_MAP_L_4,
    'Key Performance Indicators' AS ACCOUNT_MAP_L_5
    FROM
    {{ source('CES_FINANCE', 'ACCOUNT_MAPPING') }} AS D
    WHERE D.ACCOUNT_MAP_L_4 IN ('Expenses','Revenue')
    UNION ALL
    SELECT
    NULL AS SORT_ORDER_L4,
    E.ACCOUNT_CODE,
    E.ACCOUNT_MAP_L_1,
    E.ACCOUNT_MAP_L_2 AS ACCOUNT_MAP_L_2,
    E.ACCOUNT_MAP_L_4 AS ACCOUNT_MAP_L_3,
    'NPAT Percent' AS ACCOUNT_MAP_L_4,
    'Key Performance Indicators' AS ACCOUNT_MAP_L_5
    FROM
    {{ source('CES_FINANCE', 'ACCOUNT_MAPPING') }} AS E
) AM