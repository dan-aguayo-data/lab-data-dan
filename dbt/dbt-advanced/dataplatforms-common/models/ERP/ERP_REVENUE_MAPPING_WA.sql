SELECT
NVL(U.MULTI_SCHEME_ID, '-1') AS MULTI_SCHEME_ID
, NVL(U.SCHEME, 'CES') AS SCHEME
, U.REVENUE_ANALYSIS_SORT AS REVENUE_ANALYSIS_SORT
, U.PAYMENT_PROCESSES_AP_SORT AS PAYMENT_PROCESSES_AP_SORT
, U.REVENUE_ANALYSIS_CLASSIFICATION AS REVENUE_ANALYSIS_CLASSIFICATION
, U.CLASSIFICATION AS CLASSIFICATION
, U.SOURCE AS SOURCE
, U.COMMENTS AS COMMENTS
, U.ACCOUNTING_MONTH_KEY AS ACCOUNTING_MONTH_KEY
, SUM(U.AMOUNT) AS AMOUNT
, ABS(SUM(U.AMOUNT)) AS AMOUNT_INCLUDING_GST
, ABS(SUM(U.AMOUNT)) / (CASE WHEN U.SOURCE in ('BAS Payments','Inv / Accrual') THEN  1 ELSE 1.1 END) AS AMOUNT_EXCLUDING_GST
, SYSDATE() AS INSERT_DATE_UTC
FROM (
    SELECT
    L.MULTI_SCHEME_ID
    , L.SCHEME
    , M.REVENUE_ANALYSIS_SORT
    , M.PAYMENT_PROCESSES_AP_SORT
    , M.REVENUE_ANALYSIS_CLASSIFICATION
    , M.CLASSIFICATION
    , M.SOURCE
    , M.COMMENTS
    , AP.ACCOUNTING_MONTH_KEY
    , AP.AMOUNT
    FROM {{ source('CES_FINANCE', 'ERP_REVENUE_MAPPING_DEV') }} AS M
    LEFT JOIN
        (SELECT
         APT.SUPPLIER_NUMBER
         , NVL(APT.PAY_GROUP ,'') AS PAY_GROUP
         , APT.LEDGER_NAME
         , TO_CHAR(DATE_TRUNC('MONTH', APT.INV_DIST_ACCOUNTING_DATE),'YYYYMMDD') AS ACCOUNTING_MONTH_KEY
         , SUM(CASE WHEN (APT.PAY_GROUP IN ('') AND APT.COST_CENTER_CODE = '0000') THEN 0 ELSE (CASE WHEN UPPER(APT.INVOICE_NUM) LIKE '%CR%' THEN ABS(APT.TOTAL_DISTRIBUTION_AMOUNT) ELSE APT.TOTAL_DISTRIBUTION_AMOUNT END) END) AS AMOUNT
         , APT.COST_CENTER_CODE 
         FROM {{ source('CES_ERP', 'AP_TRANSACTIONS') }} AS APT
         WHERE APT.LEDGER_NAME IN ('Scheme WA Ledger AU','Processor WA Ledger AU') AND (APT.SUPPLIER_NAME NOT IN ('CONTAINER EXCHANGE(SERVICES)PTY LTD','CIRCULAR ECONOMY SYSTEMS PTY LTD','CIRCULAR ECONOMY SYSTEMS PTY LTD.') OR APT.SUPPLIER_NAME IS NULL)
         GROUP BY
         APT.SUPPLIER_NUMBER
         , NVL(APT.PAY_GROUP ,'')
         , APT.LEDGER_NAME
         , TO_CHAR(DATE_TRUNC('MONTH', APT.INV_DIST_ACCOUNTING_DATE),'YYYYMMDD')
         , APT.COST_CENTER_CODE
         ) AP
    ON CASE WHEN M.PAYMENT_PROCESSES_AP_SORT IN ('14','17') THEN AP.SUPPLIER_NUMBER = TO_CHAR(M.SUPPLIER_NUMBER) WHEN M.PAYMENT_PROCESSES_AP_SORT = 8 THEN AP.PAY_GROUP = NVL(M.PAY_GROUP,'') AND AP.SUPPLIER_NUMBER <> '1000084' ELSE AP.PAY_GROUP = NVL(M.PAY_GROUP,'') END AND M.SCHEME = 'WA'
    LEFT JOIN {{ ref('ERP_LEDGER') }} AS L
    ON L.LEDGER_NAME = AP.LEDGER_NAME
    WHERE M.SOURCE_TABLE = 'AP_TRANSACTIONS' AND M.SCHEME = 'WA' AND M.REVENUE_ANALYSIS_SORT NOT IN ('3', '10', '17')
    UNION ALL
    SELECT
    AR.MULTI_SCHEME_ID
    , AR.SCHEME
    , M.REVENUE_ANALYSIS_SORT
    , M.PAYMENT_PROCESSES_AP_SORT
    , M.REVENUE_ANALYSIS_CLASSIFICATION
    , M.CLASSIFICATION
    , M.SOURCE
    , M.COMMENTS
    , LEFT(AR.ACCOUNTING_DATE_KEY,6) || '01' AS ACCOUNTING_MONTH_KEY
    , NVL(AR.AMOUNT_DR,0) + NVL(AR.AMOUNT_CR,0) AS AMOUNT
    FROM {{ source('CES_FINANCE', 'ERP_REVENUE_MAPPING_DEV') }} AS M
    LEFT JOIN {{ ref('ERP_GL_TRANSACTIONS') }} AS AR
    ON M.TRANSACTION_TYPE = AR.TRANSACTION_TYPE AND AR.LEDGER_NAME = 'Scheme WA Ledger AU' AND AR.EVENT_TYPE_NAME <> 'Credit Memo Updated' AND AR.ACCOUNT <> '21020 - GST Output' AND AR.COST_CENTER_PARENT = 'Balance Sheet' AND M.SCHEME = 'WA'
    WHERE M.SOURCE_TABLE = 'GL_TRANSACTIONS' AND M.SCHEME = 'WA' AND AR.BUSINESS_CLASS_NAME = 'Receivable'
    UNION ALL
    SELECT
    AR.MULTI_SCHEME_ID
    , AR.SCHEME
    , M.REVENUE_ANALYSIS_SORT
    , M.PAYMENT_PROCESSES_AP_SORT
    , M.REVENUE_ANALYSIS_CLASSIFICATION
    , M.CLASSIFICATION
    , M.SOURCE
    , M.COMMENTS
    , LEFT(AR.ACCOUNTING_DATE_KEY,6) || '01' AS ACCOUNTING_MONTH_KEY
    , ABS(NVL(AR.AMOUNT_DR,0)) + ABS(NVL(AR.AMOUNT_CR,0)) AS AMOUNT
    FROM {{ source('CES_FINANCE', 'ERP_REVENUE_MAPPING_DEV') }} AS M
    LEFT JOIN {{ ref('ERP_GL_TRANSACTIONS') }} AS AR
    ON AR.LEDGER_NAME = 'Scheme WA Ledger AU' AND AR.EVENT_TYPE_NAME <> 'Credit Memo Updated' AND AR.ACCOUNT <> '21020 - GST Output' AND AR.COST_CENTER_PARENT = 'Balance Sheet' AND M.SCHEME = 'WA'
    WHERE M.SOURCE_TABLE = 'GL_TRANSACTIONS' AND M.SCHEME = 'WA' AND AR.TRANSACTION_TYPE IN ('Scheme Admin Credit')  AND AR.BUSINESS_CLASS_NAME = 'Receivable' AND M.PAYMENT_PROCESSES_AP_SORT = 18
    UNION ALL
    SELECT
    B.MULTI_SCHEME_ID
    , B.SCHEME
    , M.REVENUE_ANALYSIS_SORT
    , M.PAYMENT_PROCESSES_AP_SORT
    , M.REVENUE_ANALYSIS_CLASSIFICATION
    , M.CLASSIFICATION
    , M.SOURCE
    , M.COMMENTS
    , TO_CHAR(DATE_TRUNC('MONTH', B.PERIOD),'YYYYMMDD') AS ACCOUNTING_MONTH_KEY
    , B.BASE_PERIOD_NET_ACTIVITY AS AMOUNT
    FROM {{ source('CES_FINANCE', 'ERP_REVENUE_MAPPING_DEV') }} AS M
    LEFT JOIN {{ ref('ERP_BALANCES') }} AS B
    ON B.ACCOUNT_CODE = M.ACCOUNT_CODE AND B.LEDGER_NAME = 'Scheme WA Ledger AU' AND M.SCHEME = 'WA'
    WHERE M.SOURCE_TABLE = 'GL_BALANCES' AND M.SCHEME = 'WA'
    UNION ALL
    SELECT
    '10001' AS MULTI_SCHEME_ID
    ,'WA' AS SCHEME
    , M.REVENUE_ANALYSIS_SORT
    , M.PAYMENT_PROCESSES_AP_SORT
    , M.REVENUE_ANALYSIS_CLASSIFICATION
    , M.CLASSIFICATION
    , M.SOURCE
    , M.COMMENTS
    , B.PERIOD AS ACCOUNTING_MONTH_KEY
    , B.AMOUNT AS AMOUNT
    FROM {{ source('CES_FINANCE', 'ERP_REVENUE_MAPPING_DEV') }} AS M
    INNER JOIN {{ source('CES_FINANCE', 'AP_ADHOC_MANUAL_INPUT_DEV') }} AS B
    ON M.SOURCE_TABLE = 'AP_ADHOC_MANUAL_INPUT' AND M.SCHEME = 'WA' AND B.SCHEME = 'WA'
    WHERE M.SCHEME = 'WA' AND B.SCHEME = 'WA'
    UNION ALL
    SELECT
    L.MULTI_SCHEME_ID
    , L.SCHEME
    , M.REVENUE_ANALYSIS_SORT
    , M.PAYMENT_PROCESSES_AP_SORT
    , M.REVENUE_ANALYSIS_CLASSIFICATION
    , M.CLASSIFICATION
    , M.SOURCE
    , M.COMMENTS
    , AP.ACCOUNTING_MONTH_KEY
    , AP.AMOUNT
    FROM {{ source('CES_FINANCE', 'ERP_REVENUE_MAPPING_DEV') }} AS M
    LEFT JOIN
        (SELECT 
         APT.SUPPLIER_NUMBER
         , NVL(APT.PAY_GROUP ,'') AS PAY_GROUP
         , APT.LEDGER_NAME
         , TO_CHAR(DATE_TRUNC('MONTH', APT.INV_DIST_ACCOUNTING_DATE),'YYYYMMDD') AS ACCOUNTING_MONTH_KEY
         , SUM(CASE WHEN (APT.PAY_GROUP IN ('') AND APT.COST_CENTER_CODE = '0000') THEN 0 ELSE APT.TOTAL_DISTRIBUTION_AMOUNT END) AS AMOUNT
         , APT.COST_CENTER_CODE 
         FROM {{ source('CES_ERP', 'AP_TRANSACTIONS') }} AS APT
         WHERE APT.BUSINESS_UNIT_NAME IN ('WA SCHEME BU') AND APT.PAY_GROUP IN ('ADMIN') AND APT.SUPPLIER_NAME IN ('CONTAINER EXCHANGE(SERVICES)PTY LTD','CIRCULAR ECONOMY SYSTEMS PTY LTD','CIRCULAR ECONOMY SYSTEMS PTY LTD.')
         GROUP BY
         APT.SUPPLIER_NUMBER
         , NVL(APT.PAY_GROUP ,'')
         , APT.LEDGER_NAME
         , APT.INVOICE_SOURCE_NAME
         , TO_CHAR(DATE_TRUNC('MONTH', APT.INV_DIST_ACCOUNTING_DATE),'YYYYMMDD')
         , APT.COST_CENTER_CODE
         ) AP
    ON M.PAYMENT_PROCESSES_AP_SORT = 13 AND M.SCHEME = 'WA'
    LEFT JOIN {{ ref('ERP_LEDGER') }} AS L
    ON L.LEDGER_NAME = AP.LEDGER_NAME
    WHERE M.SCHEME = 'WA'
    UNION ALL
    SELECT
    AP.MULTI_SCHEME_ID
    , AP.SCHEME
    , AP.REVENUE_ANALYSIS_SORT
    , AP.PAYMENT_PROCESSES_AP_SORT
    , AP.REVENUE_ANALYSIS_CLASSIFICATION
    , AP.CLASSIFICATION
    , AP.SOURCE
    , AP.COMMENTS
    , AP.ACCOUNTING_MONTH_KEY
    , SUM(AP.AMOUNT) + SUM(AR.AMOUNT) AS AMOUNT
    FROM
        (SELECT
        AP.MULTI_SCHEME_ID
        , AP.SCHEME
        , AP.REVENUE_ANALYSIS_SORT
        , AP.PAYMENT_PROCESSES_AP_SORT
        , AP.REVENUE_ANALYSIS_CLASSIFICATION
        , AP.CLASSIFICATION
        , AP.SOURCE
        , AP.COMMENTS
        , AP.ACCOUNTING_MONTH_KEY
        , SUM(AP.AMOUNT) * 0.2 AS AMOUNT
        FROM
            (SELECT
            L.MULTI_SCHEME_ID
            , L.SCHEME
            , M.REVENUE_ANALYSIS_SORT
            , M.PAYMENT_PROCESSES_AP_SORT
            , M.REVENUE_ANALYSIS_CLASSIFICATION
            , M.CLASSIFICATION
            , M.SOURCE
            , M.COMMENTS
            , AP.ACCOUNTING_MONTH_KEY
            , AP.AMOUNT
            FROM {{ source('CES_FINANCE', 'ERP_REVENUE_MAPPING_DEV') }} AS M
            LEFT JOIN
                (SELECT
                APT.SUPPLIER_NUMBER
                , NVL(APT.PAY_GROUP ,'') AS PAY_GROUP
                , APT.LEDGER_NAME
                , TO_CHAR(DATE_TRUNC('MONTH', APT.INV_DIST_ACCOUNTING_DATE),'YYYYMMDD') AS ACCOUNTING_MONTH_KEY
                , SUM(CASE WHEN (APT.PAY_GROUP IN ('') AND APT.COST_CENTER_CODE = '0000') THEN 0 ELSE APT.TOTAL_DISTRIBUTION_AMOUNT END) AS AMOUNT
                , APT.COST_CENTER_CODE 
                FROM {{ source('CES_ERP', 'AP_TRANSACTIONS') }} AS APT
                WHERE APT.LEDGER_NAME IN ('Scheme WA Ledger AU','Processor WA Ledger AU') AND (APT.SUPPLIER_NAME NOT IN ('CONTAINER EXCHANGE(SERVICES)PTY LTD','CIRCULAR ECONOMY SYSTEMS PTY LTD','CIRCULAR ECONOMY SYSTEMS PTY LTD.') OR APT.SUPPLIER_NAME IS NULL)
                GROUP BY
                APT.SUPPLIER_NUMBER
                , NVL(APT.PAY_GROUP ,'')
                , APT.LEDGER_NAME
                , TO_CHAR(DATE_TRUNC('MONTH', APT.INV_DIST_ACCOUNTING_DATE),'YYYYMMDD')
                , APT.COST_CENTER_CODE
                ) AP
            ON CASE WHEN M.PAYMENT_PROCESSES_AP_SORT IN ('14','17') THEN AP.SUPPLIER_NUMBER = TO_CHAR(M.SUPPLIER_NUMBER) WHEN M.PAYMENT_PROCESSES_AP_SORT = 8 THEN AP.PAY_GROUP = NVL(M.PAY_GROUP,'') AND AP.SUPPLIER_NUMBER <> '1000084' ELSE AP.PAY_GROUP = NVL(M.PAY_GROUP,'') END AND M.SCHEME = 'WA'
            LEFT JOIN {{ ref('ERP_LEDGER') }} AS L
            ON L.LEDGER_NAME = AP.LEDGER_NAME
            WHERE M.SOURCE_TABLE = 'AP_TRANSACTIONS' AND M.SCHEME = 'WA' AND M.REVENUE_ANALYSIS_SORT IN ('3', '17')
            ) AP
        GROUP BY ALL
        ) AP
    LEFT JOIN (
        SELECT
        AR.MULTI_SCHEME_ID
        , AR.SCHEME
        , AR.REVENUE_ANALYSIS_SORT
        , AR.PAYMENT_PROCESSES_AP_SORT
        , AR.REVENUE_ANALYSIS_CLASSIFICATION
        , AR.CLASSIFICATION
        , AR.SOURCE
        , AR.COMMENTS
        , AR.ACCOUNTING_MONTH_KEY
        , SUM(AR.AMOUNT) AS AMOUNT
        FROM (
            SELECT
            AR.MULTI_SCHEME_ID
            , AR.SCHEME
            , M.REVENUE_ANALYSIS_SORT
            , M.PAYMENT_PROCESSES_AP_SORT
            , M.REVENUE_ANALYSIS_CLASSIFICATION
            , M.CLASSIFICATION
            , M.SOURCE
            , M.COMMENTS
            , LEFT(AR.ACCOUNTING_DATE_KEY,6) || '01' AS ACCOUNTING_MONTH_KEY
            , ABS(NVL(AR.AMOUNT_DR,0)) + ABS(NVL(AR.AMOUNT_CR,0)) AS AMOUNT
            FROM {{ source('CES_FINANCE', 'ERP_REVENUE_MAPPING_DEV') }} AS M
            LEFT JOIN {{ ref('ERP_GL_TRANSACTIONS') }} AS AR
            ON M.TRANSACTION_TYPE = AR.TRANSACTION_TYPE AND AR.LEDGER_NAME = 'Scheme WA Ledger AU' AND AR.EVENT_TYPE_NAME <> 'Credit Memo Updated' AND AR.ACCOUNT <> '21020 - GST Output' AND AR.COST_CENTER_PARENT = 'Balance Sheet' AND M.SCHEME = 'WA'
            WHERE M.SOURCE_TABLE = 'GL_TRANSACTIONS' AND M.SCHEME = 'WA' AND AR.BUSINESS_CLASS_NAME = 'Receivable' AND M.REVENUE_ANALYSIS_SORT = '2'
            ) AR
        GROUP BY ALL
        ) AR
    ON AP.ACCOUNTING_MONTH_KEY = AR.ACCOUNTING_MONTH_KEY
    GROUP BY ALL
    UNION ALL
    SELECT
    L.MULTI_SCHEME_ID
    , L.SCHEME
    , M.REVENUE_ANALYSIS_SORT
    , M.PAYMENT_PROCESSES_AP_SORT
    , M.REVENUE_ANALYSIS_CLASSIFICATION
    , M.CLASSIFICATION
    , M.SOURCE
    , M.COMMENTS
    , AP.ACCOUNTING_MONTH_KEY
    , AP.AMOUNT
    FROM {{ source('CES_FINANCE', 'ERP_REVENUE_MAPPING_DEV') }} AS M
    LEFT JOIN
        (SELECT
        APT.SUPPLIER_NUMBER
        , NVL(APT.PAY_GROUP ,'') AS PAY_GROUP
        , APT.LEDGER_NAME
        , TO_CHAR(DATE_TRUNC('MONTH', APT.INV_DIST_ACCOUNTING_DATE),'YYYYMMDD') AS ACCOUNTING_MONTH_KEY
        , SUM(CASE WHEN (APT.PAY_GROUP IN ('') AND APT.COST_CENTER_CODE = '0000') THEN 0 ELSE APT.TOTAL_DISTRIBUTION_AMOUNT END) AS AMOUNT
        , APT.COST_CENTER_CODE 
        FROM {{ source('CES_ERP', 'AP_TRANSACTIONS') }} AS APT
        WHERE APT.LEDGER_NAME IN ('Scheme WA Ledger AU','Processor WA Ledger AU') AND (APT.SUPPLIER_NAME NOT IN ('CONTAINER EXCHANGE(SERVICES)PTY LTD','CIRCULAR ECONOMY SYSTEMS PTY LTD','CIRCULAR ECONOMY SYSTEMS PTY LTD.')) AND APT.PAY_GROUP IN ('LOGISTICS FEES') AND APT.SUPPLIER_NUMBER <> '1000084'
        GROUP BY
        APT.SUPPLIER_NUMBER
        , NVL(APT.PAY_GROUP ,'')
        , APT.LEDGER_NAME
        , TO_CHAR(DATE_TRUNC('MONTH', APT.INV_DIST_ACCOUNTING_DATE),'YYYYMMDD')
        , APT.COST_CENTER_CODE
        UNION ALL 
        SELECT
        APT.SUPPLIER_NUMBER
        , NVL(APT.PAY_GROUP ,'') AS PAY_GROUP
        , APT.LEDGER_NAME
        , TO_CHAR(DATE_TRUNC('MONTH', APT.INV_DIST_ACCOUNTING_DATE),'YYYYMMDD') AS ACCOUNTING_MONTH_KEY
        , SUM(CASE WHEN (APT.PAY_GROUP IN ('') AND APT.COST_CENTER_CODE = '0000') THEN 0 ELSE APT.TOTAL_DISTRIBUTION_AMOUNT END) AS AMOUNT
        , APT.COST_CENTER_CODE 
        FROM {{ source('CES_ERP', 'AP_TRANSACTIONS') }} AS APT
        WHERE APT.BUSINESS_UNIT_NAME IN ('WA SCHEME BU') AND (APT.SUPPLIER_NAME NOT IN ('CONTAINER EXCHANGE(SERVICES)PTY LTD','CIRCULAR ECONOMY SYSTEMS PTY LTD','CIRCULAR ECONOMY SYSTEMS PTY LTD.')) AND APT.PAY_GROUP IN ('ADMIN') AND APT.SUPPLIER_NUMBER <> '1000084' AND APT.INVOICE_SOURCE_NAME IN ('MANUAL')
        GROUP BY
        APT.SUPPLIER_NUMBER
        , NVL(APT.PAY_GROUP ,'')
        , APT.LEDGER_NAME
        , TO_CHAR(DATE_TRUNC('MONTH', APT.INV_DIST_ACCOUNTING_DATE),'YYYYMMDD')
        , APT.COST_CENTER_CODE
        UNION ALL 
        SELECT
        APT.SUPPLIER_NUMBER
        , NVL(APT.PAY_GROUP ,'') AS PAY_GROUP
        , APT.LEDGER_NAME
        , TO_CHAR(DATE_TRUNC('MONTH', APT.INV_DIST_ACCOUNTING_DATE),'YYYYMMDD') AS ACCOUNTING_MONTH_KEY
        , SUM(CASE WHEN (APT.PAY_GROUP IN ('') AND APT.COST_CENTER_CODE = '0000') THEN 0 ELSE APT.TOTAL_DISTRIBUTION_AMOUNT END) AS AMOUNT
        , APT.COST_CENTER_CODE 
        FROM {{ source('CES_ERP', 'AP_TRANSACTIONS') }} AS APT
        WHERE APT.BUSINESS_UNIT_NAME IN ('WA SCHEME BU') AND APT.PAY_GROUP IN ('ADMIN') AND APT.INVOICE_SOURCE_NAME IN ('Manual invoice entry') AND (APT.SUPPLIER_NUMBER IS NULL OR (APT.SUPPLIER_NUMBER <> '1000084' AND APT.SUPPLIER_NUMBER <> '10002'))
        GROUP BY
        APT.SUPPLIER_NUMBER
        , NVL(APT.PAY_GROUP ,'')
        , APT.LEDGER_NAME
        , TO_CHAR(DATE_TRUNC('MONTH', APT.INV_DIST_ACCOUNTING_DATE),'YYYYMMDD')
        , APT.COST_CENTER_CODE
         ) AP
    ON AP.PAY_GROUP = NVL(M.PAY_GROUP,'') AND M.PAYMENT_PROCESSES_AP_SORT = 8
    LEFT JOIN {{ ref('ERP_LEDGER') }} AS L
    ON L.LEDGER_NAME = AP.LEDGER_NAME
    WHERE M.SOURCE_TABLE = 'AP_TRANSACTIONS' AND M.SCHEME = 'WA' AND M.REVENUE_ANALYSIS_SORT IN ('10')
) U
GROUP BY 
U.MULTI_SCHEME_ID
, U.SCHEME
, U.REVENUE_ANALYSIS_SORT
, U.PAYMENT_PROCESSES_AP_SORT
, U.REVENUE_ANALYSIS_CLASSIFICATION
, U.CLASSIFICATION
, U.SOURCE
, U.COMMENTS
, U.ACCOUNTING_MONTH_KEY
