SELECT
L.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, L.SCHEME AS SCHEME
, B.ID AS ID
, A.ACCOUNT_L31_CODE AS ACCOUNT_L31_CODE
, A.ACCOUNT_L31_CODE || ' - ' ||  REPLACE(A.ACCOUNT_L31_DESC,'Sub-Total','') AS ACCOUNT_L31
, A.ACCOUNT_L30_CODE || ' - ' ||  REPLACE(A.ACCOUNT_L30_DESC,'Sub-Total','') AS ACCOUNT_L30
, A.ACCOUNT_L29_CODE || ' - ' ||  REPLACE(A.ACCOUNT_L29_DESC,'Sub-Total','') AS ACCOUNT_L29
, A.ACCOUNT_CODE || ' - ' ||  A.ACCOUNT_DESC AS ACCOUNT
, A.ACCOUNT_CODE AS ACCOUNT_CODE
, A.ACCOUNT_TREE_CODE AS ACCOUNT_TREE_CODE
, NVL(B.ENTITY_CODE || ' - ' ||  E.ENTITY_DESC, B.ENTITY_CODE) AS ENTITY
, E.ENTITY_L31_CODE|| ' - ' ||  E.ENTITY_L31_DESC AS ENTITY_PARENT
, B.COST_CENTER_CODE || ' - ' ||  C.COST_CENTER_DESC AS COST_CENTER
, CC.COST_CENTER_MAP_L_1 AS COST_CENTER_PARENT
, B.CURRENCY_CODE AS CURRENCY
, M.MAT_TYPE_DESC AS MAT_TYPE_DESC
, B.PROJECT_CODE || ' - ' ||  PR.PROJECT_DESC AS SPARE
, NVL(P1.FISCAL_PERIOD_START_DATE,P2.FISCAL_PERIOD_START_DATE) AS PERIOD
, TO_CHAR(NVL(P1.FISCAL_PERIOD_START_DATE,P2.FISCAL_PERIOD_START_DATE), 'YYYYMMDD') AS PERIOD_KEY
, P1.FISCAL_YEAR AS FISCAL_YEAR_PRIMARY
, P2.FISCAL_YEAR AS FISCAL_YEAR_SECONDARY
, P1.FISCAL_PERIOD_NUM AS FISCAL_PERIOD_PRIMARY
, P2.FISCAL_PERIOD_NUM AS FISCAL_PERIOD_SECONDARY
, B.LEDGER_NAME AS LEDGER_NAME
, B.SCENARIO AS SCENARIO
, CASE WHEN A.ACCOUNT_L31_CODE = '40000' THEN -1 * B.BASE_BEGIN_BALANCE ELSE B.BASE_BEGIN_BALANCE END AS BASE_BEGIN_BALANCE
, CASE WHEN A.ACCOUNT_L31_CODE = '40000' THEN -1 * B.BASE_PERIOD_NET_ACTIVITY ELSE B.BASE_PERIOD_NET_ACTIVITY END AS BASE_PERIOD_NET_ACTIVITY
, CASE WHEN A.ACCOUNT_L31_CODE = '40000' THEN -1 * (B.BASE_BEGIN_BALANCE + B.BASE_PERIOD_NET_ACTIVITY) ELSE (B.BASE_BEGIN_BALANCE + B.BASE_PERIOD_NET_ACTIVITY) END AS ENDING_BALANCE
, B.FORECAST_VALUE AS FORECAST_VALUE
, B.BUDGET_VALUE AS BUDGET_VALUE
, CASE WHEN B.LEDGER_NAME = 'Service Co Ledger AU' THEN S.SCHEME_DESC ELSE NULL END AS CES_SCHEME
, SYSDATE() AS INSERT_DATE_UTC
FROM (
    SELECT 
    B.CONCATENATED_SEGMENTS || '-' || B.LEDGER_NAME || '-' || B.PERIOD_NAME AS ID
    , B.ENTITY_CODE
    , B.MATERIAL_TYPE_CODE
    , B.COST_CENTER_CODE
    , B.ACCOUNT_CODE
    , B.LEDGER_NAME
    , B.PERIOD_NAME
    , B.INTERCOMPANY_CODE
    , B.PROJECT_CODE
    , B.CURRENCY_CODE
    , B.BALANCE_TYPE AS SCENARIO
    , B.BASE_BEGIN_BALANCE
    , B.BASE_PERIOD_NET_ACTIVITY
    , NULL AS BUDGET_VALUE
    , NULL AS FORECAST_VALUE
    , SCHEME_CODE
    FROM 
    {{ source('CES_ERP', 'GL_BALANCES') }} AS B
    UNION ALL
    SELECT
    BG._LINE || ' - ' || BG.SCENARIO AS ID
    , TO_CHAR(BG.ENTITY_CODE) AS ENTITY_CODE
    , LTRIM(BG.MATERIAL_TYPE_CODE,'M')
    , LTRIM(BG.COST_CENTER_CODE,'C')
    , TO_CHAR(BG.ACCOUNT_CODE) AS ACCOUNT_CODE
    , BG.LEDGER_NAME
    , BG.PERIOD_NAME||'-'||LTRIM(BG.FIN_YEAR,'FY') AS PERIOD_NAME
    , NULL AS INTERCOMPANY_CODE
    , NULL AS PROJECT_CODE
    , NULL AS CURRENCY_CODE
    , BG.SCENARIO
    , NULL AS BASE_BEGIN_BALANCE
    , NULL AS BASE_PERIOD_NET_ACTIVITY
    , BG.VALUE AS BUDGET_VALUE
    , NULL AS FORECAST_VALUE
    , NULL AS SCHEME_CODE
    FROM 
    {{ source('CES_FINANCE', 'BUDGETS_SCHEME') }} AS BG
    UNION ALL
    SELECT
    F._LINE || ' - ' || F.SCENARIO AS ID
    , TO_CHAR(F.ENTITY_CODE) AS ENTITY_CODE
    , LTRIM(F.MATERIAL_TYPE_CODE,'M')
    , LTRIM(F.COST_CENTER_CODE,'C')
    , TO_CHAR(F.ACCOUNT_CODE) AS ACCOUNT_CODE
    , F.LEDGER_NAME
    , F.PERIOD_NAME||'-'||LTRIM(F.FIN_YEAR,'FY') AS PERIOD_NAME
    , NULL AS INTERCOMPANY_CODE
    , NULL AS PROJECT_CODE
    , NULL AS CURRENCY_CODE
    , F.SCENARIO
    , NULL AS BASE_BEGIN_BALANCE
    , NULL AS BASE_PERIOD_NET_ACTIVITY
    , NULL AS BUDGET_VALUE
    , F.VALUE AS FORECAST_VALUE
    , NULL AS SCHEME_CODE
    FROM 
    {{ source('CES_FINANCE', 'FORECASTS_SCHEME') }} AS F
) B 
LEFT JOIN {{ source('CES_ERP', 'GL_SCHEME') }} AS S
ON B.SCHEME_CODE = S.SCHEME_CODE 
LEFT JOIN {{ ref('ERP_LEDGER') }} AS L
ON B.LEDGER_NAME = L.LEDGER_NAME
LEFT JOIN {{ source('CES_ERP', 'GL_ENTITY') }} AS E
ON B.ENTITY_CODE = E.ENTITY_CODE
AND E.ENTITY_TREE_CODE = L.ENTITY_TREE_CODE
INNER JOIN {{ source('CES_ERP', 'GL_ACCOUNT') }} AS A
ON B.ACCOUNT_CODE = A.ACCOUNT_CODE
AND A.ACCOUNT_TREE_CODE = L.ACCOUNT_TREE_CODE
LEFT JOIN {{ source('CES_ERP', 'GL_PERIOD') }} AS P1
ON L.FISCAL_PERIOD_PRIMARY= P1.FISCAL_PERIOD_SET_NAME
AND B.PERIOD_NAME = CASE WHEN B.SCENARIO <> 'Actual' and P1.ADJ_PERIOD_IND =  'No'  THEN TO_CHAR(P1.FISCAL_PERIOD_START_DATE, 'MON') ||'-'|| RIGHT(P1.FISCAL_YEAR,2) ELSE P1.FISCAL_PERIOD END
LEFT JOIN {{ source('CES_ERP', 'GL_PERIOD') }} AS P2
ON L.FISCAL_PERIOD_SECONDARY = P2.FISCAL_PERIOD_SET_NAME
AND B.PERIOD_NAME = CASE WHEN B.SCENARIO <> 'Actual' and P2.ADJ_PERIOD_IND =  'No'  THEN TO_CHAR(P2.FISCAL_PERIOD_START_DATE, 'MON') ||'-'|| RIGHT(P2.FISCAL_YEAR,2) ELSE P2.FISCAL_PERIOD END
LEFT JOIN {{ source('CES_ERP', 'GL_COST_CENTER') }} AS C
ON B.COST_CENTER_CODE= C.COST_CENTER_CODE
AND C.COST_CENTER_TREE_CODE= L.COST_CENTRE_TREE_CODE
LEFT JOIN {{ source('CES_ERP', 'GL_MATERIAL_TYPE') }} AS M
ON B.MATERIAL_TYPE_CODE = M.MAT_TYPE_CODE
AND M.MAT_TYPE_TREE_CODE = L.MAT_TYPE_TREE_CODE
LEFT JOIN {{ source('CES_FINANCE', 'COST_CENTRE_MAPPING') }} AS CC
ON B.COST_CENTER_CODE = CC.COST_CENTER_CODE
LEFT JOIN {{ source('CES_ERP', 'GL_PROJECT') }} AS PR
ON B.PROJECT_CODE = PR.PROJECT_CODE
AND L.PROJECT_TREE_CODE= PR.PROJECT_TREE_CODE