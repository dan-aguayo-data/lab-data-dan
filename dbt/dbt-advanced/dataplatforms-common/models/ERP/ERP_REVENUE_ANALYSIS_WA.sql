SELECT
-1 AS MULTI_SCHEME_ID
, 'CES' AS SCHEME
, M.ID AS ID
, M.CATEGORY AS SORT_CATEGORY
, M.GROUP_BY AS GROUP_BY
, M.SORT_BY AS SORT_BY
, M.REVENUE_ANALYSIS_CLASSIFICATION AS REVENUE_ANALYSIS_CLASSIFICATION
, CASE WHEN M.REVENUE_ANALYSIS_CLASSIFICATION IN ('Data Platform - Fixed Fee') THEN S.DRIVER_VALUE ELSE COALESCE(S.TOTAL_FEE,R.AMOUNT) END AS AMOUNT
, F.AMOUNT AS FORECAST_VALUE
, M.UNIT_PRICING AS UNIT_PRICING
, M.FORECAST_REVENUE_PERCENT AS FORECAST_REVENUE_PERCENT
, M.ACTUAL_REVENUE_PERCENT AS ACTUAL_REVENUE_PERCENT
, COALESCE(S.PERIOD_KEY,R.ACCOUNTING_MONTH_KEY,F.FORECAST_DATE_KEY) AS ACCOUNTING_MONTH_KEY
, (CASE WHEN M.REVENUE_ANALYSIS_CLASSIFICATION = 'Recycling Payment to PRO' THEN 0.8 WHEN M.REVENUE_ANALYSIS_CLASSIFICATION = 'Processor and Recycler Auction Payments' THEN 0.2 ELSE 1 END) * (CASE WHEN M.REVENUE_ANALYSIS_CLASSIFICATION IN ('Recycling Payment to PRO', 'Processor and Recycler Auction Payments') THEN (COALESCE(S.TOTAL_FEE,R.AMOUNT)-SUB.ACTUAL) WHEN M.REVENUE_ANALYSIS_CLASSIFICATION IN ('Data Platform - Fixed Fee') THEN S.DRIVER_VALUE ELSE COALESCE(S.TOTAL_FEE,R.AMOUNT) END) AS ACTUAL
, (CASE WHEN M.REVENUE_ANALYSIS_CLASSIFICATION = 'Recycling Payment to PRO' THEN 0.8 WHEN M.REVENUE_ANALYSIS_CLASSIFICATION = 'Processor and Recycler Auction Payments' THEN 0.2 ELSE 1 END) * (CASE WHEN M.REVENUE_ANALYSIS_CLASSIFICATION IN ('Recycling Payment to PRO', 'Processor and Recycler Auction Payments') THEN (COALESCE(S.TOTAL_FEE,R.AMOUNT)-SUB.ACTUAL) WHEN M.REVENUE_ANALYSIS_CLASSIFICATION IN ('Data Platform - Fixed Fee') THEN S.DRIVER_VALUE ELSE COALESCE(S.TOTAL_FEE,R.AMOUNT) END)/(CASE WHEN M.REVENUE_ANALYSIS_CLASSIFICATION IN ('Processor and Recycler Auction Payments','Processing Payment','Logistics Fees','Administration Fees (PRO WA BU)', 'Scheme Float- Administration Fees (PRO)','Other Direct Expenses','BAS payments','Recycling Payment to PRO') THEN 1 ELSE 1.1 END) AS ACTUAL_EXC_GST
, CASE WHEN M.REVENUE_ANALYSIS_CLASSIFICATION IN ('Administration Fees (PRO WA BU)', 'Scheme Float- Administration Fees (PRO)', 'BAS payments','Branding Fee - Public Website','Data Platform - Fixed Fee','Data Platform - Licensing Fee') THEN F.AMOUNT WHEN M.REVENUE_ANALYSIS_CLASSIFICATION IN ('Branding Fee - Project Fee','Data Platform - Project Fee') THEN F.AMOUNT/0.9 ELSE F.AMOUNT*1.1 END AS GST_INC_FORECAST
, CASE WHEN M.UNIT_PRICING <> 0 THEN (0.9*(CASE WHEN M.REVENUE_ANALYSIS_CLASSIFICATION IN ('Administration Fees (PRO WA BU)', 'Scheme Float- Administration Fees (PRO)', 'BAS payments','Branding Fee - Public Website','Data Platform - Fixed Fee','Data Platform - Licensing Fee') THEN F.AMOUNT WHEN M.REVENUE_ANALYSIS_CLASSIFICATION IN ('Branding Fee - Project Fee','Data Platform - Project Fee') THEN F.AMOUNT/0.9 ELSE F.AMOUNT*1.1 END))/M.UNIT_PRICING ELSE 0 END AS FORECAST_UNIT
, CASE WHEN M.UNIT_PRICING <> 0 THEN (CASE WHEN M.REVENUE_ANALYSIS_CLASSIFICATION = 'Recycling Payment to PRO' THEN 0.8 WHEN M.REVENUE_ANALYSIS_CLASSIFICATION = 'Processor and Recycler Auction Payments' THEN 0.2 ELSE 1 END) * (CASE WHEN M.REVENUE_ANALYSIS_CLASSIFICATION IN ('Recycling Payment to PRO', 'Processor and Recycler Auction Payments') THEN (COALESCE(S.TOTAL_FEE,R.AMOUNT)-SUB.ACTUAL) ELSE COALESCE(S.TOTAL_FEE,R.AMOUNT) END)/M.UNIT_PRICING ELSE 0 END AS ACTUAL_UNIT
, SYSDATE() AS INSERT_DATE_UTC
FROM 
{{ source('CES_FINANCE', 'ERP_REVENUE_VARIANCE_ANALYSIS_DEV') }} AS M
LEFT JOIN (
    SELECT *
    FROM {{ ref('ERP_REVENUE_MAPPING_WA') }} AS R
    WHERE R.COMMENTS NOT IN ('Amounts Refunded to Customers (All Payment Types), Collection Fees')
) R
ON R.REVENUE_ANALYSIS_CLASSIFICATION = M.REVENUE_ANALYSIS_CLASSIFICATION AND M.SOURCE = 'AP' AND M.SCHEME = 'WA'
LEFT JOIN {{ ref('ERP_SERVICE_FEE_SUMMARY_WA') }} AS S
ON S.DRIVER = M.CES_SUMMARY_MAPPING AND M.SOURCE = 'SUMMARY' AND M.SCHEME = 'WA'
LEFT JOIN (
    SELECT 
    M.REVENUE_ANALYSIS_CLASSIFICATION,
    M.SOURCE,
    COALESCE(S.PERIOD_KEY,R.ACCOUNTING_MONTH_KEY,F.FORECAST_DATE_KEY) AS ACCOUNTING_MONTH_KEY,
    COALESCE(S.TOTAL_FEE,R.AMOUNT) AS ACTUAL
    FROM 
    {{ source('CES_FINANCE', 'ERP_REVENUE_VARIANCE_ANALYSIS_DEV') }} AS M
    LEFT JOIN {{ ref('ERP_REVENUE_MAPPING_WA') }} AS R
    ON R.REVENUE_ANALYSIS_CLASSIFICATION = M.REVENUE_ANALYSIS_CLASSIFICATION AND M.SOURCE = 'AP' AND M.SCHEME = 'WA'
    LEFT JOIN {{ ref('ERP_SERVICE_FEE_SUMMARY_WA') }} AS S
    ON S.DRIVER = M.CES_SUMMARY_MAPPING AND M.SOURCE = 'SUMMARY' AND M.SCHEME = 'WA'
    FULL JOIN {{ source('CES_FINANCE', 'ERP_REVENUE_ANALYSIS_FORECAST_DEV') }} AS F
    ON F.FORECAST_DATE_KEY= COALESCE(S.PERIOD_KEY,R.ACCOUNTING_MONTH_KEY) AND F.SCHEME = 'WA'
    AND F.ID = M.ID
    WHERE M.REVENUE_ANALYSIS_CLASSIFICATION = 'Processor and Recycler Auction Receipts'
) SUB
ON SUB.ACCOUNTING_MONTH_KEY = R.ACCOUNTING_MONTH_KEY AND M.SOURCE = 'AP' AND M.SCHEME = 'WA' AND M.REVENUE_ANALYSIS_CLASSIFICATION IN ('Recycling Payment to PRO', 'Processor and Recycler Auction Payments')
FULL JOIN {{ source('CES_FINANCE', 'ERP_REVENUE_ANALYSIS_FORECAST_DEV') }} AS F
ON F.FORECAST_DATE_KEY= COALESCE(S.PERIOD_KEY,R.ACCOUNTING_MONTH_KEY) AND F.SCHEME = 'WA'
AND F.ID = M.ID
WHERE M.SCHEME = 'WA'