SELECT
CASE WHEN F.SCHEME = 'QLD' THEN '10000' WHEN F.SCHEME = 'WA' THEN '10001' ELSE '-1' END AS MULTI_SCHEME_ID
, F.SCHEME AS SCHEME
, COALESCE(RM.SORT,MA.SORT) || COALESCE(RM.CODE,MA.CODE) || COALESCE(FO.FORECAST_DATE_KEY,F.ACCOUNTING_MONTH_KEY,MA.PERIOD) AS ID
, COALESCE(RM.CODE,MA.CODE) AS CODE
, COALESCE(RM.ITEM,MA.ITEM) AS ITEM
, COALESCE(RM.DRIVER,MA.DRIVER) AS DRIVER
, IFNULL(MA.DRIVER_VALUE,F.AMOUNT) AS DRIVER_VALUE
, CASE WHEN IFNULL(MA.RATE_MARGIN_TYPE,RM.RATE_MARGIN_TYPE) = 'Percent' THEN ROUND((IFNULL(MA.RATE_MARGIN,RM.RATE_MARGIN) * 100),2) || '%' ELSE IFNULL(MA.RATE_MARGIN,RM.RATE_MARGIN) END AS RATE_MARGIN
, IFNULL(MA.RATE_MARGIN_TYPE,RM.RATE_MARGIN_TYPE) AS RATE_MARGIN_TYPE
, FO.AMOUNT AS FORECAST
, COALESCE(RM.COMMENT,MA.COMMENT) AS COMMENT
, COALESCE(FO.FORECAST_DATE_KEY,F.ACCOUNTING_MONTH_KEY,MA.PERIOD) AS PERIOD_KEY
, COALESCE(RM.SORT,MA.SORT) AS SORT
, CASE WHEN IFNULL(MA.RATE_MARGIN_TYPE,RM.RATE_MARGIN_TYPE) IN ('Percent' ,'Rate') THEN IFNULL(MA.RATE_MARGIN,RM.RATE_MARGIN) * IFNULL(MA.DRIVER_VALUE,F.AMOUNT) ELSE IFNULL(MA.DRIVER_VALUE,F.AMOUNT) END AS TOTAL_FEE
, NVL((CASE WHEN IFNULL(MA.RATE_MARGIN_TYPE,RM.RATE_MARGIN_TYPE) IN ('Percent' ,'Rate') THEN IFNULL(MA.RATE_MARGIN,RM.RATE_MARGIN) * IFNULL(MA.DRIVER_VALUE,F.AMOUNT) ELSE IFNULL(MA.DRIVER_VALUE,F.AMOUNT) END),0) - NVL(FO.AMOUNT,0) AS VARIANCE
, SYSDATE() AS INSERT_DATE_UTC
FROM 
{{ source('CES_FINANCE', 'CES_SERVICE_FEE_SUMMARY_DEV') }} AS RM -- MAPPING
LEFT JOIN (
    --AP ERP_REVENUE_MAPPING
    SELECT
    'QLD' AS SCHEME,
    RM.SORT AS ID,
    F.ACCOUNTING_MONTH_KEY,
    SUM(F.AMOUNT_INCLUDING_GST) AS AMOUNT
    FROM {{ ref('ERP_REVENUE_MAPPING_QLD') }} AS F 
    INNER JOIN {{ source('CES_FINANCE', 'CES_SERVICE_FEE_SUMMARY_DEV') }} AS RM -- MAPPING
    ON RM.AP_LINK_LOGIC = F.REVENUE_ANALYSIS_SORT AND RM.AP_LINK_LOGIC IN ('6','7','8')
    WHERE RM.SCHEME = 'QLD'
    GROUP BY 
    RM.SORT,
    F.ACCOUNTING_MONTH_KEY
 
    UNION ALL
    --AR + AP - 1.7 Material Brokerage Auction Fee QLD
    SELECT
    'QLD' AS SCHEME,
    9 AS ID,
    C.ACCOUNTING_MONTH_KEY AS ACCOUNTING_MONTH_KEY,
    SUM(C.AMOUNT) AS AMOUNT
    FROM (
          SELECT --PROCESSOR NEGATIVE
          B.INVOICE_NUMBER,
          LEFT(B.ACCOUNTING_DATE_KEY,6) || '01' AS ACCOUNTING_MONTH_KEY,
          (CASE WHEN SUM((B.TOTAL_DISTRIBUTION_AMOUNT/1.1) * 0.026) > 14.5 THEN SUM((B.TOTAL_DISTRIBUTION_AMOUNT/1.1) * 0.026) ELSE 14.5 END) AS AMOUNT
          FROM {{ ref('ERP_AP_TRANSACTIONS') }} AS B
          WHERE B.PAY_GROUP = 'RECYCLER NEGATIVE AUCTION' AND B.BUSINESS_UNIT_NAME = 'Scheme QLD BU' AND B.LEDGER_NAME IN ('Scheme Ledger AU','Processor QLD Ledger AU')
          GROUP BY LEFT(B.ACCOUNTING_DATE_KEY,6) || '01', B.INVOICE_NUMBER
          UNION ALL
          SELECT 
          C.TRANSACTION_NUMBER AS INVOICE_NUMBER,
          LEFT(C.ACCOUNTING_DATE_KEY,6) || '01' AS ACCOUNTING_MONTH_KEY,
          (CASE WHEN SUM((C.AMOUNT_DR/1.1) * 0.026) > 14.5 THEN SUM((C.AMOUNT_DR/1.1) * 0.026) ELSE 14.5 END) AS AMOUNT
          FROM {{ ref('ERP_GL_TRANSACTIONS') }} AS C
          WHERE C.TRANSACTION_TYPE IN ('AuctionPrcRecyclrInv','AuctionPrcRecyclr Cr') AND C.BUSINESS_UNIT_NAME = 'Scheme QLD BU' AND C.LEDGER_NAME IN ('Scheme Ledger AU','Processor QLD Ledger AU') AND C.JOURNAL_CATEGORY_NAME <> 'Credit Memos'
          GROUP BY LEFT(C.ACCOUNTING_DATE_KEY,6) || '01', C.TRANSACTION_NUMBER) C --PROCESSOR_POSITIVE
     GROUP BY C.ACCOUNTING_MONTH_KEY
 
    UNION ALL
    --AR ERP_REVENUE_MAPPING QLD
    SELECT
    'QLD' AS SCHEME,
    7 AS ID,
    LEFT(C.ACCOUNTING_DATE_KEY,6) || '01' AS ACCOUNTING_MONTH_KEY,
    SUM(C.AMOUNT_DR)*(2/3) AS AMOUNT
    FROM {{ ref('ERP_GL_TRANSACTIONS') }} AS C
    WHERE C.JOURNAL_CATEGORY_NAME = 'Adjustment' AND C.COST_CENTER = '8100 - Marketing' AND C.LEDGER_NAME IN ('Scheme Ledger AU','Processor QLD Ledger AU','Service Co Ledger AU')
    GROUP BY LEFT(C.ACCOUNTING_DATE_KEY,6) || '01'
 
    UNION ALL
    --AR ERP_REVENUE_MAPPING QLD
    SELECT
    'QLD' AS SCHEME,
    8 AS ID,
    LEFT(C.ACCOUNTING_DATE_KEY,6) || '01' AS ACCOUNTING_MONTH_KEY,
    SUM(C.AMOUNT_DR) AS AMOUNT
    FROM {{ ref('ERP_GL_TRANSACTIONS') }} AS C
    WHERE C.JOURNAL_CATEGORY_NAME IN ('Purchase Invoices','Payroll','Adjustment') AND C.COST_CENTER = '8400 - Call Centre' AND C.LEDGER_NAME IN ('Scheme Ledger AU','Processor QLD Ledger AU','Service Co Ledger AU')
    GROUP BY LEFT(C.ACCOUNTING_DATE_KEY,6) || '01'
 
    UNION ALL
    --AP ERP_REVENUE_MAPPING SUMMARY TOTAL QLD
    SELECT
    'QLD' AS SCHEME,
    RM.SORT AS ID,
    F.ACCOUNTING_MONTH_KEY,
    CASE WHEN RM.SORT = 1 THEN SUM(F.AMOUNT_INCLUDING_GST) ELSE SUM(F.AMOUNT_INCLUDING_GST) * 0.0068 END AS AMOUNT
    FROM {{ ref('ERP_REVENUE_MAPPING_QLD') }} AS F 
    CROSS JOIN {{ source('CES_FINANCE', 'CES_SERVICE_FEE_SUMMARY_DEV') }} AS RM -- MAPPING
    WHERE RM.SORT IN (1,2) AND RM.SCHEME = 'QLD' AND F.PAYMENT_PROCESSES_AP_SORT <> 0
    GROUP BY 
    RM.SORT,
    F.ACCOUNTING_MONTH_KEY
) F
ON F.ID = RM.SORT
    --MANUAL ENTRY/ADJUSTMENTS BY ESHAN QLD
FULL JOIN (
          SELECT
          RM.CODE AS CODE
          , RM.ITEM AS ITEM
          , RM.SORT AS SORT
          , RM.DRIVER AS DRIVER
          , M.RATE_MARGIN
          , M.RATE_MARGIN_TYPE
          , RM.FORECAST_PN_L_LINE_CODE 
          , RM.COMMENT
          , M.PERIOD
          , M.DRIVER_VALUE
          FROM
          {{ source('CES_FINANCE', 'SERVICE_FEE_MANUAL_INPUT_DEV') }} AS M
          LEFT JOIN {{ source('CES_FINANCE', 'CES_SERVICE_FEE_SUMMARY_DEV') }} AS RM
          ON M.SORT = RM.SORT
          WHERE M.SCHEME = 'QLD' AND RM.SCHEME = 'QLD') MA
ON MA.SORT = RM.SORT AND MA.PERIOD = F.ACCOUNTING_MONTH_KEY
LEFT JOIN {{ source('CES_FINANCE', 'ERP_SUMMARY_FORECAST_DEV') }} AS FO -- FORECAST
ON FO.PNL_LINE = COALESCE(RM.FORECAST_PN_L_LINE_CODE,MA.FORECAST_PN_L_LINE_CODE) AND COALESCE(MA.PERIOD,F.ACCOUNTING_MONTH_KEY) = FO.FORECAST_DATE_KEY AND FO.SCHEME = 'QLD'
WHERE NVL(RM.AP_LINK_LOGIC,0) NOT IN ('6','8') AND RM.SCHEME = 'QLD' --AND COALESCE(FO.FORECAST_DATE_KEY,F.ACCOUNTING_MONTH_KEY,MA.PERIOD) = '20221201'