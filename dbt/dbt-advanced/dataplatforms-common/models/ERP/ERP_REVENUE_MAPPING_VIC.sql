SELECT
NVL(U.MULTI_SCHEME_ID, '-1') AS MULTI_SCHEME_ID
, NVL(U.SCHEME, 'CES') AS SCHEME
, U.REVENUE_ANALYSIS_SORT AS REVENUE_ANALYSIS_SORT
, U.PAYMENT_PROCESSES_AP_SORT AS PAYMENT_PROCESSES_AP_SORT
, U.REVENUE_ANALYSIS_CLASSIFICATION AS REVENUE_ANALYSIS_CLASSIFICATION
, U.CLASSIFICATION AS CLASSIFICATION
, U.SOURCE AS SOURCE
, U.COMMENTS AS COMMENTS
, U.ACCOUNTING_MONTH_KEY AS ACCOUNTING_MONTH_KEY
, CASE WHEN U.REVENUE_ANALYSIS_CLASSIFICATION IN ('Payments to ATO') THEN ABS(SUM(U.AMOUNT)) ELSE SUM(U.AMOUNT) END AS AMOUNT
, CASE WHEN U.REVENUE_ANALYSIS_CLASSIFICATION IN ('State Service Fee', 'Payments to ATO') THEN 1 ELSE 1.1 END*CASE WHEN U.REVENUE_ANALYSIS_CLASSIFICATION IN ('Payments to ATO') THEN ABS(SUM(U.AMOUNT)) ELSE SUM(U.AMOUNT) END AS AMOUNT_INCLUDING_GST
, CASE WHEN U.REVENUE_ANALYSIS_CLASSIFICATION IN ('Payments to ATO') THEN ABS(SUM(U.AMOUNT)) ELSE SUM(U.AMOUNT) END AS AMOUNT_EXCLUDING_GST
, F.AMOUNT AS FORECAST_VALUE
, NVL(CASE WHEN U.REVENUE_ANALYSIS_CLASSIFICATION IN ('State Service Fee', 'Payments to ATO') THEN 1 ELSE 1.1 END*CASE WHEN U.REVENUE_ANALYSIS_CLASSIFICATION IN ('Payments to ATO') THEN ABS(SUM(U.AMOUNT)) ELSE SUM(U.AMOUNT) END, 0) - NVL(F.AMOUNT, 0) AS VARIANCE
, (NVL(CASE WHEN U.REVENUE_ANALYSIS_CLASSIFICATION IN ('State Service Fee', 'Payments to ATO') THEN 1 ELSE 1.1 END*CASE WHEN U.REVENUE_ANALYSIS_CLASSIFICATION IN ('Payments to ATO') THEN ABS(SUM(U.AMOUNT)) ELSE SUM(U.AMOUNT) END, 0) - NVL(F.AMOUNT, 0)) * 0.0042 AS SERVICE_FEE_IMPACT
, SYSDATE() AS INSERT_DATE_UTC
FROM (
    SELECT
    AR.MULTI_SCHEME_ID
    , AR.SCHEME
    , M.REVENUE_ANALYSIS_SORT
    , M.PAYMENT_PROCESSES_AP_SORT
    , M.REVENUE_ANALYSIS_CLASSIFICATION
    , M.CLASSIFICATION
    , M.SOURCE
    , M.COMMENTS
    , LEFT(AR.ACCOUNTING_DATE_KEY,6) || '01' AS ACCOUNTING_MONTH_KEY
    , NVL(AR.AMOUNT_DR,0) - NVL(AR.AMOUNT_CR,0) AS AMOUNT
    FROM {{ source('CES_FINANCE', 'ERP_REVENUE_MAPPING_DEV') }} AS M
    LEFT JOIN {{ ref('ERP_GL_TRANSACTIONS') }} AS AR
    ON M.ACCOUNT_CODE = LEFT(AR.ACCOUNT, 5) AND AR.LEDGER_NAME = 'Scheme VIC Ledger' AND M.SCHEME = 'VIC' AND (M.ACCOUNT_CODE NOT IN ('40005', '14600') AND M.COST_CENTER_PARENT IS NULL) AND AR.JOURNAL_CATEGORY_NAME IN ('Purchase Invoices')
    WHERE M.SOURCE_TABLE = 'GL_TRANSACTIONS' AND M.SCHEME = 'VIC' --AND AR.BUSINESS_CLASS_NAME = 'Receivable'
    UNION ALL
    SELECT
    AR.MULTI_SCHEME_ID
    , AR.SCHEME
    , M.REVENUE_ANALYSIS_SORT
    , M.PAYMENT_PROCESSES_AP_SORT
    , M.REVENUE_ANALYSIS_CLASSIFICATION
    , M.CLASSIFICATION
    , M.SOURCE
    , M.COMMENTS
    , LEFT(AR.ACCOUNTING_DATE_KEY,6) || '01' AS ACCOUNTING_MONTH_KEY
    , ABS(NVL(AR.AMOUNT_DR,0) - NVL(AR.AMOUNT_CR,0)) AS AMOUNT
    FROM {{ source('CES_FINANCE', 'ERP_REVENUE_MAPPING_DEV') }} AS M
    LEFT JOIN {{ ref('ERP_GL_TRANSACTIONS') }} AS AR
    ON M.ACCOUNT_CODE = LEFT(AR.ACCOUNT, 5) AND AR.LEDGER_NAME = 'Scheme VIC Ledger' AND M.SCHEME = 'VIC' AND M.ACCOUNT_CODE = 14600 AND M.COST_CENTER_PARENT = 'Balance Sheet' AND AR.JOURNAL_CATEGORY_NAME = 'Purchase Invoices' AND AR.COST_CENTER_PARENT = 'Balance Sheet'
    WHERE M.SOURCE_TABLE = 'GL_TRANSACTIONS' AND M.SCHEME = 'VIC' --AND AR.BUSINESS_CLASS_NAME = 'Receivable'
    UNION ALL
    SELECT
    AR.MULTI_SCHEME_ID
    , AR.SCHEME
    , M.REVENUE_ANALYSIS_SORT
    , M.PAYMENT_PROCESSES_AP_SORT
    , M.REVENUE_ANALYSIS_CLASSIFICATION
    , M.CLASSIFICATION
    , M.SOURCE
    , M.COMMENTS
    , LEFT(AR.ACCOUNTING_DATE_KEY,6) || '01' AS ACCOUNTING_MONTH_KEY
    , NVL(AR.AMOUNT_DR,0) - NVL(AR.AMOUNT_CR,0) AS AMOUNT
    FROM {{ source('CES_FINANCE', 'ERP_REVENUE_MAPPING_DEV') }} AS M
    LEFT JOIN {{ ref('ERP_GL_TRANSACTIONS') }} AS AR
    ON M.ACCOUNT_CODE = LEFT(AR.ACCOUNT, 5) AND AR.LEDGER_NAME = 'Scheme VIC Ledger' AND M.SCHEME = 'VIC' AND M.ACCOUNT_CODE = 14600 AND M.COST_CENTER_PARENT IS NULL AND AR.JOURNAL_CATEGORY_NAME = 'Purchase Invoices' AND AR.COST_CENTER_PARENT <> 'Balance Sheet' AND AR.POSTING_DATE IS NOT NULL
    WHERE M.SOURCE_TABLE = 'GL_TRANSACTIONS' AND M.SCHEME = 'VIC' --AND AR.BUSINESS_CLASS_NAME = 'Receivable'
    UNION ALL
    SELECT
    AR.MULTI_SCHEME_ID
    , AR.SCHEME
    , M.REVENUE_ANALYSIS_SORT
    , M.PAYMENT_PROCESSES_AP_SORT
    , M.REVENUE_ANALYSIS_CLASSIFICATION
    , M.CLASSIFICATION
    , M.SOURCE
    , M.COMMENTS
    , LEFT(AR.ACCOUNTING_DATE_KEY,6) || '01' AS ACCOUNTING_MONTH_KEY
    , ABS(NVL(AR.AMOUNT_DR,0) - NVL(AR.AMOUNT_CR,0)) AS AMOUNT
    FROM {{ source('CES_FINANCE', 'ERP_REVENUE_MAPPING_DEV') }} AS M
    LEFT JOIN {{ ref('ERP_GL_TRANSACTIONS') }} AS AR
    ON M.ACCOUNT_CODE = LEFT(AR.ACCOUNT, 5) AND AR.LEDGER_NAME = 'Scheme VIC Ledger' AND M.SCHEME = 'VIC' AND M.ACCOUNT_CODE = 40005 AND AR.JOURNAL_CATEGORY_NAME IN ('Sales Invoices') AND AR.COST_CENTER_PARENT <> 'Balance Sheet'
    WHERE M.SOURCE_TABLE = 'GL_TRANSACTIONS' AND M.SCHEME = 'VIC' --AND AR.BUSINESS_CLASS_NAME = 'Receivable'
    UNION ALL
    SELECT
    AR.MULTI_SCHEME_ID
    , AR.SCHEME
    , M.REVENUE_ANALYSIS_SORT
    , M.PAYMENT_PROCESSES_AP_SORT
    , M.REVENUE_ANALYSIS_CLASSIFICATION
    , M.CLASSIFICATION
    , M.SOURCE
    , M.COMMENTS
    , LEFT(AR.ACCOUNTING_DATE_KEY,6) || '01' AS ACCOUNTING_MONTH_KEY
    , NVL(AR.AMOUNT_DR,0) - NVL(AR.AMOUNT_CR,0) AS AMOUNT
    FROM {{ source('CES_FINANCE', 'ERP_REVENUE_MAPPING_DEV') }} AS M
    LEFT JOIN {{ ref('ERP_GL_TRANSACTIONS') }} AS AR
    ON M.REVENUE_ANALYSIS_SORT = 11 AND AR.LEDGER_NAME = 'Scheme VIC Ledger' AND M.SCHEME = 'VIC' AND AR.JOURNAL_CATEGORY_NAME IN ('Purchase Invoices') AND AR.COST_CENTER_PARENT <> 'Balance Sheet' AND LEFT(AR.ACCOUNT, 5) NOT IN ('40005', '14600', '54005', '56005', '57005', '57010', '58015', '58005', '58010') AND AR.COST_CENTER <> '5800 - Board' AND AR.POSTING_DATE IS NOT NULL
    WHERE M.SOURCE_TABLE = 'GL_TRANSACTIONS' AND M.SCHEME = 'VIC' --AND AR.BUSINESS_CLASS_NAME = 'Receivable'
    UNION ALL
    SELECT
    -1 AS MULTI_SCHEME_ID
    , 'CES' AS SCHEME
    , M.REVENUE_ANALYSIS_SORT
    , M.PAYMENT_PROCESSES_AP_SORT
    , M.REVENUE_ANALYSIS_CLASSIFICATION
    , M.CLASSIFICATION
    , M.SOURCE
    , M.COMMENTS
    , B.PERIOD AS ACCOUNTING_MONTH_KEY
    , B.AMOUNT AS AMOUNT
    FROM {{ source('CES_FINANCE', 'ERP_REVENUE_MAPPING_DEV') }} AS M
    INNER JOIN {{ source('CES_FINANCE', 'AP_ADHOC_MANUAL_INPUT_DEV') }} AS B
    ON M.SOURCE_TABLE = 'AP_ADHOC_MANUAL_INPUT' AND M.SCHEME = 'VIC' AND B.SCHEME = 'VIC'
    WHERE M.SCHEME = 'VIC' AND B.SCHEME = 'VIC'
    UNION ALL
    SELECT
    AR.MULTI_SCHEME_ID
    , AR.SCHEME
    , M.REVENUE_ANALYSIS_SORT
    , M.PAYMENT_PROCESSES_AP_SORT
    , M.REVENUE_ANALYSIS_CLASSIFICATION
    , M.CLASSIFICATION
    , M.SOURCE
    , M.COMMENTS
    , LEFT(AR.ACCOUNTING_DATE_KEY,6) || '01' AS ACCOUNTING_MONTH_KEY
    , NVL(AR.AMOUNT_DR,0) - NVL(AR.AMOUNT_CR,0) AS AMOUNT
    FROM {{ source('CES_FINANCE', 'ERP_REVENUE_MAPPING_DEV') }} AS M
    LEFT JOIN {{ ref('ERP_GL_TRANSACTIONS') }} AS AR
    ON M.ACCOUNT_CODE = LEFT(AR.ACCOUNT, 5) AND AR.LEDGER_NAME = 'Scheme VIC Ledger' AND M.SCHEME = 'VIC' AND M.ACCOUNT_CODE = 21010 AND M.COST_CENTER_PARENT = 'Balance Sheet' AND AR.JOURNAL_CATEGORY_NAME = 'Other' AND AR.COST_CENTER_PARENT = 'Balance Sheet' AND UPPER(AR.JOURNAL_NAME) LIKE '%GST REALLOCATION%'
    WHERE M.SOURCE_TABLE = 'GL_TRANSACTIONS' AND M.SCHEME = 'VIC' --AND AR.BUSINESS_CLASS_NAME = 'Receivable'
) U
FULL JOIN {{ source('CES_FINANCE', 'ERP_REVENUE_MAPPING_FORECAST_DEV') }} AS F
ON F.FORECAST_DATE_KEY = U.ACCOUNTING_MONTH_KEY
AND F.REVENUE_ANALYSIS_CLASSIFICATION = U.REVENUE_ANALYSIS_CLASSIFICATION
GROUP BY 
U.MULTI_SCHEME_ID
, U.SCHEME
, U.REVENUE_ANALYSIS_SORT
, U.PAYMENT_PROCESSES_AP_SORT
, U.REVENUE_ANALYSIS_CLASSIFICATION
, U.CLASSIFICATION
, U.SOURCE
, U.COMMENTS
, U.ACCOUNTING_MONTH_KEY
, F.AMOUNT
