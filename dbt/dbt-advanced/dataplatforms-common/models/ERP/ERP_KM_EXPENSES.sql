SELECT
10000 AS MULTI_SCHEME_ID
, 'COEX' AS SCHEME
, E.EXPENSE_LINE_ID AS EXPENSE_LINE_ID
, CAST(E.EXPENSE_START_DATE AS DATE) AS START_DATE
, TO_CHAR(E.EXPENSE_START_DATE, 'YYYYMMDD') AS START_DATE_KEY
, E.EMPLOYEE_NAME AS EMPLOYEE_NAME
, E.TRIP_DISTANCE AS TRIP_DISTANCE
, E.EXPENSE_TYPE AS EXPENSE_TYPE
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_ERP', 'KM_EXPENSES') }} AS E