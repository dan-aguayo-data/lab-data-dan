SELECT
CASE WHEN F.SCHEME = 'QLD' THEN '10000' WHEN F.SCHEME = 'WA' THEN '10001' ELSE '-1' END AS MULTI_SCHEME_ID
, F.SCHEME AS SCHEME
, COALESCE(RM.SORT,MA.SORT) || COALESCE(RM.CODE,MA.CODE) || COALESCE(FO.FORECAST_DATE_KEY,F.ACCOUNTING_MONTH_KEY,MA.PERIOD) AS ID
, COALESCE(RM.CODE,MA.CODE) AS CODE
, COALESCE(RM.ITEM,MA.ITEM) AS ITEM
, COALESCE(RM.DRIVER,MA.DRIVER) AS DRIVER
, IFNULL(MA.DRIVER_VALUE,F.AMOUNT) AS DRIVER_VALUE
, CASE WHEN IFNULL(MA.RATE_MARGIN_TYPE,RM.RATE_MARGIN_TYPE) = 'Percent' THEN ROUND((IFNULL(MA.RATE_MARGIN,RM.RATE_MARGIN) * 100),2) || '%' ELSE IFNULL(MA.RATE_MARGIN,RM.RATE_MARGIN) END AS RATE_MARGIN
, IFNULL(MA.RATE_MARGIN_TYPE,RM.RATE_MARGIN_TYPE) AS RATE_MARGIN_TYPE
, FO.AMOUNT AS FORECAST
, COALESCE(RM.COMMENT,MA.COMMENT) AS COMMENT
, COALESCE(FO.FORECAST_DATE_KEY,F.ACCOUNTING_MONTH_KEY,MA.PERIOD) AS PERIOD_KEY
, COALESCE(RM.SORT,MA.SORT) AS SORT
, CASE WHEN IFNULL(MA.RATE_MARGIN_TYPE,RM.RATE_MARGIN_TYPE) IN ('Percent' ,'Rate') THEN IFNULL(MA.RATE_MARGIN,RM.RATE_MARGIN) * IFNULL(MA.DRIVER_VALUE,F.AMOUNT) ELSE IFNULL(MA.DRIVER_VALUE,F.AMOUNT) END AS TOTAL_FEE
, NVL((CASE WHEN IFNULL(MA.RATE_MARGIN_TYPE,RM.RATE_MARGIN_TYPE) IN ('Percent' ,'Rate') THEN IFNULL(MA.RATE_MARGIN,RM.RATE_MARGIN) * IFNULL(MA.DRIVER_VALUE,F.AMOUNT) ELSE IFNULL(MA.DRIVER_VALUE,F.AMOUNT) END),0) - NVL(FO.AMOUNT,0) AS VARIANCE
, SYSDATE() AS INSERT_DATE_UTC
FROM 
{{ source('CES_FINANCE', 'CES_SERVICE_FEE_SUMMARY_DEV') }} AS RM -- MAPPING
LEFT JOIN (
    --AP ERP_REVENUE_MAPPING
    SELECT
    'WA' AS SCHEME,
    RM.SORT AS ID,
    F.ACCOUNTING_MONTH_KEY,
    SUM(F.AMOUNT_INCLUDING_GST) AS AMOUNT
    FROM {{ ref('ERP_REVENUE_MAPPING_WA') }} AS F 
    INNER JOIN {{ source('CES_FINANCE', 'CES_SERVICE_FEE_SUMMARY_DEV') }} AS RM -- MAPPING
    ON RM.AP_LINK_LOGIC = F.REVENUE_ANALYSIS_SORT AND RM.AP_LINK_LOGIC IN ('1','6','7','8')
    WHERE RM.SCHEME = 'WA' AND F.COMMENTS NOT IN ('Amounts Refunded to Customers (All Payment Types), Collection Fees')
    GROUP BY 
    RM.SORT,
    F.ACCOUNTING_MONTH_KEY
 
    UNION ALL
    --AR + AP - 1.7 Material Brokerage Auction Fee WA
    SELECT
    'WA' AS SCHEME,
    12 AS ID,
    C.ACCOUNTING_MONTH_KEY AS ACCOUNTING_MONTH_KEY,
    SUM(C.AMOUNT) AS AMOUNT
    FROM (
          SELECT --PROCESSOR NEGATIVE
          B.INVOICE_NUMBER,
          LEFT(B.ACCOUNTING_DATE_KEY,6) || '01' AS ACCOUNTING_MONTH_KEY,
          (CASE WHEN SUM(B.TOTAL_DISTRIBUTION_AMOUNT/1.1) = 0 THEN 0 WHEN SUM((B.TOTAL_DISTRIBUTION_AMOUNT/1.1) * 0.026) > (CASE WHEN LEFT(B.ACCOUNTING_DATE_KEY,6) || '01' < 20211001 THEN 14.5 WHEN LEFT(B.ACCOUNTING_DATE_KEY,6) || '01' >= 20211001 AND LEFT(B.ACCOUNTING_DATE_KEY,6) || '01' < 20221001 THEN 15.11 WHEN LEFT(B.ACCOUNTING_DATE_KEY,6) || '01' >= 20221001 AND LEFT(B.ACCOUNTING_DATE_KEY,6) || '01' < 20231001 THEN 16.17 WHEN LEFT(B.ACCOUNTING_DATE_KEY,6) || '01' >= 20231001 AND LEFT(B.ACCOUNTING_DATE_KEY,6) || '01' < 20241001 THEN 17.13 WHEN LEFT(B.ACCOUNTING_DATE_KEY,6) || '01' >= 20241001 THEN 17.93 END) THEN SUM((B.TOTAL_DISTRIBUTION_AMOUNT/1.1) * 0.026) ELSE (CASE WHEN LEFT(B.ACCOUNTING_DATE_KEY,6) || '01' < 20211001 THEN 14.5 WHEN LEFT(B.ACCOUNTING_DATE_KEY,6) || '01' >= 20211001 AND LEFT(B.ACCOUNTING_DATE_KEY,6) || '01' < 20221001 THEN 15.11 WHEN LEFT(B.ACCOUNTING_DATE_KEY,6) || '01' >= 20221001 AND LEFT(B.ACCOUNTING_DATE_KEY,6) || '01' < 20231001 THEN 16.17 WHEN LEFT(B.ACCOUNTING_DATE_KEY,6) || '01' >= 20231001 AND LEFT(B.ACCOUNTING_DATE_KEY,6) || '01' < 20241001 THEN 17.13 WHEN LEFT(B.ACCOUNTING_DATE_KEY,6) || '01' >= 20241001 THEN 17.93 END) END) AS AMOUNT
          FROM {{ ref('ERP_AP_TRANSACTIONS') }} AS B
          WHERE B.PAY_GROUP = 'RECYCLER NEGATIVE AUCTION' AND B.BUSINESS_UNIT_NAME = 'WA SCHEME BU' AND B.LEDGER_NAME IN ('Scheme WA Ledger AU','Processor WA Ledger AU')
          GROUP BY LEFT(B.ACCOUNTING_DATE_KEY,6) || '01', B.INVOICE_NUMBER
          UNION ALL
          SELECT --PROCESSOR POSITIVE
          C.TRANSACTION_NUMBER AS INVOICE_NUMBER,
          LEFT(C.ACCOUNTING_DATE_KEY,6) || '01' AS ACCOUNTING_MONTH_KEY,
          (CASE WHEN CR.CR_INVOICE_NUMBER IS NULL THEN 1 ELSE 0 END) * (CASE WHEN SUM(C.AMOUNT_DR/1.1) = 0 THEN 0 WHEN SUM((C.AMOUNT_DR/1.1) * 0.026) > (CASE WHEN LEFT(C.ACCOUNTING_DATE_KEY,6) || '01' < 20211001 THEN 14.5 WHEN LEFT(C.ACCOUNTING_DATE_KEY,6) || '01' >= 20211001 AND LEFT(C.ACCOUNTING_DATE_KEY,6) || '01' < 20221001 THEN 15.11 WHEN LEFT(C.ACCOUNTING_DATE_KEY,6) || '01' >= 20221001 AND LEFT(C.ACCOUNTING_DATE_KEY,6) || '01' < 20231001 THEN 16.17 WHEN LEFT(C.ACCOUNTING_DATE_KEY,6) || '01' >= 20231001 AND LEFT(C.ACCOUNTING_DATE_KEY,6) || '01' < 20241001 THEN 17.13 WHEN LEFT(C.ACCOUNTING_DATE_KEY,6) || '01' >= 20241001 THEN 17.93 END) THEN SUM((C.AMOUNT_DR/1.1) * 0.026) ELSE (CASE WHEN LEFT(C.ACCOUNTING_DATE_KEY,6) || '01' < 20211001 THEN 14.5 WHEN LEFT(C.ACCOUNTING_DATE_KEY,6) || '01' >= 20211001 AND LEFT(C.ACCOUNTING_DATE_KEY,6) || '01' < 20221001 THEN 15.11 WHEN LEFT(C.ACCOUNTING_DATE_KEY,6) || '01' >= 20221001 AND LEFT(C.ACCOUNTING_DATE_KEY,6) || '01' < 20231001 THEN 16.17 WHEN LEFT(C.ACCOUNTING_DATE_KEY,6) || '01' >= 20231001 AND LEFT(C.ACCOUNTING_DATE_KEY,6) || '01' < 20241001 THEN 17.13 WHEN LEFT(C.ACCOUNTING_DATE_KEY,6) || '01' >= 20241001 THEN 17.93 END) END) AS AMOUNT
          FROM {{ ref('ERP_GL_TRANSACTIONS') }} AS C
          LEFT JOIN (
              SELECT
              DISTINCT C.TRANSACTION_NUMBER AS CR_INVOICE_NUMBER,
              LEFT(C.ACCOUNTING_DATE_KEY,6) || '01' AS ACCOUNTING_MONTH_KEY
              FROM {{ ref('ERP_GL_TRANSACTIONS') }} AS C
              WHERE C.TRANSACTION_TYPE IN ('AuctionPrcRecyclrInv','AuctionPrcRecyclr Cr') AND C.BUSINESS_UNIT_NAME = 'WA SCHEME BU' AND C.LEDGER_NAME IN ('Scheme WA Ledger AU','Processor WA Ledger AU') AND C.JOURNAL_CATEGORY_NAME = 'Credit Memos' AND C.BUSINESS_CLASS_NAME IN ('Receivable') AND C.TRANSACTION_NUMBER LIKE '%CR%') CR
              ON C.TRANSACTION_NUMBER = REGEXP_REPLACE(CR.CR_INVOICE_NUMBER, '(CR\-|\-CR)', '') AND LEFT(C.ACCOUNTING_DATE_KEY,6) || '01' = CR.ACCOUNTING_MONTH_KEY
          WHERE C.TRANSACTION_TYPE IN ('AuctionPrcRecyclrInv','AuctionPrcRecyclr Cr') AND C.BUSINESS_UNIT_NAME = 'WA SCHEME BU' AND C.LEDGER_NAME IN ('Scheme WA Ledger AU','Processor WA Ledger AU') AND C.JOURNAL_CATEGORY_NAME <> 'Credit Memos'
          GROUP BY LEFT(C.ACCOUNTING_DATE_KEY,6) || '01', C.TRANSACTION_NUMBER, CR.CR_INVOICE_NUMBER
          UNION ALL
          SELECT --MRF AUCTION
          DISTINCT B.AR_TRANSACTION_NUMBER,
          LEFT(TO_CHAR(NVL(B.ACCOUNTING_DATE,J.ACCOUNTING_DATE), 'YYYYMMDD'), 6) || '01' AS ACCOUNTING_MONTH_KEY,
          ((CASE WHEN B.AR_TRANSACTION_NUMBER LIKE '%CR%' THEN -1 ELSE 1 END) * (CASE WHEN LEFT(TO_CHAR(NVL(B.ACCOUNTING_DATE,J.ACCOUNTING_DATE), 'YYYYMMDD'), 6) || '01' < 20250101 THEN 20.69 WHEN LEFT(TO_CHAR(NVL(B.ACCOUNTING_DATE,J.ACCOUNTING_DATE), 'YYYYMMDD'), 6) || '01' >= 20250101 AND LEFT(TO_CHAR(NVL(B.ACCOUNTING_DATE,J.ACCOUNTING_DATE), 'YYYYMMDD'), 6) || '01' < 20251001 THEN 24.56 END)) AS AMOUNT
          FROM {{ source('CES_ERP', 'GL_TRANSACTIONS_SUBLEDGER') }} AS B
          FULL JOIN {{ source('CES_ERP', 'GL_JOURNALS') }} AS J
          ON J.JOURNAL_HEADER_ID = B.GL_JOURNAL_HEADER_ID
          AND J.JOURNAL_LINE_NUM = B.GL_JOURNAL_LINE_NUM
          LEFT JOIN {{ ref('ERP_LEDGER') }} AS L
          ON NVL(B.LEDGER_NAME,J.LEDGER_NAME) = L.LEDGER_NAME
          INNER JOIN {{ source('CES_ERP', 'GL_ACCOUNT') }} AS A
          ON NVL(B.ACCOUNT_CODE,J.ACCOUNT_CODE) = A.ACCOUNT_CODE
          AND A.ACCOUNT_TREE_CODE = L.ACCOUNT_TREE_CODE
          WHERE B.LEDGER_NAME IN ('Scheme WA Ledger AU')
          AND B.TRANSACTION_TYPE IN ('AuctionMRFRecyclrInv', 'AuctionMRFRecyclr Cr')
          AND B.BUSINESS_CLASS_NAME IN ('Receivable')) C
     GROUP BY C.ACCOUNTING_MONTH_KEY
 
    UNION ALL
    --AP - Freight Management Technology Platform Fee
    SELECT
    'WA' AS SCHEME,
    11 AS ID,
    C.ACCOUNTING_MONTH_KEY AS ACCOUNTING_MONTH_KEY,
    ROUND(SUM(C.AMOUNT), 2) AS AMOUNT
    FROM (
          SELECT
          B.INVOICE_NUMBER,
          LEFT(B.ACCOUNTING_DATE_KEY,6) || '01' AS ACCOUNTING_MONTH_KEY,
          SUM(B.TOTAL_DISTRIBUTION_AMOUNT) AS AMOUNT
          FROM {{ ref('ERP_AP_TRANSACTIONS') }} AS B
          WHERE (B.PAY_GROUP = 'LOGISTICS FEES' AND B.BUSINESS_UNIT_NAME = 'WA SCHEME BU' AND B.LEDGER_NAME IN ('Scheme WA Ledger AU') AND B.ACCOUNT NOT IN ('21015 - GST Input') AND B.COST_CENTER NOT IN ('0000 - Balance Sheet')) OR (B.PAY_GROUP IN ('ADMIN' ) AND B.BUSINESS_UNIT_NAME = 'WA SCHEME BU' AND B.LEDGER_NAME IN ('Scheme WA Ledger AU') AND B.ACCOUNT IN ('52005 - Logistics Fees','52010 - Self Service Kiosk - Logistics','53006 - Processing Regional Glass') AND B.COST_CENTER IN ('1600 - Logistics'))
          GROUP BY LEFT(B.ACCOUNTING_DATE_KEY,6) || '01', B.INVOICE_NUMBER) C
     GROUP BY C.ACCOUNTING_MONTH_KEY
 
    UNION ALL
    --AR ERP_REVENUE_MAPPING WA
    SELECT
    'WA' AS SCHEME,
    10 AS ID,
    LEFT(C.ACCOUNTING_DATE_KEY,6) || '01' AS ACCOUNTING_MONTH_KEY,
    SUM(C.AMOUNT_DR) - SUM(C.AMOUNT_CR) AS AMOUNT
    FROM {{ ref('ERP_GL_TRANSACTIONS') }} AS C
    WHERE C.JOURNAL_CATEGORY_NAME IN ('Purchase Invoices','Payroll','Adjustment','Prepaid Expense') AND C.COST_CENTER = '8400 - Call Centre' AND C.LEDGER_NAME IN ('Service Co Ledger AU') AND C.SCHEME_CODE IN ('16')
    GROUP BY LEFT(C.ACCOUNTING_DATE_KEY,6) || '01'
 
    UNION ALL
    --AR ERP_REVENUE_MAPPING WA
    SELECT
    'WA' AS SCHEME,
    8 AS ID,
    LEFT(C.ACCOUNTING_DATE_KEY,6) || '01' AS ACCOUNTING_MONTH_KEY,
    NVL(SUM(C.AMOUNT_DR), 0) - NVL(SUM(C.AMOUNT_CR), 0) AS AMOUNT
    FROM {{ ref('ERP_GL_TRANSACTIONS') }} AS C
    WHERE C.JOURNAL_CATEGORY_NAME = 'Purchase Invoices' AND (C.ACCOUNT LIKE '600%' OR C.ACCOUNT LIKE '610%' OR C.ACCOUNT LIKE '74830 - %') AND C.COST_CENTER = '5500 - Marketing' AND C.LEDGER_NAME IN ('Scheme WA Ledger AU')
    GROUP BY LEFT(C.ACCOUNTING_DATE_KEY,6) || '01'
 
    UNION ALL
    --AP ERP_REVENUE_MAPPING SUMMARY TOTAL WA
    SELECT
    'WA' AS SCHEME,
    RM.SORT AS ID,
    F.ACCOUNTING_MONTH_KEY,
    CASE WHEN RM.SORT = 1 THEN SUM(F.AMOUNT_INCLUDING_GST) ELSE SUM(F.AMOUNT_INCLUDING_GST) * 0.005 END AS AMOUNT
    FROM {{ ref('ERP_REVENUE_MAPPING_WA') }} AS F 
    CROSS JOIN {{ source('CES_FINANCE', 'CES_SERVICE_FEE_SUMMARY_DEV') }} AS RM -- MAPPING
    WHERE RM.SORT IN (1,2) AND RM.SCHEME = 'WA' AND F.PAYMENT_PROCESSES_AP_SORT <> 0 AND F.COMMENTS NOT IN ('Auction Amounts Received', 'Amounts Refunded to Customers (All Payment Types)', 'Amounts Refunded to Customers (All Payment Types), CRP Refund')
    GROUP BY 
    RM.SORT,
    F.ACCOUNTING_MONTH_KEY
) F
ON F.ID = RM.SORT
    --MANUAL ENTRY/ADJUSTMENTS BY ESHAN
FULL JOIN (
          SELECT
          RM.CODE AS CODE
          , RM.ITEM AS ITEM
          , RM.SORT AS SORT
          , RM.DRIVER AS DRIVER
          , M.RATE_MARGIN
          , M.RATE_MARGIN_TYPE
          , RM.FORECAST_PN_L_LINE_CODE 
          , RM.COMMENT
          , M.PERIOD
          , REPLACE(M.DRIVER_VALUE, ',', '') AS DRIVER_VALUE
          FROM
          {{ source('CES_FINANCE', 'SERVICE_FEE_MANUAL_INPUT_DEV') }} AS M
          LEFT JOIN {{ source('CES_FINANCE', 'CES_SERVICE_FEE_SUMMARY_DEV') }} AS RM
          ON M.SORT = RM.SORT
          WHERE M.SCHEME = 'WA' AND RM.SCHEME = 'WA') MA
ON MA.SORT = RM.SORT AND (MA.PERIOD = F.ACCOUNTING_MONTH_KEY OR F.ACCOUNTING_MONTH_KEY IS NULL)
LEFT JOIN {{ source('CES_FINANCE', 'ERP_SUMMARY_FORECAST_DEV') }} AS FO -- FORECAST
ON FO.PNL_LINE = COALESCE(RM.FORECAST_PN_L_LINE_CODE,MA.FORECAST_PN_L_LINE_CODE) AND COALESCE(MA.PERIOD,F.ACCOUNTING_MONTH_KEY) = FO.FORECAST_DATE_KEY AND FO.SCHEME = 'WA'
WHERE NVL(RM.AP_LINK_LOGIC,0) NOT IN ('6','8') AND RM.SCHEME = 'WA' --AND COALESCE(FO.FORECAST_DATE_KEY,F.ACCOUNTING_MONTH_KEY,MA.PERIOD) = '20221201'
