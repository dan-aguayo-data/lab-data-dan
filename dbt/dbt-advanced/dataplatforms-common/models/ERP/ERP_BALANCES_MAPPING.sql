SELECT DISTINCT 
A.ACCOUNT_L31_CODE,
A.ACCOUNT_L31_DESC,
CASE WHEN A.ACCOUNT_L31_CODE >= 40000 THEN 'Calculated Current Year Profit' ELSE A.ACCOUNT_L31_CODE || '-' ||  REPLACE(A.ACCOUNT_L31_DESC,'Sub-Total','') END AS TITLE,
CASE WHEN A.ACCOUNT_L31_CODE >= 40000 THEN 'Net Profit' ELSE A.ACCOUNT_L31_CODE || '-' ||  REPLACE(A.ACCOUNT_L31_DESC,'Sub-Total','') END AS PNL_TITLE
FROM {{ source('CES_ERP', 'GL_ACCOUNT') }} AS A
UNION ALL
SELECT DISTINCT 
A.ACCOUNT_L31_CODE,
A.ACCOUNT_L31_DESC,
'Net Equity' AS TITLE,
CASE WHEN A.ACCOUNT_L31_CODE >= 40000 THEN NULL ELSE A.ACCOUNT_L31_CODE || '-' ||  REPLACE(A.ACCOUNT_L31_DESC,'Sub-Total','') END AS PNL_TITLE
FROM {{ source('CES_ERP', 'GL_ACCOUNT') }} AS A
WHERE A.ACCOUNT_L31_CODE >= 30000