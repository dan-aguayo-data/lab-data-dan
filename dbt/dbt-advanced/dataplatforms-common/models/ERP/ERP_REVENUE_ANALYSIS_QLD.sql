SELECT
-1 AS MULTI_SCHEME_ID
, 'CES' AS SCHEME
, M.ID AS ID
, M.CATEGORY AS SORT_CATEGORY
, M.GROUP_BY AS GROUP_BY
, M.SORT_BY AS SORT_BY
, M.REVENUE_ANALYSIS_CLASSIFICATION AS REVENUE_ANALYSIS_CLASSIFICATION
, COALESCE(S.TOTAL_FEE,R.AMOUNT) AS AMOUNT
, F.AMOUNT AS FORECAST_VALUE
, M.UNIT_PRICING AS UNIT_PRICING
, M.FORECAST_REVENUE_PERCENT AS FORECAST_REVENUE_PERCENT
, M.ACTUAL_REVENUE_PERCENT AS ACTUAL_REVENUE_PERCENT
, COALESCE(S.PERIOD_KEY,R.ACCOUNTING_MONTH_KEY,F.FORECAST_DATE_KEY) AS ACCOUNTING_MONTH_KEY
, (CASE WHEN M.REVENUE_ANALYSIS_CLASSIFICATION = 'Processing Refunds (MRF)' THEN 1.1 WHEN M.REVENUE_ANALYSIS_CLASSIFICATION IN ('Administration Fees (PRO QLD BU)', 'Scheme Float- Administration Fees (PRO)') THEN -1 WHEN M.REVENUE_ANALYSIS_CLASSIFICATION = 'Recycling Payment to PRO' THEN 0.8 WHEN M.REVENUE_ANALYSIS_CLASSIFICATION = 'Processor and Recycler Auction Payments' THEN 0.2 ELSE 1 END) * COALESCE(S.TOTAL_FEE,R.AMOUNT) AS ACTUAL
, ACTUAL/(CASE WHEN M.REVENUE_ANALYSIS_CLASSIFICATION IN ('Processor and Recycler Auction Payments','Processing Payment','Logistics Fees','Administration Fees (PRO QLD BU)', 'Scheme Float- Administration Fees (PRO)','Other Direct Expenses','BAS payments','Recycling Payment to PRO') THEN 1 ELSE 1.1 END) AS ACTUAL_EXC_GST
, CASE WHEN M.REVENUE_ANALYSIS_CLASSIFICATION IN ('Administration Fees (PRO QLD BU)', 'Scheme Float- Administration Fees (PRO)', 'BAS payments','Branding Fee - Public Website','Data Platform - Fixed Fee','Data Platform - Licensing Fee') THEN F.AMOUNT WHEN M.REVENUE_ANALYSIS_CLASSIFICATION IN ('Branding Fee - Project Fee','Data Platform - Project Fee') THEN F.AMOUNT/0.9 ELSE F.AMOUNT*1.1 END AS GST_INC_FORECAST
, M.UNIT_PRICING * GST_INC_FORECAST AS FORECAST_UNIT
, M.UNIT_PRICING * ACTUAL AS ACTUAL_UNIT
, SYSDATE() AS INSERT_DATE_UTC
FROM 
{{ source('CES_FINANCE', 'ERP_REVENUE_VARIANCE_ANALYSIS_DEV') }} AS M
LEFT JOIN {{ ref('ERP_REVENUE_MAPPING_QLD') }} AS R
ON R.REVENUE_ANALYSIS_CLASSIFICATION = M.REVENUE_ANALYSIS_CLASSIFICATION AND M.SOURCE = 'AP'
LEFT JOIN {{ ref('ERP_SERVICE_FEE_SUMMARY_QLD') }} AS S
ON S.DRIVER = M.CES_SUMMARY_MAPPING AND M.SOURCE = 'SUMMARY'
FULL JOIN {{ source('CES_FINANCE', 'ERP_REVENUE_ANALYSIS_FORECAST_DEV') }} AS F
ON F.FORECAST_DATE_KEY= COALESCE(S.PERIOD_KEY,R.ACCOUNTING_MONTH_KEY) AND F.SCHEME = 'QLD'
AND F.ID = M.ID
WHERE M.SCHEME = 'QLD'