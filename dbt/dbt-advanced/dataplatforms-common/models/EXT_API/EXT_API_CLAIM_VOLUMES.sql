SELECT
 TYPE
,ROUND(SUM(CVD.CLAIM_VOLUME_ADJUST)) AS STD_VOLUME
,MAX(CVD.PERIOD) AS LATEST_PERIOD
,MAX(CVD.TRANSACTION_DATE) AS LATEST_TRANSACTION_DATE
FROM 
{{ source('COEX_ACTUALS', 'MV_CLAIM_VOLUMES_DAILY') }} AS CVD
--COEX_DEV.ACTUALS.MV_CLAIM_VOLUMES_DAILY AS CVD
WHERE CVD.MATERIAL_TYPE_ID <> 'INELIGIBLE'
AND CVD.TYPE IN ('CRP','MRF')
GROUP BY 1