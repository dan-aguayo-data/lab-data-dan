SELECT
C.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, C.SCHEME AS SCHEME
, C.CONSUMER_ID AS CONSUMER_ID
, C.CONSUMER_NAME AS CONSUMER_NAME
, C.EMAIL AS EMAIL
, C.MOBILE AS MOBILE
, C.PHONE_NUMBER AS PHONE_NUMBER
, C.ADDRESS_LINE_1 AS ADDRESS_LINE_1
, C.ADDRESS_LINE_2 AS ADDRESS_LINE_2
, C.SUBURB AS SUBURB
, C.STATE AS STATE
, C.POSTCODE AS POSTCODE
, C.STATUS AS CONSUMER_STATUS
, C.CONSUMER_TYPE AS CONSUMER_TYPE
, P.PAYMENT_METHOD AS PAYMENT_METHOD
, B.BANK_ACCOUNT_NUMBER AS BANK_ACCOUNT_NUMBER
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ ref('CONSUMER') }} AS C
LEFT JOIN {{ source('CES_MSCM', 'PYMT_PAY_PARTY_PROFILES') }} AS P
ON C.CONSUMER_ID = P.SCHEME_PARTICIPANT_ID
AND SYSDATE() BETWEEN NVL(P.START_DATE_ACTIVE, TO_DATE('01/JAN/1900', 'DD/MON/YYYY')) AND NVL(P.END_DATE_ACTIVE, TO_DATE('01/JAN/9999', 'DD/MON/YYYY'))
LEFT JOIN {{ source('CES_SECURE', 'BANK_ACCOUNTS_MASK') }} AS B
ON P.BANK_ACCOUNT_ID = B.BANK_ACCOUNT_ID
WHERE CONSUMER_ID <> '-'