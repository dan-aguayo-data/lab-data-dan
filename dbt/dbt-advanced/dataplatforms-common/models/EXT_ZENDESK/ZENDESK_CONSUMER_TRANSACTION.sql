SELECT
C.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, C.SCHEME AS SCHEME
, H.TRANSACTION_ID AS POS_TXN_NUM
, C.CONSUMER_ID AS CONSUMER_ID
, C.CONSUMER_NAME AS CONSUMER_NAME
, C.EMAIL AS EMAIL
, C.MOBILE AS MOBILE
, C.PHONE_NUMBER AS PHONE_NUMBER
, C.STATUS AS CONSUMER_STATUS
, C.CONSUMER_TYPE AS CONSUMER_TYPE
, H.PAYMENT_METHOD AS PAYMENT_METHOD
, H.TRANSACTION_DATE AS TRANSACTION_DATE
, H.STATUS AS TRANSACTION_STATUS
, H.GROSS_AMOUNT AS GROSS_AMOUNT
, PP.ACTION AS ACTION
, NVL(PP.PAY_REF_NUMBER, R.PAY_REF_NUMBER) AS PAY_REF_NUMBER
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ ref('CONSUMER') }} AS C
INNER JOIN {{ ref('CRP_COLLECTION_HDR') }} AS H
ON C.CONSUMER_ID = H.CONSUMER_ID
LEFT JOIN (
    SELECT
    P.POS_TXN_NUM
    , P.ACTION
    , P.PAY_REF_NUMBER
    FROM {{ ref('CONSUMER_PAYMENTS_PENDING') }} AS P
    QUALIFY ROW_NUMBER() OVER (PARTITION BY P.POS_TXN_NUM ORDER BY P.BANK_DETAILS_UPDATED_ON DESC) = 1
) PP
ON H.TRANSACTION_ID = PP.POS_TXN_NUM
LEFT JOIN (
    SELECT DISTINCT
    RTP.POS_TXN_NUM
    , RTP.PAY_REF_NUMBER
    FROM {{ ref('FIN_RTP') }} AS RTP
    WHERE RTP.PAYMENT_STATUS_VOID = 'Paid'
    AND RTP.PYMT_AMOUNT_RECENT_FLAG = 1
) R
ON H.TRANSACTION_ID = R.POS_TXN_NUM
WHERE C.CONSUMER_ID <> '-'