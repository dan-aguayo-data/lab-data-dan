SELECT
CW.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, CW.CUSTOMER_ID AS CUSTOMER_ID
, CW.CUSTOMER_NUMBER AS CUSTOMER_NUMBER
, CW.MARK_AS_DELETED AS MARK_AS_DELETED
, CW.MODIFIED_BY AS MODIFIED_BY
, CW.KAFKA_DATETIME AS INSERT_DATE
FROM
{{ source('CES_MSCM_KAFKA', 'CONSUMER_WATCHLIST') }} AS CW
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME 
ON CW.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID