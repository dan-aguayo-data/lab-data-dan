SELECT
M.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, M.MANIFEST_ID AS MANIFEST_ID
, M.MANIFEST_WEIGHT_KG AS MANIFEST_WEIGHT_KG
, M.LOT_ID AS LOT_ID
, M.EMPTY_TRUCK_WEIGHT_KG AS EMPTY_TRUCK_WEIGHT_KG
, M.EMPTY_CONTAINER_WEIGHT_KG AS EMPTY_CONTAINER_WEIGHT_KG
, M.TOTAL_TRUCK_WEIGHT AS TOTAL_TRUCK_WEIGHT
, M.MANIFEST_DATE AS MANIFEST_DATE
, TO_CHAR(M.MANIFEST_DATE,'YYYYMMDD') AS MANIFEST_DATE_KEY
, M.SELLER_ID AS SELLER_ID
, M.SELLER_NAME AS SELLER_NAME
, M.BUYER_ID AS BUYER_ID
, M.BUYER_NAME AS BUYER_NAME
, M.MATERIAL_TYPE AS MATERIAL_TYPE_ID
, NVL(MT.NAME,MR.NAME) AS MATERIAL_TYPE
, M.PICKUP_LOCATION AS PICKUP_LOCATION
, M.MANIFEST_WEIGHT_KG/1000 AS MANIFEST_WEIGHT_TONNES
, M.ACTUAL_BLOCKS AS ACTUAL_BLOCKS
, M.STATUS AS STATUS
, M.SALE_PRICE_PER_TONNE AS SALE_PRICE_PER_TONNE
, M.RESERVE_PRICE_PER_TONNE AS RESERVE_PRICE_PER_TONNE
, M.FINAL_MANIFEST AS FINAL_MANIFEST
, M.SALE_PRICE_PER_TONNE*M.MANIFEST_WEIGHT_TONNES AS ESTIMATED_VALUE
, M.DESTINATION_COUNTRY AS DESTINATION_COUNTRY
, M.EXPORT AS EXPORT
, M.SALE_MODE AS SALE_MODE
, M.AGREEMENT_DATE AS AGREEMENT_DATE
, M.FLAG AS FLAG
, M.COMMENT AS COMMENT
, ROUND(E.LME_USD , 2) AS LME_USD
, ROUND(E.AVG_FX, 7) AS AVG_FX
, E.LME_USD/E.AVG_FX AS LME_AUD
, M.CARRIER AS CARRIER
, M.CONSIGNMENT_NO AS CONSIGNMENT_NO
, M.REGISTRATION_NO AS REGISTRATION_NO
, M.TRANSPORT_UNIT_TYPE AS TRANSPORT_UNIT_TYPE
, M.TRANSPORT_UNIT_COUNT AS TRANSPORT_UNIT_COUNT
, M.DELIVERY_ID AS DELIVERY_ID
, M.FINAL_ADDRESS AS FINAL_ADDRESS
, M.FINAL_SUBURB AS FINAL_SUBURB
, M.FINAL_STATE AS FINAL_STATE
, M.FINAL_COUNTRY AS FINAL_COUNTRY
, M.FINAL_POST_CODE AS FINAL_POST_CODE
, M.FINAL_PHONE_NUMBER AS FINAL_PHONE_NUMBER
, M.DELIVERY_ADDRESS AS DELIVERY_ADDRESS
, M.DELIVERY_SUBURB AS DELIVERY_SUBURB
, M.DELIVERY_STATE AS DELIVERY_STATE
, M.DELIVERY_COUNTRY AS DELIVERY_COUNTRY
, M.DELIVERY_POST_CODE AS DELIVERY_POST_CODE
, M.DELIVERY_PHONE_NUMBER AS DELIVERY_PHONE_NUMBER
, M.MANIFEST_DATE_UTC AS MANIFEST_DATE_UTC
, M.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, M.LAST_MODIFIED_ON_UTC AS LAST_MODIFIED_ON_UTC
, M.DELIVERY_CREATED_BY AS DELIVERY_CREATED_BY
, M.DELIVERY_CREATED_ON_UTC AS DELIVERY_CREATED_ON_UTC
, M.DELIVERY_LAST_MODIFIED_BY AS DELIVERY_LAST_MODIFIED_BY
, M.DELIVERY_LAST_MODIFIED_ON_UTC AS DELIVERY_LAST_MODIFIED_ON_UTC
, M.MODIFIED_ON_LAST_1_DAY_EXTRACT AS MODIFIED_ON_LAST_1_DAY_EXTRACT
, M.MODIFIED_ON_LAST_1_DAY AS MODIFIED_ON_LAST_1_DAY
, M.DELIVERY_LAST_MODIFIED_ON AS DELIVERY_LAST_MODIFIED_ON
, SYSDATE() AS INSERT_DATE_UTC
FROM (
    SELECT
    NVL(LG.MULTI_SCHEME_ID, 10000) AS MULTI_SCHEME_ID
    , LG.DOCKET_NO AS MANIFEST_ID
    , LG.NET_WEIGHT*1000 AS MANIFEST_WEIGHT_KG
    , '-' AS LOT_ID
    , LG.TARE_WEIGHT*1000 AS EMPTY_TRUCK_WEIGHT_KG
    , NULL AS EMPTY_CONTAINER_WEIGHT_KG
    , LG.GROSS_WEIGHT*1000 AS TOTAL_TRUCK_WEIGHT
    , LG.DELIVERY_DATE AS MANIFEST_DATE
    , LG.PROCESSSOR_ID AS SELLER_ID
    , PS_S.SITE_NAME AS SELLER_NAME
    , LG.BUYER_ID AS BUYER_ID
    , PS_B.SITE_NAME AS BUYER_NAME
    , NVL(LG.MATERIAL_TYPE_ID,'GLASSMIXED') AS MATERIAL_TYPE
    , NULL AS PICKUP_LOCATION
    , LG.NET_WEIGHT * 1 AS MANIFEST_WEIGHT_TONNES
    , NULL AS ACTUAL_BLOCKS
    , NULL AS STATUS
    , TO_NUMBER(CASE WHEN LG.NET_WEIGHT=0 THEN LG.EX_GST ELSE LG.EX_GST/LG.NET_WEIGHT END) AS SALE_PRICE_PER_TONNE
    , NULL AS RESERVE_PRICE_PER_TONNE
    , NULL AS FINAL_MANIFEST
    , NVL(LG.DESTINATION,'AUSTRALIA') AS DESTINATION_COUNTRY
    , CASE WHEN NVL(LG.EXPORT,'N') = 'N' THEN 'No' ELSE 'Yes' END AS EXPORT
    , NULL AS SALE_MODE
    , NULL AS AGREEMENT_DATE
    , 'COEX Glass Data' AS FLAG
    , NULL AS COMMENT
    , NULL AS CARRIER
    , NULL AS CONSIGNMENT_NO
    , NULL AS REGISTRATION_NO
    , NULL AS TRANSPORT_UNIT_TYPE
    , NULL AS TRANSPORT_UNIT_COUNT
    , NULL AS DELIVERY_ID
    , NULL AS FINAL_ADDRESS
    , NULL AS FINAL_SUBURB
    , NULL AS FINAL_STATE
    , NULL AS FINAL_COUNTRY
    , NULL AS FINAL_POST_CODE
    , NULL AS FINAL_PHONE_NUMBER
    , NULL AS DELIVERY_ADDRESS
    , NULL AS DELIVERY_SUBURB
    , NULL AS DELIVERY_STATE
    , NULL AS DELIVERY_COUNTRY
    , NULL AS DELIVERY_POST_CODE
    , NULL AS DELIVERY_PHONE_NUMBER
    , NULL AS MANIFEST_DATE_UTC
    , NULL AS LAST_MODIFIED_BY
    , NULL AS LAST_MODIFIED_ON_UTC
    , NULL AS DELIVERY_CREATED_BY
    , NULL AS DELIVERY_CREATED_ON_UTC
    , NULL AS DELIVERY_LAST_MODIFIED_BY
    , NULL AS DELIVERY_LAST_MODIFIED_ON_UTC
    , NULL AS MODIFIED_ON_LAST_1_DAY_EXTRACT
    , NULL AS MODIFIED_ON_LAST_1_DAY
    , NULL AS DELIVERY_LAST_MODIFIED_ON
    FROM 
    {{ source('REF_COEX', 'GLASS_MASTER') }} AS LG
    LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS_S
    ON TRIM(LG.PROCESSSOR_ID) = PS_S.SITE_NUMBER
    LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS_B
    ON TRIM(LG.BUYER_ID) = PS_B.SITE_NUMBER
    UNION ALL
    SELECT
    L.MULTI_SCHEME_ID  AS MULTI_SCHEME_ID 
    , LM.ID AS MANIFEST_ID
    , LM.ACTUAL_WEIGHT_KGS AS MANIFEST_WEIGHT_KG
    , L.ID AS LOT_ID
    , LM.EMPTY_TRUCK_WEIGHT AS EMPTY_TRUCK_WEIGHT_KG
    , LM.EMPTY_CONTAINER_WEIGHT AS EMPTY_CONTAINER_WEIGHT_KG
    , LM.TOTAL_TRUCK_WEIGHT AS TOTAL_TRUCK_WEIGHT
    , CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(LM.MANIFEST_DATE AS TIMESTAMP))  AS MANIFEST_DATE
    , L.SELLER_ID
    , PS_S.SITE_NAME AS SELLER_NAME
    , L.BUYER_ID
    , PS_B.SITE_NAME AS BUYER_NAME
    , NVL(L.SCHEME_MATERIAL_TYPE_ID, L.MRF_MATERIAL_TYPE_ID) AS MATERIAL_TYPE
    , L.PICKUP_LOCATION
    , LM.ACTUAL_WEIGHT_KGS / 1000 AS MANIFEST_WEIGHT_TONNES
    , LM.ACTUAL_BLOCKS AS ACTUAL_BLOCKS
    , L.STATUS
    , L.SALE_PRICE_PER_TONNE
    , COALESCE(L.RESERVE_PRICE_PER_TONNE, R.RESERVE_PRICE_PER_TONNE, RR.RESERVE_PRICE_PER_TONNE) AS RESERVE_PRICE_PER_TONNE
    , CASE WHEN LM.FINAL_MANIFEST = 1 THEN 'Yes' else 'No' end AS FINAL_MANIFEST
    , D.FINAL_COUNTRY AS DESTINATION_COUNTRY
    , CASE WHEN D.FINAL_STATE = 'EXP' THEN 'Yes' ELSE 'No' END AS EXPORT
    , CASE WHEN L.DIRECT_SALE_MODE = 1 THEN 'DIRECT_SALE' WHEN  L.STATUS IN ('AWAITING_COLLECTION','SOLD_AND_COLLECTED','AWAITING_DESTINATION_CONFIRMATION') THEN 'AUCTION' ELSE 'NOT_SOLD' END AS SALE_MODE
    , CASE WHEN L.DIRECT_SALE_MODE = 1 THEN CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, CAST(L.AGREEMENT_DATE AS TIMESTAMP)) ELSE EL.EVENT_END_DATE END AS AGREEMENT_DATE
    , CASE WHEN LM.NOTE IS NOT NULL THEN 'Yes' ELSE 'No' END AS FLAG
    , LM.NOTE AS COMMENT
    , LM.CARRIER AS CARRIER
    , LM.CONSIGNMENT_NO AS CONSIGNMENT_NO
    , LM.REGISTRATION_NO AS REGISTRATION_NO
    , LM.TRANSPORT_UNIT_TYPE AS TRANSPORT_UNIT_TYPE
    , LM.TRANSPORT_UNIT_COUNT AS TRANSPORT_UNIT_COUNT
    , D.ID AS DELIVERY_ID
    , D.FINAL_ADDRESS AS FINAL_ADDRESS
    , D.FINAL_SUBURB AS FINAL_SUBURB
    , D.FINAL_STATE AS FINAL_STATE
    , D.FINAL_COUNTRY AS FINAL_COUNTRY
    , D.FINAL_POST_CODE AS FINAL_POST_CODE
    , D.FINAL_PHONE_NUMBER AS FINAL_PHONE_NUMBER
    , D.DELIVERY_ADDRESS AS DELIVERY_ADDRESS
    , D.DELIVERY_SUBURB AS DELIVERY_SUBURB
    , D.DELIVERY_STATE AS DELIVERY_STATE
    , D.DELIVERY_COUNTRY AS DELIVERY_COUNTRY
    , D.DELIVERY_POST_CODE AS DELIVERY_POST_CODE
    , D.DELIVERY_PHONE_NUMBER AS DELIVERY_PHONE_NUMBER
    , LM.MANIFEST_DATE AS MANIFEST_DATE_UTC
    , LM.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
    , LM.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
    , D.CREATED_BY AS DELIVERY_CREATED_BY
    , D.CREATED_ON AS DELIVERY_CREATED_ON_UTC
    , D.LAST_MODIFIED_BY AS DELIVERY_LAST_MODIFIED_BY
    , D.LAST_MODIFIED_ON AS DELIVERY_LAST_MODIFIED_ON_UTC
    , CASE WHEN DATEADD(DAY,1,D.LAST_MODIFIED_ON) >= SYSDATE()  THEN 'Y' ELSE 'N' END AS MODIFIED_ON_LAST_1_DAY_EXTRACT
    , CASE WHEN DATEADD(DAY,1,D.LAST_MODIFIED_ON) >= SYSDATE() AND hour(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,sysdate())) >= 12 THEN 'Y' ELSE 'N' END AS MODIFIED_ON_LAST_1_DAY
    , CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(D.LAST_MODIFIED_ON AS TIMESTAMP))  AS DELIVERY_LAST_MODIFIED_ON
    FROM {{ source('CES_MSCM', 'LOT_ITEM_MANIFEST') }} AS LM
    FULL JOIN {{ source('CES_MSCM', 'LOT_ITEM_DELIVERY') }} AS D
    ON LM.LOT_ITEM_ID = D.LOT_ITEM_ID
    LEFT JOIN {{ source('CES_MSCM', 'LOT_ITEM') }} AS L
    ON NVL(LM.LOT_ITEM_ID, D.LOT_ITEM_ID) = L.ID
    LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS_S
    ON L.SELLER_ID = PS_S.SITE_NUMBER
    LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS_B
    ON L.BUYER_ID = PS_B.SITE_NUMBER
    LEFT JOIN {{ source('CES_MSCM', 'RESERVE_PRICE_REFERENCE') }} AS R
    ON L.SELLER_ID = R.SCHEME_PARTICIPANT_ID
    AND COALESCE(L.SCHEME_MATERIAL_TYPE_ID,L.MRF_MATERIAL_TYPE_ID) = COALESCE(R.MRF_MATERIAL_TYPE_ID,R.SCHEME_MATERIAL_TYPE_ID)
    AND (CASE WHEN L.STATUS IN ('PENDING_REVIEW','READY_FOR_SALE') THEN SYSDATE() ELSE L.AGREEMENT_DATE END) BETWEEN CAST(R.EFFECTIVE_FROM AS DATE) AND coalesce(CAST(R.EFFECTIVE_TO AS DATE),(CASE WHEN L.STATUS IN ('PENDING_REVIEW','READY_FOR_SALE') THEN SYSDATE() ELSE L.AGREEMENT_DATE END))
    LEFT JOIN {{ source('CES_MSCM', 'RESERVE_PRICE_REFERENCE') }} AS RR
    ON COALESCE(L.SCHEME_MATERIAL_TYPE_ID,L.MRF_MATERIAL_TYPE_ID) = COALESCE(RR.MRF_MATERIAL_TYPE_ID,RR.SCHEME_MATERIAL_TYPE_ID)
    AND (CASE WHEN L.STATUS IN ('PENDING_REVIEW','READY_FOR_SALE') THEN SYSDATE() ELSE L.AGREEMENT_DATE END) BETWEEN CAST(RR.EFFECTIVE_FROM AS DATE) AND coalesce(CAST(RR.EFFECTIVE_TO AS DATE),(CASE WHEN L.STATUS IN ('PENDING_REVIEW','READY_FOR_SALE') THEN SYSDATE() ELSE L.AGREEMENT_DATE END))
    AND RR.SCHEME_PARTICIPANT_ID IS NULL
    LEFT JOIN (
        SELECT 
        AEL.LOT_ITEM_ID,
        MAX(AEL.END_DATE) AS EVENT_END_DATE,
        MAX(AEL.COLLECTION_END_DATE) AS COLLECTION_END_DATE
        FROM {{ ref('AUCTION_EVENT_LOT') }} AS AEL
        GROUP BY
        AEL.LOT_ITEM_ID
    ) EL
    ON L.ID = EL.LOT_ITEM_ID
    INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
    ON L.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
) M
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON M.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_AUCTION', 'EXCHANGE_RATE') }} AS E
ON TO_CHAR(TO_DATE(E.DATE,'DD/MM/YYYY'),'YYYYMM') = TO_CHAR(M.MANIFEST_DATE,'YYYYMM')
LEFT JOIN {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS MT
ON M.MATERIAL_TYPE = MT.ID 
LEFT JOIN {{ source('CES_MSCM', 'MRF_MATERIAL_TYPE') }} AS MR
ON M.MATERIAL_TYPE = MR.ID 
{% if target.name.upper() != 'UAT' %}
WHERE LOWER(M.SELLER_NAME) NOT LIKE '%pvt%' AND LOWER(M.SELLER_NAME) NOT LIKE '%test%'
AND LOWER(M.BUYER_NAME) NOT LIKE '%pvt%' AND LOWER(M.BUYER_NAME) NOT LIKE '%test%'
{% endif %}