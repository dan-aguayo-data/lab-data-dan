SELECT
L.MULTI_SCHEME_ID  AS MULTI_SCHEME_ID 
, SCHEME.NAME AS SCHEME
, L.ID AS LOT_ITEM_ID
, AR.VALUE AS SELLER_TYPE
, L.SELLER_ID AS SELLER_SITE_NUMBER
, PS.SITE_NAME AS SELLER_NAME
, BSS.ABN AS SELLER_ABN
, L.BUYER_ID AS BUYER_SITE_NUMBER
, PSS.SITE_NAME AS BUYER_NAME
, COALESCE(L.SCHEME_MATERIAL_TYPE_ID,L.MRF_MATERIAL_TYPE_ID) AS MATERIAL_TYPE_ID
, COALESCE(M.NAME,MM.NAME) AS MATERIAL_TYPE
, L.PICKUP_LOCATION AS PICKUP_LOCATION
, L.PICKUP_POST_CODE AS PICKUP_POST_CODE
, L.WEIGHT_IN_TONNES AS WEIGHT_IN_TONNES
, L.BLOCK_LENGTH_IN_CM AS BLOCK_LENGTH_IN_CM
, L.BLOCK_WIDTH_IN_CM AS BLOCK_WIDTH_IN_CM
, L.BLOCK_DEPTH_IN_CM AS BLOCK_DEPTH_IN_CM
, (L.BLOCK_LENGTH_IN_CM*L.BLOCK_WIDTH_IN_CM*L.BLOCK_DEPTH_IN_CM)/1000000 AS BLOCK_VOLUME_M3
, CASE WHEN L.STATUS IN ('AWAITING_COLLECTION','SOLD_AND_COLLECTED','AWAITING_DESTINATION_CONFIRMATION') THEN L.SALE_PRICE_PER_TONNE*L.WEIGHT_IN_TONNES ELSE 0 END AS ESTIMATED_VALUE
, L.NUMBER_OF_BLOCKS AS NUMBER_OF_BLOCKS
, L.SOURCE AS SOURCE
, CASE WHEN L.DIRECT_SALE_MODE=1 THEN 'DIRECT_SALE' WHEN  L.STATUS IN ('AWAITING_COLLECTION','SOLD_AND_COLLECTED','AWAITING_DESTINATION_CONFIRMATION') THEN 'AUCTION' ELSE 'NOT_SOLD' END AS EVENT_SOLD
, L.STATUS AS LOT_STATUS
, COALESCE(L.RESERVE_PRICE_PER_TONNE,NVL(R.RESERVE_PRICE_PER_TONNE,RR.RESERVE_PRICE_PER_TONNE)) AS RESERVE_PRICE_PER_TONNE
, L.SALE_PRICE_PER_TONNE AS SALE_PRICE_PER_TONNE
, L.COMMENTS AS COMMENTS
, L.COLLECTION_CONSIDERATIONS AS COLLECTION_CONSIDERATIONS
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(L.AGREEMENT_DATE AS TIMESTAMP))  AS AGREEMENT_DATE
, TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(L.AGREEMENT_DATE AS TIMESTAMP)),'YYYYMMDD')  AS AGREEMENT_DATE_KEY
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(L.AVAILABLE_FROM AS TIMESTAMP))  AS AVAILABLE_FROM
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(L.SOLD_ON AS TIMESTAMP))  AS SOLD_ON
, CASE WHEN L.DIRECT_SALE_MODE=1 THEN CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(L.AGREEMENT_DATE AS TIMESTAMP))  ELSE EL.EVENT_END_DATE END AS EVENT_END_AGREEMENT_DATE
, L.SALE_TERMS AS SALE_TERMS
, CASE WHEN L.RESERVE_PRICE_PER_TONNE = 0 THEN NULL ELSE (L.SALE_PRICE_PER_TONNE-L.RESERVE_PRICE_PER_TONNE)/L.RESERVE_PRICE_PER_TONNE END AS ABOVE_RESERVE_PERCENT
, CASE WHEN EL.COLLECTION_END_DATE IS NULL THEN NULL ELSE DATEDIFF(DAY, TRUNCATE(SYSDATE(),'DAY'), EL.COLLECTION_END_DATE) END AS DAYS_UNTIL_COLLECTION_PERIOD_ENDS
, LF.LAST_4_WEEKS_AVG_RESERVE_PRICE AS LAST_4_WEEKS_AVG_RESERVE_PRICE
, LF.LAST_4_WEEKS_AVG_SALE_PRICE AS LAST_4_WEEKS_AVG_SALE_PRICE
, LSS.EVENT_SOLD AS LAST_SALE_MODE
, LSS.LOT_ITEM_ID AS LAST_SOLD_LOT_ID
, LSS.RESERVE_PRICE_PER_TONNE AS LAST_SOLD_RESERVE_PRICE
, LSS.AGREEMENT_DATE AS LAST_SOLD_DATE
, LSS.SALE_PRICE_PER_TONNE AS LAST_SOLD_SALE_PRICE
, TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(L.AGREEMENT_DATE AS TIMESTAMP)),'YYYY-MM')  AS AGREEMENT_MONTH
, RD.WEEK_END AS AGREEMENT_DATE_WEEK_END
, L.BUYER_USER_ID AS BUYER_USER_ID
, L.AGREEMENT_DATE AS AGREEMENT_DATE_UTC
, L.CREATED_BY AS CREATED_BY
, L.CREATED_ON AS CREATED_ON_UTC
, L.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, L.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM 
{{ source('CES_MSCM', 'LOT_ITEM') }} AS L
LEFT JOIN {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS M
ON L.SCHEME_MATERIAL_TYPE_ID = M.ID 
LEFT JOIN {{ source('CES_MSCM', 'MRF_MATERIAL_TYPE') }} AS MM
ON L.MRF_MATERIAL_TYPE_ID = MM.ID 
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON L.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS
ON PS.SITE_NUMBER=L.SELLER_ID
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PSS
ON PSS.SITE_NUMBER=L.BUYER_ID
LEFT JOIN {{ source('CES_MSCM', 'SCHEME_REF_CODES') }} AS AR
ON PS.SITE_TYPE_ID = AR.SCHEME_REF_CODES_ID
LEFT JOIN {{ source('CES_MSCM', 'RESERVE_PRICE_REFERENCE') }} AS R
ON L.SELLER_ID = R.SCHEME_PARTICIPANT_ID
AND COALESCE(L.SCHEME_MATERIAL_TYPE_ID,L.MRF_MATERIAL_TYPE_ID) = COALESCE(R.MRF_MATERIAL_TYPE_ID,R.SCHEME_MATERIAL_TYPE_ID)
AND (CASE WHEN L.STATUS IN ('PENDING_REVIEW','READY_FOR_SALE') THEN SYSDATE() ELSE L.AGREEMENT_DATE END) BETWEEN CAST(R.EFFECTIVE_FROM AS DATE) AND coalesce(CAST(R.EFFECTIVE_TO AS DATE),(CASE WHEN L.STATUS IN ('PENDING_REVIEW','READY_FOR_SALE') THEN SYSDATE() ELSE L.AGREEMENT_DATE END))
LEFT JOIN {{ source('CES_MSCM', 'RESERVE_PRICE_REFERENCE') }} AS RR
ON COALESCE(L.SCHEME_MATERIAL_TYPE_ID,L.MRF_MATERIAL_TYPE_ID) = COALESCE(RR.MRF_MATERIAL_TYPE_ID,RR.SCHEME_MATERIAL_TYPE_ID)
AND (CASE WHEN L.STATUS IN ('PENDING_REVIEW','READY_FOR_SALE') THEN SYSDATE() ELSE L.AGREEMENT_DATE END) BETWEEN CAST(RR.EFFECTIVE_FROM AS DATE) AND coalesce(CAST(RR.EFFECTIVE_TO AS DATE),(CASE WHEN L.STATUS IN ('PENDING_REVIEW','READY_FOR_SALE') THEN SYSDATE() ELSE L.AGREEMENT_DATE END))
AND RR.SCHEME_PARTICIPANT_ID IS NULL
LEFT JOIN (
    SELECT 
    LOT_ITEM_ID,
    MAX(END_DATE) AS EVENT_END_DATE,
    MAX(COLLECTION_END_DATE) AS COLLECTION_END_DATE
    FROM {{ ref('AUCTION_EVENT_LOT') }} AS EL
    GROUP BY
    LOT_ITEM_ID
) EL
ON EL.LOT_ITEM_ID = L.ID
LEFT JOIN (
    SELECT
    COALESCE(LF.SCHEME_MATERIAL_TYPE_ID,LF.MRF_MATERIAL_TYPE_ID) AS MATERIAL_TYPE_ID,
    AVG(COALESCE(LF.RESERVE_PRICE_PER_TONNE,NVL(R.RESERVE_PRICE_PER_TONNE,RR.RESERVE_PRICE_PER_TONNE))) AS LAST_4_WEEKS_AVG_RESERVE_PRICE,    
    AVG(LF.SALE_PRICE_PER_TONNE) AS LAST_4_WEEKS_AVG_SALE_PRICE
    FROM 
    {{ source('CES_MSCM', 'LOT_ITEM') }} AS LF
    LEFT JOIN {{ source('CES_MSCM', 'RESERVE_PRICE_REFERENCE') }} AS R
    ON LF.SELLER_ID = R.SCHEME_PARTICIPANT_ID
    AND COALESCE(LF.SCHEME_MATERIAL_TYPE_ID,LF.MRF_MATERIAL_TYPE_ID) = COALESCE(R.MRF_MATERIAL_TYPE_ID,R.SCHEME_MATERIAL_TYPE_ID)
    AND (CASE WHEN LF.STATUS IN ('PENDING_REVIEW','READY_FOR_SALE') THEN SYSDATE() ELSE LF.AGREEMENT_DATE END) BETWEEN CAST(R.EFFECTIVE_FROM AS DATE) AND coalesce(CAST(R.EFFECTIVE_TO AS DATE),(CASE WHEN LF.STATUS IN ('PENDING_REVIEW','READY_FOR_SALE') THEN SYSDATE() ELSE LF.AGREEMENT_DATE END))    
    LEFT JOIN {{ source('CES_MSCM', 'RESERVE_PRICE_REFERENCE') }} AS RR
    ON COALESCE(LF.SCHEME_MATERIAL_TYPE_ID,LF.MRF_MATERIAL_TYPE_ID) = COALESCE(RR.MRF_MATERIAL_TYPE_ID,RR.SCHEME_MATERIAL_TYPE_ID)
    AND (CASE WHEN LF.STATUS IN ('PENDING_REVIEW','READY_FOR_SALE') THEN SYSDATE() ELSE LF.AGREEMENT_DATE END) BETWEEN CAST(RR.EFFECTIVE_FROM AS DATE) AND coalesce(CAST(RR.EFFECTIVE_TO AS DATE),(CASE WHEN LF.STATUS IN ('PENDING_REVIEW','READY_FOR_SALE') THEN SYSDATE() ELSE LF.AGREEMENT_DATE END))
    AND RR.SCHEME_PARTICIPANT_ID IS NULL  
    WHERE (LF.DIRECT_SALE_MODE=1 OR LF.STATUS IN ('AWAITING_COLLECTION','SOLD_AND_COLLECTED','AWAITING_DESTINATION_CONFIRMATION')) AND LF.AGREEMENT_DATE >= DATEADD(DAY, -28, SYSDATE())
    GROUP BY COALESCE(LF.SCHEME_MATERIAL_TYPE_ID,LF.MRF_MATERIAL_TYPE_ID)
) LF 
ON LF.MATERIAL_TYPE_ID = COALESCE(L.SCHEME_MATERIAL_TYPE_ID,L.MRF_MATERIAL_TYPE_ID)
LEFT JOIN (
    SELECT
    LF.SELLER_ID AS SELLER_SITE_NUMBER,
    COALESCE(LF.SCHEME_MATERIAL_TYPE_ID,LF.MRF_MATERIAL_TYPE_ID) AS MATERIAL_TYPE_ID,
    ROW_NUMBER() OVER (PARTITION BY COALESCE(LF.SCHEME_MATERIAL_TYPE_ID,LF.MRF_MATERIAL_TYPE_ID),LF.SELLER_ID ORDER BY LF.AGREEMENT_DATE DESC) AS ROW_NUMBER,
    CASE WHEN LF.DIRECT_SALE_MODE=1 THEN 'DIRECT_SALE' WHEN  LF.STATUS IN ('AWAITING_COLLECTION','SOLD_AND_COLLECTED','AWAITING_DESTINATION_CONFIRMATION') THEN 'AUCTION' ELSE 'NOT_SOLD' END AS EVENT_SOLD,
    LF.ID AS LOT_ITEM_ID,
    COALESCE(LF.RESERVE_PRICE_PER_TONNE,NVL(R.RESERVE_PRICE_PER_TONNE,RR.RESERVE_PRICE_PER_TONNE)) AS RESERVE_PRICE_PER_TONNE,
    LF.SALE_PRICE_PER_TONNE,
    LF.AGREEMENT_DATE
    FROM 
    {{ source('CES_MSCM', 'LOT_ITEM') }} AS LF
    LEFT JOIN {{ source('CES_MSCM', 'RESERVE_PRICE_REFERENCE') }} AS R
    ON LF.SELLER_ID = R.SCHEME_PARTICIPANT_ID
    AND COALESCE(LF.SCHEME_MATERIAL_TYPE_ID,LF.MRF_MATERIAL_TYPE_ID) = COALESCE(R.MRF_MATERIAL_TYPE_ID,R.SCHEME_MATERIAL_TYPE_ID)
    AND (CASE WHEN LF.STATUS IN ('PENDING_REVIEW','READY_FOR_SALE') THEN SYSDATE() ELSE LF.AGREEMENT_DATE END) BETWEEN CAST(R.EFFECTIVE_FROM AS DATE) AND coalesce(CAST(R.EFFECTIVE_TO AS DATE),(CASE WHEN LF.STATUS IN ('PENDING_REVIEW','READY_FOR_SALE') THEN SYSDATE() ELSE LF.AGREEMENT_DATE END))
    LEFT JOIN {{ source('CES_MSCM', 'RESERVE_PRICE_REFERENCE') }} AS RR
    ON COALESCE(LF.SCHEME_MATERIAL_TYPE_ID,LF.MRF_MATERIAL_TYPE_ID) = COALESCE(RR.MRF_MATERIAL_TYPE_ID,RR.SCHEME_MATERIAL_TYPE_ID)
    AND (CASE WHEN LF.STATUS IN ('PENDING_REVIEW','READY_FOR_SALE') THEN SYSDATE() ELSE LF.AGREEMENT_DATE END) BETWEEN CAST(RR.EFFECTIVE_FROM AS DATE) AND coalesce(CAST(RR.EFFECTIVE_TO AS DATE),(CASE WHEN LF.STATUS IN ('PENDING_REVIEW','READY_FOR_SALE') THEN SYSDATE() ELSE LF.AGREEMENT_DATE END))
    AND RR.SCHEME_PARTICIPANT_ID IS NULL
    WHERE LF.DIRECT_SALE_MODE=1 OR LF.STATUS IN ('AWAITING_COLLECTION','SOLD_AND_COLLECTED','AWAITING_DESTINATION_CONFIRMATION')
) LSS
ON LSS.SELLER_SITE_NUMBER = L.SELLER_ID AND LSS.MATERIAL_TYPE_ID = COALESCE(L.SCHEME_MATERIAL_TYPE_ID,L.MRF_MATERIAL_TYPE_ID) AND LSS.ROW_NUMBER = 1
LEFT JOIN {{ ref('REF_DATE') }} AS RD
ON TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(L.AGREEMENT_DATE AS TIMESTAMP)),'YYYYMMDD')  = RD.KEY
LEFT JOIN (
    SELECT DISTINCT
    LOT_ID
    FROM {{ ref('AUCTION_MANIFEST_CLEANSED') }} AS C
) AMC
ON L.ID = AMC.LOT_ID
LEFT JOIN {{ ref('B2B_SITES') }} AS BS
ON L.SELLER_ID = BS.SITE_NUMBER
LEFT JOIN {{ ref('B2B_SUPPLIERS') }} AS BSS
ON BSS.SUPPLIER_NUMBER = BS.SUPPLIER_NUMBER

UNION ALL
 
SELECT
-1 AS MULTI_SCHEME_ID
, 'CES' AS SCHEME
, '-' AS LOT_ITEM_ID
, 'Processor' AS SELLER_TYPE
, NULL AS SELLER_SITE_NUMBER
, NULL AS SELLER_NAME
, NULL AS SELLER_ABN
, '-' AS BUYER_SITE_NUMBER
, NULL AS BUYER_NAME
, NULL AS MATERIAL_TYPE_ID
, NULL AS MATERIAL_TYPE
, NULL AS PICKUP_LOCATION
, NULL AS PICKUP_POST_CODE
, NULL AS WEIGHT_IN_TONNES
, NULL AS BLOCK_LENGTH_IN_CM
, NULL AS BLOCK_WIDTH_IN_CM
, NULL AS BLOCK_DEPTH_IN_CM
, NULL AS BLOCK_VOLUME_M3
, NULL AS ESTIMATED_VALUE
, NULL AS NUMBER_OF_BLOCKS
, NULL AS SOURCE
, NULL AS EVENT_SOLD
, NULL AS LOT_STATUS
, NULL AS RESERVE_PRICE_PER_TONNE
, NULL AS SALE_PRICE_PER_TONNE
, NULL AS COMMENTS
, NULL AS COLLECTION_CONSIDERATIONS
, NULL AS AGREEMENT_DATE
, NULL AS AGREEMENT_DATE_KEY
, NULL AS AVAILABLE_FROM
, NULL AS SOLD_ON
, NULL AS EVENT_END_AGREEMENT_DATE
, NULL AS SALE_TERMS
, NULL AS ABOVE_RESERVE_PERCENT
, NULL AS DAYS_UNTIL_COLLECTION_PERIOD_ENDS
, NULL AS LAST_4_WEEKS_AVG_RESERVE_PRICE
, NULL AS LAST_4_WEEKS_AVG_SALE_PRICE
, NULL AS LAST_SALE_MODE
, NULL AS LAST_SOLD_LOT_ID
, NULL AS LAST_SOLD_RESERVE_PRICE
, NULL AS LAST_SOLD_DATE
, NULL AS LAST_SOLD_SALE_PRICE
, NULL AS AGREEMENT_MONTH
, NULL AS AGREEMENT_DATE_WEEK_END
, NULL AS BUYER_USER_ID
, NULL AS AGREEMENT_DATE_UTC
, NULL AS CREATED_BY
, TO_DATE('01/01/2021', 'DD/MM/YYYY') AS CREATED_ON_UTC
, NULL AS LAST_MODIFIED_BY
, TO_DATE('01/01/2021', 'DD/MM/YYYY') AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC