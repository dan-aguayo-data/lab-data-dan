SELECT
R.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, R.ID AS ID
, R.KAFKA_ID || '-' || R.EMAIL AS CONTACT_ID
, R.KAFKA_ID AS KAFKA_ID
, R.KAFKA_DATETIME AS KAFKA_DATETIME
, R.REGISTRATION_ID AS REGISTRATION_ID
, R.EMAIL AS EMAIL
, R.ROLE_NAME AS ROLE_NAME
, REG.RECENT_FLAG AS RECENT_FLAG
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM_KAFKA', 'PARTICIPANT_REGISTRATION_CONTACTS_ROLE') }} AS R
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON R.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
INNER JOIN (
    SELECT
    PR.KAFKA_ID
    , CASE WHEN ROW_NUMBER() OVER (PARTITION BY PR.REGISTRATION_ID ORDER BY PR.KAFKA_DATETIME DESC, PR.TYPE_ORDER DESC) = 1 THEN 1 ELSE 0 END AS RECENT_FLAG
    FROM {{ source('CES_MSCM_KAFKA', 'PARTICIPANT_REGISTRATION') }} AS PR
) REG
ON R.KAFKA_ID = REG.KAFKA_ID