SELECT
PS.MULTI_SCHEME_ID  AS MULTI_SCHEME_ID 
, SCHEME.NAME AS SCHEME
, CR.CONTACT_ROLE_ID  AS CONTACT_ROLE_ID 
, C.CONTACT_ID   AS CONTACT_ID  
, C.FIRST_NAME || ' ' || C.LAST_NAME AS CONTACT_NAME
, R_T.VALUE AS ROLE
, CASE WHEN R_T.VALUE = 'Group Admin' THEN 'CAPTAIN' WHEN R_T.VALUE = 'Group Member' THEN 'TEAMMATE ' ELSE R_T.VALUE END AS GROUP_ROLE
, CASE WHEN CR.ACTIVE = 1 THEN 'Active' ELSE 'Inactive' END AS ROLE_ACTIVE
, C.ACTIVE AS CONTACT_ACTIVE
, CR.ASSIGNMENT_TYPE AS ASSIGNMENT_TYPE
, C.PHONE_NUMBER  AS PHONE_NUMBER 
, C.PHONE_EXT  AS PHONE_EXT 
, C.MOBILE_PHONE_NUMBER AS MOBILE_PHONE_NUMBER
, TRIM(LOWER(C.EMAIL)) AS EMAIL
, PS.SITE_NUMBER  AS CONSUMER_ID
, CC.CONSUMER_ID AS CONSUMER_ID_INDIVIDUAL
, CAST(CR.EFFECTIVE_START_DATE AS DATE) AS EFFECTIVE_FROM
, CAST(CR.EFFECTIVE_END_DATE AS DATE) AS EFFECTIVE_TO
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(CR.CREATED_ON AS TIMESTAMP)) AS CREATED_ON
, TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(CR.CREATED_ON AS TIMESTAMP)),'YYYYMMDD') AS CREATED_ON_KEY
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(CR.LAST_MODIFIED_ON AS TIMESTAMP)) AS LAST_MODIFIED_ON 
, CR.CREATED_BY AS CREATED_BY
, CR.CREATED_ON AS CREATED_ON_UTC
, CR.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, CR.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM', 'MDT_CONTACTS') }} AS C
INNER JOIN {{ source('CES_MSCM', 'MDT_CONTACT_ROLES') }} AS CR 
ON C.CONTACT_ID = CR.CONTACT_ID
INNER JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS
ON CR.PARTICIPANT_SITE_ID = PS.PARTICIPANT_SITE_ID
INNER JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANTS') }} AS P
ON CR.PARTICIPANT_ID = P.PARTICIPANT_ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON PS.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'SCHEME_REF_CODES') }} AS R_T
ON CR.ROLE_TYPE_ID = R_T.SCHEME_REF_CODES_ID
LEFT JOIN {{ source('CES_MSCM', 'SCHEME_REF_CODES') }} AS R_TT
ON PS.TAXONOMY_TYPE_ID = R_TT.SCHEME_REF_CODES_ID 
LEFT JOIN (
    SELECT 
         PS.MULTI_SCHEME_ID
        ,CR.PARTICIPANT_SITE_ID
        ,CR.CONTACT_ID  
        ,C.FIRST_NAME
        ,C.LAST_NAME
        ,C.EMAIL
        ,C.MOBILE_PHONE_NUMBER
        ,R.CODE
        ,PS.SITE_NUMBER AS CONSUMER_ID
        ,R_G.VALUE AS CUSTOMER_GROUP
        ,GREATEST(NVL(C.LAST_MODIFIED_ON, TO_DATE('01/01/1900', 'DD/MM/YYYY')), NVL(CR.LAST_MODIFIED_ON, TO_DATE('01/01/1900', 'DD/MM/YYYY'))) AS LAST_MODIFIED_ON_UTC
    FROM {{ source('CES_MSCM', 'MDT_CONTACTS') }} AS C
    INNER JOIN {{ source('CES_MSCM', 'MDT_CONTACT_ROLES') }} AS CR
    ON C.CONTACT_ID = CR.CONTACT_ID
    INNER JOIN {{ source('CES_MSCM', 'SCHEME_REF_CODES') }} AS R
    ON CR.ROLE_TYPE_ID = R.SCHEME_REF_CODES_ID
    INNER JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS
    ON CR.PARTICIPANT_SITE_ID = PS.PARTICIPANT_SITE_ID
    INNER JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANTS') }} AS P
    ON P.PARTICIPANT_ID = PS.PARTICIPANT_ID
    LEFT JOIN {{ source('CES_MSCM', 'SCHEME_REF_CODES') }} AS R_G
    ON P.PARTICIPANT_GROUP_ID = R_G.SCHEME_REF_CODES_ID
    LEFT JOIN {{ source('CES_MSCM', 'SCHEME_REF_CODES') }} AS R_TT
    ON PS.TAXONOMY_TYPE_ID = R_TT.SCHEME_REF_CODES_ID
    WHERE CR.ASSIGNMENT_TYPE = 'SITE'
        AND R.CODE = 'AUTHORISED_CONTACT_B2C'
        AND C.PRIMARY = 1
        AND C.ACTIVE = 1
        AND CR.ACTIVE = 1
        AND C.FIRST_NAME IS NOT NULL
        AND R_G.VALUE = 'Individual Consumer'
        QUALIFY ROW_NUMBER() OVER (PARTITION BY CR.PARTICIPANT_SITE_ID ORDER BY NVL(CR.EFFECTIVE_END_DATE, TO_DATE('01/01/9999', 'DD/MM/YYYY')) DESC) = 1
) CC 
ON CC.CONTACT_ID  = CR.CONTACT_ID 
AND PS.MULTI_SCHEME_ID = CC.MULTI_SCHEME_ID
AND PS.SITE_NUMBER <> CC.CONSUMER_ID
WHERE PS.SITE_TYPE_ID = '1537'
AND R_T.VALUE IN ('Group Member','Group Admin')