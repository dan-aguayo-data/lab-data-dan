SELECT
P.PARTICIPANT_ID AS SUPPLIER_ID
, P.PARTICIPANT_NUMBER AS SUPPLIER_NUMBER
, P.PARTICIPANT_NAME AS SUPPLIER_NAME
, P.ALTERNATE_NAME  AS ALTERNATE_NAME 
, P.LEGAL_NAME AS LEGAL_NAME
, INITCAP(P.STATUS) AS STATUS
, P.ERP_BUSINESS_RELATIONSHIP AS ERP_BUSINESS_RELATIONSHIP
, P.ERP_REGISTRY_ID AS ERP_REGISTRY_ID
, P.ERP_SUPPLIER_TYPE AS ERP_SUPPLIER_TYPE
, P.ESTABLISHED_DATE AS ESTABLISHED_DATE
, P.INACTIVE_DATE AS INACTIVE_DATE
, P.REG_ADDR_CONTACT_PHONE_NUMBER AS PHONE_NUMBER
, P.REG_ADDR_CONTACT_PHONE_EXT AS PHONE_EXT
, P.REG_ADDR_CONTACT_EMAIL AS EMAIL
, P.REG_ADDR_ADDRESS_LINE_1 AS ADDRESS_LINE_1
, P.REG_ADDR_ADDRESS_LINE_2 AS ADDRESS_LINE_2
, P.REG_ADDR_CITY_SUBURB AS SUBURB
, P.REG_ADDR_STATE AS STATE
, P.REG_ADDR_POST_CODE AS POSTCODE
, P.COMPANY_NUMBER AS ACN
, P.TAX_REGISTRATION_NUMBER  AS ABN
, P.TAX_ORGANIZATION_TYPE  AS TAX_ORGANISATION_TYPE 
, P.AP_TAX_CLASS  AS AP_TAX_CLASS 
, P.AR_TAX_CLASS  AS AR_TAX_CLASS 
, P.GST_REGISTERED AS GST_REGISTERED
, P.GST_CONCESSION AS GST_CONCESSION
, P.CREATED_ON AS CREATED_ON_UTC
, P.CREATED_BY AS CREATED_BY
, P.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, P.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, ABN.ABN AS ABR_ABN
, ABN.ABNSTATUSFROMDATE AS ABR_ABN_STATUS_FROM_DATE
, ABN.ABNSTATUS AS ABR_ABN_STATUS
, ABN.GSTSTATUS AS ABR_GST_STATUS
, CASE WHEN ABN.ENTITYTYPETEXT = 'Individual/Sole Trader' THEN ABN.FAMILYNAME || ' ' || ABN.GIVENNAME ELSE ABN.NONINDIVIDUALNAMETEXT END AS ABR_LEGAL_NAME
, CASE WHEN ABN.ENTITYTYPETEXT = 'Individual/Sole Trader' THEN ABN.GIVENNAME || '%' || ABN.FAMILYNAME ELSE ABN.NONINDIVIDUALNAMETEXT END AS ABR_LEGAL_NAME_SOLE_TRADER_FOR_RECONCILIATION
, ABN.ENTITYTYPETEXT AS ABR_ENTITY_TYPE
, CASE WHEN ABN.ABN IS NULL THEN 'ABN Not Registered' ELSE 'Reconciled' END AS ABN_RECONCILIATION
, CASE WHEN (INITCAP(P.STATUS) = 'Active' AND ABN.ABNSTATUS = 'ACT') OR (INITCAP(P.STATUS) = 'Inactive' AND ABN.ABNSTATUS = 'CAN') THEN 'Reconciled' WHEN INITCAP(P.STATUS) = 'Inactive' AND ABN.ABNSTATUS = 'ACT' THEN 'Contract Inactive, ABR Active' WHEN INITCAP(P.STATUS) = 'Active' AND ABN.ABNSTATUS = 'CAN' THEN 'Contract Active, ABR Inactive' ELSE 'Not Reconciled' END AS ABN_STATUS_RECONCILIATION
, CASE WHEN ABN.ENTITYTYPETEXT = 'Individual/Sole Trader' AND REPLACE(TRIM(UPPER(CASE WHEN P.LEGAL_NAME LIKE 'INVALID %' THEN REPLACE(P.LEGAL_NAME, 'INVALID ') ELSE P.LEGAL_NAME END)), ',') LIKE ANY (UPPER(ABR_LEGAL_NAME) || '%', UPPER(ABR_LEGAL_NAME_SOLE_TRADER_FOR_RECONCILIATION) || '%') THEN 'Reconciled' WHEN REPLACE(REPLACE(REPLACE(TRIM(LOWER(CASE WHEN P.LEGAL_NAME LIKE 'INVALID %' THEN REPLACE(P.LEGAL_NAME, 'INVALID ') ELSE P.LEGAL_NAME END)), 'pty.', 'pty'), 'ltd.', 'ltd'), 'co.', 'co') = REPLACE(REPLACE(REPLACE(TRIM(LOWER(ABN.NONINDIVIDUALNAMETEXT)), 'pty.', 'pty'), 'ltd.', 'ltd'), 'co.', 'co') THEN 'Reconciled' ELSE 'Not Reconciled' END AS LEGAL_NAME_RECONCILIATION
, CASE WHEN ABN_RECONCILIATION = 'Reconciled' AND ABN_STATUS_RECONCILIATION IN ('Reconciled', 'Contract Inactive, ABR Active') AND LEGAL_NAME_RECONCILIATION = 'Reconciled' THEN 'Reconciled' ELSE 'Not Reconciled' END AS FINAL_RECONCILIATION
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM', 'MDT_PARTICIPANTS') }} AS P
INNER JOIN (
    SELECT DISTINCT
    S.PARTICIPANT_ID
    FROM {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS S
    WHERE S.SITE_TYPE_ID != '1537'
) PS
ON PS.PARTICIPANT_ID = P.PARTICIPANT_ID
LEFT JOIN {{ source('CES_ABN', 'ABN_EXTRACT') }} AS ABN
ON P.TAX_REGISTRATION_NUMBER = ABN.ABN || ''