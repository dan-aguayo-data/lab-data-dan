SELECT
O.SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, U.TRIP_UNIT_ID AS ID
, U.TRIP_LEG_ID AS TRIP_LEG_ID
, U.MANIFEST_NUMBER AS MANIFEST_NUMBER
, U.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID
, MT.NAME AS MATERIAL_TYPE
, U.NO_OF_CONTAINERS AS UNIT_QTY
, U.UNIT_WEIGHT_START AS UNIT_WEIGHT_START
, U.UNIT_WEIGHT_END AS UNIT_WEIGHT_END
, U.SHIPPER_UNIT_REF AS SHIPPER_UNIT_REF
, R.VALUE AS ADJUST_REASON
, U.CREATED_BY AS CREATED_BY
, U.CREATED_ON AS CREATED_ON_UTC
, U.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, U.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM', 'FMT_TRIP_UNITS') }} AS U
INNER JOIN {{ source('CES_MSCM', 'FMT_TRIP_LEGS') }} AS L
ON U.TRIP_LEG_ID = L.TRIP_LEG_ID
INNER JOIN {{ source('CES_MSCM', 'FMT_TRIPS') }} AS T
ON L.TRIP_ID = T.TRIP_ID
INNER JOIN {{ source('CES_MSCM', 'FMT_ORGANISATIONS') }} AS O
ON T.ORGANISATION_ID = O.ORGANISATION_ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON O.SCHEME_ID = SCHEME.MULTI_SCHEME_ID
INNER JOIN {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS MT
ON U.MATERIAL_TYPE_ID = MT.ID
LEFT JOIN {{ source('CES_MSCM', 'FMT_SCHEME_REF_CODES') }} AS R
ON U.ADJUST_REASON_ID = R.ID