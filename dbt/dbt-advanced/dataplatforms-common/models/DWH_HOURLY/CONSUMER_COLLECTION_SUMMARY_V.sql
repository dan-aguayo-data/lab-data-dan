SELECT
C.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, C.SCHEME AS SCHEME
, C.MULTI_SCHEME_ID || '-' || C.CONSUMER_ID || '-' || C.SITE_NUMBER || '-' || C.TRANSACTION_DATE_KEY AS ID
, C.CONSUMER_ID AS CONSUMER_ID
, C.SITE_NUMBER AS SITE_NUMBER
, C.TRANSACTION_DATE AS TRANSACTION_DATE
, C.TRANSACTION_DATE_KEY AS TRANSACTION_DATE_KEY
, C.COLLECTION_QTY AS COLLECTION_QTY
, C.VISIT_SEQUENCE AS VISIT_SEQUENCE
, C.RETURN_CYCLE AS RETURN_CYCLE
, CASE WHEN C.RETURN_CYCLE BETWEEN 1 AND 14 THEN '1-14 days' WHEN C.RETURN_CYCLE BETWEEN 15 AND 30 THEN '15-30 days' WHEN C.RETURN_CYCLE BETWEEN 31 AND 45 THEN '31-45 days' WHEN C.RETURN_CYCLE BETWEEN 46 AND 60 THEN '46-60 days' WHEN C.RETURN_CYCLE BETWEEN 61 AND 150 THEN '61-150 days' WHEN C.RETURN_CYCLE BETWEEN 151 AND 365 THEN '151-365 days' WHEN C.RETURN_CYCLE > 365 THEN '365+ days' END AS RETURN_CYCLE_BANDING
, CASE WHEN C.RETURN_CYCLE BETWEEN 1 AND 14 THEN 1 WHEN C.RETURN_CYCLE BETWEEN 15 AND 30 THEN 2 WHEN C.RETURN_CYCLE BETWEEN 31 AND 45 THEN 3 WHEN C.RETURN_CYCLE BETWEEN 46 AND 60 THEN 4 WHEN C.RETURN_CYCLE BETWEEN 61 AND 150 THEN 5 WHEN C.RETURN_CYCLE BETWEEN 151 AND 365 THEN 6 WHEN C.RETURN_CYCLE > 365 THEN 7 END AS RETURN_CYCLE_BANDING_ORDER
, SUM(CASE WHEN C.TRANSACTION_DATE BETWEEN DATEADD('MONTH',-12,C.TRANSACTION_DATE) AND C.TRANSACTION_DATE THEN C.COLLECTION_QTY ELSE 0 END) OVER (PARTITION BY C.CONSUMER_ID) AS CONSUMER_COLLECTION_QTY_LAST_12_MONTHS
, SYSDATE() AS INSERT_DATE_UTC
FROM (
    SELECT
    BASE.MULTI_SCHEME_ID
    , BASE.SCHEME
    , BASE.CONSUMER_ID
    , BASE.TRANSACTION_DATE
    , BASE.TRANSACTION_DATE_KEY
    , BASE.SITE_NUMBER
    , BASE.COLLECTION_QTY
    , ROW_NUMBER() OVER (PARTITION BY BASE.CONSUMER_ID ORDER BY BASE.TRANSACTION_DATE) AS VISIT_SEQUENCE
    , DATEDIFF('DAY', LAG(BASE.TRANSACTION_DATE, 1, NULL) OVER (PARTITION BY BASE.CONSUMER_ID ORDER BY BASE.TRANSACTION_DATE), BASE.TRANSACTION_DATE) AS RETURN_CYCLE
    FROM (
        SELECT
        HDR.MULTI_SCHEME_ID
        , HDR.SCHEME
        , HDR.CONSUMER_ID
        , MIN(HDR.TRANSACTION_DATE) AS TRANSACTION_DATE
        , HDR.TRANSACTION_DATE_KEY
        , HDR.SITE_NUMBER
        , SUM(HDR.COLLECTION_QTY) AS COLLECTION_QTY
        FROM {{ ref('CRP_COLLECTION_HDR') }} AS HDR
        WHERE CONSUMER_ID <> '-'
        GROUP BY
        HDR.MULTI_SCHEME_ID
        , HDR.SCHEME
        , HDR.CONSUMER_ID
        , HDR.TRANSACTION_DATE_KEY
        , HDR.SITE_NUMBER
    ) BASE
) C