SELECT
10001 AS MULTI_SCHEME_ID
, D.MANIFEST_ID AS MANIFEST_ID
, D.BILL_TO_CUSTOMER_NAME AS BILL_TO_CUSTOMER_NAME
, D.INVOICE_NUMBER AS INVOICE_NUMBER
, LM.CARRIER AS CARRIER
, LM.CONSIGNMENT_NO AS CONSIGNMENT_NO
, LM.REGISTRATION_NO AS REGISTRATION_NO
FROM
{{ source('CES_ERP', 'DST_ORORA_MANIFEST_RECON') }} AS D
LEFT JOIN {{ source('CES_MSCM', 'LOT_ITEM_MANIFEST') }} AS LM
ON LM.ID = D.MANIFEST_ID
WHERE D.MANIFEST_ID <> 'LM46410'
OR D.INVOICE_NUMBER <> '878025'