SELECT
H.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, H.SCHEME AS SCHEME
, D.ID AS ID
, H.TRANSACTION_ID AS TRANSACTION_ID
, H.CONSUMER_ID AS CONSUMER_ID
, H.RECIPIENT_CONSUMER_ID AS RECIPIENT_CONSUMER_ID
, H.BAG_LABEL_ID AS BAG_LABEL_ID
, H.BAG_ISSUE_TYPE AS BAG_ISSUE_TYPE
, H.PAYMENT_METHOD AS PAYMENT_METHOD
, H.CUSTOMER_DECLARATION AS CUSTOMER_DECLARATION
, H.STATUS AS STATUS
, H.TRANSACTED_BY AS TRANSACTED_BY
, H.TRANSACTION_DATE_KEY AS TRANSACTION_DATE_KEY
, H.SITE_NUMBER AS SITE_NUMBER
, H.SITE_NAME AS SITE_NAME
, H.POS_DEVICE_ID AS POS_DEVICE_ID
, D.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID
, D.COLLECTION_QTY AS COLLECTION_QTY
, D.GROSS_AMOUNT AS GROSS_AMOUNT
, D.GST_AMOUNT AS GST_AMOUNT
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ ref('CRP_COLLECTION_HDR') }} AS H
INNER JOIN {{ ref('CRP_COLLECTION_DTL') }} AS D
ON H.TRANSACTION_ID = D.TRANSACTION_ID
WHERE H.SITE_NUMBER IN ('QC10003051', 'QS10003051', 'WC20000002')