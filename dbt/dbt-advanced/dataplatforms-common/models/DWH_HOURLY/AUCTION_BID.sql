SELECT
B.MULTI_SCHEME_ID  AS MULTI_SCHEME_ID 
, SCHEME.NAME AS SCHEME
, B.ID AS ID
, B.AUCTION_EVENT_LOT_ID AS EVENT_LOT_ID
, B.BIDDER AS BIDDER
, R.SITE_NAME AS BIDDER_NAME
, B.BID_PRICE_PER_TONNE AS BID_PRICE_PER_TONNE
, CONVERT_TIMEZONE('UTC','Australia/NSW',CAST(B.SUBMITTED_ON AS TIMESTAMP))  AS SUBMITTED_DATE_NSW
, CASE WHEN B.AUCTION_PROXY_BID_ID IS NULL THEN 'Manual Bid' ELSE 'Proxy Bid' END AS BID_TYPE
, B.AUCTION_PROXY_BID_ID AS PROXY_BID_ID
, P.STARTING_BID AS PROXY_STARTING_BID
, P.MAXIMUM_BID AS PROXY_MAXIMUM_BID
, CASE WHEN E.END_DATE<B.SUBMITTED_ON OR E.END_DATE<P.SUBMITTED_ON THEN 1 ELSE 0 END AS OVERTIME_BID
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(P.SUBMITTED_ON AS TIMESTAMP))  AS PROXY_SUBMITTED_DATE
, B.SUBMITTED_ON AS SUBMITTED_DATE_UTC
, P.SUBMITTED_ON AS PROXY_SUBMITTED_DATE_UTC
, B.CREATED_BY AS CREATED_BY
, B.CREATED_ON AS CREATED_ON_UTC
, B.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, B.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, B.CANCELLED_BY AS CANCELLED_BY
, CONVERT_TIMEZONE('UTC','Australia/NSW',CAST(B.CANCELLED_ON AS TIMESTAMP))  AS CANCELLED_ON_NSW
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM', 'AUCTION_BID') }} AS B
LEFT JOIN {{ source('CES_MSCM', 'AUCTION_PROXY_BIDS') }} AS P
ON B.AUCTION_EVENT_LOT_ID = P.AUCTION_EVENT_LOT_ID
AND B.BIDDER = P.BIDDER
AND B.AUCTION_PROXY_BID_ID = P.AUCTION_PROXY_BID_ID
AND B.MSC_BIDDER_SITE_ID = P.MSC_BIDDER_SITE_ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON B.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'AUCTION_EVENT_LOT') }} AS A
ON A.ID = B.AUCTION_EVENT_LOT_ID
LEFT JOIN {{ source('CES_MSCM', 'AUCTION_EVENT') }} AS E
ON E.ID = A.AUCTION_EVENT_ID
LEFT JOIN {{ ref('RECYCLER_SITES') }} AS R
ON  B.BIDDER = R.SITE_NUMBER