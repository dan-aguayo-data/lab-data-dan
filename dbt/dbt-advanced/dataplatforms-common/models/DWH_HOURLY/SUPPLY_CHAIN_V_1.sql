SELECT
F.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.SCHEME AS SCHEME
, F.DATE_KEY || '-' || F.MATERIAL_TYPE_ID || '-' || F.PROCESSOR_SITE_NUMBER || '-' || F.CRP_SITE_NUMBER AS ID
, F.DATE_KEY AS DATE_KEY
, F.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID
, F.CRP_SITE_NUMBER AS CRP_SITE_NUMBER
, F.PROCESSOR_SITE_NUMBER AS PROCESSOR_SITE_NUMBER
, F.COLLECTION_WEIGHT_TONNE AS COLLECTION_WEIGHT_TONNE
, F.SHIPPING_MANIFEST_WEIGHT_TONNE AS SHIPPING_MANIFEST_WEIGHT_TONNE
, F.RECEIPT_WEIGHT_TONNE AS RECEIPT_WEIGHT_TONNE
, F.GROSS_AMOUNT AS GROSS_AMOUNT
, F.PROCESSOR_CLAIM_WEIGHT_TONNE AS PROCESSOR_CLAIM_WEIGHT_TONNE
, PF.AMOUNT AS PROCESSOR_RATE
, PF.AMOUNT * F.RECEIPT_WEIGHT_TONNE * 1000 AS PAYMENT_PROJECTION
, F.RECEIPT_WEIGHT_TONNE-F.SHIPPING_MANIFEST_WEIGHT_TONNE AS VARIANCE_C_MINUS_B
, F.RECEIPT_WEIGHT_TONNE-F.PROCESSOR_CLAIM_WEIGHT_TONNE AS VARIANCE_C_MINUS_D
, (PF.AMOUNT * F.RECEIPT_WEIGHT_TONNE * 1000)-F.GROSS_AMOUNT AS VARIANCE_E_MINUS_F
FROM (
SELECT
COALESCE(CRP.MULTI_SCHEME_ID, M.MULTI_SCHEME_ID, R.MULTI_SCHEME_ID) AS MULTI_SCHEME_ID
, COALESCE(CRP.TRANSACTION_DATE_KEY, M.GENERATED_ON, R.PERIOD_KEY) AS DATE_KEY
, COALESCE(CRP.MATERIAL_TYPE_ID, M.TRANSACTION_MATERIAL_TYPE_ID, R.MATERIAL_TYPE_ID) AS MATERIAL_TYPE_ID
, NVL(COALESCE(CRP.CRP_SITE_NUMBER, M.CRP_SITE_NUMBER, R.CRP_SITE_NUMBER),'-') AS CRP_SITE_NUMBER
, NVL(RR.PROCESSOR_SITE_NUMBER,'-') AS PROCESSOR_SITE_NUMBER
, CRP.COLLECTION_KG_DERIVED/1000 AS COLLECTION_WEIGHT_TONNE
, M.SHIPPING_MANIFEST_WEIGHT_KG/1000 AS SHIPPING_MANIFEST_WEIGHT_TONNE
, R.RECEIPT_WEIGHT_KG/1000 AS RECEIPT_WEIGHT_TONNE
, NULL AS GROSS_AMOUNT
, NULL AS PROCESSOR_CLAIM_WEIGHT_TONNE
FROM (
    SELECT
    HDR.MULTI_SCHEME_ID
    , HDR.TRANSACTION_DATE_KEY
    , HDR.SITE_NUMBER AS CRP_SITE_NUMBER
    , DTL.MATERIAL_TYPE_ID
    , DTL.MATERIAL_TYPE
    , SUM(DTL.COLLECTION_KG_DERIVED) AS COLLECTION_KG_DERIVED
    FROM
    {{ ref('CRP_COLLECTION_HDR') }} AS HDR
    INNER JOIN {{ ref('CRP_COLLECTION_DTL') }} AS DTL
    ON HDR.TRANSACTION_ID = DTL.TRANSACTION_ID 
    GROUP BY
    HDR.MULTI_SCHEME_ID
    , HDR.TRANSACTION_DATE_KEY
    , HDR.SITE_NUMBER
    , DTL.MATERIAL_TYPE_ID
    , DTL.MATERIAL_TYPE
) CRP                                                                                                                                           --A
FULL OUTER JOIN (
    SELECT
    SM.MULTI_SCHEME_ID
    , SM.GENERATED_ON
    , SM.CRP_SITE_NUMBER
    , SM.TRANSACTION_MATERIAL_TYPE_ID
    , SM.TRANSACTION_MATERIAL_TYPE
    , SUM(SM.CONVERTED_WEIGHT - SM.EMPTY_WEIGHT) AS SHIPPING_MANIFEST_WEIGHT_KG
    FROM (
        SELECT
        CRPM.MULTI_SCHEME_ID
        , TO_CHAR(CRPM.GENERATED_ON,'YYYYMMDD') as GENERATED_ON
        , CRPM.CRP_SITE_NUMBER
        , CRPM.TRANSACTION_MATERIAL_TYPE_ID
        , CRPM.TRANSACTION_MATERIAL_TYPE
        , CRPM.EMPTY_WEIGHT
        , CRPM.CONVERTED_WEIGHT
        FROM {{ ref('CRP_SHIPPING_MANIFEST') }} AS CRPM
        INNER JOIN (
            SELECT DISTINCT
            R.MANIFEST_NUMBER
            --, R.ASSET_ID
            --, R.MATERIAL_TYPE_ID
            FROM {{ ref('PROCESSOR_RECEIPT') }} AS R
            WHERE NOT(R.RECEIVED = 0 AND R.STATUS = 'RECEIVED')
        ) R_FILTER
        ON CRPM.MANIFEST_NUMBER = R_FILTER.MANIFEST_NUMBER
        --AND CRPM.ASSET_ID = R_FILTER.ASSET_ID
        --AND CRPM.MATERIAL_TYPE_ID = R_FILTER.MATERIAL_TYPE_ID
    ) SM
    GROUP BY
    SM.MULTI_SCHEME_ID
    , SM.GENERATED_ON
    , SM.CRP_SITE_NUMBER
    , SM.TRANSACTION_MATERIAL_TYPE_ID
    , SM.TRANSACTION_MATERIAL_TYPE
) M                                                                                                                                             --B
ON CRP.MULTI_SCHEME_ID = M.MULTI_SCHEME_ID
AND CRP.TRANSACTION_DATE_KEY = M.GENERATED_ON
AND CRP.MATERIAL_TYPE_ID = M.TRANSACTION_MATERIAL_TYPE_ID
AND CRP.CRP_SITE_NUMBER = M.CRP_SITE_NUMBER
FULL OUTER JOIN (
    SELECT
    RG.MULTI_SCHEME_ID
    , RG.PERIOD_KEY
    , RG.MATERIAL_TYPE_ID
    , RG.MATERIAL_TYPE
    , RG.CRP_SITE_NUMBER
    , SUM(RG.RECEIPT_WEIGHT_KG) AS RECEIPT_WEIGHT_KG
    FROM (
        SELECT
        PR.MULTI_SCHEME_ID
        , PR.PERIOD_KEY
        , PR.MATERIAL_TYPE_ID
        , PR.MATERIAL_TYPE
        , CRPS.CRP_SITE_NUMBER
        , PR.RECEIVED_KG_DERIVED AS RECEIPT_WEIGHT_KG
        FROM {{ ref('PROCESSOR_RECEIPT') }} AS PR
        LEFT JOIN (
            SELECT DISTINCT
            CRPSM.MANIFEST_NUMBER
            , CRPSM.CRP_SITE_NUMBER
            FROM {{ ref('CRP_SHIPPING_MANIFEST') }} AS CRPSM 
        ) CRPS
        ON PR.MANIFEST_NUMBER = CRPS.MANIFEST_NUMBER
        WHERE PR.STATUS = 'RECEIVED'
    ) RG
    GROUP BY
    RG.MULTI_SCHEME_ID
    , RG.PERIOD_KEY
    , RG.MATERIAL_TYPE_ID
    , RG.MATERIAL_TYPE
    , RG.CRP_SITE_NUMBER
) R                                                                                                                                             --C
ON COALESCE(CRP.MULTI_SCHEME_ID, M.MULTI_SCHEME_ID) = R.MULTI_SCHEME_ID
AND COALESCE(CRP.TRANSACTION_DATE_KEY, M.GENERATED_ON) = R.PERIOD_KEY
AND COALESCE(CRP.MATERIAL_TYPE_ID, M.TRANSACTION_MATERIAL_TYPE_ID) = R.MATERIAL_TYPE_ID
AND COALESCE(CRP.CRP_SITE_NUMBER, M.CRP_SITE_NUMBER) = R.CRP_SITE_NUMBER
LEFT JOIN (
     SELECT
     CRP_SITE_NUMBER
     , PROCESSOR_SITE_NUMBER
     , MATERIAL_TYPE_ID
     , CP_EFFECTIVE_FROM
     , CASE WHEN CP_EFFECTIVE_TO IS NULL THEN NULL ELSE DATEADD('day',-1,to_date(CP_EFFECTIVE_TO)) END AS CP_EFFECTIVE_TO
     , COUNT(*) AS DUPS
     FROM
     {{ ref('B2B_RELATIONSHIP') }} AS R
     GROUP BY
     CRP_SITE_NUMBER
     , PROCESSOR_SITE_NUMBER
     , MATERIAL_TYPE_ID
     , CP_EFFECTIVE_FROM
     , CASE WHEN CP_EFFECTIVE_TO IS NULL THEN NULL ELSE DATEADD('day',-1,to_date(CP_EFFECTIVE_TO)) END-- HAVING COUNT(*) > 1
) RR                                                                                                                                            --REF
ON COALESCE(CRP.CRP_SITE_NUMBER, M.CRP_SITE_NUMBER, R.CRP_SITE_NUMBER) = RR.CRP_SITE_NUMBER
AND COALESCE(CRP.MATERIAL_TYPE_ID, M.TRANSACTION_MATERIAL_TYPE_ID,R.MATERIAL_TYPE_ID) = RR.MATERIAL_TYPE_ID 
AND COALESCE(CRP.TRANSACTION_DATE_KEY, M.GENERATED_ON, R.PERIOD_KEY) BETWEEN TO_CHAR(RR.CP_EFFECTIVE_FROM,'YYYYMMDD') AND TO_CHAR(NVL(RR.CP_EFFECTIVE_TO,SYSDATE()),'YYYYMMDD') -- 1,621,315 
UNION ALL
SELECT
FPP.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, FPP.PERIOD_KEY AS DATE_KEY
, FPP.MATERIAL_TYPE_ID
, '-' AS CRP_SITE_NUMBER
, FPP.SITE_NUMBER AS PROCESSOR_SITE_NUMBER
, NULL AS COLLECTION_WEIGHT_TONNE
, NULL AS SHIPPING_MANIFEST_WEIGHT_TONNE
, NULL AS RECEIPT_WEIGHT_TONNE
, SUM(FPP.GROSS_AMOUNT) AS GROSS_AMOUNT  
, SUM(FPP.VOLUME_ORIGINAL)/1000 AS PROCESSOR_CLAIM_WEIGHT_TONNE
FROM
{{ ref('FIN_PROCESSOR_PAYMENT') }} AS FPP
GROUP BY
FPP.SITE_NUMBER
, FPP.MATERIAL_TYPE_ID
, FPP.PERIOD_KEY          
, FPP.MULTI_SCHEME_ID -- 17,005 
) F                                                                                                                                           --D
INNER JOIN {{ ref('REF_SCHEME') }} AS SCHEME
ON F.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN (
     SELECT
     SITE_NUMBER
     , ID
     , AMOUNT  
     , MATERIAL_TYPE_ID
     , EFFECTIVE_FROM
     , CASE WHEN EFFECTIVE_TO IS NULL THEN NULL ELSE DATEADD('day',-1,to_date(EFFECTIVE_TO)) END AS EFFECTIVE_TO
     , ROW_NUMBER() OVER (PARTITION BY SITE_NUMBER, MATERIAL_TYPE_ID, EFFECTIVE_FROM ORDER BY LAST_MODIFIED_ON_UTC DESC) AS DUP_FILTER
     FROM
     {{ ref('REF_PROCESSOR_FEE') }} AS FEE
) PF                                                                                                                                           --REF
ON F.PROCESSOR_SITE_NUMBER = PF.SITE_NUMBER
AND F.MATERIAL_TYPE_ID  = PF.MATERIAL_TYPE_ID 
AND F.DATE_KEY BETWEEN TO_CHAR(PF.EFFECTIVE_FROM,'YYYYMMDD') AND TO_CHAR(NVL(PF.EFFECTIVE_TO,SYSDATE()),'YYYYMMDD') --1,622,722 
AND PF.DUP_FILTER = 1