SELECT
H.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, H.SCHEME AS SCHEME
, D.ID AS ID
, CAST(H.TRANSACTION_DATE AS DATE) AS TRANSACTION_DATE
, TO_CHAR(H.TRANSACTION_DATE, 'HH:MI:SS') AS TRANSACTION_TIME
, TO_CHAR(H.TRANSACTION_DATE, 'HH') AS HOUR
, TO_CHAR(H.TRANSACTION_DATE, 'MI') AS MINUTE
, H.TRANSACTION_ID AS TRANSACTION_ID
, H.SITE_NUMBER AS SITE_NUMBER
, H.CONSUMER_ID AS CONSUMER_ID
, H.RECIPIENT_CONSUMER_ID AS RECIPIENT_CONSUMER_ID
, D.MATERIAL_TYPE AS MATERIAL_TYPE
, H.PAYMENT_METHOD AS PAYMENT_METHOD
, H.PAYMENT_TYPE AS PAYMENT_TYPE
, H.DEVICE_NAME AS DEVICE_NAME
, H.POS_USER_NAME AS POS_USER_NAME
, D.COLLECTION_QTY AS COLLECTION_QTY
, H.COLLECTION_QTY AS TRANSACTION_QTY
, H.BAG_LABEL_ID AS BAG_LABEL_ID
, H.BAG_ISSUE_TYPE AS BAG_ISSUE_TYPE
, H.BAG_ISSUE_DESC AS BAG_ISSUE_DESC
, D.CREATED_ON_UTC AS CREATED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ ref('CRP_COLLECTION_HDR') }} AS H
INNER JOIN {{ ref('CRP_COLLECTION_DTL') }} AS D
ON H.TRANSACTION_ID = D.TRANSACTION_ID
WHERE H.TRANSACTION_DATE_KEY >= TO_CHAR(DATEADD(MONTH, -6, SYSDATE()), 'YYYYMMDD')