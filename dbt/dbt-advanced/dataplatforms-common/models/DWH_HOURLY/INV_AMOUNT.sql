SELECT
I.MULTI_SCHEME_ID  AS MULTI_SCHEME_ID 
, CAST(I.ORIG_HEADER_ID AS VARCHAR(25)) AS ID
, 'PYMT_TRXN_HEADER_ID' AS ID_TYPE
, CAST(SUM(I.INVOICE_AMOUNT) AS DECIMAL(18,2)) AS INVOICE_AMOUNT
, LISTAGG(I.INVOICE_NUMBER || '(' || I.STATUS || ')' , ', ') WITHIN GROUP (ORDER BY I.INVOICE_NUMBER) AS INVOICE_NUMBER_AND_STATUS
, max(created_on) AS CREATED_ON_UTC
, max(updated_on) AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM', 'INV_AP_INVOICES_INT') }} AS I
WHERE I.CANCELLED_FLAG <> 'Y'
GROUP BY I.ORIG_HEADER_ID
, I.MULTI_SCHEME_ID
UNION ALL
SELECT
I.MULTI_SCHEME_ID  AS MULTI_SCHEME_ID 
, I.ATTRIBUTE1 AS ID
, 'POS_TXN_NUM' AS ID_TYPE
, CAST(SUM(I.INVOICE_AMOUNT) AS DECIMAL(18,2)) AS INVOICE_AMOUNT
, LISTAGG(I.INVOICE_NUMBER || '(' || I.STATUS || ')' , ', ') WITHIN GROUP (ORDER BY I.INVOICE_NUMBER) AS INVOICE_NUMBER_AND_STATUS
, max(created_on) AS CREATED_ON_UTC
, max(updated_on) AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM', 'INV_AP_INVOICES_INT') }} AS I
WHERE I.CANCELLED_FLAG <> 'Y'
GROUP BY I.ATTRIBUTE1
, I.MULTI_SCHEME_ID