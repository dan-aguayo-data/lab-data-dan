SELECT
BD.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, BD.ID AS ID
, BD.BOM_HDR_ID AS BOM_HDR_ID
, BH.SCHEME_PARTICIPANT_ID AS SITE_NUMBER
, BD.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID
, M.NAME AS MATERIAL_TYPE
, BH.MRF_MATERIAL_TYPE_ID AS MRF_MATERIAL_TYPE_ID
, M_MRF.NAME AS MRF_MATERIAL_TYPE
, BD.PERCENT_ELIGIBLE_CONTAINER AS PERCENT_ELIGIBLE_CONTAINER
, BD.ELIGIBLE_CONTAINER_PER_KG AS ELIGIBLE_CONTAINER_PER_KG
, CAST(BH.EFFECTIVE_FROM AS DATE) AS EFFECTIVE_FROM
, TO_CHAR(BH.EFFECTIVE_FROM, 'YYYYMMDD') AS EFFECTIVE_FROM_KEY
, CAST(BH.EFFECTIVE_TO AS DATE) AS EFFECTIVE_TO
, BD.CREATED_BY AS CREATED_BY
, BD.CREATED_ON AS CREATED_ON_UTC
, BD.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, BD.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM', 'MRF_MTL_BOM_REFERENCE_DTL') }} AS BD
INNER JOIN {{ source('CES_MSCM', 'MRF_MTL_BOM_REFERENCE_HDR') }} AS BH
ON BD.BOM_HDR_ID = BH.ID
LEFT JOIN {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS M
ON BD.MATERIAL_TYPE_ID = M.ID
LEFT JOIN {{ source('CES_MSCM', 'MRF_MATERIAL_TYPE') }} AS M_MRF
ON BH.MRF_MATERIAL_TYPE_ID = M_MRF.ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON BD.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID