SELECT
PS.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, PS.SITE_NUMBER AS SITE_NUMBER
, PS.SITE_NAME AS SITE_NAME
, CASE WHEN PS.MULTI_SCHEME_ID LIKE '10002%' THEN 0 ELSE NVL(PS.AGGREGATION_POINT_ID, 0) END AS AGGREGATION_POINT_FLAG
, CASE WHEN PS.MULTI_SCHEME_ID LIKE '10002%' THEN NULL ELSE PS.AGGREGATION_POINT_ADDRESS END AS AGGREGATION_POINT_ADDRESS
, CASE WHEN PS.MULTI_SCHEME_ID LIKE '10002%' THEN NULL ELSE NVL(CASE WHEN PS.AGGREGATION_POINT_ADDRESS IS NULL THEN NULL ELSE MAX(CASE WHEN PS.AGGREGATION_POINT_ID = 1 AND PS.STATUS = 'Active' THEN PS.SITE_NUMBER ELSE NULL END) OVER (PARTITION BY PS.AGGREGATION_POINT_ADDRESS, PS.TAXONOMY_TYPE_ID) END,PS.SITE_NUMBER) END AS AGGREGATION_POINT
, CASE WHEN PS.MULTI_SCHEME_ID LIKE '10002%' THEN NULL ELSE NVL(CASE WHEN PS.AGGREGATION_POINT_ADDRESS IS NULL THEN NULL ELSE MAX(CASE WHEN PS.AGGREGATION_POINT_ID = 1 AND PS.STATUS = 'Active' THEN PS.SITE_NAME ELSE NULL END) OVER (PARTITION BY PS.AGGREGATION_POINT_ADDRESS, PS.TAXONOMY_TYPE_ID) END,PS.SITE_NAME) END AS AGGREGATION_POINT_NAME
, P.PARTICIPANT_NUMBER AS SUPPLIER_NUMBER
, P.PARTICIPANT_NAME AS SUPPLIER_NAME
, R_TT.VALUE AS TAXONOMY
, PS.TAXONOMY_SIZE AS TAXONOMY_SIZE
, NULL AS INVOICE_FREQUENCY
, CASE WHEN PS.MULTI_SCHEME_ID = 10000 THEN AG.SITE_STATUS ELSE PS.STATUS END AS STATUS
, P.INACTIVE_DATE AS SITE_INACTIVE_DATE
, PS.CONTRACT_ORGANISATION_ID AS CONTRACT_ORGANISATION_ID
, CASE WHEN PS.MULTI_SCHEME_ID LIKE ANY ('10002%', '10003%') THEN PS.ATTRIBUTE5 WHEN PS.MULTI_SCHEME_ID = 10000 AND R.REGION IS NULL THEN '00 Unknown' ELSE NVL(R.REGION, 'Unknown') END AS REGION
, CASE WHEN PS.MULTI_SCHEME_ID = 10000 AND R.SUBREGION IS NULL THEN '00 Unknown' ELSE NVL(R.SUBREGION, 'Unknown') END AS SUBREGION
, PS.ADDRESS_LINE_1 AS ADDRESS_LINE_1
, PS.ADDRESS_LINE_2 AS ADDRESS_LINE_2
, PS.CITY_SUBURB AS SUBURB
, PS.STATE AS STATE
, PS.POST_CODE AS POSTCODE
, R_C.VALUE AS COUNTRY
, LGA.VALUE AS LGA
, AR.VALUE AS AREA
, PS.X_CORDINDATES AS X_COORDINATES
, PS.Y_CORDINATES AS Y_COORDINATES
, PS.SITE_ADDR_CONTACT_PHONE_NUMBER AS PHONE_NUMBER
, PS.SITE_ADDR_CONTACT_PHONE_EXT AS PHONE_EXT
, PS.SITE_ADDR_CONTACT_EMAIL AS EMAIL
, CASE WHEN PS.MULTI_SCHEME_ID = 10000 THEN AG.EMAIL_ADDRESS ELSE PS.ATTRIBUTE_CATEGORY END AS SITE_CONTACT_EMAIL
, PS.PO_COMMUNICATION_EMAIL AS PO_COMMUNICATION_EMAIL
, PS.PYMT_REMIT_ADV_EMAIL AS PYMT_REMIT_ADV_EMAIL
, PT.INVOICE_TYPE AS INVOICE_TYPE
, PT.INVOICE_PAYMENT_GROUP AS INVOICE_PAYMENT_GROUP
, PT.INV_PAYMENT_TERMS AS INV_PAYMENT_TERMS
, PSU_ST.SOLD_TO_CUST_ACC_NUMBER AS SOLD_TO_CUST_ACC_NUMBER
, PS.WEB_SITE_URL AS WEB_SITE_URL
, PS.DISPLAY_IN_MARKETING AS DISPLAY_IN_MARKETING
, PS.CRM_SITE_ID AS CRM_SITE_ID
, PS.ERP_ADDRESS_ID AS ERP_ADDRESS_ID
, PS.INVENTORY_PICK_UP AS INVENTORY_PICK_UP
, PS.ELECTORATE_UPPER AS ELECTORATE_UPPER
, PS.ELECTORATE_LOWER AS ELECTORATE_LOWER
, PS.SOCIAL_ENTERPRISE AS SOCIAL_ENTERPRISE
, PS.BAG_DROP_SITE AS BAG_DROP_SITE
, PS.DEPOT_SITE AS DEPOT_SITE
, PS.RVM_SITE AS RVM_SITE
, PS.POP_UP_SITE AS POP_UP_SITE
, PS.EFT_VIA_SCHEME_ID AS EFT_SITE
, PS.PAYPAL_SITE AS PAYPAL_SITE
, PS.RETAIL_VOUCHERS_SITE AS RETAIL_VOUCHERS_SITE
, PS.CASH_SITE AS CASH_SITE
, PS.MIN_CONTAINER_QTY AS MIN_CONTAINER_QTY
, PS.MAX_CONTAINER_QTY AS MAX_CONTAINER_QTY
, PS.DISABLED_ACCESS AS DISABLED_ACCESS
, PS.SITE_ADDTL_INFO AS SITE_ADDTL_INFO
, PS.REFUND_POINT_MIN_STANDARD AS REFUND_POINT_MIN_STANDARD
, PS.REFUND_POINT_FULL_TIME AS REFUND_POINT_FULL_TIME
, CO.CONTRACT_ORGANIZATION_NUMBER AS CONTRACT_ORGANIZATION_NUMBER
, CO.CRM_CONTRACT_ORG_ID AS CRM_CONTRACT_ORG_ID
, CO.CONTRACT_TYPE AS CONTRACT_TYPE
, CO.STATUS AS CONTRACT_STATUS
, CO.ESTABLISHED_DATE AS CONTRACT_ESTABLISHED_DATE
, CO.INACTIVE_DATE AS CONTRACT_INACTIVE_DATE
, CO.CURRENT_CONTRACT_EXPIRY_DATE AS CONTRACT_EXPIRY_DATE
, CO.CURRENT_CONTRACT_TERM AS CONTRACT_TERM
, CO.CONTRACT_MANAGER AS CONTRACT_MANAGER
, CC.FIRST_NAME || ' ' || CC.LAST_NAME AS SITE_CONTRACT_MANAGER_NAME
, PS.ATTRIBUTE2 AS SITE_CONTRACT_MANAGER_EMAIL
, CASE WHEN PS.MULTI_SCHEME_ID = 10001 THEN NVL(D.MOBILEPHONE, CC.PHONE_NUMBER) ELSE CC.PHONE_NUMBER END AS SITE_CONTRACT_MANAGER_PHONE_NUMBER
, PS.ATTRIBUTE11 AS CRM_CONTRACT_ORGANIZATION_ID
, LEFT(PS.ATTRIBUTE12, POSITION('-',PS.ATTRIBUTE12)-1) AS LEGAL_ENTITY_ID
, CASE WHEN (INITCAP(PS.STATUS) = 'Active' AND S.ABR_ABN_STATUS = 'ACT') OR (INITCAP(PS.STATUS) = 'Inactive' AND S.ABR_ABN_STATUS = 'CAN') THEN 'Reconciled' WHEN INITCAP(PS.STATUS) = 'Inactive' AND S.ABR_ABN_STATUS = 'ACT' THEN 'Contract Inactive, ABR Active' WHEN INITCAP(PS.STATUS) = 'Active' AND S.ABR_ABN_STATUS = 'CAN' THEN 'Contract Active, ABR Inactive' ELSE 'Not Reconciled' END AS ABN_STATUS_RECONCILIATION_SITE
, CASE WHEN S.ABN_RECONCILIATION = 'Reconciled' AND ABN_STATUS_RECONCILIATION_SITE IN ('Reconciled', 'Contract Inactive, ABR Active') AND S.LEGAL_NAME_RECONCILIATION = 'Reconciled' THEN 'Reconciled' ELSE 'Not Reconciled' END AS FINAL_RECONCILIATION
, PS.ATTRIBUTE1 AS SCHEME_COMMENCEMENT_DATE
, CASE WHEN PS.ATTRIBUTE4 = '1' THEN 'Yes' ELSE 'No' END AS THIRD_PARTY_FLAG
, PS.ATTRIBUTE5 AS ZONE
, PS.ATTRIBUTE6 AS CCSP_PAIR
, PS.ATTRIBUTE7 AS AUTOMATED_COUNTING_FACILITY
, PS.ATTRIBUTE8 AS OVER_THE_COUNTER
, PS.ATTRIBUTE9 AS NOT_FOR_PROFIT
, PS.ATTRIBUTE10 AS SUPPLIER_ARRANGEMENT_NO
, PS.ATTRIBUTE13 AS DRIVE_THROUGH_FACILITY
, PS.ATTRIBUTE15 AS EXTERNAL_SITE_NUMBER
, PSSC.SITE_CATEGORY_PARENT AS SITE_CATEGORY_PARENT
, PSSC.SITE_CATEGORY AS SITE_CATEGORY
, PS.CREATED_BY AS CREATED_BY
, PS.CREATED_ON AS CREATED_ON_UTC
, PS.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, PS.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS
INNER JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANTS') }} AS P
ON P.PARTICIPANT_ID = PS.PARTICIPANT_ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON PS.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN 
    (SELECT
    SU.PARTICIPANT_SITE_ID,
    SU.INV_PAYMENT_TERMS
    FROM (
        SELECT 
        ROW_NUMBER() OVER (PARTITION BY U.PARTICIPANT_SITE_ID ORDER BY U.LAST_MODIFIED_ON DESC) AS N,
        U.PARTICIPANT_SITE_ID,
        U.INV_PAYMENT_TERMS
        FROM {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITE_USES') }} AS U
    ) SU
    WHERE SU.INV_PAYMENT_TERMS IS NOT NULL
    AND SU.N = 1
    ) PSU_PT
ON PS.PARTICIPANT_SITE_ID = PSU_PT.PARTICIPANT_SITE_ID
LEFT JOIN 
    (SELECT
    SU.PARTICIPANT_SITE_ID,
    SU.SOLD_TO_CUST_ACC_NUMBER
    FROM (
        SELECT 
        ROW_NUMBER() OVER (PARTITION BY U.PARTICIPANT_SITE_ID ORDER BY U.LAST_MODIFIED_ON DESC) AS N,
        U.PARTICIPANT_SITE_ID,
        U.SOLD_TO_CUST_ACC_NUMBER
        FROM {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITE_USES') }} AS U
        WHERE U.SITE_USE_TYPE = 'BILL_TO'
    ) SU
    WHERE SU.SOLD_TO_CUST_ACC_NUMBER IS NOT NULL
    AND SU.N = 1
    ) PSU_ST
ON PS.PARTICIPANT_SITE_ID = PSU_ST.PARTICIPANT_SITE_ID
LEFT JOIN (
    SELECT
    C.FIRST_NAME,
    C.LAST_NAME,
    LOWER(C.EMAIL) AS EMAIL,
    C.PHONE_NUMBER,
    ROW_NUMBER() OVER (PARTITION BY LOWER(C.EMAIL) ORDER BY C.LAST_MODIFIED_ON DESC) AS RN
    FROM {{ source('CES_MSCM', 'MDT_CONTACTS') }} AS C
    WHERE ACTIVE = 1
    ) CC
ON LOWER(PS.ATTRIBUTE2) = CC.EMAIL
LEFT JOIN (
    SELECT
    PSC.MULTI_SCHEME_ID,
    PSC.PARTICIPANT_SITE_ID,
    PSC.SITE_NUMBER,
    LISTAGG(DISTINCT SITE_CATEGORY, ', ') WITHIN GROUP (ORDER BY SITE_CATEGORY) AS SITE_CATEGORY_PARENT,
    LISTAGG(DISTINCT CASE WHEN SITE_CATEGORY = 'DEPOT_SITE' THEN SITE_CATEGORY || ' - ' || PSC.THIRD_PARTY ELSE SITE_CATEGORY END, ', ') WITHIN GROUP (ORDER BY CASE WHEN SITE_CATEGORY = 'DEPOT_SITE' THEN SITE_CATEGORY || ' - ' || PSC.THIRD_PARTY ELSE SITE_CATEGORY END) AS SITE_CATEGORY
    FROM (
        SELECT 
        PSB.MULTI_SCHEME_ID, 
        PSB.PARTICIPANT_SITE_ID,
        PSB.SITE_NUMBER, 
        PSB.DEPOT_SITE, 
        PSB.RVM_SITE, 
        CAST(PSB.ATTRIBUTE8 AS NUMBER) AS OTC,
        CASE WHEN PSB.ATTRIBUTE4 = '1' THEN 'Partner Operated' ELSE 'No Operated' END AS THIRD_PARTY
        FROM {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PSB
        WHERE PSB.SITE_TYPE_ID IN ('1538', '2591', '2688')
    ) PSC
    UNPIVOT (FLAG FOR SITE_CATEGORY IN (DEPOT_SITE, RVM_SITE, OTC))
    WHERE FLAG = 1
    GROUP BY ALL
) PSSC
ON PS.PARTICIPANT_SITE_ID = PSSC.PARTICIPANT_SITE_ID
LEFT JOIN (
    SELECT
    WINDOWSLIVEID
    , FIRSTNAME
    , LASTNAME
    , MOBILEPHONE
    FROM WARRRL_REF.WARRRL_DYNAMICS_PROD.SYSTEMUSER
    WHERE WINDOWSLIVEID IS NOT NULL
    QUALIFY ROW_NUMBER() OVER (PARTITION BY WINDOWSLIVEID ORDER BY MODIFIEDON DESC) = 1
) D
ON LOWER(PS.ATTRIBUTE2) = LOWER(D.WINDOWSLIVEID)
LEFT JOIN {{ source('CES_MSCM', 'SCHEME_REF_CODES') }} AS R_TT
ON PS.TAXONOMY_TYPE_ID || '' = R_TT.SCHEME_REF_CODES_ID || ''
LEFT JOIN {{ source('CES_MSCM', 'SCHEME_REF_CODES') }} AS R_C
ON PS.COUNTRY_ID = R_C.SCHEME_REF_CODES_ID
LEFT JOIN {{ source('CES_MSCM', 'SCHEME_REF_CODES') }} AS LGA
ON PS.LGA_ID = LGA.SCHEME_REF_CODES_ID
LEFT JOIN {{ source('CES_MSCM', 'SCHEME_REF_CODES') }} AS AR
ON PS.AREA_ID = AR.SCHEME_REF_CODES_ID
LEFT JOIN {{ source('CES_MSCM', 'MDT_SCHEME_CONTRACT_ORGS') }} AS CO
ON PS.CONTRACT_ORGANISATION_ID = CO.CONTRACT_ORGANIZATION_ID
LEFT JOIN {{ ref('B2B_SUPPLIERS') }} AS S
ON P.PARTICIPANT_NUMBER = S.SUPPLIER_NUMBER
LEFT JOIN {{ ref('B2B_REGION') }} AS R
ON PS.SITE_NUMBER = R.SITE_NUMBER
LEFT JOIN (
    SELECT
    *
    FROM
    {{ source('RAW_COEX_AGILOFT', 'AG_LOCATION') }} AS AG
    QUALIFY ROW_NUMBER() OVER (PARTITION BY AG.SCHEME_SITE_ID ORDER BY AG.DATE_UPDATED DESC) = 1
) AG
ON AG.SCHEME_SITE_ID = CASE WHEN R_TT.VALUE LIKE '%CCSP%' THEN 'QC'||RIGHT(PS.SITE_NUMBER, 8) ELSE PS.SITE_NUMBER END
AND AG.LOCATION_TYPE LIKE '%CRP%' AND AG.DEMO_DATA = 'No'
LEFT JOIN (
    SELECT
    INVOICE_TYPE,
    PAYMENT_GROUP AS INVOICE_PAYMENT_GROUP,
    VALUE AS INV_PAYMENT_TERMS
    FROM {{ source('CES_MSCM', 'INV_PAYMENT_TERMS_LOV') }} AS INPT
    WHERE INPT.INVOICE_TYPE = 'AP'
    AND INPT.SCHEME_PARTICIPANT_TYPE = 'CRP'
    AND INPT.PAYMENT_GROUP = 'COLLECTION_FEES'
) PT
WHERE PS.SITE_TYPE_ID IN ('1538', '2591', '2688')
AND NVL(CC.RN,1) = 1
 
UNION ALL
 
