SELECT
L.MULTI_SCHEME_ID  AS MULTI_SCHEME_ID 
, SCHEME.NAME AS SCHEME
, LM.ID AS ID
, L.ID AS LOT_ITEM_ID
, LM.ACTUAL_WEIGHT_KGS AS MANIFEST_WEIGHT_KG
, LM.ACTUAL_BLOCKS AS ACTUAL_BLOCKS
, LM.CARRIER AS CARRIER
, LM.CONSIGNMENT_NO AS CONSIGNMENT_NO
, LM.REGISTRATION_NO AS REGISTRATION_NO
, LM.TRANSPORT_UNIT_TYPE AS TRANSPORT_UNIT_TYPE
, LM.TRANSPORT_UNIT_COUNT AS TRANSPORT_UNIT_COUNT
, CASE WHEN LM.FINAL_MANIFEST = 1 THEN 'Yes' else 'No' end AS FINAL_MANIFEST
, LM.EMPTY_TRUCK_WEIGHT AS EMPTY_TRUCK_WEIGHT
, LM.EMPTY_CONTAINER_WEIGHT AS EMPTY_CONTAINER_WEIGHT
, LM.TOTAL_TRUCK_WEIGHT AS TOTAL_TRUCK_WEIGHT
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(LM.MANIFEST_DATE AS TIMESTAMP))  AS MANIFEST_DATE
, TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(LM.MANIFEST_DATE AS TIMESTAMP)),'YYYYMMDD') AS MANIFEST_DATE_KEY
, D.ID AS DELIVERY_ID
, D.FINAL_ADDRESS AS FINAL_ADDRESS
, D.FINAL_SUBURB AS FINAL_SUBURB
, D.FINAL_STATE AS FINAL_STATE
, D.FINAL_COUNTRY AS FINAL_COUNTRY
, D.FINAL_POST_CODE AS FINAL_POST_CODE
, D.FINAL_PHONE_NUMBER AS FINAL_PHONE_NUMBER
, D.DELIVERY_ADDRESS AS DELIVERY_ADDRESS
, D.DELIVERY_SUBURB AS DELIVERY_SUBURB
, D.DELIVERY_STATE AS DELIVERY_STATE
, D.DELIVERY_COUNTRY AS DELIVERY_COUNTRY
, D.DELIVERY_POST_CODE AS DELIVERY_POST_CODE
, D.DELIVERY_PHONE_NUMBER AS DELIVERY_PHONE_NUMBER
, LM.MANIFEST_DATE AS MANIFEST_DATE_UTC
, LM.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, LM.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, D.CREATED_BY AS DELIVERY_CREATED_BY
, D.CREATED_ON AS DELIVERY_CREATED_ON_UTC
, D.LAST_MODIFIED_BY AS DELIVERY_LAST_MODIFIED_BY
, D.LAST_MODIFIED_ON AS DELIVERY_LAST_MODIFIED_ON_UTC
, CASE WHEN D.FINAL_STATE = 'EXP' THEN 'Yes' ELSE 'No' END AS EXPORT_FLAG
, COALESCE(L.SCHEME_MATERIAL_TYPE_ID,L.MRF_MATERIAL_TYPE_ID) AS MATERIAL_TYPE_ID
, CASE WHEN DATEADD(DAY,1,D.LAST_MODIFIED_ON)>=SYSDATE()  THEN 'Y' ELSE 'N' END AS MODIFIED_ON_LAST_1_DAY_EXTRACT
, CASE WHEN DATEADD(DAY,1,D.LAST_MODIFIED_ON)>=SYSDATE() AND hour(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,sysdate())) >= 12 THEN 'Y' ELSE 'N' END AS MODIFIED_ON_LAST_1_DAY
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(D.LAST_MODIFIED_ON AS TIMESTAMP))  AS DELIVERY_LAST_MODIFIED_ON
, CASE WHEN LM.NOTE IS NOT NULL THEN 'Yes' ELSE 'No' END AS ADJUSTMENT_FLAG
, LM.NOTE AS LAST_ADJUSTMENT_NOTE
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM', 'LOT_ITEM_MANIFEST') }} AS LM
FULL JOIN {{ source('CES_MSCM', 'LOT_ITEM_DELIVERY') }} AS D
ON LM.LOT_ITEM_ID = D.LOT_ITEM_ID
LEFT JOIN {{ source('CES_MSCM', 'LOT_ITEM') }} AS L
ON COALESCE(LM.LOT_ITEM_ID,D.LOT_ITEM_ID) = L.ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON L.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID