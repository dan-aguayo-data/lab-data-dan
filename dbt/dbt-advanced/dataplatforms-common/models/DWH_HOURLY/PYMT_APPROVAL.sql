SELECT
PN.MULTI_SCHEME_ID  AS MULTI_SCHEME_ID 
, CAST(PA.SOURCE_ID AS VARCHAR(25)) AS ID
, 'PYMT_TRXN_HEADER_ID' AS ID_TYPE
, PA.APPROVAL_ID AS APPROVAL_ID
, PA.STATUS AS STATUS
, PN.ASSIGNED_TO AS ASSIGNED_TO
, CU_CA.LOGIN_ID AS LOGIN_ID
, max(cast(n.pcs_id as int)) over (partition by pa.source_id) AS PCS_ID
, PN.CREATED_ON AS CREATED_ON_UTC
, CASE WHEN PN.UPDATED_ON > PA.UPDATED_ON THEN PN.UPDATED_ON ELSE PA.UPDATED_ON END AS LAST_MODIFIED_ON_UTC
, CA.LAST_MODIFIED_ON_SYD AS LAST_MODIFIED_ON_SYD
, SYSDATE() AS INSERT_DATE_UTC
, row_number() over (partition by pa.source_id order by pn.notification_id desc) AS RECENT
FROM
{{ source('CES_MSCM', 'PYMT_NOTIFICATIONS') }} AS PN
INNER JOIN {{ source('CES_MSCM', 'PYMT_APPROVALS') }} AS  PA
ON PA.APPROVAL_ID = PN.APPROVAL_ID
AND APP_ORDER = 2 
INNER JOIN {{ source('CES_MSCM', 'CUSTOM_USER') }} AS CU
ON PN.ASSIGNED_TO = CU.ID
INNER JOIN (
    SELECT 
    APPROVAL_ID
    , MAX(CAST(NULLIF(PCS_ID,'') AS INT)) AS PCS_ID 
    FROM {{ source('CES_MSCM', 'PYMT_NOTIFICATIONS') }} AS PYMT_N
    WHERE APP_ORDER = 1 
    AND PCS_ID IS NOT NULL
    GROUP BY APPROVAL_ID
) N
ON PA.APPROVAL_ID = N.APPROVAL_ID
LEFT JOIN (
    SELECT 
    C.APPROVAL_ID
    , C.ASSIGNED_TO
    , C.LAST_MODIFIED_ON_SYD
    FROM (
        SELECT
        N.APPROVAL_ID
        , N.ASSIGNED_TO
        , CONVERT_TIMEZONE('UTC', 'Australia/Sydney', N.UPDATED_ON) AS LAST_MODIFIED_ON_SYD
        , ROW_NUMBER() OVER (PARTITION BY N.APPROVAL_ID ORDER BY N.UPDATED_ON DESC) AS N
        FROM {{ source('CES_MSCM', 'PYMT_NOTIFICATIONS') }} AS N
        WHERE PCS_ID IS NOT NULL
    ) C
    WHERE C.N = 1
) CA
ON PA.APPROVAL_ID = CA.APPROVAL_ID
LEFT JOIN {{ source('CES_MSCM', 'CUSTOM_USER') }} AS CU_CA
ON CA.ASSIGNED_TO = CU_CA.ID
UNION ALL
SELECT
PN.MULTI_SCHEME_ID  AS MULTI_SCHEME_ID 
, H.POS_TXN_NUM AS ID
, 'POS_TXN_NUM' AS ID_TYPE
, PA.APPROVAL_ID AS APPROVAL_ID
, PA.STATUS AS STATUS
, PN.ASSIGNED_TO AS ASSIGNED_TO
, CU_CA.LOGIN_ID AS LOGIN_ID
, max(cast(n.pcs_id as int)) over (partition by H.POS_TXN_NUM) AS PCS_ID
, PN.CREATED_ON AS CREATED_ON_UTC
, CASE WHEN PN.UPDATED_ON > PA.UPDATED_ON THEN PN.UPDATED_ON ELSE PA.UPDATED_ON END AS LAST_MODIFIED_ON_UTC
, CA.LAST_MODIFIED_ON_SYD AS LAST_MODIFIED_ON_SYD
, SYSDATE() AS INSERT_DATE_UTC
, row_number() over (partition by H.POS_TXN_NUM order by pn.notification_id desc) AS RECENT
FROM
{{ source('CES_MSCM', 'PYMT_NOTIFICATIONS') }} AS PN
INNER JOIN {{ source('CES_MSCM', 'PYMT_APPROVALS') }} AS  PA
ON PA.APPROVAL_ID = PN.APPROVAL_ID
AND APP_ORDER = 2 
INNER JOIN  {{ source('CES_MSCM', 'CUSTOM_USER') }} AS  CU
ON PN.ASSIGNED_TO = CU.ID
INNER JOIN {{ source('CES_MSCM', 'PYMT_TRANSACTION_HEADERS') }} AS H
ON H.PYMT_TRXN_HEADER_ID = PA.SOURCE_ID
INNER JOIN {{ source('CES_MSCM', 'PYMT_PAYMENT_STATUS') }} AS S
ON H.PYMT_TRXN_HEADER_ID = S.PYMT_TRXN_HEADER_ID
AND S.STATUS IN('REPROCESS', 'FAILED PAYPAL BATCH CREATION') 
INNER JOIN (
    SELECT 
    APPROVAL_ID
    , MAX(CAST(NULLIF(PCS_ID,'') AS INT)) AS PCS_ID 
    FROM {{ source('CES_MSCM', 'PYMT_NOTIFICATIONS') }} AS PYMT_N
    WHERE APP_ORDER = 1 
    AND PCS_ID IS NOT NULL 
    GROUP BY APPROVAL_ID
) N
ON PA.APPROVAL_ID = N.APPROVAL_ID
LEFT JOIN (
    SELECT 
    C.APPROVAL_ID
    , C.ASSIGNED_TO
    , C.LAST_MODIFIED_ON_SYD
    FROM (
        SELECT
        N.APPROVAL_ID
        , N.ASSIGNED_TO
        , CONVERT_TIMEZONE('UTC', 'Australia/Sydney', N.UPDATED_ON) AS LAST_MODIFIED_ON_SYD
        , ROW_NUMBER() OVER (PARTITION BY N.APPROVAL_ID ORDER BY N.UPDATED_ON DESC) AS N
        FROM {{ source('CES_MSCM', 'PYMT_NOTIFICATIONS') }} AS N
        WHERE PCS_ID IS NOT NULL
    ) C
    WHERE C.N = 1
) CA
ON PA.APPROVAL_ID = CA.APPROVAL_ID
LEFT JOIN {{ source('CES_MSCM', 'CUSTOM_USER') }} AS CU_CA
ON CA.ASSIGNED_TO = CU_CA.ID