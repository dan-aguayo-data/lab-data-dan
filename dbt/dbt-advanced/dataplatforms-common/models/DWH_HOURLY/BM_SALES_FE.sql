WITH BASE AS (
SELECT
L.MULTI_SCHEME_ID
, L.MANUFACTURER_ID AS SITE_NUMBER
, L.MATERIAL_TYPE_ID
, L.YEAR_MONTH
, L.PERIOD_KEY
, BM.PERIOD
, BM.ENTRY_TYPE
, BM.VOLUME
, BM.SUBMITTED_DATE_UTC
, PS.TAXONOMY_SUB_TYPE
, CASE WHEN PS.TAXONOMY_SUB_TYPE = 'Manufacturer - Large' THEN L.YEAR_MONTH WHEN PS.TAXONOMY_SUB_TYPE = 'Manufacturer - Small' THEN LEFT(L.YEAR_MONTH, 4) || '-' || DECODE(RIGHT(L.YEAR_MONTH, 2), '01', '03', '02', '03', '03', '03', '04', '06', '05', '06', '06', '06', '07', '09', '08', '09', '09', '09', '10', '12', '11', '12', '12', '12') WHEN PS.TAXONOMY_SUB_TYPE = 'Manufacturer - Micro' THEN CASE WHEN RIGHT(L.YEAR_MONTH, 2) BETWEEN '01' AND '06' THEN LEFT(L.YEAR_MONTH, 4) || '-' || '06' WHEN RIGHT(L.YEAR_MONTH, 2) BETWEEN '07' AND '12' THEN TO_NUMBER(LEFT(L.YEAR_MONTH, 4) + 1) || '-' || '06' ELSE NULL END ELSE NULL END AS YEAR_MONTH_FOR_CALCULATION
FROM (
    SELECT
    DT.YEAR_MONTH
    , DT.KEY AS PERIOD_KEY
    , HDR.MULTI_SCHEME_ID
    , HDR.MANUFACTURER_ID
    , MT.MATERIAL_TYPE_ID
    FROM (
        SELECT
        *
        FROM {{ ref('REF_DATE') }} AS D
        WHERE DAY = 1
        AND YEAR >= 2019
        AND YEAR <= YEAR(SYSDATE()) + 1
    ) DT
    CROSS JOIN (
        SELECT
        MULTI_SCHEME_ID
        , ID AS MATERIAL_TYPE_ID
        FROM {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS MT
    ) MT
    CROSS JOIN (
        SELECT DISTINCT
        H.MULTI_SCHEME_ID
        , H.MANUFACTURER_ID
        FROM {{ source('CES_MSCM', 'MFG_SALES_VOLUME_HDR') }} AS H
    ) HDR
    WHERE MT.MULTI_SCHEME_ID = HDR.MULTI_SCHEME_ID
) L
LEFT JOIN (
    SELECT
    HDR.MULTI_SCHEME_ID
    , HDR.MANUFACTURER_ID
    , HDR.PERIOD
    , HDR.ENTRY_TYPE
    , HDR.SUBMITTED_DATE AS SUBMITTED_DATE_UTC
    , DTL.MATERIAL_TYPE_ID
    , DTL.VOLUME
    FROM {{ source('CES_MSCM', 'MFG_SALES_VOLUME_HDR') }} AS HDR
    INNER JOIN {{ source('CES_MSCM', 'MFG_SALES_VOLUME_DTL') }} AS DTL
    ON HDR.ID = DTL.MFG_SALES_VOLUME_HDR_ID
    WHERE HDR.ENTRY_TYPE IN ('R', 'L', 'H')
    AND HDR.STATUS IN ('INVOICED', 'FINAL', 'HISTORIC')
) BM
ON L.MULTI_SCHEME_ID = BM.MULTI_SCHEME_ID
AND L.MANUFACTURER_ID = BM.MANUFACTURER_ID
AND L.YEAR_MONTH = BM.PERIOD
AND L.MATERIAL_TYPE_ID = BM.MATERIAL_TYPE_ID
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS
ON L.MANUFACTURER_ID = PS.SITE_NUMBER
)
 
SELECT
B1.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, B1.SITE_NUMBER || '-' || B1.PERIOD_KEY || '-' || B1.MATERIAL_TYPE_ID AS ID
, B1.SITE_NUMBER AS SITE_NUMBER
, B1.YEAR_MONTH AS PERIOD
, B1.PERIOD_KEY AS PERIOD_KEY
, B1.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID
, MT.NAME AS MATERIAL_TYPE
, COUNT(B2.PERIOD) AS COUNT_N
, AVG(B2.VOLUME) AS AVG_VOLUME
, AVG(B2.VOLUME * SI.VALUE) AS FORECAST_VOLUME
, AVG(B2.VOLUME * SI.VALUE * SP.SCHEME_PRICE) AS FORECAST_GROSS_AMOUNT
, 'FE' AS ENTRY_TYPE
, 'FINAL-FE' AS STATUS
, SYSDATE() AS INSERT_DATE_UTC
FROM
BASE B1
LEFT JOIN BASE B2
ON B1.MULTI_SCHEME_ID = B2.MULTI_SCHEME_ID
AND B1.SITE_NUMBER = B2.SITE_NUMBER
AND B1.MATERIAL_TYPE_ID = B2.MATERIAL_TYPE_ID
AND B2.YEAR_MONTH 
    BETWEEN CASE WHEN RIGHT(B1.YEAR_MONTH_FOR_CALCULATION, 2) = '12' THEN LEFT(B1.YEAR_MONTH_FOR_CALCULATION, 4) || '-01' ELSE TO_NUMBER(LEFT(B1.YEAR_MONTH_FOR_CALCULATION, 4) - 1) || '-' || TO_CHAR(RIGHT(B1.YEAR_MONTH_FOR_CALCULATION, 2) + 1, 'FM00') END
    AND CASE WHEN B1.TAXONOMY_SUB_TYPE =  'Manufacturer - Large' OR B2.ENTRY_TYPE = 'L' THEN CASE WHEN RIGHT(B1.YEAR_MONTH_FOR_CALCULATION, 2) = '01' THEN TO_NUMBER(LEFT(B1.YEAR_MONTH_FOR_CALCULATION, 4) - 1) || '-12' ELSE LEFT(B1.YEAR_MONTH_FOR_CALCULATION, 4) || '-' || TO_CHAR(RIGHT(B1.YEAR_MONTH_FOR_CALCULATION, 2) - 1, 'FM00') END ELSE B1.YEAR_MONTH_FOR_CALCULATION END
LEFT JOIN {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS MT
ON B1.MATERIAL_TYPE_ID = MT.ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON B1.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN (
    SELECT
    MULTI_SCHEME_ID
    , MATERIAL_TYPE_ID
    , VALUE
    , TO_CHAR(EFFECTIVE_FROM, 'YYYYMMDD') AS PERIOD_KEY --There is no data for EFFECTIVE_TO. So use EFFECTIVE_FROM as the period.
    FROM
    {{ source('CES_MSCM', 'SEASONALITY_INDEX_REFERENCE') }} AS I
) SI
ON B1.MULTI_SCHEME_ID = SI.MULTI_SCHEME_ID
AND B1.MATERIAL_TYPE_ID = SI.MATERIAL_TYPE_ID
AND B1.PERIOD_KEY = SI.PERIOD_KEY
LEFT JOIN (
    SELECT
    MULTI_SCHEME_ID
    , MATERIAL_TYPE_ID
    , SCHEME_PRICE
    , TO_CHAR(EFFECTIVE_FROM, 'YYYYMMDD') AS PERIOD_KEY --There is no data for EFFECTIVE_TO. So use EFFECTIVE_FROM as the period.
    FROM
    {{ source('CES_MSCM', 'SCHEME_PRICE_REFERENCE') }} AS P
    QUALIFY ROW_NUMBER() OVER (PARTITION BY MULTI_SCHEME_ID, MATERIAL_TYPE_ID, PERIOD_KEY ORDER BY ID DESC) = 1 --remove duplicates
) SP
ON B1.MULTI_SCHEME_ID = SP.MULTI_SCHEME_ID
AND B1.MATERIAL_TYPE_ID = SP.MATERIAL_TYPE_ID
AND B1.PERIOD_KEY = SP.PERIOD_KEY
LEFT JOIN (
    SELECT
    P.MULTI_SCHEME_ID
    , P.PAYMENT_PERIOD_FLAG
    , MIN(P.BASE_RUN_ON) AS PE_RUN_ON_UTC
    , MAX(P.BASE_RUN_ON) AS MAX_PE_RUN_ON_UTC
    FROM(
        SELECT
        PT.MULTI_SCHEME_ID
        , PT.CREATED_ON AS BASE_RUN_ON
        , LEFT(PT.PAYMENT_PERIOD, 1) AS PAYMENT_PERIOD_FLAG
        , CASE WHEN LEFT(PT.PAYMENT_PERIOD, 1) = 'M' THEN SUBSTR(PT.PAYMENT_PERIOD, 2, 4) || RIGHT(PT.PAYMENT_PERIOD, 2) || '01' WHEN LEFT(PT.PAYMENT_PERIOD, 1) = 'Q' THEN SUBSTR(PT.PAYMENT_PERIOD, 2, 4) || DECODE(RIGHT(PT.PAYMENT_PERIOD, 1), '1', '0101', '2', '0401', '3', '0701', '4', '1001') WHEN LEFT(PT.PAYMENT_PERIOD, 1) = 'Y' THEN SUBSTR(PT.PAYMENT_PERIOD, 2, 4) ELSE NULL END AS PAYMENT_PERIOD_KEY
        , RANK() OVER (PARTITION BY PT.MULTI_SCHEME_ID, PAYMENT_PERIOD_FLAG ORDER BY PAYMENT_PERIOD_KEY DESC) AS RK
        FROM {{ source('CES_MSCM', 'PAYMENT_TRANSACTION_REC') }} AS PT
        WHERE PT.SCHEME_PARTICIPANT_TYPE = 'MANUFACTURER'
    ) P
    WHERE P.RK = 1
    GROUP BY ALL
) B
ON B2.MULTI_SCHEME_ID = B.MULTI_SCHEME_ID
AND (CASE WHEN B2.TAXONOMY_SUB_TYPE = 'Manufacturer - Large' THEN 'M' WHEN B2.TAXONOMY_SUB_TYPE = 'Manufacturer - Small' THEN 'Q' WHEN B2.TAXONOMY_SUB_TYPE = 'Manufacturer - Micro' THEN 'Y' END) = B.PAYMENT_PERIOD_FLAG
WHERE CASE WHEN B2.TAXONOMY_SUB_TYPE <> 'Manufacturer - Micro' THEN B2.SUBMITTED_DATE_UTC <= NVL(B.PE_RUN_ON_UTC, SYSDATE()) ELSE 1 END
GROUP BY ALL
HAVING COUNT_N >= 3