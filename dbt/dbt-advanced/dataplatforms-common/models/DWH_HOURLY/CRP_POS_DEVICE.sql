    config(
        materialized = 'incremental',
        incremental_strategy = 'merge',
        unique_key = 'ID',
        snowflake_warehouse= wh_selector_models("ETL_CES_DEV","ETL_CES_SIT","ETL_CES_UAT","ETL_CES_SMALL")
    )
}}


WITH INCREMENTAL_DATE_REF AS (

 SELECT DATEADD(HOUR, {{var('general_delta_load_hours')}} , SYSDATE()) AS INCREMENTAL_DELTA

), CRP_BAG_DROP_LABEL AS (
    SELECT
    BL.CREATED_BY
    , MAX(BL.GENERATED_ON) AS LAST_BAG_LABEL_ON
    FROM {{ ref('CRP_BAG_DROP_LABEL') }} AS BL
    GROUP BY
    BL.CREATED_BY


), CRP_COLLECTION_HDR AS (

    SELECT
    CH.POS_DEVICE_ID
    , MAX(CH.TRANSACTION_DATE) AS LAST_TRANSACTION_ON
    FROM {{ ref('CRP_COLLECTION_HDR') }} AS CH
    GROUP BY
    CH.POS_DEVICE_ID

), CES_DUMMY_DATA AS (

SELECT
-1 AS MULTI_SCHEME_ID
, 'CES' AS SCHEME
, '-' AS ID
, NULL AS CRP_SITE_NUMBER
, NULL AS CRP_SITE_NAME
, NULL AS SUPPLIER_NUMBER
, NULL AS SUPPLIER_NAME
, NULL AS NAME
, NULL AS TYPE
, NULL AS STATUS
, NULL AS SYNCED
, NULL AS CURRENT_VERSION
, NULL AS CURRENT_OS_VERSION
, NULL AS ENVIRONMENT
, NULL AS LATITUDE
, NULL AS LONGITUDE
, NULL AS LAST_HEARTBEAT_ON
, NULL AS LAST_BAG_LABEL_ON
, NULL AS LAST_TRANSACTION_ON
, NULL AS LAST_DATE
, NULL AS POS_FLAG
, TO_DATE('01/01/2021', 'DD/MM/YYYY') AS CREATED_ON
, NULL AS CREATED_BY
, TO_DATE('01/01/2021', 'DD/MM/YYYY') AS CREATED_ON_UTC
, NULL AS LAST_MODIFIED_BY
, TO_DATE('01/01/2021', 'DD/MM/YYYY') AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC

), POS_DEVICE_HEARTBEAT as (

SELECT * 
FROM  {{ ref('CRP_POS_DEVICE_HEARTBEAT') }} AS H
WHERE  H.LAST_MODIFIED_ORDER = 1


{% if is_incremental() %} 

), POS_DEVICE_MODIFIED AS (

SELECT DISTINCT
PD.ID AS ID
FROM
{{ source('CES_MSCM', 'POS_DEVICE') }} AS PD
LEFT JOIN POS_DEVICE_HEARTBEAT AS H
ON PD.ID = H.POS_DEVICE_ID
LEFT JOIN CRP_BAG_DROP_LABEL L
ON PD.ID = L.CREATED_BY
LEFT JOIN CRP_COLLECTION_HDR C
ON PD.ID = C.POS_DEVICE_ID
WHERE 
(PD.LAST_MODIFIED_ON >= (SELECT INCREMENTAL_DELTA FROM INCREMENTAL_DATE_REF)
OR H.LAST_MODIFIED_ON_UTC>= (SELECT INCREMENTAL_DELTA FROM INCREMENTAL_DATE_REF)
OR C.LAST_TRANSACTION_ON >= (SELECT INCREMENTAL_DELTA FROM INCREMENTAL_DATE_REF)
OR  L.LAST_BAG_LABEL_ON  >= (SELECT INCREMENTAL_DELTA FROM INCREMENTAL_DATE_REF)
)

{% endif %}
)

SELECT
PD.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, PD.ID AS ID
, PD.CRP_ID AS CRP_SITE_NUMBER
, PS.SITE_NAME AS CRP_SITE_NAME
, P.PARTICIPANT_NUMBER AS SUPPLIER_NUMBER
, P.PARTICIPANT_NAME AS SUPPLIER_NAME
, PD.NAME AS NAME
, PD.TYPE AS TYPE
, PD.STATUS AS STATUS
, PD.SYNCED AS SYNCED
, NVL(H.VERSION, '-') AS CURRENT_VERSION
, NVL(H.OS_VERSION, '-') AS CURRENT_OS_VERSION
, H.ENVIRONMENT AS ENVIRONMENT
, H.LATITUDE AS LATITUDE
, H.LONGITUDE AS LONGITUDE
, H.LAST_MODIFIED_ON AS LAST_HEARTBEAT_ON
, L.LAST_BAG_LABEL_ON AS LAST_BAG_LABEL_ON
, C.LAST_TRANSACTION_ON AS LAST_TRANSACTION_ON
, GREATEST(NVL(H.LAST_MODIFIED_ON, TO_TIMESTAMP('19000101','YYYYMMDD')) , NVL(L.LAST_BAG_LABEL_ON, TO_TIMESTAMP('19000101','YYYYMMDD')), NVL(C.LAST_TRANSACTION_ON, TO_TIMESTAMP('19000101','YYYYMMDD'))) AS LAST_DATE
, CASE WHEN L.LAST_BAG_LABEL_ON IS NOT NULL THEN 'Bag Drop' WHEN C.LAST_TRANSACTION_ON IS NOT NULL THEN 'Transactional' ELSE 'Not Use' END AS POS_FLAG
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(PD.CREATED_ON AS TIMESTAMP)) AS CREATED_ON
, PD.CREATED_BY AS CREATED_BY
, PD.CREATED_ON AS CREATED_ON_UTC
, PD.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, PD.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM', 'POS_DEVICE') }} AS PD
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS
ON PD.CRP_ID = PS.SITE_NUMBER
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANTS') }} AS P
ON PS.PARTICIPANT_ID = P.PARTICIPANT_ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON PD.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN POS_DEVICE_HEARTBEAT AS H
ON PD.ID = H.POS_DEVICE_ID
LEFT JOIN CRP_BAG_DROP_LABEL L
ON PD.ID = L.CREATED_BY
LEFT JOIN CRP_COLLECTION_HDR C
ON PD.ID = C.POS_DEVICE_ID
{% if is_incremental() %} 
INNER JOIN POS_DEVICE_MODIFIED MOD 
ON PD.ID = MOD.ID
{% endif %}
{% if target.name | upper in ['DEV', 'UAT'] %}  --in dev and uat we have pos_device_id's that have more than one name.. this behaviour deosn't exist in prod, it is only 1 to 1

WHERE PD.ID NOT IN ( 
      SELECT POS_DEVICE_ID
  FROM {{ ref('CRP_POS_DEVICE_HEARTBEAT') }}
  GROUP BY POS_DEVICE_ID
  HAVING COUNT(DISTINCT NAME) > 1
)
{% endif %} 

{% if not is_incremental() %} 
UNION ALL

SELECT * FROM CES_DUMMY_DATA

{% endif %}