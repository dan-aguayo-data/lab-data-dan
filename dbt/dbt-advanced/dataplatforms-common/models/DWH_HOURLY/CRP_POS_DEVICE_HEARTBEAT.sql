SELECT
NVL(PD.MULTI_SCHEME_ID, PS.MULTI_SCHEME_ID) AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, PD.ID AS ID
, PD.DEVICE_ID AS POS_DEVICE_ID
, PD.VERSION AS VERSION
, PD.NAME AS NAME
, PD.ENVIRONMENT AS ENVIRONMENT
, PD.TYPE AS TYPE
, PD.OS_VERSION AS OS_VERSION
, PD.IP_ADDRESS AS IP_ADDRESS
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(PD.LAST_MODIFIED_ON AS TIMESTAMP)) AS LAST_MODIFIED_ON
, ROW_NUMBER() OVER (PARTITION BY PD.NAME ORDER BY PD.LAST_MODIFIED_ON DESC, PD.CREATED_ON DESC) AS LAST_MODIFIED_ORDER
, PD.CRP_ID AS CRP_SITE_NUMBER
, PD.LONGITUDE AS LONGITUDE
, PD.LATITUDE AS LATITUDE
, PD.CREATED_BY AS CREATED_BY
, PD.CREATED_ON AS CREATED_ON_UTC
, PD.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, PD.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM', 'POS_DEVICE_HEARTBEAT') }} AS PD
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS
ON PD.CRP_ID = PS.SITE_NUMBER
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON NVL(PD.MULTI_SCHEME_ID, PS.MULTI_SCHEME_ID) = SCHEME.MULTI_SCHEME_ID


