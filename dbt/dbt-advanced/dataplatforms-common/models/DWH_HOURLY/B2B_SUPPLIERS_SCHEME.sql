SELECT
PS.MULTI_SCHEME_ID  AS MULTI_SCHEME_ID 
, SCHEME.NAME AS SCHEME
, PS.MULTI_SCHEME_ID || '-' || P.PARTICIPANT_NUMBER AS ID
, P.PARTICIPANT_NUMBER AS SUPPLIER_NUMBER
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM', 'MDT_PARTICIPANTS') }} AS P
INNER JOIN (
    SELECT
    S.PARTICIPANT_ID
    , S.MULTI_SCHEME_ID
    FROM {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS S
    WHERE S.SITE_TYPE_ID != '1537'
    GROUP BY S.PARTICIPANT_ID, S.MULTI_SCHEME_ID
) PS
ON PS.PARTICIPANT_ID = P.PARTICIPANT_ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON PS.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID