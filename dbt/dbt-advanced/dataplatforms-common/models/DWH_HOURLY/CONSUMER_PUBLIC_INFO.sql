SELECT
PS.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, PS.SITE_NUMBER AS CONSUMER_ID
, PI.DESCRIPTION AS DESCRIPTION
, PI.CATEGORIES AS CATEGORIES
, PI.CATEGORY_CODES AS CATEGORY_CODES
, PI.CATEGORY_NAMES AS CATEGORY_NAMES
, PI.PHONE_NUMBER AS PHONE_NUMBER
, PI.EMAIL_ADDRESS AS EMAIL_ADDRESS
, PI.WEB_SITE_URL AS WEB_SITE_URL
, CASE WHEN PI.PUBLIC_WEBSITE_CONSENT IN ('1', 'Y') THEN 'Y' ELSE 'N' END AS PUBLIC_WEBSITE_CONSENT
, CASE WHEN PI.ACTIVE_FLAG IN ('1', 'Y') THEN 'Y' ELSE 'N' END AS ACTIVE_FLAG
, PI.CREATED_BY AS CREATED_BY
, PI.CREATED_ON AS CREATED_ON_UTC
, PI.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, PI.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_DRUPAL', 'CONSUMER_PUBLIC_INFO') }} AS PI
INNER JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS
ON PS.PARTICIPANT_ID = PI.PARTICIPANT_ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON PS.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
QUALIFY ROW_NUMBER() OVER (PARTITION BY PI.PARTICIPANT_ID ORDER BY PI.CONSUMER_PUBLIC_INFO_ID DESC) = 1