SELECT
V.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, V.SCHEME AS SCHEME
, V.ID AS ID
, V.BM_SALES_VOLUME_HDR_ID AS BM_SALES_VOLUME_HDR_ID
, V.SITE_NUMBER AS SITE_NUMBER
, V.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID
, V.MATERIAL_TYPE AS MATERIAL_TYPE
, NULL AS AVG_VOLUME
, V.VOLUME AS VOLUME
, V.VOLUME * SP.SCHEME_PRICE AS GROSS_AMOUNT
, V.VOLUME_HEADER AS VOLUME_HEADER
, V.UOM AS UOM
, V.PERIOD AS PERIOD
, V.PERIOD_KEY AS PERIOD_KEY
, V.PERIOD_TYPE AS PERIOD_TYPE
, V.ENTRY_TYPE AS ENTRY_TYPE
, V.STATUS AS STATUS
, V.SUBMITTED_DATE AS SUBMITTED_DATE
, V.SUBMITTED_DATE_KEY AS SUBMITTED_DATE_KEY
, V.SUBMITTED_BY AS SUBMITTED_BY
, V.SUBMITTED_DATE_UTC AS SUBMITTED_DATE_UTC
, V.SS_AUDIT_ADJUSTMENT_ID AS SS_AUDIT_ADJUSTMENT_ID
, V.ADJUSTMENT_REASON AS ADJUSTMENT_REASON
, V.CREATED_BY AS CREATED_BY
, V.CREATED_ON_UTC AS CREATED_ON_UTC
, V.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, V.LAST_MODIFIED_ON_UTC AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ ref('BM_SALES_VOLUME') }} AS V
LEFT JOIN (
    SELECT
    MULTI_SCHEME_ID
    , MATERIAL_TYPE_ID
    , SCHEME_PRICE
    , TO_CHAR(EFFECTIVE_FROM, 'YYYYMMDD') AS PERIOD_KEY --There is no data for EFFECTIVE_TO. So use EFFECTIVE_FROM as the period.
    FROM
    {{ source('CES_MSCM', 'SCHEME_PRICE_REFERENCE') }} AS P
    QUALIFY ROW_NUMBER() OVER (PARTITION BY MULTI_SCHEME_ID, MATERIAL_TYPE_ID, PERIOD_KEY ORDER BY ID DESC) = 1 --remove duplicates
) SP
ON V.MULTI_SCHEME_ID = SP.MULTI_SCHEME_ID
AND V.MATERIAL_TYPE_ID = SP.MATERIAL_TYPE_ID
AND V.PERIOD_KEY = SP.PERIOD_KEY
 
UNION ALL
 
SELECT
FE.MULTI_SCHEME_ID
, FE.SCHEME
, FE.ID
, NULL AS BM_SALES_VOLUME_HDR_ID
, FE.SITE_NUMBER
, FE.MATERIAL_TYPE_ID
, FE.MATERIAL_TYPE
, FE.AVG_VOLUME
, FE.FORECAST_VOLUME AS VOLUME
, FE.FORECAST_GROSS_AMOUNT AS GROSS_AMOUNT
, 'Volume' AS VOLUME_HEADER
, 'UNIT' AS UOM
, FE.PERIOD
, FE.PERIOD_KEY
, 'M' AS PERIOD_TYPE
, 'FE' AS ENTRY_TYPE
, FE.STATUS
, NULL AS SUBMITTED_DATE
, NULL AS SUBMITTED_DATE_KEY
, NULL AS SUBMITTED_BY
, NULL AS SUBMITTED_DATE_UTC
, NULL AS SS_AUDIT_ADJUSTMENT_ID
, NULL AS ADJUSTMENT_REASON
, 'FE' AS CREATED_BY
, TO_TIMESTAMP(FE.PERIOD_KEY, 'YYYYMMDD') AS CREATED_ON_UTC
, 'FE' AS LAST_MODIFIED_BY
, SYSDATE() AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM {{ ref('BM_SALES_FE') }} AS FE