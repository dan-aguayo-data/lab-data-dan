SELECT
H.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, H.SCHEME AS SCHEME
, CONCAT_WS('-', H.SITE_NUMBER, H.TRANSACTION_DATE_KEY, H.PAYMENT_METHOD, H.PAYMENT_TYPE, H.CONSUMER_TYPE, H.SCHEME_CONSUMER_FLAG, H.TRANSACTION_BANDING) AS ID
, H.SITE_NUMBER AS SITE_NUMBER
, H.TRANSACTION_DATE_KEY AS TRANSACTION_DATE_KEY
, H.PAYMENT_METHOD AS PAYMENT_METHOD
, H.PAYMENT_TYPE AS PAYMENT_TYPE
, H.CONSUMER_TYPE AS CONSUMER_TYPE
, H.SCHEME_CONSUMER_FLAG AS SCHEME_CONSUMER_FLAG
, H.TRANSACTION_BANDING AS TRANSACTION_BANDING
, COUNT(H.TRANSACTION_ID) AS TOTAL_TRANSACTIONS
, SUM(H.COLLECTION_QTY) AS TOTAL_QTY
, SUM(H.COLLECTION_QTY_INELIGIBLE) AS TOTAL_QTY_INELIGIBLE
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ ref('CRP_COLLECTION_HDR') }} AS H
GROUP BY ALL