SELECT
S.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, S.SCHEME_REF_CODES_ID AS ID
, S.CODE AS CODE
, S.VALUE AS VALUE
, S.CATEGORY AS CATEGORY
, S.DESCRIPTION AS DESCRIPTION
, S.EFFECTIVE_FROM AS EFFECTIVE_FROM_UTC
, S.EFFECTIVE_TO AS EFFECTIVE_TO_UTC
, S.CREATED_BY AS CREATED_BY
, S.CREATED_ON AS CREATED_ON_UTC
, S.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, S.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, S.ROW_EDITING_ENABLED AS ROW_EDITING_ENABLED
, S.ROW_DISPLAY_ENABLED AS ROW_DISPLAY_ENABLED
FROM {{ source('CES_MSCM', 'SCHEME_REF_CODES') }} AS S
LEFT JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON S.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID