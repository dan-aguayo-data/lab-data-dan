SELECT
O.SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, L.TRIP_LEG_ID AS TRIP_LEG_ID
, L.LEG_SEQUENCE AS LEG_SEQUENCE
, O.SCHEME_PARTICIPANT_ID AS LSP_SITE_NUMBER
, O.SUPPLIER_NUMBER AS LSP_SUPPLIER_NUMBER
, COALESCE(L.VEHICLE_ID,T.VEHICLE_ID,-1) AS VEHICLE_ID
, NVL(L.DRIVER_ID,T.PERSON_ID) AS DRIVER_ID
, FMTP.FIRST_NAME || ' ' || FMTP.LAST_NAME AS DRIVER_NAME
, L.TRIP_ID AS TRIP_ID
, TG.TRIP_GROUP AS TRIP_GROUP
, CASE WHEN TG.TRIP_GROUP IS NULL OR NVL(C.LEG_TYPE,'Others') = 'Others' THEN NULL ELSE ROW_NUMBER() OVER (PARTITION BY (CASE WHEN NVL(C.LEG_TYPE,'Others') = 'Others' THEN NULL ELSE TG.TRIP_GROUP END) ORDER BY  L.LEG_SEQUENCE) END AS GROUP_SEQUENCE
, CASE WHEN C.LEG_TYPE IS NULL OR C.LEG_TYPE = 'Others' THEN 'Others' ELSE C.LEG_TYPE END AS LEG_TYPE
, CASE WHEN TG.TRIP_GROUP IS NULL OR NVL(C.LEG_TYPE,'Others') = 'Others' THEN 0 ELSE 1 END AS EXCEPTION_FLAG
, R_LS.VALUE AS LEG_STATUS
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(L.SCHEDULED_START AS TIMESTAMP)) AS SCHEDULED_START
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(L.SCHEDULED_END AS TIMESTAMP)) AS SCHEDULED_END
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(L.ACTUAL_START AS TIMESTAMP)) AS ACTUAL_START
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(L.ACTUAL_END AS TIMESTAMP)) AS ACTUAL_END
, TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(L.ACTUAL_START AS TIMESTAMP)), 'YYYYMMDD') AS ACTUAL_START_KEY
, NVL(DATEDIFF('S', L.ACTUAL_START, L.ACTUAL_END), 0)/60 AS TOTAL_TIME
, S.TOTAL_STOP_TIME AS BREAK_TIME
, NVL(DATEDIFF('S', L.ACTUAL_START, L.ACTUAL_END), 0)/60 - NVL(S.TOTAL_STOP_TIME, 0) AS TRAVEL_TIME
, NVL(DATEDIFF('S', L.SCHEDULED_START, L.SCHEDULED_END), 0)/60 AS SCHEDULED_TRAVEL_TIME
, TO_CHAR(TRUNC((NVL(DATEDIFF('S', L.ACTUAL_START, L.ACTUAL_END), 0)/60 - NVL(S.TOTAL_STOP_TIME, 0))/60),'FM00') || ':' ||TO_CHAR(ROUND(MOD((NVL(DATEDIFF('S', L.ACTUAL_START, L.ACTUAL_END), 0)/60 - NVL(S.TOTAL_STOP_TIME, 0)),60)), 'FM00') AS TRAVEL_TIME_FORMATTED
, TO_CHAR(TRUNC((NVL(DATEDIFF('S', L.SCHEDULED_START, L.SCHEDULED_END), 0)/60)/60),'FM00') || ':' ||TO_CHAR(ROUND(MOD((NVL(DATEDIFF('S', L.SCHEDULED_START, L.SCHEDULED_END), 0)/60),60)), 'FM00') AS SCHEDULED_TRAVEL_TIME_FORMATTED
, NVL(DATEDIFF('S', L.ACTUAL_START, L.ACTUAL_END), 0)/3600 AS TOTAL_TIME_HOUR
, NVL(DATEDIFF('S', L.SCHEDULED_START, L.SCHEDULED_END), 0)/3600 AS SCHEDULED_TRAVEL_TIME_HOUR
, L_LS.SCHEME_LOCATION_NO AS SITE_NUMBER_START
, L_LE.SCHEME_LOCATION_NO AS SITE_NUMBER_END
, CASE WHEN L_LS.LOCATION_TYPE_ID != 1378 AND L_LE.LOCATION_TYPE_ID = 1378 THEN L_LE.SCHEME_LOCATION_NO WHEN L_LS.LOCATION_TYPE_ID = 1378 THEN L_LS.SCHEME_LOCATION_NO ELSE '-' END AS CRP_SITE_NUMBER
, L.START_WEIGHT AS START_WEIGHT
, L.END_WEIGHT AS END_WEIGHT
, L.ACTUAL_DISTANCE_TRAVELLED AS DISTANCE_TRAVELLED
, L.SHIPPER_UNIT_STATUS AS SHIPPER_UNIT_STATUS
, L.NOTES AS NOTES
, R_LCR.VALUE AS CANCEL_REASON
, CAST(L.CANCEL_DATE AS DATE) AS CANCEL_DATE
, L.MANIFEST_NUMBER AS MANIFEST_NUMBER
, R_TS.VALUE AS TRIP_STATUS
, R_TT.VALUE AS TRIP_TYPE
, R_TCR.VALUE AS TRIP_CANCEL_REASON
, CAST(T.CANCEL_DATE AS DATE) AS TRIP_CANCEL_DATE
, T.PROVIDER_REF_NO AS PROVIDER_REF_NO
, L.PROVIDER_LEG_REF AS PROVIDER_LEG_REF
, NVL(CL.VEHICLE_RATE_ID, -1) AS VEHICLE_RATE_ID
, CASE WHEN L.ACTUAL_START IS NULL AND L.ACTUAL_END IS NULL THEN 'Future' ELSE 'Past' END AS PAST_FUTURE_FLAG
, CASE WHEN A.TRIP_LEG_ID IS NOT NULL THEN 'Y' ELSE 'N' END AS ADJUSTMENTS_FLAG
, L.CREATED_BY AS CREATED_BY
, L.CREATED_ON AS CREATED_ON_UTC
, L.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, L.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM', 'FMT_TRIP_LEGS') }} AS L
INNER JOIN {{ source('CES_MSCM', 'FMT_TRIPS') }} AS T
ON L.TRIP_ID = T.TRIP_ID
INNER JOIN {{ source('CES_MSCM', 'FMT_ORGANISATIONS') }} AS O
ON T.ORGANISATION_ID = O.ORGANISATION_ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON O.SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'FMT_PEOPLE') }} AS FMTP
ON NVL(L.DRIVER_ID,T.PERSON_ID) = FMTP.PERSON_ID
LEFT JOIN {{ source('CES_MSCM', 'FMT_LOCATIONS') }} AS L_LS
ON L.START_LOCATION_ID = L_LS.LOCATION_ID
LEFT JOIN {{ source('CES_MSCM', 'FMT_LOCATIONS') }} AS L_LE
ON L.END_LOCATION_ID = L_LE.LOCATION_ID
LEFT JOIN {{ source('CES_MSCM', 'FMT_LOCATIONS') }} AS L_TS
ON T.START_LOCATION_ID = L_TS.LOCATION_ID
LEFT JOIN {{ source('CES_MSCM', 'FMT_LOCATIONS') }} AS L_TE
ON T.END_LOCATION_ID = L_TE.LOCATION_ID
LEFT JOIN {{ source('CES_MSCM', 'FMT_SCHEME_REF_CODES') }} AS R_LS
ON L.LEG_STATUS_ID = R_LS.ID
LEFT JOIN {{ source('CES_MSCM', 'FMT_SCHEME_REF_CODES') }} AS R_LCR
ON L.CANCEL_REASON_ID= R_LCR.ID
LEFT JOIN {{ source('CES_MSCM', 'FMT_SCHEME_REF_CODES') }} AS R_TS
ON T.TRIP_STATUS_ID = R_TS.ID
LEFT JOIN {{ source('CES_MSCM', 'FMT_SCHEME_REF_CODES') }} AS R_TT
ON T.TRIP_TYPE_ID = R_TT.ID
LEFT JOIN {{ source('CES_MSCM', 'FMT_SCHEME_REF_CODES') }} AS R_TCR
ON T.CANCEL_REASON_ID= R_TCR.ID
LEFT JOIN (
    SELECT
    STOP.TRIP_LEG_ID
    ,SUM(DATEDIFF('S', STOP.START_TIME, STOP.END_TIME)/60) AS TOTAL_STOP_TIME
    FROM {{ source('CES_MSCM', 'FMT_TRIP_STOPS') }} AS STOP
    GROUP BY STOP.TRIP_LEG_ID
) S
ON L.TRIP_LEG_ID = S.TRIP_LEG_ID
LEFT JOIN (
    SELECT  
    L.TRIP_LEG_ID
    ,L.LEG_SEQUENCE
    ,CASE WHEN LS.LOCATION_TYPE_ID = 1378 AND LE.LOCATION_TYPE_ID = 1378 THEN 'C-C'
    WHEN LS.LOCATION_TYPE_ID != 1378 AND LE.LOCATION_TYPE_ID = 1378 THEN 'LP-C'
    WHEN LS.LOCATION_TYPE_ID = 1378 AND LE.LOCATION_TYPE_ID != 1378 THEN 'C-LP'
    ELSE 'Others' END AS LEG_TYPE
    FROM {{ source('CES_MSCM', 'FMT_TRIP_LEGS') }} AS L
    INNER JOIN {{ source('CES_MSCM', 'FMT_TRIPS') }} AS T
    ON L.TRIP_ID = T.TRIP_ID
    LEFT JOIN {{ source('CES_MSCM', 'FMT_LOCATIONS') }} AS LS
    ON L.START_LOCATION_ID = LS.LOCATION_ID
    LEFT JOIN {{ source('CES_MSCM', 'FMT_LOCATIONS') }} AS LE
    ON L.END_LOCATION_ID = LE.LOCATION_ID
    WHERE L.LEG_STATUS_ID in (1406, 1715)
) C
ON L.TRIP_LEG_ID = C.TRIP_LEG_ID
LEFT JOIN (
    SELECT
    TF.TRIP_ID || '-' || TF.TRIP_LEG_ID || '-' || TL.TRIP_LEG_ID AS TRIP_GROUP
    ,TF.TRIP_ID
    ,TF.TRIP_LEG_ID AS TRIP_LEG_START
    ,TL.TRIP_LEG_ID AS TRIP_LEG_END
    ,TF.LEG_SEQUENCE AS LEG_SEQUENCE_START
    ,TL.LEG_SEQUENCE AS LEG_SEQUENCE_END
    FROM (
        SELECT  
        ROW_NUMBER() OVER (PARTITION BY T.TRIP_ID ORDER BY L.LEG_SEQUENCE) AS N
        ,T.TRIP_ID
        ,L.TRIP_LEG_ID
        ,L.LEG_SEQUENCE
        ,CASE WHEN LS.LOCATION_TYPE_ID != 1378 AND LE.LOCATION_TYPE_ID = 1378 THEN 'LP-C'
        WHEN LS.LOCATION_TYPE_ID = 1378 AND LE.LOCATION_TYPE_ID != 1378 THEN 'C-LP'
        END AS LEG_TYPE
        FROM {{ source('CES_MSCM', 'FMT_TRIP_LEGS') }} AS L
        INNER JOIN {{ source('CES_MSCM', 'FMT_TRIPS') }} AS T
        ON L.TRIP_ID = T.TRIP_ID
        LEFT JOIN {{ source('CES_MSCM', 'FMT_LOCATIONS') }} AS LS
        ON L.START_LOCATION_ID = LS.LOCATION_ID
        LEFT JOIN {{ source('CES_MSCM', 'FMT_LOCATIONS') }} AS LE
        ON L.END_LOCATION_ID = LE.LOCATION_ID
        WHERE L.LEG_STATUS_ID in (1406, 1715)
        AND NOT (LS.LOCATION_TYPE_ID = 1378 AND LE.LOCATION_TYPE_ID = 1378)
    ) TF
    INNER JOIN (
        SELECT  
        ROW_NUMBER() OVER (PARTITION BY T.TRIP_ID ORDER BY L.LEG_SEQUENCE) AS N
        ,T.TRIP_ID
        ,L.TRIP_LEG_ID
        ,L.LEG_SEQUENCE
        ,CASE WHEN LS.LOCATION_TYPE_ID != 1378 AND LE.LOCATION_TYPE_ID = 1378 THEN 'LP-C'
        WHEN LS.LOCATION_TYPE_ID = 1378 AND LE.LOCATION_TYPE_ID != 1378 THEN 'C-LP'
        END AS LEG_TYPE
        FROM {{ source('CES_MSCM', 'FMT_TRIP_LEGS') }} AS L
        INNER JOIN {{ source('CES_MSCM', 'FMT_TRIPS') }} AS T
        ON L.TRIP_ID = T.TRIP_ID
        LEFT JOIN {{ source('CES_MSCM', 'FMT_LOCATIONS') }} AS LS
        ON L.START_LOCATION_ID = LS.LOCATION_ID
        LEFT JOIN {{ source('CES_MSCM', 'FMT_LOCATIONS') }} AS LE
        ON L.END_LOCATION_ID = LE.LOCATION_ID
        WHERE L.LEG_STATUS_ID in (1406, 1715)
        AND NOT (LS.LOCATION_TYPE_ID = 1378 AND LE.LOCATION_TYPE_ID = 1378)
    ) TL
    ON TF.TRIP_ID = TL.TRIP_ID
    AND TF.N = TL.N-1
    WHERE TF.LEG_TYPE= 'LP-C' 
    AND TL.LEG_TYPE = 'C-LP'
) TG
ON L.TRIP_ID = TG.TRIP_ID
AND L.LEG_SEQUENCE BETWEEN TG.LEG_SEQUENCE_START AND TG.LEG_SEQUENCE_END
LEFT JOIN {{ source('CES_MSCM', 'FMT_TRIP_CLAIM_LINES') }} AS CL
ON L.TRIP_LEG_ID = CL.TRIP_LEG_ID
LEFT JOIN (
    SELECT DISTINCT
    LA.TRIP_LEG_ID
    FROM {{ source('CES_MSCM', 'FMT_TRIP_LEG_ADJUSTMENTS') }} AS LA
) A
ON L.TRIP_LEG_ID = A.TRIP_LEG_ID