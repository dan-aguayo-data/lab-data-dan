SELECT
M.MULTI_SCHEME_ID
, LOWER(TRIM(M.LOGIN_ID)) AS LOGIN_ID
, M.FULL_NAME
, M.SITE_SCHEME_ID AS CONSUMER_ID
, M.SITE_NAME AS CONSUMER_NAME
, M.PARTNER_ID
, M.PARTNER_NAME
, M.PARTNER_TYPE
, M.PARTNER_SUB_TYPE
, M.ACTIVE
, M.LAUNCH_DATE
, M.DATE_CREATED AS CRATED_ON
, M.DATE_UPDATED AS LAST_MODIFIED_ON
FROM {{ source('COEX_AGILOFT', 'AG_PARTNER_SECURITY_MAPPING') }} AS M