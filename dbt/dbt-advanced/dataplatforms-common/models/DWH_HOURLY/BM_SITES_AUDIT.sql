SELECT
PS.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, PS.SITE_NUMBER AS SITE_NUMBER
, PS.SITE_NAME AS SITE_NAME
, P.PARTICIPANT_NUMBER AS SUPPLIER_NUMBER
, P.PARTICIPANT_NAME AS SUPPLIER_NAME
, PS.TAXONOMY_SUB_TYPE AS MANUFACTURER_TYPE
, DECODE(PS.TAXONOMY_SUB_TYPE, 'Manufacturer - Large', 'MONTHLY', 'Manufacturer - Small', 'QUARTERLY', 'Manufacturer - Micro', 'YEARLY') AS INVOICE_FREQUENCY
, DECODE(CK.TAXONOMY_SUB_TYPE, 'Manufacturer - Large', 'MONTHLY', 'Manufacturer - Small', 'QUARTERLY', 'Manufacturer - Micro', 'YEARLY') AS INVOICE_FREQUENCY_PREVIOUS
, CASE WHEN PS.TAXONOMY_SUB_TYPE <>  CK.TAXONOMY_SUB_TYPE THEN 1 ELSE 0 END AS INVOICE_FREQUENCY_UPDATED
, CASE WHEN PS.TAXONOMY_SUB_TYPE <>  CK.TAXONOMY_SUB_TYPE THEN CASE WHEN ROW_NUMBER() OVER (PARTITION BY PS.SITE_NUMBER, PS.TAXONOMY_SUB_TYPE <>  CK.TAXONOMY_SUB_TYPE ORDER BY PS.LAST_MODIFIED_ON DESC) = 1 THEN 1 ELSE 0 END ELSE NULL END AS INVOICE_FREQUENCY_LAST_UPDATE_FLAG
,PS.AUDIT_DATE AS AUDIT_DATE_ON_UTC
, PS.CREATED_BY AS CREATED_BY
, PS.CREATED_ON AS CREATED_ON_UTC
, CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, PS.CREATED_ON) AS CREATED_ON
, PS.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, PS.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, PS.LAST_MODIFIED_ON) AS LAST_MODIFIED_ON
, SYSDATE() AS INSERT_DATE_UTC
FROM (
    SELECT 
    PSA.MULTI_SCHEME_ID
    , PSA.SITE_NUMBER
    , PSA.SITE_NAME
    , PSA.TAXONOMY_SUB_TYPE
    , PSA.PARTICIPANT_ID
    , PSA.SITE_TYPE_ID
    ,PSA.AUDIT_DATE
    , PSA.CREATED_BY
    , PSA.CREATED_ON
    , PSA.LAST_MODIFIED_BY
    , PSA.LAST_MODIFIED_ON
    , ROW_NUMBER() OVER (PARTITION BY PSA.SITE_NUMBER ORDER BY PSA.LAST_MODIFIED_ON DESC) AS CURRENT_RN
    FROM {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES_A') }} AS PSA
) PS
INNER JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANTS') }} AS P
ON P.PARTICIPANT_ID = PS.PARTICIPANT_ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON PS.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN (
    SELECT 
    PSA.MULTI_SCHEME_ID
    , PSA.SITE_NUMBER
    , PSA.SITE_NAME
    , PSA.TAXONOMY_SUB_TYPE
    , ROW_NUMBER() OVER (PARTITION BY PSA.SITE_NUMBER ORDER BY PSA.LAST_MODIFIED_ON DESC) AS PREVIOUS
    FROM {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES_A') }} AS PSA
) CK
ON PS.SITE_NUMBER = CK.SITE_NUMBER
AND CK.PREVIOUS - 1 = PS.CURRENT_RN
WHERE PS.SITE_TYPE_ID IN ('1540')