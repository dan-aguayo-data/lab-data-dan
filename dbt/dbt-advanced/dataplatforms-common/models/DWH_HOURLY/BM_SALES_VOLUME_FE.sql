SELECT
V.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, V.SCHEME AS SCHEME
, V.ID AS ID
, V.BM_SALES_VOLUME_HDR_ID AS BM_SALES_VOLUME_HDR_ID
, V.SITE_NUMBER AS SITE_NUMBER
, V.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID
, V.MATERIAL_TYPE AS MATERIAL_TYPE
, V.AVG_VOLUME AS AVG_VOLUME
, V.VOLUME AS VOLUME
, V.GROSS_AMOUNT AS GROSS_AMOUNT
, V.VOLUME_HEADER AS VOLUME_HEADER
, V.UOM AS UOM
, V.PERIOD AS PERIOD
, V.PERIOD_KEY AS PERIOD_KEY
, V.PERIOD_TYPE AS PERIOD_TYPE
, V.ENTRY_TYPE AS ENTRY_TYPE
, CASE WHEN V.ENTRY_TYPE IN ('R', 'F', 'FE') THEN 'R' WHEN V.ENTRY_TYPE IN ('A', 'FO') THEN 'A' ELSE NULL END AS ENTRY_TYPE_PAYMENT_MAPPING
, V.STATUS AS STATUS
, TO_CHAR(ADD_MONTHS(SYSDATE(), -1), 'YYYYMM01') AS CURRENT_MONTH_KEY
, CASE WHEN PS.TAXONOMY_SUB_TYPE IN ('Manufacturer - Large', 'Manufacturer - Small') THEN CASE WHEN LEFT(CURRENT_MONTH_KEY, 4) ||  TO_CHAR(CEIL(SUBSTR(CURRENT_MONTH_KEY, 5, 2) / (CASE WHEN PS.TAXONOMY_SUB_TYPE = 'Manufacturer - Large' THEN 1 ELSE 3 END)), 'FM00') > LEFT(V.PERIOD_KEY, 4) || TO_CHAR(CEIL(SUBSTR(V.PERIOD_KEY, 5, 2) / (CASE WHEN PS.TAXONOMY_SUB_TYPE = 'Manufacturer - Large' THEN 1 ELSE 3 END)), 'FM00') THEN 'PREVIOUS' WHEN CURRENT_MONTH_KEY >= V.PERIOD_KEY AND LEFT(CURRENT_MONTH_KEY, 4) ||  TO_CHAR(CEIL(SUBSTR(CURRENT_MONTH_KEY, 5, 2) / (CASE WHEN PS.TAXONOMY_SUB_TYPE = 'Manufacturer - Large' THEN 1 ELSE 3 END)), 'FM00') = LEFT(V.PERIOD_KEY, 4) || TO_CHAR(CEIL(SUBSTR(V.PERIOD_KEY, 5, 2) / (CASE WHEN PS.TAXONOMY_SUB_TYPE = 'Manufacturer - Large' THEN 1 ELSE 3 END)), 'FM00') THEN 'CURRENT' ELSE NULL END WHEN PS.TAXONOMY_SUB_TYPE IN ('Manufacturer - Micro') THEN CASE WHEN LEFT(CURRENT_MONTH_KEY, 4) + FLOOR(SUBSTR(CURRENT_MONTH_KEY, 5, 2) / 7) = LEFT(V.PERIOD_KEY, 4) + FLOOR(SUBSTR(V.PERIOD_KEY, 5, 2) / 7) THEN 'CURRENT' ELSE 'PREVIOUS' END END AS PERIOD_FLAG
, CASE WHEN COUNT(CASE WHEN V.ENTRY_TYPE = 'R' AND V.STATUS = 'FINAL' THEN 1 ELSE NULL END) OVER (PARTITION BY V.MULTI_SCHEME_ID, V.SITE_NUMBER, V.PERIOD, V.MATERIAL_TYPE_ID) >= 1 THEN 'R' ELSE 'FE' END AS R_FE_FLAG
, CASE WHEN PS.MULTI_SCHEME_ID = 10000 
AND PS.CREATED_BY LIKE '%internal - participant client%' 
AND V.PERIOD <= '2023-10' 
--AND TO_CHAR(PS.CREATED_ON, 'YYYYMM01') <= '20231001'
AND TO_CHAR(PS.CREATED_ON, 'YYYYMM01') >= V.PERIOD_KEY 
THEN 
	CASE WHEN V.ENTRY_TYPE = 'R' 
	AND V.STATUS = 'FINAL' 
	AND V.VOLUME + SUM(CASE WHEN V.ENTRY_TYPE = 'A' AND V.STATUS = 'FINAL' THEN V.VOLUME ELSE NULL END) OVER (PARTITION BY V.SITE_NUMBER, V.PERIOD, V.MATERIAL_TYPE_ID) = 0 
	THEN 1 
	WHEN V.ENTRY_TYPE = 'A' 
	AND V.STATUS = 'FINAL' 
	AND V.VOLUME + SUM(CASE WHEN V.ENTRY_TYPE = 'R' AND V.STATUS = 'FINAL' THEN V.VOLUME ELSE NULL END) OVER (PARTITION BY V.SITE_NUMBER, V.PERIOD, V.MATERIAL_TYPE_ID) = 0 
	THEN 1 
	ELSE 0 
	END 
ELSE 0 
END AS IGNORE_BY_PE_FLAG
, B_PS.LAST_PE_RUN_ON_UTC AS LAST_PE_RUN_ON_UTC
, CASE WHEN IGNORE_BY_PE_FLAG = 0 THEN 
	CASE WHEN PERIOD_FLAG = 'PREVIOUS' 
		AND PS.MULTI_SCHEME_ID = 10000
		AND PS.CREATED_BY LIKE '%internal - participant client%' 
		AND PS.TAXONOMY_SUB_TYPE = 'Manufacturer - Large'
		AND V.PERIOD_KEY <= '20231001'
		THEN 0
	WHEN PERIOD_FLAG = 'PREVIOUS' 
		AND V.ENTRY_TYPE IN ('R', 'A', 'FO') 
		AND V.STATUS = 'FINAL' 
		AND (
			(V.SUBMITTED_DATE_UTC <= B.PE_RUN_ON_UTC AND TO_CHAR(B.PE_RUN_ON_UTC, 'YYYYMM') = TO_CHAR(SYSDATE(), 'YYYYMM'))
			OR (V.SUBMITTED_DATE_UTC >= B.PE_RUN_ON_UTC AND TO_CHAR(B.PE_RUN_ON_UTC, 'YYYYMM') < TO_CHAR(SYSDATE(), 'YYYYMM'))
			OR B.PE_RUN_ON_UTC IS NULL
			)
	THEN 1 
	WHEN TO_CHAR(B.PE_RUN_ON_UTC, 'YYYYMM') <> TO_CHAR(SYSDATE(), 'YYYYMM') 
		AND PERIOD_FLAG = 'CURRENT' 
		THEN
		CASE WHEN R_FE_FLAG = 'R' 
			AND V.ENTRY_TYPE IN ('R', 'A', 'FO') 
			AND V.STATUS = 'FINAL'
		THEN 1 
		WHEN R_FE_FLAG = 'FE' 
			AND V.ENTRY_TYPE IN ('FE') 
			AND V.STATUS = 'FINAL-FE' 
		THEN 1 
		ELSE 0
		END
	WHEN TO_CHAR(B.PE_RUN_ON_UTC, 'YYYYMM') = TO_CHAR(SYSDATE(), 'YYYYMM') 
		AND PERIOD_FLAG = 'CURRENT' 
		AND PS.MULTI_SCHEME_ID = 10000
		AND PS.CREATED_BY LIKE '%internal - participant client%' 
		AND PS.TAXONOMY_SUB_TYPE = 'Manufacturer - Micro'
		AND V.PERIOD_KEY <= '20231001'
		THEN 0
	WHEN TO_CHAR(B.PE_RUN_ON_UTC, 'YYYYMM') = TO_CHAR(SYSDATE(), 'YYYYMM') 
		AND PERIOD_FLAG = 'CURRENT' 
		THEN
		CASE WHEN R_FE_FLAG = 'R' 
			AND V.ENTRY_TYPE IN ('R', 'A', 'FO') 
			AND V.STATUS = 'FINAL' 
			AND V.SUBMITTED_DATE_UTC <= B.PE_RUN_ON_UTC
		THEN 1 
		WHEN R_FE_FLAG = 'R' 
			AND V.ENTRY_TYPE IN ('FE') 
			AND MAX(CASE WHEN V.ENTRY_TYPE = 'R' AND V.STATUS = 'FINAL' THEN V.SUBMITTED_DATE_UTC ELSE NULL END) OVER (PARTITION BY V.MULTI_SCHEME_ID, V.SITE_NUMBER, V.PERIOD, V.MATERIAL_TYPE_ID) > B.PE_RUN_ON_UTC
		THEN 1 
		WHEN R_FE_FLAG = 'FE' 
			AND V.ENTRY_TYPE IN ('A')
			AND V.SS_AUDIT_ADJUSTMENT_ID <> '-1'
			AND V.STATUS = 'INVOICED'
			AND PS.TAXONOMY_SUB_TYPE = 'Manufacturer - Micro'
		THEN 0
		WHEN R_FE_FLAG = 'FE' 
			AND V.ENTRY_TYPE IN ('A')
			AND (
				V.SS_AUDIT_ADJUSTMENT_ID <> '-1'
				OR V.ADJUSTMENT_REASON = 'APPROVED_STAT_DEC_FINAL_UPDATE'
			)
			AND V.STATUS = 'FINAL'
			AND V.SUBMITTED_DATE_UTC <= B.PE_RUN_ON_UTC
		THEN 1
		WHEN R_FE_FLAG = 'FE' 
			AND V.ENTRY_TYPE IN ('FE') 
			AND V.STATUS = 'FINAL-FE' 
			AND SUM(CASE WHEN V.ENTRY_TYPE = 'FE' OR (V.ENTRY_TYPE = 'A' AND V.SS_AUDIT_ADJUSTMENT_ID <> '-1') THEN 1 ELSE 0 END) OVER (PARTITION BY V.MULTI_SCHEME_ID, V.SITE_NUMBER, V.PERIOD, V.MATERIAL_TYPE_ID) = 1
			AND PS.MULTI_SCHEME_ID = 10000
			AND PS.CREATED_BY LIKE '%internal - participant client%' 
			AND V.PERIOD <= '2023-10'
			AND TO_CHAR(PS.CREATED_ON, 'YYYYMM01') <= '20231001'
			AND TO_CHAR(PS.CREATED_ON, 'YYYYMM01') <= V.PERIOD_KEY
		THEN 0
		WHEN R_FE_FLAG = 'FE' 
			AND V.ENTRY_TYPE IN ('FE') 
			AND V.STATUS = 'FINAL-FE' 
			AND SUM(CASE WHEN V.ENTRY_TYPE = 'FE' OR (V.ENTRY_TYPE = 'A' AND V.SS_AUDIT_ADJUSTMENT_ID <> '-1') THEN 1 ELSE 0 END) OVER (PARTITION BY V.MULTI_SCHEME_ID, V.SITE_NUMBER, V.PERIOD, V.MATERIAL_TYPE_ID) = 1
			AND PS.MULTI_SCHEME_ID = 10000
			AND PS.CREATED_BY LIKE '%internal - participant client%' 
			AND (V.PERIOD <= '2023-10' OR V.PERIOD_KEY < TO_CHAR(PS.CREATED_ON, 'YYYYMM01'))
			AND TO_CHAR(PS.CREATED_ON, 'YYYYMM01') >= '20231101'
		THEN 0
		WHEN R_FE_FLAG = 'FE' 
			AND V.ENTRY_TYPE IN ('FE') 
			AND V.STATUS = 'FINAL-FE' 
			AND SUM(CASE WHEN V.ENTRY_TYPE = 'FE' OR (V.ENTRY_TYPE = 'A' AND V.SS_AUDIT_ADJUSTMENT_ID <> '-1') THEN 1 ELSE 0 END) OVER (PARTITION BY V.MULTI_SCHEME_ID, V.SITE_NUMBER, V.PERIOD, V.MATERIAL_TYPE_ID) = 1
			AND SUM(CASE WHEN V.ENTRY_TYPE IN ('R', 'F', 'H') AND V.STATUS IN ('INVOICED', 'HISTORIC') THEN 1 ELSE 0 END) OVER (PARTITION BY V.MULTI_SCHEME_ID, V.SITE_NUMBER, V.PERIOD, V.MATERIAL_TYPE_ID) = 1
			AND PS.TAXONOMY_SUB_TYPE = 'Manufacturer - Micro'
		THEN 0
		WHEN R_FE_FLAG = 'FE' 
			AND V.ENTRY_TYPE IN ('FE') 
			AND V.STATUS = 'FINAL-FE' 
			AND SUM(CASE WHEN V.ENTRY_TYPE = 'FE' OR (V.ENTRY_TYPE = 'A' AND V.SS_AUDIT_ADJUSTMENT_ID <> '-1') THEN 1 ELSE 0 END) OVER (PARTITION BY V.MULTI_SCHEME_ID, V.SITE_NUMBER, V.PERIOD, V.MATERIAL_TYPE_ID) = 1
			AND PS.MULTI_SCHEME_ID LIKE '10002%'
			AND 
				(V.PERIOD <= '2023-10'
				OR TO_CHAR(PS.CREATED_ON, 'YYYYMM01') > V.PERIOD_KEY)
		THEN 0
		WHEN R_FE_FLAG = 'FE' 
			AND V.ENTRY_TYPE IN ('FE') 
			AND V.STATUS = 'FINAL-FE' 
			AND SUM(CASE WHEN V.ENTRY_TYPE = 'FE' OR (V.ENTRY_TYPE = 'A' AND V.SS_AUDIT_ADJUSTMENT_ID <> '-1') THEN 1 ELSE 0 END) OVER (PARTITION BY V.MULTI_SCHEME_ID, V.SITE_NUMBER, V.PERIOD, V.MATERIAL_TYPE_ID) = 1
			AND PS.MULTI_SCHEME_ID LIKE '10003%'
			AND 
				(V.PERIOD <= '2025-04'
				OR TO_CHAR(PS.CREATED_ON, 'YYYYMM01') > V.PERIOD_KEY)
		THEN 0
		WHEN R_FE_FLAG = 'FE' 
			AND V.ENTRY_TYPE IN ('FE') 
			AND V.STATUS = 'FINAL-FE' 
			AND SUM(CASE WHEN V.ENTRY_TYPE = 'FE' OR (V.ENTRY_TYPE = 'A' AND V.SS_AUDIT_ADJUSTMENT_ID <> '-1') THEN 1 ELSE 0 END) OVER (PARTITION BY V.MULTI_SCHEME_ID, V.SITE_NUMBER, V.PERIOD, V.MATERIAL_TYPE_ID) = 1
		THEN 1 
		ELSE 0
		END
	ELSE 0 
	END 
ELSE 0 
END AS PE_FLAG
, V.SUBMITTED_DATE AS SUBMITTED_DATE
, V.SUBMITTED_DATE_KEY AS SUBMITTED_DATE_KEY
, V.SUBMITTED_BY AS SUBMITTED_BY
, V.SUBMITTED_DATE_UTC AS SUBMITTED_DATE_UTC
, V.SS_AUDIT_ADJUSTMENT_ID AS SS_AUDIT_ADJUSTMENT_ID
, V.CREATED_BY AS CREATED_BY
, V.CREATED_ON_UTC AS CREATED_ON_UTC
, V.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, V.LAST_MODIFIED_ON_UTC AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ ref('BM_SALES_VOLUME_FE_BASE') }} AS V
LEFT JOIN (
    SELECT
    MPS.MULTI_SCHEME_ID,
    MPS.SITE_NUMBER,
    MPS.TAXONOMY_SUB_TYPE,
    MPS.CREATED_BY,
    CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, MPS.CREATED_ON) AS CREATED_ON
    FROM {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS MPS
    INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
    ON MPS.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
) PS
ON V.SITE_NUMBER = PS.SITE_NUMBER
LEFT JOIN (
    SELECT
    PT.SCHEME_PARTICIPANT_ID AS SITE_NUMBER
    , MAX(PT.CREATED_ON) AS LAST_PE_RUN_ON_UTC
    FROM {{ source('CES_MSCM', 'PAYMENT_TRANSACTION_REC') }} AS PT
    WHERE PT.SCHEME_PARTICIPANT_TYPE = 'MANUFACTURER'
    GROUP BY PT.SCHEME_PARTICIPANT_ID
) B_PS
ON V.SITE_NUMBER = B_PS.SITE_NUMBER
LEFT JOIN (
    SELECT
    NVL(PAY.MULTI_SCHEME_ID, Y.MULTI_SCHEME_ID) AS MULTI_SCHEME_ID
    , NVL(PAY.PAYMENT_PERIOD_FLAG, Y.PAYMENT_PERIOD_FLAG) AS PAYMENT_PERIOD_FLAG
    , NVL(PAY.PE_RUN_ON_UTC, Y.PE_RUN_ON_UTC) AS PE_RUN_ON_UTC
    , NVL(PAY.MAX_PE_RUN_ON_UTC, Y.MAX_PE_RUN_ON_UTC) AS MAX_PE_RUN_ON_UTC
    FROM (
        SELECT
        P.MULTI_SCHEME_ID
        , P.PAYMENT_PERIOD_FLAG
        , MIN(P.BASE_RUN_ON) AS PE_RUN_ON_UTC
        , MAX(P.BASE_RUN_ON) AS MAX_PE_RUN_ON_UTC
        FROM(
            SELECT
            PT.MULTI_SCHEME_ID
            , PT.CREATED_ON AS BASE_RUN_ON
            , LEFT(PT.PAYMENT_PERIOD, 1) AS PAYMENT_PERIOD_FLAG
            , CASE WHEN LEFT(PT.PAYMENT_PERIOD, 1) = 'M' THEN SUBSTR(PT.PAYMENT_PERIOD, 2, 4) || RIGHT(PT.PAYMENT_PERIOD, 2) || '01' WHEN LEFT(PT.PAYMENT_PERIOD, 1) = 'Q' THEN SUBSTR(PT.PAYMENT_PERIOD, 2, 4) || DECODE(RIGHT(PT.PAYMENT_PERIOD, 1), '1', '0101', '2', '0401', '3', '0701', '4', '1001') WHEN LEFT(PT.PAYMENT_PERIOD, 1) = 'Y' THEN SUBSTR(PT.PAYMENT_PERIOD, 2, 4) ELSE NULL END AS PAYMENT_PERIOD_KEY
            , RANK() OVER (PARTITION BY PT.MULTI_SCHEME_ID, PAYMENT_PERIOD_FLAG ORDER BY PAYMENT_PERIOD_KEY DESC) AS RK
            FROM {{ source('CES_MSCM', 'PAYMENT_TRANSACTION_REC') }} AS PT
            WHERE PT.SCHEME_PARTICIPANT_TYPE = 'MANUFACTURER'
            AND PT.STATUS <> 'STALE'
        ) P
        WHERE P.RK = 1
        GROUP BY ALL
    ) PAY
    FULL OUTER JOIN (
        SELECT
        MULTI_SCHEME_ID
        , PAYMENT_PERIOD_FLAG
        , PE_RUN_ON_UTC
        , MAX_PE_RUN_ON_UTC
        FROM (VALUES(10000, 'Y', SYSDATE(), SYSDATE()), (10001, 'Y', SYSDATE(), SYSDATE()), (10002, 'Y', SYSDATE(), SYSDATE()), (10003, 'Y', SYSDATE(), SYSDATE()))
        AS V (
        MULTI_SCHEME_ID
        , PAYMENT_PERIOD_FLAG
        , PE_RUN_ON_UTC
        , MAX_PE_RUN_ON_UTC
        )
    ) Y
    ON PAY.MULTI_SCHEME_ID = Y.MULTI_SCHEME_ID
    AND PAY.PAYMENT_PERIOD_FLAG = Y.PAYMENT_PERIOD_FLAG
) B
ON V.MULTI_SCHEME_ID = B.MULTI_SCHEME_ID
AND (CASE WHEN PS.TAXONOMY_SUB_TYPE = 'Manufacturer - Large' THEN 'M' WHEN PS.TAXONOMY_SUB_TYPE = 'Manufacturer - Small' THEN 'Q' WHEN PS.TAXONOMY_SUB_TYPE = 'Manufacturer - Micro' THEN 'Y' END) = B.PAYMENT_PERIOD_FLAG