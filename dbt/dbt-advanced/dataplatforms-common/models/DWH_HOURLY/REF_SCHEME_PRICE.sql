SELECT
P.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, P.ID AS ID
, MT.NAME AS MATERIAL_TYPE
, P.SCHEME_PRICE AS SCHEME_PRICE
, CAST(P.EFFECTIVE_FROM AS DATE) AS EFFECTIVE_FROM
, CAST(P.EFFECTIVE_TO AS DATE) AS EFFECTIVE_TO
, CASE WHEN FILTER.N = 1 THEN 'Y' ELSE 'N' END AS ACTIVE_FLAG
, P.CREATED_BY AS CREATED_BY
, P.CREATED_ON AS CREATED_ON_UTC
, P.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, P.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM', 'SCHEME_PRICE_REFERENCE') }} AS P
INNER JOIN {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS MT
ON P.MATERIAL_TYPE_ID = MT.ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON P.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN
    (SELECT
    P.ID
    ,ROW_NUMBER() OVER (PARTITION BY P.MULTI_SCHEME_ID, P.MATERIAL_TYPE_ID ORDER BY P.EFFECTIVE_FROM DESC, P.EFFECTIVE_TO DESC) N
    FROM {{ source('CES_MSCM', 'SCHEME_PRICE_REFERENCE') }} AS P
    WHERE CAST(CONVERT_TIMEZONE('UTC', 'Australia/Perth', SYSTIMESTAMP()) AS DATE)  BETWEEN NVL(P.EFFECTIVE_FROM,TO_DATE('01/JAN/1900','DD/MON/YYYY')) AND NVL(P.EFFECTIVE_TO,TO_DATE('01/JAN/9999','DD/MON/YYYY'))
    ) FILTER
ON P.ID = FILTER.ID