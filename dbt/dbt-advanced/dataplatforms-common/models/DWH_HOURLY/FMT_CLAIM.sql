SELECT
L.SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, L.TRIP_CLAIM_LINE_ID AS ID
, L.TRIP_CLAIM_ID AS TRIP_CLAIM_ID
, L.SCHEME_PARTICIPANT_ID AS SITE_NUMBER
, L.SUPPLIER_NUMBER AS SUPPLIER_NUMBER
, R_T.VALUE AS CLAIM_TYPE
, R_S.VALUE AS STATUS
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(L.CLAIM_DATE AS TIMESTAMP)) AS SUBMITTED_DATE
, TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(L.CLAIM_DATE AS TIMESTAMP)),'YYYYMMDD') AS SUBMITTED_DATE_KEY
, L.RECEIPT_ID AS RECEIPT_ID
, L.PO_NUMBER AS PO_NUMBER
, L.SUBMITTED_BY AS SUBMITTED_BY
, L.INVOICE_NUMBER AS INVOICE_NUMBER
, L.ERP_INVOICE_ID AS ERP_INVOICE_ID
, L.SUPPLIER_INVOICE_TOTAL AS SUPPLIER_INVOICE_TOTAL
, L.LAST_PAYMENT_DATE AS LAST_PAYMENT_DATE
, L.TRIP_LEG_ID AS TRIP_LEG_ID
, L.LINE_NUM AS LINE_NUMBER
, L.VEHICLE_RATE_ID AS VEHICLE_RATE_ID
, L.CHARGE_RATE AS CHARGE_RATE
, R.VALUE AS CHARGE_RATE_TYPE
, R_CT.VALUE AS CHARGE_TYPE
, L.CHARGE_QTY AS CHARGE_QTY
, R_U.VALUE AS CHARGE_UOM
, R_CS.VALUE AS CHARGE_STATUS
, L.CHARGE_AMOUNT AS CHARGE_AMOUNT
, R_CR.VALUE AS CHARGE_REASON
, L.NOTES AS NOTES
, CAST(L.CLAIM_DATE AS TIMESTAMP) AS SUBMITTED_DATE_UTC
, L.CREATED_BY AS CREATED_BY
, L.CREATED_ON AS CREATED_ON_UTC
, L.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, L.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM (
    SELECT
    O.SCHEME_ID 
    , L.TRIP_CLAIM_LINE_ID
    , C.TRIP_CLAIM_ID  
    , O.SCHEME_PARTICIPANT_ID  
    , O.SUPPLIER_NUMBER  
    , C.CLAIM_DATE
    , C.RECEIPT_ID  
    , C.SUBMITTED_BY 
    , C.INVOICE_NUMBER  
    , C.SUPPLIER_INVOICE_TOTAL 
    , C.LAST_PAYMENT_DATE  
    , L.TRIP_LEG_ID 
    , L.LINE_NUM  
    , C.ERP_INVOICE_ID
    , L.VEHICLE_RATE_ID  
    , L.CHARGE_RATE  
    , L.CHARGE_QTY 
    , L.CHARGE_AMOUNT  
    , L.NOTES  
    , C.CLAIM_TYPE_ID
    , C.CLAIM_STATUS_ID
    , L.CHARGE_TYPE_ID
    , L.CHARGE_UOM_ID
    , L.CHARGE_STATUS_ID
    , L.CHARGE_REASON_ID
    , C.PO_NUMBER
    , L.CREATED_BY 
    , L.CREATED_ON 
    , L.LAST_MODIFIED_BY
    , L.LAST_MODIFIED_ON
    FROM
    {{ source('CES_MSCM', 'FMT_TRIP_CLAIMS') }} AS C
    INNER JOIN {{ source('CES_MSCM', 'FMT_TRIP_CLAIM_LINES') }} AS L
    ON C.TRIP_CLAIM_ID = L.TRIP_CLAIM_ID
    INNER JOIN {{ source('CES_MSCM', 'FMT_ORGANISATIONS') }} AS O
    ON C.ORGANISATION_ID = O.ORGANISATION_ID
     
    UNION ALL
     
    SELECT
    LSP.MULTI_SCHEME_ID AS SCHEME_ID 
    ,NULL AS TRIP_CLAIM_LINE_ID
    ,NULL AS TRIP_CLAIM_ID
    ,LSP.SITE_NUMBER AS SCHEME_PARTICIPANT_ID
    ,NULL AS SUPPLIER_NUMBER
    ,LSP.MONTH AS CLAIM_DATE
    ,NULL AS RECEIPT_ID
    ,NULL AS SUBMITTED_BY
    ,NULL AS INVOICE_NUMBER
    ,NULL AS SUPPLIER_INVOICE_TOTAL
    ,NULL AS LAST_PAYMENT_DATE
    ,NULL AS TRIP_LEG_ID
    ,NULL AS LINE_NUMBER
    , NULL AS ERP_INVOICE_ID
    ,NULL AS VEHICLE_RATE_ID
    ,NULL AS CHARGE_RATE
    ,NULL AS CHARGE_QTY
    ,LSP.COST AS CHARGE_AMOUNT
    ,NULL AS NOTES
    ,NULL AS CLAIM_TYPE_ID
    , NULL AS CLAIM_STATUS_ID
    , NULL AS CHARGE_TYPE_ID
    , NULL AS CHARGE_UOM_ID
    , NULL AS CHARGE_STATUS_ID
    , NULL AS CHARGE_REASON_ID
    , NULL AS PO_NUMBER
    ,NULL AS CREATED_BY
    ,LSP.DATE_ADDED AS CREATED_ON
    ,NULL AS LAST_MODIFIED_BY
    ,LSP.DATE_ADDED AS LAST_MODIFIED_ON
    FROM
    {{ source('LOOKUPS', 'LSP_MONTHLY_COST') }} AS LSP
) L
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON L.SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'FMT_SCHEME_REF_CODES') }} AS R_T
ON L.CLAIM_TYPE_ID = R_T.ID
LEFT JOIN {{ source('CES_MSCM', 'FMT_SCHEME_REF_CODES') }} AS R_S
ON L.CLAIM_STATUS_ID = R_S.ID
LEFT JOIN {{ source('CES_MSCM', 'FMT_SCHEME_REF_CODES') }} AS R_CT
ON L.CHARGE_TYPE_ID = R_CT.ID
LEFT JOIN {{ source('CES_MSCM', 'FMT_SCHEME_REF_CODES') }} AS R_U
ON L.CHARGE_UOM_ID = R_U.ID
LEFT JOIN {{ source('CES_MSCM', 'FMT_SCHEME_REF_CODES') }} AS R_CS
ON L.CHARGE_STATUS_ID = R_CS.ID
LEFT JOIN {{ source('CES_MSCM', 'FMT_SCHEME_REF_CODES') }} AS R_CR
ON L.CHARGE_REASON_ID = R_CR.ID
LEFT JOIN {{ source('CES_MSCM', 'FMT_VEHICLE_RATES') }} AS VR
ON L.VEHICLE_RATE_ID = VR.VEHICLE_RATE_ID
LEFT JOIN {{ source('CES_MSCM', 'FMT_SCHEME_REF_CODES') }} AS R
ON VR.RATE_TYPE_ID = R.ID