SELECT
PTH.MULTI_SCHEME_ID  AS MULTI_SCHEME_ID 
, SCHEME.NAME AS SCHEME_NAME
, CAST(PTH.PYMT_TRXN_HEADER_ID AS VARCHAR(25)) AS PYMT_TRXN_HEADER_ID
, PTH.POS_TXN_NUM AS POS_TXN_NUM
, PTH.BATCH_ID AS PAYMENT_BATCH_ID
, PTH.PAYMENT_METHOD AS PAYMENT_METHOD
, MPS.SITE_NUMBER AS CONSUMER_ID
, SP.PARTICIPANT_NAME AS CONSUMER_NAME
, RD.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID
, PTL.LINE_NUM AS LINE_NUM
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(RH.TRANSACTED_ON AS TIMESTAMP))  AS PAYMENT_PERIOD
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(PTH.CREATED_ON AS TIMESTAMP))  AS PERIOD
, PTL.QUANTITY AS VOLUME
, PTL.AMOUNT AS GROSS_AMOUNT
, CASE WHEN PTH.VOIDED = 'Y' THEN 'VOIDED' ELSE 'NOT VOIDED' END AS VOID_STATUS
, PTH.PAY_REF_NUMBER AS PAY_REF_NUMBER
, PTH.PAID AS PAID
, PTH.INVOICED AS INVOICED
, PTH.ERP_PAID AS ERP_PAID
, PTH.AMOUNT AS PAYMENT_AMOUNT
, SUM(PTL.AMOUNT) OVER (PARTITION BY PTL.PYMT_TRXN_HEADER_ID) AS PAYMENT_LINE_AGG
, NVL(NULLIF(RH.REFUND_CRP,''),PD.CRP_ID) AS CRP_SITE_NUMBER
, PS.SITE_NAME AS CRP_SITE_NAME
, CC.FIRST_NAME || ' ' || CC.LAST_NAME AS SITE_CONTRACT_MANAGER_NAME
, PS.SITE_ADDR_CONTACT_EMAIL AS EMAIL
, PS.PO_COMMUNICATION_EMAIL AS PO_COMMUNICATION_EMAIL
, PTH.CREATED_BY AS CREATED_BY
, PTH.CREATED_ON AS CREATED_ON_UTC
, PTH.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, PTH.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
, RANK() OVER (PARTITION BY PTH.POS_TXN_NUM ORDER BY PTH.PYMT_TRXN_HEADER_ID DESC) AS RECENT
FROM
{{ source('CES_MSCM', 'PYMT_TRANSACTION_HEADERS') }} AS PTH 
INNER JOIN {{ source('CES_MSCM', 'PYMT_TRANSACTION_LINES') }} AS PTL 
ON PTH.PYMT_TRXN_HEADER_ID = PTL.PYMT_TRXN_HEADER_ID
AND PTH.TRANSACTION_TYPE = 'REFUND'
INNER JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANTS') }} AS SP 
ON SP.PARTICIPANT_ID = PTH.PARTICIPANT_ID
INNER JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS MPS 
ON PTH.PARTICIPANT_SITE_ID = MPS.PARTICIPANT_SITE_ID
AND SP.PARTICIPANT_ID = MPS.PARTICIPANT_ID
INNER JOIN {{ source('CES_MSCM', 'CONSUMER_REFUND_TXN_DTL') }} AS RD 
ON PTL.ORIG_LINE_REFERENCE = RD.ID
INNER JOIN {{ source('CES_MSCM', 'CONSUMER_REFUND_TXN_HDR') }} AS RH 
ON RH.ID = PTH.POS_TXN_NUM
LEFT JOIN {{ source('CES_MSCM', 'POS_DEVICE') }} AS PD
ON RH.POS_DEVICE_ID = PD.ID
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS
ON NVL(NULLIF(RH.REFUND_CRP,''),PD.CRP_ID) = PS.SITE_NUMBER
LEFT JOIN (
    SELECT
    C.FIRST_NAME,
    C.LAST_NAME,
    LOWER(C.EMAIL) AS EMAIL
    FROM {{ source('CES_MSCM', 'MDT_CONTACTS') }} AS C
    WHERE ACTIVE = 1
    QUALIFY ROW_NUMBER() OVER (PARTITION BY LOWER(C.EMAIL) ORDER BY C.LAST_MODIFIED_ON DESC) = 1
    ) CC
ON LOWER(PS.ATTRIBUTE2) = CC.EMAIL
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME 
ON MPS.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
WHERE SP.CONSUMER_NUMBER IS NOT NULL