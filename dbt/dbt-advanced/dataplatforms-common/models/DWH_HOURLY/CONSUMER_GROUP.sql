SELECT
PS_G.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, PS_G.SITE_NUMBER || '-' || NVL(TO_CHAR(CR_G.CONTACT_ROLE_ID), '') AS ID
, NVL(PS_G.SITE_NUMBER || '-' || RT_G.CODE || '-' || TO_CHAR(CR_G.EFFECTIVE_START_DATE, 'YYYYMMDD') || '-' || TO_CHAR(NVL(DATEADD(DAY, -1, CR_G.EFFECTIVE_END_DATE), SYSDATE()), 'YYYYMMDD') || '-' || NVL(I.CONSUMER_ID_INDIVIDUAL, '-'), PS_G.SITE_NUMBER || '-' || NVL(TO_CHAR(CR_G.CONTACT_ROLE_ID), '')) AS ID2
, NVL(TO_CHAR(CR_G.EFFECTIVE_START_DATE, 'YYYYMMDD') || '-' || TO_CHAR(NVL(DATEADD(DAY, -1, CR_G.EFFECTIVE_END_DATE), SYSDATE()), 'YYYYMMDD') || '-' || NVL(I.CONSUMER_ID_INDIVIDUAL, '-'), PS_G.SITE_NUMBER || '-' || NVL(TO_CHAR(CR_G.CONTACT_ROLE_ID), '')) AS ID3
, PS_G.SITE_NUMBER AS CONSUMER_ID_GROUP
, R_G.VALUE AS CUSTOMER_GROUP
, CR_G.EFFECTIVE_START_DATE AS EFFECTIVE_START_DATE_GROUP
, CR_G.EFFECTIVE_END_DATE AS EFFECTIVE_END_DATE_GROUP
, CR_G.ACTIVE AS ROLE_ACTIVE_GROUP
, I.CONSUMER_ID_INDIVIDUAL AS CONSUMER_ID_INDIVIDUAL
, I.EFFECTIVE_START_DATE AS EFFECTIVE_START_DATE_INDIVIDUAL
, I.EFFECTIVE_END_DATE AS EFFECTIVE_END_DATE_INDIVIDUAL
, I.ACTIVE AS ROLE_ACTIVE_INDIVIDUAL
, RT_G.VALUE AS ROLE
, CASE WHEN RT_G.VALUE = 'Group Admin' THEN 'CAPTAIN' WHEN RT_G.VALUE = 'Group Member' THEN 'TEAMMATE' ELSE '-' END AS GROUP_ROLE
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS_G
INNER JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANTS') }} AS P_G
ON PS_G.PARTICIPANT_ID = P_G.PARTICIPANT_ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON PS_G.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'SCHEME_REF_CODES') }} AS R_G
ON P_G.PARTICIPANT_GROUP_ID = R_G.SCHEME_REF_CODES_ID
LEFT JOIN {{ source('CES_MSCM', 'MDT_CONTACT_ROLES') }} AS CR_G
ON PS_G.PARTICIPANT_SITE_ID = CR_G.PARTICIPANT_SITE_ID
LEFT JOIN {{ source('CES_MSCM', 'SCHEME_REF_CODES') }} AS RT_G
ON CR_G.ROLE_TYPE_ID = RT_G.SCHEME_REF_CODES_ID
LEFT JOIN (
    SELECT
    PS.MULTI_SCHEME_ID,
    PS.SITE_NUMBER AS CONSUMER_ID_INDIVIDUAL,
    CR.CONTACT_ID,
    CR.EFFECTIVE_START_DATE,
    CR.EFFECTIVE_END_DATE,
    CR.ACTIVE
    FROM {{ source('CES_MSCM', 'MDT_CONTACT_ROLES') }} AS CR
    INNER JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS
    ON CR.PARTICIPANT_SITE_ID = PS.PARTICIPANT_SITE_ID
    INNER JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANTS') }} AS P
    ON PS.PARTICIPANT_ID = P.PARTICIPANT_ID
    WHERE CR.ASSIGNMENT_TYPE = 'SITE'
    AND CR.ROLE_TYPE_ID = 2382 --Authorised Contact B2C
    AND P.PARTICIPANT_GROUP_ID = 1534 --Individual Consumer
    QUALIFY ROW_NUMBER() OVER (PARTITION BY PS.MULTI_SCHEME_ID, CR.CONTACT_ID ORDER BY PS.LAST_MODIFIED_ON DESC) = 1 --TO REMOVE THE DUPS SCXT-3407
) I
ON CR_G.CONTACT_ID = I.CONTACT_ID
AND PS_G.MULTI_SCHEME_ID = I.MULTI_SCHEME_ID
WHERE PS_G.SITE_TYPE_ID = '1537'
AND P_G.PARTICIPANT_GROUP_ID <> 1534 --Individual Consumer
AND NVL(RT_G.VALUE, '-') IN ('Group Admin', 'Group Member', '-')
QUALIFY ROW_NUMBER() OVER (PARTITION BY ID2 ORDER BY CR_G.LAST_MODIFIED_ON DESC) = 1 --remove dups SCXT-3415
AND ROW_NUMBER() OVER (PARTITION BY ID3 ORDER BY CONSUMER_ID_GROUP DESC) = 1 --remove individuals belong to multi groups at the same time period SCXT-3420