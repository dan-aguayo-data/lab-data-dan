SELECT
CA.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, CA.CLAIM_ID AS CLAIM_ID
, CA.SITE_NUMBER AS SITE_NUMBER
, PS.SITE_NAME AS SITE_NAME
, PS.PARTICIPANT_ID AS SUPPLIER_ID
, P.PARTICIPANT_NUMBER AS SUPPLIER_NUMBER
, P.PARTICIPANT_NAME AS SUPPLIER_NAME
, CA.PERIOD_TYPE AS PERIOD_TYPE
, CA.PERIOD AS PERIOD
, CA.ENTRY_TYPE AS ENTRY_TYPE
, CA.ENTRY_TYPE_DESCRIPTION AS ENTRY_TYPE_DESCRIPTION
, CA.VOLUME AS VOLUME
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(CA.SUBMITTED_DATE_UTC AS TIMESTAMP)) AS SUBMITTED_DATE_UTC
, CA.SUBMITTED_BY AS SUBMITTED_BY
, CA.STATUS AS STATUS
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(CA.REVIEWED_DATE_UTC AS TIMESTAMP)) AS REVIEWED_DATE_UTC
, CA.REVIEWED_BY AS REVIEWED_BY
, CA.KAFKA_DATETIME AS KAFKA_DATETIME
, SYSDATE() AS INSERT_DATE_UTC
FROM (
    SELECT
    CA.MULTI_SCHEME_ID
    , CA.CLAIM_ID
    , CA.CRP_SITE_NUMBER AS SITE_NUMBER
    , CA.PERIOD_TYPE AS PERIOD_TYPE
    , CA.PERIOD AS PERIOD
    , CA.TYPE_FLAG AS ENTRY_TYPE
    , CASE WHEN CA.TYPE_FLAG = 'R' THEN 'Claim' WHEN CA.TYPE_FLAG = 'A' THEN 'Adjustment' ELSE CA.TYPE_FLAG END AS ENTRY_TYPE_DESCRIPTION
    , CA.VOLUME AS VOLUME
    , CA.SUBMITTED_DATE_UTC AS SUBMITTED_DATE_UTC
    , CA.SUBMITTED_BY AS SUBMITTED_BY
    , CA.STATUS AS STATUS
    , CA.REVIEWED_DATE_UTC AS REVIEWED_DATE_UTC
    , CA.REVIEWED_BY AS REVIEWED_BY
    , CA.KAFKA_DATETIME AS KAFKA_DATETIME
    FROM {{ source('CES_MSCM_KAFKA', 'CRP_CLAIM_APPROVAL') }} AS CA
    UNION
    SELECT
    CC.MULTI_SCHEME_ID
    , CC.CLAIM_ID AS CLAIM_ID
    , CC.SITE_NUMBER AS SITE_NUMBER
    , CC.PERIOD_TYPE AS PERIOD_TYPE
    , CC.PERIOD AS PERIOD
    , 'R' AS ENTRY_TYPE
    , 'Claim'AS ENTRY_TYPE_DESCRIPTION
    , CC.VOLUME AS VOLUME
    , CC.SUBMITTED_DATE AS SUBMITTED_DATE_UTC
    , CC.SUBMITTED_BY AS SUBMITTED_BY
    , CC.STATUS AS STATUS
    , NULL AS REVIEWED_DATE_UTC
    , NULL AS REVIEWED_BY
    , CC.KAFKA_DATETIME AS KAFKA_DATETIME
    FROM {{ source('CES_MSCM_KAFKA', 'CRP_CLAIM') }} AS CC
    UNION
    SELECT
    CCA.MULTI_SCHEME_ID
    , CCA.ADJUSTMENT_ID AS CLAIM_ID
    , CCA.SITE_NUMBER AS SITE_NUMBER
    , CCA.PERIOD_TYPE AS PERIOD_TYPE
    , CCA.PERIOD AS PERIOD
    , 'A' AS ENTRY_TYPE
    , 'Adjustment' AS ENTRY_TYPE_DESCRIPTION
    , NULL AS VOLUME --not ready, not use it for now. Will add it until crp_claim_items is ready
    , CCA.SUBMITTED_DATE AS SUBMITTED_DATE_UTC
    , CCA.SUBMITTED_BY AS SUBMITTED_BY
    , CCA.STATUS AS STATUS
    , NULL AS REVIEWED_DATE_UTC
    , NULL AS REVIEWED_BY
    , CCA.KAFKA_DATETIME AS KAFKA_DATETIME
    FROM {{ source('CES_MSCM_KAFKA', 'CRP_CLAIM_ADJUSTMENT') }} AS CCA
) CA
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS
ON CA.SITE_NUMBER = PS.SITE_NUMBER
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANTS') }} AS P
ON PS.PARTICIPANT_ID = P.PARTICIPANT_ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON CA.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID