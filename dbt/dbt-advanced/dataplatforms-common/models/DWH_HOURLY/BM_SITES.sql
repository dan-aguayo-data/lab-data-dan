SELECT
PS.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, PS.SITE_NUMBER AS SITE_NUMBER
, PS.SITE_NAME AS SITE_NAME
, P.PARTICIPANT_NUMBER AS SUPPLIER_NUMBER
, P.PARTICIPANT_NAME AS SUPPLIER_NAME
, R_TT.VALUE AS TAXONOMY
, PS.TAXONOMY_SIZE AS TAXONOMY_SIZE
, DECODE(PS.TAXONOMY_SUB_TYPE, 'Manufacturer - Large', 'MONTHLY', 'Manufacturer - Small', 'QUARTERLY', 'Manufacturer - Micro', 'YEARLY') AS INVOICE_FREQUENCY
, PS.STATUS AS STATUS
, P.INACTIVE_DATE AS SITE_INACTIVE_DATE
, PS.CONTRACT_ORGANISATION_ID AS CONTRACT_ORGANISATION_ID
, CASE WHEN PS.MULTI_SCHEME_ID = 10000 AND COALESCE(SSC.REGION, POA.REGION, R.REGION) IS NULL THEN '00 Unknown' ELSE NVL(COALESCE(SSC.REGION, POA.REGION, R.REGION), 'Unknown') END AS REGION
, CASE WHEN PS.MULTI_SCHEME_ID = 10000 AND COALESCE(SSC.SUBREGION, POA.SUBREGION, R.SUBREGION) IS NULL THEN '00 Unknown' ELSE NVL(COALESCE(SSC.SUBREGION, POA.SUBREGION, R.SUBREGION), 'Unknown') END AS SUBREGION
, PS.ADDRESS_LINE_1 AS ADDRESS_LINE_1
, PS.ADDRESS_LINE_2 AS ADDRESS_LINE_2
, PS.CITY_SUBURB AS SUBURB
, PS.STATE AS STATE
, PS.POST_CODE AS POSTCODE
, R_C.VALUE AS COUNTRY
, LGA.VALUE AS LGA
, AR.VALUE AS AREA
, PS.X_CORDINDATES AS X_COORDINATES
, PS.Y_CORDINATES AS Y_COORDINATES
, PS.SITE_ADDR_CONTACT_PHONE_NUMBER AS PHONE_NUMBER
, PS.SITE_ADDR_CONTACT_PHONE_EXT AS PHONE_EXT
, PS.SITE_ADDR_CONTACT_EMAIL AS EMAIL
, PS.PO_COMMUNICATION_EMAIL AS PO_COMMUNICATION_EMAIL
, PS.PYMT_REMIT_ADV_EMAIL AS PYMT_REMIT_ADV_EMAIL
, PT.INVOICE_TYPE AS INVOICE_TYPE
, PT.INVOICE_PAYMENT_GROUP AS INVOICE_PAYMENT_GROUP
, PT.INV_PAYMENT_TERMS AS INV_PAYMENT_TERMS
, PSU_ST.SOLD_TO_CUST_ACC_NUMBER AS SOLD_TO_CUST_ACC_NUMBER
, PS.WEB_SITE_URL AS WEB_SITE_URL
, PS.DISPLAY_IN_MARKETING AS DISPLAY_IN_MARKETING
, PS.CRM_SITE_ID AS CRM_SITE_ID
, PS.ERP_ADDRESS_ID AS ERP_ADDRESS_ID
, PS.TAXONOMY_SUB_TYPE AS MANUFACTURER_TYPE
, CO.CONTRACT_ORGANIZATION_NUMBER AS CONTRACT_ORGANIZATION_NUMBER
, CO.CRM_CONTRACT_ORG_ID AS CRM_CONTRACT_ORG_ID
, CO.CONTRACT_TYPE AS CONTRACT_TYPE
, CO.STATUS AS CONTRACT_STATUS
, CO.ESTABLISHED_DATE AS CONTRACT_ESTABLISHED_DATE
, CO.INACTIVE_DATE AS CONTRACT_INACTIVE_DATE
, CO.CURRENT_CONTRACT_EXPIRY_DATE AS CONTRACT_EXPIRY_DATE
, CO.CURRENT_CONTRACT_TERM AS CONTRACT_TERM
, CO.CONTRACT_MANAGER AS CONTRACT_MANAGER
, LEFT(PS.ATTRIBUTE12, POSITION('-',PS.ATTRIBUTE12)-1) AS LEGAL_ENTITY_ID
, CASE WHEN (INITCAP(PS.STATUS) = 'Active' AND S.ABR_ABN_STATUS = 'ACT') OR (INITCAP(PS.STATUS) = 'Inactive' AND S.ABR_ABN_STATUS = 'CAN') THEN 'Reconciled' WHEN INITCAP(PS.STATUS) = 'Inactive' AND S.ABR_ABN_STATUS = 'ACT' THEN 'Contract Inactive, ABR Active' WHEN INITCAP(PS.STATUS) = 'Active' AND S.ABR_ABN_STATUS = 'CAN' THEN 'Contract Active, ABR Inactive' ELSE 'Not Reconciled' END AS ABN_STATUS_RECONCILIATION_SITE
, CASE WHEN S.ABN_RECONCILIATION = 'Reconciled' AND ABN_STATUS_RECONCILIATION_SITE IN ('Reconciled', 'Contract Inactive, ABR Active') AND S.LEGAL_NAME_RECONCILIATION = 'Reconciled' THEN 'Reconciled' ELSE 'Not Reconciled' END AS FINAL_RECONCILIATION
, NVL(BS.SUBMITTED_LAST_3_MONTHS, 'No') AS SUBMITTED_LAST_3_MONTHS
, NVL(BS2.SUBMITTED_AT_LEAST_3_MONTHS, 'Never') AS SUBMITTED_AT_LEAST_3_MONTHS
, PS.ATTRIBUTE1 AS SCHEME_COMMENCEMENT_DATE
, CASE WHEN PS.ATTRIBUTE4 = '1' THEN 'Yes' ELSE 'No' END AS THIRD_PARTY_FLAG
, PS.ATTRIBUTE5 AS ZONE
, PS.ATTRIBUTE6 AS CCSP_PAIR
, PS.ATTRIBUTE7 AS AUTOMATED_COUNTING_FACILITY
, PS.ATTRIBUTE8 AS OVER_THE_COUNTER
, PS.ATTRIBUTE9 AS NOT_FOR_PROFIT
, PS.ATTRIBUTE10 AS SUPPLIER_ARRANGEMENT_NO
, PS.ATTRIBUTE13 AS DRIVE_THROUGH_FACILITY
, CASE WHEN PS.ATTRIBUTE16 = 1 THEN 'true' WHEN PS.ATTRIBUTE16 = 0 THEN 'false' ELSE NULL END AS W_S_FLAG
, CASE WHEN CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(PS.CREATED_ON AS TIMESTAMP)) >= DATE_TRUNC('MONTH', DATEADD(MONTH, -11, CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, SYSDATE()))) THEN 1 ELSE 0 END AS CREATED_LESS_THAN_11_CALENDAR_MONTHS
, SV.SALES_VOLUME_LAST_12_MONTHS AS SALES_VOLUME_LAST_12_MONTHS
, CASE WHEN CREATED_LESS_THAN_11_CALENDAR_MONTHS = 0 THEN CASE WHEN SV.SALES_VOLUME_LAST_12_MONTHS >= 300000 THEN 'MONTHLY' WHEN SV.SALES_VOLUME_LAST_12_MONTHS < 100000 AND PS.MULTI_SCHEME_ID = 10000 AND TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(PS.CREATED_ON AS TIMESTAMP)), 'YYYYMMDD') >= '20231101' THEN 'YEARLY' WHEN SV.SALES_VOLUME_LAST_12_MONTHS IS NULL THEN 'No Submission in 12 Months' ELSE 'QUARTERLY' END ELSE 'BM Created in 12 Months' END AS CALCULATED_INVOICE_FREQUENCY
, CASE WHEN CREATED_LESS_THAN_11_CALENDAR_MONTHS = 0 THEN CASE WHEN DECODE(PS.TAXONOMY_SUB_TYPE, 'Manufacturer - Large', 'MONTHLY', 'Manufacturer - Small', 'QUARTERLY', 'Manufacturer - Micro', 'YEARLY') = CALCULATED_INVOICE_FREQUENCY THEN 'TRUE' WHEN SV.SALES_VOLUME_LAST_12_MONTHS IS NULL THEN 'No Submission in 12 Months' ELSE 'FALSE' END ELSE 'BM Created in 12 Months' END AS INVOICE_FREQUENCY_CHECK
, CASE WHEN PS.TAXONOMY_SUB_TYPE = PS.TAXONOMY_SIZE THEN 'TRUE' ELSE 'FLASE' END AS TAXONOMY_CHECK
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(PS.CREATED_ON AS TIMESTAMP)) AS CREATED_ON
, PS.CREATED_BY AS CREATED_BY
, PS.CREATED_ON AS CREATED_ON_UTC
, PS.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, PS.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS
INNER JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANTS') }} AS P
ON P.PARTICIPANT_ID = PS.PARTICIPANT_ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON PS.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN 
    (SELECT
    SU.PARTICIPANT_SITE_ID,
    SU.INV_PAYMENT_TERMS
    FROM (
        SELECT 
        ROW_NUMBER() OVER (PARTITION BY U.PARTICIPANT_SITE_ID ORDER BY U.LAST_MODIFIED_ON DESC) AS N,
        U.PARTICIPANT_SITE_ID,
        U.INV_PAYMENT_TERMS
        FROM {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITE_USES') }} AS U
    ) SU
    WHERE SU.INV_PAYMENT_TERMS IS NOT NULL
    AND SU.N = 1
    ) PSU_PT
ON PS.PARTICIPANT_SITE_ID = PSU_PT.PARTICIPANT_SITE_ID
LEFT JOIN 
    (SELECT
    SU.PARTICIPANT_SITE_ID,
    SU.SOLD_TO_CUST_ACC_NUMBER
    FROM (
        SELECT 
        ROW_NUMBER() OVER (PARTITION BY U.PARTICIPANT_SITE_ID ORDER BY U.LAST_MODIFIED_ON DESC) AS N,
        U.PARTICIPANT_SITE_ID,
        U.SOLD_TO_CUST_ACC_NUMBER
        FROM {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITE_USES') }} AS U
        WHERE U.SITE_USE_TYPE = 'BILL_TO'
    ) SU
    WHERE SU.SOLD_TO_CUST_ACC_NUMBER IS NOT NULL
    AND SU.N = 1
    ) PSU_ST
ON PS.PARTICIPANT_SITE_ID = PSU_ST.PARTICIPANT_SITE_ID
LEFT JOIN {{ source('CES_MSCM', 'SCHEME_REF_CODES') }} AS R_TT
ON PS.TAXONOMY_TYPE_ID = R_TT.SCHEME_REF_CODES_ID
LEFT JOIN {{ source('CES_MSCM', 'SCHEME_REF_CODES') }} AS R_C
ON PS.COUNTRY_ID = R_C.SCHEME_REF_CODES_ID
LEFT JOIN {{ source('CES_MSCM', 'SCHEME_REF_CODES') }} AS LGA
ON PS.LGA_ID = LGA.SCHEME_REF_CODES_ID
LEFT JOIN {{ source('CES_MSCM', 'SCHEME_REF_CODES') }} AS AR
ON PS.AREA_ID = AR.SCHEME_REF_CODES_ID
LEFT JOIN {{ source('CES_MSCM', 'MDT_SCHEME_CONTRACT_ORGS') }} AS CO
ON PS.CONTRACT_ORGANISATION_ID = CO.CONTRACT_ORGANIZATION_ID
LEFT JOIN {{ ref('B2B_SUPPLIERS') }} AS S
ON P.PARTICIPANT_NUMBER = S.SUPPLIER_NUMBER
LEFT JOIN (
    SELECT 
    BMS.SITE_NUMBER,
    CASE WHEN COUNT(DISTINCT BMS.PERIOD) >= 3 THEN 'Yes' ELSE 'No' END AS SUBMITTED_LAST_3_MONTHS
    FROM
    {{ ref('BM_SALES_VOLUME') }} AS BMS
    WHERE BMS.STATUS = 'INVOICED' 
    AND BMS.ENTRY_TYPE = 'R'
    AND LEFT(DATEADD('MONTH',-3,SYSDATE()),7) <= BMS.PERIOD 
    GROUP BY BMS.SITE_NUMBER) BS
ON PS.SITE_NUMBER = BS.SITE_NUMBER 
LEFT JOIN (
    SELECT 
    BMS.SITE_NUMBER,
    CASE WHEN COUNT(DISTINCT BMS.PERIOD) >= 3 THEN 'Yes' WHEN COUNT(DISTINCT BMS.PERIOD) = 0 THEN 'Never' ELSE 'No' END AS SUBMITTED_AT_LEAST_3_MONTHS
    FROM
    {{ ref('BM_SALES_VOLUME') }} AS BMS
    WHERE BMS.STATUS = 'INVOICED' 
    AND BMS.ENTRY_TYPE = 'R'
    GROUP BY BMS.SITE_NUMBER) BS2
ON PS.SITE_NUMBER = BS2.SITE_NUMBER 
LEFT JOIN (
    SELECT
    SH.MULTI_SCHEME_ID
    , SH.MANUFACTURER_ID AS SITE_NUMBER
    , SUM(SD.VOLUME) AS SALES_VOLUME_LAST_12_MONTHS
    FROM
    {{ source('CES_MSCM', 'MFG_SALES_VOLUME_DTL') }} AS SD
    INNER JOIN {{ source('CES_MSCM', 'MFG_SALES_VOLUME_HDR') }} AS SH
    ON SD.MFG_SALES_VOLUME_HDR_ID = SH.ID
    LEFT JOIN {{ ref('REF_DATE') }} AS DT
    ON DT.DAY = 1
    AND SH.PERIOD = DT.YEAR_MONTH
    WHERE SH.ENTRY_TYPE IN ('R', 'A', 'L')
    AND SH.STATUS IN ('FINAL', 'INVOICED')
    AND DT.LAST_N_MONTH BETWEEN 2 AND 13
    GROUP BY ALL
) SV
ON PS.SITE_NUMBER = SV.SITE_NUMBER
LEFT JOIN {{ ref('REF_STATE') }} AS STATE
ON STATE.STATE = PS.STATE 
LEFT JOIN {{ ref('REF_LOCALITY_SSC') }} AS SSC
ON PS.CITY_SUBURB = SSC.SUBURB
AND PS.POST_CODE = SSC.POSTCODE
AND STATE.STATE_NAME = SSC.STATE
LEFT JOIN {{ ref('REF_LOCALITY_POA') }} AS POA
ON PS.POST_CODE = POA.POSTCODE
AND STATE.STATE_NAME = POA.STATE
LEFT JOIN {{ ref('B2B_REGION') }} AS R
ON PS.SITE_NUMBER = R.SITE_NUMBER
LEFT JOIN (
    SELECT
    MULTI_SCHEME_ID,
    INVOICE_TYPE,
    PAYMENT_GROUP AS INVOICE_PAYMENT_GROUP,
    VALUE AS INV_PAYMENT_TERMS
    FROM {{ source('CES_MSCM', 'INV_PAYMENT_TERMS_LOV') }} AS INPT
    WHERE INPT.INVOICE_TYPE = 'AR'
    AND INPT.SCHEME_PARTICIPANT_TYPE = 'MANUFACTURER'
    AND INPT.PAYMENT_GROUP = 'SCHEME_CONTRIBUTION'
) PT
ON CASE WHEN TO_CHAR(PS.MULTI_SCHEME_ID) NOT LIKE '10003%' THEN PT.MULTI_SCHEME_ID IS NULL ELSE PS.MULTI_SCHEME_ID = PT.MULTI_SCHEME_ID END

WHERE PS.SITE_TYPE_ID ='1540'
 
UNION ALL
 
SELECT
-1 AS MULTI_SCHEME_ID
, 'CES' AS SCHEME
, '-' AS SITE_NUMBER
, NULL AS SITE_NAME
, NULL AS SUPPLIER_NUMBER
, NULL AS SUPPLIER_NAME
, NULL AS TAXONOMY
, NULL AS TAXONOMY_SIZE
, NULL AS INVOICE_FREQUENCY
, NULL AS STATUS
, NULL AS SITE_INACTIVE_DATE
, NULL AS CONTRACT_ORGANISATION_ID
, NULL AS REGION
, NULL AS SUBREGION
, NULL AS ADDRESS_LINE_1
, NULL AS ADDRESS_LINE_2
, NULL AS SUBURB
, NULL AS STATE
, NULL AS POSTCODE
, NULL AS COUNTRY
, NULL AS LGA
, NULL AS AREA
, NULL AS X_COORDINATES
, NULL AS Y_COORDINATES
, NULL AS PHONE_NUMBER
, NULL AS PHONE_EXT
, NULL AS EMAIL
, NULL AS PO_COMMUNICATION_EMAIL
, NULL AS PYMT_REMIT_ADV_EMAIL
, NULL AS INVOICE_TYPE
, NULL AS INVOICE_PAYMENT_GROUP
, NULL AS INV_PAYMENT_TERMS
, NULL AS SOLD_TO_CUST_ACC_NUMBER
, NULL AS WEB_SITE_URL
, NULL AS DISPLAY_IN_MARKETING
, NULL AS CRM_SITE_ID
, NULL AS ERP_ADDRESS_ID
, NULL AS MANUFACTURER_TYPE
, NULL AS CONTRACT_ORGANIZATION_NUMBER
, NULL AS CRM_CONTRACT_ORG_ID
, NULL AS CONTRACT_TYPE
, NULL AS CONTRACT_STATUS
, NULL AS CONTRACT_ESTABLISHED_DATE
, NULL AS CONTRACT_INACTIVE_DATE
, NULL AS CONTRACT_EXPIRY_DATE
, NULL AS CONTRACT_TERM
, NULL AS CONTRACT_MANAGER
, NULL AS LEGAL_ENTITY_ID
, NULL AS ABN_STATUS_RECONCILIATION_SITE
, NULL AS FINAL_RECONCILIATION
, NULL AS SUBMITTED_LAST_3_MONTHS
, NULL AS SUBMITTED_AT_LEAST_3_MONTHS
, NULL AS SCHEME_COMMENCEMENT_DATE
, NULL AS THIRD_PARTY_FLAG
, NULL AS ZONE
, NULL AS CCSP_PAIR
, NULL AS AUTOMATED_COUNTING_FACILITY
, NULL AS OVER_THE_COUNTER
, NULL AS NOT_FOR_PROFIT
, NULL AS SUPPLIER_ARRANGEMENT_NO
, NULL AS DRIVE_THROUGH_FACILITY
, NULL AS W_S_FLAG
, 0 AS CREATED_LESS_THAN_11_CALENDAR_MONTHS
, NULL AS SALES_VOLUME_LAST_12_MONTHS
, NULL AS CALCULATED_INVOICE_FREQUENCY
, NULL AS INVOICE_FREQUENCY_CHECK
, NULL AS TAXONOMY_CHECK
, NULL AS CREATED_ON
, NULL AS CREATED_BY
, TO_DATE('01/01/2021', 'DD/MM/YYYY') AS CREATED_ON_UTC
, NULL AS LAST_MODIFIED_BY
, TO_DATE('01/01/2021', 'DD/MM/YYYY') AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
