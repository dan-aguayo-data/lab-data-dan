SELECT
SP.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, SP.ID AS ID
, SP.PRODUCT_ID AS PRODUCT_ID
, SP.MANUFACTURER_ID AS BM_SITE_NUMBER
, PS_BM.SITE_NAME AS BM_SITE_NAME
, NVL2(PDS.SCHEME_PRODUCT_ID, PDS.NAME, PA.NAME) AS PRODUCT_NAME
, NVL2(PDS.SCHEME_PRODUCT_ID, PDS.EAN, PA.EAN) AS BARCODE
, REPLACE(UPPER(NVL2(PDS.SCHEME_PRODUCT_ID, PDS.GLASS_COLOUR, PA.GLASS_COLOUR)), '/', '_') AS GLASS_COLOUR
, UPPER(SP.STATUS) AS STATUS
, SP.STATUS_CHANGE_TEXT AS STATUS_CHANGE_TEXT
, CAST(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(SP.STATUS_CHANGED_ON AS TIMESTAMP)) AS DATE) AS STATUS_CHANGED_DATE
, TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(SP.STATUS_CHANGED_ON AS TIMESTAMP)), 'YYYYMMDD') AS STATUS_CHANGED_DATE_KEY
, SP.SUBMITTED_BY AS SUBMITTED_BY
, CAST(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(SP.SUBMITTED_DATE AS TIMESTAMP)) AS DATE) AS SUBMITTED_DATE
, SP.SUBMITTED_SOURCE AS SUBMITTED_SOURCE
, SP.AUDIT_TYPE AS AUDIT_TYPE
, SP.AUDIT_DATE AS AUDIT_DATE
, SP.CREATED_BY AS CREATED_BY
, SP.CREATED_ON AS CREATED_ON_UTC
, SP.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, SP.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM', 'SCHEME_PRODUCT_A') }} AS SP
LEFT JOIN {{ source('CES_MSCM', 'PRODUCT_STAGING') }} AS PDS
ON SP.ID = PDS.SCHEME_PRODUCT_ID
LEFT JOIN {{ source('CES_MSCM', 'PRODUCT_GROUP') }} AS G
ON PDS.PRODUCT_GROUP_ID = G.ID
LEFT JOIN (
    SELECT
    PD.ID,
    PD.NAME,
    PD.GLASS_COLOUR,
    PD.EAN
    FROM {{ source('CES_MSCM', 'PRODUCT') }} AS PD
    INNER JOIN {{ source('CES_MSCM', 'PRODUCT_GROUP') }} AS G
    ON PD.PRODUCT_GROUP_ID = G.ID
) PA 
ON SP.PRODUCT_ID = PA.ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON SP.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS_BM
ON SP.MANUFACTURER_ID = PS_BM.SITE_NUMBER