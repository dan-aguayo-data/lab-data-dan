SELECT
RP.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, RP.ID AS ID
, RP.SELLER_ID AS SELLER_ID
, PS.SITE_NAME AS SELLER_NAME
, RP.BUYER_ID AS BUYER_ID
, P.SITE_NAME AS BUYER_NAME
, RP.SCHEME_MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID
, MT.NAME AS MATERIAL_TYPE
, RP.MRF_MATERIAL_TYPE_ID AS MRF_MATERIAL_TYPE_ID
, MT_MRF.NAME AS MRF_MATERIAL_TYPE
, RP.PRICE_PER_TONNE AS PRICE_PER_TONNE
, CAST(RP.EFFECTIVE_FROM AS DATE) AS EFFECTIVE_FROM
, TO_CHAR(RP.EFFECTIVE_FROM, 'YYYYMMDD') AS EFFECTIVE_FROM_KEY
, CAST(RP.EFFECTIVE_TO AS DATE) AS EFFECTIVE_TO
, RP.SUBMITTED_BY AS SUBMITTED_BY
, RP.SUBMITTED_ON AS SUBMITTED_ON_UTC
, RP.CREATED_BY AS CREATED_BY
, RP.CREATED_ON AS CREATED_ON_UTC
, RP.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, RP.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM', 'DIRECT_SALE_CONTRACT') }} AS RP
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON RP.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS
ON RP.SELLER_ID= PS.SITE_NUMBER
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS P
ON RP.BUYER_ID= P.SITE_NUMBER
LEFT JOIN {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS MT
ON RP.SCHEME_MATERIAL_TYPE_ID = MT.ID
LEFT JOIN {{ source('CES_MSCM', 'MRF_MATERIAL_TYPE') }} AS MT_MRF
ON RP.MRF_MATERIAL_TYPE_ID = MT_MRF.ID