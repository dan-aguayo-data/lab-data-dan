SELECT
PTH.MULTI_SCHEME_ID  AS MULTI_SCHEME_ID 
, SCHEME.NAME AS SCHEME
, PTH.PYMT_TRXN_HEADER_ID AS ID
, PTH.POS_TXN_NUM AS POS_TXN_NUM
, PTH.PAYMENT_BATCH_ID AS PAYMENT_BATCH_ID
, PTH.PAYMENT_METHOD AS PAYMENT_METHOD
, PTH.CONSUMER_ID AS CONSUMER_ID
, PTH.CONSUMER_NAME AS CONSUMER_NAME
, PTH.CRP_SITE_NUMBER AS CRP_SITE_NUMBER
, PTH.CRP_SITE_NAME AS CRP_SITE_NAME
, PTH.SITE_CONTRACT_MANAGER_NAME AS SITE_CONTRACT_MANAGER_NAME
, PTH.EMAIL AS EMAIL
, PTH.PO_COMMUNICATION_EMAIL AS PO_COMMUNICATION_EMAIL
, PTH.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID
, PTH.LINE_NUM AS LINE_NUM
, PTH.PAYMENT_PERIOD AS PAYMENT_PERIOD
, PTH.PERIOD AS PERIOD
, PTH.VOLUME AS VOLUME
, PTH.GROSS_AMOUNT AS GROSS_AMOUNT
, PTH.VOID_STATUS AS VOID_STATUS
, PTH.PAY_REF_NUMBER AS PAY_REF_NUMBER
, PTH.PAID AS PAID
, PTH.INVOICED AS INVOICED
, PTH.ERP_PAID AS ERP_PAID
, PTH.PAYMENT_AMOUNT AS PAYMENT_AMOUNT
, PTH.PAYMENT_LINE_AGG AS PAYMENT_LINE_AGG
, PTH.CREATED_BY AS CREATED_BY
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(PTH.CREATED_ON_UTC AS TIMESTAMP)) AS CREATED_ON
, PTH.CREATED_ON_UTC AS CREATED_ON_UTC
, PTH.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, GREATEST(NVL(PTH.LAST_MODIFIED_ON_UTC, TO_DATE('01/01/1900', 'DD/MM/YYYY')), NVL(PYMT.LAST_MODIFIED_ON_UTC, TO_DATE('01/01/1900', 'DD/MM/YYYY')), NVL(POS_STATUS.LAST_MODIFIED_ON_UTC, TO_DATE('01/01/1900', 'DD/MM/YYYY')), NVL(INV.LAST_MODIFIED_ON_UTC, TO_DATE('01/01/1900', 'DD/MM/YYYY')), NVL(INV_POS.LAST_MODIFIED_ON_UTC, TO_DATE('01/01/1900', 'DD/MM/YYYY')), NVL(PA_2.LAST_MODIFIED_ON_UTC, TO_DATE('01/01/1900', 'DD/MM/YYYY')), NVL(POS.LAST_MODIFIED_ON_UTC, TO_DATE('01/01/1900', 'DD/MM/YYYY'))) AS LAST_MODIFIED_ON_UTC
, PYMT.APPROVAL_FLAG AS APPROVAL_FLAG
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(PYMT.PAID_DATE AS TIMESTAMP)) AS PAID_DATE
, TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(PYMT.PAID_DATE AS TIMESTAMP)),'YYYYMMDD') AS PAID_DATE_KEY
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(PYMT.ERP_PAID_DATE AS TIMESTAMP)) AS ERP_PAID_DATE
, TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(PYMT.ERP_PAID_DATE AS TIMESTAMP)),'YYYYMMDD') AS ERP_PAID_DATE_KEY
, CONVERT_TIMEZONE('UTC','Australia/Sydney',CAST(PYMT.FILE_RECEIVED_DATE AS TIMESTAMP)) AS FILE_RECEIVED_DATE
, TO_CHAR(CONVERT_TIMEZONE('UTC','Australia/Sydney',CAST(PYMT.FILE_RECEIVED_DATE AS TIMESTAMP)),'YYYYMMDD') AS FILE_RECEIVED_DATE_KEY
, CASE WHEN PTH.MULTI_SCHEME_ID IN (10000, 10001) AND B.PAY_REF_NUMBER IS NOT NULL AND (TO_CHAR(CONVERT_TIMEZONE('UTC', 'Australia/Sydney', PYMT.FILE_RECEIVED_DATE), 'HH24MI') >= '1930' OR D.WORKDAY_FLAG_NSW = 0) THEN D.NEXT_WORKDAY ELSE CAST(CONVERT_TIMEZONE('UTC', 'Australia/Sydney', PYMT.FILE_RECEIVED_DATE) AS DATE) END AS PROCESSING_DATE
, TO_CHAR(CASE WHEN PTH.MULTI_SCHEME_ID IN (10000, 10001) AND B.PAY_REF_NUMBER IS NOT NULL AND (TO_CHAR(CONVERT_TIMEZONE('UTC', 'Australia/Sydney', PYMT.FILE_RECEIVED_DATE), 'HH24MI') >= '1930' OR D.WORKDAY_FLAG_NSW = 0) THEN D.NEXT_WORKDAY ELSE CAST(CONVERT_TIMEZONE('UTC', 'Australia/Sydney', PYMT.FILE_RECEIVED_DATE) AS DATE) END, 'YYYYMMDD') AS PROCESSING_DATE_KEY
, PYMT.VOID AS VOID
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(PYMT.VOIDED_DATE AS TIMESTAMP)) AS VOIDED_DATE
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(PYMT.INVOICED_DATE AS TIMESTAMP)) AS INVOICED_DATE
, TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(PYMT.INVOICED_DATE AS TIMESTAMP)),'YYYYMMDD') AS INVOICED_DATE_KEY
, coalesce(pymt.paid, pymt.payment_error, 'Not Paid') AS PAYMENT_STATUS
, coalesce(pa_2.status, pos.status) AS APPROVAL_STATUS
, NVL(PA_2.LOGIN_ID, POS.LOGIN_ID) AS CURRENT_APPROVAL_LEVEL
, NVL(PA_2.LAST_MODIFIED_ON_SYD, POS.LAST_MODIFIED_ON_SYD) AS APPROVAL_LAST_MODIFIED_ON_SYD
, coalesce(pymt.invoiced, pymt.error_inv_erp, pos_status.invoiced, 'NOT INVOICED') AS COMPLETE_STATUS
, coalesce(pa_2.pcs_id, pos.pcs_id) AS NOTIFICATION_ID
, coalesce(pymt.erp_payment_complete, pymt.error_pay_erp, pymt.no_valid_erp_bnk, pos_status.erp_payment_complete, 'NO ERP PAYMENT') AS ERP_PAYMENT_STATUS
, coalesce(inv.invoice_amount, inv_pos.invoice_amount) AS INVOICE_AMOUNT
, coalesce(inv.invoice_number_and_status, inv_pos.invoice_number_and_status) AS INVOICE_NUMBER_AND_STATUS
, CASE WHEN coalesce(pymt.invoiced, pymt.error_inv_erp, pos_status.invoiced, 'NOT INVOICED') = 'Invoiced' OR coalesce(pymt.invoiced, pymt.error_inv_erp, pos_status.invoiced, 'NOT INVOICED') LIKE '%ERROR%' THEN coalesce(pymt.invoiced, pymt.error_inv_erp, pos_status.invoiced, 'NOT INVOICED') ELSE 'Not Invoiced' END AS INVOICE_STATUS
, NVL2(coalesce(pa_2.pcs_id, pos.pcs_id), 'Y', 'N') AS NOTIFICATION_ID_ASSIGNED_FLAG
, CASE WHEN PYMT.APPROVAL_FLAG = 'N' THEN 'Payment Without Approval' WHEN PYMT.APPROVAL_FLAG = 'Y' THEN 'Workflow Amount' ELSE '-' END AS WORKFLOW_STATUS
, CASE WHEN PTH.INVOICED = 'Y' THEN 'Invoiced' ELSE 'Not Invoiced' END AS ERP_INVOICE_STATUS_VOID
, CASE WHEN PTH.ERP_PAID = 'Y' THEN 'ERP Payment Completed' ELSE 'No ERP Payment' END AS ERP_PAYMENT_STATUS_VOID
, CASE WHEN PTH.PAID = 'Y' AND PTH.VOID_STATUS = 'VOIDED' THEN 'Return from Bank' WHEN PTH.PAID = 'Y' THEN 'Paid' ELSE 'Not Paid' END AS PAYMENT_STATUS_VOID
, 'Gross Amount' AS GROSS_AMOUNT_HEADER
, 'Volume' AS VOLUME_HEADER
, 'Number of Transactions' AS NUMBER_OF_TRANSACTIONS_HEADER
, SYSDATE() AS INSERT_DATE_UTC
, PTH.RECENT AS PYMT_AMOUNT_RECENT_FLAG
, CASE WHEN coalesce(pymt.invoiced, pymt.error_inv_erp, pos_status.invoiced, 'NOT INVOICED') = 'INVOICED'
    AND coalesce(pymt.paid, pymt.payment_error, 'Not Paid') = 'PAID'
    AND coalesce(pymt.erp_payment_complete, pymt.error_pay_erp, pymt.no_valid_erp_bnk, pos_status.erp_payment_complete, 'NO ERP PAYMENT') = 'ERP PAYMENT COMPLETED'
    AND round(PTH.PAYMENT_AMOUNT,2) = round(coalesce(inv.invoice_amount, inv_pos.invoice_amount),2)
    THEN 'Reconciled Amount'
    ELSE (CASE WHEN round(PTH.PAYMENT_AMOUNT,2) > round(coalesce(inv.invoice_amount, inv_pos.invoice_amount),2)
        THEN 'PAAS Amount is More Than ERP'
        WHEN round(PTH.PAYMENT_AMOUNT,2) < round(coalesce(inv.invoice_amount, inv_pos.invoice_amount),2)
        THEN 'PAAS Amount is Less Than ERP'
        ELSE 'Other Unreconciled Amount' END
        )
    END AS RECONCILIATION_FLAG
, CASE WHEN coalesce(pymt.invoiced, pymt.error_inv_erp, pos_status.invoiced, 'NOT INVOICED') = 'INVOICED'
    AND coalesce(pymt.paid, pymt.payment_error, 'Not Paid') = 'PAID'
    AND coalesce(pymt.erp_payment_complete, pymt.error_pay_erp, pymt.no_valid_erp_bnk, pos_status.erp_payment_complete, 'NO ERP PAYMENT') = 'ERP PAYMENT COMPLETED'
    AND round(PTH.PAYMENT_AMOUNT,2) = round(coalesce(inv.invoice_amount, inv_pos.invoice_amount),2)
    THEN 'Reconciled Amount'
    ELSE 'Unreconciled Amount'
    END AS RECONCILIATION_FLAG_SIMPLE
FROM
{{ ref('PYMT_AMOUNT') }} AS PTH
INNER JOIN {{ ref('PYMT_STATUS') }} AS PYMT 
ON PYMT.ID = PTH.PYMT_TRXN_HEADER_ID 
AND PYMT.ID_TYPE = 'PYMT_TRXN_HEADER_ID'
--AND PTH.RECENT = 1
LEFT JOIN {{ ref('PYMT_STATUS') }} AS POS_STATUS 
ON POS_STATUS.ID = PTH.POS_TXN_NUM 
AND POS_STATUS.ID_TYPE = 'POS_TXN_NUM' 
LEFT JOIN {{ ref('INV_AMOUNT') }} AS INV 
ON INV.ID = PTH.PYMT_TRXN_HEADER_ID 
AND INV.ID_TYPE = 'PYMT_TRXN_HEADER_ID'
LEFT JOIN {{ ref('INV_AMOUNT') }} AS INV_POS 
ON INV_POS.ID = PTH.POS_TXN_NUM 
AND INV_POS .ID_TYPE = 'POS_TXN_NUM'
LEFT JOIN {{ ref('PYMT_APPROVAL') }} AS PA_2 
ON PA_2.ID = PTH.PYMT_TRXN_HEADER_ID 
AND PA_2.ID_TYPE = 'PYMT_TRXN_HEADER_ID'
AND PA_2.RECENT = 1
LEFT JOIN {{ ref('PYMT_APPROVAL') }} AS POS 
ON POS.ID = PTH.POS_TXN_NUM 
AND POS.ID_TYPE = 'POS_TXN_NUM'
AND POS.RECENT = 1
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME 
ON SCHEME.MULTI_SCHEME_ID = PTH.MULTI_SCHEME_ID
LEFT JOIN (
    SELECT DISTINCT
    SD.PAY_REF_NUMBER
    FROM {{ source('CES_MSCM_KAFKA', 'PYMT_STEP_DOWN') }} AS SD
    WHERE SD.PAY_REF_NUMBER NOT IN (
        SELECT DISTINCT
        CASE WHEN L.TYPE_CODE = 495 AND L.CUSTOMER_REF_NUM IS NULL THEN SPLIT_PART(L.TEXT, ' ', -1) ELSE L.CUSTOMER_REF_NUM END AS PAY_REF_NUMBER
        FROM {{ source('RAW_CES_FINANCE', 'ANZ_BTR_LINES') }} AS L
        WHERE CASE WHEN L.TYPE_CODE = 495 AND L.CUSTOMER_REF_NUM IS NULL THEN SPLIT_PART(L.TEXT, ' ', -1) ELSE L.CUSTOMER_REF_NUM END IS NOT NULL
        AND CASE WHEN L.TYPE_CODE = 495 AND NVL(L.CUSTOMER_REF_NUM, SPLIT_PART(L.TEXT, ' ', -1)) IN (
            SELECT DISTINCT
            L.CUSTOMER_REF_NUM AS PAY_REF_NUMBER
            FROM {{ source('RAW_CES_FINANCE', 'ANZ_BTR_LINES') }} AS L
            WHERE L.TYPE_CODE IN (266, 195)
            AND L.CUSTOMER_REF_NUM IS NOT NULL
        )
        THEN 0 
        WHEN L.TYPE_CODE IN (266, 195) THEN 0 ELSE 1 END = 1
    )
) B
ON PTH.PAY_REF_NUMBER = B.PAY_REF_NUMBER
LEFT JOIN (
    SELECT
    DT.KEY
    , DT.WORKDAY_FLAG_NSW
    , TO_DATE(LAG (CASE WHEN DT.WORKDAY_FLAG_NSW = 0 THEN NULL ELSE DT.KEY END, -1) IGNORE NULLS OVER (ORDER BY DT.KEY), 'YYYYMMDD') AS NEXT_WORKDAY
    , LAG (CASE WHEN DT.WORKDAY_FLAG_NSW = 0 THEN NULL ELSE DT.KEY END, -1) IGNORE NULLS OVER (ORDER BY DT.KEY) AS NEXT_WORKDAY_KEY
    FROM {{ ref('REF_DATE') }} AS DT
) D
ON TO_CHAR(CONVERT_TIMEZONE('UTC', 'Australia/Sydney', PYMT.FILE_RECEIVED_DATE), 'YYYYMMDD') = D.KEY