SELECT
AM.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, AM.SCHEME AS SCHEME
, AM.MANIFEST_ID || '-' || AI.INVOICE_NUMBER || '-' || AI.INVOICE_TYPE AS ID
, AM.MANIFEST_DATE AS MANIFEST_DATE
, AM.MANIFEST_DATE_KEY AS MANIFEST_DATE_KEY
, AI.INVOICE_NUMBER AS INVOICE_NUMBER
, TO_DATE(AI.INVOICE_DATE_ATP, 'YYYY/MM/DD') AS INVOICE_DATE_ATP
, AI.INVOICE_DATE_ERP AS INVOICE_DATE_ERP
, CASE WHEN TO_DATE(AI.INVOICE_DATE_ATP, 'YYYY/MM/DD') = AI.INVOICE_DATE_ERP THEN 'Yes' WHEN (TO_DATE(AI.INVOICE_DATE_ATP, 'YYYY/MM/DD') IS NULL AND AI.INVOICE_DATE_ERP IS NULL) THEN NULL ELSE 'No' END AS DATE_RECONCILIATION_FLAG
, AM.MANIFEST_ID AS MANIFEST_ID
, AM.MANIFEST_WEIGHT_KG AS MANIFEST_WEIGHT_KG
, AM.MANIFEST_WEIGHT_KG/1000 AS MANIFEST_WEIGHT_TONNES
, AM.SALE_PRICE_PER_TONNE AS SALE_PRICE_PER_TONNE
, AM.RESERVE_PRICE_PER_TONNE AS RESERVE_PRICE_PER_TONNE
, AI.INVOICE_TYPE AS INVOICE_TYPE
, CASE WHEN AI.PAY_GROUP_ATP IN ('AuctionPrcRecyclrInv', 'PROCESSOR AUCTION', 'MRF AUCTION', 'AuctionMRFRecyclrInv', 'AuctionPlatfomMRFInv', 'RECYCLER NEGATIVE AUCTION') THEN '100%' WHEN AI.PAY_GROUP_ATP IS NULL THEN NULL ELSE '80%' END AS VOLUME_ATP
, CASE WHEN AI.PAY_GROUP_ERP IN ('AuctionPrcRecyclrInv', 'PROCESSOR AUCTION', 'MRF AUCTION', 'AuctionMRFRecyclrInv', 'AuctionPlatfomMRFInv', 'RECYCLER NEGATIVE AUCTION') THEN '100%' WHEN AI.PAY_GROUP_ERP IS NULL THEN NULL ELSE '80%' END AS VOLUME_ERP
, CASE WHEN AI.PAY_GROUP_ATP = AI.PAY_GROUP_ERP THEN 'Yes' WHEN (AI.PAY_GROUP_ATP IS NULL AND AI.PAY_GROUP_ERP IS NULL) THEN NULL ELSE 'No' END AS VOLUME_RECONCILIATION_FLAG
, AI.SUPPLIER_NAME_ATP AS SUPPLIER_NAME_ATP
, AI.SUPPLIER_NAME_ERP AS SUPPLIER_NAME_ERP
, AI.SITE_NUMBER_ATP AS SITE_NUMBER_ATP
, AI.SITE_NUMBER_ERP AS SITE_NUMBER_ERP
, CASE WHEN AI.SITE_NUMBER_ATP = AI.SITE_NUMBER_ERP THEN 'Yes' WHEN (AI.SITE_NUMBER_ATP IS NULL AND AI.SITE_NUMBER_ERP IS NULL) THEN NULL ELSE 'No' END AS SITE_RECONCILIATION_FLAG
, AI.PAY_GROUP_ATP AS PAY_GROUP_ATP
, AI.PAY_GROUP_ERP AS PAY_GROUP_ERP
, AI.INVOICE_AMOUNT_ATP AS INVOICE_AMOUNT_ATP
, ROUND(AI.INVOICE_AMOUNT_ATP*1.1, 2) AS INVOICE_AMOUNT_ATP_PLUS_GST
, AI.INVOICE_AMOUNT_ERP AS INVOICE_AMOUNT_ERP
, CASE WHEN (ABS(AI.INVOICE_AMOUNT_ERP - ROUND(AI.INVOICE_AMOUNT_ATP*1.1, 2)) < 0.05 OR ABS(ROUND(AI.INVOICE_AMOUNT_ATP*1.1, 2) - AI.INVOICE_AMOUNT_ERP) < 0.05) THEN 'Yes' WHEN (AI.INVOICE_AMOUNT_ERP IS NULL AND AI.INVOICE_AMOUNT_ATP IS NULL) THEN NULL ELSE 'No' END AS INVOICE_AMOUNT_RECONCILIATION_FLAG
, AI.DUE_DATE AS DUE_DATE
, SYSDATE() AS INSERT_DATE_UTC
FROM (
    SELECT
    AMC.MULTI_SCHEME_ID
    , AMC.SCHEME
    , AMC.MANIFEST_ID
    , AMC.MANIFEST_DATE
    , AMC.MANIFEST_DATE_KEY
    , AMC.MANIFEST_WEIGHT_KG
    , AMC.SALE_PRICE_PER_TONNE
    , AMC.RESERVE_PRICE_PER_TONNE
    FROM {{ ref('AUCTION_MANIFEST_CLEANSED') }} AS AMC
    WHERE AMC.MANIFEST_ID LIKE 'LM%'
) AM
LEFT JOIN (
    SELECT
    REGEXP_SUBSTR(AP.DISTRIBUTION_DESC, 'LM\\d+') AS MANIFEST_ID
    , AP.INVOICE_NUM AS INVOICE_NUMBER
    , AP.INVOICE_DATE AS INVOICE_DATE_ERP
    , AH.INVOICE_DATE AS INVOICE_DATE_ATP
    , 'AP' AS INVOICE_TYPE
    , AP.SUPPLIER_NAME AS SUPPLIER_NAME_ERP
    , S.SITE_NAME AS SUPPLIER_NAME_ATP
    , AP.SUPPLIER_SITE_CODE AS SITE_NUMBER_ERP
    , AH.SUPPLIER_SITE AS SITE_NUMBER_ATP
    , AP.PAY_GROUP AS PAY_GROUP_ERP
    , AH.PAY_GROUP AS PAY_GROUP_ATP
    , AP.INVOICE_AMOUNT AS INVOICE_AMOUNT_ERP
    , AH.INVOICE_AMOUNT AS INVOICE_AMOUNT_ATP
    , APP.DUE_DATE AS DUE_DATE
    FROM {{ source('CES_ERP', 'AP_TRANSACTIONS') }} AS AP
    FULL OUTER JOIN (
        SELECT 
        AH.INVOICE_NUMBER
        , AH.INVOICE_DATE
        , AH.SUPPLIER_SITE
        , AH.PAY_GROUP
        , AH.INVOICE_AMOUNT
        FROM {{ source('CES_MSCM', 'INVOICE_AP_TXN_HDR') }} AS AH
        WHERE AH.INVOICE_SOURCE IN ('AUCTION')
        QUALIFY ROW_NUMBER() OVER (PARTITION BY AH.INVOICE_NUMBER ORDER BY AH.CREATED_ON DESC) = 1
    ) AH --ATP AP INVOICES
    ON AP.INVOICE_NUM = AH.INVOICE_NUMBER
    LEFT JOIN (
        SELECT
        APP.INVOICE_NUMBER 
        , APP.DUE_DATE
        , APP.SUPPLIER_SITE
        FROM {{ source('CES_ERP', 'AP_BALANCES') }} AS APP
        QUALIFY ROW_NUMBER() OVER (PARTITION BY APP.INVOICE_ID, APP.INVOICE_NUMBER ORDER BY APP.INVOICE_DATE DESC) = 1
    ) APP
    ON AP.INVOICE_NUM = APP.INVOICE_NUMBER
    AND AP.SUPPLIER_SITE_CODE = APP.SUPPLIER_SITE
    LEFT JOIN {{ ref('B2B_SITES') }} AS S
    ON AH.SUPPLIER_SITE = S.SITE_NUMBER
    WHERE AP.PAY_GROUP IN ('PROCESSOR AUCTION', 'MRF AUCTION', 'RECYCLER NEGATIVE AUCTION')
    AND AP.DISTRIBUTION_DESC LIKE '%Manifest ID%'
    QUALIFY ROW_NUMBER() OVER (PARTITION BY MANIFEST_ID, AP.INVOICE_NUM ORDER BY AP.DISTRIBUTION_LINE_NUM DESC) = 1

    UNION

    SELECT
    M.MANIFEST_ID AS MANIFEST_ID
    , AR.TRANSACTION_NUMBER AS INVOICE_NUMBER
    , AR.TRANSACTION_DATE AS INVOICE_DATE_ERP
    , AT.TRANSACTION_DATE AS INVOICE_DATE_ATP
    , 'AR' AS INVOICE_TYPE
    , AR.BILL_TO_CUST_NAME AS SUPPLIER_NAME_ERP
    , S.SITE_NAME AS SUPPLIER_NAME_ATP
    , AR.BILL_TO_SITE_NUM AS SITE_NUMBER_ERP
    , AT.BILL_TO_CUST_SITE_NUMBER AS SITE_NUMBER_ATP
    , AR.TRANSACTION_TYPE AS PAY_GROUP_ERP
    , AT.TRANSACTION_TYPE AS PAY_GROUP_ATP
    , SUM(AR.TRANSACTION_ENTERED_AMT) AS INVOICE_AMOUNT_ERP
    , AT.TXN_LINE_AMOUNT AS INVOICE_AMOUNT_ATP
    , ARDUE.DUE_DATE AS DUE_DATE
    FROM {{ source('CES_ERP', 'AR_TRANSACTIONS') }} AS AR
    LEFT JOIN (
        SELECT
        TRANSACTION_NUMBER,
        REGEXP_SUBSTR(LINE_DESC, 'LM\\d+') AS MANIFEST_ID
        FROM {{ source('CES_ERP', 'AR_TRANSACTIONS_LINE_DTL') }} AS AL
        WHERE TRANSACTION_SOURCE_NAME IN ('AUCTION')
        AND LINE_DESC IS NOT NULL
        QUALIFY ROW_NUMBER() OVER (PARTITION BY TRANSACTION_NUMBER ORDER BY MANIFEST_ID) = 1
    ) M
    ON AR.TRANSACTION_NUMBER = M.TRANSACTION_NUMBER
    FULL OUTER JOIN (
        SELECT
        ATR.TXN_NUMBER
        , REGEXP_SUBSTR(ATR.TXN_LINE_DESCRIPTION, 'LM\\d+') AS MANIFEST_ID
        , ATR.TRANSACTION_DATE 
        , ATR.BILL_TO_CUST_SITE_NUMBER
        , ATR.TRANSACTION_TYPE
        , ATR.TXN_LINE_AMOUNT AS TXN_LINE_AMOUNT
        FROM {{ source('CES_MSCM', 'INVOICE_AR_TRANSACTION_REC') }} AS ATR
        WHERE BATCH_SOURCE IN ('AUCTION')
        AND TXN_LINE_DESCRIPTION IS NOT NULL
        QUALIFY ROW_NUMBER() OVER (PARTITION BY TXN_NUMBER ORDER BY REGEXP_SUBSTR(TXN_LINE_DESCRIPTION, 'LM\\d+')) = 1
    ) AT --ATP AR INVOICES
    ON AT.TXN_NUMBER = AR.TRANSACTION_NUMBER 
    AND AT.MANIFEST_ID = M.MANIFEST_ID
    LEFT JOIN (
        SELECT 
        ARDUE.TRANSACTION_NUMBER
        , ARDUE.DUE_DATE
        FROM {{ source('CES_ERP', 'AR_TRANSACTIONS_DUE_SCHED') }} AS ARDUE
        LEFT JOIN {{ source('CES_ERP', 'AR_TRANSACTIONS_DUE_APP') }} AS ADP
        ON ARDUE.PAYMENT_SCHEDULE_ID = ADP.PAYMENT_SCHEDULE_ID
        QUALIFY ROW_NUMBER() OVER (PARTITION BY ARDUE.PAYMENT_SCHEDULE_ID ORDER BY ADP.RECEIPT_DATE DESC) = 1
    ) ARDUE
    ON AR.TRANSACTION_NUMBER = ARDUE.TRANSACTION_NUMBER
    LEFT JOIN {{ ref('B2B_SITES') }} AS S
    ON AT.BILL_TO_CUST_SITE_NUMBER = S.SITE_NUMBER
    WHERE AR.TRANSACTION_SOURCE_NAME IN ('AUCTION')
    AND AR.TRANSACTION_TYPE IN ('AuctionPlatfomMRFInv', 'AuctionMRFRecyclrInv', 'AuctionProcessor Inv', 'AuctionPrcRecyclrInv')
    AND AR.ACCOUNTING_CLASS IN ('Receivable')
    AND AR.ACCOUNTING_CALENDAR_NAME IN ('Scheme Ledger')
    GROUP BY
    M.MANIFEST_ID
    , AR.TRANSACTION_NUMBER
    , AR.TRANSACTION_TYPE
    , AR.TRANSACTION_DATE
    , AR.BILL_TO_SITE_NUM
    , AR.BILL_TO_CUST_NAME
    , AT.TRANSACTION_DATE
    , AT.BILL_TO_CUST_SITE_NUMBER
    , AT.TRANSACTION_TYPE
    , AT.TXN_LINE_AMOUNT
    , S.SITE_NAME
    , ARDUE.DUE_DATE
) AI
ON AM.MANIFEST_ID = AI.MANIFEST_ID
LEFT JOIN {{ ref('REF_DATE') }} AS D_AM
ON AM.MANIFEST_DATE_KEY = D_AM.KEY
LEFT JOIN {{ ref('REF_DATE') }} AS D_ERP
ON TO_CHAR(AI.INVOICE_DATE_ERP, 'YYYYMMDD') = D_ERP.KEY
LEFT JOIN {{ ref('REF_DATE') }} AS D_ATP
ON TO_CHAR(TO_DATE(AI.INVOICE_DATE_ATP, 'YYYY/MM/DD'), 'YYYYMMDD') = D_ATP.KEY