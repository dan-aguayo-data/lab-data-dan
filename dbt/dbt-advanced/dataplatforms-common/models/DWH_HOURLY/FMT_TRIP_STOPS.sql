SELECT
O.SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, S.TRIP_STOP_ID AS ID
, S.TRIP_LEG_ID AS TRIP_LEG_ID
, S.TRIP_ID AS TRIP_ID
, R_S.VALUE AS STOP_TYPE
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(S.START_TIME AS TIMESTAMP)) AS START_TIME
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(S.END_TIME AS TIMESTAMP)) AS END_TIME
, R_A.VALUE AS ADJUST_REASON
, S.NOTES AS NOTES
, S.CREATED_BY AS CREATED_BY
, S.CREATED_ON AS CREATED_ON_UTC
, S.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, S.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM', 'FMT_TRIP_STOPS') }} AS S
INNER JOIN {{ source('CES_MSCM', 'FMT_TRIP_LEGS') }} AS L
ON S.TRIP_LEG_ID = L.TRIP_LEG_ID
INNER JOIN {{ source('CES_MSCM', 'FMT_TRIPS') }} AS T
ON L.TRIP_ID = T.TRIP_ID
INNER JOIN {{ source('CES_MSCM', 'FMT_ORGANISATIONS') }} AS O
ON T.ORGANISATION_ID = O.ORGANISATION_ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON O.SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'FMT_SCHEME_REF_CODES') }} AS R_S
ON S.STOP_TYPE_ID = R_S.ID
LEFT JOIN {{ source('CES_MSCM', 'FMT_SCHEME_REF_CODES') }} AS R_A
ON S.ADJUST_REASON_ID = R_A.ID