SELECT
T.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, T.SCHEME AS SCHEME
, T.TRIP_LEG_ID AS TRIP_LEG_ID
, T.SITE_NUMBER_START AS SITE_NUMBER_START
, T.SITE_NUMBER_END AS SITE_NUMBER_END
, GEOS.GEO_TIME AS START_TIME
, GEOE.GEO_TIME AS END_TIME
, DATEDIFF('S', GEOS.GEO_TIME, GEOE.GEO_TIME)/60 AS TRIP_TIME
, CASE WHEN T.SITE_NUMBER_END = T_DWELL.SITE_NUMBER_START THEN DATEDIFF('S', GEOE.GEO_TIME, GEO_DWELL.GEO_TIME)/60 ELSE NULL END AS DWELL_TIME
FROM
{{ ref('FMT_TRIPS') }} AS T
LEFT JOIN (
    SELECT
    LOG.TRIP_LEG_ID
    ,MIN(LOG.DATE_MODIFIED) AS GEO_TIME
    FROM {{ source('CES_MSCM', 'FMT_TRIP_LEG_STATUS_LOGS') }} AS LOG
    WHERE LOG.NEW_DISPLAY_STATUS_ID IN (1279, 1493, 1509)
    GROUP BY LOG.TRIP_LEG_ID
) GEOS
ON T.TRIP_LEG_ID = GEOS.TRIP_LEG_ID
LEFT JOIN (
    SELECT
    LOG.TRIP_LEG_ID
    ,MIN(LOG.DATE_MODIFIED) AS GEO_TIME
    FROM {{ source('CES_MSCM', 'FMT_TRIP_LEG_STATUS_LOGS') }} AS LOG
    WHERE LOG.NEW_DISPLAY_STATUS_ID IN (1479, 1488, 1749)
    GROUP BY LOG.TRIP_LEG_ID
) GEOE
ON T.TRIP_LEG_ID = GEOE.TRIP_LEG_ID
LEFT JOIN {{ ref('FMT_TRIPS') }} AS T_DWELL
ON T.TRIP_GROUP = T_DWELL.TRIP_GROUP
AND T.GROUP_SEQUENCE = T_DWELL.GROUP_SEQUENCE - 1
LEFT JOIN (
    SELECT
    LOG.TRIP_LEG_ID
    ,MIN(LOG.DATE_MODIFIED) AS GEO_TIME
    FROM {{ source('CES_MSCM', 'FMT_TRIP_LEG_STATUS_LOGS') }} AS LOG
    WHERE LOG.NEW_DISPLAY_STATUS_ID IN (1279, 1493, 1509)
    GROUP BY LOG.TRIP_LEG_ID
) GEO_DWELL
ON T_DWELL.TRIP_LEG_ID = GEO_DWELL.TRIP_LEG_ID