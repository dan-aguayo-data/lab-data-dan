SELECT
C.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, C.ID AS ID
, C.KAFKA_ID AS KAFKA_ID
, C.KAFKA_DATETIME AS KAFKA_DATETIME
, C.REGISTRATION_ID AS REGISTRATION_ID
, C.EMAIL AS EMAIL
, C.FIRST_NAME AS FIRST_NAME
, C.LAST_NAME AS LAST_NAME
, C.PHONE_NUMBER AS PHONE_NUMBER
, C.POSITION_TITLE AS POSITION_TITLE
, C.PHYS_ADDR_POSTCODE AS POSTCODE
, C.PHYS_ADDR_STATE AS STATE
, C.PHYS_ADDR_STREET_ADDRESS AS STREET_ADDRESS
, C.PHYS_ADDR_SUBURB AS SUBURB
, CASE "'ACCOUNTS_CONTACT'" WHEN 1 THEN 'Yes' WHEN 0 THEN 'No' ELSE NULL END AS ACCOUNTS_CONTACT_FLAG
, CASE "'AUTHORISED_CONTACT'" WHEN 1 THEN 'Yes' WHEN 0 THEN 'No' ELSE NULL END AS AUTHORISED_CONTACT_FLAG
, CASE "'CONTRACT_NOTICE_MANAGER'" WHEN 1 THEN 'Yes' WHEN 0 THEN 'No' ELSE NULL END AS CONTRACT_NOTICE_MANAGER_FLAG
, CASE "'PORTAL_USER'" WHEN 1 THEN 'Yes' WHEN 0 THEN 'No' ELSE NULL END AS PORTAL_USER_FLAG
, CASE "'SIGNATORY'" WHEN 1 THEN 'Yes' WHEN 0 THEN 'No' ELSE NULL END AS SIGNATORY_FLAG
, CASE "'SIGNATORY_1'" WHEN 1 THEN 'Yes' WHEN 0 THEN 'No' ELSE NULL END AS SIGNATORY_1_FLAG
, CASE "'SIGNATORY_2'" WHEN 1 THEN 'Yes' WHEN 0 THEN 'No' ELSE NULL END AS SIGNATORY_2_FLAG
, CASE "'WITNESS'" WHEN 1 THEN 'Yes' WHEN 0 THEN 'No' ELSE NULL END AS WITNESS_FLAG
, CASE WHEN ("'SIGNATORY'" = 1 OR "'SIGNATORY_1'" = 1 OR "'SIGNATORY_2'" = 1) AND "'PORTAL_USER'" = 1 THEN 'Yes' ELSE 'No' END AS SIGNATORY_PORTAL_ACCESS_REQUESTED
, REG.RECENT_FLAG AS RECENT_FLAG
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM_KAFKA', 'PARTICIPANT_REGISTRATION_CONTACTS') }} AS C
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON C.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN (
    SELECT
    *
    FROM (
        SELECT 
        CR.ID
        , CR.KAFKA_ID
        , CR.EMAIL
        , CR.ROLE_NAME
        FROM {{ source('CES_MSCM_KAFKA', 'PARTICIPANT_REGISTRATION_CONTACTS_ROLE') }} AS CR
        )
    PIVOT(COUNT(CR.ID) FOR ROLE_NAME IN (ANY))
) R
ON C.KAFKA_ID = R.KAFKA_ID
AND C.EMAIL = R.EMAIL
INNER JOIN (
    SELECT
    PR.KAFKA_ID
    , CASE WHEN ROW_NUMBER() OVER (PARTITION BY PR.REGISTRATION_ID ORDER BY PR.KAFKA_DATETIME DESC, PR.TYPE_ORDER DESC) = 1 THEN 1 ELSE 0 END AS RECENT_FLAG
    FROM {{ source('CES_MSCM_KAFKA', 'PARTICIPANT_REGISTRATION') }} AS PR
) REG
ON C.KAFKA_ID = REG.KAFKA_ID