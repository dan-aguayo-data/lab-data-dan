
{{
    config(
        materialized = 'incremental',
        incremental_strategy = 'merge',
        unique_key = 'INCREMENTAL_ID',
        snowflake_warehouse= wh_selector_models("ETL_CES_DEV","ETL_CES_SIT","ETL_CES_UAT","ETL_CES_SMALL"),
                        post_hook="
                {% if is_incremental() %}
                DELETE FROM {{this}} a
                WHERE a.DELETE_FLAG = 'TRUE' ;
                {% else %}
                SELECT 1 ;
                {% endif %}
                "
    )
}}




WITH CRP_COLLECTION_DTL_REF AS ( --  USED IN FULL REFRESH TO CATCH REFERENCES (LINEAGE)

SELECT * FROM  {{ ref('CRP_COLLECTION_DTL') }}

) {% if is_incremental() %} ,CRP_COLLECTION_AGG_1_STAGE AS (

SELECT
D.ID
, CONCAT_WS('-',
  COALESCE(H.SITE_NUMBER, ''),
  COALESCE(H.CONSUMER_ID, ''),
  COALESCE(H.TRANSACTION_DATE_KEY, ''),
  COALESCE(H.PAYMENT_METHOD, ''),
  COALESCE(H.SCHEME_CONSUMER_FLAG, ''),
  COALESCE(H.TRANSACTION_BANDING, ''),
  COALESCE(C.CONSUMER_TYPE, ''),
  COALESCE(D.MATERIAL_TYPE_ID, ''),
  COALESCE(PD.NAME, ''),
  COALESCE(H.TRANSACTION_POSTCODE, '')
) AS INCREMENTAL_ID
FROM  {{ source('COMMON_DWH','CRP_COLLECTION_HDR') }} AS H
INNER JOIN CRP_COLLECTION_DTL_REF AS D
ON H.TRANSACTION_ID = D.TRANSACTION_ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON H.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'POS_DEVICE') }} AS PD
ON H.POS_DEVICE_ID = PD.ID
LEFT JOIN {{ source('COMMON_DWH','CONSUMER') }} AS C
ON H.CONSUMER_ID = C.CONSUMER_ID

) ,INCREMENTAL_DATE_REF AS (

 SELECT DATEADD(HOUR, {{var('general_delta_load_hours')}} , SYSDATE()) AS INCREMENTAL_DELTA


) ,INCREMENTAL_LOAD_INCOMING AS (
SELECT
D.ID
FROM COMMON_PROD.DWH.CRP_COLLECTION_HDR AS H
INNER JOIN COMMON_PROD.DWH.CRP_COLLECTION_DTL AS D
ON H.TRANSACTION_ID = D.TRANSACTION_ID 
INNER JOIN RAW_PROD.CES_MSCM_ORACLE.SCHEME AS SCHEME
ON H.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID 
LEFT JOIN RAW_PROD.CES_MSCM_ORACLE.POS_DEVICE AS PD  --9K ROWS
ON H.POS_DEVICE_ID = PD.ID 
LEFT JOIN COMMON_PROD.DWH.CONSUMER AS C --1.2 M ROWS
ON H.CONSUMER_ID = C.CONSUMER_ID 
WHERE 
(H.LAST_MODIFIED_ON_UTC >= (SELECT INCREMENTAL_DELTA FROM INCREMENTAL_DATE_REF)
OR D.LAST_MODIFIED_ON_UTC>= (SELECT INCREMENTAL_DELTA FROM INCREMENTAL_DATE_REF)
OR SCHEME.LAST_MODIFIED_ON >= (SELECT INCREMENTAL_DELTA FROM INCREMENTAL_DATE_REF)
OR  PD.LAST_MODIFIED_ON  >= (SELECT INCREMENTAL_DELTA FROM INCREMENTAL_DATE_REF)
OR C.LAST_MODIFIED_ON_UTC    >= (SELECT INCREMENTAL_DELTA FROM INCREMENTAL_DATE_REF)
)
), initial_txn AS (
SELECT   
A.ID,
A.INCREMENTAL_ID
FROM CRP_COLLECTION_AGG_1_STAGE A
INNER JOIN INCREMENTAL_LOAD_INCOMING B 
ON  A.ID = B.ID
GROUP BY A.ID, 
A.INCREMENTAL_ID
), RECALCULATE_CURRENT_KEYS AS ( -- GETTING ALL CURRENT KEYS THAT HAVE TO BE RECALCULATED

SELECT DISTINCT 
A.INCREMENTAL_ID
FROM CRP_COLLECTION_AGG_1_STAGE A
INNER JOIN initial_txn B
ON A.INCREMENTAL_ID = B.INCREMENTAL_ID
GROUP BY 
A.INCREMENTAL_ID


), INCREMENTAL_LOAD_SCOPE AS (   -- WE HAVE TO RE-SUM THE TRANSACTION_ID BASED ON THE INCREMENTAL_ID
 
 SELECT DISTINCT
 A.ID
 FROM CRP_COLLECTION_AGG_1_STAGE A
 WHERE A.ID IN  (SELECT DISTINCT ID FROM INCREMENTAL_LOAD_INCOMING) 
 OR A.INCREMENTAL_ID  IN (SELECT INCREMENTAL_ID FROM RECALCULATE_CURRENT_KEYS)

), DELETE_FLAG AS (

SELECT * FROM {{this}} a
WHERE NOT EXISTS  (SELECT 1 FROM CRP_COLLECTION_AGG_1_STAGE b
                    WHERE a.INCREMENTAL_ID = b.INCREMENTAL_ID )

), CRP_COLLECTION_DTL_INCREMENTAL AS (
SELECT D.* 
FROM CRP_COLLECTION_DTL_REF D
INNER JOIN INCREMENTAL_LOAD_SCOPE IL
ON D.ID = IL.ID
)
{% endif %}

SELECT
H.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, CONCAT_WS('-', H.SITE_NUMBER, H.CONSUMER_ID, H.TRANSACTION_DATE_KEY, H.PAYMENT_METHOD, H.SCHEME_CONSUMER_FLAG, H.TRANSACTION_BANDING, C.CONSUMER_TYPE, D.MATERIAL_TYPE_ID, PD.NAME) AS ID
, CONCAT_WS('-',
  COALESCE(H.SITE_NUMBER, ''),
  COALESCE(H.CONSUMER_ID, ''),
  COALESCE(H.TRANSACTION_DATE_KEY, ''),
  COALESCE(H.PAYMENT_METHOD, ''),
  COALESCE(H.SCHEME_CONSUMER_FLAG, ''),
  COALESCE(H.TRANSACTION_BANDING, ''),
  COALESCE(C.CONSUMER_TYPE, ''),
  COALESCE(D.MATERIAL_TYPE_ID, ''),
  COALESCE(PD.NAME, ''),
  COALESCE(H.TRANSACTION_POSTCODE, '')
) AS INCREMENTAL_ID
, H.SITE_NUMBER AS SITE_NUMBER
, H.CONSUMER_ID AS CONSUMER_ID
, CAST(H.TRANSACTION_DATE AS DATE) AS TRANSACTION_DATE
, H.TRANSACTION_DATE_KEY AS TRANSACTION_DATE_KEY
, H.PAYMENT_METHOD AS PAYMENT_METHOD
, H.SCHEME_CONSUMER_FLAG AS SCHEME_CONSUMER_FLAG
, H.TRANSACTION_BANDING AS TRANSACTION_BANDING
, H.TRANSACTION_POSTCODE AS TRANSACTION_POSTCODE
, C.CONSUMER_TYPE AS CONSUMER_TYPE
, D.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID
, PD.NAME AS POS_DEVICE_NAME
, COUNT(DISTINCT H.TRANSACTION_ID) AS TOTAL_TRANSACTIONS
, SUM(D.COLLECTION_QTY) AS TOTAL_QTY
, SUM(D.GROSS_AMOUNT) AS TOTAL_GROSS_AMOUNT
, SUM(D.GST_AMOUNT) AS TOTAL_GST_AMOUNT
, SUM(D.TAXABLE_AMOUNT) AS TOTAL_TAXABLE_AMOUNT
, SYSDATE() AS INSERT_DATE_UTC
, 'FALSE' AS DELETE_FLAG
FROM {{ ref('CRP_COLLECTION_HDR') }} AS H
{% if is_incremental() %}
INNER JOIN CRP_COLLECTION_DTL_INCREMENTAL AS D
ON H.TRANSACTION_ID = D.TRANSACTION_ID
{% else %}
INNER JOIN CRP_COLLECTION_DTL_REF  AS D
ON H.TRANSACTION_ID = D.TRANSACTION_ID
{% endif %}
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }}  AS SCHEME
ON H.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'POS_DEVICE') }} AS PD
ON H.POS_DEVICE_ID = PD.ID
LEFT JOIN  {{ ref('CONSUMER') }}  AS C
ON H.CONSUMER_ID = C.CONSUMER_ID
GROUP BY ALL

{% if is_incremental() %}


UNION ALL

SELECT
MULTI_SCHEME_ID,  
SCHEME,  
ID,  
INCREMENTAL_ID,  
SITE_NUMBER,  
CONSUMER_ID,  
TRANSACTION_DATE, 
TRANSACTION_DATE_KEY,  
PAYMENT_METHOD,  
SCHEME_CONSUMER_FLAG,  
TRANSACTION_BANDING,  
TRANSACTION_POSTCODE,  
CONSUMER_TYPE,  
MATERIAL_TYPE_ID,  
POS_DEVICE_NAME,  
TOTAL_TRANSACTIONS,  
TOTAL_QTY,  
TOTAL_GROSS_AMOUNT,  
TOTAL_GST_AMOUNT,  
TOTAL_TAXABLE_AMOUNT,  
INSERT_DATE_UTC,  
 'TRUE' DELETE_FLAG
FROM DELETE_FLAG

{% endif %}
