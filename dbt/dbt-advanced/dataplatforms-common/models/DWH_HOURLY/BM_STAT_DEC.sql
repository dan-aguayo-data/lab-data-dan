SELECT
NVL(D.MULTI_SCHEME_ID, S.MULTI_SCHEME_ID) AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, S.ID || NVL('-' || D.ID, '') AS ID
, NVL(D.SITE_NUMBER, S.SITE_NUMBER) AS SITE_NUMBER
, D.ENTRY_TYPE AS ENTRY_TYPE
, D.STATUS AS STATUS
, D.SUBMITTED_BY AS SUBMITTED_BY
, D.SUBMITTED_ON AS SUBMITTED_ON
, D.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, D.LAST_MODIFIED_ON AS LAST_MODIFIED_ON
, NVL(D.PERIOD_KEY, S.PERIOD_KEY) AS PERIOD_KEY
, NVL(D.MATERIAL_TYPE_ID, S.MATERIAL_TYPE_ID) AS MATERIAL_TYPE_ID
, D.VOLUME AS STAT_DEC_VOLUME
, CASE WHEN NVL(D.ENTRY_TYPE, 'R') = 'R' THEN S.SALES_VOLUME ELSE NULL END AS SALES_VOLUME
, CASE WHEN NVL(D.ENTRY_TYPE, 'R') = 'R' THEN S.VOLUME_BEFORE_STAT_DEC ELSE NULL END AS VOLUME_BEFORE_STAT_DEC
, CASE WHEN NVL(D.ENTRY_TYPE, 'R') = 'R' THEN S.VOLUME_F ELSE NULL END AS VOLUME_F
, CASE WHEN S.COUNT_L >= 1 THEN 1 ELSE 0 END AS L_FLAG
, NVL(D.UOM, S.UOM) AS UOM
, D.AUDITOR_COMMENTS AS AUDITOR_COMMENTS
, CASE WHEN D.ID IS NOT NULL THEN 'Y' ELSE 'N' END AS STAT_DEC_FLAG
, D.MFG_STATUTORY_DECLARATION_ID AS MFG_STATUTORY_DECLARATION_ID
, D.DISCUSSION_STATUS AS DISCUSSION_STATUS
, SYSDATE() AS INSERT_DATE_UTC
FROM (
    SELECT
    HDR.MULTI_SCHEME_ID
    , HDR.MFG_STAT_DEC_PERIOD_HDR_ID AS ID
    , HDR.MANUFACTURER_ID AS SITE_NUMBER
    , HDR.ENTRY_TYPE
    , SD.SUBMITTED_BY AS BM_USER_EMAIL
    , SD.STATUS
    , SD.SUBMITTED_BY
    , SD.SUBMITTED_ON
    , SD.LAST_MODIFIED_BY
    , SD.LAST_MODIFIED_ON
    , CONCAT(REPLACE(HDR.PERIOD, '-', ''), '01') AS PERIOD_KEY
    , DTL.MATERIAL_TYPE_ID
    , DTL.VOLUME
    , DTL.UOM
    , SD.AUDITOR_COMMENTS
    , SD.MFG_STATUTORY_DECLARATION_ID
    , SD.DISCUSSION_STATUS
    FROM {{ source('CES_MSCM', 'MFG_STAT_DEC_PERIOD_HDR') }} AS HDR
    LEFT JOIN {{ source('CES_MSCM', 'MFG_STAT_DEC_PERIOD_DTL') }} AS DTL
    ON HDR.MFG_STAT_DEC_PERIOD_HDR_ID = DTL.MFG_STAT_DEC_PERIOD_HDR_ID
    LEFT JOIN {{ source('CES_MSCM', 'MFG_STATUTORY_DECLARATION') }} AS SD
    ON HDR.MFG_STATUTORY_DECLARATION_ID = SD.MFG_STATUTORY_DECLARATION_ID
) D
FULL OUTER JOIN (
    SELECT
    SV.MULTI_SCHEME_ID
    , SV.MULTI_SCHEME_ID || '-' || SV.SITE_NUMBER || '-' || SV.PERIOD_KEY || '-' || SV.MATERIAL_TYPE_ID AS ID
    , SV.SITE_NUMBER
    , SV.PERIOD_KEY
    , SV.MATERIAL_TYPE_ID
    , SUM(CASE WHEN SV.ENTRY_TYPE = 'L' THEN 1 ELSE 0 END) AS COUNT_L
    , SUM(SV.VOLUME) AS SALES_VOLUME
    , SUM(CASE WHEN (SV.ENTRY_TYPE IN ('R', 'L') OR SV.SS_AUDIT_ADJUSTMENT_ID <> '-1' OR (SV.ENTRY_TYPE = 'A' AND SV.PERIOD BETWEEN '2021-07' AND '2022-06' AND LOWER(SV.SUBMITTED_BY) NOT IN ('declarations@containerexchange.com.au', 'sophia.mcguckin@warrrl.com.au')) OR (SV.ENTRY_TYPE = 'A' AND SV.PERIOD BETWEEN '2022-07' AND '2023-06' AND LOWER(SV.SUBMITTED_BY) NOT IN ('declarations@containerexchange.com.au', 'commercial@warrrl.com.au'))) THEN SV.VOLUME ELSE NULL END) AS VOLUME_BEFORE_STAT_DEC
    , SUM(CASE WHEN SV.ENTRY_TYPE = 'F' THEN SV.VOLUME ELSE 0 END) AS VOLUME_F
    , SV.UOM
    FROM {{ ref('BM_SALES_VOLUME') }} AS SV
    GROUP BY
    SV.MULTI_SCHEME_ID
    , SV.SCHEME
    , SV.SITE_NUMBER
    , SV.PERIOD_KEY
    , SV.MATERIAL_TYPE_ID
    , SV.UOM
) S
ON D.MULTI_SCHEME_ID = S.MULTI_SCHEME_ID
AND D.SITE_NUMBER = S.SITE_NUMBER
AND D.PERIOD_KEY = S.PERIOD_KEY
AND D.MATERIAL_TYPE_ID = S.MATERIAL_TYPE_ID
AND D.UOM = S.UOM
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON NVL(D.MULTI_SCHEME_ID, S.MULTI_SCHEME_ID) = SCHEME.MULTI_SCHEME_ID