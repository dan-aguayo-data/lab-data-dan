SELECT
PS.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, G.GOAL_D_ID AS ID
, G.GOAL_UID || '-' || G.PARTICIPANT_SITE_ID || '-' || G.GOAL_MEMBER_TYPE || '-' || TO_CHAR(G.GOAL_START_DATE, 'YYYYMMDD') AS GOAL_ID
, G.GOAL_UID AS GOAL_UID
, G.GOAL_LAST_MODIFIED_FLAG AS GOAL_LAST_MODIFIED_FLAG
, PS.SITE_NUMBER AS CONSUMER_ID
, G.GOAL_NAME AS GOAL_NAME
, G.GOAL_AMOUNT AS GOAL_AMOUNT
, G.GOAL_MEMBER_TYPE AS GOAL_MEMBER_TYPE
, CAST(G.GOAL_START_DATE AS DATE) AS GOAL_START_DATE
, CAST(G.GOAL_END_DATE AS DATE) AS GOAL_END_DATE
, DATEDIFF(DAY, G.GOAL_START_DATE, G.GOAL_END_DATE) AS DAYS_FOR_GOAL_COMPLETION
, CASE WHEN G.GOAL_STATUS = 1 AND CONVERT_TIMEZONE('UTC', 'Australia/Queensland', SYSDATE()) BETWEEN G.GOAL_START_DATE AND G.GOAL_END_DATE THEN 1 ELSE 0 END AS ACTIVE_GOAL_FLAG
, NVL(COUNT(H.TRANSACTION_ID), 0) AS TOTAL_TRANSACTIONS
, NVL(SUM(H.COLLECTION_QTY), 0) AS TOTAL_COLLECTION_QTY
, NVL(SUM(H.GROSS_AMOUNT), 0) AS TOTAL_GROSS_AMOUNT
, NVL(AVG(H.COLLECTION_QTY), 0) AS AVG_COLLECTION_QTY
, NVL(AVG(H.GROSS_AMOUNT), 0) AS AVG_GROSS_AMOUNT
, CASE WHEN G.GOAL_AMOUNT <= NVL(SUM(H.GROSS_AMOUNT), 0) THEN 1 ELSE 0 END AS GOAL_REACHED_FLAG
, G.CREATED_BY AS CREATED_BY
, G.CREATED_ON AS CREATED_ON_UTC
, G.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, G.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM (
    SELECT
    CFCG.GOAL_D_ID
    , CFCG.GOAL_UID
    , CASE WHEN ROW_NUMBER() OVER (PARTITION BY CFCG.GOAL_UID, CFCG.PARTICIPANT_SITE_ID, CFCG.GOAL_MEMBER_TYPE, TO_CHAR(CFCG.GOAL_START_DATE, 'YYYYMMDD') ORDER BY CFCG.LAST_MODIFIED_ON DESC) = 1 THEN 1 ELSE 0 END AS GOAL_LAST_MODIFIED_FLAG
    , CFCG.GOAL_NAME
    , CFCG.GOAL_AMOUNT
    , CFCG.PARTICIPANT_SITE_ID
    , CFCG.GOAL_STATUS
    , CFCG.GOAL_START_DATE
    , CFCG.GOAL_END_DATE
    , CFCG.GOAL_MEMBER_TYPE
    , CFCG.CREATED_BY
    , CFCG.CREATED_ON
    , CFCG.LAST_MODIFIED_BY
    , CFCG.LAST_MODIFIED_ON
    FROM {{ source('CES_DRUPAL', 'CFC_GOAL') }} AS CFCG
    WHERE CFCG._FIVETRAN_DELETED = 'FALSE'
    AND CFCG.GOAL_AMOUNT <> 0
) G
INNER JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS
ON G.PARTICIPANT_SITE_ID = PS.PARTICIPANT_SITE_ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON PS.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ ref('CRP_COLLECTION_HDR') }} AS H
ON PS.SITE_NUMBER = H.CONSUMER_ID
AND H.TRANSACTION_DATE BETWEEN G.GOAL_START_DATE AND G.GOAL_END_DATE
GROUP BY ALL