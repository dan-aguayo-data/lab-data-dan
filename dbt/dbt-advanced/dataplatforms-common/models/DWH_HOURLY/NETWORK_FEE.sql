SELECT
NF.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, NF.SCHEME AS SCHEME
, NF.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID
, MT.NAME AS MATERIAL_TYPE
, NF.CENTS_PER_CONTAINER_EX_GST AS CENTS_PER_CONTAINER_EX_GST
, NF.EFFECTIVE_FROM AS EFFECTIVE_FROM
, NF.EFFECTIVE_TO AS EFFECTIVE_TO
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_REFERENCE', 'NETWORK_FEE') }} AS NF
LEFT JOIN {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS MT
ON NF.MATERIAL_TYPE_ID = MT.ID