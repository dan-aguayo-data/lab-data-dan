SELECT
DATA.SUPPLIER_NUMBER AS ORG_ID
, DATA.SUPPLIER_NAME AS TRAD_NAME
, DATA.FIRST_NAME AS FNAME
, DATA.LAST_NAME AS LNAME
, DATA.EMAIL AS EMAIL
, MAX(DATA.PHONE_NUMBER) AS PHONE
, DATA.CONTRACT_STATUS AS CONT_STAT
, MAX(DATA.BM) AS BM
, MAX(DATA.EXPORTER) AS EXPORTER
, SYSDATE() AS INSERT_DATE_UTC
FROM (
    SELECT 
    COALESCE(BM.SUPPLIER_NUMBER,EX.SUPPLIER_NUMBER) AS SUPPLIER_NUMBER,
    COALESCE(BM.SUPPLIER_NAME,EX.SUPPLIER_NAME) AS SUPPLIER_NAME,
    COALESCE(BM.FIRST_NAME,EX.FIRST_NAME) AS FIRST_NAME,
    COALESCE(BM.LAST_NAME,EX.LAST_NAME) AS LAST_NAME,
    COALESCE(BM.EMAIL,EX.EMAIL) AS EMAIL,
    COALESCE(BM.PHONE_NUMBER,EX.PHONE_NUMBER) AS PHONE_NUMBER,
    COALESCE(BM.CONTRACT_STATUS,EX.CONTRACT_STATUS) AS CONTRACT_STATUS,
    CASE WHEN BM.TAXONOMY IS NOT NULL THEN 'Y' ELSE 'N' END AS BM,
    CASE WHEN EX.TAXONOMY IS NOT NULL THEN 'Y' ELSE 'N' END AS EXPORTER,
    COALESCE(BM.MULTI_SCHEME_ID,EX.MULTI_SCHEME_ID) AS MULTI_SCHEME_ID
    FROM {{ ref('MC_BM') }} AS BM
    FULL OUTER JOIN {{ ref('MC_EX') }} AS EX
    ON BM.SUPPLIER_NUMBER= EX.SUPPLIER_NUMBER
    AND BM.SUPPLIER_NAME= EX.SUPPLIER_NAME
    AND BM.FIRST_NAME = EX.FIRST_NAME
    AND BM.LAST_NAME = EX.LAST_NAME
    AND BM.EMAIL = EX.EMAIL
    AND BM.PHONE_NUMBER = EX.PHONE_NUMBER
    AND BM.CONTRACT_STATUS = EX.CONTRACT_STATUS
    AND BM.MULTI_SCHEME_ID = EX.MULTI_SCHEME_ID
) DATA
GROUP BY
DATA.SUPPLIER_NUMBER
, DATA.SUPPLIER_NAME
, DATA.FIRST_NAME
, DATA.LAST_NAME
, DATA.EMAIL
, DATA.CONTRACT_STATUS