SELECT
DATA.SUPPLIER_NUMBER AS ORG_ID
, DATA.SUPPLIER_NAME AS TRAD_NAME
, DATA.FIRST_NAME AS FNAME
, DATA.LAST_NAME AS LNAME
, DATA.EMAIL AS EMAIL
, MAX(DATA.PHONE_NUMBER) AS PHONE
, MAX(CASE WHEN DATA.TAXONOMY = 'Logistics Provider' THEN 'Y' ELSE 'N' END) AS LOGISTICS
, MAX(CASE WHEN DATA.TAXONOMY = 'MRF' THEN 'Y' ELSE 'N' END) AS MRF
, MAX(CASE WHEN DATA.TAXONOMY = 'Processor' THEN 'Y' ELSE 'N' END) AS PROCESSOR
, MAX(CASE WHEN DATA.TAXONOMY = 'Recycler' THEN 'Y' ELSE 'N' END) AS RECYCLER
, LISTAGG(DATA.SUBURB, ', ') WITHIN GROUP (ORDER BY DATA.SUBURB) AS CITY_SUB
, DATA.CONTRACT_STATUS AS CONT_STAT
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ ref('MC_SITES') }} AS DATA
WHERE
DATA.LAST_MODIFIED_ON_UTC >= DATEADD(DAY, -1, SYSDATE())
GROUP BY
DATA.SUPPLIER_NUMBER
, DATA.SUPPLIER_NAME
, DATA.FIRST_NAME
, DATA.LAST_NAME
, DATA.EMAIL
, DATA.CONTRACT_STATUS