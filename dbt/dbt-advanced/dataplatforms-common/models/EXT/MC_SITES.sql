SELECT
S.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, S.SCHEME AS SCHEME
, S.SUPPLIER_NUMBER AS SUPPLIER_NUMBER
, S.SUPPLIER_NAME AS SUPPLIER_NAME
, CC.FIRST_NAME AS FIRST_NAME
, CC.LAST_NAME AS LAST_NAME
, LOWER(NVL(CC.EMAIL, S.PO_COMMUNICATION_EMAIL)) AS EMAIL
, NVL(CC.PHONE_NUMBER, S.PHONE_NUMBER) AS PHONE_NUMBER
, S.TAXONOMY AS TAXONOMY
, S.CONTRACT_STATUS AS CONTRACT_STATUS
, S.SUBURB AS SUBURB
, S.LAST_MODIFIED_ON_UTC AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM (
    SELECT DISTINCT
    PS.SUPPLIER_NUMBER
    , PS.SUPPLIER_NAME
    , PS.PO_COMMUNICATION_EMAIL
    , PS.PHONE_NUMBER
    , PS.TAXONOMY
    , PS.SUBURB
    , PS.CONTRACT_STATUS
    , PS.LAST_MODIFIED_ON_UTC
    , PS.MULTI_SCHEME_ID
    , PS.SCHEME
    , PS.SITE_NUMBER
    , PS.SITE_NAME
    , PS.STATUS
    FROM (
        SELECT 
        PS.SUPPLIER_NUMBER
        , PS.SUPPLIER_NAME
        , PS.PO_COMMUNICATION_EMAIL
        , PS.PHONE_NUMBER
        , PS.TAXONOMY
        , PS.SUBURB
        , PS.CONTRACT_STATUS
        , PS.LAST_MODIFIED_ON_UTC
        , PS.MULTI_SCHEME_ID
        , PS.SCHEME
        , PS.SITE_NUMBER
        , PS.SITE_NAME
        , PS.STATUS
        FROM {{ ref('LSP_SITES') }} AS PS
        UNION ALL
        SELECT 
        PS.SUPPLIER_NUMBER
        , PS.SUPPLIER_NAME
        , PS.PO_COMMUNICATION_EMAIL
        , PS.PHONE_NUMBER
        , PS.TAXONOMY
        , PS.SUBURB
        , PS.CONTRACT_STATUS
        , PS.LAST_MODIFIED_ON_UTC
        , PS.MULTI_SCHEME_ID
        , PS.SCHEME
        , PS.SITE_NUMBER
        , PS.SITE_NAME
        , PS.STATUS
        FROM {{ ref('PROCESSOR_SITES') }} AS PS
        UNION ALL
        SELECT 
        PS.SUPPLIER_NUMBER
        , PS.SUPPLIER_NAME
        , PS.PO_COMMUNICATION_EMAIL
        , PS.PHONE_NUMBER
        , PS.TAXONOMY
        , PS.SUBURB
        , PS.CONTRACT_STATUS
        , PS.LAST_MODIFIED_ON_UTC
        , PS.MULTI_SCHEME_ID
        , PS.SCHEME
        , PS.SITE_NUMBER
        , PS.SITE_NAME
        , PS.STATUS
        FROM {{ ref('MRF_SITES') }} AS PS
        UNION ALL
        SELECT 
        PS.SUPPLIER_NUMBER
        , PS.SUPPLIER_NAME
        , PS.PO_COMMUNICATION_EMAIL
        , PS.PHONE_NUMBER
        , PS.TAXONOMY
        , PS.SUBURB
        , PS.CONTRACT_STATUS
        , PS.LAST_MODIFIED_ON_UTC
        , PS.MULTI_SCHEME_ID
        , PS.SCHEME
        , PS.SITE_NUMBER
        , PS.SITE_NAME
        , PS.STATUS
        FROM {{ ref('RECYCLER_SITES') }} AS PS
    ) PS
) S
LEFT JOIN (
    SELECT DISTINCT
    C.SITE_NUMBER
    , C.FIRST_NAME
    , C.LAST_NAME
    , C.EMAIL
    , CASE WHEN C.PHONE_NUMBER = '+61 0 0000' THEN NULL ELSE C.PHONE_NUMBER END AS PHONE_NUMBER
    FROM {{ ref('B2B_CONTACTS') }} AS C
    WHERE C.ASSIGNMENT_TYPE = 'SITE'
    AND C.ROLE = 'Authorised Contact'
    AND C.ROLE_ACTIVE = 1
    AND C.CONTACT_ACTIVE = 1
    AND C.FIRST_NAME IS NOT NULL
    AND C.EMAIL NOT IN ('test@yopmail.com', 'it-test@coexservices.com.au')
) CC
ON S.SITE_NUMBER = CC.SITE_NUMBER
WHERE S.MULTI_SCHEME_ID = 10000
AND S.STATUS = 'Active'
AND S.PO_COMMUNICATION_EMAIL NOT IN ('test@yopmail.com', 'it-test@coexservices.com.au')
AND S.SITE_NAME NOT LIKE '%PVT%'
AND S.CONTRACT_STATUS = 'Active'