SELECT
C.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SUBSTR(C.CONSUMER_ID, 1, 9) AS SCHEME_ID
, CASE WHEN C.CONSUMER_TYPE = 'Consumer' THEN NULL ELSE C.LEGAL_NAME END AS TRAD_NAME
, C.FIRST_NAME AS FNAME
, C.LAST_NAME AS LNAME
, C.EMAIL AS EMAIL
, C.POSTCODE AS POST_CODE
, TRIM(REGEXP_REPLACE(C.REGION, '[0-9]',  '')) AS REGION
, C.CONSUMER_TYPE AS TAXONOMY
, CAST(C.REGISTRATION_DATE AS DATE) AS REG_DATE
, CASE WHEN COL.FLAG = 1 THEN 'Y' ELSE 'N' END AS ACTIVE_ID
, CASE WHEN C.CONSUMER_TYPE = 'Charity' THEN I.DESCRIPTION ELSE NULL END AS WEB_DESC
, CASE WHEN C.CONSUMER_TYPE = 'Charity' THEN (CASE WHEN I.PUBLIC_WEBSITE_CONSENT IS NOT NULL THEN 'Y' ELSE 'N' END) ELSE NULL END AS WEB_CONS
, CASE WHEN I.CATEGORIES LIKE '%2109%' THEN 'Y' ELSE 'N' END AS "AGED_CARE"
, CASE WHEN I.CATEGORIES LIKE '%1083%' THEN 'Y' ELSE 'N' END AS "ANIMALS"
, CASE WHEN I.CATEGORIES LIKE '%1084%' THEN 'Y' ELSE 'N' END AS "ARTS_CULT"
, CASE WHEN I.CATEGORIES LIKE '%1085%' THEN 'Y' ELSE 'N' END AS "COMM_DEV"
, CASE WHEN I.CATEGORIES LIKE '%2111%' THEN 'Y' ELSE 'N' END AS "COM_SAFETY"
, CASE WHEN I.CATEGORIES LIKE '%1086%' THEN 'Y' ELSE 'N' END AS "DISABILITY"
, CASE WHEN I.CATEGORIES LIKE '%1088%' THEN 'Y' ELSE 'N' END AS "DIS_RELIEF"
, CASE WHEN I.CATEGORIES LIKE '%1087%' THEN 'Y' ELSE 'N' END AS "FAM_VIOLEN"
, CASE WHEN I.CATEGORIES LIKE '%1089%' THEN 'Y' ELSE 'N' END AS "EDUCATION"
, CASE WHEN I.CATEGORIES LIKE '%1090%' THEN 'Y' ELSE 'N' END AS "ENVIRON"
, CASE WHEN I.CATEGORIES LIKE '%1091%' THEN 'Y' ELSE 'N' END AS "HEALTH"
, CASE WHEN I.CATEGORIES LIKE '%1092%' THEN 'Y' ELSE 'N' END AS "HUMAN_CIVL"
, CASE WHEN I.CATEGORIES LIKE '%1093%' THEN 'Y' ELSE 'N' END AS "HUMAN_SERV"
, CASE WHEN I.CATEGORIES LIKE '%2112%' THEN 'Y' ELSE 'N' END AS "INDEG_AU"
, CASE WHEN I.CATEGORIES LIKE '%1094%' THEN 'Y' ELSE 'N' END AS "INTERNAT"
, CASE WHEN I.CATEGORIES LIKE '%2113%' THEN 'Y' ELSE 'N' END AS "MHS"
, CASE WHEN I.CATEGORIES LIKE '%1095%' THEN 'Y' ELSE 'N' END AS "RELIGION"
, CASE WHEN I.CATEGORIES LIKE '%1096%' THEN 'Y' ELSE 'N' END AS "RESEARCH"
, CASE WHEN I.CATEGORIES LIKE '%1097%' THEN 'Y' ELSE 'N' END AS "SOCIAL_ENT"
, CASE WHEN I.CATEGORIES LIKE '%1099%' THEN 'Y' ELSE 'N' END AS "VET_SERV"
, CASE WHEN I.CATEGORIES LIKE '%2110%' THEN 'Y' ELSE 'N' END AS "YSS"
, NVL(EP.LATEST_NEWS, 'Y') AS LATEST_NEWS
, NVL(EP.COMPETITION_AND_PROMOTIONS, 'Y') AS COMPETITION_AND_PROMOTIONS
, NVL(EP.REFUND_POINT, 'Y') AS REFUND_POINT
, NVL(EP.OPT_EVENTS, 'Y') AS OPT_EVENTS
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ ref('CONSUMER') }} AS C
LEFT JOIN (
    SELECT DISTINCT
    H.CONSUMER_ID
    , 1 AS FLAG
    FROM {{ ref('CRP_COLLECTION_HDR') }} AS H
    WHERE H.COLLECTION_QTY IS NOT NULL
) COL
ON C.CONSUMER_ID = COL.CONSUMER_ID
LEFT JOIN {{ ref('CONSUMER_PUBLIC_INFO') }} AS I
ON C.CONSUMER_ID = I.CONSUMER_ID
LEFT JOIN (
    SELECT
    P.EMAIL
    , (CASE REGEXP_COUNT(TO_CHAR(VALUE,'utf8'), '\\blatest_news\\b', 1) WHEN 1 THEN 'N' ELSE 'Y' END) AS LATEST_NEWS
    , (CASE REGEXP_COUNT(TO_CHAR(VALUE,'utf8'), '\\bcompetition_and_promotions\\b', 1) WHEN 1 THEN 'N' ELSE 'Y' END) AS COMPETITION_AND_PROMOTIONS
    , (CASE REGEXP_COUNT(TO_CHAR(VALUE,'utf8'), '\\brefund_point\\b', 1) WHEN 1 THEN 'N' ELSE 'Y' END) AS REFUND_POINT
    , (CASE REGEXP_COUNT(TO_CHAR(VALUE,'utf8'), '\\bopt_events\\b', 1) WHEN 1 THEN 'N' ELSE 'Y' END) AS OPT_EVENTS
    FROM {{ source('CES_DRUPAL', 'MARKETING_EMAIL_PREFERENCES') }} AS P
    QUALIFY ROW_NUMBER() OVER (PARTITION BY P.EMAIL ORDER BY DECODE(NVL(LOWER(P.TYPE), ''), 'organisation', 1, 'individual', 2, 99)) = 1
) EP
ON LOWER(C.EMAIL) = LOWER(EP.EMAIL)
WHERE C.MULTI_SCHEME_ID = 10000
AND C.EMAIL IS NOT NULL