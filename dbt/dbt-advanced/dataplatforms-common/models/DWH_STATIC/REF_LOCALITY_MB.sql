SELECT
MB.MB_CODE_2021 AS MB_CODE
, MB.MB_CATEGORY_2021 AS MB_CATEGORY_NAME
, CAST(MB.AREA_ALBERS_SQKM AS FLOAT) AS AREA_ALBERS_SQKM
, MB.SA1_CODE_2021 AS SA1_CODE
, MB.SA2_CODE_2021 AS SA2_CODE
, MB.SA2_NAME_2021 AS SA2_NAME
, MB.SA3_CODE_2021 AS SA3_CODE
, MB.SA3_NAME_2021 AS SA3_NAME
, MB.SA4_CODE_2021 AS SA4_CODE
, MB.SA4_NAME_2021 AS SA4_NAME
, MB.GCCSA_CODE_2021 AS GCCSA_CODE
, MB.GCCSA_NAME_2021 AS GCCSA_NAME
, MB.STATE_CODE_2021 AS STATE_CODE
, MB.STATE_NAME_2021 AS STATE_NAME
, POA.POA_CODE_2021 AS POA_CODE
, POA.POA_NAME_2021 AS POA_NAME
, SSC.SAL_CODE_2021 AS SSC_CODE
, TRIM(SPLIT_PART(SSC.SAL_NAME_2021, '(',1)) AS SSC_NAME
, LGA.LGA_CODE_2021 AS LGA_CODE
, LGA.LGA_NAME_2021 AS LGA_NAME
, SED.SED_CODE_2021 AS SED_CODE
, SED.SED_NAME_2021 AS SED_NAME
, TR.TR_CODE_2021 AS TR_CODE
, TR.TR_NAME_2021 AS TR_NAME
, ISA.ILOC_CODE_2021 AS ILOC_CODE
, ISA.ILOC_NAME_2021 AS ILOC_NAME
, ISA.IARE_CODE_2021 AS IARE_CODE
, ISA.IARE_NAME_2021 AS IARE_NAME
, ISA.IREG_CODE_2021 AS IREG_CODE
, ISA.IREG_NAME_2021 AS IREG_NAME
, CASE WHEN DG.ILOC_CODE_2021 IS NULL THEN 0 ELSE 1 END AS ABORIGINAL_SHIRE_FLAG
, MBC.DWELLING AS DWELLING
, MBC.PERSON AS POPULATION
, MBLL.LONGITUDE AS LONGITUDE
, MBLL.LATITUDE AS LATITUDE
, CASE WHEN R.REGION = 'Goldfields-Esperance' THEN 'Goldfields - Esperance' ELSE R.REGION END AS REGION
, CASE WHEN MB.STATE_NAME_2021 = 'Queensland' AND R.SUBREGION IS NULL THEN '00 Unknown' ELSE R.SUBREGION END AS SUBREGION
FROM 
{{ source('ABS', 'MB_2021') }} AS MB
INNER JOIN {{ source('ABS', 'MESH_BLOCK_COUNTS_2021') }} AS MBC
ON MB.MB_CODE_2021 = MBC.MB_CODE_2021
INNER JOIN {{ source('ABS', 'MB_CENTROID_2021') }} AS MBLL
ON MB.MB_CODE_2021 = MBLL.MB_CODE_2021
INNER JOIN {{ source('ABS', 'SED_2021') }} AS SED
ON MB.MB_CODE_2021 = SED.MB_CODE_2021
INNER JOIN {{ source('ABS', 'LGA_2021') }} AS LGA
ON MB.MB_CODE_2021 = LGA.MB_CODE_2021
INNER JOIN {{ source('ABS', 'POA_2021') }} AS POA
ON MB.MB_CODE_2021 = POA.MB_CODE_2021
INNER JOIN {{ source('ABS', 'SAL_2021') }} AS SSC
ON MB.MB_CODE_2021 = SSC.MB_CODE_2021
INNER JOIN {{ source('ABS', 'INDIGENOUS_STRUCTURE_ALLOCATION_2021') }} AS ISA
ON MB.SA1_CODE_2021 = ISA.SA1_CODE_2021
INNER JOIN {{ source('ABS', 'TR_2021') }} AS TR
ON MB.SA2_CODE_2021 = TR.SA2_CODE_2021
LEFT JOIN (
    SELECT
    ILOC_CODE_2021
    , ILOC_NAME_2021
    FROM {{ source('ABS', 'ILOC_2021') }} AS ILOC
    WHERE ILOC_CODE_2021 IN ('30700301','30300801','30700201','30600301','30700202','30400202','30700501','30700101','30300401','30700401','30300802','30300501','30700302','30300601','30700303','30300701','30300702','30300803','31000901','30300901','30700402','30700304','30700203','30300804','30700503','30300805','30700403','30500404','30901102','30901201','30700404')
) DG
ON ISA.ILOC_CODE_2021 = DG.ILOC_CODE_2021
LEFT JOIN (
    SELECT
    LGA_CODE_2021
    , LGA_NAME_2021
    , COEX_SUBREGION AS SUBREGION
    , COEX_REGION AS REGION
    FROM {{ source('ABS', 'COEX_LGA_REGION_MAPPING_2021') }} AS QLDR
    UNION ALL
    SELECT
    LGA_CODE_2021
    , LGA_NAME_2021
    , NULL AS SUBREGION
    , WARRRL_REGION AS REGION
    FROM {{ source('ABS', 'WARRRL_LGA_REGION_MAPPING_2021') }} AS WAR
) R
ON LGA.LGA_CODE_2021 = R.LGA_CODE_2021