WITH AGG AS (
  SELECT
   SA2
  , SA2_NAME 
  , SA3_NAME 
  , SA4_NAME 
  , GCCSA_NAME 
  , POSTCODE 
  , STATE
  , LGA 
  , REGION 
  , SUM(AREA) AS AREA_B
  , SUM(POPULATION) AS POPULATION_B
  FROM 
  {{ ref('REF_LOCALITY_SA1_OLD') }} AS V
  GROUP BY POA_SSC_ID
  , SA2
  , SA2_NAME 
  , SA3_NAME 
  , SA4_NAME 
  , GCCSA_NAME 
  , POSTCODE 
  , SUBURB 
  , STATE
  , LGA 
  , REGION 
)

, RANK AS (
  SELECT *, 
      ROW_NUMBER() OVER (PARTITION BY POSTCODE ORDER BY AREA_B DESC) AS RNK, 
      SUM(AREA_B) OVER (PARTITION BY POSTCODE) AS AREA, 
      SUM(POPULATION_B) OVER (PARTITION BY POSTCODE) AS POPULATION
  FROM AGG
)

SELECT
    POSTCODE 
  , STATE
  , LGA 
  , REGION 
  , AREA
  , POPULATION
  , SA2
  , SA2_NAME 
  , SA3_NAME 
  , SA4_NAME 
  , GCCSA_NAME 
FROM RANK
WHERE RNK = 1