{{
    config(
        materialized = 'incremental',
        unique_key = 'SITE_NUMBER'
    )
}} 

WITH PS AS (
SELECT
PS.MULTI_SCHEME_ID
, PS.SITE_NUMBER
, PS.Y_CORDINATES AS LONGITUDE
, PS.X_CORDINDATES AS LATITUDE
, CASE WHEN PS.Y_CORDINATES BETWEEN -180 AND 180 AND PS.X_CORDINDATES BETWEEN -90 AND 90 THEN ST_MAKEPOINT(PS.Y_CORDINATES, PS.X_CORDINDATES) ELSE NULL END AS PS_POINT
, PS.SITE_TYPE_ID
, PS.LAST_MODIFIED_ON
FROM {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS
{% if is_incremental() %}
    LEFT JOIN {{this}} R
    ON PS.SITE_NUMBER = R.SITE_NUMBER
{% endif %}
WHERE Y_CORDINATES > 0
AND SITE_TYPE_ID <> '1537'

{% if is_incremental() %}
    AND
        (
            R.SITE_NUMBER IS NULL
            OR PS.Y_CORDINATES <> R.LONGITUDE
            OR PS.X_CORDINDATES <> R.LATITUDE
            )
{% endif %}
)

/* CRP QLD */
SELECT
PS.MULTI_SCHEME_ID
, PS.SITE_NUMBER
, PS.LONGITUDE
, PS.LATITUDE
, PS.LAST_MODIFIED_ON
, ADD.MB_CODE
, ADD.REGION
, ADD.SUBREGION
, 'CRP' AS TAXONOMY
FROM PS
CROSS JOIN {{ ref('ADDRESS_VIEW') }} ADD
WHERE PS.MULTI_SCHEME_ID = 10000
AND PS.SITE_TYPE_ID = '1538'
AND ADD.STATE = 'QLD'
QUALIFY ROW_NUMBER() OVER (PARTITION BY PS.SITE_NUMBER ORDER BY ST_DISTANCE(PS.PS_POINT, ADD.ADD_POINT)) = 1

UNION ALL

