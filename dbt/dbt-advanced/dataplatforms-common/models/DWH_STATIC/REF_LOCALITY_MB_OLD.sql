SELECT
MB.MB_CODE_2016 AS MB_CODE
, MB.MB_CATEGORY_NAME_2016 AS MB_CATEGORY_NAME
, CAST(MB.AREA_ALBERS_SQKM AS FLOAT) AS AREA_ALBERS_SQKM
, MB.SA1_MAINCODE_2016 AS SA1_MAINCODE
, MB.SA1_7DIGITCODE_2016 AS SA1_7DIGITCODE
, MB.SA2_MAINCODE_2016 AS SA2_MAINCODE
, MB.SA2_5DIGITCODE_2016 AS SA2_5DIGITCODE
, MB.SA2_NAME_2016 AS SA2_NAME
, MB.SA3_NAME_2016 AS SA3_NAME
, MB.SA4_NAME_2016 AS SA4_NAME
, MB.GCCSA_CODE_2016 AS GCCSA_CODE
, MB.GCCSA_NAME_2016 AS GCCSA_NAME
, POA.POA_CODE_2016 AS POA_CODE
, POA.POA_NAME_2016 AS POA_NAME
, SSC.SSC_CODE_2016 AS SSC_CODE
, TRIM(SPLIT_PART(SSC.SSC_NAME_2016, '(',1)) AS SSC_NAME
, SSC.STATE_NAME_2016 AS STATE_NAME
, LGA.LGA_CODE_2020 AS LGA_CODE
, LGA.LGA_NAME_2020 AS LGA_NAME
, COALESCE(QLD.REGION, CASE WHEN WA.REGION = 'Goldfields-Esperance' THEN 'Goldfields - Esperance' ELSE WA.REGION END) AS REGION
FROM 
{{ source('LOOKUPS', 'MB_2016_AUST') }} AS MB
LEFT JOIN {{ source('LOOKUPS', 'POA_2016_AUST') }} AS POA
ON MB.MB_CODE_2016 = POA.MB_CODE_2016
LEFT JOIN {{ source('LOOKUPS', 'SSC_2016_AUST') }} AS SSC
ON MB.MB_CODE_2016 = SSC.MB_CODE_2016
LEFT JOIN {{ source('LOOKUPS', 'LGA_2020_AUST') }} AS LGA
ON MB.MB_CODE_2016 = LGA.MB_CODE_2016
LEFT JOIN {{ source('LOOKUPS', 'REGION_QLD') }} AS QLD
ON LGA.LGA_NAME_2020 = QLD.LGA_NAME
LEFT JOIN {{ source('LOOKUPS', 'REGION_WA') }} AS WA
ON POA.POA_CODE_2016 = WA.POA_CODE
AND TRIM(SPLIT_PART(SSC.SSC_NAME_2016, '(',1)) = WA.SSC_NAME