WITH AGG AS (
  SELECT
    POA_SSC_ID 
  , SA2
  , SA2_NAME 
  , SA3_NAME 
  , SA4_NAME 
  , GCCSA_NAME 
  , POSTCODE 
  , SUBURB 
  , STATE
  , LGA 
  , REGION 
  , SUBREGION 
  , SUM(AREA) AS AREA
  , SUM(POPULATION) AS POPULATION
  FROM 
  {{ ref('REF_LOCALITY_SA1') }} AS SA1
  GROUP BY
  POA_SSC_ID
  , SA2
  , SA2_NAME 
  , SA3_NAME 
  , SA4_NAME 
  , GCCSA_NAME 
  , POSTCODE 
  , SUBURB 
  , STATE
  , LGA 
  , REGION 
  , SUBREGION 
)

SELECT
POA_SSC_ID 
, SA2
, SA2_NAME 
, SA3_NAME 
, SA4_NAME 
, GCCSA_NAME 
, POSTCODE 
, SUBURB 
, STATE
, LGA 
, REGION 
, SUBREGION 
, SUM(AREA) OVER (PARTITION BY POA_SSC_ID) AS AREA
, SUM(POPULATION) OVER (PARTITION BY POA_SSC_ID) AS POPULATION
FROM AGG
QUALIFY ROW_NUMBER() OVER (PARTITION BY POA_SSC_ID ORDER BY AREA DESC) = 1