WITH AGG AS (
  SELECT
    MB.SA1_CODE
  , MB.SA2_CODE
  , MB.SA2_NAME 
  , MB.SA3_NAME 
  , MB.SA4_NAME 
  , MB.GCCSA_NAME 
  , MB.POA_CODE 
  , MB.SSC_NAME 
  , MB.STATE_NAME
  , MB.LGA_NAME 
  , MB.REGION 
  , MB.SUBREGION 
  , SUM(MB.POPULATION) AS POPULATION
  , SUM(MB.AREA_ALBERS_SQKM) AS AREA_ALBERS_SQKM
  FROM 
  {{ ref('REF_LOCALITY_MB') }} AS MB
  GROUP BY
    MB.SA1_CODE
  , MB.SA2_CODE 
  , MB.SA2_NAME 
  , MB.SA3_NAME 
  , MB.SA4_NAME
  , MB.GCCSA_NAME 
  , MB.POA_CODE 
  , MB.SSC_NAME 
  , MB.STATE_NAME 
  , MB.LGA_NAME 
  , MB.REGION 
  , MB.SUBREGION 
)

SELECT
AGG.SA1_CODE AS SA1
, AGG.POA_CODE || '-' || AGG.SSC_NAME AS POA_SSC_ID
, AGG.POA_CODE AS POSTCODE
, AGG.SSC_NAME AS SUBURB
, AGG.STATE_NAME AS STATE
, AGG.LGA_NAME AS LGA
, AGG.REGION AS REGION
, AGG.SUBREGION AS SUBREGION
, AGG.SA2_CODE AS SA2
, AGG.SA2_NAME AS SA2_NAME
, AGG.SA3_NAME AS SA3_NAME
, AGG.SA4_NAME AS SA4_NAME
, AGG.GCCSA_NAME AS GCCSA_NAME
, LL.LONGITUDE
, LL.LATITUDE
, SUM(AGG.POPULATION) OVER (PARTITION BY AGG.SA1_CODE) AS POPULATION
, SUM(AGG.AREA_ALBERS_SQKM) OVER (PARTITION BY AGG.SA1_CODE) AS AREA
FROM AGG
LEFT JOIN (
    SELECT
    MB.SA1_CODE
    , MB.LONGITUDE
    , MB.LATITUDE
    FROM   {{ ref('REF_LOCALITY_MB') }} AS MB
    QUALIFY ROW_NUMBER() OVER (PARTITION BY MB.SA1_CODE ORDER BY MB.AREA_ALBERS_SQKM DESC) = 1
) LL
ON AGG.SA1_CODE = LL.SA1_CODE
QUALIFY ROW_NUMBER() OVER (PARTITION BY AGG.SA1_CODE ORDER BY AGG.AREA_ALBERS_SQKM DESC) = 1