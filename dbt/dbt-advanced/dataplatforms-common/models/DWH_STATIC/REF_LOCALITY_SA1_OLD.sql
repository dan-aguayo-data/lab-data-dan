WITH AGG AS (
  SELECT
    MB.SA1_MAINCODE 
  , MB.SA1_7DIGITCODE
  , MB.SA2_MAINCODE
  , MB.SA2_NAME 
  , MB.SA3_NAME 
  , MB.SA4_NAME 
  , MB.GCCSA_NAME 
  , MB.POA_CODE 
  , MB.SSC_NAME 
  , MB.STATE_NAME
  , MB.LGA_NAME 
  , MB.REGION 
  , SUM(MB.AREA_ALBERS_SQKM) AS AREA_ALBERS_SQKM
  FROM 
  {{ ref('REF_LOCALITY_MB_OLD') }} AS MB
  GROUP BY MB.SA1_MAINCODE
  , MB.SA1_7DIGITCODE
  , MB.SA2_MAINCODE 
  , MB.SA2_NAME 
  , MB.SA3_NAME 
  , MB.SA4_NAME
  , MB.GCCSA_NAME 
  , MB.POA_CODE 
  , MB.SSC_NAME 
  , MB.STATE_NAME 
  , MB.LGA_NAME 
  , MB.REGION 
)

, RANK AS (
  SELECT *, 
      ROW_NUMBER() OVER (PARTITION BY SA1_MAINCODE ORDER BY AREA_ALBERS_SQKM DESC) AS RNK, 
      SUM(AREA_ALBERS_SQKM) OVER (PARTITION BY SA1_MAINCODE) AS AREA
  FROM AGG
)

SELECT
    SA1_MAINCODE AS SA1
  , SA1_7DIGITCODE AS SA1_7DIGIT
  , POA_CODE || '-' || SSC_NAME AS POA_SSC_ID
  , POA_CODE AS POSTCODE
  , SSC_NAME AS SUBURB
  , STATE_NAME AS STATE
  , LGA_NAME AS LGA
  , REGION AS REGION
  , AREA
  , POPULATION
  , SA2_MAINCODE AS SA2
  , SA2_NAME AS SA2_NAME
  , SA3_NAME AS SA3_NAME
  , SA4_NAME AS SA4_NAME
  , GCCSA_NAME AS GCCSA_NAME
FROM RANK
LEFT JOIN {{ ref('REF_POPULATION') }} AS POP
ON RANK.SA1_7DIGITCODE = POP.SA1
AND POP.RECENT_FLAG = 1
WHERE RNK = 1