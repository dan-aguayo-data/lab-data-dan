WITH AGG AS (
  SELECT
   MB.SA2_CODE AS SA2
  , MB.SA2_NAME 
  , MB.SA3_NAME 
  , MB.SA4_NAME 
  , MB.GCCSA_NAME 
  , MB.POA_CODE AS POSTCODE 
  , MB.STATE_NAME AS STATE
  , MB.LGA_NAME AS LGA 
  , MB.REGION 
  , MB.SUBREGION 
  , SUM(MB.AREA_ALBERS_SQKM) AS AREA
  , SUM(MB.POPULATION) AS POPULATION
  FROM 
  {{ ref('REF_LOCALITY_MB') }} AS MB
  GROUP BY
   MB.SA2_CODE
  , MB.SA2_NAME 
  , MB.SA3_NAME 
  , MB.SA4_NAME 
  , MB.GCCSA_NAME 
  , MB.POA_CODE 
  , MB.STATE_NAME
  , MB.LGA_NAME
  , MB.REGION 
  , MB.SUBREGION 
)

SELECT
AGG.POSTCODE || '-' || AGG.STATE AS POA_ID
, AGG.SA2
, AGG.SA2_NAME 
, AGG.SA3_NAME 
, AGG.SA4_NAME 
, AGG.GCCSA_NAME 
, AGG.POSTCODE 
, AGG.STATE
, AGG.LGA 
, AGG.REGION 
, AGG.SUBREGION 
, LL.LONGITUDE
, LL.LATITUDE
, SUM(AGG.AREA) OVER (PARTITION BY AGG.POSTCODE, AGG.STATE) AS AREA
, SUM(AGG.POPULATION) OVER (PARTITION BY AGG.POSTCODE, AGG.STATE) AS POPULATION
FROM AGG
LEFT JOIN (
    SELECT
    MB.POA_CODE AS POSTCODE
    , MB.STATE_NAME AS STATE
    , MB.LONGITUDE
    , MB.LATITUDE
    FROM {{ ref('REF_LOCALITY_MB') }} AS MB
    QUALIFY ROW_NUMBER() OVER (PARTITION BY MB.POA_CODE, MB.STATE_NAME ORDER BY MB.AREA_ALBERS_SQKM DESC) = 1
) LL
ON AGG.POSTCODE = LL.POSTCODE
AND AGG.STATE = LL.STATE
QUALIFY ROW_NUMBER() OVER (PARTITION BY AGG.POSTCODE, AGG.STATE ORDER BY AGG.AREA DESC) = 1