SELECT
ERP.SA1 AS SA1
, ERP.YEAR AS YEAR
, CAST(REPLACE(ERP.POPULATION,',','') AS FLOAT) AS POPULATION
, CASE WHEN YEAR = MAX(ERP.YEAR) OVER () THEN 1 ELSE 0 END AS RECENT_FLAG
FROM
{{ source('LOOKUPS', 'ERP_SA1_2020_AUST') }} AS ERP
UNPIVOT(POPULATION FOR YEAR IN ("2011", "2012", "2013", "2014", "2015", "2016", "2017", "2018", "2019", "2020"))