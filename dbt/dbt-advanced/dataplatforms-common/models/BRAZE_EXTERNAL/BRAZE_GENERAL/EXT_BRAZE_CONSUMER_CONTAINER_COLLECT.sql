SELECT
PS.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, CCB.SCHEME_ID AS SCHEME_ID
, CCB.PICKUP_STATUS AS PICKUP_STATUS
, CCB.CONTAINERS_COLLECTED AS CONTAINERS_COLLECTED
, TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(CCB.DATE AS TIMESTAMP)),'YYYYMMDD') AS CONTAINER_COLLECT_DATE_KEY
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('COEX_COLLECT', 'CONTAINER_COLLECT_BOOKINGS') }} AS CCB
LEFT JOIN {{ source('CES_DRUPAL', 'PARTICIPANT_SITES') }} AS PS
ON CCB.SCHEME_ID = PS.SITE_NUMBER
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON PS.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID