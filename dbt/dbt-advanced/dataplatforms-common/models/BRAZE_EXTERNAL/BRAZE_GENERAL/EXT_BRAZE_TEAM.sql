I.CONSUMER_ID_INDIVIDUAL AS "consumer_id",
{% endif %}
--********* PROD *********--

  PG.CONSUMER_NUMBER AS "team_member_number"
, PG.ALTERNATE_NAME AS "team_name"
, PSG.POST_CODE AS "team_postcode"
, PSG.CITY_SUBURB AS "team_suburb"
, CASE WHEN PSG.TAXONOMY_TYPE_ID = 'Consumer GST Registered' THEN 'Business' ELSE PSG.TAXONOMY_TYPE_ID END AS "team_type"

--********* PROD *********--
{% if target.name.upper() == 'PROD' %}
, CASE WHEN CRG.ROLE_TYPE_CODE = 'GROUP_MEMBER' THEN 'team_mate' ELSE 'team_captain' END AS "role"
{% endif %}
--********* PROD *********--

, NVL(CRP.FLAG,'FALSE') AS "team_member_number_transacted"
, PPP.PAYMENT_METHOD AS "team_payment_method"
, PSG.CREATED_ON AS "team_registration_date"
, TO_NUMBER(NULLIF(TRIM(REGEXP_REPLACE(NVL(SSC.SUBREGION, POA.SUBREGION), '[^[:digit:]]', ' ')), '')) AS "team_subregion_id"

--********* PROD *********--
{% if target.name.upper() == 'PROD' %}
, PSG.PARTICIPANT_SITE_ID AS PARTICIPANT_SITE_ID
, COUNT(DISTINCT I.CONSUMER_ID_INDIVIDUAL) OVER (PARTITION BY PG.CONSUMER_NUMBER) AS "team_num_teammates"
{% endif %}
--********* PROD *********--

, CASE WHEN PW.PUBLIC_WEBSITE_CONSENT = 'Y' THEN 'TRUE' ELSE 'FALSE' END AS "team_shared_cause"

--********* UAT *********--
{% if target.name.upper() != 'PROD' %}

, NVL(CASE WHEN CONVERT_TIMEZONE('UTC','Australia/Queensland',SYSDATE()) BETWEEN TRUNC(G.GOAL_START_DATE, 'DAY') AND TRUNC(G.GOAL_END_DATE, 'DAY') THEN TRUE ELSE FALSE END, 'FALSE') AS "team_goal_set_flag"
, CRP.TRANSACTIONS_LAST_3_MONTHS AS "team_transactions_last_3_months"
, CASE WHEN COUNT(DISTINCT BS.POST_CODE) OVER (PARTITION BY PSG.POST_CODE) > 0 THEN 'TRUE' ELSE 'FALSE' END AS "team_container_collect_available_flag"
, DATEDIFF('DAY',CONVERT_TIMEZONE('UTC','Australia/Queensland',SYSDATE()),G.GOAL_END_DATE) AS "team_days_remaining_to_goal_end_date"
, CRP.TRANSACTION_DATE_UTC AS "team_last_transaction_date"
, CRP.CRP_SITE_NAME AS "team_last_visited_rp"
, CCB.LAST_CONTAINER_COLLECT_BOOKING_DATE AS "team_last_container_collect_booking_date"
, CRP.COLLECTION_QTY_LIFETIME AS "team_collection_qty_lifetime"
, CRP.REFUND_AMOUNT_LIFETIME AS "team_refund_amount_lifetime"
, CRP.REFUND_AMOUNT_DONATED_LIFETIME AS "team_donated_amount_lifetime"
, CRP.CONTAINERS_DONATED_LIFETIME AS "team_donated_collection_qty_lifetime"
, CRP.COLLECTION_QTY_LAST_12_MONTHS AS "team_collection_qty_last_12_months"
, CRP.REFUND_AMOUNT_LAST_12_MONTHS AS "team_refund_amount_last_12_months"
, CRP.CONTAINERS_DONATED_LAST_12_MONTHS AS "team_containers_donated_last_12_months"
, CRP.REFUND_AMOUNT_DONATED_LAST_12_MONTHS AS "team_refund_amount_donated_last_12_months"
, CASE WHEN CONVERT_TIMEZONE('UTC','Australia/Queensland',SYSDATE()) BETWEEN G.GOAL_START_DATE AND G.GOAL_END_DATE THEN CEIL((G.GOAL_AMOUNT) / CEIL(DATEDIFF('DAY',G.GOAL_START_DATE,G.GOAL_END_DATE)/7 ,0),1) ELSE NULL END AS "team_target_amount_per_week"
, CASE WHEN CONVERT_TIMEZONE('UTC','Australia/Queensland',SYSDATE()) BETWEEN G.GOAL_START_DATE AND G.GOAL_END_DATE THEN CEIL((G.GOAL_AMOUNT * 10) / CEIL(DATEDIFF('DAY',G.GOAL_START_DATE,G.GOAL_END_DATE)/7 ,0)) ELSE NULL END AS "team_target_qty_per_week"
, CEIL(G.COLLECTION_QTY_ALUMINIUM,0) AS "team_qty_returned_towards_goal_aluminium"
, CEIL(G.COLLECTION_QTY_GLASS,0) AS "team_qty_returned_towards_goal_glass"
, CEIL(G.COLLECTION_QTY_PLASTIC,0) AS "team_qty_returned_towards_goal_plastic"
, CEIL(G.GOAL_AMOUNT * 1.1,1) AS "team_10_percent_more_amount_earned_than_previous_goal"
, CEIL((G.GOAL_AMOUNT * 10) * 1.1) AS "team_10_percent_more_containers_than_previous_goal"
, CEIL(G.COLLECTION_QTY / 10,2) AS "team_amount_earned_previous_goal"
, G.COLLECTION_QTY AS "team_containers_returned_previous_goal"
, CEIL(((G.GOAL_AMOUNT ) / (CEIL(DATEDIFF('DAY',G.GOAL_START_DATE,G.GOAL_END_DATE)/7 ,0))) * 0.1,1) AS "team_difference_target_amount_per_week"
, CEIL(((G.GOAL_AMOUNT * 10) / (CEIL(DATEDIFF('DAY',G.GOAL_START_DATE,G.GOAL_END_DATE)/7 ,0))) * 0.1) AS "team_difference_target_qty_per_week"
, CEIL(G.COLLECTION_QTY_BIKES,0) AS "team_goal_return_impact_qty_bikes"
, CEIL(G.COLLECTION_QTY_JUMPERS,0) AS "team_goal_return_impact_qty_jumpers"
, CEIL(G.COLLECTION_QTY_WINDSHIELDS,0) AS "team_goal_return_impact_qty_windshields"
, CEIL(((G.GOAL_AMOUNT * 10) / (CEIL(DATEDIFF('DAY',G.GOAL_START_DATE,G.GOAL_END_DATE)/7 ,0))) * 1.1) AS "team_new_target_qty_per_week"
, CEIL(((G.GOAL_AMOUNT) / (CEIL(DATEDIFF('DAY',G.GOAL_START_DATE,G.GOAL_END_DATE)/7 ,0))) * 1.1) AS "team_new_target_amount_per_week"
, CRP.COLLECTION_QTY_LAST_1_MONTHS AS "team_collection_qty_last_1_month"
, CRP.REFUND_AMOUNT_LAST_1_MONTHS AS "team_refund_amount_last_1_month"
, CRP.CONTAINERS_DONATED_LAST_1_MONTHS AS "team_donated_qty_last_1_month"
, CRP.REFUND_AMOUNT_DONATED_LAST_1_MONTHS AS "team_donated_amount_last_1_month"
, CRP.TRANSACTIONS_LAST_12_MONTHS AS "team_transactions_last_12_months"
, CRP.RP_VISITED_LAST_12_MONTHS AS "team_rp_visited_last_12_months"
, CRP.TOP_CHARITY_LAST_12_MONTH AS "team_top_charity_12_months"
, NVL(BS.DAY_OF_SERVICE, 'NA') AS "team_container_collect_day_of_service"
, LOWER(CRP2.MATERIAL_NAME_1) AS "team_material_name_1"
, CASE WHEN CRP2.MATERIAL_QTY_1 = 0 THEN NULL ELSE CRP2.MATERIAL_QTY_1 END AS "team_material_qty_1"
, CRP.MOST_VISITED_RP AS "team_most_visited_rp"
, CASE WHEN CRP2.MATERIAL_NAME_1='ALUMINIUM' THEN 'Bikes' WHEN CRP2.MATERIAL_NAME_1='GLASS' THEN 'Windscreens' WHEN CRP2.MATERIAL_NAME_1='PLASTIC' THEN 'Jumpers'  ELSE NULL END AS "team_return_impact_item_name"
, CEIL(CASE WHEN CRP2.MATERIAL_NAME_1='ALUMINIUM' THEN CRP2.MATERIAL_QTY_1/67 WHEN CRP2.MATERIAL_NAME_1='GLASS' THEN CRP2.MATERIAL_QTY_1/48 WHEN CRP2.MATERIAL_NAME_1='PLASTIC' THEN CRP2.MATERIAL_QTY_1/35 ELSE 0 END,0) AS "team_return_impact_item_qty"

{% endif %}
