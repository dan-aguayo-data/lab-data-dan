FROM 
{{ source('CES_DRUPAL', 'CONTACTS') }} AS CG
INNER JOIN {{ source('CES_DRUPAL', 'CONTACT_ROLES') }} AS CRG
ON CG.CONTACT_ID = CRG.CONTACT_ID AND CRG._FIVETRAN_DELETED = FALSE
INNER JOIN {{ source('CES_DRUPAL', 'PARTICIPANT_SITES') }} AS PSG
ON CRG.PARTICIPANT_SITE_ID = PSG.PARTICIPANT_SITE_ID AND PSG._FIVETRAN_DELETED = FALSE
INNER JOIN {{ source('CES_DRUPAL', 'PARTICIPANTS') }} AS PG
ON PG.PARTICIPANT_ID = PSG.PARTICIPANT_ID AND PG._FIVETRAN_DELETED = FALSE
INNER JOIN (
    SELECT
    PS.MULTI_SCHEME_ID,
    P.CONSUMER_NUMBER AS CONSUMER_ID_INDIVIDUAL,
    CR.CONTACT_ID,
    CR.EFFECTIVE_START_DATE,
    CR.EFFECTIVE_END_DATE,
    CR.ACTIVE

    --********* UAT *********--
    {% if target.name.upper() != 'PROD' %}
    ,CR.ROLE_TYPE_CODE
    {% endif %}
    --********* UAT *********--

    FROM {{ source('CES_DRUPAL', 'CONTACT_ROLES') }} AS CR
    LEFT JOIN {{ source('CES_DRUPAL', 'PARTICIPANT_SITES') }} AS PS
    ON CR.PARTICIPANT_SITE_ID = PS.PARTICIPANT_SITE_ID AND PS._FIVETRAN_DELETED = FALSE
    LEFT JOIN {{ source('CES_DRUPAL', 'PARTICIPANTS') }} AS P
    ON P.PARTICIPANT_ID = PS.PARTICIPANT_ID AND P._FIVETRAN_DELETED = FALSE
    WHERE CR.ROLE_TYPE_CODE = 'AUTHORISED_CONTACT_B2C' AND CR._FIVETRAN_DELETED = FALSE --Authorised Contact B2C
    AND P.PARTICIPANT_GROUP = 'IND_CONSUMER' --Individual Consumer
    AND PS.TAXONOMY_TYPE_ID = 'Consumer' 
    QUALIFY ROW_NUMBER() OVER (PARTITION BY PS.MULTI_SCHEME_ID, CR.CONTACT_ID ORDER BY PS.LAST_MODIFIED_ON DESC) = 1 --TO REMOVE THE DUPS SCXT-3407
) I
ON CRG.CONTACT_ID = I.CONTACT_ID
AND PSG.MULTI_SCHEME_ID = I.MULTI_SCHEME_ID

--********* UAT *********--
{% if target.name.upper() != 'PROD' %}

LEFT JOIN (
    SELECT 
    C.*
    , FIRST_VALUE(C.NOMINATED_CHARITY) OVER (PARTITION BY C.CONSUMER_ID ORDER BY CASE WHEN C.NOMINATED_CHARITY IS NULL THEN 0 ELSE C.REFUND_AMOUNT_CHARITY_LAST_12_MONTHS END DESC) AS TOP_CHARITY_LAST_12_MONTH
    , FIRST_VALUE(C.CRP_SITE_NAME) OVER (PARTITION BY C.CONSUMER_ID ORDER BY C.MOST_RP_VISITED_LAST_12_MONTHS DESC) AS MOST_VISITED_RP
    FROM (
        SELECT 
        H.CONSUMER_ID
        , PTT.PARTICIPANT_NAME AS NOMINATED_CHARITY
        , 'TRUE' AS FLAG
        , H.PAYMENT_METHOD AS LAST_USED_PAYMENT_METHOD
        , COUNT(DISTINCT (CASE WHEN H.TRANSACTION_DATE_UTC BETWEEN DATEADD('MONTH',-3,SYSDATE()) AND  SYSDATE() THEN H.TRANSACTION_ID ELSE NULL END)) OVER (PARTITION BY H.CONSUMER_ID) AS TRANSACTIONS_LAST_3_MONTHS
        , COUNT(DISTINCT (CASE WHEN H.TRANSACTION_DATE_UTC BETWEEN DATEADD('MONTH',-12,SYSDATE()) AND  SYSDATE() THEN H.TRANSACTION_ID ELSE NULL END)) OVER (PARTITION BY H.CONSUMER_ID) AS TRANSACTIONS_LAST_12_MONTHS
        , H.SITE_NAME AS CRP_SITE_NAME 
        , H.TRANSACTION_DATE_UTC
         --CONTAINERS
        , SUM(D.COLLECTION_QTY) OVER (PARTITION BY H.CONSUMER_ID) AS COLLECTION_QTY_LIFETIME
        , SUM(D.GROSS_AMOUNT) OVER (PARTITION BY H.CONSUMER_ID) AS REFUND_AMOUNT_LIFETIME
        , SUM(CASE WHEN H.TRANSACTION_DATE_UTC BETWEEN DATEADD('MONTH',-1,SYSDATE()) AND  SYSDATE() THEN D.GROSS_AMOUNT ELSE 0 END) OVER (PARTITION BY H.CONSUMER_ID) AS REFUND_AMOUNT_LAST_1_MONTHS
        , SUM(CASE WHEN H.TRANSACTION_DATE_UTC BETWEEN DATEADD('MONTH',-12,SYSDATE()) AND  SYSDATE() THEN D.GROSS_AMOUNT ELSE 0 END) OVER (PARTITION BY H.CONSUMER_ID) AS REFUND_AMOUNT_LAST_12_MONTHS
        , SUM(CASE WHEN H.TRANSACTION_DATE_UTC BETWEEN DATEADD('MONTH',-1,SYSDATE()) AND  SYSDATE() THEN D.COLLECTION_QTY ELSE 0 END) OVER (PARTITION BY H.CONSUMER_ID) AS COLLECTION_QTY_LAST_1_MONTHS
        , SUM(CASE WHEN H.TRANSACTION_DATE_UTC BETWEEN DATEADD('MONTH',-12,SYSDATE()) AND  SYSDATE() THEN D.COLLECTION_QTY ELSE 0 END) OVER (PARTITION BY H.CONSUMER_ID) AS COLLECTION_QTY_LAST_12_MONTHS
         --CONTAINERS_DONATED
        , SUM(CASE WHEN PTT.PARTICIPANT_NAME IS NOT NULL THEN D.GROSS_AMOUNT ELSE 0 END) OVER (PARTITION BY H.CONSUMER_ID) AS REFUND_AMOUNT_DONATED_LIFETIME
        , SUM(CASE WHEN PTT.PARTICIPANT_NAME IS NOT NULL THEN D.COLLECTION_QTY ELSE 0 END) OVER (PARTITION BY H.CONSUMER_ID) AS CONTAINERS_DONATED_LIFETIME
        , SUM(CASE WHEN PTT.PARTICIPANT_NAME IS NOT NULL AND H.TRANSACTION_DATE_UTC BETWEEN DATEADD('MONTH',-1,SYSDATE())AND SYSDATE() THEN D.COLLECTION_QTY ELSE 0 END)  OVER (PARTITION BY H.CONSUMER_ID) AS CONTAINERS_DONATED_LAST_1_MONTHS
        , SUM(CASE WHEN PTT.PARTICIPANT_NAME IS NOT NULL AND H.TRANSACTION_DATE_UTC BETWEEN DATEADD('MONTH',-12,SYSDATE())AND SYSDATE() THEN D.COLLECTION_QTY ELSE 0 END)  OVER (PARTITION BY H.CONSUMER_ID) AS CONTAINERS_DONATED_LAST_12_MONTHS 
        , SUM(CASE WHEN PTT.PARTICIPANT_NAME IS NOT NULL AND H.TRANSACTION_DATE_UTC BETWEEN DATEADD('MONTH',-1,SYSDATE()) AND SYSDATE() THEN D.GROSS_AMOUNT  ELSE 0 END)  OVER (PARTITION BY H.CONSUMER_ID) AS REFUND_AMOUNT_DONATED_LAST_1_MONTHS
        , SUM(CASE WHEN PTT.PARTICIPANT_NAME IS NOT NULL AND H.TRANSACTION_DATE_UTC BETWEEN DATEADD('MONTH',-12,SYSDATE()) AND SYSDATE() THEN D.GROSS_AMOUNT  ELSE 0 END)  OVER (PARTITION BY H.CONSUMER_ID) AS REFUND_AMOUNT_DONATED_LAST_12_MONTHS
        , COUNT(DISTINCT (CASE WHEN H.TRANSACTION_DATE_UTC BETWEEN DATEADD('MONTH',-12,SYSDATE()) AND SYSDATE() THEN H.SITE_NUMBER ELSE NULL END)) OVER (PARTITION BY H.CONSUMER_ID) AS RP_VISITED_LAST_12_MONTHS
        , COUNT((CASE WHEN H.TRANSACTION_DATE_UTC BETWEEN DATEADD('MONTH',-12,SYSDATE()) AND  SYSDATE() THEN H.TRANSACTION_ID ELSE NULL END)) OVER (PARTITION BY H.CONSUMER_ID, H.SITE_NUMBER) AS MOST_RP_VISITED_LAST_12_MONTHS
        , SUM(CASE WHEN PTT.PARTICIPANT_NAME IS NOT NULL AND H.TRANSACTION_DATE_UTC BETWEEN DATEADD('MONTH',-12,SYSDATE()) AND SYSDATE() THEN D.GROSS_AMOUNT ELSE 0 END)  OVER (PARTITION BY H.CONSUMER_ID,PTT.PARTICIPANT_NAME ) AS REFUND_AMOUNT_CHARITY_LAST_12_MONTHS
        FROM {{ ref('CRP_COLLECTION_HDR') }} AS H
        INNER JOIN {{ ref('CRP_COLLECTION_DTL') }} AS D
        ON D.TRANSACTION_ID = H.TRANSACTION_ID
        INNER JOIN {{ source('CES_DRUPAL', 'PARTICIPANT_SITES') }} AS PSC
        ON PSC.SITE_NUMBER = H.CONSUMER_ID AND PSC.TAXONOMY_TYPE_ID <> 'Consumer' AND PSC._FIVETRAN_DELETED = FALSE
        INNER JOIN {{ source('CES_DRUPAL', 'PARTICIPANTS') }} AS P 
        ON P.PARTICIPANT_ID = PSC.PARTICIPANT_ID --AND P.PARTICIPANT_GROUP = 'IND_CONSUMER' AND P._FIVETRAN_DELETED = FALSE
        --DELEGATED_SITES
        LEFT JOIN {{ source('CES_DRUPAL', 'PARTICIPANT_SITES') }} AS PT
        ON PT.SITE_NUMBER = H.RECIPIENT_CONSUMER_ID AND H.RECIPIENT_CONSUMER_ID <> H.CONSUMER_ID AND PT._FIVETRAN_DELETED = FALSE
        LEFT JOIN {{ source('CES_DRUPAL', 'PARTICIPANTS') }} AS PTT
        ON PTT.PARTICIPANT_ID = PT.PARTICIPANT_ID AND PTT._FIVETRAN_DELETED = FALSE
        WHERE H.MULTI_SCHEME_ID = 10000 AND D.MATERIAL_TYPE_ID <> 'INELIGIBLE' 
        QUALIFY ROW_NUMBER() OVER (PARTITION BY H.CONSUMER_ID ORDER BY H.TRANSACTION_DATE DESC) = 1 --IF 2 ACTIVE GOALS EXIST
    ) C
) CRP
ON CRP.CONSUMER_ID = PSG.SITE_NUMBER
LEFT JOIN (
    SELECT 
    PPP.SCHEME_PARTICIPANT_ID
    , PPP.PAYMENT_METHOD
    FROM {{ source('CES_MSCM', 'PYMT_PAY_PARTY_PROFILES') }} AS PPP
    WHERE PPP.DEFAULT_FLAG = 'Y' AND PPP.MULTI_SCHEME_ID = 10000
    AND SYSDATE() BETWEEN PPP.START_DATE_ACTIVE AND NVL(PPP.END_DATE_ACTIVE,'9999-12-01')
    QUALIFY ROW_NUMBER() OVER (PARTITION BY PPP.SCHEME_PARTICIPANT_ID ORDER BY PPP.LAST_MODIFIED_ON DESC) = 1
) PPP
ON PPP.SCHEME_PARTICIPANT_ID = PG.CONSUMER_NUMBER
--SUBREGION MAPPING
LEFT JOIN {{ ref('REF_STATE') }} AS STATE
ON STATE.STATE = PSG.STATE 
LEFT JOIN {{ ref('REF_LOCALITY_SSC') }} AS SSC
ON PSG.CITY_SUBURB = SSC.SUBURB
AND PSG.POST_CODE = SSC.POSTCODE
AND STATE.STATE_NAME = SSC.STATE
LEFT JOIN {{ ref('REF_LOCALITY_POA') }} AS POA
ON PSG.POST_CODE = POA.POSTCODE
LEFT JOIN {{ ref('CONSUMER_PUBLIC_INFO') }} AS PW
ON PW.CONSUMER_ID = PG.CONSUMER_NUMBER AND PW.PUBLIC_WEBSITE_CONSENT = 'Y'
LEFT JOIN (
  SELECT DISTINCT
  A.POST_CODE,
  A.DAY_OF_SERVICE,
  IFNULL(A.SUBURB_NAME,A.ABS_SUBURB) AS SUBURB_NAME
  FROM {{ source('COEX_AGILOFT', 'AG_SUBURB') }} AS A
  WHERE STATUS = '05 LIVE') BS
ON BS.POST_CODE =  PSG.POST_CODE
AND BS.SUBURB_NAME =  PSG.CITY_SUBURB
LEFT JOIN (
    SELECT 
    CCB.BOOKING_CONSUMER_ID,
    MAX(CCB.BOOKING_PICK_UP_DATE) AS LAST_CONTAINER_COLLECT_BOOKING_DATE
    FROM {{ ref('EXT_CONTAINER_COLLECT_BOOKINGS_COEX') }} AS CCB
    --WHERE SYSDATE() <= CCB.DATE
    GROUP BY CCB.BOOKING_CONSUMER_ID
) CCB
ON CCB.BOOKING_CONSUMER_ID = PSG.SITE_NUMBER
LEFT JOIN (
    SELECT 
    G.GOAL_START_DATE,
    G.GOAL_END_DATE,
    G.PARTICIPANT_SITE_ID,
    G.GOAL_NAME,
    G.GOAL_AMOUNT,
    G.CREATED_ON AS GOAL_CREATED_ON,
    NVL(SUM(D.COLLECTION_QTY) OVER (PARTITION BY PS.SITE_NUMBER,G.GOAL_D_ID),0) AS COLLECTION_QTY,
    SUM(CASE WHEN D.MATERIAL_TYPE_ID IN ('PETCOLORED','PETCLEAR','HDPE') THEN D.COLLECTION_QTY ELSE 0 END) OVER (PARTITION BY PS.SITE_NUMBER,G.GOAL_D_ID) AS COLLECTION_QTY_PLASTIC,
    SUM(CASE WHEN D.MATERIAL_TYPE_ID ='GLASSMIXED' THEN D.COLLECTION_QTY ELSE 0 END) OVER (PARTITION BY PS.SITE_NUMBER,G.GOAL_D_ID) AS COLLECTION_QTY_GLASS,
    SUM(CASE WHEN D.MATERIAL_TYPE_ID ='ALUMINIUM' THEN D.COLLECTION_QTY ELSE 0 END) OVER (PARTITION BY PS.SITE_NUMBER,G.GOAL_D_ID) AS COLLECTION_QTY_ALUMINIUM,
    SUM(CASE WHEN D.MATERIAL_TYPE_ID IN ('PETCOLORED','PETCLEAR','HDPE') THEN D.COLLECTION_QTY/35 ELSE 0 END) OVER (PARTITION BY PS.SITE_NUMBER,G.GOAL_D_ID) AS COLLECTION_QTY_JUMPERS,
    SUM(CASE WHEN D.MATERIAL_TYPE_ID ='GLASSMIXED' THEN D.COLLECTION_QTY/48 ELSE 0 END) OVER (PARTITION BY PS.SITE_NUMBER,G.GOAL_D_ID) AS COLLECTION_QTY_WINDSHIELDS,
    SUM(CASE WHEN D.MATERIAL_TYPE_ID ='ALUMINIUM' THEN D.COLLECTION_QTY/67 ELSE 0 END) OVER (PARTITION BY PS.SITE_NUMBER,G.GOAL_D_ID) AS COLLECTION_QTY_BIKES
    FROM {{ source('CES_DRUPAL', 'CFC_GOAL') }} AS G
    INNER JOIN {{ source('CES_DRUPAL', 'PARTICIPANT_SITES') }} AS PS
    ON G.PARTICIPANT_SITE_ID = PS.PARTICIPANT_SITE_ID AND PS._FIVETRAN_DELETED = FALSE
    INNER JOIN {{ source('CES_DRUPAL', 'PARTICIPANTS') }} AS P 
    ON P.PARTICIPANT_ID = PS.PARTICIPANT_ID AND P._FIVETRAN_DELETED = FALSE
    LEFT JOIN {{ ref('CRP_COLLECTION_HDR') }} AS H
    ON PS.SITE_NUMBER = H.CONSUMER_ID 
    AND H.TRANSACTION_DATE BETWEEN G.GOAL_START_DATE AND G.GOAL_END_DATE
    LEFT JOIN {{ ref('CRP_COLLECTION_DTL') }} AS D
    ON D.TRANSACTION_ID = H.TRANSACTION_ID AND D.MATERIAL_TYPE_ID <> 'INELIGIBLE'
    WHERE G.GOAL_MEMBER_TYPE = 1 AND G._FIVETRAN_DELETED = 'FALSE'
    AND PS.MULTI_SCHEME_ID = 10000 --COEX
    AND PS.TAXONOMY_TYPE_ID <> 'Consumer'
    AND TRUNC(G.GOAL_START_DATE, 'DAY') <> TRUNC(G.GOAL_END_DATE, 'DAY')
    QUALIFY ROW_NUMBER() OVER (PARTITION BY G.PARTICIPANT_SITE_ID ORDER BY G.GOAL_D_ID DESC) = 1 --IF 2 ACTIVE GOALS EXIST
) G --GOAL STAT
ON G.PARTICIPANT_SITE_ID = PSG.PARTICIPANT_SITE_ID
LEFT JOIN (
    SELECT 
    CRP.CONSUMER_ID
    , CRP.LAST_TRANSACTION_DATE 
    , FIRST_VALUE(CASE WHEN CRP.MATERIAL_RANK = 1 THEN CRP.MATERIAL_TYPE_ID_CATEGORISED ELSE NULL END) OVER (PARTITION BY CRP.CONSUMER_ID ORDER BY CRP.MATERIAL_RANK = 1 DESC) AS MATERIAL_NAME_1
    , FIRST_VALUE(CASE WHEN CRP.MATERIAL_RANK = 1 THEN CRP.COLLECTION_QTY_BY_MATERIAL ELSE NULL END) OVER (PARTITION BY CRP.CONSUMER_ID ORDER BY CRP.MATERIAL_RANK = 1 DESC) AS MATERIAL_QTY_1
     FROM   
        (SELECT 
        C.*
        , CASE WHEN C.MATERIAL_RANK_RN = 1 THEN RANK() OVER (PARTITION BY C.CONSUMER_ID,C.MATERIAL_RANK_RN = 1 ORDER BY C.COLLECTION_QTY_BY_MATERIAL DESC) ELSE 0 END AS MATERIAL_RANK
        FROM
            (SELECT 
             --JOINING FIELDS
            H.CONSUMER_ID
            , D.MATERIAL_TYPE_ID
            , MAX(H.TRANSACTION_DATE_UTC) OVER (PARTITION BY H.CONSUMER_ID) AS LAST_TRANSACTION_DATE -- C09
            , CASE WHEN D.MATERIAL_TYPE_ID = 'LQDPAPERBRD' THEN 'LIQUID PAPERBOARD' WHEN D.MATERIAL_TYPE_ID = 'ALUMINIUM' THEN D.MATERIAL_TYPE_ID WHEN D.MATERIAL_TYPE_ID = 'GLASSMIXED' THEN 'GLASS' WHEN D.MATERIAL_TYPE_ID IN ('PETCOLORED','PETCLEAR','HDPE') THEN 'PLASTIC' ELSE NULL END AS MATERIAL_TYPE_ID_CATEGORISED
             --MATERIAL_RANK
            , SUM(D.COLLECTION_QTY) OVER (PARTITION BY H.CONSUMER_ID, (CASE WHEN D.MATERIAL_TYPE_ID IN ('PETCOLORED','PETCLEAR','HDPE') THEN 'PET' ELSE D.MATERIAL_TYPE_ID END)) AS COLLECTION_QTY_BY_MATERIAL
            , ROW_NUMBER() OVER (PARTITION BY H.CONSUMER_ID,(CASE WHEN D.MATERIAL_TYPE_ID IN ('PETCOLORED','PETCLEAR','HDPE') THEN 'PET' ELSE D.MATERIAL_TYPE_ID END) ORDER BY TRUNCATE(H.TRANSACTION_DATE_UTC,'DAY')) AS MATERIAL_RANK_RN --1
            FROM {{ ref('CRP_COLLECTION_HDR') }} AS H
            INNER JOIN {{ ref('CRP_COLLECTION_DTL') }} AS D
            ON D.TRANSACTION_ID = H.TRANSACTION_ID
            INNER JOIN {{ source('CES_DRUPAL', 'PARTICIPANT_SITES') }} AS PSC
            ON PSC.SITE_NUMBER = H.CONSUMER_ID AND PSC.TAXONOMY_TYPE_ID <> 'Consumer' AND PSC._FIVETRAN_DELETED = FALSE
            INNER JOIN {{ source('CES_DRUPAL', 'PARTICIPANTS') }} AS P 
            ON P.PARTICIPANT_ID = PSC.PARTICIPANT_ID --AND P.PARTICIPANT_GROUP = 'IND_CONSUMER' AND P._FIVETRAN_DELETED = FALSE
            WHERE H.MULTI_SCHEME_ID = 10000 AND D.MATERIAL_TYPE_ID <> 'INELIGIBLE' 
            AND H.TRANSACTION_DATE_UTC BETWEEN DATEADD('MONTH',-12,SYSDATE()) AND SYSDATE()
        ) C 
      ) CRP
      QUALIFY ROW_NUMBER() OVER (PARTITION BY CRP.CONSUMER_ID ORDER BY CRP.CONSUMER_ID DESC) = 1         
    ) CRP2 --LAST 12 MONTHS
ON CRP2.CONSUMER_ID = PSG.SITE_NUMBER
WHERE PSG.TAXONOMY_TYPE_ID <> 'Consumer'
