SELECT
P.CONSUMER_NUMBER || '-' ||  I.CONSUMER_ID_INDIVIDUAL || '-' || TO_CHAR(G.GOAL_START_DATE,'YYYY-MM-DD') || '-' || G.GOAL_MEMBER_TYPE AS "id"
, UUID.MARKETING_UUID AS "external_id"
, G.GOAL_D_ID AS "team_goal_d_id"
, G.GOAL_NAME AS "team_goal_name"
, G.GOAL_AMOUNT AS "team_goal_target_amount"
, G.GOAL_AMOUNT * 10 AS "team_goal_target_qty"
, CAST(G.GOAL_START_DATE AS TIMESTAMP) AS "team_goal_start_date"
, CAST(G.GOAL_END_DATE AS TIMESTAMP) AS "team_goal_end_date"
, P.CONSUMER_NUMBER AS "team_member_number"
, I.CONSUMER_ID_INDIVIDUAL AS "consumer_id"
FROM 
{{ source('CES_DRUPAL', 'CONTACTS') }} AS CG
INNER JOIN {{ source('CES_DRUPAL', 'CONTACT_ROLES') }} AS CRG
ON CG.CONTACT_ID = CRG.CONTACT_ID AND CRG._FIVETRAN_DELETED = FALSE
INNER JOIN {{ source('CES_DRUPAL', 'PARTICIPANT_SITES') }} AS PS
ON CRG.PARTICIPANT_SITE_ID = PS.PARTICIPANT_SITE_ID AND PS._FIVETRAN_DELETED = FALSE
INNER JOIN {{ source('CES_DRUPAL', 'PARTICIPANTS') }} AS P
ON P.PARTICIPANT_ID = PS.PARTICIPANT_ID AND P._FIVETRAN_DELETED = FALSE
INNER JOIN (
    SELECT
    PS.MULTI_SCHEME_ID,
    P.CONSUMER_NUMBER AS CONSUMER_ID_INDIVIDUAL,
    CR.CONTACT_ID,
    CR.EFFECTIVE_START_DATE,
    CR.EFFECTIVE_END_DATE,
    CR.ACTIVE
    FROM {{ source('CES_DRUPAL', 'CONTACT_ROLES') }} AS CR
    INNER JOIN {{ source('CES_DRUPAL', 'PARTICIPANT_SITES') }} AS PS
    ON CR.PARTICIPANT_SITE_ID = PS.PARTICIPANT_SITE_ID AND PS._FIVETRAN_DELETED = FALSE
    INNER JOIN {{ source('CES_DRUPAL', 'PARTICIPANTS') }} AS P
    ON P.PARTICIPANT_ID = PS.PARTICIPANT_ID AND P._FIVETRAN_DELETED = FALSE
    WHERE CR.ROLE_TYPE_CODE = 'AUTHORISED_CONTACT_B2C'  AND CR._FIVETRAN_DELETED = FALSE--Authorised Contact B2C
    AND P.PARTICIPANT_GROUP = 'IND_CONSUMER' --Individual Consumer
    AND PS.TAXONOMY_TYPE_ID = 'Consumer' 
    QUALIFY ROW_NUMBER() OVER (PARTITION BY PS.MULTI_SCHEME_ID, CR.CONTACT_ID ORDER BY PS.LAST_MODIFIED_ON DESC) = 1 --TO REMOVE THE DUPS SCXT-3407
) I
ON CRG.CONTACT_ID = I.CONTACT_ID
AND PS.MULTI_SCHEME_ID = I.MULTI_SCHEME_ID
INNER JOIN {{ source('CES_DRUPAL', 'CFC_GOAL') }} AS G
ON G.PARTICIPANT_SITE_ID = PS.PARTICIPANT_SITE_ID
INNER JOIN {{ source('CES_DRUPAL', 'CFC_UUID') }} AS UUID
ON UUID.CONSUMER_NUMBER  = I.CONSUMER_ID_INDIVIDUAL AND UUID.MULTI_SCHEME_ID = 10000 AND UUID._FIVETRAN_DELETED = FALSE
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME --ONLY REQUIRED FOR REPORTING PURPOSES
ON PS.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
WHERE G.GOAL_AMOUNT <> 0 AND G.GOAL_MEMBER_TYPE = 1 AND G._FIVETRAN_DELETED = 'FALSE'--TEAM
AND PS.MULTI_SCHEME_ID = 10000 --COEX
AND PS.TAXONOMY_TYPE_ID <> 'Consumer'
AND CRG.ROLE_TYPE_CODE <> 'AUTHORISED_CONTACT_B2C'
AND CG.ACTIVE = 1  AND CG._FIVETRAN_DELETED = FALSE
AND CRG.ACTIVE = 1
AND TRUNC(G.GOAL_START_DATE, 'DAY') <> TRUNC(G.GOAL_END_DATE, 'DAY')
AND UUID.MARKETING_UUID IS NOT NULL
QUALIFY ROW_NUMBER() OVER (PARTITION BY  P.CONSUMER_NUMBER || I.CONSUMER_ID_INDIVIDUAL || TRUNC("team_goal_start_date",'DAY') || G.GOAL_MEMBER_TYPE ORDER BY G.GOAL_D_ID DESC) = 1
