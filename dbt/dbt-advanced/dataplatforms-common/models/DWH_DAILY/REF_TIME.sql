SELECT
H.N || ':' || M.N || ':' || S.N AS "TIME"
, H.N || M.N || S.N AS KEY
, H.N AS HOUR
, M.N AS MINUTE
, S.N AS SECOND
, CASE WHEN H.N <= 11 THEN 'AM' ELSE 'PM' END AS AM_PM
FROM (
    SELECT TO_CHAR(SEQ4(), 'FM00') AS N
    FROM TABLE(GENERATOR(ROWCOUNT => 24))
) H
CROSS JOIN (
    SELECT TO_CHAR(SEQ4(), 'FM00') AS N
    FROM TABLE(GENERATOR(ROWCOUNT => 60))
) M
CROSS JOIN (
    SELECT TO_CHAR(SEQ4(), 'FM00') AS N
    FROM TABLE(GENERATOR(ROWCOUNT => 60))
) S