SELECT
VD.MULTI_SCHEME_ID  AS MULTI_SCHEME_ID 
, SCHEME.NAME AS SCHEME
, VD.ID AS ID
, VD.PROCESSED_VOLUME_HDR_ID AS VOLUME_HDR_ID
, VH.PROCESSOR_ID AS SITE_NUMBER 
, PS.SITE_NAME  AS SITE_NAME 
, VD.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID 
, MT.NAME AS MATERIAL_TYPE
, VD.VOLUME AS VOLUME
, VD.BLOCKS AS BLOCKS
, VD.UOM AS UOM
, CASE VD.UOM WHEN 'KILOGRAM' THEN VD.VOLUME WHEN 'UNIT' THEN VD.VOLUME/NVL(U_KG_QTY_A.CONVERSION_FACTOR,U_KG_QTY_B.CONVERSION_FACTOR) END AS VOLUME_KG_DERIVED
, CASE VD.UOM WHEN 'UNIT' THEN VD.VOLUME WHEN 'KILOGRAM' THEN VD.VOLUME*NVL(U_KG_QTY_A.CONVERSION_FACTOR,U_KG_QTY_B.CONVERSION_FACTOR) END AS VOLUME_QTY_DERIVED
, VH.STATUS AS STATUS
, VH.ENTRY_TYPE AS ENTRY_TYPE
, VH.PERIOD AS PERIOD
, REPLACE(VH.PERIOD,'-','') AS PERIOD_KEY
, VH.PERIOD_TYPE AS PERIOD_TYPE
, VH.SUBMITTED_BY AS SUBMITTED_BY
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(VH.SUBMITTED_DATE AS TIMESTAMP)) AS SUBMITTED_DATE
, VH.SUBMITTED_DATE AS SUBMITTED_DATE_UTC
, VD.CREATED_BY AS CREATED_BY
, VD.CREATED_ON AS CREATED_ON_UTC
, VD.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, VD.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM', 'PROCESSED_VOLUME_DTL') }} AS VD
INNER JOIN {{ source('CES_MSCM', 'PROCESSED_VOLUME_HDR') }} AS VH
ON VD.PROCESSED_VOLUME_HDR_ID = VH.ID
INNER JOIN {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS MT
ON VD.MATERIAL_TYPE_ID = MT.ID
LEFT JOIN {{ source('CES_MSCM', 'UOM_REFERENCE') }} AS U_KG_QTY_A
ON VD.MATERIAL_TYPE_ID = U_KG_QTY_A.MATERIAL_TYPE_ID
AND U_KG_QTY_A.FROM_UNIT = 'KILOGRAM'
AND U_KG_QTY_A.TO_UNIT = 'UNIT'
AND SYSDATE() BETWEEN NVL(U_KG_QTY_A.EFFECTIVE_FROM,TO_DATE('01/JAN/1900','DD/MON/YYYY')) AND NVL(U_KG_QTY_A.EFFECTIVE_TO,TO_DATE('01/JAN/9999','DD/MON/YYYY'))
AND VH.PROCESSOR_ID = U_KG_QTY_A.SCHEME_PARTICIPANT_ID
AND VH.MULTI_SCHEME_ID = U_KG_QTY_A.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'UOM_REFERENCE') }} AS U_KG_QTY_B
ON VD.MATERIAL_TYPE_ID = U_KG_QTY_B.MATERIAL_TYPE_ID
AND U_KG_QTY_B.FROM_UNIT = 'KILOGRAM'
AND U_KG_QTY_B.TO_UNIT = 'UNIT'
AND SYSDATE() BETWEEN NVL(U_KG_QTY_B.EFFECTIVE_FROM,TO_DATE('01/JAN/1900','DD/MON/YYYY')) AND NVL(U_KG_QTY_B.EFFECTIVE_TO,TO_DATE('01/JAN/9999','DD/MON/YYYY'))
AND U_KG_QTY_B.SCHEME_PARTICIPANT_ID IS NULL
AND VH.MULTI_SCHEME_ID = U_KG_QTY_B.MULTI_SCHEME_ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON VD.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS
ON PS.SITE_NUMBER=VH.PROCESSOR_ID