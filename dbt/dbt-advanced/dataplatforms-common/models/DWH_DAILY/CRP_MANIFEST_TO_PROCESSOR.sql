SELECT
COALESCE(C.MULTI_SCHEME_ID,P.MULTI_SCHEME_ID) AS MULTI_SCHEME_ID
, C.CRP_SITE_NUMBER AS CRP_SITE_NUMBER
, C.LSP_SITE_NUMBER AS LSP_SITE_NUMBER
, P.SITE_NUMBER AS PROCESSOR_SITE_NUMBER
, P.STATUS AS PROCESSOR_RECEIPT_STATUS
, COALESCE(C.PERIOD_KEY,P.PERIOD_KEY) AS PERIOD_KEY
, COALESCE(C.MATERIAL_TYPE_ID,P.MATERIAL_TYPE_ID) AS MATERIAL_TYPE_ID
, SUM(C.CONVERTED_WEIGHT - C.EMPTY_WEIGHT)/1000  AS SHIPPING_MANIFEST_WEIGHT_TONNES
, SUM(P.RECEIVED_KG_DERIVED)/1000 AS RECEIVED_TONNES
FROM
{{ ref('CRP_SHIPPING_MANIFEST') }} AS C
LEFT JOIN {{ ref('PROCESSOR_RECEIPT') }} AS P 
ON C.MANIFEST_NUMBER = P.MANIFEST_NUMBER
AND C.ASSET_ID = P.ASSET_ID
AND C.MATERIAL_TYPE_ID = P.MATERIAL_TYPE_ID
--WHERE P.STATUS = 'RECEIVED'
GROUP BY 
COALESCE(C.MULTI_SCHEME_ID,P.MULTI_SCHEME_ID),
C.CRP_SITE_NUMBER,
C.LSP_SITE_NUMBER,
P.SITE_NUMBER,
COALESCE(C.PERIOD_KEY,P.PERIOD_KEY),
COALESCE(C.MATERIAL_TYPE_ID,P.MATERIAL_TYPE_ID),
P.STATUS