SELECT
10001 AS MULTI_SCHEME_ID
, 'WA' AS SCHEME
, 'WA-' || MRF.DATEKEY || '-' || MRF.MATERIAL_TYPE_ID || '-' || MRF.ACTUAL_FORECAST AS ID
, MRF.DATEKEY AS DATE_KEY
, MRF.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID
, MRF.VOLUME AS COLLECTION_QTY
, MRF.ACTUAL_FORECAST AS TYPE
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('WARRRL_OPERATIONS', 'MRF_MATERIAL_TYPE_BREAKDOWN') }} AS MRF
 
UNION ALL
 
SELECT
10000 AS MULTI_SCHEME_ID
, 'QLD' AS SCHEME
, 'QLD-' || REPLACE(MRF.MONTH, '-') || '-' || MRF.MATERIAL_TYPE_ID || '-' || MRF.TYPE AS ID
, REPLACE(MRF.MONTH, '-') AS DATE_KEY
, MRF.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID
, SUM(MRF.VOLUME) AS COLLECTION_QTY
, CASE WHEN MRF.TYPE = 'ACTUAL' THEN 'A' WHEN MRF.TYPE = 'PLANNED' THEN 'F' END AS TYPE
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('COEX_ACTUALS', 'MRF_VOLUMES_REGION') }} AS MRF
UNPIVOT(VOLUME FOR MATERIAL_TYPE_ID IN (ALUMINIUM, GLASSMIXED, PETCLEAR, PETCOLORED, HDPE, LQDPAPERBRD, STEEL, OTHER))
WHERE MRF.MONTH IS NOT NULL
GROUP BY
MONTH
, TYPE
, MATERIAL_TYPE_ID