SELECT
O.SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, V.VEHICLE_ID AS ID
, O.SCHEME_PARTICIPANT_ID AS SITE_NUMBER
, O.SUPPLIER_NUMBER AS SUPPLIER_NUMBER
, V.REGISTRATION_NUMBER AS REGISTRATION_NUMBER
, R_SR.VALUE AS STATE_OF_REGISTRATION
, R_S.VALUE AS STATUS
, V.YEAR_OF_MANUFACTURE AS YEAR_OF_MANUFACTURE
, V.NO_OF_TRAILERS AS NO_OF_TRAILERS
, V.VEHICLE_TYPE_ID AS VEHICLE_TYPE_ID
, VT.VEHICLE_TYPE_NAME AS VEHICLE_TYPE
, VT.MAKE AS MAKE
, VT.MODEL_NAME AS MODEL_NAME
, VT.GVM AS GVM
, VT.PAYLOAD AS PAYLOAD
, VT.NO_OF_AXLES AS NO_OF_AXLES
, VT.CONFIGURATION AS CONFIGURATION
, CAST(V.START_DATE_ACTIVE AS DATE) AS EFFECTIVE_FROM
, CAST(V.END_DATE_ACTIVE AS DATE) AS EFFECTIVE_TO
, CASE WHEN CAST(CONVERT_TIMEZONE('UTC', 'Australia/Perth', SYSTIMESTAMP()) AS DATE)  BETWEEN NVL(V.START_DATE_ACTIVE,TO_DATE('01/JAN/1900','DD/MON/YYYY')) AND NVL(V.END_DATE_ACTIVE,TO_DATE('01/JAN/9999','DD/MON/YYYY')) THEN 1 ELSE 0 END AS ACTIVE_FLAG
, V.CREATED_BY AS CREATED_BY
, V.CREATED_ON AS CREATED_ON_UTC
, V.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, V.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM', 'FMT_VEHICLES') }} AS V
INNER JOIN {{ source('CES_MSCM', 'FMT_ORGANISATIONS') }} AS O
ON V.ORGANISATION_ID = O.ORGANISATION_ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON O.SCHEME_ID = SCHEME.MULTI_SCHEME_ID
INNER JOIN {{ source('CES_MSCM', 'FMT_VEHICLE_TYPES') }} AS VT
ON V.VEHICLE_TYPE_ID = VT.VEHICLE_TYPE_ID
LEFT JOIN {{ source('CES_MSCM', 'FMT_SCHEME_REF_CODES') }} AS R_SR
ON V.STATE_OF_REGISTRATION_ID = R_SR.ID
LEFT JOIN {{ source('CES_MSCM', 'FMT_SCHEME_REF_CODES') }} AS R_S
ON V.VEHICLE_STATUS_ID = R_S.ID
UNION ALL
SELECT
-1 AS MULTI_SCHEME_ID
, 'CES' AS SCHEME
, -1 AS ID
, NULL AS SITE_NUMBER
, NULL AS SUPPLIER_NUMBER
, NULL AS REGISTRATION_NUMBER
, NULL AS STATE_OF_REGISTRATION
, NULL AS STATUS
, NULL AS YEAR_OF_MANUFACTURE
, NULL AS NO_OF_TRAILERS
, NULL AS VEHICLE_TYPE_ID
, NULL AS VEHICLE_TYPE
, NULL AS MAKE
, NULL AS MODEL_NAME
, NULL AS GVM
, NULL AS PAYLOAD
, NULL AS NO_OF_AXLES
, NULL AS CONFIGURATION
, NULL AS EFFECTIVE_FROM
, NULL AS EFFECTIVE_TO
, NULL AS ACTIVE_FLAG
, NULL AS CREATED_BY
, TO_DATE('01/01/2021', 'DD/MM/YYYY') AS CREATED_ON_UTC
, NULL AS LAST_MODIFIED_BY
, TO_DATE('01/01/2021', 'DD/MM/YYYY') AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC