SELECT
A.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, A.AGREEMENT_ID AS AGREEMENT_ID
, A.AGREEMENT_NUMBER AS AGREEMENT_NUMBER
, A.VERSION AS VERSION
, A.STATUS AS STATUS
, A.FEE_RATE AS FEE_RATE
, A.FEE_TYPE AS FEE_TYPE
, CAST(A.EFFECTIVE_DATE_FROM AS DATE) AS EFFECTIVE_FROM
, CAST(A.EFFECTIVE_DATE_TO AS DATE) AS EFFECTIVE_TO
, A.CUSTOMER_SITE_NUMBER AS CONSUMER_ID
, A.PARTICIPANT_SITE_NUMBER AS SITE_NUMBER
, A.PARTICIPANT_SITE_NAME AS SITE_NAME
, A.CREATED_ON AS CREATED_ON_UTC
, A.KAFKA_DATETIME AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM_KAFKA', 'PSF_AGREEMENT') }} AS A
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON A.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID