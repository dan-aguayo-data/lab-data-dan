SELECT
U.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, U.SCHEME AS SCHEME
, U.TRIP_LEG_ID AS ID
, U.TRIP_ID AS TRIP_ID
, U.TRIP_LEG_ID AS TRIP_LEG_ID
, U.VEHICLE_M3 AS VEHICLE_M3
, U.REGISTRATION_NUMBER AS REGISTRATION_NUMBER
, U.REGION AS REGION
, U.AGGREGATION_POINT AS AGGREGATION_POINT
, U.AGGREGATION_POINT_NAME AS AGGREGATION_POINT_NAME
, U.ACTUAL_START AS ACTUAL_START
, U.ACTUAL_START_KEY AS ACTUAL_START_KEY
, SUM(U.QTY) AS QTY
, SUM(U.TONNE) AS TONNE
, SUM(U.M3) AS M3
, SUM(U.M3) / U.VEHICLE_M3 AS UTILISATION
, SYSDATE() AS INSERT_DATE_UTC
FROM (
    SELECT
    T.MULTI_SCHEME_ID,
    T.SCHEME,
    T.TRIP_ID,
    T.TRIP_LEG_ID,
    V.NO_OF_AXLES AS VEHICLE_M3,
    V.REGISTRATION_NUMBER,
    S.REGION,
    S.AGGREGATION_POINT,
    S.AGGREGATION_POINT_NAME,
    T.ACTUAL_START,
    T.ACTUAL_START_KEY,
    SM.QTY,
    SM.KG/1000 AS TONNE,
    SM.M3,
    ROW_NUMBER() OVER (PARTITION BY TU.MANIFEST_NUMBER, T.TRIP_ID, TU.MATERIAL_TYPE_ID, SM.QTY ORDER BY T.TRIP_LEG_ID DESC) AS N
    FROM
    {{ ref('FMT_TRIPS') }} AS T
    LEFT JOIN (
        SELECT DISTINCT
        UNITS.TRIP_LEG_ID
        , UNITS.MANIFEST_NUMBER
        , UNITS.MATERIAL_TYPE_ID
        FROM {{ ref('FMT_TRIP_UNITS') }} AS UNITS
    ) TU
    ON T.TRIP_LEG_ID = TU.TRIP_LEG_ID
    LEFT JOIN (
        SELECT
        CRPM.MULTI_SCHEME_ID
        , CRPM.MANIFEST_NUMBER_ADJ
        , CRPM.CRP_SITE_NUMBER
        , CRPM.MATERIAL_TYPE_ID
        , SUM(CRPM.QTY) AS QTY
        , SUM(CRPM.CONVERTED_WEIGHT) AS KG
        , SUM(CRPM.M3_DERIVED) AS M3
        FROM {{ ref('CRP_SHIPPING_MANIFEST') }} AS CRPM
        GROUP BY
        CRPM.MULTI_SCHEME_ID
        , CRPM.MANIFEST_NUMBER_ADJ
        , CRPM.CRP_SITE_NUMBER
        , CRPM.MATERIAL_TYPE_ID
    ) SM 
    ON TU.MANIFEST_NUMBER = SM.MANIFEST_NUMBER_ADJ
    AND TU.MATERIAL_TYPE_ID = SM.MATERIAL_TYPE_ID
    LEFT JOIN {{ ref('FMT_VEHICLES') }} AS V
    ON T.VEHICLE_ID = V.ID
    LEFT JOIN {{ ref('CRP_SITES') }} AS S 
    ON SM.CRP_SITE_NUMBER = S.SITE_NUMBER
    WHERE T.MULTI_SCHEME_ID = 10001
    AND NOT(T.MULTI_SCHEME_ID = 10001 AND TO_CHAR(T.ACTUAL_START, 'YYYYMMDD') <= '20200930')
    AND T.CANCEL_REASON IS NULL
    AND T.TRIP_CANCEL_REASON IS NULL
) U
WHERE U.N = 1
GROUP BY
U.MULTI_SCHEME_ID,
U.SCHEME,
U.TRIP_ID,
U.TRIP_LEG_ID,
U.VEHICLE_M3,
U.REGISTRATION_NUMBER,
U.REGION,
U.AGGREGATION_POINT,
U.AGGREGATION_POINT_NAME,
U.ACTUAL_START,
U.ACTUAL_START_KEY