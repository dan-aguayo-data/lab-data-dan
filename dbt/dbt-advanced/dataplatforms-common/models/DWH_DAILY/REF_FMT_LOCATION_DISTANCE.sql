SELECT
PS_LS.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, L_LS.SCHEME_LOCATION_NO || '-' || L_LE.SCHEME_LOCATION_NO AS ID
, L_LS.SCHEME_LOCATION_NO AS SITE_NUMBER_START
, L_LE.SCHEME_LOCATION_NO AS SITE_NUMBER_END
, D.PLAN_DISTANCE_KM AS DISTANCES_KM
, D.PLAN_TIME_MINUTES AS TIME_MINS
, D.CREATED_BY AS CREATED_BY
, D.CREATED_ON AS CREATED_ON_UTC
, D.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, D.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM', 'FMT_LOCATION_DISTANCES') }} AS D
LEFT JOIN {{ source('CES_MSCM', 'FMT_LOCATIONS') }} AS L_LS
ON D.FROM_LOCATION_ID = L_LS.LOCATION_ID
LEFT JOIN {{ source('CES_MSCM', 'FMT_LOCATIONS') }} AS L_LE
ON D.TO_LOCATION_ID = L_LE.LOCATION_ID
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS_LS
ON L_LS.SCHEME_LOCATION_NO = PS_LS.SITE_NUMBER
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON PS_LS.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID