SELECT
B.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, B.ID AS ID
, B.BUYER_ID AS BUYER_ID
, PS.SITE_NAME AS BUYER_NAME
, B.SELLER_ID AS SELLER_ID
, PE.SITE_NAME AS SELLER_NAME
, B.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID
, MT.NAME AS MATERIAL_TYPE
, B.MRF_MATERIAL_TYPE_ID AS MRF_MATERIAL_TYPE_ID
, MT_MRF.NAME AS MRF_MATERIAL_TYPE
, CAST(B.EFFECTIVE_FROM AS DATE) AS EFFECTIVE_FROM
, TO_CHAR(B.EFFECTIVE_FROM, 'YYYYMMDD') AS EFFECTIVE_FROM_KEY
, CAST(B.EFFECTIVE_TO AS DATE) AS EFFECTIVE_TO
{% if target.name.upper() == 'UAT' %}
, CASE WHEN SYSDATE() BETWEEN CAST(B.EFFECTIVE_FROM AS DATE) AND NVL(CAST(B.EFFECTIVE_TO AS DATE),'9999-12-01') THEN 'Y' ELSE 'N' END AS ACTIVE_FLAG
{%- else -%}
, 1  AS ACTIVE_FLAG
{% endif %}
, B.CREATED_BY AS CREATED_BY
, B.CREATED_ON AS CREATED_ON_UTC
, B.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, B.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM', 'BUYER_BLACKLIST') }} AS B
LEFT JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON B.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS
ON B.BUYER_ID = PS.SITE_NUMBER
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PE
ON B.SELLER_ID = PE.SITE_NUMBER
LEFT JOIN {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS MT
ON B.MATERIAL_TYPE_ID = MT.ID
LEFT JOIN {{ source('CES_MSCM', 'MRF_MATERIAL_TYPE') }} AS MT_MRF
ON B.MRF_MATERIAL_TYPE_ID = MT_MRF.ID
