SELECT
H.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, H.SCHEME AS SCHEME
, H.TRANSACTION_DATE_KEY || S.AGGREGATION_POINT AS ID
, CAST(H.TRANSACTION_DATE AS DATE) AS TRANSACTION_DATE
, H.TRANSACTION_DATE_KEY AS TRANSACTION_DATE_KEY
, S.AGGREGATION_POINT AS AGGREGATION_POINT
, S.AGGREGATION_POINT_NAME AS AGGREGATION_POINT_NAME
, SA.REGION AS REGION
, SUM(D.COLLECTION_M3_DERIVED) AS COLLECTION_M3
, SUM(CASE WHEN MT.GLASS_FLAG = 'Glass' THEN D.COLLECTION_M3_DERIVED ELSE 0 END) AS COLLECTION_M3_GLASS
, SUM(CASE WHEN MT.GLASS_FLAG = 'Non Glass' THEN D.COLLECTION_M3_DERIVED ELSE 0 END) AS COLLECTION_M3_NON_GLASS
, U.GLASS_BIN_M3 AS GLASS_BIN_M3
, U.NON_GLASS_BIN_M3 AS NON_GLASS_BIN_M3
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ ref('CRP_COLLECTION_HDR') }} AS H
INNER JOIN {{ ref('CRP_COLLECTION_DTL') }} AS D
ON H.TRANSACTION_ID = D.TRANSACTION_ID
LEFT JOIN {{ ref('REF_MATERIAL_TYPE') }} AS MT
ON D.MATERIAL_TYPE_ID = MT.MATERIAL_TYPE_ID
LEFT JOIN {{ ref('CRP_SITES') }} AS S
ON H.SITE_NUMBER = S.SITE_NUMBER
LEFT JOIN {{ ref('CRP_SITES') }} AS SA
ON S.AGGREGATION_POINT = SA.SITE_NUMBER
INNER JOIN {{ source('LOOKUPS', 'RAW_COLLECTION_INFRASTRUCTURE_WA_20201125') }} AS U
ON S.AGGREGATION_POINT = U.SCHEME_ID
WHERE MT.MATERIAL_TYPE <> 'Ineligible Containers'
GROUP BY
H.MULTI_SCHEME_ID
, H.SCHEME
, H.TRANSACTION_DATE_KEY || S.AGGREGATION_POINT
, CAST(H.TRANSACTION_DATE AS DATE)
, H.TRANSACTION_DATE_KEY
, S.AGGREGATION_POINT
, S.AGGREGATION_POINT_NAME
, SA.REGION
, U.GLASS_BIN_M3
, U.NON_GLASS_BIN_M3
, CAST(SYSDATE() AS DATE)