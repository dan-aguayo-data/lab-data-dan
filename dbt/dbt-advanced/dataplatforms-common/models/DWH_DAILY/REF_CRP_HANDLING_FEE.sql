SELECT
H.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, H.ID AS ID
, H.SCHEME_PARTICIPANT_ID AS SITE_NUMBER
, PS.SITE_NAME AS SITE_NAME
, P.PARTICIPANT_NUMBER AS SUPPLIER_NUMBER
, P.PARTICIPANT_NAME AS SUPPLIER_NAME
, MT.NAME AS MATERIAL_TYPE
, H.AMOUNT AS AMOUNT
, CAST(H.EFFECTIVE_FROM AS DATE) AS EFFECTIVE_FROM
, CAST(H.EFFECTIVE_TO AS DATE) AS EFFECTIVE_TO
, CASE WHEN FILTER.N = 1 THEN 'Y' ELSE 'N' END AS ACTIVE_FLAG
, H.CREATED_BY AS CREATED_BY
, H.CREATED_ON AS CREATED_ON_UTC
, H.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, H.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM', 'HANDLING_FEE_REFERENCE') }} AS H
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS
ON H.SCHEME_PARTICIPANT_ID = PS.SITE_NUMBER
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANTS') }} AS P
ON PS.PARTICIPANT_ID = P.PARTICIPANT_ID
INNER JOIN {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS MT
ON H.MATERIAL_TYPE_ID = MT.ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON H.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN
    (SELECT
    P.ID
    ,ROW_NUMBER() OVER (PARTITION BY P.MULTI_SCHEME_ID, P.SCHEME_PARTICIPANT_ID, P.MATERIAL_TYPE_ID ORDER BY P.LAST_MODIFIED_ON DESC, P.EFFECTIVE_FROM DESC, P.EFFECTIVE_TO DESC) N
    FROM {{ source('CES_MSCM', 'HANDLING_FEE_REFERENCE') }} AS P
    WHERE CAST(CONVERT_TIMEZONE('UTC', 'Australia/Perth', SYSTIMESTAMP()) AS DATE)  BETWEEN NVL(P.EFFECTIVE_FROM,TO_DATE('01/JAN/1900','DD/MON/YYYY')) AND NVL(P.EFFECTIVE_TO,TO_DATE('01/JAN/9999','DD/MON/YYYY'))
    ) FILTER
ON H.ID = FILTER.ID