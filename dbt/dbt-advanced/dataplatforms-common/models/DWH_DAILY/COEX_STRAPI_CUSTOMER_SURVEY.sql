SELECT
10000 AS MULTI_SCHEME_ID
, 'QLD' AS SCHEME
, S.ID AS ID
, S.SOURCE AS SOURCE
, S.RATING AS RATING
, S.REASONS AS REASONS
, S.COMMENT AS COMMENT
, S.CRP AS CRP_NAME
, NVL(S.SCHEMEID, '-') AS CONSUMER_ID
, S.TRANSACTIONID AS TRANSACTION_ID
, S.REFUNDAMOUNT AS REFUND_AMOUNT
, CONVERT_TIMEZONE('UTC', 'Australia/Brisbane', S.TRANSACTIONDATE) AS TRANSACTION_DATE
, S.RECOMMENDSCORE AS RECOMMEND_SCORE
, S.REFERREDBY AS REFERRED_BY
, S.WHYPARTICIPATE AS WHY_PARTICIPATE
, S.CRPVISITS AS CRP_VISITS
, CASE WHEN S.RECOMMENDSCORE = '0' THEN 'DETRACTOR' WHEN S.RECOMMENDSCORE = '1' THEN 'DETRACTOR' WHEN S.RECOMMENDSCORE = '2' THEN 'DETRACTOR' WHEN S.RECOMMENDSCORE = '3' THEN 'DETRACTOR' WHEN S.RECOMMENDSCORE = '4' THEN 'DETRACTOR' WHEN S.RECOMMENDSCORE = '5' THEN 'DETRACTOR' WHEN S.RECOMMENDSCORE = '6' THEN 'DETRACTOR' WHEN S.RECOMMENDSCORE = '7' THEN 'PASSIVE' WHEN S.RECOMMENDSCORE = '8' THEN 'PASSIVE' WHEN S.RECOMMENDSCORE = '9' THEN 'PROMOTER' WHEN S.RECOMMENDSCORE = '10' THEN 'PROMOTER' ELSE NULL END AS NPS
, S.OTHERCOMMENTS AS OTHER_COMMENTS
, S.WAITTIME AS WAIT_TIME
, TO_NUMBER(REPLACE(S.WAITTIME, '+', '')) AS WAIT_TIME_ORDER
, NVL(S.SITENUMBER, '-') AS SITE_NUMBER
, CONVERT_TIMEZONE('UTC', 'Australia/Brisbane', S.CREATED_AT) AS CREATED_ON
, TO_CHAR(CONVERT_TIMEZONE('UTC', 'Australia/Brisbane', S.CREATED_AT),'YYYYMMDD') AS CREATED_ON_DATE_KEY
, TO_CHAR(CONVERT_TIMEZONE('UTC', 'Australia/Brisbane', S.CREATED_AT),'HHMISS') AS CREATED_ON_TIME_KEY
, CONVERT_TIMEZONE('UTC', 'Australia/Brisbane', S.UPDATED_AT) AS LAST_MODIFIED_ON
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('COEX', 'STRAPI_CUSTOMER_SURVEY') }} AS S
 
UNION ALL
 
SELECT
10000 AS MULTI_SCHEME_ID
, 'QLD' AS SCHEME
, Concat(RIGHT(Regexp_replace(id, '[^\\d]*'), 8), RIGHT(REPLACE(S.created_at, '.', ''), 5)) AS ID
, S.SOURCE
, S.RATING
, S.REASONS
, S.COMMENT
, S.SITE_NAME AS CRP_NAME
, NVL(S.MEMBER_NUMBER, '-') AS CONSUMER_ID
, S.TRANSACTION_ID
, S.REFUND_AMOUNT
, CONVERT_TIMEZONE('UTC', 'Australia/Brisbane', S.TRANSACTION_DATE) AS TRANSACTION_DATE
, NULL AS RECOMMEND_SCORE
, NULL AS REFERRED_BY
, S.WHY_PARTICIPATE
, NULL AS CRP_VISITS
, NULL AS NPS
, NULL AS OTHER_COMMENTS
, NULL AS WAIT_TIME
, NULL AS WAIT_TIME_ORDER
, NVL(S.SITE_NUMBER, '-') AS SITE_NUMBER
, CONVERT_TIMEZONE('UTC', 'Australia/Brisbane', S.CREATED_AT) AS CREATED_ON
, TO_CHAR(CONVERT_TIMEZONE('UTC', 'Australia/Brisbane', S.CREATED_AT),'YYYYMMDD') AS CREATED_ON_DATE_KEY
, TO_CHAR(CONVERT_TIMEZONE('UTC', 'Australia/Brisbane', S.CREATED_AT),'HHMISS') AS CREATED_ON_TIME_KEY
, CONVERT_TIMEZONE('UTC', 'Australia/Brisbane', S.UPDATED_AT) AS LAST_MODIFIED_AT
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('COEX', 'RMC_REVIEW_SURVEY') }} AS S
QUALIFY ROW_NUMBER() OVER (PARTITION BY Concat(RIGHT(Regexp_replace(id, '[^\\d]*'), 8), RIGHT(REPLACE(S.created_at, '.', ''), 5)) ORDER BY CONVERT_TIMEZONE('UTC', 'Australia/Brisbane', S.UPDATED_AT) DESC) = 1