WITH SITES_CTE AS(
    SELECT 
    S.MULTI_SCHEME_ID,
    S.SCHEME, 
    S.SITE_NUMBER, 
    S.SITE_NAME,
    R.DATE AS WEEK_START,
    R.YEAR_WEEK_ISO, 
    R.WEEK_END, 
    S.STATUS
    FROM {{ ref('CRP_SITES') }} AS S
    CROSS JOIN {{ ref('REF_DATE') }} AS R
    WHERE R.DAY_NAME = 'Mon' 
    AND S.MULTI_SCHEME_ID LIKE '10002%' 
    AND R.DATE BETWEEN '2023-11-01' AND SYSDATE()
    AND S.MULTI_SCHEME_ID LIKE '10002%' 
)
,AUDIT_CTE AS(
    SELECT 
    C.SITE_NUMBER, 
    C.YEAR_WEEK_ISO, 
    C.WEEK_START AS WEEK_START, 
    C.WEEK_END, 
    S.STATUS,
    S.LAST_MODIFIED_ON_UTC,
    S.DISPLAY_IN_MARKETING
    FROM SITES_CTE C
    LEFT JOIN {{ ref('CRP_SITES_AUDIT') }} AS S
    ON S.SITE_NUMBER = C.SITE_NUMBER 
    AND S.LAST_MODIFIED_ON_UTC <= C.WEEK_END 
    QUALIFY ROW_NUMBER() OVER (PARTITION BY C.SITE_NUMBER, C.YEAR_WEEK_ISO ORDER BY S.LAST_MODIFIED_ON_UTC DESC) =1
)
,NOP_CLAIM_CTE AS(
    SELECT 
    N.SITE_NUMBER,
    MIN(TO_VARCHAR(TO_DATE(N.PERIOD_KEY, 'YYYYMMDD'), 'YYYY-MM-DD')) AS FIRST_PERIOD
    FROM {{ ref('NOP_CLAIM') }} AS N
    GROUP BY N.SITE_NUMBER
)
SELECT
C.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, C.SCHEME AS SCHEME
, C.SITE_NUMBER AS SITE_NUMBER
, C.SITE_NAME AS SITE_NAME
, C.WEEK_START AS WEEK_START
, C.WEEK_END AS WEEK_END
, C.STATUS AS STATUS
, P.FIRST_PERIOD AS FIRST_PERIOD
, CASE WHEN P.FIRST_PERIOD <= C.WEEK_END THEN 1 ELSE 0 END  AS SUBMISSION_FLAG
, SYSDATE() AS INSERT_DATE_UTC
FROM SITES_CTE C
LEFT JOIN AUDIT_CTE A 
ON C.SITE_NUMBER = A.SITE_NUMBER 
AND C.YEAR_WEEK_ISO = A.YEAR_WEEK_ISO
LEFT JOIN NOP_CLAIM_CTE P 
ON C.SITE_NUMBER = P.SITE_NUMBER 
WHERE A.DISPLAY_IN_MARKETING = 1
AND SUBMISSION_FLAG = 0
ORDER BY C.SITE_NUMBER, C.YEAR_WEEK_ISO