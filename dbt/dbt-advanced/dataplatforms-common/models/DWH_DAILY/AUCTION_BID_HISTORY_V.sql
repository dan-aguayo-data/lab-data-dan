SELECT
B.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, B.ID AS ID
, CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, E.END_DATE_UTC) AS END_DATE
, EL.AUCTION_EVENT_ID AS AUCTION_EVENT_ID
, EL.LOT_ITEM_ID AS LOT_ITEM_ID
, CASE WHEN B.AUCTION_PROXY_BID_ID IS NULL THEN 'Manual Bid' ELSE 'Proxy Bid' END AS BID_TYPE
, B.BIDDER_ID AS BIDDER_ID
, PS_B.SITE_NAME AS BIDDER_NAME
, B.BID_PRICE_PER_TONNE AS BID_PRICE_PER_TONNE
, I.SELLER_ID AS SELLER_ID
, PS_S.SITE_NAME AS SELLER_NAME
, CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, B.SUBMITTED_ON) AS SUBMITTED_ON_NSW
, B.CREATED_BY AS CREATED_BY
, B.CANCELLED_BY AS CANCELLED_BY
, SYSDATE() AS INSERT_DATE_UTC
FROM (
    SELECT
    AB.MULTI_SCHEME_ID
    , AB.ID
    , AB.AUCTION_EVENT_LOT_ID
    , AB.AUCTION_PROXY_BID_ID
    , AB.BIDDER AS BIDDER_ID
    , AB.BID_PRICE_PER_TONNE
    , AB.SUBMITTED_ON
    , AB.CREATED_BY
    , AB.CANCELLED_BY
    FROM {{ source('CES_MSCM', 'AUCTION_BID') }} AS AB
    WHERE UPPER(AB.LAST_MODIFIED_BY) NOT LIKE '%@YOPMAIL.COM'
) B
LEFT JOIN (
    SELECT
    AEL.ID
    , AEL.AUCTION_EVENT_ID
    , AEL.LOT_ITEM_ID
    FROM {{ source('CES_MSCM', 'AUCTION_EVENT_LOT') }} AS AEL
    WHERE UPPER(AEL.LAST_MODIFIED_BY) NOT LIKE '%@YOPMAIL.COM'
) EL
ON B.AUCTION_EVENT_LOT_ID = EL.ID
LEFT JOIN (
    SELECT
    LI.ID
    , LI.MSC_SELLER_SITE_ID
    , LI.SELLER_ID
    FROM {{ source('CES_MSCM', 'LOT_ITEM') }} AS LI
    WHERE UPPER(NVL(LI.LAST_MODIFIED_BY, 'NA')) NOT LIKE '%@YOPMAIL.COM'
) I
ON EL.LOT_ITEM_ID = I.ID
LEFT JOIN (
    SELECT
    AE.ID
    , AE.END_DATE AS END_DATE_UTC
    FROM {{ source('CES_MSCM', 'AUCTION_EVENT') }} AS AE
    WHERE UPPER(AE.LAST_MODIFIED_BY) NOT LIKE '%@YOPMAIL.COM'
) E
ON EL.AUCTION_EVENT_ID = E.ID
LEFT JOIN (
    SELECT
    PS.SITE_NUMBER
    , PS.SITE_NAME
    FROM {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS
    WHERE UPPER(PS.LAST_MODIFIED_BY) NOT LIKE '%@YOPMAIL.COM'
) PS_B
ON B.BIDDER_ID = PS_B.SITE_NUMBER
LEFT JOIN (
    SELECT
    PS.PARTICIPANT_SITE_ID
    , PS.SITE_NAME
    FROM {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS
    WHERE UPPER(PS.LAST_MODIFIED_BY) NOT LIKE '%@YOPMAIL.COM'
) PS_S
ON I.MSC_SELLER_SITE_ID = PS_S.PARTICIPANT_SITE_ID
LEFT JOIN (
    SELECT
    SCHEME.MULTI_SCHEME_ID
    , SCHEME.NAME
    , SCHEME.TIMEZONE
    FROM {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
    WHERE UPPER(SCHEME.LAST_MODIFIED_BY) NOT LIKE '%@YOPMAIL.COM'
) SCHEME
ON B.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID