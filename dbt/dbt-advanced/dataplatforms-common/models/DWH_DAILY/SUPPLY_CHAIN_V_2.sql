SELECT
COALESCE(R.MULTI_SCHEME_ID, P.MULTI_SCHEME_ID, A.MULTI_SCHEME_ID) AS MULTI_SCHEME_ID
, SCHEME.SCHEME AS SCHEME
, COALESCE(R.PERIOD_KEY, P.PERIOD_KEY, A.MANIFEST_DATE_KEY) || '-' || COALESCE(R.MATERIAL_TYPE_ID, P.MATERIAL_TYPE_ID, A.MATERIAL_TYPE_ID) || '-' || COALESCE(R.PROCESSOR_SITE_NUMBER, P.PROCESSOR_SITE_NUMBER, A.PROCESSOR_SITE_NUMBER) AS ID
, COALESCE(R.PERIOD_KEY, P.PERIOD_KEY, A.MANIFEST_DATE_KEY) AS DATE_KEY
, COALESCE(R.MATERIAL_TYPE_ID, P.MATERIAL_TYPE_ID, A.MATERIAL_TYPE_ID) AS MATERIAL_TYPE_ID
, COALESCE(R.MATERIAL_TYPE, P.MATERIAL_TYPE, A.MATERIAL_TYPE) AS MATERIAL_TYPE
, COALESCE(R.PROCESSOR_SITE_NUMBER, P.PROCESSOR_SITE_NUMBER, A.PROCESSOR_SITE_NUMBER) AS PROCESSOR_SITE_NUMBER
, PRO.SITE_NAME AS PROCESSOR_SITE_NAME
, R.RECEIPT_WEIGHT_KG/1000 AS RECEIPT_WEIGHT_TONNE
, P.PROCESSED_WEIGHT_KG/1000 AS PROCESSED_WEIGHT_TONNE
, A.AUCTION_WEIGHT_KG/1000 AS AUCTION_WEIGHT_TONNE
FROM (
    SELECT
    RG.MULTI_SCHEME_ID
    , RG.PERIOD_KEY
    , RG.MATERIAL_TYPE_ID
    , RG.MATERIAL_TYPE
    , RG.PROCESSOR_SITE_NUMBER
    , SUM(RG.RECEIPT_WEIGHT_KG) AS RECEIPT_WEIGHT_KG
    FROM (
        SELECT
        PR.MULTI_SCHEME_ID
        , PR.PERIOD_KEY
        , PR.MATERIAL_TYPE_ID
        , PR.MATERIAL_TYPE
        , PR.SITE_NUMBER AS PROCESSOR_SITE_NUMBER
        , PR.RECEIVED_KG_DERIVED AS RECEIPT_WEIGHT_KG
        FROM {{ ref('PROCESSOR_RECEIPT') }} AS PR
        WHERE PR.STATUS = 'RECEIVED'
    ) RG
    GROUP BY
    RG.MULTI_SCHEME_ID
    , RG.PERIOD_KEY
    , RG.MATERIAL_TYPE_ID
    , RG.MATERIAL_TYPE
    , RG.PROCESSOR_SITE_NUMBER
) R
FULL OUTER JOIN (
    SELECT
    PV.MULTI_SCHEME_ID
    , PV.PERIOD_KEY
    , PV.MATERIAL_TYPE_ID
    , PV.MATERIAL_TYPE
    , PV.SITE_NUMBER AS PROCESSOR_SITE_NUMBER
    , SUM(PV.VOLUME_KG_DERIVED) AS PROCESSED_WEIGHT_KG
    FROM {{ ref('PROCESSOR_VOLUME') }} AS PV
    GROUP BY
    PV.MULTI_SCHEME_ID
    , PV.PERIOD_KEY
    , PV.MATERIAL_TYPE_ID
    , PV.MATERIAL_TYPE
    , PV.SITE_NUMBER
) P
ON R.MULTI_SCHEME_ID = P.MULTI_SCHEME_ID
AND R.PERIOD_KEY = P.PERIOD_KEY
AND R.MATERIAL_TYPE_ID = P.MATERIAL_TYPE_ID
AND R.PROCESSOR_SITE_NUMBER = P.PROCESSOR_SITE_NUMBER
FULL OUTER JOIN (
    SELECT
    AM.MULTI_SCHEME_ID
    , AM.MANIFEST_DATE_KEY
    , AM.MATERIAL_TYPE_ID
    , AM.MATERIAL_TYPE
    , AM.SELLER_ID AS PROCESSOR_SITE_NUMBER
    , SUM(AM.MANIFEST_WEIGHT_KG) AS AUCTION_WEIGHT_KG
    FROM {{ ref('AUCTION_MANIFEST_CLEANSED') }} AS AM
    GROUP BY
    AM.MULTI_SCHEME_ID
    , AM.MANIFEST_DATE_KEY
    , AM.MATERIAL_TYPE_ID
    , AM.MATERIAL_TYPE
    , AM.SELLER_ID
) A
ON COALESCE(R.MULTI_SCHEME_ID, P.MULTI_SCHEME_ID) = A.MULTI_SCHEME_ID
AND COALESCE(R.PERIOD_KEY, P.PERIOD_KEY) = A.MANIFEST_DATE_KEY
AND COALESCE(R.MATERIAL_TYPE_ID, P.MATERIAL_TYPE_ID) = A.MATERIAL_TYPE_ID
AND COALESCE(R.PROCESSOR_SITE_NUMBER, P.PROCESSOR_SITE_NUMBER) = A.PROCESSOR_SITE_NUMBER
INNER JOIN {{ ref('REF_SCHEME') }} AS SCHEME
ON COALESCE(R.MULTI_SCHEME_ID, P.MULTI_SCHEME_ID, A.MULTI_SCHEME_ID) = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ ref('PROCESSOR_SITES') }} AS PRO
ON COALESCE(R.PROCESSOR_SITE_NUMBER, P.PROCESSOR_SITE_NUMBER, A.PROCESSOR_SITE_NUMBER) = PRO.SITE_NUMBER