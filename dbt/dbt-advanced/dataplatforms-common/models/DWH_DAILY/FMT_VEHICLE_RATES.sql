SELECT
VR.SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, VR.VEHICLE_RATE_ID AS ID
, VR.SCHEME_VEHICLE_TYPE_ID AS VEHICLE_TYPE_ID
, VT.VEHICLE_TYPE_NAME AS VEHICLE_TYPE
, O.SCHEME_PARTICIPANT_ID AS SITE_NUMBER
, O.SUPPLIER_NUMBER AS SUPPLIER_NUMBER
, VR.AGREEMENT_NUMBER AS AGREEMENT_NUMBER
, R_T.VALUE AS RATE_TYPE
, R_U.VALUE AS RATE_UOM
, VR.RATE AS RATE
, VR.PO_LINE_NO AS PO_LINE_NO
, VR.PO_SHIPMENT_NO AS PO_SHIPMENT_NO
, CAST(VR.START_DATE_ACTIVE AS DATE) AS EFFECTIVE_FROM
, CAST(VR.END_DATE_ACTIVE AS DATE) AS EFFECTIVE_TO
, CASE WHEN CONVERT_TIMEZONE('UTC','Australia/Perth',SYSTIMESTAMP()) BETWEEN NVL(VR.START_DATE_ACTIVE,TO_DATE('01/JAN/1900','DD/MON/YYYY')) AND NVL(VR.END_DATE_ACTIVE,TO_DATE('01/JAN/9999','DD/MON/YYYY')) THEN 1 ELSE 0 END AS ACTIVE_FLAG
, VR.CREATED_BY AS CREATED_BY
, VR.CREATED_ON AS CREATED_ON_UTC
, VR.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, VR.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM', 'FMT_VEHICLE_RATES') }} AS VR
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON VR.SCHEME_ID = SCHEME.MULTI_SCHEME_ID
INNER JOIN {{ source('CES_MSCM', 'FMT_VEHICLE_TYPES') }} AS VT
ON VR.SCHEME_VEHICLE_TYPE_ID = VT.VEHICLE_TYPE_ID
LEFT JOIN {{ source('CES_MSCM', 'FMT_ORGANISATIONS') }} AS O
ON VR.ORGANISATION_ID = O.ORGANISATION_ID
LEFT JOIN {{ source('CES_MSCM', 'FMT_SCHEME_REF_CODES') }} AS R_T
ON VR.RATE_TYPE_ID = R_T.ID
LEFT JOIN {{ source('CES_MSCM', 'FMT_SCHEME_REF_CODES') }} AS R_U
ON VR.RATE_UOM_ID = R_U.ID
UNION ALL
SELECT
-1 AS MULTI_SCHEME_ID
, 'CES' AS SCHEME
, -1 AS ID
, NULL AS VEHICLE_TYPE_ID
, NULL AS VEHICLE_TYPE
, NULL AS SITE_NUMBER
, NULL AS SUPPLIER_NUMBER
, NULL AS AGREEMENT_NUMBER
, NULL AS RATE_TYPE
, NULL AS RATE_UOM
, NULL AS RATE
, NULL AS PO_LINE_NO
, NULL AS PO_SHIPMENT_NO
, NULL AS EFFECTIVE_FROM
, NULL AS EFFECTIVE_TO
, NULL AS ACTIVE_FLAG
, NULL AS CREATED_BY
, TO_DATE('01/01/2021', 'DD/MM/YYYY') AS CREATED_ON_UTC
, NULL AS LAST_MODIFIED_BY
, TO_DATE('01/01/2021', 'DD/MM/YYYY') AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC