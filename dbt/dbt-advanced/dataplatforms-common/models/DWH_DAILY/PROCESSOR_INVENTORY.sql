SELECT
ID.MULTI_SCHEME_ID  AS MULTI_SCHEME_ID 
, SCHEME.NAME AS SCHEME
, ID.ID AS ID
, ID.PROCESSOR_INVENTORY_HDR_ID AS INVENTORY_HDR_ID
, IH.PROCESSOR_ID AS SITE_NUMBER 
, PS.SITE_NAME  AS SITE_NAME 
, ID.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID
, MT.NAME AS MATERIAL_TYPE
, ID.VOLUME AS VOLUME
, ID.UOM AS UOM
, CASE ID.UOM WHEN 'KILOGRAM' THEN ID.VOLUME WHEN 'UNIT' THEN ID.VOLUME/NVL(U_KG_QTY_A.CONVERSION_FACTOR,U_KG_QTY_B.CONVERSION_FACTOR) END AS INVENTORY_KG_DERIVED
, CASE ID.UOM WHEN 'UNIT' THEN ID.VOLUME WHEN 'KILOGRAM' THEN ID.VOLUME*NVL(U_KG_QTY_A.CONVERSION_FACTOR,U_KG_QTY_B.CONVERSION_FACTOR) END AS INVENTORY_QTY_DERIVED
, IH.ENTRY_TYPE AS ENTRY_TYPE
, IH.PERIOD AS PERIOD
, REPLACE(IH.PERIOD,'-','') AS PERIOD_KEY
, IH.PERIOD_TYPE AS PERIOD_TYPE
, IH.SUBMITTED_BY AS SUBMITTED_BY
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(IH.SUBMITTED_DATE AS TIMESTAMP)) AS SUBMITTED_DATE
, IH.SUBMITTED_DATE AS SUBMITTED_DATE_UTC
, ID.CREATED_BY AS CREATED_BY
, ID.CREATED_ON AS CREATED_ON_UTC
, ID.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, ID.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM', 'PROCESSOR_INVENTORY_DTL') }} AS ID
INNER JOIN {{ source('CES_MSCM', 'PROCESSOR_INVENTORY_HDR') }} AS IH
ON ID.PROCESSOR_INVENTORY_HDR_ID = IH.ID
INNER JOIN {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS MT
ON ID.MATERIAL_TYPE_ID = MT.ID
LEFT JOIN {{ source('CES_MSCM', 'UOM_REFERENCE') }} AS U_KG_QTY_A
ON ID.MATERIAL_TYPE_ID = U_KG_QTY_A.MATERIAL_TYPE_ID
AND U_KG_QTY_A.FROM_UNIT = 'KILOGRAM'
AND U_KG_QTY_A.TO_UNIT = 'UNIT'
AND SYSDATE() BETWEEN NVL(U_KG_QTY_A.EFFECTIVE_FROM,TO_DATE('01/JAN/1900','DD/MON/YYYY')) AND NVL(U_KG_QTY_A.EFFECTIVE_TO,TO_DATE('01/JAN/9999','DD/MON/YYYY'))
AND IH.PROCESSOR_ID = U_KG_QTY_A.SCHEME_PARTICIPANT_ID
AND IH.MULTI_SCHEME_ID = U_KG_QTY_A.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'UOM_REFERENCE') }} AS U_KG_QTY_B
ON ID.MATERIAL_TYPE_ID = U_KG_QTY_B.MATERIAL_TYPE_ID
AND U_KG_QTY_B.FROM_UNIT = 'KILOGRAM'
AND U_KG_QTY_B.TO_UNIT = 'UNIT'
AND SYSDATE() BETWEEN NVL(U_KG_QTY_B.EFFECTIVE_FROM,TO_DATE('01/JAN/1900','DD/MON/YYYY')) AND NVL(U_KG_QTY_B.EFFECTIVE_TO,TO_DATE('01/JAN/9999','DD/MON/YYYY'))
AND U_KG_QTY_B.SCHEME_PARTICIPANT_ID IS NULL
AND IH.MULTI_SCHEME_ID = U_KG_QTY_B.MULTI_SCHEME_ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON ID.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS
ON PS.SITE_NUMBER=IH.PROCESSOR_ID