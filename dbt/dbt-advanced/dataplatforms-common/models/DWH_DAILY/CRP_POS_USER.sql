SELECT
NVL(PU.MULTI_SCHEME_ID, PS.MULTI_SCHEME_ID) AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, PU.ID AS ID
, PU.CRP_ID AS CRP_SITE_NUMBER
, PS.SITE_NAME AS CRP_SITE_NAME
, P.PARTICIPANT_NUMBER AS SUPPLIER_NUMBER
, P.PARTICIPANT_NAME AS SUPPLIER_NAME
, PU.POS_USER_NAME AS POS_USER_NAME
, PU.POS_ACCESS AS POS_ACCESS
, PU.STATUS AS STATUS
, PU.CREATED_BY AS CREATED_BY
, PU.CREATED_ON AS CREATED_ON_UTC
, PU.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, PU.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM', 'POS_USER') }} AS PU
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS
ON PU.CRP_ID = PS.SITE_NUMBER
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANTS') }} AS P
ON PS.PARTICIPANT_ID = P.PARTICIPANT_ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON NVL(PU.MULTI_SCHEME_ID, PS.MULTI_SCHEME_ID) = SCHEME.MULTI_SCHEME_ID