SELECT
TO_NUMBER(NVL(C.MULTI_SCHEME_ID, RD.MULTI_SCHEME_ID)) AS MULTI_SCHEME_ID
, COALESCE(C.PERIOD, RD.PERIOD) AS PERIOD
, COALESCE(C.SITE_NUMBER, RD.SITE_NUMBER) AS SITE_NUMBER
, COALESCE(C.ZONE, RD.ZONE) AS ZONE
, COALESCE(C.CRP_TYPE, RD.CRP_TYPE) AS CRP_TYPE
, NVL(SUM(C.CLAIM_QTY), 0) AS TOTAL_PERIOD_CLAIM_QTY
, SYSDATE() AS INSERT_DATE_UTC
FROM
(
        SELECT
        NC.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
        , NC.CLAIM_ID || '_' || H.CRP_SITE_NUMBER || '-' || H.PAYMENT_TYPE || '-' || NVL(H.LATE_SYNC, '-') || '-' || MT.ID AS ID
        , NC.CLAIM_ID AS CLAIM_ID
        , H.CRP_SITE_NUMBER AS SITE_NUMBER
        , CS.ZONE AS ZONE
        , CASE WHEN CS.AUTOMATED_COUNTING_FACILITY = 1 THEN 'AUTOMATED_COUNTING_FACILITY' WHEN CS.OVER_THE_COUNTER = 1 THEN 'OVER_THE_COUNTER' WHEN CS.AUTOMATED_COUNTING_FACILITY = 0 AND CS.OVER_THE_COUNTER = 0 THEN 'UNKNOWN' END AS CRP_TYPE        , NC.PERIOD AS PERIOD
        , 'R' AS ENTRY_TYPE
        , NC.STATUS AS STATUS
        , MT.ID AS MATERIAL_TYPE_ID
        , NVL(SUM(D.CONTAINER_COUNT), 0) AS CLAIM_QTY
        , H.PAYMENT_TYPE AS PAYMENT_TYPE
        , NC.SUBMITTED_DATE_UTC AS CLAIM_SUBMITTED_DATE_UTC
        , NC.SUBMITTED_BY AS CLAIM_SUBMITTED_BY
        , NULL AS ADJUSTMENT_SUBMITTED_DATE_UTC
        , NULL AS ADJUSTMENT_SUBMITTED_BY
        , H.LATE_SYNC AS LATE_SYNC
        FROM
            (SELECT
             NOPC.MULTI_SCHEME_ID
             , NOPC.CLAIM_ID
             , NOPC.PERIOD
             , NOPC.STATUS
             , NOPC.SUBMITTED_DATE_UTC
             , NOPC.SUBMITTED_BY
            FROM {{ source('CES_MSCM_KAFKA', 'NOP_CLAIM') }} AS NOPC
            QUALIFY ROW_NUMBER() OVER (PARTITION BY NOPC.CLAIM_ID ORDER BY NOPC.KAFKA_DATETIME DESC) = 1
            ) NC --LATEST STATUS
        INNER JOIN {{ source('CES_MSCM_KAFKA', 'NOP_CLAIM_REFUND') }} AS H
        ON NC.CLAIM_ID = H.CLAIM_ID
        LEFT JOIN {{ ref('CRP_SITES') }} AS CS
        ON H.CRP_SITE_NUMBER = CS.SITE_NUMBER
        CROSS JOIN {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS MT
        LEFT JOIN {{ source('CES_MSCM_KAFKA', 'NOP_CLAIM_REFUND_ITEMS') }} AS D
        ON H.REFUND_TRANSACTION_ID = D.REFUND_TRANSACTION_ID
        AND MT.ID = D.MATERIAL_TYPE_ID
        WHERE LEFT(NC.MULTI_SCHEME_ID, 5) = MT.MULTI_SCHEME_ID
        GROUP BY ALL
        UNION ALL
        SELECT
        HDR.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
        , HDR.ADJUSTMENT_ID || '_' || HDR.SITE_NUMBER || '-' || HDR.PAYMENT_TYPE || '-' || DTL.MATERIAL_TYPE_ID AS ID
        , HDR.CLAIM_ID AS CLAIM_ID
        , HDR.SITE_NUMBER AS SITE_NUMBER
        , CS.ZONE AS ZONE
        , CASE WHEN CS.AUTOMATED_COUNTING_FACILITY = 1 THEN 'AUTOMATED_COUNTING_FACILITY' WHEN CS.OVER_THE_COUNTER = 1 THEN 'OVER_THE_COUNTER' WHEN CS.AUTOMATED_COUNTING_FACILITY = 0 AND CS.OVER_THE_COUNTER = 0 THEN 'UNKNOWN' END AS CRP_TYPE        , NC.PERIOD AS PERIOD
        , 'A' AS ENTRY_TYPE
        , NC.STATUS AS STATUS
        , DTL.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID
        , SUM(DTL.CONTAINER_COUNT) AS CLAIM_QTY
        , HDR.PAYMENT_TYPE AS PAYMENT_TYPE
        , NC.SUBMITTED_DATE_UTC AS CLAIM_SUBMITTED_DATE_UTC
        , NC.SUBMITTED_BY AS CLAIM_SUBMITTED_BY
        , HDR.SUBMITTED_DATE_UTC AS ADJUSTMENT_SUBMITTED_DATE_UTC
        , HDR.SUBMITTED_BY AS ADJUSTMENT_SUBMITTED_BY
        , NULL AS LATE_SYNC
        FROM
        {{ source('CES_MSCM_KAFKA', 'NOP_CLAIM_ADJUSTMENT') }} AS HDR
        LEFT JOIN {{ ref('CRP_SITES') }} AS CS
        ON HDR.SITE_NUMBER = CS.SITE_NUMBER
        INNER JOIN {{ source('CES_MSCM_KAFKA', 'NOP_CLAIM_ADJ_ITEMS') }} AS DTL
        ON HDR.ADJUSTMENT_ID = DTL.ADJUSTMENT_ID
        INNER JOIN
            (SELECT
             NOPC.MULTI_SCHEME_ID
             , NOPC.CLAIM_ID
             , NOPC.PERIOD
             , NOPC.STATUS
             , NOPC.SUBMITTED_DATE_UTC
             , NOPC.SUBMITTED_BY
            FROM {{ source('CES_MSCM_KAFKA', 'NOP_CLAIM') }} AS NOPC
            QUALIFY ROW_NUMBER() OVER (PARTITION BY NOPC.CLAIM_ID ORDER BY NOPC.KAFKA_DATETIME DESC) = 1
            ) NC --LATEST STATUS
        ON HDR.CLAIM_ID = NC.CLAIM_ID
        GROUP BY ALL
) C
FULL JOIN 
        (SELECT 
         C.MULTI_SCHEME_ID
         , R.YEAR_WEEK_ISO AS PERIOD
         , C.SITE_NUMBER
         , C.ZONE
        , CASE WHEN C.AUTOMATED_COUNTING_FACILITY = 1 THEN 'AUTOMATED_COUNTING_FACILITY' WHEN C.OVER_THE_COUNTER = 1 THEN 'OVER_THE_COUNTER' WHEN C.AUTOMATED_COUNTING_FACILITY = 0 AND C.OVER_THE_COUNTER = 0 THEN 'UNKNOWN' END AS CRP_TYPE         
         FROM {{ ref('CRP_SITES') }} AS C
         CROSS JOIN {{ ref('REF_DATE') }} AS R
         WHERE R.YEAR_WEEK_ISO >= '2023-01'
         AND R.YEAR_WEEK_ISO <= YEAROFWEEKISO(CURRENT_DATE) || '-' || TO_CHAR(WEEKISO(CURRENT_DATE),'FM00')
         QUALIFY ROW_NUMBER() OVER (PARTITION BY R.YEAR_WEEK_ISO ORDER BY R.YEAR_WEEK_ISO DESC) = 1
) RD 
ON C.PERIOD = RD.PERIOD 
AND C.SITE_NUMBER = RD.SITE_NUMBER
GROUP BY ALL