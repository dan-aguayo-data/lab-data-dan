SELECT
UOM.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, UOM.ID AS ID
, UOM.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID
, MT.NAME AS MATERIAL_TYPE
, UOM.FROM_UNIT AS FROM_UNIT
, UOM.TO_UNIT AS TO_UNIT
, UOM.CONVERSION_FACTOR AS CONVERSION_FACTOR
, CAST(UOM.EFFECTIVE_FROM AS DATE) AS EFFECTIVE_FROM
, CAST(UOM.EFFECTIVE_TO AS DATE) AS EFFECTIVE_TO
, CASE WHEN FILTER.N = 1 THEN 'Y' ELSE 'N' END AS ACTIVE_FLAG
, UOM.CREATED_BY AS CREATED_BY
, UOM.CREATED_ON AS CREATED_ON_UTC
, UOM.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, UOM.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM', 'UOM_REFERENCE') }} AS UOM
INNER JOIN {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS MT
ON UOM.MATERIAL_TYPE_ID = MT.ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON UOM.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN
    (SELECT
    P.ID
    ,ROW_NUMBER() OVER (PARTITION BY P.MULTI_SCHEME_ID, P.MATERIAL_TYPE_ID, P.FROM_UNIT, P.TO_UNIT ORDER BY P.LAST_MODIFIED_ON DESC, P.EFFECTIVE_FROM DESC, P.EFFECTIVE_TO DESC) N
    FROM {{ source('CES_MSCM', 'UOM_REFERENCE') }} AS P
    WHERE CAST(CONVERT_TIMEZONE('UTC', 'Australia/Perth', SYSTIMESTAMP()) AS DATE)  BETWEEN NVL(P.EFFECTIVE_FROM,TO_DATE('01/JAN/1900','DD/MON/YYYY')) AND NVL(P.EFFECTIVE_TO,TO_DATE('01/JAN/9999','DD/MON/YYYY'))
    ) FILTER
ON UOM.ID = FILTER.ID