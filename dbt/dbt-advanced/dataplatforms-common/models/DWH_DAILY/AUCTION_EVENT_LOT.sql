SELECT
SS.MULTI_SCHEME_ID  AS MULTI_SCHEME_ID 
, SCHEME.NAME AS SCHEME
, SS.ID AS ID
, SS.LOT_ITEM_ID AS LOT_ITEM_ID
, CASE WHEN SS.EVENT_ID  ='DIRECT_SALE' THEN 'DIRECT_SALE' ELSE 'AUCTION' END AS EVENT_TYPE
, SS.EVENT_ID AS EVENT_ID
, SS.NAME AS NAME
, SS.DESCRIPTION AS DESCRIPTION
, CASE WHEN SS.EVENT_ID  ='DIRECT_SALE' OR (CAST(SS.AGREEMENT_DATE AS DATE) <= CAST(SS.END_DATE AS DATE) AND SS.BID_PRICE_PER_TONNE >= SS.RESERVE_PRICE_PER_TONNE ) THEN 1 ELSE 0 END AS SOLD
, SS.STATUS AS STATUS
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(SS.START_DATE AS TIMESTAMP))  AS START_DATE
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(SS.END_DATE AS TIMESTAMP))  AS END_DATE
, TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(SS.END_DATE AS TIMESTAMP)),'YYYYMMDD') AS END_DATE_KEY
, RD.WEEK_END AS END_DATE_WEEK_END
, SS.BID_PRICE_PER_TONNE AS MAX_BID
, CASE WHEN SS.EVENT_ID  ='DIRECT_SALE' OR (CAST(SS.AGREEMENT_DATE AS DATE) <= CAST(SS.END_DATE AS DATE) AND SS.BID_PRICE_PER_TONNE >= SS.RESERVE_PRICE_PER_TONNE ) THEN SS.BID_PRICE_PER_TONNE ELSE 0 END AS WINNING_BID
, SS.WEIGHT_IN_TONNES AS WEIGHT_IN_TONNES
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(SS.AGREEMENT_DATE AS TIMESTAMP))  AS AGREEMENT_DATE
, WD.WRKDAY AS COLLECTION_END_DATE
, SS.SUBMITTED_BY AS SUBMITTED_BY
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(SS.SUBMITTED_ON AS TIMESTAMP))  AS SUBMITTED_DATE
, SS.AGREEMENT_DATE AS AGREEMENT_DATE_UTC
, SS.SUBMITTED_ON AS SUBMITTED_DATE_UTC
, SS.CREATED_BY AS CREATED_BY
, SS.CREATED_ON AS CREATED_ON_UTC
, SS.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, SS.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM (
    SELECT 
    EL.MULTI_SCHEME_ID 
    , EL.ID
    , E.ID AS EVENT_ID
    , E.NAME 
    , E.DESCRIPTION 
    , EL.LOT_ITEM_ID
    , E.STATUS
    , E.START_DATE
    , NVL(ED.END_DATE_TIME,E.END_DATE) AS END_DATE
    , E.SUBMITTED_BY
    , E.SUBMITTED_ON 
    , EL.CREATED_BY
    , EL.CREATED_ON
    , EL.LAST_MODIFIED_BY
    , EL.LAST_MODIFIED_ON 
    , L.AVAILABLE_FROM
    , L.AGREEMENT_DATE
    , B.BID_PRICE_PER_TONNE
    , L.RESERVE_PRICE_PER_TONNE 
    , L.WEIGHT_IN_TONNES
    FROM {{ source('CES_MSCM', 'AUCTION_EVENT') }} AS E
    LEFT JOIN {{ source('CES_MSCM', 'AUCTION_EVENT_LOT') }} AS EL
    ON E.ID = EL.AUCTION_EVENT_ID
    LEFT JOIN {{ source('CES_MSCM', 'LOT_ITEM') }} AS L
    ON EL.LOT_ITEM_ID = L.ID
    LEFT JOIN (
        SELECT 
        AB.AUCTION_EVENT_LOT_ID
        , MAX(AB.BID_PRICE_PER_TONNE) AS BID_PRICE_PER_TONNE
        FROM {{ source('CES_MSCM', 'AUCTION_BID') }} AS AB
        WHERE AB.CANCELLED_ON IS NULL
        GROUP BY AB.AUCTION_EVENT_LOT_ID
    ) B
    ON EL.ID = B.AUCTION_EVENT_LOT_ID
    LEFT JOIN
    (SELECT AUCTION_EVENT_ID, MAX(END_DATE_TIME) AS END_DATE_TIME
    FROM {{ source('CES_MSCM', 'AUCTION_EVENT_HISTORY') }} AS EH
    GROUP BY AUCTION_EVENT_ID) ED ON ED.AUCTION_EVENT_ID=E.ID
    UNION ALL
    SELECT
    LL.MULTI_SCHEME_ID 
    , 'DIRECT_SALE' || '-' || LL.ID AS ID
    , 'DIRECT_SALE' AS EVENT_ID
    , 'DIRECT_SALE' AS NAME 
    , 'DIRECT_SALE' AS DESCRIPTION 
    , LL.ID AS LOT_ITEM_ID
    , NULL AS STATUS
    , NULL AS START_DATE
    , NULL AS END_DATE 
    , NULL AS SUBMITTED_BY
    , NULL AS SUBMITTED_ON 
    , NULL AS CREATED_BY
    , NULL AS CREATED_ON
    , NULL AS LAST_MODIFIED_BY
    , NULL AS LAST_MODIFIED_ON 
    , LL.AVAILABLE_FROM
    , LL.AGREEMENT_DATE
    , NULL AS BID_PRICE_PER_TONNE
    , NULL AS RESERVE_PRICE_PER_TONNE
    , NULL AS WEIGHT_IN_TONNES
    FROM {{ source('CES_MSCM', 'LOT_ITEM') }} AS LL
    WHERE LL.DIRECT_SALE_MODE = 1
) SS
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON SS.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ ref('REF_DATE') }} AS RD
ON TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(SS.END_DATE AS TIMESTAMP)),'YYYYMMDD') = RD.KEY
LEFT JOIN (
    SELECT * 
    FROM (
        SELECT 
        D.DATE AS WRKDAY
        ,ROW_NUMBER() OVER (ORDER BY DATE) AS SEQ 
        FROM {{ ref('REF_DATE') }} AS D
        WHERE DAY_TYPE = 'WEEKDAY'
    ) DATE_A
    LEFT JOIN (
        SELECT 
        D.DATE
        , ROW_NUMBER() OVER (ORDER BY DATE) + 10 AS SEQ 
        FROM {{ ref('REF_DATE') }} AS D
        WHERE DAY_TYPE = 'WEEKDAY'
    ) DATE_B 
    ON DATE_B.SEQ=DATE_A.SEQ
) WD 
ON WD.DATE = 
CAST(
    CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, 
        CAST(
            (
                CASE WHEN SS.AVAILABLE_FROM < coalesce(SS.END_DATE,SS.AGREEMENT_DATE)  
                THEN coalesce(SS.END_DATE,SS.AGREEMENT_DATE) 
                ELSE SS.AVAILABLE_FROM 
                END
            ) 
        AS TIMESTAMP)
    )
AS DATE) + 
(
    CASE WHEN DAYOFWEEKISO(
        CAST(
            CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, 
                CAST(
                    (
                        CASE WHEN SS.AVAILABLE_FROM < coalesce(SS.END_DATE,SS.AGREEMENT_DATE)
                        THEN coalesce(SS.END_DATE,SS.AGREEMENT_DATE) 
                        ELSE SS.AVAILABLE_FROM
                        END
                    ) 
                AS TIMESTAMP)
            )
        AS DATE)) = 6
    THEN 2
    WHEN DAYOFWEEKISO(
        CAST(
            CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE,
                CAST(
                    (
                        CASE WHEN SS.AVAILABLE_FROM < coalesce(SS.END_DATE,SS.AGREEMENT_DATE)   
                        THEN coalesce(SS.END_DATE,SS.AGREEMENT_DATE) 
                        ELSE SS.AVAILABLE_FROM 
                        END
                    ) 
                AS TIMESTAMP)
            )
        AS DATE)) = 7
    THEN 1
    ELSE 0 END
)
 
UNION ALL
 
SELECT
-1 AS MULTI_SCHEME_ID
, 'CES' AS SCHEME
, '-' AS ID
, '-' AS LOT_ITEM_ID
, NULL AS EVENT_TYPE
, NULL AS EVENT_ID
, NULL AS NAME
, NULL AS DESCRIPTION
, NULL AS SOLD
, NULL AS STATUS
, NULL AS START_DATE
, NULL AS END_DATE
, NULL AS END_DATE_KEY
, NULL AS END_DATE_WEEK_END
, NULL AS MAX_BID
, NULL AS WINNING_BID
, NULL AS WEIGHT_IN_TONNES
, NULL AS AGREEMENT_DATE
, NULL AS COLLECTION_END_DATE
, NULL AS SUBMITTED_BY
, NULL AS SUBMITTED_DATE
, NULL AS AGREEMENT_DATE_UTC
, NULL AS SUBMITTED_DATE_UTC
, NULL AS CREATED_BY
, TO_DATE('01/01/2021', 'DD/MM/YYYY') AS CREATED_ON_UTC
, NULL AS LAST_MODIFIED_BY
, TO_DATE('01/01/2021', 'DD/MM/YYYY') AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC