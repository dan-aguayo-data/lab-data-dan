SELECT
H.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, H.SCHEME AS SCHEME
, TO_CHAR(DATE_TRUNC('MONTH', H.TRANSACTION_DATE), 'YYYYMMDD') || H.CONSUMER_ID AS ID
, H.CONSUMER_ID AS CONSUMER_ID
, TO_CHAR(DATE_TRUNC('MONTH', H.TRANSACTION_DATE), 'YYYYMMDD') AS TRANSACTION_MONTH_KEY
, SUM(H.COLLECTION_QTY) AS COLLECTION_QTY
, COUNT(H.ID) AS TRANSACTION_COUNT
FROM
{{ ref('CRP_COLLECTION_HDR') }} AS H
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON H.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
WHERE
H.CONSUMER_ID <> '-'
AND H.TRANSACTION_DATE_KEY < TO_CHAR(DATE_TRUNC('MONTH', CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(SYSDATE() AS TIMESTAMP))),'YYYYMMDD')
GROUP BY
H.MULTI_SCHEME_ID,
H.SCHEME,
H.CONSUMER_ID,
TO_CHAR(DATE_TRUNC('MONTH', H.TRANSACTION_DATE), 'YYYYMMDD')