SELECT
MRF.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, MRF.SCHEME AS SCHEME
, MRF.ID AS ID
, MRF.DATE_KEY AS DATE_KEY
, MRF.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID
, MRF.COLLECTION_QTY AS COLLECTION_QTY
, MRF.TYPE AS TYPE
, 'MRF' AS FLAG
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ ref('MRF_COLLECTION_MONTHLY') }} AS MRF
 
UNION ALL
 
SELECT
H.MULTI_SCHEME_ID
, H.SCHEME
, H.SCHEME || '-' || TO_CHAR(DATE_TRUNC(MONTH, H.TRANSACTION_DATE), 'YYYYMMDD') || '-' || D.MATERIAL_TYPE_ID || '-' || 'A' AS ID
, TO_CHAR(DATE_TRUNC(MONTH, H.TRANSACTION_DATE), 'YYYYMMDD') AS DATE_KEY
, D.MATERIAL_TYPE_ID
, SUM(D.COLLECTION_QTY) AS COLLECTION_QTY
, 'A' AS TYPE
, 'CRP' AS FLAG
, SYSDATE() AS INSERT_DATE_UTC
FROM {{ ref('CRP_COLLECTION_HDR') }} AS H
INNER JOIN {{ ref('CRP_COLLECTION_DTL') }} AS D
ON H.TRANSACTION_ID = D.TRANSACTION_ID
GROUP BY
H.MULTI_SCHEME_ID
, H.SCHEME
, DATE_KEY
, D.MATERIAL_TYPE_ID
, SYSDATE ()