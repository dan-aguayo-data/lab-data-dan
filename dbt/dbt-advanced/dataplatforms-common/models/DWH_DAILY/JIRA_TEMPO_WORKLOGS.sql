WITH JIRA_ISSUE AS (
SELECT 
CASE WHEN CS.SCHEME = 'COEX' THEN 10000 WHEN CS.SCHEME = 'WARRRL' THEN 10001 WHEN CS.SCHEME = 'VIC-VicReturn' THEN 10002 WHEN CS.SCHEME = 'Vic Return' THEN 10002 WHEN CS.SCHEME = 'VIC-Return-IT' THEN 100020001 WHEN CS.SCHEME = 'COEX;VIC-Return-IT;VIC-VicReturn;WARRRL' THEN -1 ELSE 0 END AS MULTI_SCHEME_ID
, CASE WHEN CS.SCHEME = 'Internal' THEN 'CES' WHEN CS.SCHEME = '' THEN 'CES' ELSE CS.SCHEME END AS SCHEME
, CN.CLIENT_NAME AS CLIENT_NAME
, CAST(I.ID AS VARCHAR) AS ID
, I.KEY AS KEY
, NVL(IH.INI_KEY, '-') AS INI_KEY
, COALESCE(IH.L2_KEY, EPIC.PARENT_KEY, '-') AS L2_KEY
, U_A.NAME AS ASSIGNEE
, IT.NAME AS ISSUE_TYPE
, I.SUMMARY AS SUMMARY
, IH.INI_SUMMARY AS INI_SUMMARY
, NVL(IH.L2_SUMMARY, EPIC.SUMMARY) AS L2_SUMMARY
, NVL(IH.L2_DESCRIPTION, EPIC.DESCRIPTION) AS L2_DESCRIPTION
, PC.PRODUCT_CATEGORISATION AS PRODUCT_CATEGORISATION
, W.WORKSTREAM AS WORKSTREAM
, WT.WORK_TYPE AS WORK_TYPE
, P.KEY AS PROJECT_KEY
, P.NAME AS PROJECT_NAME
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_JIRA', 'ISSUE') }} AS I
LEFT JOIN {{ source('CES_JIRA', 'USER') }} AS U_A
ON I.ASSIGNEE = U_A.ID
LEFT JOIN {{ source('CES_JIRA', 'ISSUE_TYPE') }} AS IT
ON I.ISSUE_TYPE = IT.ID
LEFT JOIN {{ source('CES_JIRA', 'PROJECT') }} AS P
ON I.PROJECT = P.ID
LEFT JOIN (
    SELECT
    F.ISSUE_ID
    , LISTAGG(F.VALUE, ';') WITHIN GROUP (ORDER BY F.VALUE) AS SCHEME
    FROM {{ source('CES_JIRA', 'ISSUE_FIELD_HISTORY') }} AS F
    WHERE FIELD_ID IN ('customfield_11038', 'customfield_10207')
    AND IS_ACTIVE = TRUE
    GROUP BY F.ISSUE_ID
    
    UNION
    
    SELECT
    I.ISSUE_ID
    , LISTAGG(O.NAME, ';') WITHIN GROUP (ORDER BY O.NAME) AS SCHEME
    FROM {{ source('CES_JIRA', 'ISSUE_MULTISELECT_HISTORY') }} AS I
    LEFT JOIN {{ source('CES_JIRA', 'FIELD_OPTION') }} AS O 
    ON I.VALUE = O.ID
    WHERE FIELD_ID IN ('customfield_11038', 'customfield_10207')
    AND IS_ACTIVE = TRUE
    GROUP BY I.ISSUE_ID
) CS
ON I.ID = CS.ISSUE_ID
LEFT JOIN (
    SELECT
    I.ISSUE_ID
    , LISTAGG(O.NAME, '; ') WITHIN GROUP (ORDER BY O.NAME) AS CLIENT_NAME
    FROM {{ source('CES_JIRA', 'ISSUE_MULTISELECT_HISTORY') }} AS I
    LEFT JOIN {{ source('CES_JIRA', 'FIELD_OPTION') }} AS O 
    ON I.VALUE = O.ID
    WHERE FIELD_ID IN ('customfield_11190')
    AND IS_ACTIVE = TRUE
    GROUP BY I.ISSUE_ID
) CN
ON I.ID = CN.ISSUE_ID
LEFT JOIN (
    SELECT
    I.ISSUE_ID
    , O.NAME AS PRODUCT_CATEGORISATION
    FROM {{ source('CES_JIRA', 'ISSUE_FIELD_HISTORY') }} AS I
    LEFT JOIN {{ source('CES_JIRA', 'FIELD_OPTION') }} AS O 
    ON I.VALUE = O.ID
    WHERE FIELD_ID IN ('customfield_11230')
    AND IS_ACTIVE = TRUE
) PC
ON I.ID = PC.ISSUE_ID
LEFT JOIN (
    SELECT
    I.ISSUE_ID
    , O.NAME AS WORKSTREAM
    FROM {{ source('CES_JIRA', 'ISSUE_FIELD_HISTORY') }} AS I
    LEFT JOIN {{ source('CES_JIRA', 'FIELD_OPTION') }} AS O 
    ON I.VALUE = O.ID
    WHERE FIELD_ID IN ('customfield_10533')
    AND IS_ACTIVE = TRUE
) W
ON I.ID = W.ISSUE_ID
LEFT JOIN (
    SELECT
    I.ISSUE_ID
    , O.NAME AS WORK_TYPE
    FROM {{ source('CES_JIRA', 'ISSUE_FIELD_HISTORY') }} AS I
    LEFT JOIN {{ source('CES_JIRA', 'FIELD_OPTION') }} AS O 
    ON I.VALUE = O.ID
    WHERE FIELD_ID IN ('customfield_11191')
    AND IS_ACTIVE = TRUE
) WT
ON I.ID = WT.ISSUE_ID
LEFT JOIN (
    SELECT
    H.KEY
    , REGEXP_SUBSTR(H.ISSUE_HIERARCHY, '[^/]+', 1, 1) AS INI_KEY
    , REGEXP_SUBSTR(H.ISSUE_HIERARCHY, '[^/]+', 1, 2) AS L2_KEY
    , H.LEVEL_NUMBER
    , H.ISSUE_HIERARCHY
    , INI.SUMMARY AS INI_SUMMARY
    , L2.SUMMARY AS L2_SUMMARY
    , L2.DESCRIPTION AS L2_DESCRIPTION
    FROM (
        SELECT
        SYS_CONNECT_BY_PATH(I.KEY, '/') AS ISSUE_HIERARCHY
        , LEVEL AS LEVEL_NUMBER
        , I.KEY
        FROM (
            SELECT
            JI.KEY
            , JI.ISSUE_TYPE
            , JPI.KEY AS PARENT_KEY
            FROM {{ source('CES_JIRA', 'ISSUE') }} AS JI
            LEFT JOIN {{ source('CES_JIRA', 'ISSUE') }} AS JPI
            ON JI.PARENT_ID = JPI.ID
        ) I
        START WITH I.ISSUE_TYPE = 10191
        CONNECT BY NULLIF(I.PARENT_KEY, '-') = PRIOR I.KEY
    ) H
    LEFT JOIN (
        SELECT 
        JI.KEY
        , JI.SUMMARY
        FROM {{ source('CES_JIRA', 'ISSUE') }} AS JI
    ) INI
    ON INI.KEY = REGEXP_SUBSTR(H.ISSUE_HIERARCHY, '[^/]+', 1, 1)
    LEFT JOIN (
        SELECT 
        JI.KEY
        , JI.DESCRIPTION
        , JI.SUMMARY
        FROM {{ source('CES_JIRA', 'ISSUE') }} AS JI
    ) L2
    ON L2.KEY = REGEXP_SUBSTR(H.ISSUE_HIERARCHY, '[^/]+', 1, 2)
) IH
ON I.KEY = IH.KEY
LEFT JOIN (
    SELECT
    JI.KEY
    , JI.ISSUE_TYPE
    , JPI.KEY AS PARENT_KEY
    , JPI.SUMMARY AS SUMMARY
    , JPI.DESCRIPTION AS DESCRIPTION
    FROM {{ source('CES_JIRA', 'ISSUE') }} AS JI
    LEFT JOIN {{ source('CES_JIRA', 'ISSUE') }} AS JPI
    ON JI.PARENT_ID = JPI.ID
    WHERE JI.ISSUE_TYPE NOT IN (10003, 10196, 10000, 10197, 10191)
) EPIC
ON I.KEY = EPIC.KEY
 
UNION ALL
 
SELECT
-1 AS MULTI_SCHEME_ID
, 'CES' AS SCHEME
, 'Internal' AS CLIENT_NAME
, '-' AS ID
, '-' AS KEY
, '-' AS INI_KEY
, '-' AS L2_KEY
, NULL AS ASSIGNEE
, NULL AS ISSUE_TYPE
, NULL AS SUMMARY
, NULL AS INI_SUMMARY
, NULL AS L2_SUMMARY
, NULL AS L2_DESCRIPTION
, NULL AS PRODUCT_CATEGORISATION
, NULL AS WORKSTREAM
, NULL AS WORK_TYPE
, NULL AS PROJECT_KEY
, NULL AS PROJECT_NAME
, SYSDATE() AS INSERT_DATE_UTC
)

SELECT
I.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, I.SCHEME AS SCHEME
, L.TEMPOWORKLOGID || '-' || L.JIRAWORKLOGID || '-' || L.ISSUEID AS ID
, L.TEMPOWORKLOGID AS TEMPOWORKLOGID
, L.JIRAWORKLOGID AS JIRA_WORKLOG_ID
, I.PROJECT_KEY AS PROJECT_KEY
, I.PROJECT_NAME AS PROJECT_NAME
, L.ISSUEID AS ISSUE_ID
, I.ISSUE_TYPE AS ISSUE_TYPE
, L.ISSUEKEY AS ISSUE_KEY
, I.SUMMARY AS ISSUE_SUMMARY
, I.WORKSTREAM AS WORKSTREAM
, I.CLIENT_NAME AS CLIENT_NAME
, I.PRODUCT_CATEGORISATION AS PRODUCT_CATEGORISATION
, I.WORK_TYPE AS WORK_TYPE
, I.L2_KEY AS EPIC_KEY
, I.L2_SUMMARY AS EPIC_SUMMARY
, I.L2_DESCRIPTION AS EPIC_DESCRIPTION
, I.INI_KEY AS INI_KEY
, I.INI_SUMMARY AS INI_SUMMARY
, L.ACCOUNTID AS TEMPOUSER_ACCOUNTID
, U.NAME AS TEMPOUSER_NAME
, M.TEAM_NAME AS TEMPO_TEAM
, CAST(CAST(L.STARTDATETIME AS TIMESTAMP) AS DATE) AS TEMPO_START_DATE
, TO_CHAR(L.STARTDATETIME, 'YYYYMMDD') AS TEMPO_START_DATE_KEY
, CAST(CAST(L.CREATEDAT AS TIMESTAMP) AS DATE) AS TEMPO_CREATED_AT
, TO_CHAR(L.CREATEDAT , 'YYYYMMDD') AS TEMPO_CREATED_AT_KEY
, CAST(CAST(L.UPDATEDAT AS TIMESTAMP) AS DATE) AS TEMPO_UPDATED_AT
, TO_CHAR(L.UPDATEDAT, 'YYYYMMDD') AS TEMPO_UPDATED_AT_KEY
, L.DESCRIPTION AS TEMPO_WORKLOG_DESCRIPTION
, L.TIMESPENTINSECONDS / 3600 AS TIMESPENTINHOUR
, CASE WHEN L.TIMESPENTINSECONDS / 3600 < 0.25 THEN 0.25 ELSE L.TIMESPENTINSECONDS / 3600 END AS MIN_TOTAL_TIME_SPENT_HOUR
, CASE WHEN NVL(I.MULTI_SCHEME_ID, 0) = 10002 THEN BRC.VICRETURN_RATE WHEN NVL(I.MULTI_SCHEME_ID, 0) = 100020001 THEN BRC.RETURNIT_RATE WHEN NVL(I.MULTI_SCHEME_ID, 0) = 10000 THEN BRC.COEX_RATE WHEN NVL(I.MULTI_SCHEME_ID, 0) = 10001 THEN BRC.WARRRL_RATE ELSE NULL END AS BILLING_RATE
, CASE WHEN L.TIMESPENTINSECONDS / 3600 < 0.25 THEN 0.25 ELSE L.TIMESPENTINSECONDS / 3600 END * CASE WHEN NVL(I.MULTI_SCHEME_ID, 0) = 10002 THEN BRC.VICRETURN_RATE WHEN NVL(I.MULTI_SCHEME_ID, 0) = 100020001 THEN BRC.RETURNIT_RATE WHEN NVL(I.MULTI_SCHEME_ID, 0) = 10000 THEN BRC.COEX_RATE WHEN NVL(I.MULTI_SCHEME_ID, 0) = 10001 THEN BRC.WARRRL_RATE ELSE NULL END AS BILLING_COST
, CRM.ZENDESK_SCHEME AS ZENDESK_SCHEME
, CRM.ZENDESK_TICKET_ID AS ZENDESK_TICKET_ID
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_TEMPO', 'TEMPO_WORKLOGS') }} AS L
LEFT JOIN JIRA_ISSUE I
ON L.ISSUEKEY = I.KEY
LEFT JOIN {{ source('CES_JIRA', 'USER') }} AS U
ON L.ACCOUNTID = U.ID
LEFT JOIN (
    SELECT
    M.TEAM_ID,
    T.NAME AS TEAM_NAME,
    M.ACCOUNTID,
    M.ACTIVE_ID,
    NVL(TO_CHAR(MIN(M.ACTIVE_SOURCE), 'YYYYMMDD'), TO_CHAR(MIN(M.LANDED_DATETIME_SYD), 'YYYYMMDD')) AS ACTIVE_FROM,
    TO_CHAR(MAX(M.LANDED_DATETIME_SYD), 'YYYYMMDD') AS ACTIVE_TO,
    FROM {{ source('CES_TEMPO', 'TEMPO_TEAM_MEMBERS_HISTORY') }} AS M
    LEFT JOIN {{ source('CES_TEMPO', 'TEMPO_TEAMS') }} AS T
    ON M.TEAM_ID = T.ID
    WHERE M.ACTIVE_ID IS NOT NULL
    GROUP BY ALL
) M
ON M.ACCOUNTID = L.ACCOUNTID
AND TO_CHAR(L.STARTDATETIME, 'YYYYMMDD') >= M.ACTIVE_FROM AND TO_CHAR(L.STARTDATETIME, 'YYYYMMDD') <= M.ACTIVE_TO
LEFT JOIN {{ source('CES_FINANCE', 'BILLING_RATE_CARD') }} AS BRC
ON REPLACE(LOWER(U.EMAIL), '@coexservices.com.au', '@cesystems.com') = REPLACE(LOWER(BRC.EMAIL), '@coexservices.com.au', '@cesystems.com')
AND TO_CHAR(CAST(L.STARTDATETIME AS DATE), 'YYYYMMDD') BETWEEN BRC.EFFECTIVE_FROM_YYYYMMDD AND NVL(BRC.EFFECTIVE_TO_YYYYMMDD, 99990101)
LEFT JOIN (
    SELECT 
    CM.JIRA_TICKET_ID
    , LISTAGG(CM.ZENDESK_TICKET_ID, ', ') WITHIN GROUP (ORDER BY CM.ZENDESK_TICKET_ID) AS ZENDESK_TICKET_ID
    , LISTAGG(DISTINCT C.SCHEME, ', ') WITHIN GROUP (ORDER BY C.SCHEME) AS ZENDESK_SCHEME
    FROM {{ ref('CRM_JIRA_MAPPING') }} AS CM
    LEFT JOIN {{ ref('CRM_INCIDENTS') }} AS C
    ON CM.ZENDESK_TICKET_ID = C.TICKET_ID
    GROUP BY CM.JIRA_TICKET_ID
) CRM
ON I.KEY = CRM.JIRA_TICKET_ID
WHERE L.CREATEDAT >= '2024-01-01'
QUALIFY ROW_NUMBER() OVER (PARTITION BY L.TEMPOWORKLOGID ORDER BY ACTIVE_ID DESC) = 1