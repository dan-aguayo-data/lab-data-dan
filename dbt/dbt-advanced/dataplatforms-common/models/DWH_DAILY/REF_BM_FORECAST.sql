SELECT
BM.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, BM.MONTH AS MONTH
, TO_DATE(BM.MONTH || '-01', 'YYYY-MM-DD') AS MONTH_FIRST_DAY
, REPLACE(BM.MONTH, '-', '') || '01' AS MONTH_KEY
, BM.NET_VOLUME AS NET_VOLUME
, BM.CRP_VOLUME AS CRP_VOLUME
, BM.MRF_VOLUME AS MRF_VOLUME
--, BM.MATERIAL_TYPE AS MATERIAL_TYPE
--, BM.REGION AS REGION
FROM
{{ source('LOOKUPS', 'BM_FORECAST') }} AS BM