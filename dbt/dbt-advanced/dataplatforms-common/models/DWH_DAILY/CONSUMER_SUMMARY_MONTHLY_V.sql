SELECT
NVL(CRP.MULTI_SCHEME_ID, C.MULTI_SCHEME_ID) AS MULTI_SCHEME_ID
, NVL(CRP.SCHEME, C.SCHEME) AS SCHEME
, NVL(CRP.MULTI_SCHEME_ID, C.MULTI_SCHEME_ID) || '-' || NVL(CRP.YEAR_MONTH, C.YEAR_MONTH) || '-' || NVL(CRP.CONSUMER_TYPE, C.CONSUMER_TYPE) AS ID
, REPLACE(NVL(CRP.YEAR_MONTH, C.YEAR_MONTH), '-', '') || '01' AS YEAR_MONTH_KEY
, NVL(CRP.CONSUMER_TYPE, C.CONSUMER_TYPE) AS CONSUMER_TYPE
, CRP.TOTAL_COLLECTION_QTY AS TOTAL_COLLECTION_QTY
, C.TOTAL_CONSUMERS AS TOTAL_CONSUMERS
FROM (
    SELECT
    H.MULTI_SCHEME_ID,
    H.SCHEME,
    D.YEAR_MONTH,
    H.CONSUMER_TYPE,
    SUM(H.COLLECTION_QTY) AS TOTAL_COLLECTION_QTY
    FROM {{ ref('CRP_COLLECTION_HDR') }} AS H
    INNER JOIN {{ ref('REF_DATE') }} AS D 
    ON H.TRANSACTION_DATE_KEY = D.KEY
    WHERE H.CONSUMER_TYPE IS NOT NULL
    GROUP BY
    H.MULTI_SCHEME_ID,
    H.SCHEME,
    D.YEAR_MONTH,
    H.CONSUMER_TYPE
) CRP 
FULL OUTER JOIN (
    SELECT
    C.MULTI_SCHEME_ID,
    C.SCHEME,
    D.YEAR_MONTH,
    C.CONSUMER_TYPE,
    COUNT(C.CONSUMER_ID) AS TOTAL_CONSUMERS
    FROM {{ ref('CONSUMER') }} AS C
    INNER JOIN {{ ref('REF_DATE') }} AS D 
    ON C.REGISTRATION_DATE_KEY = D.KEY
    WHERE C.CONSUMER_ID <> '-'
    GROUP BY
    C.MULTI_SCHEME_ID,
    C.SCHEME,
    D.YEAR_MONTH,
    C.CONSUMER_TYPE
) C
ON CRP.MULTI_SCHEME_ID = C.MULTI_SCHEME_ID
AND CRP.SCHEME = C.SCHEME
AND CRP.YEAR_MONTH = C.YEAR_MONTH
AND CRP.CONSUMER_TYPE = C.CONSUMER_TYPE