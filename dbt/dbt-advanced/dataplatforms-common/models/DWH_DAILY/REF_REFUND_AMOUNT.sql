SELECT
RP.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, RP.ID AS ID
, RP.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID
, MT.NAME AS MATERIAL_TYPE
, RP.REFUND_AMOUNT AS REFUND_AMOUNT
, CAST(RP.EFFECTIVE_FROM AS DATE) AS EFFECTIVE_FROM
, TO_CHAR(RP.EFFECTIVE_FROM, 'YYYYMMDD') AS EFFECTIVE_FROM_KEY
, CAST(RP.EFFECTIVE_TO AS DATE) AS EFFECTIVE_TO
, CASE WHEN FILTER.N = 1 THEN 'Y' ELSE 'N' END AS ACTIVE_FLAG
, RP.CREATED_BY AS CREATED_BY
, RP.CREATED_ON AS CREATED_ON_UTC
, RP.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, RP.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM', 'REFUND_AMOUNT_REFERENCE') }} AS RP
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON RP.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS MT
ON RP.MATERIAL_TYPE_ID = MT.ID
LEFT JOIN
    (SELECT
    P.ID
    ,ROW_NUMBER() OVER (PARTITION BY P.MULTI_SCHEME_ID, P.MATERIAL_TYPE_ID ORDER BY P.LAST_MODIFIED_ON DESC, P.EFFECTIVE_FROM DESC, P.EFFECTIVE_TO DESC) N
    FROM {{ source('CES_MSCM', 'REFUND_AMOUNT_REFERENCE') }} AS P
    WHERE CAST(CONVERT_TIMEZONE('UTC', 'Australia/Perth', SYSTIMESTAMP()) AS DATE)  BETWEEN NVL(P.EFFECTIVE_FROM,TO_DATE('01/JAN/1900','DD/MON/YYYY')) AND NVL(P.EFFECTIVE_TO,TO_DATE('01/JAN/9999','DD/MON/YYYY'))
    ) FILTER
ON RP.ID = FILTER.ID