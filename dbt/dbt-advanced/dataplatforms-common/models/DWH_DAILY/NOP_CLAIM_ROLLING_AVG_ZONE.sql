SELECT
N1.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, N1.PERIOD AS PERIOD
, N1.SITE_NUMBER AS SITE_NUMBER
, N1.ZONE AS ZONE
, N1.TOTAL_PERIOD_CLAIM_QTY AS TOTAL_PERIOD_CLAIM_QTY
, AVG(N2.TOTAL_PERIOD_CLAIM_QTY) AS AVG_CLAIM_QTY_1_MONTH_ROLLING
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ ref('NOP_CLAIM_ROLLING_BASE') }} AS N1
LEFT JOIN {{ ref('NOP_CLAIM_ROLLING_BASE') }} AS N2
ON N1.MULTI_SCHEME_ID = N2.MULTI_SCHEME_ID
AND N1.ZONE = N2.ZONE
AND N2.PERIOD 
BETWEEN CASE WHEN RIGHT(N1.PERIOD, 2) + 0 IN (1,2,3) THEN LEFT(N1.PERIOD, 4) - 1 || '-' || TO_CHAR(RIGHT(N1.PERIOD, 2) + 9, 'FM00') ELSE LEFT(N1.PERIOD, 5) || TO_CHAR(RIGHT(N1.PERIOD, 2) - 3, 'FM00') END 
AND N1.PERIOD
GROUP BY ALL