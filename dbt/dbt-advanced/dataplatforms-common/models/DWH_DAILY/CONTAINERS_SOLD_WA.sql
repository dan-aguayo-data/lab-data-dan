SELECT 
COALESCE(FRS.MULTI_SCHEME_ID, FC.MULTI_SCHEME_ID) AS MULTI_SCHEME_ID
, COALESCE(FRS.PERIOD, FC.MONTH) AS MONTH
, TO_DATE(REPLACE(CONCAT(TO_CHAR(COALESCE(FRS.PERIOD, FC.MONTH)),'-01'),'-','/'),'YYYY/MM/DD') AS MONTH_FIRST_DAY
, REPLACE(CONCAT(TO_CHAR(COALESCE(FRS.PERIOD, FC.MONTH)),'-01'),'-','') AS MONTH_KEY
, D.NUM_DAYS_MONTH  
, FC.NET_VOLUME AS FORECAST_NET_VOLUME
, FRS.NET_VOLUME As FRS_NET_VOLUME
, POP.REGION
, POP.POPULATION
, POP.POPULATION / (SUM(POP.POPULATION) OVER (PARTITION BY COALESCE(FRS.PERIOD, FC.MONTH))) AS POPULATION_PERCENTAGE
, CASE WHEN ADD_MONTHS(CURRENT_DATE(),-2) > TO_DATE(REPLACE(CONCAT(TO_CHAR(COALESCE(FRS.PERIOD, FC.MONTH)),'-01'),'-','/'),'YYYY/MM/DD') 
    THEN FRS.NET_VOLUME * (POP.POPULATION / (SUM(POP.POPULATION) OVER (PARTITION BY COALESCE(FRS.PERIOD, FC.MONTH))))
    WHEN ADD_MONTHS(CURRENT_DATE(),-1) > TO_DATE(REPLACE(CONCAT(TO_CHAR(COALESCE(FRS.PERIOD, FC.MONTH)),'-01'),'-','/'),'YYYY/MM/DD') 
    THEN FC.NET_VOLUME * (POP.POPULATION / (SUM(POP.POPULATION) OVER (PARTITION BY COALESCE(FRS.PERIOD, FC.MONTH))))
    ELSE ((FC.NET_VOLUME * (POP.POPULATION / (SUM(POP.POPULATION) OVER (PARTITION BY COALESCE(FRS.PERIOD, FC.MONTH))))) / D.NUM_DAYS_MONTH) * (DAY(CURRENT_DATE())-1) 
    END AS CONTAINERS_SOLD
FROM (
    SELECT
    COALESCE(S.MULTI_SCHEME_ID, E.MULTI_SCHEME_ID) AS MULTI_SCHEME_ID
    , COALESCE(S.PERIOD, E.PERIOD) AS PERIOD
    , NVL(SALES_VOL,0) - NVL(EXPORT_VOL,0) AS NET_VOLUME
    FROM (
        SELECT 
        MULTI_SCHEME_ID
        , PERIOD
        , SUM(VOLUME) AS SALES_VOL
        FROM {{ ref('BM_SALES_VOLUME') }}
        WHERE STATUS = 'INVOICED' 
        AND MULTI_SCHEME_ID = '10001'
        GROUP BY  
        MULTI_SCHEME_ID
        , PERIOD
    ) S
    FULL OUTER JOIN (
        SELECT 
        MULTI_SCHEME_ID
        , PERIOD
        , SUM(VOLUME) AS EXPORT_VOL 
        FROM {{ ref('BM_EXPORT_VOLUME') }}
        WHERE STATUS = 'INVOICED' 
        AND MULTI_SCHEME_ID = '10001'
        GROUP BY  
        MULTI_SCHEME_ID
        , PERIOD
    ) E
    ON S.MULTI_SCHEME_ID = E.MULTI_SCHEME_ID
    AND S.PERIOD = E.PERIOD
) FRS
FULL OUTER JOIN {{ source('LOOKUPS', 'BM_FORECAST') }} AS FC
ON FRS.MULTI_SCHEME_ID = FC.MULTI_SCHEME_ID
AND FRS.PERIOD = FC.MONTH
CROSS JOIN ( 
    SELECT REGION, SUM(POPULATION) AS POPULATION 
    FROM {{ ref('REF_LOCALITY_POA') }}
    WHERE STATE = 'Western Australia' 
    GROUP BY REGION
) POP
LEFT JOIN {{ ref('REF_DATE') }} AS D
ON D.DATE = TO_DATE(REPLACE(CONCAT(TO_CHAR(COALESCE(FRS.PERIOD, FC.MONTH)),'-01'),'-','/'),'YYYY/MM/DD')
WHERE CONVERT_TIMEZONE('UTC', 'Australia/Perth', SYSDATE()) >= TO_DATE(REPLACE(CONCAT(TO_CHAR(COALESCE(FRS.PERIOD, FC.MONTH)),'-01'),'-','/'),'YYYY/MM/DD')