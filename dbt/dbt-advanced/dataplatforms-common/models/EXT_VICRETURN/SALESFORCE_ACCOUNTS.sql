SELECT
C.SITE_NAME AS NAME
, 'NETWORK' AS RECORDTYPEID
, NULL AS ACCOUNTSOURCE
, C.ADDRESS_LINE_1 AS BILLINGSTREET
, C.SUBURB AS BILLINGCITY
, C.STATE AS BILLINGSTATE
, C.POSTCODE AS BILLINGPOSTALCODE
, C.COUNTRY AS BILLINGCOUNTRY
, C.X_COORDINATES AS BILLINGLATITUDE
, C.Y_COORDINATES AS BILLINGLONGITUDE
, NULL AS DESCRIPTION
, C.EMAIL AS EMAIL__C
, NULL AS NUMBEROFEMPLOYEES
, C.LGA AS LGA__C
, CASE WHEN C.SITE_NUMBER IN ('VAN29071001','VBN29072001','VCN29073001') THEN NULL WHEN C.MULTI_SCHEME_ID = 100020001 THEN 'VAN29071001' WHEN C.MULTI_SCHEME_ID = 100020002 THEN 'VBN29072001' WHEN C.MULTI_SCHEME_ID = 100020003 THEN 'VCN29073001' ELSE NULL END AS PARENTID
, C.PHONE_NUMBER AS PHONE
, C.SCHEME AS SCHEME__C
, C.ADDRESS_LINE_1 AS SHIPPINGSTREET
, C.SUBURB AS SHIPPINGCITY
, C.STATE AS SHIPPINGSTATE
, C.POSTCODE AS SHIPPINGPOSTALCODE
, C.COUNTRY AS SHIPPINGCOUNTRY
, C.X_COORDINATES AS SHIPPINGLATITUDE
, C.Y_COORDINATES AS SHIPPINGLONGITUDE
, C.SITE_NUMBER AS SITE_ID__C
, C.STATUS AS STATUS__C
, CASE WHEN C.SITE_NUMBER IN ('VCN29073001','VBN29072001','VAN29071001') THEN 'Network Operators' ELSE REPLACE(REPLACE(REPLACE(C.SITE_CATEGORY_PARENT, 'OTC', 'Site - OTC'), 'RVM_SITE', 'Site - RVM'), 'DEPOT_SITE', 'Site - Depot') END  AS TYPE
, C.WEB_SITE_URL AS WEBSITE
, C.ZONE AS ZONE__C
, CRP.COLLECTION_QTY_AVG_3_MONTHS AS X3_MONTH_MOVING_AVERAGE_VOLUME_UNITS__C
, CRP.COLLECTION_QTY_MTD AS MONTH_TO_DATE_VOLUME_UNITS__C
FROM 
{{ source('SCHEME_PARTICIPANT', 'CRP_SITES') }} AS C
LEFT JOIN (
    SELECT 
    H.SITE_NUMBER
     --CONTAINERS
    , ROUND(SUM(CASE WHEN H.TRANSACTION_DATE BETWEEN DATEADD('MONTH',-3,TRUNC(SYSDATE(), 'MONTH')) AND  TRUNC(SYSDATE(), 'MONTH') THEN H.COLLECTION_QTY ELSE 0 END) / 3) AS COLLECTION_QTY_AVG_3_MONTHS
    , SUM(CASE WHEN H.TRANSACTION_DATE BETWEEN TRUNC(SYSDATE(), 'MONTH') AND  SYSDATE() THEN H.COLLECTION_QTY ELSE 0 END) AS COLLECTION_QTY_MTD
    FROM {{ source('CRPO', 'CRP_COLLECTION_HDR') }} AS H
    GROUP BY H.SITE_NUMBER
) CRP
ON C.SITE_NUMBER= CRP.SITE_NUMBER
WHERE C.SITE_NUMBER NOT IN ('VCN29071002','VAN29071002')