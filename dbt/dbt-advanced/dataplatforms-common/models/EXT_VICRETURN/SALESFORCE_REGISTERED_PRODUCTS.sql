SELECT
TRIM(P.BARCODE) AS BARCODE__C
, NULL AS CREATEDBYID
, NULL AS LASTMODIFIEDBYID
, NULL AS OWNERID
, P.PRODUCT_NAME AS PRODUCT_NAME__C
, P.SUBMITTED_DATE AS REGISTERED_DATE__C
, P.PRODUCT_NAME AS NAME
, P.STATUS AS STATUS__C
, P.STATUS_CHANGE_TEXT AS STATUS_CHANGED_TEXT__C
, P.RECOMMENDATION AS RECOMENDATION
, P.RECOMMENDED_INFO AS RECOMENDED_INFO
, P.BM_SITE_NUMBER AS FIRST_SUPPLIER_NUMBER__C
, P.BM_SITE_NAME AS FIRST_SUPPLIER__C
, P.WITHDRAWN_OTHER_REASON AS WITHDRAWN_REASON
FROM 
{{ source('APPROVED_CONTAINER', 'REF_PRODUCT') }} AS P
WHERE P.SUBMITTED_SOURCE = 'VIC'
AND ((P.STATUS = 'APPROVED' AND P.ACTIVE_FLAG = 'Y' AND P.GO_LIVE_DATE <= SYSDATE()) OR (P.STATUS IN ('CANCELLED', 'EXPIRED', 'REJECTED', 'WITHDRAWN') AND P.EFFECTIVE_TO IS NULL))
QUALIFY ROW_NUMBER() OVER (PARTITION BY TRIM(P.BARCODE) ORDER BY P.LAST_MODIFIED_ON_UTC DESC) = 1