SELECT
CH.SITE_NUMBER AS ACCOUNT__C
, NULL AS CREATEDBYID
, CH.FRI_OPEN AS FRI_OPEN__C
, CH.FRI_CLOSE AS FRI_CLOSE__C
, NULL AS LASTMODIFIEDBYID
, CH.MON_CLOSE AS MON_CLOSE__C
, CH.MON_OPEN AS MON_OPEN__C
, CASE WHEN CH.OPEN_24_HOURS = 'Y' THEN TRUE ELSE FALSE END AS OPEN_24_HOURS__C
, NULL AS OWNERID
, CH.SAT_CLOSE AS SAT_CLOSE__C
, CH.SAT_OPEN AS SAT_OPEN__C
, CH.SCHEME AS SCHEME__C
, C.SITE_NAME AS NAME
, CH.SPECIAL_TRADING_HOURS AS SPECIAL_TRADING_HOURS__C
, CH.SUN_CLOSE AS SUN_CLOSE__C
, CH.SUN_OPEN AS SUN_OPEN__C
, CH.THU_CLOSE AS THURS_CLOSE__C
, CH.THU_OPEN AS THURS_OPEN__C
, CH.TUE_CLOSE AS TUES_CLOSE__C
, CH.TUE_OPEN AS TUES_OPEN__C
, CH.WED_CLOSE AS WED_CLOSE__C
, CH.WED_OPEN AS WED_OPEN__C
FROM 
{{ source('SCHEME_PARTICIPANT', 'CRP_SITE_HOURS') }} AS CH
LEFT JOIN {{ source('SCHEME_PARTICIPANT', 'CRP_SITES') }} AS C
ON CH.SITE_NUMBER = C.SITE_NUMBER
WHERE C.SITE_NUMBER NOT IN ('VCN29071002','VAN29071002')