SELECT
CONCAT(P.SCHEME, '-', TRIM(P.BARCODE)) AS ID
, NULL AS CREATEDBYID
, NULL AS LASTMODIFIEDBYID
, NULL AS OWNERID
, P.SCHEME AS SOURCE_REGISTRY__C
, TRIM(P.BARCODE) AS REGISTERED_PRODUCT__C
, P.LAST_MODIFIED_ON_UTC AS LAST_UPDATED_DATE__C
, NULL AS REGISTRATION__C
, P.CAPACITY_ML AS CAPACITY__C
, P.HEIGHT_MM AS HEIGHT_MM_C
, P.DIAMETER_MM AS LARGEST_DIAMETER_MM__C
, P.WEIGHT_GM AS WEIGHT_EMPTY__C
, P.MATERIAL_TYPE AS MATERIAL_TYPE__C
, P.CONTAINER_LID_MATERIAL_TYPE AS LID_MATERIAL_TYPE__C
, P.LABEL_TYPE AS LABEL_TYPE__C
, P.GLASS_COLOUR AS GLASS_COLOUR__C
, P.PET_COLOUR AS PET_COLOUR__C
, P.NATIONAL_REFUND_LOGO AS REFUND_MARK__C
, P.PRODUCT_GROUP AS PRODUCT_GROUP__C
, P.PRODUCT_GROUP_OTHER AS PRODUCT_GROUP_OTHER
, P.DECISION_DATE AS LAST_UPDATED__C
FROM 
{{ source('APPROVED_CONTAINER', 'REF_PRODUCT') }} AS P
WHERE P.SUBMITTED_SOURCE = 'VIC'
AND ((P.STATUS = 'APPROVED' AND P.ACTIVE_FLAG = 'Y' AND P.GO_LIVE_DATE <= SYSDATE()) OR (P.STATUS IN ('CANCELLED', 'EXPIRED', 'REJECTED', 'WITHDRAWN') AND P.EFFECTIVE_TO IS NULL))
QUALIFY ROW_NUMBER() OVER (PARTITION BY TRIM(P.BARCODE), P.BM_SITE_NUMBER ORDER BY P.LAST_MODIFIED_ON_UTC DESC) = 1