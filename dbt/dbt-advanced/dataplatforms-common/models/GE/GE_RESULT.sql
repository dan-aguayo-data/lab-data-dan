SELECT
  NVL(R.MULTI_SCHEME_ID, -1) AS MULTI_SCHEME_ID
, SCHEME.SCHEME AS SCHEME
, R.EXPECTATION_SUITE_NAME || '-' || TO_CHAR(R.VALIDATION_TIME, 'YYYYMMDDHH24MISSFF') AS ID
, R.EXPECTATION_SUITE_NAME AS EXPECTATION_SUITE_NAME
, CAST(CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, R.RUN_TIME) AS DATE) AS RUN_DATE
, TO_CHAR(CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, R.RUN_TIME), 'YYYYMMDD') AS RUN_DATE_KEY
, TO_CHAR(CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, R.RUN_TIME), 'HHMISS') AS RUN_TIME_KEY
, CAST(CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, R.VALIDATION_TIME) AS DATE) AS VALIDATION_DATE
, R.EXPECTATION_TYPE AS EXPECTATION_TYPE
, DECODE(R.EXPECTATION_TYPE, 'expect_column_values_to_not_be_null', 'Completeness', 'expect_column_values_to_be_unique', 'Uniqueness', 'expect_column_values_to_match_regex', 'Consistency', 'expect_column_values_to_match_like_pattern', 'Consistency', 'expect_column_values_to_not_match_like_pattern', 'Consistency') AS DQ_DIMENSION
, CASE WHEN TO_CHAR(RUN_TIME, 'YYYYMMDD') <= 20230514 THEN NULL ELSE SPLIT_PART(R.EXPECTATION_SUITE_NAME, '.', 1) END AS CHECK_DATABASE
, CASE WHEN TO_CHAR(RUN_TIME, 'YYYYMMDD') <= 20230514 THEN NULL ELSE SPLIT_PART(R.EXPECTATION_SUITE_NAME, '.', 2) END AS CHECK_SCHEMA
, CASE WHEN TO_CHAR(RUN_TIME, 'YYYYMMDD') <= 20230514 THEN SPLIT_PART(R.EXPECTATION_SUITE_NAME, '.', 1) ELSE SPLIT_PART(R.EXPECTATION_SUITE_NAME, '.', 3) END AS CHECK_TABLE
, CASE WHEN TO_CHAR(RUN_TIME, 'YYYYMMDD') <= 20230514 THEN SPLIT_PART(R.EXPECTATION_SUITE_NAME, '.', 1) ELSE SPLIT_PART(R.EXPECTATION_SUITE_NAME, '.', 1) || '.' || SPLIT_PART(R.EXPECTATION_SUITE_NAME, '.', 2) || '.' || SPLIT_PART(R.EXPECTATION_SUITE_NAME, '.', 3) END AS CHECK_TABLE_PATH
, R.CHECK_COLUMN AS CHECK_COLUMN
, R.ELEMENT_COUNT AS ELEMENT_COUNT
, R.MISSING_COUNT AS MISSING_COUNT
, NVL(R.ELEMENT_COUNT, 0) - NVL(R.MISSING_COUNT, 0) AS NONMISSING_COUNT
, R.UNEXPECTED_COUNT AS UNEXPECTED_COUNT
, R.UNEXPECTED_PERCENT / 100 AS UNEXPECTED_PERCENT
, R.UNEXPECTED_PERCENT_NONMISSING / 100 AS UNEXPECTED_PERCENT_NONMISSING
, R.UNEXPECTED_PERCENT_TOTAL / 100 AS UNEXPECTED_PERCENT_TOTAL
, R.SUCCESS AS SUCCESS
, R.SUCCESSFUL_EXPECTATIONS AS SUCCESSFUL_EXPECTATIONS
, R.UNSUCCESSFUL_EXPECTATIONS AS UNSUCCESSFUL_EXPECTATIONS
, R.REGEX AS REGEX
, R.LIKE_PATTERN AS LIKE_PATTERN
, R.UNEXPECTED_LIST AS UNEXPECTED_LIST
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_GREAT_EXPECTATIONS', 'GE_TEST_RESULTS') }} AS R
INNER JOIN {{ ref('REF_SCHEME') }} AS SCHEME
ON NVL(R.MULTI_SCHEME_ID, -1) = SCHEME.MULTI_SCHEME_ID