{{ source('CES_DRUPAL', 'PARTICIPANT_SITES') }} AS PS
INNER JOIN {{ source('CES_DRUPAL', 'PARTICIPANTS') }} AS P
ON P.PARTICIPANT_ID = PS.PARTICIPANT_ID AND P._FIVETRAN_DELETED = FALSE
LEFT JOIN (
    SELECT CR.PARTICIPANT_SITE_ID
        ,C.FIRST_NAME
        ,C.LAST_NAME
        ,C.EMAIL
        ,C.MOBILE_PHONE_NUMBER
        ,GREATEST(NVL(C.LAST_MODIFIED_ON, TO_DATE('01/01/1900', 'DD/MM/YYYY')), NVL(CR.LAST_MODIFIED_ON, TO_DATE('01/01/1900', 'DD/MM/YYYY'))) AS LAST_MODIFIED_ON_UTC
    FROM {{ source('CES_DRUPAL', 'CONTACTS') }} AS C
    LEFT JOIN {{ source('CES_DRUPAL', 'CONTACT_ROLES') }} AS CR
    ON C.CONTACT_ID = CR.CONTACT_ID AND CR._FIVETRAN_DELETED = FALSE
    WHERE CR.ASSIGNMENT_TYPE = 'SITE'
    AND CR.ROLE_TYPE_CODE = 'AUTHORISED_CONTACT_B2C' --Role type was changed to AUTHORISED_CONTACT_B2C instead of AUTHORISED for consumers since 15/02/2022
    AND C.PRIMARY = 1
    AND C.ACTIVE = 1
    AND CR.ACTIVE = 1
    AND C._FIVETRAN_DELETED = FALSE
    AND C.FIRST_NAME IS NOT NULL
    QUALIFY ROW_NUMBER() OVER (PARTITION BY CR.PARTICIPANT_SITE_ID ORDER BY NVL(CR.EFFECTIVE_END_DATE, TO_DATE('01/01/9999', 'DD/MM/YYYY')), CR.LAST_MODIFIED_ON DESC) = 1
) CC 
ON PS.PARTICIPANT_SITE_ID = CC.PARTICIPANT_SITE_ID
LEFT JOIN {{ ref('REF_STATE') }} AS STATE
ON STATE.STATE = PS.STATE 
LEFT JOIN {{ ref('REF_LOCALITY_SSC') }} AS SSC
ON PS.CITY_SUBURB = SSC.SUBURB
AND PS.POST_CODE = SSC.POSTCODE
AND STATE.STATE_NAME = SSC.STATE
LEFT JOIN {{ ref('REF_LOCALITY_POA') }} AS POA
ON PS.POST_CODE = POA.POSTCODE
AND STATE.STATE_NAME = POA.STATE
LEFT JOIN (
    SELECT 
    CCB.BOOKING_CONSUMER_ID,
    MAX(CCB.BOOKING_PICK_UP_DATE) AS LAST_CONTAINER_COLLECT_BOOKING_DATE
    FROM {{ ref('EXT_CONTAINER_COLLECT_BOOKINGS_COEX') }} AS CCB
    --WHERE SYSDATE() <= CCB.DATE
    GROUP BY CCB.BOOKING_CONSUMER_ID
) CCB
ON CCB.BOOKING_CONSUMER_ID = PS.SITE_NUMBER
LEFT JOIN (
    SELECT 
    G.GOAL_START_DATE,
    G.GOAL_END_DATE,
    G.PARTICIPANT_SITE_ID,
    G.GOAL_NAME,
    G.GOAL_AMOUNT,
    G.CREATED_ON AS GOAL_CREATED_ON,
    NVL(SUM(D.COLLECTION_QTY) OVER (PARTITION BY PS.SITE_NUMBER,G.GOAL_D_ID),0) AS COLLECTION_QTY,
    SUM(CASE WHEN D.MATERIAL_TYPE_ID IN ('PETCOLORED','PETCLEAR','HDPE') THEN D.COLLECTION_QTY ELSE 0 END) OVER (PARTITION BY PS.SITE_NUMBER,G.GOAL_D_ID) AS COLLECTION_QTY_PLASTIC,
    SUM(CASE WHEN D.MATERIAL_TYPE_ID ='GLASSMIXED' THEN D.COLLECTION_QTY ELSE 0 END) OVER (PARTITION BY PS.SITE_NUMBER,G.GOAL_D_ID) AS COLLECTION_QTY_GLASS,
    SUM(CASE WHEN D.MATERIAL_TYPE_ID ='ALUMINIUM' THEN D.COLLECTION_QTY ELSE 0 END) OVER (PARTITION BY PS.SITE_NUMBER,G.GOAL_D_ID) AS COLLECTION_QTY_ALUMINIUM,
    SUM(CASE WHEN D.MATERIAL_TYPE_ID IN ('PETCOLORED','PETCLEAR','HDPE') THEN D.COLLECTION_QTY/35 ELSE 0 END) OVER (PARTITION BY PS.SITE_NUMBER,G.GOAL_D_ID) AS COLLECTION_QTY_JUMPERS,
    SUM(CASE WHEN D.MATERIAL_TYPE_ID ='GLASSMIXED' THEN D.COLLECTION_QTY/48 ELSE 0 END) OVER (PARTITION BY PS.SITE_NUMBER,G.GOAL_D_ID) AS COLLECTION_QTY_WINDSHIELDS,
    SUM(CASE WHEN D.MATERIAL_TYPE_ID ='ALUMINIUM' THEN D.COLLECTION_QTY/67 ELSE 0 END) OVER (PARTITION BY PS.SITE_NUMBER,G.GOAL_D_ID) AS COLLECTION_QTY_BIKES
    FROM {{ source('CES_DRUPAL', 'CFC_GOAL') }} AS G
    INNER JOIN {{ source('CES_DRUPAL', 'PARTICIPANT_SITES') }} AS PS
    ON G.PARTICIPANT_SITE_ID = PS.PARTICIPANT_SITE_ID AND PS._FIVETRAN_DELETED = FALSE
    INNER JOIN {{ source('CES_DRUPAL', 'PARTICIPANTS') }} AS P 
    ON P.PARTICIPANT_ID = PS.PARTICIPANT_ID AND P._FIVETRAN_DELETED = FALSE
    LEFT JOIN {{ ref('CRP_COLLECTION_HDR') }} AS H
    ON PS.SITE_NUMBER = H.CONSUMER_ID 
    AND H.TRANSACTION_DATE BETWEEN G.GOAL_START_DATE AND G.GOAL_END_DATE
    LEFT JOIN {{ ref('CRP_COLLECTION_DTL') }} AS D
    ON D.TRANSACTION_ID = H.TRANSACTION_ID AND D.MATERIAL_TYPE_ID <> 'INELIGIBLE'
    WHERE G.GOAL_MEMBER_TYPE = 0 AND G._FIVETRAN_DELETED = FALSE  --ACTIVE AND INDIVIDUALS
    AND PS.MULTI_SCHEME_ID = 10000 --COEX
    AND PS.TAXONOMY_TYPE_ID = 'Consumer'
    AND P.PARTICIPANT_GROUP = 'IND_CONSUMER'--Just send to individual customers
    --AND (LOWER(PS.SITE_NAME) NOT LIKE '%pvt%' AND LOWER(PS.SITE_NAME) NOT LIKE'% test %')  --Test sites
    AND PS.SITE_NUMBER <> 'C10625269' --2 customer with same info (exclude customer without transactions)
    AND PS.STATE = 'QLD' --Customer address is of another state
    AND TRUNC(G.GOAL_START_DATE, 'DAY') <> TRUNC(G.GOAL_END_DATE, 'DAY')

    --********* UAT *********--
    {% if target.name.upper() != 'PROD' %}
    QUALIFY ROW_NUMBER() OVER (PARTITION BY G.PARTICIPANT_SITE_ID ORDER BY G.GOAL_D_ID, G.LAST_MODIFIED_ON DESC) = 1 --IF 2 ACTIVE GOALS EXIST
    {%- else -%}
    QUALIFY ROW_NUMBER() OVER (PARTITION BY G.PARTICIPANT_SITE_ID ORDER BY G.GOAL_START_DATE, G.LAST_MODIFIED_ON DESC) = 1 --IF 2 ACTIVE GOALS EXIST
    {% endif %}
    --********* UAT *********--

) G --GOAL STAT
ON G.PARTICIPANT_SITE_ID = PS.PARTICIPANT_SITE_ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON PS.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN (
  SELECT DISTINCT
  A.POST_CODE,
  A.DAY_OF_SERVICE,
  IFNULL(A.SUBURB_NAME,A.ABS_SUBURB) AS SUBURB_NAME
  FROM {{ source('COEX_AGILOFT', 'AG_SUBURB') }} AS A
  WHERE STATUS = '05 LIVE') BS
ON BS.POST_CODE =  PS.POST_CODE
AND BS.SUBURB_NAME =  PS.CITY_SUBURB
LEFT JOIN (
    SELECT 
    C.*
    , FIRST_VALUE(C.NOMINATED_CHARITY) OVER (PARTITION BY C.CONSUMER_ID ORDER BY CASE WHEN C.NOMINATED_CHARITY IS NULL THEN 0 ELSE C.REFUND_AMOUNT_CHARITY_LAST_12_MONTHS END DESC) AS TOP_CHARITY_LAST_12_MONTH
    , FIRST_VALUE(C.NOMINATED_CHARITY) OVER (PARTITION BY C.CONSUMER_ID ORDER BY CASE WHEN C.NOMINATED_CHARITY IS NULL THEN 0 ELSE C.REFUND_AMOUNT_CHARITY_LAST_1_MONTHS END DESC) AS TOP_CHARITY_LAST_1_MONTH
    , FIRST_VALUE(C.CRP_SITE_NAME) OVER (PARTITION BY C.CONSUMER_ID ORDER BY C.MOST_RP_VISITED_LAST_12_MONTHS DESC) AS MOST_VISITED_RP
    , FIRST_VALUE(C.CRP_SITE_NAME) OVER (PARTITION BY C.CONSUMER_ID ORDER BY C.TRANSACTION_DATE_UTC DESC) AS LAST_VISITED_RP
    FROM
            (SELECT 
             --JOINING FIELDS
            H.CONSUMER_ID
            , H.SITE_NAME AS CRP_SITE_NAME 
            , PTT.PARTICIPANT_NAME  AS NOMINATED_CHARITY
            , P.PARTICIPANT_NAME AS TRADING_NAME
            , CASE WHEN D.MATERIAL_TYPE_ID IN ('LQDPAPERBRD','ALUMINIUM','GLASSMIXED') THEN D.MATERIAL_TYPE_ID WHEN D.MATERIAL_TYPE_ID IN ('PETCOLORED','PETCLEAR','HDPE') THEN 'PET' ELSE NULL END AS MATERIAL_TYPE_ID_CATEGORISED
            , H.TRANSACTION_DATE_UTC
             --TRANSACTIONS
            , COUNT(DISTINCT H.TRANSACTION_ID) OVER (PARTITION BY H.CONSUMER_ID) AS TRANSACTIONS_LIFETIME
            , COUNT(DISTINCT (CASE WHEN YEAR(H.TRANSACTION_DATE_UTC) = 2021 THEN H.TRANSACTION_ID ELSE NULL END)) OVER (PARTITION BY H.CONSUMER_ID) AS TRANSACTIONS_2021
            , COUNT(DISTINCT (CASE WHEN YEAR(H.TRANSACTION_DATE_UTC) = 2022 THEN H.TRANSACTION_ID ELSE NULL END)) OVER (PARTITION BY H.CONSUMER_ID) AS TRANSACTIONS_2022
            , COUNT(DISTINCT (CASE WHEN H.TRANSACTION_DATE_UTC BETWEEN DATEADD('MONTH',-12,SYSDATE()) AND  SYSDATE() THEN H.TRANSACTION_ID ELSE NULL END)) OVER (PARTITION BY H.CONSUMER_ID) AS TRANSACTIONS_LAST_12_MONTHS
