SELECT
NVL(UUID.MULTI_SCHEME_ID, -1) AS MULTI_SCHEME_ID
, NVL(SCHEME.NAME, 'CES') AS SCHEME
, C.ID AS ID
, C.USER_ID AS USER_ID
, C.EXTERNAL_USER_ID AS EXTERNAL_USER_ID
, NVL(UUID.CONSUMER_ID, '-') AS CONSUMER_ID
, CONVERT_TIMEZONE('UTC', COALESCE(SCHEME.TIMEZONE, C.TIMEZONE, 'Australia/Queensland'), TO_TIMESTAMP(C.TIME)) AS CONVERSION_DATE
, TO_CHAR(CONVERT_TIMEZONE('UTC', COALESCE(SCHEME.TIMEZONE, C.TIMEZONE, 'Australia/Queensland'), TO_TIMESTAMP(C.TIME)), 'YYYYMMDD') AS CONVERSION_DATE_KEY
, C.APP_GROUP_ID AS APP_GROUP_ID
, C.CANVAS_ID AS CANVAS_ID
, C.IN_CONTROL_GROUP AS IN_CONTROL_GROUP
, CC.COLLECTION_QTY_IN_CONVERSION_MONTH AS COLLECTION_QTY_IN_CONVERSION_MONTH
, C.CREATED_ON_UTC AS CREATED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM (
    SELECT
    M.ID
    , M.USER_ID
    , M.EXTERNAL_USER_ID
    , M.TIME
    , M.TIMEZONE
    , NVL(M.APP_GROUP_ID, '-') AS APP_GROUP_ID
    , NVL(M.CANVAS_ID, '-') AS CANVAS_ID
    , NVL(E.IN_CONTROL_GROUP, 'FALSE') AS IN_CONTROL_GROUP
    , CONVERT_TIMEZONE('UTC', M.SF_CREATED_AT) AS CREATED_ON_UTC
    FROM {{ source('BRAZE', 'USERS_CANVAS_CONVERSION_SHARED') }} AS M
    LEFT JOIN {{ source('BRAZE', 'USERS_CANVAS_ENTRY_SHARED') }} AS E
    ON M.USER_ID = E.USER_ID
    AND M.CANVAS_ID = E.CANVAS_ID
    AND M.TIME >= E.TIME
    QUALIFY ROW_NUMBER() OVER (PARTITION BY M.ID ORDER BY E.TIME DESC) = 1
) C
LEFT JOIN (
    SELECT
    ID.MULTI_SCHEME_ID
    , ID.CONSUMER_NUMBER AS CONSUMER_ID
    , ID.MARKETING_UUID
    FROM {{ source('CES_DRUPAL', 'CFC_UUID') }} AS ID
    QUALIFY ROW_NUMBER() OVER (PARTITION BY ID.MARKETING_UUID ORDER BY ID.CFC_UUID_ID DESC) = 1
) UUID
ON C.EXTERNAL_USER_ID = UUID.MARKETING_UUID
LEFT JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON UUID.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN (
    SELECT
    H.CONSUMER_ID
    , REPLACE(D.YEAR_MONTH, '-') || '01' AS YEAR_MONTH_KEY
    , SUM(H.COLLECTION_QTY) AS COLLECTION_QTY_IN_CONVERSION_MONTH
    FROM {{ ref('CRP_COLLECTION_HDR') }} AS H
    LEFT JOIN {{ ref('REF_DATE') }} AS D
    ON H.TRANSACTION_DATE_KEY = D.KEY
    WHERE H.CONSUMER_ID <> '-'
    GROUP BY ALL
) CC
ON UUID.CONSUMER_ID = CC.CONSUMER_ID
AND TO_CHAR(CONVERT_TIMEZONE('UTC', COALESCE(SCHEME.TIMEZONE, C.TIMEZONE, 'Australia/Queensland'), TO_TIMESTAMP(C.TIME)), 'YYYYMM01') = CC.YEAR_MONTH_KEY