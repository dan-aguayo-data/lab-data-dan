SELECT
NVL(UUID.MULTI_SCHEME_ID, -1) AS MULTI_SCHEME_ID
, NVL(SCHEME.NAME, 'CES') AS SCHEME
, S.ID AS ID
, S.USER_ID AS USER_ID
, S.EXTERNAL_USER_ID AS EXTERNAL_USER_ID
, NVL(UUID.CONSUMER_ID, '-') AS CONSUMER_ID
, NVL(CASE WHEN B2B."external_id" IS NOT NULL THEN 'B2B Customer' ELSE NULL END, R_TT.VALUE) AS CONSUMER_TYPE
, CONVERT_TIMEZONE('UTC', COALESCE(SCHEME.TIMEZONE, S.TIMEZONE, 'Australia/Queensland'), TO_TIMESTAMP(S.TIME)) AS SUBSCRIPTION_CHANGE_DATE
, TO_CHAR(CONVERT_TIMEZONE('UTC', COALESCE(SCHEME.TIMEZONE, S.TIMEZONE, 'Australia/Queensland'), TO_TIMESTAMP(S.TIME)), 'YYYYMMDD') AS SUBSCRIPTION_CHANGE_DATE_KEY
, S.CAMPAIGN_ID AS CAMPAIGN_ID
, S.CANVAS_ID AS CANVAS_ID
, S.CHANNEL AS CHANNEL
, S.EMAIL AS EMAIL
, S.PHONE AS PHONE
, S.SUBSCRIPTION_STATUS AS SUBSCRIPTION_STATUS
, S.SUBSCRIPTION_GROUP_API_ID AS SUBSCRIPTION_GROUP_API_ID
, S.CREATED_ON_UTC AS CREATED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM (
    SELECT
    M.ID
    , M.USER_ID
    , M.EXTERNAL_USER_ID
    , M.TIME
    , M.TIMEZONE
    , NVL(M.CAMPAIGN_ID, '-') AS CAMPAIGN_ID
    , NVL(M.CANVAS_ID, '-') AS CANVAS_ID
    , M.CHANNEL
    , M.EMAIL_ADDRESS AS EMAIL
    , M.PHONE_NUMBER AS PHONE
    , M.SUBSCRIPTION_STATUS
    , M.SUBSCRIPTION_GROUP_API_ID
    , CONVERT_TIMEZONE('UTC', M.SF_CREATED_AT) AS CREATED_ON_UTC
    FROM {{ source('BRAZE', 'USERS_BEHAVIORS_SUBSCRIPTIONGROUP_STATECHANGE_SHARED') }} AS M
 
    UNION ALL
 
    SELECT
    M.ID
    , M.USER_ID
    , M.EXTERNAL_USER_ID
    , M.TIME
    , M.TIMEZONE
    , NVL(M.CAMPAIGN_ID, '-') AS CAMPAIGN_ID
    , NVL(M.CANVAS_ID, '-') AS CANVAS_ID
    , M.CHANNEL
    , M.EMAIL_ADDRESS AS EMAIL
    , NULL AS PHONE
    , M.SUBSCRIPTION_STATUS
    , NULL AS SUBSCRIPTION_GROUP_API_ID
    , CONVERT_TIMEZONE('UTC', M.SF_CREATED_AT) AS CREATED_ON_UTC
    FROM {{ source('BRAZE', 'USERS_BEHAVIORS_SUBSCRIPTION_GLOBALSTATECHANGE_SHARED') }} AS M
) S
LEFT JOIN (
    SELECT
    ID.MULTI_SCHEME_ID
    , ID.CONSUMER_NUMBER AS CONSUMER_ID
    , ID.MARKETING_UUID
    FROM {{ source('CES_DRUPAL', 'CFC_UUID') }} AS ID
    QUALIFY ROW_NUMBER() OVER (PARTITION BY ID.MARKETING_UUID ORDER BY ID.CFC_UUID_ID DESC) = 1
) UUID
ON S.EXTERNAL_USER_ID = UUID.MARKETING_UUID
LEFT JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON UUID.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS
ON UUID.CONSUMER_ID = PS.SITE_NUMBER
LEFT JOIN {{ source('CES_MSCM', 'SCHEME_REF_CODES') }} AS R_TT
ON PS.TAXONOMY_TYPE_ID = R_TT.SCHEME_REF_CODES_ID
LEFT JOIN {{ ref('BRAZE_B2B_CUSTOMERS') }} AS B2B
ON S.EXTERNAL_USER_ID = B2B."external_id"