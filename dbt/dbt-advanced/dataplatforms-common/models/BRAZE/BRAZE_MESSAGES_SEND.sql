SELECT
NVL(UUID.MULTI_SCHEME_ID, -1) AS MULTI_SCHEME_ID
, NVL(SCHEME.NAME, 'CES') AS SCHEME
, S.ID AS ID
, S.USER_ID AS USER_ID
, S.EXTERNAL_USER_ID AS EXTERNAL_USER_ID
, NVL(UUID.CONSUMER_ID, '-') AS CONSUMER_ID
, CONVERT_TIMEZONE('UTC', COALESCE(SCHEME.TIMEZONE, S.TIMEZONE, 'Australia/Queensland'), TO_TIMESTAMP(S.TIME)) AS SEND_DATE
, TO_CHAR(CONVERT_TIMEZONE('UTC', COALESCE(SCHEME.TIMEZONE, S.TIMEZONE, 'Australia/Queensland'), TO_TIMESTAMP(S.TIME)), 'YYYYMMDD') AS SEND_DATE_KEY
, S.APP_GROUP_ID AS APP_GROUP_ID
, S.DISPATCH_ID AS DISPATCH_ID
, S.CAMPAIGN_ID AS CAMPAIGN_ID
, S.CANVAS_ID AS CANVAS_ID
, S.MESSAGE_VARIATION_API_ID AS MESSAGE_VARIATION_API_ID
, S.CHANNEL AS CHANNEL
, S.EMAIL AS EMAIL
, S.PHONE AS PHONE
, S.CREATED_ON_UTC AS CREATED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM (
    SELECT
    M.ID
    , M.USER_ID
    , M.EXTERNAL_USER_ID
    , M.TIME
    , M.TIMEZONE
    , NVL(M.APP_GROUP_ID, '-') AS APP_GROUP_ID
    , NVL(M.DISPATCH_ID, '-') AS DISPATCH_ID
    , NVL(M.CAMPAIGN_ID, '-') AS CAMPAIGN_ID
    , NVL(M.CANVAS_ID, '-') AS CANVAS_ID
    , NVL(M.MESSAGE_VARIATION_API_ID, '-') AS MESSAGE_VARIATION_API_ID
    , 'email' AS CHANNEL
    , M.EMAIL_ADDRESS AS EMAIL
    , NULL AS PHONE
    , CONVERT_TIMEZONE('UTC', M.SF_CREATED_AT) AS CREATED_ON_UTC
    FROM {{ source('BRAZE', 'USERS_MESSAGES_EMAIL_SEND_SHARED') }} AS M
 
    UNION ALL
 
    SELECT
    M.ID
    , M.USER_ID
    , M.EXTERNAL_USER_ID
    , M.TIME
    , M.TIMEZONE
    , NVL(M.APP_GROUP_ID, '-') AS APP_GROUP_ID
    , NVL(M.DISPATCH_ID, '-') AS DISPATCH_ID
    , NVL(M.CAMPAIGN_ID, '-') AS CAMPAIGN_ID
    , NVL(M.CANVAS_ID, '-') AS CANVAS_ID
    , NVL(M.MESSAGE_VARIATION_API_ID, '-') AS MESSAGE_VARIATION_API_ID
    , 'sms' AS CHANNEL
    , NULL AS EMAIL
    , M.TO_PHONE_NUMBER AS PHONE
    , CONVERT_TIMEZONE('UTC', M.SF_CREATED_AT) AS CREATED_ON_UTC
    FROM {{ source('BRAZE', 'USERS_MESSAGES_SMS_SEND_SHARED') }} AS M
 
    UNION ALL
 
    SELECT
    M.ID
    , M.USER_ID
    , M.EXTERNAL_USER_ID
    , M.TIME
    , M.TIMEZONE
    , NVL(M.APP_GROUP_ID, '-') AS APP_GROUP_ID
    , NVL(M.DISPATCH_ID, '-') AS DISPATCH_ID
    , NVL(M.CAMPAIGN_ID, '-') AS CAMPAIGN_ID
    , NVL(M.CANVAS_ID, '-') AS CANVAS_ID
    , NVL(M.MESSAGE_VARIATION_API_ID, '-') AS MESSAGE_VARIATION_API_ID
    , 'push' AS CHANNEL
    , NULL AS EMAIL
    , NULL AS PHONE
    , CONVERT_TIMEZONE('UTC', M.SF_CREATED_AT) AS CREATED_ON_UTC
    FROM {{ source('BRAZE', 'USERS_MESSAGES_PUSHNOTIFICATION_SEND_SHARED') }} AS M
) S
LEFT JOIN (
    SELECT
    ID.MULTI_SCHEME_ID
    , ID.CONSUMER_NUMBER AS CONSUMER_ID
    , ID.MARKETING_UUID
    FROM {{ source('CES_DRUPAL', 'CFC_UUID') }} AS ID
    QUALIFY ROW_NUMBER() OVER (PARTITION BY ID.MARKETING_UUID ORDER BY ID.CFC_UUID_ID DESC) = 1
) UUID
ON S.EXTERNAL_USER_ID = UUID.MARKETING_UUID
LEFT JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON UUID.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID