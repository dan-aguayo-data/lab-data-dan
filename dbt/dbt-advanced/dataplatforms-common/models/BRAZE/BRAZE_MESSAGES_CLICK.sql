SELECT
B1.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, B1.SCHEME AS SCHEME
, B1.ID AS ID
, B1.USER_ID AS USER_ID
, B1.EXTERNAL_USER_ID AS EXTERNAL_USER_ID
, B1.CONSUMER_ID AS CONSUMER_ID
, B1.CLICK_DATE AS CLICK_DATE
, B1.CLICK_DATE_KEY AS CLICK_DATE_KEY
, B1.APP_GROUP_ID AS APP_GROUP_ID
, B1.DISPATCH_ID AS DISPATCH_ID
, B1.CAMPAIGN_ID AS CAMPAIGN_ID
, B1.CANVAS_ID AS CANVAS_ID
, B1.MESSAGE_VARIATION_API_ID AS MESSAGE_VARIATION_API_ID
, B1.CHANNEL AS CHANNEL
, B1.EMAIL AS EMAIL
, B1.CLICK_SEQUENCE AS CLICK_SEQUENCE
, CAST(B1.CLICK_DATE AS DATE) - CAST(B2.CLICK_DATE AS DATE) AS DAYS_DIFF
, CASE WHEN B1.CLICK_SEQUENCE = 1 OR DAYS_DIFF >= 7 THEN 1 ELSE 0 END AS UNIQUE_CLICK_FLAG
, B1.CREATED_ON_UTC AS CREATED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ ref('BRAZE_MESSAGES_CLICK_BASE') }} AS B1
LEFT JOIN {{ ref('BRAZE_MESSAGES_CLICK_BASE') }} AS B2
ON B1.USER_ID = B2.USER_ID
AND B1.EMAIL = B2.EMAIL
AND B1.APP_GROUP_ID = B2.APP_GROUP_ID
AND B1.DISPATCH_ID = B2.DISPATCH_ID
AND B1.CAMPAIGN_ID = B2.CAMPAIGN_ID
AND B1.CANVAS_ID = B2.CANVAS_ID
AND B1.MESSAGE_VARIATION_API_ID = B2.MESSAGE_VARIATION_API_ID
AND B1.CHANNEL = B2.CHANNEL
AND B1.CLICK_SEQUENCE = B2.CLICK_SEQUENCE + 1