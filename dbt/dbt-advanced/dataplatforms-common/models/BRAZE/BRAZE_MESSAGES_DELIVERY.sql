SELECT
NVL(UUID.MULTI_SCHEME_ID, -1) AS MULTI_SCHEME_ID
, NVL(SCHEME.NAME, 'CES') AS SCHEME
, D.ID AS ID
, D.USER_ID AS USER_ID
, D.EXTERNAL_USER_ID AS EXTERNAL_USER_ID
, NVL(UUID.CONSUMER_ID, '-') AS CONSUMER_ID
, CONVERT_TIMEZONE('UTC', COALESCE(SCHEME.TIMEZONE, D.TIMEZONE, 'Australia/Queensland'), TO_TIMESTAMP(D.TIME)) AS DELIVERY_DATE
, TO_CHAR(CONVERT_TIMEZONE('UTC', COALESCE(SCHEME.TIMEZONE, D.TIMEZONE, 'Australia/Queensland'), TO_TIMESTAMP(D.TIME)), 'YYYYMMDD') AS DELIVERY_DATE_KEY
, D.APP_GROUP_ID AS APP_GROUP_ID
, D.DISPATCH_ID AS DISPATCH_ID
, D.CAMPAIGN_ID AS CAMPAIGN_ID
, D.CANVAS_ID AS CANVAS_ID
, D.MESSAGE_VARIATION_API_ID AS MESSAGE_VARIATION_API_ID
, D.CHANNEL AS CHANNEL
, D.EMAIL AS EMAIL
, D.PHONE AS PHONE
, D.CREATED_ON_UTC AS CREATED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM (
    SELECT
    M.ID
    , M.USER_ID
    , M.EXTERNAL_USER_ID
    , M.TIME
    , M.TIMEZONE
    , NVL(M.APP_GROUP_ID, '-') AS APP_GROUP_ID
    , NVL(M.DISPATCH_ID, '-') AS DISPATCH_ID
    , NVL(M.CAMPAIGN_ID, '-') AS CAMPAIGN_ID
    , NVL(M.CANVAS_ID, '-') AS CANVAS_ID
    , NVL(M.MESSAGE_VARIATION_API_ID, '-') AS MESSAGE_VARIATION_API_ID
    , 'email' AS CHANNEL
    , M.EMAIL_ADDRESS AS EMAIL
    , NULL AS PHONE
    , CONVERT_TIMEZONE('UTC', M.SF_CREATED_AT) AS CREATED_ON_UTC
    FROM {{ source('BRAZE', 'USERS_MESSAGES_EMAIL_DELIVERY_SHARED') }} AS M
) D
LEFT JOIN (
    SELECT
    ID.MULTI_SCHEME_ID
    , ID.CONSUMER_NUMBER AS CONSUMER_ID
    , ID.MARKETING_UUID
    FROM {{ source('CES_DRUPAL', 'CFC_UUID') }} AS ID
    QUALIFY ROW_NUMBER() OVER (PARTITION BY ID.MARKETING_UUID ORDER BY ID.CFC_UUID_ID DESC) = 1
) UUID
ON D.EXTERNAL_USER_ID = UUID.MARKETING_UUID
LEFT JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON UUID.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID