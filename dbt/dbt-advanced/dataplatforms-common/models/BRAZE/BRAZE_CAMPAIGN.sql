SELECT
-1 AS MULTI_SCHEME_ID
, 'CES' AS SCHEME
, C.ID AS ID
, C.NAME AS NAME
, LS.LAST_SEND_DATE AS LAST_SEND_DATE
, MIN(TO_TIMESTAMP(C.TIME)) OVER (PARTITION BY C.ID) AS CREATED_ON_UTC
, MAX(TO_TIMESTAMP(C.TIME)) OVER (PARTITION BY C.ID) AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('BRAZE', 'CHANGELOGS_CAMPAIGN_SHARED') }} AS C
LEFT JOIN (
    SELECT
    S.CAMPAIGN_ID
    , MAX(SEND_DATE) AS LAST_SEND_DATE
    FROM {{ ref('BRAZE_MESSAGES_SEND') }} AS S
    WHERE S.CAMPAIGN_ID IS NOT NULL
    GROUP BY ALL
) LS
ON C.ID = LS.CAMPAIGN_ID
QUALIFY ROW_NUMBER() OVER (PARTITION BY C.ID ORDER BY C.TIME DESC) = 1
 
UNION ALL
 
SELECT
-1 AS MULTI_SCHEME_ID
, 'CES' AS SCHEME
, '-' AS ID
, NULL AS NAME
, NULL AS LAST_SEND_DATE
, TO_DATE('01/01/2021', 'DD/MM/YYYY') AS CREATED_ON_UTC
, TO_DATE('01/01/2021', 'DD/MM/YYYY') AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC