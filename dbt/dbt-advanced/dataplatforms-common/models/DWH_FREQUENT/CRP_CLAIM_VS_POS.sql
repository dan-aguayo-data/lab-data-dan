SELECT
NVL(C.MULTI_SCHEME_ID, CLAIM.MULTI_SCHEME_ID) AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, NVL(C.SITE_NUMBER, CLAIM.SITE_NUMBER) AS SITE_NUMBER
, PS.SITE_NAME AS SITE_NAME
, P.PARTICIPANT_NUMBER AS SUPPLIER_NUMBER
, P.PARTICIPANT_NAME AS SUPPLIER_NAME
, NVL(C.PERIOD_KEY, CLAIM.PERIOD_KEY) AS PERIOD_KEY
, NVL(C.ENTRY_TYPE, CLAIM.ENTRY_TYPE) AS ENTRY_TYPE
, NVL(CLAIM.STATUS, 'Not Claim') AS STATUS
, NVL(C.PAYMENT_METHOD, CLAIM.PAYMENT_METHOD) AS PAYMENT_METHOD
, NVL(C.MATERIAL_TYPE_ID, CLAIM.MATERIAL_TYPE_ID) AS MATERIAL_TYPE_ID
, CLAIM.CLAIM_QTY AS CLAIM_QTY
, CLAIM.CLAIM_GROSS_AMOUNT AS CLAIM_GROSS_AMOUNT
, C.POS_QTY AS POS_QTY
, C.POS_GROSS_AMOUNT AS POS_GROSS_AMOUNT
, SYSDATE() AS INSERT_DATE_UTC
FROM (
  SELECT
  H.MULTI_SCHEME_ID
  , WS.KEY AS PERIOD_KEY
  , H.CRP_ID AS SITE_NUMBER
  , H.ENTRY_TYPE
  , H.STATUS
  , CASE WHEN D.WHO_PAYS = 'CRP' THEN 'CASH' WHEN D.WHO_PAYS = 'PRO' THEN 'SCHEME' ELSE D.WHO_PAYS END AS PAYMENT_METHOD
  , D.MATERIAL_TYPE_ID
  , D.VOLUME AS CLAIM_QTY
  , CASE WHEN D.MATERIAL_TYPE_ID IN ('INELIGIBLE', 'WA_INELIGIBLE') THEN 0 ELSE D.VOLUME * 0.1 END AS CLAIM_GROSS_AMOUNT
  FROM
  {{ source('CES_MSCM', 'CRP_CLAIM_HDR') }} AS H
  INNER JOIN {{ source('CES_MSCM', 'CRP_CLAIM_DTL') }} AS D
  ON H.ID = D.CRP_CLAIM_HDR_ID
  LEFT JOIN (
      SELECT
      D.KEY
      ,D.YEAR_WEEK_ISO
      FROM {{ ref('REF_DATE') }} AS D
      WHERE DAY_OF_WEEK = 1
  ) WS
  ON H.PERIOD = WS.YEAR_WEEK_ISO
) CLAIM
FULL OUTER JOIN (
  SELECT
  GRP.MULTI_SCHEME_ID
  , GRP.PERIOD_KEY
  , PD.CRP_ID AS SITE_NUMBER
  , GRP.MATERIAL_TYPE_ID
  , GRP.PAYMENT_METHOD
  , 'R' AS ENTRY_TYPE
  , SUM(GRP.QUANTITY) AS POS_QTY
  , SUM(GRP.GROSS_AMOUNT) AS POS_GROSS_AMOUNT
  FROM (
    SELECT
    D.MATERIAL_TYPE_ID
    , D.QUANTITY
    , D.GROSS_AMOUNT
    , CASE WHEN H.PAYMENT_METHOD IN ('CASH', 'OTHER', 'VOUCHER') THEN 'CASH' 
      WHEN H.PAYMENT_METHOD IN ('BANK','PAYPAL','SCHEME') THEN 'SCHEME'
      ELSE NULL END AS PAYMENT_METHOD
    , H.POS_DEVICE_ID
    , TO_CHAR(TRUNC(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,H.TRANSACTED_ON), 'W'), 'YYYYMMDD') AS PERIOD_KEY
    , H.MULTI_SCHEME_ID
    FROM {{ source('CES_MSCM', 'CRP_REFUND_TXN_DTL') }} AS D
    INNER JOIN {{ source('CES_MSCM', 'CRP_REFUND_TXN_HDR') }} AS H
    ON D.TRANSACTION_ID = H.ID
    INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
    ON H.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
    UNION ALL
    SELECT
    D.MATERIAL_TYPE_ID
    , D.QUANTITY
    , D.GROSS_AMOUNT
    , CASE WHEN H.PAYMENT_METHOD IN ('CASH', 'OTHER', 'VOUCHER') THEN 'CASH' 
      WHEN H.PAYMENT_METHOD IN ('BANK','PAYPAL','SCHEME') THEN 'SCHEME'
      ELSE NULL END AS PAYMENT_METHOD
    , H.POS_DEVICE_ID
    , TO_CHAR(TRUNC(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,H.TRANSACTED_ON), 'W'), 'YYYYMMDD') AS PERIOD_KEY
    , H.MULTI_SCHEME_ID
    FROM {{ source('CES_MSCM', 'CONSUMER_REFUND_TXN_DTL') }} AS D
    INNER JOIN {{ source('CES_MSCM', 'CONSUMER_REFUND_TXN_HDR') }} AS H
    ON D.TRANSACTION_ID = H.ID
    INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
    ON H.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
  ) GRP
  LEFT JOIN {{ source('CES_MSCM', 'POS_DEVICE') }} AS PD
  ON GRP.POS_DEVICE_ID = PD.ID
  GROUP BY 
  GRP.MULTI_SCHEME_ID
  , GRP.PERIOD_KEY
  , PD.CRP_ID
  , GRP.MATERIAL_TYPE_ID
  , GRP.PAYMENT_METHOD
) C
ON CLAIM.MULTI_SCHEME_ID = C.MULTI_SCHEME_ID
AND CLAIM.SITE_NUMBER = C.SITE_NUMBER
AND CLAIM.PERIOD_KEY = C.PERIOD_KEY
AND CLAIM.ENTRY_TYPE = C.ENTRY_TYPE
AND CLAIM.PAYMENT_METHOD = C.PAYMENT_METHOD
AND CLAIM.MATERIAL_TYPE_ID = C.MATERIAL_TYPE_ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON NVL(C.MULTI_SCHEME_ID, CLAIM.MULTI_SCHEME_ID) = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS
ON NVL(C.SITE_NUMBER, CLAIM.SITE_NUMBER) = PS.SITE_NUMBER
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANTS') }} AS P
ON PS.PARTICIPANT_ID = P.PARTICIPANT_ID