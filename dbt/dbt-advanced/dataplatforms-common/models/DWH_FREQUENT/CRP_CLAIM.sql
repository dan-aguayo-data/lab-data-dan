WITH CRP_CLAIM AS (
SELECT
HDR.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, DTL.ID AS ID
, HDR.ID AS CLAIM_HDR_ID
, HDR.CRP_ID AS SITE_NUMBER
, PS.SITE_NAME AS SITE_NAME
, PS.PARTICIPANT_ID AS SUPPLIER_ID
, P.PARTICIPANT_NUMBER AS SUPPLIER_NUMBER
, P.PARTICIPANT_NAME AS SUPPLIER_NAME
, HDR.PERIOD AS PERIOD
, WS.KEY AS PERIOD_KEY
, HDR.ENTRY_TYPE AS ENTRY_TYPE
, CASE WHEN HDR.ENTRY_TYPE = 'R' THEN 'Claim' WHEN HDR.ENTRY_TYPE = 'A' THEN 'Adjustment' ELSE HDR.ENTRY_TYPE END AS ENTRY_TYPE_DESCRIPTION
, COALESCE(CA.STATUS, HDR.STATUS) AS STATUS
, HDR.SUBMITTED_BY AS SUBMITTED_BY
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(HDR.SUBMITTED_DATE AS TIMESTAMP)) AS SUBMITTED_DATE
, TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(HDR.SUBMITTED_DATE AS TIMESTAMP)),'YYYYMMDD') AS SUBMITTED_DATE_KEY
, NVL(HDR.SS_AUDIT_ADJUSTMENT_ID, -1) AS SS_AUDIT_ADJUSTMENT_ID
, DTL.WHO_PAYS AS WHO_PAYS
, CASE WHEN DTL.WHO_PAYS = 'CRP' THEN 'Cash' WHEN DTL.WHO_PAYS = 'PRO' THEN 'Scheme' ELSE DTL.WHO_PAYS END AS PAYMENT_TYPE
, DTL.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID
, MT.NAME AS MATERIAL_TYPE
, DTL.VOLUME AS CLAIM_QTY
, 'Claim QTY' AS CLAIM_QTY_HEADER
, DTL.UOM AS UOM
, DTL.VOLUME/NVL(U_KG_QTY_A.CONVERSION_FACTOR,U_KG_QTY_B.CONVERSION_FACTOR) AS CLAIM_KG_DERIVED
, HDR.SUBMITTED_DATE AS SUBMITTED_DATE_UTC
, DTL.CREATED_BY AS CREATED_BY
, DTL.CREATED_ON AS CREATED_ON_UTC
, DTL.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, DATE_TRUNC(SECOND, DTL.LAST_MODIFIED_ON) AS LAST_MODIFIED_ON_UTC
,GREATEST(
    DTL.LAST_MODIFIED_ON,
    HDR.LAST_MODIFIED_ON,
    COALESCE(CA.KAFKA_DATETIME, TO_TIMESTAMP_NTZ('1999-06-16 04:38:09.666')),
    COALESCE(PS.LAST_MODIFIED_ON, TO_TIMESTAMP_NTZ('1999-06-16 04:38:09.666'))
) AS INCREMENTAL_DATE
, D.YEAR_WEEK_ISO AS LAST_MODIFIED_ON_UTC_YEAR_WEEK_ISO
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM', 'CRP_CLAIM_HDR') }} AS HDR
INNER JOIN {{ source('CES_MSCM', 'CRP_CLAIM_DTL') }} AS DTL
ON HDR.ID = DTL.CRP_CLAIM_HDR_ID
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS
ON HDR.CRP_ID = PS.SITE_NUMBER
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANTS') }} AS P
ON PS.PARTICIPANT_ID = P.PARTICIPANT_ID
INNER JOIN {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS MT
ON DTL.MATERIAL_TYPE_ID = MT.ID
LEFT JOIN (
    SELECT
    D.KEY
    ,D.YEAR_WEEK_ISO
    FROM {{ ref('REF_DATE') }} AS D
    WHERE DAY_OF_WEEK = 1
) WS
ON HDR.PERIOD = WS.YEAR_WEEK_ISO
LEFT JOIN {{ ref('REF_DATE') }} AS D
ON TO_CHAR(DTL.LAST_MODIFIED_ON, 'YYYYMMDD') = D.KEY
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON HDR.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'UOM_REFERENCE') }} AS U_KG_QTY_A
ON DTL.MATERIAL_TYPE_ID = U_KG_QTY_A.MATERIAL_TYPE_ID
AND U_KG_QTY_A.FROM_UNIT = 'KILOGRAM'
AND U_KG_QTY_A.TO_UNIT = 'UNIT'
AND SYSDATE() BETWEEN NVL(U_KG_QTY_A.EFFECTIVE_FROM,TO_DATE('01/JAN/1900','DD/MON/YYYY')) AND NVL(U_KG_QTY_A.EFFECTIVE_TO,TO_DATE('01/JAN/9999','DD/MON/YYYY'))
AND HDR.CRP_ID = U_KG_QTY_A.SCHEME_PARTICIPANT_ID
AND CASE WHEN DTL.MULTI_SCHEME_ID = '100020001' THEN  '10002' ELSE DTL.MULTI_SCHEME_ID END = U_KG_QTY_A.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'UOM_REFERENCE') }} AS U_KG_QTY_B
ON DTL.MATERIAL_TYPE_ID = U_KG_QTY_B.MATERIAL_TYPE_ID
AND U_KG_QTY_B.FROM_UNIT = 'KILOGRAM'
AND U_KG_QTY_B.TO_UNIT = 'UNIT'
AND SYSDATE() BETWEEN NVL(U_KG_QTY_B.EFFECTIVE_FROM,TO_DATE('01/JAN/1900','DD/MON/YYYY')) AND NVL(U_KG_QTY_B.EFFECTIVE_TO,TO_DATE('01/JAN/9999','DD/MON/YYYY'))
AND U_KG_QTY_B.SCHEME_PARTICIPANT_ID IS NULL
AND CASE WHEN DTL.MULTI_SCHEME_ID = '100020001' THEN  '10002' ELSE DTL.MULTI_SCHEME_ID END = U_KG_QTY_B.MULTI_SCHEME_ID
LEFT JOIN (
    SELECT
        CA.CLAIM_ID,
        CA.ENTRY_TYPE,
        CA.STATUS,
        CA.KAFKA_DATETIME,
        ROW_NUMBER() OVER (PARTITION BY CA.CLAIM_ID ORDER BY CA.KAFKA_DATETIME DESC) AS RN
    FROM {{ ref('CRP_CLAIM_APPROVAL_HISTORY') }} AS CA
) CA
ON HDR.ID = CA.CLAIM_ID
AND HDR.ENTRY_TYPE = CA.ENTRY_TYPE
AND RN = 1
)
SELECT
MULTI_SCHEME_ID, 
SCHEME, 
ID, 
CLAIM_HDR_ID, 
SITE_NUMBER, 
SITE_NAME, 
SUPPLIER_ID, 
SUPPLIER_NUMBER, 
SUPPLIER_NAME, 
PERIOD, 
PERIOD_KEY, 
ENTRY_TYPE, 
ENTRY_TYPE_DESCRIPTION, 
STATUS, 
SUBMITTED_BY, 
SUBMITTED_DATE, 
SUBMITTED_DATE_KEY, 
SS_AUDIT_ADJUSTMENT_ID, 
WHO_PAYS, 
PAYMENT_TYPE, 
MATERIAL_TYPE_ID, 
MATERIAL_TYPE, 
CLAIM_QTY, 
CLAIM_QTY_HEADER, 
UOM, 
CLAIM_KG_DERIVED, 
SUBMITTED_DATE_UTC, 
CREATED_BY, 
CREATED_ON_UTC, 
LAST_MODIFIED_BY, 
LAST_MODIFIED_ON_UTC, 
LAST_MODIFIED_ON_UTC_YEAR_WEEK_ISO, 
INSERT_DATE_UTC
FROM CRP_CLAIM

{% if is_incremental() %}
WHERE INCREMENTAL_DATE >= DATEADD(HOUR, {{var('general_delta_load_hours')}}, (SELECT MAX(LAST_MODIFIED_ON_UTC) FROM {{ this }}))
{% endif %}



