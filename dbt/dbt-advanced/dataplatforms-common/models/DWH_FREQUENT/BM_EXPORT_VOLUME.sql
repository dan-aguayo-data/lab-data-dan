WITH BM_EXPORT AS (
SELECT
EH.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, ED.ID AS ID
, ED.EXPORT_VOLUME_HDR_ID AS BM_EXPORT_VOLUME_HDR_ID
, ED.MANUFACTURER_ID AS SITE_NUMBER
, ED.TO_STATE_ID AS EXPORT_TO
, EH.EXPORTER_ID AS EXPORTER_SITE_NUMBER
, ED.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID
, MT.NAME AS MATERIAL_TYPE
, ED.VOLUME AS VOLUME
, 'Volume' AS VOLUME_HEADER
, ED.UOM AS UOM
, EH.PERIOD AS PERIOD
, REPLACE(CONCAT(TO_CHAR(EH.PERIOD),'01'), '-','') AS PERIOD_KEY
, EH.PERIOD_TYPE AS PERIOD_TYPE
, EH.ENTRY_TYPE AS ENTRY_TYPE
, EH.STATUS AS STATUS
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(EH.SUBMITTED_DATE AS TIMESTAMP)) AS SUBMITTED_DATE
, TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(EH.SUBMITTED_DATE AS TIMESTAMP)),'YYYYMMDD') AS SUBMITTED_DATE_KEY
, GREATEST(ED.LAST_MODIFIED_ON,EH.LAST_MODIFIED_ON) AS INCREMENTAL_DATE_UTC
, EH.SUBMITTED_BY AS SUBMITTED_BY
, EH.SUBMITTED_DATE AS SUBMITTED_DATE_UTC
, NVL(EH.SS_AUDIT_ADJUSTMENT_ID, -1) AS SS_AUDIT_ADJUSTMENT_ID
, ED.CREATED_BY AS CREATED_BY
, ED.CREATED_ON AS CREATED_ON_UTC
, ED.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, ED.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM', 'EXPORT_VOLUME_DTL') }} AS ED
INNER JOIN {{ source('CES_MSCM', 'EXPORT_VOLUME_HDR') }} AS EH
ON ED.EXPORT_VOLUME_HDR_ID = EH.ID
LEFT JOIN {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS MT
ON ED.MATERIAL_TYPE_ID = MT.ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON EH.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
)
SELECT  
MULTI_SCHEME_ID, 
SCHEME, 
ID, 
BM_EXPORT_VOLUME_HDR_ID, 
SITE_NUMBER, 
EXPORT_TO, 
EXPORTER_SITE_NUMBER, 
MATERIAL_TYPE_ID, 
MATERIAL_TYPE, 
VOLUME, 
VOLUME_HEADER, 
UOM, 
PERIOD, 
PERIOD_KEY, 
PERIOD_TYPE, 
ENTRY_TYPE, 
STATUS, 
SUBMITTED_DATE, 
SUBMITTED_DATE_KEY, 
SUBMITTED_BY, 
SUBMITTED_DATE_UTC, 
SS_AUDIT_ADJUSTMENT_ID, 
CREATED_BY, 
CREATED_ON_UTC, 
LAST_MODIFIED_BY, 
LAST_MODIFIED_ON_UTC, 
INSERT_DATE_UTC
FROM BM_EXPORT 
{% if is_incremental() %}
WHERE INCREMENTAL_DATE_UTC  >= DATEADD(HOUR, {{var('general_delta_load_hours')}}, (SELECT MAX(LAST_MODIFIED_ON_UTC) FROM {{ this }}))
{% endif %}

