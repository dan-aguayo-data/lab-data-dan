SELECT
DTL.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, DTL.ID AS ID
, '-' AS LINK_ID
, HDR.TRANSACTION_ID AS TRANSACTION_ID
, DTL.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID
, MT.NAME AS MATERIAL_TYPE
, DTL.QUANTITY AS COLLECTION_QTY
, DTL.GROSS_AMOUNT AS GROSS_AMOUNT
, DTL.GST_AMOUNT AS GST_AMOUNT
, DTL.TAXABLE_AMOUNT AS TAXABLE_AMOUNT
, DTL.SHIPPER_UNIT_ID AS SHIPPER_UNIT_ID
, DTL.QUANTITY/NVL(U_KG_QTY_A.CONVERSION_FACTOR,U_KG_QTY_B.CONVERSION_FACTOR) AS COLLECTION_KG_DERIVED
, DTL.QUANTITY/NVL(U_M3_QTY_A.CONVERSION_FACTOR,U_M3_QTY_B.CONVERSION_FACTOR) AS COLLECTION_M3_DERIVED
, NVL(RR.TARGET_PARTICIPANT_ID ,'-') AS LSP_SITE_NUMBER
, TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(HDR.TRANSACTED_ON AS TIMESTAMP)),'YYYYMMDD') AS TRANSACTION_DATE_KEY
, CASE WHEN TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(HDR.TRANSACTED_ON AS TIMESTAMP)),'YYYYMMDD') = TO_CHAR(CONVERT_TIMEZONE('UTC', 'Australia/NSW', SYSDATE()), 'YYYYMMDD') THEN 1 ELSE 0 END AS CURRENT_DAY_FLAG
, DTL.CREATED_BY AS CREATED_BY
, DTL.CREATED_ON AS CREATED_ON_UTC
, DTL.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, DTL.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM (
    SELECT ID, 
        D.TRANSACTION_ID || '-CRP' AS HDR_ID,
        D.TRANSACTION_ID,
        D.MATERIAL_TYPE_ID,
        D.QUANTITY,
        D.GROSS_AMOUNT,
        D.GST_AMOUNT,
        D.TAXABLE_AMOUNT,
        D.SHIPPER_UNIT_ID,
        D.CREATED_BY,
        D.CREATED_ON,
        D.LAST_MODIFIED_BY,
        D.LAST_MODIFIED_ON,
        D.MULTI_SCHEME_ID
    FROM {{ source('CES_MSCM', 'CRP_REFUND_TXN_DTL') }} AS D
    UNION ALL
    SELECT ID, 
        D.TRANSACTION_ID || '-C' AS HDR_ID,
        D.TRANSACTION_ID,
        D.MATERIAL_TYPE_ID,
        D.QUANTITY,
        D.GROSS_AMOUNT,
        D.GST_AMOUNT,
        D.TAXABLE_AMOUNT,
        D.SHIPPER_UNIT_ID,
        D.CREATED_BY,
        D.CREATED_ON,
        D.LAST_MODIFIED_BY,
        D.LAST_MODIFIED_ON,
        D.MULTI_SCHEME_ID
    FROM {{ source('CES_MSCM', 'CONSUMER_REFUND_TXN_DTL') }} AS D
    UNION ALL
    SELECT ID, 
        D.REFUND_TRANSACTION_ID || '-K' AS HDR_ID,
        D.REFUND_TRANSACTION_ID,
        D.MATERIAL_TYPE_ID,
        D.CONTAINER_COUNT AS QUANTITY,
        D.CONTAINER_COUNT * 0.1 AS GROSS_AMOUNT,
        NULL AS GST_AMOUNT,
        NULL AS TAXABLE_AMOUNT,
        NULL AS SHIPPER_UNIT_ID,
        NULL AS CREATED_BY,
        D.KAFKA_DATETIME AS CREATED_ON,
        NULL AS LAST_MODIFIED_BY,
        D.KAFKA_DATETIME AS LAST_MODIFIED_ON,
        CAST(D.MULTI_SCHEME_ID AS NUMBER) AS MULTI_SCHEME_ID
    FROM {{ source('CES_MSCM_KAFKA', 'NOP_CLAIM_REFUND_ITEMS') }} AS D
    WHERE D.MULTI_SCHEME_ID IN (100020002, 100020003, 100030001)
) DTL
INNER JOIN {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS MT
ON DTL.MATERIAL_TYPE_ID = MT.ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON DTL.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
INNER JOIN (
    SELECT
    HEADER.ID,
    CASE WHEN COUNT(1) OVER (PARTITION BY HEADER.TRANSACTION_ID) = 1 THEN HEADER.TRANSACTION_ID ELSE HEADER.ID END AS TRANSACTION_ID,
    HEADER.POS_DEVICE_ID,
    HEADER.REFUND_CRP,
    HEADER.TRANSACTED_ON
    FROM (
        SELECT
            H.ID || '-CRP' AS ID,
            H.ID AS TRANSACTION_ID,
            H.POS_DEVICE_ID,
            H.REFUND_CRP,
            H.TRANSACTED_ON
        FROM {{ source('CES_MSCM', 'CRP_REFUND_TXN_HDR') }} AS H
        UNION ALL
        SELECT
            H.ID || '-C' AS ID,
            H.ID AS TRANSACTION_ID,
            H.POS_DEVICE_ID,
            H.REFUND_CRP,
            H.TRANSACTED_ON
        FROM {{ source('CES_MSCM', 'CONSUMER_REFUND_TXN_HDR') }} AS H
        UNION ALL
        SELECT
            H.REFUND_TRANSACTION_ID || '-K' AS ID,
            H.REFUND_TRANSACTION_ID AS TRANSACTION_ID,
            NVL(HDR.DEVICE_ID, '-') AS POS_DEVICE_ID,
            H.CRP_SITE_NUMBER AS REFUND_CRP,
            {% if target.name.upper() == 'UAT' %}
            CASE WHEN SUBSTR(H.TRANSACTION_DATE, -3, 1) = '+' THEN H.TRANSACTION_DATE || ':00' ELSE H.TRANSACTION_DATE END AS TRANSACTED_ON
            {%- else -%}
            H.TRANSACTION_DATE AS TRANSACTED_ON
            {% endif %}
        FROM {{ source('CES_MSCM_KAFKA', 'NOP_CLAIM_REFUND') }} AS H
        LEFT JOIN {{ source('CES_MSCM_KAFKA', 'REFUND_TRANSACTION_HDR') }} AS HDR
        ON H.EXTERNAL_REFUND_ID = HDR.EXTERNAL_REFUND_ID
        AND H.MULTI_SCHEME_ID = HDR.MULTI_SCHEME_ID
        WHERE H.MULTI_SCHEME_ID IN (100020002, 100020003, 100030001)
    ) HEADER
) HDR
ON DTL.HDR_ID = HDR.ID
LEFT JOIN {{ source('CES_MSCM', 'POS_DEVICE') }} AS PD
ON HDR.POS_DEVICE_ID = PD.ID
LEFT JOIN (
     SELECT 
     PD.MATERIAL_TYPE_ID,
     PD.EFFECTIVE_FROM,
     PD.EFFECTIVE_TO,
     PH.SOURCE_PARTICIPANT_ID,
     PH.TARGET_PARTICIPANT_ID 
     FROM
     {{ source('CES_MSCM', 'SCHEME_PARTICIPANT_REL_DTL') }} AS PD
     INNER JOIN {{ source('CES_MSCM', 'SCHEME_PARTICIPANT_REL_HDR') }} AS PH
     ON PD.SCHEME_PARTICIPANT_REL_ID = PH.ID 
     WHERE SUBSTR(PH.TARGET_PARTICIPANT_ID,2,1) = 'L'
     QUALIFY ROW_NUMBER() OVER (PARTITION BY PD.MATERIAL_TYPE_ID, PH.SOURCE_PARTICIPANT_ID ORDER BY PD.EFFECTIVE_FROM DESC) = 1
) RR
ON RR.SOURCE_PARTICIPANT_ID = NVL(HDR.REFUND_CRP,PD.CRP_ID) 
AND RR.MATERIAL_TYPE_ID = DTL.MATERIAL_TYPE_ID 
AND HDR.TRANSACTED_ON >= RR.EFFECTIVE_FROM
AND HDR.TRANSACTED_ON < NVL(RR.EFFECTIVE_TO,'01-JAN-9999') 
LEFT JOIN {{ source('CES_MSCM', 'UOM_REFERENCE') }} AS U_KG_QTY_A
ON DTL.MATERIAL_TYPE_ID = U_KG_QTY_A.MATERIAL_TYPE_ID
AND U_KG_QTY_A.FROM_UNIT = 'KILOGRAM'
AND U_KG_QTY_A.TO_UNIT = 'UNIT'
AND SYSDATE() BETWEEN NVL(U_KG_QTY_A.EFFECTIVE_FROM,TO_DATE('01/JAN/1900','DD/MON/YYYY')) AND NVL(U_KG_QTY_A.EFFECTIVE_TO,TO_DATE('01/JAN/9999','DD/MON/YYYY'))
AND NVL(HDR.REFUND_CRP,PD.CRP_ID) = U_KG_QTY_A.SCHEME_PARTICIPANT_ID
AND LEFT(DTL.MULTI_SCHEME_ID, 5) = U_KG_QTY_A.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'UOM_REFERENCE') }} AS U_KG_QTY_B
ON DTL.MATERIAL_TYPE_ID = U_KG_QTY_B.MATERIAL_TYPE_ID
AND U_KG_QTY_B.FROM_UNIT = 'KILOGRAM'
AND U_KG_QTY_B.TO_UNIT = 'UNIT'
AND SYSDATE() BETWEEN NVL(U_KG_QTY_B.EFFECTIVE_FROM,TO_DATE('01/JAN/1900','DD/MON/YYYY')) AND NVL(U_KG_QTY_B.EFFECTIVE_TO,TO_DATE('01/JAN/9999','DD/MON/YYYY'))
AND U_KG_QTY_B.SCHEME_PARTICIPANT_ID IS NULL
AND LEFT(DTL.MULTI_SCHEME_ID, 5) = U_KG_QTY_B.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'UOM_REFERENCE') }} AS U_M3_QTY_A
ON DTL.MATERIAL_TYPE_ID = U_M3_QTY_A.MATERIAL_TYPE_ID
AND U_M3_QTY_A.FROM_UNIT = 'CUBIC METRE'
AND U_M3_QTY_A.TO_UNIT = 'UNIT'
AND SYSDATE() BETWEEN NVL(U_M3_QTY_A.EFFECTIVE_FROM,TO_DATE('01/JAN/1900','DD/MON/YYYY')) AND NVL(U_M3_QTY_A.EFFECTIVE_TO,TO_DATE('01/JAN/9999','DD/MON/YYYY'))
AND NVL(HDR.REFUND_CRP,PD.CRP_ID) = U_M3_QTY_A.SCHEME_PARTICIPANT_ID
AND LEFT(DTL.MULTI_SCHEME_ID, 5) = U_M3_QTY_A.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'UOM_REFERENCE') }} AS U_M3_QTY_B
ON DTL.MATERIAL_TYPE_ID = U_M3_QTY_B.MATERIAL_TYPE_ID
AND U_M3_QTY_B.FROM_UNIT = 'CUBIC METRE'
AND U_M3_QTY_B.TO_UNIT = 'UNIT'
AND SYSDATE() BETWEEN NVL(U_M3_QTY_B.EFFECTIVE_FROM,TO_DATE('01/JAN/1900','DD/MON/YYYY')) AND NVL(U_M3_QTY_B.EFFECTIVE_TO,TO_DATE('01/JAN/9999','DD/MON/YYYY'))
AND U_M3_QTY_B.SCHEME_PARTICIPANT_ID IS NULL
AND LEFT(DTL.MULTI_SCHEME_ID, 5) = U_M3_QTY_B.MULTI_SCHEME_ID
WHERE (1=1)
{% if target.name.upper() != 'UAT' %}
AND NVL(NULLIF(HDR.REFUND_CRP,''),PD.CRP_ID) NOT IN (
'WC20000001',
'WC20000003',
'QC10006001',
'QC10006002',
'QC10006003',
'QC10006004',
'QC10006005',
'QC10006006',
'QC10006007',
'QC10006008'
)
AND 
HDR.TRANSACTION_ID NOT IN (
'6252CD065C934B408F636E368373200B',
'B2BC7606D2104F4497FA9F41030985BF',
'D3B98196FEB647BA9F1FEEFE52AF2106',
'37A6647C85C540D5994F715A7C2914E2',
'b992fe4a-29b7-49f5-afc7-e5aedcafec4e' --2bn transaction from VIC Visy
)
{% endif %}
{% if is_incremental() %}
    AND
    NVL(LAST_MODIFIED_ON_UTC, SYSDATE()) >= (select DATEADD(hour, -2, max(LAST_MODIFIED_ON_UTC)) from {{this}})
