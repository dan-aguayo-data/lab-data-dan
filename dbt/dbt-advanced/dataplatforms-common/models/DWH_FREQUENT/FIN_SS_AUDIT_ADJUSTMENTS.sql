SELECT
SS.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, SS.SS_AUDIT_ADJUSTMENT_ID AS ID
, PS.SITE_NUMBER AS SITE_NUMBER
, SS.ADJUSTER_ID AS ADJUSTER_ID
, R.VALUE AS ADJUSTMENT_REASON
, SS.COMMENTS AS COMMENTS
, CU.LOGIN_ID AS APPROVED_BY
, SS.APPROVER_COMMENTS AS APPROVER_COMMENTS
, SS.CREATED_BY AS CREATED_BY
, SS.CREATED_ON AS CREATED_ON_UTC
, SS.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, SS.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM', 'SS_AUDIT_ADJUSTMENTS') }} AS SS
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON SS.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS
ON SS.PARTICIPANT_SITE_ID = PS.PARTICIPANT_SITE_ID
LEFT JOIN {{ source('CES_MSCM', 'SCHEME_REF_CODES') }} AS R
ON SS.REASON_ID = R.SCHEME_REF_CODES_ID
LEFT JOIN {{ source('CES_MSCM', 'CUSTOM_USER') }} AS CU
ON SS.APPROVER_ID = CU.ID

UNION ALL

SELECT
-1 AS MULTI_SCHEME_ID
, 'CES' AS SCHEME
, -1 AS ID
, NULL AS SITE_NUMBER
, NULL AS ADJUSTER_ID
, NULL AS ADJUSTMENT_REASON
, NULL AS COMMENTS
, NULL AS APPROVED_BY
, NULL AS APPROVER_COMMENTS
, NULL AS CREATED_BY
, NULL AS CREATED_ON_UTC
, NULL AS LAST_MODIFIED_BY
, TO_DATE('01/01/2021', 'DD/MM/YYYY') AS LAST_MODIFIED_ON_UTC
, SYSDATE () AS INSERT_DATE_UTC