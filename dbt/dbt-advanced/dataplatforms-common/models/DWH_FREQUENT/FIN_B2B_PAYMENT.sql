{{
    config(
        materialized = 'incremental',
        incremental_strategy = 'merge',
        unique_key = 'ID',
        on_schema_change = 'append_new_columns'
    )
}}

SELECT
PT.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, PT.ID AS ID
, PT.SCHEME_PARTICIPANT_ID AS SITE_NUMBER
, PT.PERIOD AS PERIOD
, PT.PERIOD_TYPE AS PERIOD_TYPE
, CASE WHEN PT.PERIOD_TYPE = 'D' THEN REPLACE(PT.PERIOD,'-','') WHEN PT.PERIOD_TYPE = 'M' THEN REPLACE(PT.PERIOD,'-','') || '01' WHEN PT.PERIOD_TYPE = 'Q' THEN SUBSTR(PT.PERIOD,1,4) || TO_CHAR(3*TO_NUMBER(SUBSTR(PT.PERIOD,6,1))-2,'FM00') || '01' WHEN PT.PERIOD_TYPE = 'W' THEN WS.KEY END AS PERIOD_KEY
, PT.PAYMENT_PERIOD AS PAYMENT_PERIOD
, PT.PAYMENT_TYPE AS PAYMENT_TYPE
, PT.PAYMENT_METHOD AS PAYMENT_METHOD
, PT.STATUS AS STATUS
, PT.ENTRY_TYPE AS ENTRY_TYPE
, PT.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID
, PT.MRF_MATERIAL_TYPE_ID AS MRF_MATERIAL_TYPE_ID
, PT.ARREAR AS ARREAR
, PT.UNIT_SELLING_PRICE AS UNIT_SELLING_PRICE
, PT.UOM AS UOM
, CASE WHEN PT.SCHEME_PARTICIPANT_TYPE = 'CRP' AND PT.PERIOD_TYPE = 'W' THEN CASE WHEN PT.PAYMENT_TYPE = 'REFUND_AMOUNT' THEN PT.VOLUME ELSE NULL END ELSE PT.VOLUME END AS VOLUME
, PT.VOLUME AS VOLUME_ORIGINAL
, PT.GROSS_AMOUNT AS GROSS_AMOUNT
, PT.TAXABLE_AMOUNT AS TAXABLE_AMOUNT
, PT.GST_AMOUNT AS GST_AMOUNT
, CASE WHEN PT.PAYMENT_TYPE = 'COLLECTION_FEES' THEN 'Logical payment' WHEN PT.PAYMENT_TYPE = 'REFUND_AMOUNT' AND PT.PAYMENT_METHOD = 'SCHEME' THEN 'Logical payment' ELSE 'Paid via bank' END AS HOW_PAID
, 'Payment Volume' AS VOLUME_HEADER
, 'Gross Amount' AS GROSS_AMOUNT_HEADER
, PT.CREATED_BY AS CREATED_BY
, PT.CREATED_ON AS CREATED_ON_UTC
, PT.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, PT.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM', 'PAYMENT_TRANSACTION_REC') }} AS PT
LEFT JOIN (
    SELECT
    D.KEY
    ,D.YEAR_WEEK_ISO
    FROM {{ ref('REF_DATE') }} AS D
    WHERE DAY_OF_WEEK = 1
) WS
ON PT.PERIOD = WS.YEAR_WEEK_ISO
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON PT.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
WHERE PT.SCHEME_PARTICIPANT_TYPE != 'CONSUMER'
{% if is_incremental() %}
AND PT.LAST_MODIFIED_ON >= DATEADD(HOUR, {{var('general_delta_load_hours')}}, (SELECT MAX(LAST_MODIFIED_ON_UTC) FROM {{ this }}))
{% endif %}