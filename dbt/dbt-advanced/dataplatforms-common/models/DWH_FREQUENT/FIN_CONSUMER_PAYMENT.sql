{% if is_incremental() %}
WITH INCREMENTAL_DATE_REF AS (

 SELECT DATEADD(HOUR, {{var('general_delta_load_hours')}}, SYSDATE()) AS INCREMENTAL_DELTA

 ), INCREMENTAL_ID_REF AS (

SELECT 
PT.ID
FROM {{ source('CES_MSCM', 'PAYMENT_TRANSACTION_REC') }}  PT
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }}  AS SCHEME
ON PT.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
WHERE PT.LAST_MODIFIED_ON >= (SELECT INCREMENTAL_DELTA FROM INCREMENTAL_DATE_REF)
AND  PT.SCHEME_PARTICIPANT_TYPE = 'CONSUMER'

)
{% endif %}

SELECT
PT.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, PT.ID AS ID
, PT.PAYMENT_BATCH_ID AS PAYMENT_BATCH_ID
, PT.SCHEME_PARTICIPANT_ID AS CONSUMER_ID
, PT.PERIOD AS PERIOD
, PT.PERIOD_TYPE AS PERIOD_TYPE
, REPLACE(PT.PERIOD,'-','') AS PERIOD_KEY
, PT.PAYMENT_PERIOD AS PAYMENT_PERIOD
, PT.PAYMENT_TYPE AS PAYMENT_TYPE
, PT.PAYMENT_METHOD AS PAYMENT_METHOD
, PT.STATUS AS STATUS
, PT.ENTRY_TYPE AS ENTRY_TYPE
, PT.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID
, PT.MRF_MATERIAL_TYPE_ID AS MRF_MATERIAL_TYPE_ID
, PT.ARREAR AS ARREAR
, PT.UNIT_SELLING_PRICE AS UNIT_SELLING_PRICE
, PT.UOM AS UOM
, PT.VOLUME AS VOLUME
, PT.GROSS_AMOUNT AS GROSS_AMOUNT
, PT.TAXABLE_AMOUNT AS TAXABLE_AMOUNT
, PT.GST_AMOUNT AS GST_AMOUNT
, PT.PAYMENT_TIMESTAMP AS PAYMENT_TIMESTAMP
, PT.PROCESSOR_ID AS PROCESSOR_ID
, 'Payment Volume' AS VOLUME_HEADER
, 'Gross Amount' AS GROSS_AMOUNT_HEADER
, PT.CREATED_BY AS CREATED_BY
, PT.CREATED_ON AS CREATED_ON_UTC
, PT.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, PT.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM {{ source('CES_MSCM', 'PAYMENT_TRANSACTION_REC') }} AS PT
{% if is_incremental() %}
LEFT JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON PT.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
INNER JOIN INCREMENTAL_ID_REF R
ON R.ID = PT.ID
{% else %}
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON PT.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
WHERE   PT.SCHEME_PARTICIPANT_TYPE = 'CONSUMER'
{% endif %}