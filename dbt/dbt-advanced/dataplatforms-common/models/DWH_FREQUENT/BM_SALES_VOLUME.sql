WITH BM_SALES AS (
SELECT
SD.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, SCHEME.NAME AS SCHEME
, SD.ID AS ID
, SD.MFG_SALES_VOLUME_HDR_ID AS BM_SALES_VOLUME_HDR_ID
, SH.MANUFACTURER_ID AS SITE_NUMBER
, SD.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID
, MT.NAME AS MATERIAL_TYPE
, SD.VOLUME AS VOLUME
, 'Volume' AS VOLUME_HEADER
, SD.UOM AS UOM
, SH.PERIOD AS PERIOD
, REPLACE(CONCAT(TO_CHAR(SH.PERIOD),'01'), '-','') AS PERIOD_KEY
, SH.PERIOD_TYPE AS PERIOD_TYPE
, SH.ENTRY_TYPE AS ENTRY_TYPE
, SH.STATUS AS STATUS
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(SH.SUBMITTED_DATE AS TIMESTAMP)) AS SUBMITTED_DATE
, TO_CHAR(CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(SH.SUBMITTED_DATE AS TIMESTAMP)),'YYYYMMDD') AS SUBMITTED_DATE_KEY
, SH.SUBMITTED_BY AS SUBMITTED_BY
, SH.SUBMITTED_DATE AS SUBMITTED_DATE_UTC
, NVL(SH.SS_AUDIT_ADJUSTMENT_ID, -1) AS SS_AUDIT_ADJUSTMENT_ID
, SH.ADJUSTMENT_REASON AS ADJUSTMENT_REASON
, SD.CREATED_BY AS CREATED_BY
, SD.CREATED_ON AS CREATED_ON_UTC
, SD.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, SD.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, GREATEST(SD.LAST_MODIFIED_ON, SH.LAST_MODIFIED_ON) AS INCREMENTAL_DATE_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM', 'MFG_SALES_VOLUME_DTL') }} AS SD
INNER JOIN {{ source('CES_MSCM', 'MFG_SALES_VOLUME_HDR') }} AS SH
ON SD.MFG_SALES_VOLUME_HDR_ID = SH.ID
LEFT JOIN {{ source('CES_MSCM', 'MANUFACTURER') }} AS M
ON SH.MANUFACTURER_ID = M.SCHEME_PARTICIPANT_ID
LEFT JOIN {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS MT
ON SD.MATERIAL_TYPE_ID = MT.ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON SD.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
)
SELECT 
MULTI_SCHEME_ID, 
SCHEME, 
ID, 
BM_SALES_VOLUME_HDR_ID, 
SITE_NUMBER, 
MATERIAL_TYPE_ID, 
MATERIAL_TYPE, 
VOLUME, 
VOLUME_HEADER, 
UOM, 
PERIOD, 
PERIOD_KEY, 
PERIOD_TYPE, 
ENTRY_TYPE, 
STATUS, 
SUBMITTED_DATE, 
SUBMITTED_DATE_KEY, 
SUBMITTED_BY, 
SUBMITTED_DATE_UTC, 
SS_AUDIT_ADJUSTMENT_ID, 
ADJUSTMENT_REASON, 
CREATED_BY, 
CREATED_ON_UTC, 
LAST_MODIFIED_BY, 
LAST_MODIFIED_ON_UTC, 
INSERT_DATE_UTC
FROM BM_SALES
{% if is_incremental() %}
WHERE INCREMENTAL_DATE_UTC >= DATEADD(HOUR, {{var('general_delta_load_hours')}}, (SELECT MAX(LAST_MODIFIED_ON_UTC) FROM {{ this }}))
{% endif %}