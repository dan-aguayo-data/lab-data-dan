SELECT
CD.MULTI_SCHEME_ID  AS MULTI_SCHEME_ID 
, SCHEME.NAME AS SCHEME
, CD.ID AS ID
, CD.PROCESSOR_CLAIM_HDR_ID AS CLAIM_HDR_ID
, CH.PROCESSOR_ID AS SITE_NUMBER 
, PS.SITE_NAME  AS SITE_NAME 
, CD.MATERIAL_TYPE_ID  AS MATERIAL_TYPE_ID 
, MT.NAME AS MATERIAL_TYPE
, CD.VOLUME AS VOLUME
, 'Volume' AS VOLUME_HEADER
, CD.UOM AS UOM
, CASE CD.UOM WHEN 'KILOGRAM' THEN CD.VOLUME WHEN 'UNIT' THEN CD.VOLUME/NVL(U_KG_QTY_A.CONVERSION_FACTOR,U_KG_QTY_B.CONVERSION_FACTOR) END AS CLAIM_KG_DERIVED
, CASE CD.UOM WHEN 'UNIT' THEN CD.VOLUME WHEN 'KILOGRAM' THEN CD.VOLUME*NVL(U_KG_QTY_A.CONVERSION_FACTOR,U_KG_QTY_B.CONVERSION_FACTOR) END AS CLAIM_QTY_DERIVED
, CH.STATUS AS STATUS
, CH.ENTRY_TYPE AS ENTRY_TYPE
, CH.PERIOD AS PERIOD
, CH.PERIOD_TYPE AS PERIOD_TYPE
, WS.KEY AS PERIOD_KEY
, CH.SUBMITTED_BY AS SUBMITTED_BY
, CONVERT_TIMEZONE('UTC',SCHEME.TIMEZONE,CAST(CH.SUBMITTED_DATE AS TIMESTAMP)) AS SUBMITTED_DATE
, CH.SUBMITTED_DATE AS SUBMITTED_DATE_UTC
, NVL(CH.SS_AUDIT_ADJUSTMENT_ID, -1) AS SS_AUDIT_ADJUSTMENT_ID
, CD.CREATED_BY AS CREATED_BY
, CD.CREATED_ON AS CREATED_ON_UTC
, CD.LAST_MODIFIED_BY AS LAST_MODIFIED_BY
, CD.LAST_MODIFIED_ON AS LAST_MODIFIED_ON_UTC
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_MSCM', 'PROCESSOR_CLAIM_DTL') }} AS CD
INNER JOIN {{ source('CES_MSCM', 'PROCESSOR_CLAIM_HDR') }} AS CH
ON CD.PROCESSOR_CLAIM_HDR_ID = CH.ID
INNER JOIN {{ source('CES_MSCM', 'MATERIAL_TYPE') }} AS MT
ON CD.MATERIAL_TYPE_ID = MT.ID
LEFT JOIN {{ source('CES_MSCM', 'UOM_REFERENCE') }} AS U_KG_QTY_A
ON CD.MATERIAL_TYPE_ID = U_KG_QTY_A.MATERIAL_TYPE_ID
AND U_KG_QTY_A.FROM_UNIT = 'KILOGRAM'
AND U_KG_QTY_A.TO_UNIT = 'UNIT'
AND SYSDATE() BETWEEN NVL(U_KG_QTY_A.EFFECTIVE_FROM,TO_DATE('01/JAN/1900','DD/MON/YYYY')) AND NVL(U_KG_QTY_A.EFFECTIVE_TO,TO_DATE('01/JAN/9999','DD/MON/YYYY'))
AND CH.PROCESSOR_ID = U_KG_QTY_A.SCHEME_PARTICIPANT_ID
AND CH.MULTI_SCHEME_ID = U_KG_QTY_A.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'UOM_REFERENCE') }} AS U_KG_QTY_B
ON CD.MATERIAL_TYPE_ID = U_KG_QTY_B.MATERIAL_TYPE_ID
AND U_KG_QTY_B.FROM_UNIT = 'KILOGRAM'
AND U_KG_QTY_B.TO_UNIT = 'UNIT'
AND SYSDATE() BETWEEN NVL(U_KG_QTY_B.EFFECTIVE_FROM,TO_DATE('01/JAN/1900','DD/MON/YYYY')) AND NVL(U_KG_QTY_B.EFFECTIVE_TO,TO_DATE('01/JAN/9999','DD/MON/YYYY'))
AND U_KG_QTY_B.SCHEME_PARTICIPANT_ID IS NULL
AND CH.MULTI_SCHEME_ID = U_KG_QTY_B.MULTI_SCHEME_ID
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON CD.MULTI_SCHEME_ID = SCHEME.MULTI_SCHEME_ID
LEFT JOIN {{ source('CES_MSCM', 'MDT_PARTICIPANT_SITES') }} AS PS
ON PS.SITE_NUMBER=CH.PROCESSOR_ID
LEFT JOIN (
    SELECT
    D.KEY
    ,D.YEAR_WEEK_ISO
    FROM {{ ref('REF_DATE') }} AS D
    WHERE DAY_OF_WEEK = 1
) WS
ON CH.PERIOD = WS.YEAR_WEEK_ISO