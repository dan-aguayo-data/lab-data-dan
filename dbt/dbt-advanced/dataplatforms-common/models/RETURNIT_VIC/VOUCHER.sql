SELECT
100020001 AS MULTI_SCHEME_ID
, 'VIC-ReturnIT' AS SCHEME
, RD.KEY AS DEPOSITED_DATE_KEY
, R.DEPOSITED_ON AS DEPOSITED_DATE
, R.NAME AS SITE_LOCATION
, R.REGISTERED_ON AS REGISTERED_DATE
, R.RECEIPT_ID AS VOUCHER_NUMBER
, R.RECEIPT_BARCODE AS VOUCHER_BARCODE
, R.VALUE AS VOUCHER_AMOUNT
, NVL(R.REDEEMED_TIMESTAMP, RR.REDEEMED_TIMESTAMP) AS RVMS_REDEMPTION_DATE
, CASE WHEN NVL(R.REDEEMED_TIMESTAMP, RR.REDEEMED_TIMESTAMP) IS NOT NULL THEN 1 ELSE 0 END AS VOUCHER_REDEMEED_FLAG
, V.STORE_NUMBER AS STORE_NUMBER
, V.CHECKOUT_NUMBER AS CHECKOUT_NUMBER
, V.TIMESTAMP AS REDEMPTION_DATE
, V.AMOUNT AS AMOUNT_REDEEMED
, V.SOURCE AS SOURCE
, CASE WHEN REGEXP_LIKE(R.RECEIPT_BARCODE, '^[0-9]+$') THEN 'Barcode' ELSE 'Cash Receipt' END AS TYPE
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('RETURNIT_VOUCHER', 'RVMS') }} AS R
LEFT JOIN
(
    SELECT
    *
    FROM
    {{ source('RETURNIT_VOUCHER', 'RVMS_REDEEMED') }} AS RR
    QUALIFY COUNT(*) OVER (PARTITION BY RR.RECEIPT_ID, RR.RECEIPT_BARCODE) = 1
)RR
ON R.RECEIPT_BARCODE = RR.RECEIPT_BARCODE 
AND R.RECEIPT_ID = RR.RECEIPT_ID
LEFT JOIN
(
    SELECT
    CAST(W.STORE_NUMBER AS VARCHAR) AS STORE_NUMBER,
    COUNT(W.CHECKOUT_NUMBER) AS CHECKOUT_NUMBER,
    W.TENDER_BARCODE AS RECEIPTBARCODE,
    MIN(CONVERT_TIMEZONE('UTC', 'Australia/Melbourne', W.TRANSACTION_TIMESTAMP_UTC)) AS TIMESTAMP,
    SUM(W.TENDER_AMOUNT) AS AMOUNT,
    'WOOLWORTHS_VOUCHER' AS SOURCE
    FROM
    {{ source('RETURNIT_VOUCHER', 'WOOLWORTHS_VOUCHER') }} AS W
    GROUP BY ALL
UNION
    SELECT
    C.RETAILSTOREID AS STORE_NUMBER,
    NULL AS CHECKOUT_NUMBER,
    C.RECEIPTBARCODE AS RECEIPTBARCODE,
    MIN(C.TIMESTAMP) AS TIMESTAMP,
    SUM(C.AMOUNT) AS AMOUNT,
    'COLES_VOUCHER' AS SOURCE
    FROM
    {{ source('RETURNIT_VOUCHER', 'COLES_VOUCHER') }} AS C
    GROUP BY ALL
) V
ON R.RECEIPT_BARCODE = V.RECEIPTBARCODE
LEFT JOIN {{ ref('REF_DATE') }} AS RD
ON DATE(R.DEPOSITED_ON) = RD.DATE
QUALIFY ROW_NUMBER() OVER (PARTITION BY R.RECEIPT_BARCODE ORDER BY R.DEPOSITED_ON DESC) = 1