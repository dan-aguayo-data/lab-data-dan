SELECT
CS.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, CS.SCHEME AS SCHEME
, CS.PERIOD_KEY AS CRP_SHIPPING_PERIOD_KEY
, CS.PERIOD AS CRP_SHIPPING_PERIOD
, CS.CRP_SITE_NUMBER AS CRP_SITE_NUMBER
, AA.BATCH_NUMBER AS MANIFEST_NUMBER
, CASE WHEN CS.MANIFEST_NUMBER IS NOT NULL THEN 1 ELSE 0 END AS MANIFEST_RECON_FLAG
, AA.DATETIME AS ANKER_PERIOD
, CS.CLAIM_QTY AS SHIPPING_QTY
, AA.VERIFIED_COUNT AS ANKER_QTY
, NVL(CS.CLAIM_QTY, 0) - NVL(AA.VERIFIED_COUNT,0)  AS VARIANCE
, AA.MATERIAL_TYPE_ID AS MATERIAL_TYPE_ID
, SYSDATE() AS INSERT_DATE_UTC
FROM
(
    SELECT
    AA.BATCH_NUMBER
    , MAX(AA.DATETIME) AS DATETIME
    , COUNT(*) AS VERIFIED_COUNT
    , CASE
        WHEN AA.MATERIAL_TYPE_CODE = 2 THEN 'VIC_HDPE'
        WHEN AA.MATERIAL_TYPE_CODE IN (1, 3, 4, 5, 6, 80) THEN 'VIC_PET'
        WHEN AA.MATERIAL_TYPE_CODE = 9 THEN 'VIC_OTHPLASTICS'
        WHEN AA.MATERIAL_TYPE_CODE IN (41, 42) THEN 'VIC_ALUMINIUM'
        WHEN AA.MATERIAL_TYPE_CODE IN (70, 71, 72, 73, 100) THEN 'VIC_GLASS'
        WHEN AA.MATERIAL_TYPE_CODE IN (89, 91) THEN 'VIC_OTHER'
        WHEN AA.MATERIAL_TYPE_CODE = 40 THEN 'VIC_STEEL'
        WHEN AA.MATERIAL_TYPE_CODE = 90 THEN 'VIC_LQDPAPERBRD'
        WHEN AA.MATERIAL_TYPE_CODE = 0 THEN 'VIC_INELIGIBLE'
        END AS MATERIAL_TYPE_ID
    FROM 
    {{ source('RETURNIT_VOUCHER', 'ANKER_ANDERSEN') }} AS AA
    WHERE AA.BATCH_NUMBER NOT LIKE 'RVS20%'
    GROUP BY ALL
)AA
INNER JOIN (
    SELECT 
    CS.MULTI_SCHEME_ID
    , CS.SCHEME
    , CS.PERIOD
    , CS.PERIOD_KEY
    , CS.CRP_SITE_NUMBER
    , CS.MANIFEST_NUMBER
    , CS.MATERIAL_TYPE_ID
    , SUM(NVL(CS.QTY,0))  AS CLAIM_QTY
    FROM 
    {{ ref('CRP_SHIPPING_MANIFEST') }} AS CS
    GROUP BY ALL
     ) CS
ON AA.BATCH_NUMBER = LEFT(CS.MANIFEST_NUMBER,5)
AND AA.MATERIAL_TYPE_ID = CS.MATERIAL_TYPE_ID
LEFT JOIN {{ ref('REF_DATE') }} AS RD
ON CS.PERIOD_KEY = RD.KEY