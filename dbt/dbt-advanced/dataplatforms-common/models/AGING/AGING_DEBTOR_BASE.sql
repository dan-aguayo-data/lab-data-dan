SELECT
DECODE(S.LOCATION_CODE, 'CoExQLD', 10000, 'WARRRL', 10001, 'VIC RECYCLE', 10002, 'TAS RECYCLE', 10003, 'CoExService', -1) AS MULTI_SCHEME_ID
, DECODE(S.LOCATION_CODE, 'CoExQLD', 'QLD', 'WARRRL', 'WA', 'VIC RECYCLE', 'VIC', 'TAS RECYCLE', 'TAS', 'CoExService', 'CES') AS SCHEME
, S.PAYMENT_SCHEDULE_ID AS PAYMENT_SCHEDULE_ID
, S.PARTY_NAME AS PARTY_NAME
, CASE WHEN UPPER(S.TRANS_TYPE_NAME) IN ('Credit Memo', 'Invoice') THEN SM.SITE_NUMBER ELSE PS.SITE_NUMBER END AS SITE_NUMBER
, S.TRANSACTION_NUMBER AS INVOICE_NUMBER
, S.DUE_DATE AS DUE_DATE
, S.CLASS AS CLASS
, S.TRANS_TYPE AS INVOICE_TYPE
, S.TRANS_TYPE_NAME AS INVOICE_TYPE_NAME
, S.BU_NAME AS BU_NAME
, S.GL_DATE_PS AS GL_DATE_PS
, A.GL_DATE_AR AS GL_DATE_AR
, NVL(A.GL_DATE_AR, S.GL_DATE_PS) AS GL_DATE
, TO_CHAR(NVL(A.GL_DATE_AR, S.GL_DATE_PS), 'YYYYMMDD') AS GL_DATE_KEY
, NVL(S.AMOUNT_DUE_ORIGINAL_EXCH, 0) AS AMOUNT_DUE_ORIGINAL_EXCH
, A.AMOUNT_APPLIED_BY_DAY AS AMOUNT_APPLIED_BY_DAY
, ROUND(SUM(A.AMOUNT_APPLIED_BY_DAY) OVER (PARTITION BY A.PAYMENT_SCHEDULE_ID ORDER BY A.GL_DATE_AR), 2) AS AR_ACCTD_AMT_DUE_EXCH
, ROUND(NVL(S.AMOUNT_DUE_ORIGINAL_EXCH, 0) - NVL(AR_ACCTD_AMT_DUE_EXCH, 0), 2) AS OUTSTANDING_AMOUNT
, CASE WHEN OUTSTANDING_AMOUNT = 0 THEN NULL ELSE CAST(CONVERT_TIMEZONE('UTC', SCHEME.TIMEZONE, SYSDATE()) AS DATE) - S.DUE_DATE END AS DAYS_DIFF
, CASE WHEN OUTSTANDING_AMOUNT = 0 THEN 'Pay Off' ELSE CASE WHEN DAYS_DIFF <= 0 THEN 'Current' WHEN DAYS_DIFF BETWEEN 1 AND 30 THEN '1-30' WHEN DAYS_DIFF BETWEEN 31 AND 60 THEN '31-60' WHEN DAYS_DIFF BETWEEN 61 AND 90 THEN '61-90' WHEN DAYS_DIFF BETWEEN 91 AND 120 THEN '91-120' WHEN DAYS_DIFF BETWEEN 121 AND 150 THEN '121-150' WHEN DAYS_DIFF > 150 THEN '151+' END END AS DAYS_DIFF_BANDING
, CASE WHEN OUTSTANDING_AMOUNT = 0 THEN 99 ELSE CASE WHEN DAYS_DIFF <= 0 THEN 0 WHEN DAYS_DIFF BETWEEN 1 AND 30 THEN 1 WHEN DAYS_DIFF BETWEEN 31 AND 60 THEN 2 WHEN DAYS_DIFF BETWEEN 61 AND 90 THEN 3 WHEN DAYS_DIFF BETWEEN 91 AND 120 THEN 4 WHEN DAYS_DIFF BETWEEN 121 AND 150 THEN 5 WHEN DAYS_DIFF > 150 THEN 6 END END AS DAYS_DIFF_BANDING_ORDER
, CASE WHEN ROW_NUMBER() OVER (PARTITION BY S.PAYMENT_SCHEDULE_ID ORDER BY NVL(A.GL_DATE_AR, S.GL_DATE_PS) DESC) = 1 THEN 'Recent' ELSE 'Not Recent' END AS RECENT_FLAG
, CASE WHEN OUTSTANDING_AMOUNT = 0 THEN 'Pay Off' ELSE 'Outstanding' END AS OUTSTANDING_STATUS
, SYSDATE() AS INSERT_DATE_UTC
FROM
{{ source('CES_ERP', 'AR_TRANSACTIONS_DUE_SCHED') }} AS S
LEFT JOIN (
    SELECT
    APP.PAYMENT_SCHEDULE_ID
    , APP.GL_DATE_AR
    , SUM(NVL((CASE WHEN DS.CLASS = 'CM' AND APP.APPLICATION_TYPE = 'CM' THEN NVL(-APP.AMOUNT_APPLIED, 0) ELSE NVL(APP.AMOUNT_APPLIED, 0) END) * DS.EXCHANGE_RATE, 0)) AS AMOUNT_APPLIED_BY_DAY
    FROM {{ source('CES_ERP', 'AR_TRANSACTIONS_DUE_APP') }} AS APP
    LEFT JOIN {{ source('CES_ERP', 'AR_TRANSACTIONS_DUE_SCHED') }} AS DS
    ON APP.PAYMENT_SCHEDULE_ID = DS.PAYMENT_SCHEDULE_ID
    GROUP BY ALL
 
    UNION ALL
 
    SELECT
    DS.PAYMENT_SCHEDULE_ID
    , GL_DATE_PS AS GL_DATE_AR
    , 0 AS AMOUNT_APPLIED_BY_DAY
    FROM {{ source('CES_ERP', 'AR_TRANSACTIONS_DUE_SCHED') }} AS DS
 
    UNION ALL
 
    SELECT
    A.PAYMENT_SCHEDULE_ID
    , CAST(A.GL_DATE AS DATE) AS GL_DATE_AR
    , -A.AMOUNT AS AMOUNT_APPLIED_BY_DAY
    FROM {{ source('CES_ERP', 'AR_ADJUSTMENTS') }} AS A
) A
ON S.PAYMENT_SCHEDULE_ID = A.PAYMENT_SCHEDULE_ID
LEFT JOIN (
    SELECT
    B2BS.MULTI_SCHEME_ID
    , B2BS.SUPPLIER_NAME
    , B2BS.SITE_NUMBER
    , B2BS.TAXONOMY
    FROM {{ ref('B2B_SITES') }} AS B2BS
    QUALIFY ROW_NUMBER() OVER (PARTITION BY B2BS.MULTI_SCHEME_ID, B2BS.SUPPLIER_NAME, B2BS.TAXONOMY ORDER BY B2BS.SITE_NUMBER) = 1
) PS
ON DECODE(S.LOCATION_CODE, 'CoExQLD', 10000, 'WARRRL', 10001, 'VIC RECYCLE', 10002, 'TAS RECYCLE', 10003, 'CoExService', -1) = PS.MULTI_SCHEME_ID
AND S.PARTY_NAME = PS.SUPPLIER_NAME
AND CASE WHEN UPPER(S.TRANS_TYPE_NAME) LIKE ('%BM%') THEN 'Beverage Manufacturer' WHEN UPPER(S.TRANS_TYPE_NAME) LIKE ('%PROCESSOR%') THEN 'Processor' WHEN UPPER(S.TRANS_TYPE_NAME) LIKE ('%MRF%') THEN 'MRF' WHEN UPPER(S.TRANS_TYPE_NAME) LIKE ('%RECYCLR%') THEN 'Recycler' END = PS.TAXONOMY
LEFT JOIN (
    SELECT
    T.TRANSACTION_NUMBER
    , T.BILL_TO_SITE_NUM AS SITE_NUMBER
    FROM {{ source('CES_ERP', 'AR_TRANSACTIONS') }} AS T
    WHERE ACCOUNTING_CLASS = 'Receivable'
    AND ACCOUNTING_CALENDAR_NAME = 'Scheme Ledger'
    QUALIFY ROW_NUMBER() OVER (PARTITION BY T.TRANSACTION_NUMBER ORDER BY JOURNAL_LINE_NUM) = 1
) SM
ON UPPER(S.TRANS_TYPE_NAME) IN ('Credit Memo', 'Invoice')
AND S.TRANSACTION_NUMBER = SM.TRANSACTION_NUMBER
INNER JOIN {{ source('CES_MSCM', 'SCHEME') }} AS SCHEME
ON DECODE(S.LOCATION_CODE, 'CoExQLD', 10000, 'WARRRL', 10001, 'VIC RECYCLE', 10002, 'TAS RECYCLE', 10003, 'CoExService', -1) = SCHEME.MULTI_SCHEME_ID
WHERE S.CLASS IN ('CM', 'INV')
AND S.BU_NAME IN ('Scheme QLD BU', 'WA SCHEME BU', 'Scheme VIC BU', 'Scheme TAS BU')
AND UPPER(S.TRANS_TYPE_NAME) LIKE ANY ('%BM%', '%PROCESSOR%', '%MRF%', '%RECYCLR%', 'Credit Memo', 'Invoice')