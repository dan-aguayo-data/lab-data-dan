SELECT
AD.MULTI_SCHEME_ID AS MULTI_SCHEME_ID
, AD.SCHEME AS SCHEME
, AD.PAYMENT_SCHEDULE_ID AS PAYMENT_SCHEDULE_ID
, AD.END_OF_WEEK_DATE AS END_OF_WEEK_DATE
, AD.END_OF_WEEK_DATE_KEY AS END_OF_WEEK_DATE_KEY
, AD.PARTY_NAME AS PARTY_NAME
, AD.SITE_NUMBER AS SITE_NUMBER
, AD.INVOICE_NUMBER AS INVOICE_NUMBER
, AD.DUE_DATE AS DUE_DATE
, AD.CLASS AS CLASS
, AD.INVOICE_TYPE AS INVOICE_TYPE
, AD.INVOICE_TYPE_NAME AS INVOICE_TYPE_NAME
, AD.BU_NAME AS BU_NAME
, AD.GL_DATE_PS AS GL_DATE_PS
, AD.GL_DATE_AR AS GL_DATE_AR
, AD.GL_DATE AS GL_DATE
, AD.GL_DATE_KEY AS GL_DATE_KEY
, AD.AMOUNT_DUE_ORIGINAL_EXCH AS AMOUNT_DUE_ORIGINAL_EXCH
, AD.AR_ACCTD_AMT_DUE_EXCH AS AR_ACCTD_AMT_DUE_EXCH
, AD.OUTSTANDING_AMOUNT AS OUTSTANDING_AMOUNT
, AD.DAYS_DIFF AS DAYS_DIFF
, AD.DAYS_DIFF_BANDING AS DAYS_DIFF_BANDING
, AD.DAYS_DIFF_BANDING_ORDER AS DAYS_DIFF_BANDING_ORDER
, SYSDATE() AS INSERT_DATE_UTC
FROM (
    SELECT
    B.MULTI_SCHEME_ID
    , B.SCHEME
    , B.PAYMENT_SCHEDULE_ID
    , B.PARTY_NAME
    , B.SITE_NUMBER
    , B.INVOICE_NUMBER
    , B.DUE_DATE
    , B.CLASS
    , B.INVOICE_TYPE
    , B.INVOICE_TYPE_NAME
    , B.BU_NAME
    , B.GL_DATE_PS
    , B.GL_DATE_AR
    , B.GL_DATE
    , B.GL_DATE_KEY
    , B.AMOUNT_DUE_ORIGINAL_EXCH
    , B.AR_ACCTD_AMT_DUE_EXCH
    , B.OUTSTANDING_AMOUNT
    , D.DATE AS END_OF_WEEK_DATE
    , D.KEY AS END_OF_WEEK_DATE_KEY
    , D.DATE - B.DUE_DATE AS DAYS_DIFF
    , CASE WHEN D.DATE - B.DUE_DATE <= 0 THEN 'Current' WHEN D.DATE - B.DUE_DATE BETWEEN 1 AND 30 THEN '1-30' WHEN D.DATE - B.DUE_DATE BETWEEN 31 AND 60 THEN '31-60' WHEN D.DATE - B.DUE_DATE BETWEEN 61 AND 90 THEN '61-90' WHEN D.DATE - B.DUE_DATE BETWEEN 91 AND 120 THEN '91-120' WHEN D.DATE - B.DUE_DATE BETWEEN 121 AND 150 THEN '121-150' WHEN D.DATE - B.DUE_DATE > 150 THEN '151+' END AS DAYS_DIFF_BANDING
    , CASE WHEN D.DATE - B.DUE_DATE <= 0 THEN 0 WHEN D.DATE - B.DUE_DATE BETWEEN 1 AND 30 THEN 1 WHEN D.DATE - B.DUE_DATE BETWEEN 31 AND 60 THEN 2 WHEN D.DATE - B.DUE_DATE BETWEEN 61 AND 90 THEN 3 WHEN D.DATE - B.DUE_DATE BETWEEN 91 AND 120 THEN 4 WHEN D.DATE - B.DUE_DATE BETWEEN 121 AND 150 THEN 5 WHEN D.DATE - B.DUE_DATE > 150 THEN 6 END AS DAYS_DIFF_BANDING_ORDER
    FROM {{ ref('AGING_DEBTOR_BASE') }} AS B
    CROSS JOIN (
        SELECT
        DT.YEAR_WEEK_ISO
        , DT.DATE
        , DT.KEY
        FROM {{ ref('REF_DATE') }} AS DT
        WHERE DT.DAY_OF_WEEK = 7
    ) D
    WHERE B.GL_DATE <= D.DATE
    QUALIFY ROW_NUMBER() OVER (PARTITION BY B.PAYMENT_SCHEDULE_ID, D.YEAR_WEEK_ISO ORDER BY B.GL_DATE DESC) = 1
) AD
WHERE NVL(ABS(AD.AMOUNT_DUE_ORIGINAL_EXCH), 0) - NVL(ABS(AD.AR_ACCTD_AMT_DUE_EXCH), 0) > 0