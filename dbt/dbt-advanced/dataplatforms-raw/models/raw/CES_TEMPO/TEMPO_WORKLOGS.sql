SELECT 
C.JIRAWORKLOGID, 
A.TEMPOWORKLOGID, 
A.DESCRIPTION, 
A.TIMESPENTINSECONDS, 
A.BILLABLESECONDS, 
A.STARTDATETIME, 
A.CREATEDAT, 
A.UPDATEDAT,
 A.ACCOUNTID, 
 A.DISPLAYNAME,
A.ISSUEID, 
B.KEY AS ISSUEKEY
FROM {{ ref('LANDING_TEMPO_WORKLOGS') }} A
LEFT JOIN {{source('CES_JIRA','ISSUE')}} B
ON  A.ISSUEID = B.ID 
LEFT JOIN  {{ ref('LANDING_TEMPO_WORKLOGS_TO_JIRA') }}  C
ON A.TEMPOWORKLOGID = C.TEMPOWORKLOGID
ORDER BY TEMPOWORKLOGID