WITH source AS (

SELECT * FROM {{source('SNOWPIPE_UAT_PROD',tbl_name|string)}} 
), flattened_source as(
    SELECT 
        FILE_NAME, 
        FILE_ROW_NUMBER, 
        LANDED_DATETIME, 
       SUBSTR(COL_1,0,1) AS IDENTIFIER,
       TO_DATE(SUBSTR(COL_1,2,10),'DD-MM-YYYY') AS RETURN_DATE,
       SUBSTR(COL_1,12,16) AS ACCOUNT_NAME,
       SUBSTR(COL_1,28,6) AS BSB_NUMBER,
       SUBSTR(COL_1,34,21) AS ACCOUNT_NUMBER,
       TO_DATE(SUBSTR(COL_1,69,10),'DD-MM-YYYY') AS LODGEMENT_DATE,
       SUBSTR(COL_1,79,18) AS LODGEMENT_REFERENCE,
       SUBSTR(COL_1,97,16) AS REMITTER,
       SUBSTR(COL_1,113,32) AS TARGET_ACCOUNT_NAME,
       SUBSTR(COL_1,145,6) AS TARGET_ACCOUNT_BSB,
       SUBSTR(COL_1,151,21) AS TARGET_ACCOUNT_NUMBER,
       CAST(SUBSTR(COL_1,172,14) AS FLOAT) AS AMOUNT,
       SUBSTR(COL_1,186,60) AS RETURN_REASON_TEXT,
       SUBSTR(COL_1,246,3) AS RETURN_REASON_CODE,
       SUBSTR(COL_1,249,6) AS USER_IDENTIFICATION_NUMBER,
       SUBSTR(COL_1,282,12) AS TRANSACTION_IDENTIFIER,
       COL_1
FROM source
where substr(COL_1,0,1) ='2'
) 
SELECT  
       FILE_NAME, 
       FILE_ROW_NUMBER, 
       LANDED_DATETIME, 
       IDENTIFIER,
       RETURN_DATE,
       ACCOUNT_NAME,
       BSB_NUMBER,
       ACCOUNT_NUMBER,
       LODGEMENT_DATE,
       trim(LODGEMENT_REFERENCE) LODGEMENT_REFERENCE,
       REMITTER,
       TARGET_ACCOUNT_NAME,
       TARGET_ACCOUNT_BSB,
       TARGET_ACCOUNT_NUMBER,
       AMOUNT,
       RETURN_REASON_TEXT,
       RETURN_REASON_CODE,
       USER_IDENTIFICATION_NUMBER,
       TRANSACTION_IDENTIFIER,
       DECODE(ACCOUNT_NAME, 'COEX QLD AP SETT', 10000, 'WARRRL AP SETT A', 10001, 'OPERATING ACCOUN', 100020001) AS MULTI_SCHEME_ID,
       COL_1
 FROM flattened_source

    QUALIFY ROW_NUMBER() OVER (PARTITION BY LODGEMENT_REFERENCE ORDER BY LANDED_DATETIME DESC) = 1
