WITH  INCREMENTAL_DATE_REF AS (

SELECT DATEADD(DAY, -2, CURRENT_TIMESTAMP) AS INCREMENTAL_DELTA

), ANZ_BTR_HEADER AS( 

SELECT DISTINCT FILE_NAME FROM {{ref('ANZ_BTR_HEADER')}}
{% if is_incremental() %}
WHERE LANDED_DATETIME >= (SELECT INCREMENTAL_DELTA FROM INCREMENTAL_DATE_REF)

), ANZ_BTR_SOURCE AS (
 
  select 
  * 
  from {{source('SNOWPIPE_UAT_PROD',tbl_name|string)}}  
  where LANDED_DATETIME >= (SELECT INCREMENTAL_DELTA FROM INCREMENTAL_DATE_REF)
 
), ANZ_BTR_FILE_DT AS (
 
    select 
    FILE_NAME 
    ,to_date(COL_4, 'YYMMDD') as FILE_DATE 
    from ANZ_BTR_SOURCE 
    where COL_1='01'

), ANZ_BTR_FILE_ADT AS (
 
    select FILE_NAME 
    ,to_date(COL_5, 'YYMMDD') as ACCOUNTING_DATE 
    from ANZ_BTR_SOURCE 
    where COL_1='02'

)
    select
     ANZ_BTR_SOURCE.FILE_NAME
    ,ANZ_BTR_FILE_DT.FILE_DATE
    ,ANZ_BTR_SOURCE.FILE_ROW_NUMBER
    ,ANZ_BTR_SOURCE.LANDED_DATETIME
    ,CONCAT(TO_CHAR(ANZ_BTR_FILE_DT.FILE_DATE, 'YYYYMMDD'),'-',ANZ_BTR_SOURCE.COL_2,'-',ANZ_BTR_SOURCE.FILE_ROW_NUMBER)  AS ID
    ,CONCAT(TO_CHAR(ANZ_BTR_FILE_DT.FILE_DATE, 'YYYYMMDD'),'-',ANZ_BTR_SOURCE.COL_2)  AS HEADER_ID
    ,ANZ_BTR_SOURCE.COL_1 as RECORD_CODE
    ,ANZ_BTR_SOURCE.COL_2 as ACCOUNT_NUMBER
    ,AC.MULTI_SCHEME_ID as MULTI_SCHEME_ID
    ,ANZ_BTR_SOURCE.COL_3 as TYPE_CODE
    ,(CAST(ANZ_BTR_SOURCE.COL_4 AS FLOAT)/100) as AMOUNT
    ,CAST(ANZ_BTR_SOURCE.COL_5 AS DATE) as VALUE_DATE
  ,CASE WHEN ANZ_BTR_SOURCE.COL_3 in ('467','495','195','266') THEN ANZ_BTR_SOURCE.COL_6 
            ELSE NULL END as BANK_REF_NUM
    ,CASE WHEN ANZ_BTR_SOURCE.COL_3 in ('467','495','195','266') THEN  ANZ_BTR_SOURCE.COL_7 
            ELSE NULL END as CUSTOMER_REF_NUM
    ,ANZ_BTR_SOURCE.COL_8 as TEXT
    from ANZ_BTR_SOURCE
    INNER JOIN ANZ_BTR_FILE_DT 
    ON ANZ_BTR_SOURCE.FILE_NAME =   ANZ_BTR_FILE_DT.FILE_NAME
    LEFT JOIN {{source('CES_REF','BANK_REC_ACCOUNT_MAPPING')}} AC
    ON AC.ACCOUNT_NUM = ANZ_BTR_SOURCE.COL_2
    where ANZ_BTR_SOURCE.COL_1='16'
    and ANZ_BTR_SOURCE.COL_2 like any ('%8801','%0896','%2895')


{% else %}
), HISTORY_UNION AS (

select * from {{source('CES_FINANCE_LANDING','ANZ_BTR_LINES')}}
UNION 
SELECT * FROM {{source('CES_FINANCE_LANDING','ANZ_BTR_LINES_HIST')}}

) 

SELECT
HISTORY_UNION.FILE_NAME
,HISTORY_UNION.FILE_DATE
,HISTORY_UNION.FILE_ROW_NUMBER
,HISTORY_UNION.LANDED_DATETIME
,HISTORY_UNION.ID
,HISTORY_UNION.HEADER_ID
,HISTORY_UNION.RECORD_CODE
,HISTORY_UNION.ACCOUNT_NUMBER
,HISTORY_UNION.MULTI_SCHEME_ID
,HISTORY_UNION.TYPE_CODE
,HISTORY_UNION.AMOUNT
,HISTORY_UNION.VALUE_DATE
,HISTORY_UNION.BANK_REF_NUM
,HISTORY_UNION.CUSTOMER_REF_NUM
,HISTORY_UNION.TEXT
FROM HISTORY_UNION
INNER JOIN ANZ_BTR_HEADER
ON HISTORY_UNION.FILE_NAME = ANZ_BTR_HEADER.FILE_NAME

{% endif %}