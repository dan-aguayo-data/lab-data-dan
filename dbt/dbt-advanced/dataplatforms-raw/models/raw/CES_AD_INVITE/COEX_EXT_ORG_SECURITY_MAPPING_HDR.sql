

WITH DETAIL_QUERY AS (
SELECT  
 10000 AS MULTI_SCHEME_ID
,lower(EMAIL) AS LOGIN_ID 
,concat('mail#',lower(EMAIL)) AS LOGIN_ID_LIVE
,CONCAT(FIRST_NAME,' ',LAST_NAME) AS FULL_NAME
,SCHEME_ID AS SITE_SCHEME_ID
,COALESCE(PARTNER_SITE,SCHOOL_NAME) AS SITE_NAME
,PARTNER_ID AS PARTNER_ID
,COALESCE(PARTNER_PARENT,SCHOOL_NAME) AS PARTNER_NAME
,CATEGORY AS PARTNER_TYPE
,SUB_CATEGORY AS PARTNER_SUB_TYPE
,CASE WHEN upper(STATUS) = 'ACTIVE' THEN 1 ELSE 0 END AS "ACTIVE"
,to_date(LAUNCH_DATE ,'Mon dd yyyy') AS LAUNCH_DATE
,DATE_UPDATED AS DATE_CREATED
,DATE_CREATED AS DATE_UPDATED

 FROM {{ ref('AG_PARTNER_USERS') }} )

 SELECT 

MULTI_SCHEME_ID
,LOGIN_ID 
,LOGIN_ID_LIVE
,FULL_NAME
,null SITE_SCHEME_ID
,null SITE_NAME
,null PARTNER_ID
,null PARTNER_NAME
,null PARTNER_TYPE
,null PARTNER_SUB_TYPE
,MAX(ACTIVE) ACTIVE
,MAX(LAUNCH_DATE) LAUNCH_DATE
,MAX(DATE_CREATED) DATE_CREATED
,MAX(DATE_UPDATED) DATE_UPDATED

FROM DETAIL_QUERY

GROUP BY ALL