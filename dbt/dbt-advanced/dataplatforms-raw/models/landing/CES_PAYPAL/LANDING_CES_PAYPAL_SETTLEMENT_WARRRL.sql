SELECT 
CONCAT(TRANSACTION_ID,'-',PAYPAL_REFERENCE_ID,'-',PAYPAL_REFERENCE_ID_TYPE,'-',FEE_DEBIT_OR_CREDIT) AS ID, 
TRANSACTION_ID, --unique
CUSTOM_FIELD AS PAY_REF_NUMBER,
INVOICE_ID,
CONSUMER_ID,
PAYPAL_REFERENCE_ID, --unique
PAYPAL_REFERENCE_ID_TYPE,  --unique
TRANSACTION_EVENT_CODE,
TO_DECIMAL(NVL(GROSS_TRANSACTION_AMOUNT,0) /100, 10, 4) AS GROSS_TRANSACTION_AMOUNT,
GROSS_TRANSACTION_CURRENCY,
CASE 
WHEN TRANSACTION_DEBIT_OR_CREDIT = 'DR' THEN 'DEBIT'
WHEN TRANSACTION_DEBIT_OR_CREDIT = 'CR' THEN 'CREDIT'
ELSE TRANSACTION_DEBIT_OR_CREDIT
END AS TRANSACTION_DEBIT_OR_CREDIT,
TO_TIMESTAMP(TRANSACTION_INITIATION_DATE, 'YYYY/MM/DD HH24:MI:SS TZHTZM') as TRANSACTION_INITIATION_DATE,
TO_TIMESTAMP(TRANSACTION_COMPLETION_DATE, 'YYYY/MM/DD HH24:MI:SS TZHTZM') as TRANSACTION_COMPLETION_DATE,
FEE_DEBIT_OR_CREDIT,  -- unique
TO_DECIMAL(NVL(FEE_AMOUNT,0) /100, 10, 4) AS FEE_AMOUNT,
FEE_CURRENCY,
PAYMENT_TRACKING_ID,
STORE_ID,
BANK_REFERENCE_ID,
TO_DECIMAL(NVL(CREDIT_TRANSACTIONAL_FEE,0) /100, 10, 4) AS CREDIT_TRANSACTIONAL_FEE,
TO_DECIMAL(NVL(CREDIT_PROMOTIONAL_FEE,0) /100, 10, 4) AS CREDIT_PROMOTIONAL_FEE,
CREDIT_TERM,
TO_DATE(SUBSTRING(FILENAME, 17, 8), 'YYYYMMDD') AS PAYPAL_FILE_DATE,
LANDED_DATETIME AS PAYPAL_FILE_LANDED_DATE

FROM {{source('SNOWPIPE_PROD','CES_PAYPAL_SFTP_STL_WARRRL')}}

WHERE CODE_REF = 'SB'  AND TRANSACTION_EVENT_CODE NOT IN  ('T1503','T1105')