WITH SOURCE AS (
    SELECT
        *
    FROM
        {{ source('LANDING_ORACLE', 'AWS_RDS_STAGE_COEX') }}
    WHERE METADATA:"table-name"='FMT_ORGANISATIONS' AND DATA is not null
)

SELECT
    N.DATA:ORGANISATION_ID::bigint as ORGANISATION_ID,
    nullif(N.DATA:PARENT_ORGANISATION_ID,'')::bigint as PARENT_ORGANISATION_ID,
    N.DATA:SUPPLIER_NUMBER::bigint as SUPPLIER_NUMBER,
    N.DATA:SCHEME_PARTICIPANT_ID::string as SCHEME_PARTICIPANT_ID,
    N.DATA:ORGANISATION_NAME::string as ORGANISATION_NAME,
    N.DATA:ORGANISATION_TYPE_ID::bigint as ORGANISATION_TYPE_ID,
    N.DATA:START_DATE_ACTIVE::DATE as START_DATE_ACTIVE,
    nullif(N.DATA:END_DATE_ACTIVE,'')::DATE as END_DATE_ACTIVE,
    nullif(N.DATA:SCHEME_ID,'')::bigint as SCHEME_ID,
    N.DATA:CREATED_BY::string as CREATED_BY,
    N.DATA:CREATED_ON::TIMESTAMP_NTZ as CREATED_ON,
    N.DATA:LAST_MODIFIED_BY::string as LAST_MODIFIED_BY,
    N.DATA:LAST_MODIFIED_ON::TIMESTAMP_NTZ as LAST_MODIFIED_ON,
    nullif(N.DATA:CLAIM_FREQUENCY_ID,'')::bigint as CLAIM_FREQUENCY_ID,
    TO_TIMESTAMP(N.METADATA:timestamp::string) as METADATA_TIMESTAMP,
    N.METADATA:operation::string as METADATA_OPERATION
FROM SOURCE as N