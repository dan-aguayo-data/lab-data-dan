WITH SOURCE AS (
    SELECT
        *
    FROM
        {{ source('LANDING_ORACLE', 'AWS_RDS_STAGE_CES_MSCM') }}
    WHERE METADATA:"table-name"='AUCTION_PROXY_BIDS' AND DATA is not null
)

SELECT
    N.DATA:AUCTION_PROXY_BID_ID::bigint as AUCTION_PROXY_BID_ID,
    N.DATA:AUCTION_EVENT_LOT_ID::string as AUCTION_EVENT_LOT_ID,
    N.DATA:BIDDER::string as BIDDER,
    N.DATA:STARTING_BID::float as STARTING_BID,
    N.DATA:MAXIMUM_BID::float as MAXIMUM_BID,
    N.DATA:SUBMITTED_ON::TIMESTAMP_NTZ as SUBMITTED_ON,
    nullif(N.DATA:CANCELLED_ON,'')::TIMESTAMP_NTZ as CANCELLED_ON,
    nullif(N.DATA:CANCELLED_BY,'')::string as CANCELLED_BY,
    N.DATA:CREATED_BY::string as CREATED_BY,
    N.DATA:CREATED_ON::TIMESTAMP_NTZ as CREATED_ON,
    N.DATA:LAST_MODIFIED_BY::string as LAST_MODIFIED_BY,
    N.DATA:LAST_MODIFIED_ON::TIMESTAMP_NTZ as LAST_MODIFIED_ON,
    N.DATA:MULTI_SCHEME_ID::bigint as MULTI_SCHEME_ID,
    nullif(N.DATA:REPLACED_WITH_ID,'')::bigint as REPLACED_WITH_ID,
    nullif(N.DATA:REPLACED_ON,'')::TIMESTAMP_NTZ as REPLACED_ON,
    nullif(N.DATA:MSC_BIDDER_SITE_ID,'')::bigint as MSC_BIDDER_SITE_ID,
    TO_TIMESTAMP(N.METADATA:timestamp::string) as METADATA_TIMESTAMP,
    N.METADATA:operation::string as METADATA_OPERATION
FROM SOURCE as N