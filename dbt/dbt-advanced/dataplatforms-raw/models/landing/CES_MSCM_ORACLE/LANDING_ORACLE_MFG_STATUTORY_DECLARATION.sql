WITH SOURCE AS (
    SELECT
        *
    FROM
        {{ source('LANDING_ORACLE', 'AWS_RDS_STAGE_CES_MSCM') }}
    WHERE METADATA:"table-name"='MFG_STATUTORY_DECLARATION' AND DATA is not null
)

SELECT
    N.DATA:MFG_STATUTORY_DECLARATION_ID::bigint as MFG_STATUTORY_DECLARATION_ID,
    N.DATA:PARTICIPANT_SITE_ID::bigint as PARTICIPANT_SITE_ID,
    N.DATA:MANUFACTURER_ID::string as MANUFACTURER_ID,
    N.DATA:STATUS::string as STATUS,
    N.DATA:DECLARATION_PERIOD_ID::bigint as DECLARATION_PERIOD_ID,
    nullif(N.DATA:DECLARANT_NAME,'')::string as DECLARANT_NAME,
    nullif(N.DATA:DECLARANT_ADDRESS,'')::string as DECLARANT_ADDRESS,
    nullif(N.DATA:DECLARANT_OCCUPATION,'')::string as DECLARANT_OCCUPATION,
    N.DATA:CREATED_BY::string as CREATED_BY,
    N.DATA:CREATED_ON::TIMESTAMP_NTZ as CREATED_ON,
    N.DATA:LAST_MODIFIED_BY::string as LAST_MODIFIED_BY,
    N.DATA:LAST_MODIFIED_ON::TIMESTAMP_NTZ as LAST_MODIFIED_ON,
    N.DATA:MULTI_SCHEME_ID::bigint as MULTI_SCHEME_ID,
    nullif(N.DATA:TOTAL_SALES_VOLUME,'')::float as TOTAL_SALES_VOLUME,
    nullif(N.DATA:SUBMITTED_BY,'')::string as SUBMITTED_BY,
    nullif(N.DATA:SUBMITTED_ON,'')::TIMESTAMP_NTZ as SUBMITTED_ON,
    nullif(N.DATA:AUDITOR_COMMENTS,'')::string as AUDITOR_COMMENTS,
    nullif(N.DATA:AUDITOR_APPROVAL_BY,'')::string as AUDITOR_APPROVAL_BY,
    nullif(N.DATA:AUDITOR_APPROVAL_ON,'')::TIMESTAMP_NTZ as AUDITOR_APPROVAL_ON,
    N.DATA:DISCUSSION_STATUS::string as DISCUSSION_STATUS,
    TO_TIMESTAMP(N.METADATA:timestamp::string) as METADATA_TIMESTAMP,
    N.METADATA:operation::string as METADATA_OPERATION
FROM SOURCE as N